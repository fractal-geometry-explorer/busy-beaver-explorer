"""Writes the Lean files of bb6-vampire-family/lean.

* `Core/`: the core with F0 as a parameter `f0` (`Core.trans f0`).  Everything that never reads F0 is proved once,
  for every f0: the drain of the halved block (`pairs`, `one_pair`, `loop`, `drain`) and the rewrite of every
  context of the table (`Ctx.lean`, `tbl_sound`).
* `VLC/`, `VLA/`, `VRB/`: the three values of F0 that occur.  Each has its own E-pass (`ev`, `od`), which is where
  F0 is read, and the map with its soundness (`Map.lean`).
* `Machines/H<id>.lean`: each of the seven holdouts, renamed (and for one, mirrored) onto its variant, with its first
  E-event from blank tape and the halting criterion.

usage: python3 gen.py [core] [1LC 1LA 1RB] [machines]     (default: all; run from any directory)
The contexts of the table come from contexts.txt (written by contexts.py).
"""
