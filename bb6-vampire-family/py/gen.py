BRIDGE = r"""
/-! ## The bridge to the core

{what}  So this machine halts from blank tape exactly when the core with F0 = {f0} halts from blank tape in state
{start} (`halts_iff`), and that run is the orbit of the E-event map from `x0` (`{c} E> 1^{n}`, reached at step {t}).
-/

/-- This machine's states as states of the core (`py/family.py match`). -/
def f : St → Core.St
{frows}

theorem hδ : ∀ q b, {ns}.trans (f q) b = (trans q b).map (fun t => (t.1, {dirmap}, f t.2.2)) := by
  intro q b; cases q <;> cases b <;> rfl

/-- **The bridge**: halting from blank tape is the core's halting from blank tape in state {start}. -/
theorem halts_iff : HaltsFromBlank ↔ Halts {ns}.trans (blankCfg Core.St.{start}) := by
  have h := halts_of_map trans {ns}.trans ({cfgmap} f) ({stepmap} trans {ns}.trans f hδ) init
  {blankfix}exact h

/-- The first E-event of the core's run: `{c} E> 1^{n}` after {t} steps. -/
def x0 : List Bool × Nat × Nat := ({lbc}, {n}, {t})

theorem x0_reaches : {ns}.Reaches (blankCfg Core.St.{start}) (Core.Ev x0.1 x0.2.1) x0.2.2 :=
  ⟨{t}, Nat.le_refl _, {ns}.blank_reaches_E Core.St.{start} {t} {lbc} {n} (by decide +kernel)⟩

/-- **The halting criterion**: if the orbit of the map reaches, within `K` passes, an E-event at which the proved
table has a halting entry, this machine halts from blank tape. -/
theorem halts_of_check (K : Nat) (h : {ns}.check K x0 = true) : HaltsFromBlank :=
  halts_iff.2 ({ns}.check_sound _ K x0 h x0_reaches)

/-- If the orbit stays inside the table forever, this machine never halts. -/
theorem not_halts_of_forall (h : ∀ K, ({ns}.oiter K x0).isSome = true) : ¬ HaltsFromBlank :=
  fun hh => {ns}.not_halts_of_forall _ x0 x0_reaches h (halts_iff.1 hh)

/-- 10,000 passes inside the table, by the kernel. -/
theorem orbit_kernel : ({ns}.oiter 10000 x0).isSome = true := by decide +kernel

/-- 2^18 passes inside the table, and no halting entry met on the way (`native_decide`). -/
theorem orbit_native : ({ns}.oiter (2 ^ 18) x0).isSome = true ∧ {ns}.check (2 ^ 18) x0 = false := by
  native_decide

/-- So the core's run from state {start}, which halts exactly when this machine's does, runs more than 10^45000
steps without a halt. -/
theorem no_halt_native : ∃ y, {ns}.oiter (2 ^ 18) x0 = some y ∧ 10 ^ 45000 < y.2.2 ∧
    ∃ c, {ns}.steps y.2.2 (blankCfg Core.St.{start}) = some c := by
  cases e : {ns}.oiter (2 ^ 18) x0 with
  | none => have := orbit_native.1; rw [e] at this; cases this
  | some y =>
    refine ⟨y, rfl, ?_, {ns}.no_halt_of _ x0 x0_reaches _ y e⟩
    have b : 10 ^ 45000 < (({ns}.oiter (2 ^ 18) x0).getD x0).2.2 := by native_decide
    rw [e] at b; exact b

end {hns}
"""


def machine_file(m, ident, label):
    perm, mir, f0, start = fam.match(m)[0]
    ns = fam.NS[f0]
    hns = f"H{ident}"
    t, c, n = fam.first_event(f0, start)
    inv = {perm[i]: i for i in range(6)}
    frows = "\n".join(f"  | .{'ABCDEF'[q]} => .{'ABCDEF'[inv[q]]}" for q in range(6))
    head = machine_lean(m, hns, doc=f"BB(6) holdout {m} (bbchallenge id {ident}), one of the seven machines of the "
                        f"vampire family (`{label}` in the family's repository).")
    head = head.replace("import TM\n", f"import {ns}.Map\nimport TM.Insert\n", 1).rstrip()
    assert head.endswith(f"end {hns}")
    head = head[: -len(f"end {hns}")].rstrip() + "\n"
    if mir:
        what = (f"Mirrored (left and right swapped) and with its states renamed by `f`, this machine is the core with "
                f"F0 = {f0}: `hδ` checks the table entry by entry, and `TM.step_mirrorCfg` turns that into one step "
                "of each.")
        cfgmap, stepmap, dirmap = "mirrorCfg", "step_mirrorCfg", "t.2.1.flip"
        blankfix = "rw [show mirrorCfg f init = blankCfg (f .A) from mirrorCfg_blank f .A] at h\n  "
    else:
        what = (f"With its states renamed by `f`, this machine is the core with F0 = {f0}: `hδ` checks the table "
                "entry by entry, and `TM.step_renameCfg` turns that into one step of each.")
        cfgmap, stepmap, dirmap = "renameCfg", "step_renameCfg", "t.2.1"
        blankfix = ""
    return head + BRIDGE.format(what=what, f0=f0, start=start, c=c, n=n, t=t, ns=ns, frows=frows, dirmap=dirmap,
                                cfgmap=cfgmap, stepmap=stepmap, blankfix=blankfix, lbc=lb(c), hns=hns)


def write(rel, text):
    fn = os.path.join(LEAN, rel)
    os.makedirs(os.path.dirname(fn), exist_ok=True)
    with open(fn, "w") as fh:
        fh.write(text if text.endswith("\n") else text + "\n")
    print("wrote", rel, file=sys.stderr)


