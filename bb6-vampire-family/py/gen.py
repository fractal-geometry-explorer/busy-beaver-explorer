def ones_conv(right):
    """symtm's right tokens 1^p (11)^e 1^q blank -> (Lean term with ones q inside, total expression)"""
    toks = list(right)
    assert isinstance(toks[-1], Blank), toks
    toks = toks[:-1]
    reps = [i for i, t in enumerate(toks) if isinstance(t, Rep)]
    assert len(reps) == 1 and toks[reps[0]].word == (1, 1), toks
    i = reps[0]
    p, q = toks[:i], toks[i + 1:]
    assert all(t == 1 for t in p + q), toks
    ex = toks[i].n.lean()
    term = f"rep ({ex}) [true, true] (ones {len(q)})"
    for _ in p:
        term = f"cons true ({term})"
    return term, f"2 * ({ex}) + {len(q)} + {len(p)}"


def start_cfg(c, b):
    return (f"0^inf {' '.join(c)} C> (11)^j+1 0^inf" if b == 0 else
            f"0^inf {' '.join(c + '1')} C> 1 (11)^j+2 0^inf")


def entry(k, c, b):
    """Lean text for context number k and bit b, and (c', a) or None for a halt"""
    M = fam.core(F0_ANY)
    r = fam.rule(F0_ANY, c, b)
    for other in fam.VARIANTS:
        assert fam.rule(other, c, b) == r, (c, b, other)
    s = start_cfg(c, b)
    lhs_m = "2 * j + 2" if b == 0 else "2 * j + 5"
    left0 = f"app ({lb(c)}).reverse blank" if b == 0 else f"cons true (app ({lb(c)}).reverse blank)"
    rstart = "tt_ones' j" if b == 0 else "tt_ones_odd j"
    if r == "HALT":
        tr = []
        try:
            run(Machine.parse(M), Config.parse(s), lambda x: False, max_moves=100000, trace=tr, rotate=True)
            raise AssertionError("no halt")
        except Halted:
            pass
        fin = tr[-1][2]
        name = f"h_{k}_{b}"
        t, _ = prove(M, name, s, repr(fin), doc=f"Context `{c}`, b = {b}: `{s}` reaches `{fin}`, F reading 1.",
                     rotate=True, count_first=True, max_seg=40)
        w = [param(t), "",
             f"theorem ctx_{k}_{b} (j : Nat) : Halts (trans f0) (Cn ({left0}) ({lhs_m})) := by",
             f"  have h := {name} f0 j",
             f"  rw [{rstart}] at h",
             f"  exact ⟨_, _, h, rfl⟩"]
        return "\n".join(w), None
    c2, a = r
    N = (2 if b == 0 else 5) + a
    e = f"0^inf {' '.join(c2)} E> {'1 ' if N % 2 else ''}(11)^j+{N // 2} 0^inf"
    name = f"p_{k}_{b}"
    t, fin = prove(M, name, s, e, doc=f"Context `{c}`, b = {b}: `{s}` to `{e}`.", rotate=True, count_first=True,
                   max_seg=40)
    term, tot = ones_conv(fin.right)
    w = [param(t), "",
         f"theorem ctx_{k}_{b} (j : Nat) : Reaches f0 (Cn ({left0}) ({lhs_m})) (Ev {lb(c2)} ({lhs_m} + {a})) 0 := by",
         f"  have h := {name} f0 j",
         f"  have e : {right_term(fin.right)} = ones ({tot}) := by",
         f"    show {term} = _",
         f"    rw [rep_tt_ones]; rfl",
         f"  rw [e, {rstart}] at h",
         f"  rw [show {lhs_m} + {a} = {tot} by omega]",
         f"  exact ⟨_, Nat.zero_le _, h⟩"]
    return "\n".join(w), (c2, a)


def contexts():
    fn = os.path.join(HERE, "contexts.txt")
    return [l.split()[0] for l in open(fn) if l.strip() and l[0] != "#"]


def core_ctx():
    cs = contexts()
    out = ["import Core.Defs", "",
           "/-! The rewrites of the contexts listed in `py/contexts.txt`, for both parities of the block, every block "
           "length and every F0 (a rewrite never reads F0), " + HEADER + " -/", "", "namespace Core", "", "open TM",
           "", "section", "variable (f0 : Bool × Dir × St)", ""]
    tbl, oks = [], []
    for k, c in enumerate(cs):
        res = []
        for b in (0, 1):
            txt, r = entry(k, c, b)
            out += [txt, ""]
            res.append(r)
        e0 = f"some ({lb(res[0][0])}, {res[0][1]})" if res[0] else "none"
        e1 = f"some ({lb(res[1][0])}, {res[1][1]})" if res[1] else "none"
        tbl.append(f"({lb(c)}, {e0}, {e1})")
        oks.append(f"theorem ok_{k} : EntryOK f0 {tbl[-1]} := ⟨fun j => ctx_{k}_0 f0 j, fun j => ctx_{k}_1 f0 j⟩")
        print(f"context {k} {c}: {res}", file=sys.stderr)
    out += ["end", "",
            "/-- The table: context, then (next context, added length) for b = 0 and b = 1 (`none`: halt). -/",
            "def tbl : List (List Bool × Option (List Bool × Nat) × Option (List Bool × Nat)) := [",
            ",\n".join("  " + t for t in tbl) + "]", "", "section", "variable (f0 : Bool × Dir × St)", ""]
    out += oks
    out += ["", "theorem tbl_sound : ∀ e ∈ tbl, EntryOK f0 e := by", "  intro e he",
            "  simp only [tbl, List.mem_cons, List.not_mem_nil, or_false] at he",
            "  rcases he with " + " | ".join("rfl" for _ in tbl),
            "  " + "\n  ".join(f"· exact ok_{k} f0" for k in range(len(tbl))), "", "end", "", LOOK, "end Core"]
    return "\n".join(out)


LOOK = r"""/-- The table's entry for a context. -/
def look (c : List Bool) : Option (Option (List Bool × Nat) × Option (List Bool × Nat)) :=
  (tbl.find? (fun e => e.1 == c)).map (·.2)

theorem look_sound (f0 : Bool × Dir × St) {c : List Bool} {x : Option (List Bool × Nat) × Option (List Bool × Nat)}
    (h : look c = some x) : EntryOK f0 (c, x) := by
  unfold look at h
  cases hf : tbl.find? (fun e => e.1 == c) with
  | none => rw [hf] at h; cases h
  | some e =>
    rw [hf] at h
    simp only [Option.map_some, Option.some.injEq] at h
    have hm := List.mem_of_find?_eq_some hf
    have hc := List.find?_some hf
    have ok := tbl_sound f0 e hm
    have hc' : e.1 = c := by simpa using hc
    obtain ⟨e1, e2⟩ := e
    simp only at h hc'
    subst h hc'
    exact ok
"""

