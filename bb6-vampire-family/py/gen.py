F0_ANY = "1LC"


def lb(w):
    return "[" + ", ".join("true" if ch == "1" else "false" for ch in w) + "]"


def param(txt):
    """make a symtm proof about `trans` / `steps` into one about `trans f0` / `steps f0`"""
    txt = re.sub(r"(?<![\w.])trans(?![\w'])", "(trans f0)", txt)
    txt = re.sub(r"(?<![\w.])steps (?=[\d(⟨])", "steps f0 ", txt)
    return txt


