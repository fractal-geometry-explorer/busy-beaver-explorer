#!/usr/bin/env python3
"""Write lean/Adic/V*.lean (each variant's E-pass in the 2-adic checker's form) and lean/Adic/Machines.lean (the
halting criterion of each machine through the checker).

For a variant, an E-event (c, n), n >= 6, gives a block of m = (3n + e(n mod 2))/2 ones and the parity bit
b = q mod 2 = b(n mod 4); the rewrite of c for b then adds a.  `e` and the set of r with b(r) = 1 are below; the
Lean proofs check them against the variant's `qOf` and `mOf` (`lean/V*/Map.lean`) with omega.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'lean', 'Adic')

# variant: F0 text, e(0), e(1), {r : b(r) = 1}
VARIANTS = {
    'VLC': ('1LC', 4, 7, (1, 2)),
    'VLA': ('1LA', 2, 5, (0, 3)),
    'VRB': ('1RB', 6, 9, (0, 3)),
}

# machine id: (TNF, variant, start state, context index of x0, n of x0)
MACHINES = [
    ('21328', '1RB---_1LC0RB_0LD0LC_1RE1RB_1RD1LF_1LA0LE', 'VLA', 0, 15),
    ('119593', '1RB0RF_1LC---_1RD0LC_0RE0RD_1LF1LC_1LE1RA', 'VLA', 2, 9),
    ('121010', '1RB0LA_0RC0RB_1LD1LA_1LC1RE_1RF0RD_1LC---', 'VLC', 0, 19),
    ('92948', '1RB0RE_1RC---_0RD0RC_1LE1LF_1LD1RA_1RC0LF', 'VRB', 0, 17),
    ('160156', '1RB0LA_0RC0RB_1LD1LA_1LC1RE_1RF0RD_1LA---', 'VLA', 1, 15),
    ('82614', '1RB---_0RC0RB_1LD1LE_1LC1RF_1RB0LE_1RA0RD', 'VRB', 1, 17),
    ('134470', '1RB0RF_1LC---_1LF1LD_1RE0LD_0RC0RE_1LC1RA', 'VLC', 0, 7),
]

VTEMPLATE = '''import {V}.Map
import Adic.Link

/-!
# The core with F0 = {F0} in the 2-adic checker's form

An E-event (c, n), n ≥ 6, gives a block of (3n + e(n mod 2))/2 ones, with e = {E0}, {E1}, and the parity bit
b(n mod 4) (1 for n mod 4 ∈ {{{BS}}}); `nextOK`, `haltOK` restate `{V}.nextE_sound`, `{V}.haltE_sound` so.
`tab` is the table the checker runs on.  Generated by `py/gen_adic.py`; do not edit by hand.
-/

namespace {V}.Adic

/-- The E-pass's offset, by the parity of n. -/
def e (p : Nat) : Nat := if p = 0 then {E0} else {E1}

/-- The parity bit q mod 2 of the pass, by n mod 4. -/
def b (r : Nat) : Bool := r == {B0} || r == {B1}

theorem mOf_eq (n a : Nat) (h6 : 6 ≤ n) : mOf n + a = (3 * n + (e (n % 4 % 2) + 2 * a)) / 2 := by
  unfold mOf qOf e
  repeat' split
  all_goals omega

theorem qOf_eq (n : Nat) (h6 : 6 ≤ n) : (qOf n % 2 = 0) = (b (n % 4) = false) := by
  unfold qOf b
  apply propext
  repeat' split
  all_goals (simp only [Bool.or_eq_false_iff, beq_eq_false_iff_ne, ne_eq]; omega)

theorem pick_eq (x : Option (List Bool × Nat) × Option (List Bool × Nat)) (n : Nat) (h6 : 6 ≤ n) :
    pick x n = (if b (n % 4) then x.2 else x.1) := by
  unfold pick
  have hq := qOf_eq n h6
  cases hb : b (n % 4)
  · have : qOf n % 2 = 0 := by rw [hq]; exact hb
    simp [this]
  · have : ¬ qOf n % 2 = 0 := by rw [hq, hb]; simp
    simp [this]

theorem nextOK : _root_.Adic.NextOK f0 e b := by
  intro c n x c' a h6 hl hp
  refine ⟨n, nextE_sound (y := (c', (3 * n + (e (n % 4 % 2) + 2 * a)) / 2)) ?_⟩
  unfold nextE
  rw [hl]
  simp only [show ¬ n < 6 by omega, ↓reduceIte, pick_eq x n h6, hp, Option.map_some, mOf_eq n a h6]

theorem haltOK : _root_.Adic.HaltOK f0 b := by
  intro c n x h6 hl hp
  apply haltE_sound
  unfold haltE
  rw [hl]
  simp only [show ¬ n < 6 by omega, decide_false, Bool.not_false, Bool.true_and, pick_eq x n h6, hp,
    Option.isNone_none]

/-- The table the checker runs on. -/
def tab : _root_.Adic.Tab := _root_.Adic.mkTab e b

end {V}.Adic
'''

MHEAD = '''{IMPORTS}
import Adic.Link

/-!
# The halting criterion of each machine through the 2-adic checker

For each of the seven machines: if `Adic.seg` (`s` segments of `L` passes, leaves of up to `Lf` passes, `f` levels
of halving) finds a halting entry on the orbit of the machine's first E-event, the machine halts from blank tape.
The first E-event is `x0` of `Machines/H<id>.lean`: context `Adic.ctx i` and n, with n the one-digit list `[n]`.
Generated by `py/gen_adic.py`; do not edit by hand.
-/
'''

MTEMPLATE = '''
namespace H{ID}

/-- {TNF}: `x0` is context {I} of the table. -/
theorem x0_ctx : _root_.Adic.ctx {I} = x0.1 := by decide

/-- **{TNF} halts** if the checker finds a halt on its orbit (`{V}`, from (context {I}, {N})). -/
theorem halts_of_seg (L Lf f s : Nat) (hL : 1 ≤ L)
    (h : _root_.Adic.seg {V}.Adic.tab L Lf f (3 ^ L) s {I} [{N}] = true) : HaltsFromBlank := by
  have r := x0_reaches
  have hv : _root_.Adic.val L [{N}] = {N} := by simp [_root_.Adic.val]
  rw [← x0_ctx, show x0.2.1 = {N} from rfl, ← hv] at r
  exact halts_iff.2 (_root_.Adic.halts_of_seg {V}.Adic.nextOK {V}.Adic.haltOK L Lf f s hL r (by rw [hv]; decide) h)

end H{ID}
'''


def main():
    os.makedirs(OUT, exist_ok=True)
    for v, (f0, e0, e1, bs) in VARIANTS.items():
        s = VTEMPLATE.format(V=v, F0=f0, E0=e0, E1=e1, BS=', '.join(map(str, bs)), B0=bs[0], B1=bs[1])
        open(os.path.join(OUT, v + '.lean'), 'w').write(s)
    imports = '\n'.join(['import Adic.' + v for v in VARIANTS] + ['import Machines.H' + m[0] for m in MACHINES])
    s = MHEAD.format(IMPORTS=imports)
    for mid, tnf, v, i, n in MACHINES:
        s += MTEMPLATE.format(ID=mid, TNF=tnf, V=v, I=i, N=n)
    open(os.path.join(OUT, 'Machines.lean'), 'w').write(s)


if __name__ == '__main__':
    main()
