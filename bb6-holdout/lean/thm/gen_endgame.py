"""Write the endgame's Lean files from endgame_sym.txt (the tree for every R >= 178, with R a coordinate, written by
`ExploreNC sym 178 448 endgame_sym.txt`) and endgame_small.txt (lines 'R tokens...': one tree for each even R < 178,
the closing set included, written by `ExploreNC 176 448 "" endgame_small.txt`): EndgameStart.lean (the start classes
and the closing classes), EndgamePieces0.lean, ... (the subtree theorems, `decide +kernel`, spread over `modules`
files that compile in parallel) and EndgameTheorem.lean (the assembled checks and `endgame_stretch`).
usage: gen_endgame.py endgame_sym.txt endgame_small.txt OUTDIR [budget=40] [modules=4]"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from treegen import parse, cut, write_modules, leaves, OKEND

RLO = 178
sym = parse(open(sys.argv[1]).read().split())
small = []
for line in open(sys.argv[2]).read().split('\n'):
    if line.strip():
        toks = line.split()
        small.append((int(toks[0]), parse(toks[1:])))
outdir = sys.argv[3]
budget = int(sys.argv[4]) if len(sys.argv) > 4 else 40
nmod = int(sys.argv[5]) if len(sys.argv) > 5 else 4
assert [R for R, _ in small] == list(range(2, RLO, 2)), 'endgame_small.txt must hold every even R < 178, in order'

ksym = OKEND('448 1000 4 none EndSpec.endgame')
sym_skel, sym_proof, pieces = cut(sym, ksym, 'symStartE', 'egSymP', budget)
pieces = [p + (ksym,) for p in pieces]
small_out = []
for R, t in small:
    k = OKEND(f'448 1000 3 (closeClass {R}) EndSpec.endgame')
    skel, proof, ps = cut(t, k, f'startE {R}', f'egR{R}P', budget)
    small_out.append((R, skel, proof))
    pieces += [p + (k,) for p in ps]

start = r'''import BB6.Ends
open BB6 BB6.Sym

/-! # The endgame's start classes (generated by `thm/gen_endgame.py`; see `EndgameTheorem.lean`)

The phase-0 pass starts: walls at a = 1 + 2 y₀, b = 2 y₁ and c = E − R − 1, width E = 2 y₂, with the cone gaps a,
b − a and c − b.  `startR R` fixes R; in `symStart` the right end R = 2 y₃ is a fourth coordinate, with R ≥ 178 a
fourth cone form.  The tree checks carry the right end and the left countdown L₁ = 147 b + 280 E − 392 c − 578
(`startE`, `symStartE`). -/

/-- The right ends from whose pass starts the run can close. -/
def closingSet : List Nat := [2, 4, 8, 16, 24, 32, 48, 64, 176]

/-- The closing set with the class of L₁ that a close needs: (R, m, c) means L₁ % m = c. -/
def closeClasses : List (Nat × Int × Int) :=
  [(2, 2, 0), (4, 2, 0), (8, 8, 0), (16, 32, 0), (24, 64, 32), (32, 64, 0), (48, 128, 0), (64, 128, 0),
   (176, 128, 0)]

/-- The class of L₁ (modulus, residue) that a close from right end R needs, for R in the closing set. -/
def closeClass (R : Nat) : Option (Int × Int) := (closeClasses.find? (·.1 == R)).map (·.2)

theorem closeClass_closing {R : Nat} {p : Int × Int} (h : closeClass R = some p) : closingSet.contains R = true := by
  unfold closeClass at h
  cases hf : closeClasses.find? (·.1 == R) with
  | none => rw [hf] at h; cases h
  | some x =>
    have hx := List.mem_of_find?_eq_some hf
    have hp := List.find?_some hf
    simp only [beq_iff_eq] at hp
    subst hp
    simp only [closeClasses, List.mem_cons, List.mem_nil_iff, or_false] at hx
    rcases hx with rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl <;> rfl

def startR (R : Nat) : SState :=
  let a : YForm := ⟨1, [2, 0, 0]⟩
  let b : YForm := ⟨0, [0, 2, 0]⟩
  let E : YForm := ⟨0, [0, 0, 2]⟩
  let c := E.addc (-(R : Int) - 1)
  ([⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, c⟩], E, [a, b.sub a, c.sub b])

def startE (R : Nat) : EState :=
  (startR R, YForm.const R, L1Form ⟨0, [0, 2, 0]⟩ ((⟨0, [0, 0, 2]⟩ : YForm).addc (-(R : Int) - 1)) ⟨0, [0, 0, 2]⟩)

def symStart : SState :=
  let a : YForm := ⟨1, [2, 0, 0, 0]⟩
  let b : YForm := ⟨0, [0, 2, 0, 0]⟩
  let E : YForm := ⟨0, [0, 0, 2, 0]⟩
  let R : YForm := ⟨0, [0, 0, 0, 2]⟩
  let c := (E.sub R).addc (-1)
  ([⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, c⟩], E, [a, b.sub a, c.sub b, R.addc (448 - 178)])

def symStartE : EState := (symStart, ⟨0, [0, 0, 0, 2]⟩, YForm.const 0)
'''
open(os.path.join(outdir, 'EndgameStart.lean'), 'w').write(start)

header = r'''import EndgameStart
open BB6 BB6.Sym

/-! # Subtree checks of the endgame trees (generated by `thm/gen_endgame.py`; assembled in `EndgameTheorem.lean`) -/
'''
mods, load = write_modules(outdir, 'EndgamePieces', header, None, pieces, nmod)

small_defs = '\n'.join(
    f'def egTree{R} : Tree := {skel}\n\n'
    f'theorem egTree{R}_ok : egTree{R}.okEnd 448 1000 3 (closeClass {R}) EndSpec.endgame false (startE {R}).1.1\n'
    f'    (startE {R}).1.2.1 (startE {R}).1.2.2 (startE {R}).2.1 (startE {R}).2.2 0 none = true :=\n'
    f'  {proof}\n'
    for R, skel, proof in small_out)
small_list = ', '.join(f'({R}, egTree{R})' for R, _, _ in small_out)
small_ok = ''.join(f'List.forall_mem_cons.2 ⟨egTree{R}_ok, ' for R, _, _ in small_out) + \
    'fun _ h => nomatch h' + '⟩' * len(small_out)

lean = r'''IMPORTS
open BB6 BB6.Sym

/-! # The endgame as a theorem

The phase-0 pass starts with R ≥ 178 form one class, with R a coordinate (`symStart`); for each even R < 178, the pass
starts with that R form a class (`startR R`).  A tree of coordinate splits and skews for each class (built by the
untrusted program `ExploreNC.lean`, so it covers the class by construction; `adv` nodes run the rounds before a split
once for the whole subtree) is checked by the proved function `Tree.okEnd`, evaluated by the kernel (`decide +kernel`;
no compiler is trusted): every leaf's run is close-free and ends at an end event (`BB6/Ends.lean`), or, for R in the
closing set, the leaf shows L₁ in R's class.  The checks are cut into subtrees with a theorem each, in the modules
`EndgamePieces0`, … (compiled in parallel), and assembled here by `Tree.okEnd_node` and `Tree.okEnd_skew`.
`endgame_stretch` is the statement for the machine. -/

/-- The tree for every R ≥ 178. -/
def symTree : Tree := SYMSKEL

theorem sym_tree_ok : symTree.okEnd 448 1000 4 none EndSpec.endgame false symStartE.1.1 symStartE.1.2.1
    symStartE.1.2.2 symStartE.2.1 symStartE.2.2 0 none = true :=
  SYMPROOF

SMALLDEFS
/-- The trees for the even R < 178. -/
def smallTrees : List (Nat × Tree) := [SMALLLIST]

theorem small_trees_ok :
    ∀ p ∈ smallTrees, p.2.okEnd 448 1000 3 (closeClass p.1) EndSpec.endgame false (startE p.1).1.1
      (startE p.1).1.2.1 (startE p.1).1.2.2 (startE p.1).2.1 (startE p.1).2.2 0 none = true :=
  SMALLOK

theorem small_trees_cover :
    ((List.range 88).all fun r => smallTrees.any fun (p : Nat × Tree) => p.1 == 2 * (r + 1)) = true := by
  decide +kernel

/-- **The endgame, for the machine.**  For every even R ≥ 2 and every phase-0 pass start — walls at a, b and
c = E − R − 1, width E, with a odd, b even, E even and every gap at least 448 — either R is in the closing set and
the left countdown L₁ = 147 b + 280 E − 392 c − 578 is in R's class (`closeClass`), or the machine runs n rounds
without halting, reaching the round start that `roundsZ` computes, every end meeting on the way is at distance at
least 3 (no close), and the run ends at an end event (`EndEvent`): it left phase 0 (round 1 not G B W or round 2 not
G M B), its end meetings left the halving chain, or it is at a phase-0 pass start with a smaller even right end whose
next two rounds are G B W and G M B.  None of these holds after zero rounds (`not_endEvent_zero`). -/
theorem endgame_stretch (R : Nat) (hR : R % 2 = 0) (hR2 : 2 ≤ R)
    (a b E : Nat) (ha : a % 2 = 1) (hb : b % 2 = 0) (hE : E % 2 = 0)
    (h1 : 448 ≤ a) (h2 : a + 448 ≤ b) (h3 : b + 448 + R + 1 ≤ E) :
    (∃ m c, closeClass R = some (m, c) ∧ loopL1 b (E - R - 1) E % m = c) ∨
    ∃ n kk ms' W', steps kk (roundStart [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E) = some (roundStart ms' W') ∧
      roundsZ 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E = .newRound ms' W' ∧
      (∀ d ∈ meetsRounds 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E, 3 ≤ d) ∧
      EndEvent 1000 R n (meetsRounds 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E) ms' W' := by
  by_cases hR178 : 178 ≤ R
  · -- the tree for every R ≥ 178, at the point (a, b, E, R)
    let y : List Int := [((a : Int) - 1) / 2, (b : Int) / 2, (E : Int) / 2, (R : Int) / 2]
    have hy : inCone symStart.2.2 448 y := by
      intro f hf
      simp only [symStart, List.mem_cons, List.mem_nil_iff, or_false] at hf
      rcases hf with rfl | rfl | rfl | rfl <;>
        simp only [y, YForm.eval, YForm.sub, YForm.add, YForm.neg, YForm.addc, addL, smulL, List.map, dot] <;> omega
    have hs : agL y symStart.1 [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] := by
      refine ⟨⟨rfl, ?_⟩, ⟨rfl, ?_⟩, ⟨rfl, ?_⟩, trivial⟩ <;>
        simp only [agN, y, YForm.eval, YForm.sub, YForm.add, YForm.neg, YForm.addc, addL, smulL, List.map, dot] <;>
        omega
    have hW : agN y symStart.2.1 E := by simp only [agN, y, symStart, YForm.eval, dot]; omega
    have hRa : agN y symStartE.2.1 R := by simp only [agN, y, symStartE, YForm.eval, dot]; omega
    rcases Tree.soundEnd 448 1000 4 none .endgame symTree false _ _ _ _ _ 0 none sym_tree_ok y rfl hy _ _ R 0 []
        hs hW hRa (by simp [symStartE, YForm.const, YForm.eval]) (fun h => by cases h) (fun _ h => by cases h) with
      ⟨_, _, h, -⟩ | h
    · cases h
    · simp only [List.nil_append, Nat.zero_add] at h
      exact Or.inr h
  · -- the tree for R
    have hcov := small_trees_cover
    rw [List.all_eq_true] at hcov
    have hr := hcov (R / 2 - 1) (by simp only [List.mem_range]; omega)
    have e : 2 * (R / 2 - 1 + 1) = R := by omega
    rw [e, List.any_eq_true] at hr
    obtain ⟨⟨R', t⟩, hmem, hR'⟩ := hr
    simp only [beq_iff_eq] at hR'
    subst hR'
    have ht := small_trees_ok _ hmem
    simp only at ht
    let y : List Int := [((a : Int) - 1) / 2, (b : Int) / 2, (E : Int) / 2]
    have hy : inCone (startR R').2.2 448 y := by
      intro f hf
      simp only [startR, List.mem_cons, List.mem_nil_iff, or_false] at hf
      rcases hf with rfl | rfl | rfl <;>
        simp only [y, YForm.eval, YForm.sub, YForm.add, YForm.neg, YForm.addc, addL, smulL, List.map, dot] <;> omega
    have hs : agL y (startR R').1 [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R' - 1⟩] := by
      refine ⟨⟨rfl, ?_⟩, ⟨rfl, ?_⟩, ⟨rfl, ?_⟩, trivial⟩ <;>
        simp only [agN, y, YForm.eval, YForm.addc, dot] <;> omega
    have hW : agN y (startR R').2.1 E := by simp only [agN, y, startR, YForm.eval, dot]; omega
    have hRa : agN y (startE R').2.1 R' := by simp [agN, startE, YForm.const, YForm.eval]
    have hL : loopL1 b (E - R' - 1) E = (startE R').2.2.eval y := by
      simp only [startE, eval_L1Form, loopL1]
      simp only [y, YForm.eval, YForm.addc, dot]
      omega
    rcases Tree.soundEnd 448 1000 3 (closeClass R') .endgame t false _ _ _ _ _ 0 none ht y rfl hy _ _ R'
        (loopL1 b (E - R' - 1) E) [] hs hW hRa hL (fun h => by cases h) (fun _ h => by cases h) with h | h
    · exact Or.inl h
    · simp only [List.nil_append, Nat.zero_add] at h
      exact Or.inr h

/-- **No close from a right end outside the closing set.**  For R outside {2, 4, 8, 16, 24, 32, 48, 64, 176}, the
stretch of `endgame_stretch` always runs: close-free, to an end event. -/
theorem endgame_no_close (R : Nat) (hR : R % 2 = 0) (hR2 : 2 ≤ R) (hS : closingSet.contains R = false)
    (a b E : Nat) (ha : a % 2 = 1) (hb : b % 2 = 0) (hE : E % 2 = 0)
    (h1 : 448 ≤ a) (h2 : a + 448 ≤ b) (h3 : b + 448 + R + 1 ≤ E) :
    ∃ n kk ms' W', steps kk (roundStart [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E) = some (roundStart ms' W') ∧
      roundsZ 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E = .newRound ms' W' ∧
      (∀ d ∈ meetsRounds 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E, 3 ≤ d) ∧
      EndEvent 1000 R n (meetsRounds 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E) ms' W' := by
  rcases endgame_stretch R hR hR2 a b E ha hb hE h1 h2 h3 with ⟨_, _, hc, -⟩ | h
  · rw [closeClass_closing hc] at hS; cases hS
  · exact h

/-- L₁ ≡ 3 (mod 7) at every pass start, so each class of `closeClasses` is a class modulo 7 m: 10 mod 14 (R = 2, 4),
24 mod 56 (8), 192 mod 224 (16), 416 mod 448 (24), 192 mod 448 (32) and 640 mod 896 (48, 64, 176). -/
theorem loopL1_mod7 (b c E : Nat) : loopL1 b c E % 7 = 3 := by
  unfold loopL1; omega
'''
lean = (lean.replace('IMPORTS', '\n'.join(f'import {m}' for m in mods))
        .replace('SYMSKEL', sym_skel).replace('SYMPROOF', sym_proof)
        .replace('SMALLDEFS', small_defs).replace('SMALLLIST', small_list).replace('SMALLOK', small_ok))
open(os.path.join(outdir, 'EndgameTheorem.lean'), 'w').write(lean)
print(f'wrote EndgameStart, {", ".join(mods)}, EndgameTheorem: the tree for R >= {RLO} ({leaves(sym)} leaves) and '
      f'{len(small)} trees for R < {RLO} ({sum(leaves(t) for _, t in small)} leaves), {len(pieces)} subtree theorems, '
      f'module costs {load}')
