"""Write the endgame's Lean files from endgame_sym.txt (the tree for every R >= 178, with R a coordinate, written by
`ExploreNC sym 178 448 endgame_sym.txt`) and endgame_small.txt (lines 'R tokens...': one tree for each even R < 178
outside the closing set, written by `ExploreNC 0 448 6,10,12,... endgame_small.txt`): EndgameStart.lean (the start
classes), EndgamePieces0.lean, ... (the subtree theorems, `decide +kernel`, spread over `modules` files that compile in
parallel) and EndgameTheorem.lean (the assembled checks and `endgame_no_close`).
usage: gen_endgame.py endgame_sym.txt endgame_small.txt OUTDIR [budget=40] [modules=4]"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from treegen import parse, cut, write_modules, leaves, OKNC

CLOSING = [2, 4, 8, 16, 24, 32, 48, 64, 176]
RLO = 178
sym = parse(open(sys.argv[1]).read().split())
small = []
for line in open(sys.argv[2]).read().split('\n'):
    if line.strip():
        toks = line.split()
        small.append((int(toks[0]), parse(toks[1:])))
outdir = sys.argv[3]
budget = int(sys.argv[4]) if len(sys.argv) > 4 else 40
nmod = int(sys.argv[5]) if len(sys.argv) > 5 else 4
assert [R for R, _ in small] == [R for R in range(2, RLO, 2) if R not in CLOSING], \
    'endgame_small.txt must hold the even R < 178 outside the closing set, in order'

ksym = OKNC('448 1000 4')
ksmall = OKNC('448 1000 3')
sym_skel, sym_proof, pieces = cut(sym, ksym, 'symStart', 'egSymP', budget)
pieces = [p + (ksym,) for p in pieces]
small_out = []
for R, t in small:
    skel, proof, ps = cut(t, ksmall, f'startR {R}', f'egR{R}P', budget)
    small_out.append((R, skel, proof))
    pieces += [p + (ksmall,) for p in ps]

start = r'''import BB6.Meets
open BB6 BB6.Sym

/-! # The endgame's start classes (generated by `thm/gen_endgame.py`; see `EndgameTheorem.lean`)

The phase-0 pass starts: walls at a = 1 + 2 y₀, b = 2 y₁ and c = E − R − 1, width E = 2 y₂, with the cone gaps a,
b − a and c − b.  `startR R` fixes R; in `symStart` the right end R = 2 y₃ is a fourth coordinate, with R ≥ 178 a
fourth cone form. -/

/-- The right ends R from whose pass starts the run can close. -/
def closingSet : List Nat := [2, 4, 8, 16, 24, 32, 48, 64, 176]

def startR (R : Nat) : SState :=
  let a : YForm := ⟨1, [2, 0, 0]⟩
  let b : YForm := ⟨0, [0, 2, 0]⟩
  let E : YForm := ⟨0, [0, 0, 2]⟩
  let c := E.addc (-(R : Int) - 1)
  ([⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, c⟩], E, [a, b.sub a, c.sub b])

def symStart : SState :=
  let a : YForm := ⟨1, [2, 0, 0, 0]⟩
  let b : YForm := ⟨0, [0, 2, 0, 0]⟩
  let E : YForm := ⟨0, [0, 0, 2, 0]⟩
  let R : YForm := ⟨0, [0, 0, 0, 2]⟩
  let c := (E.sub R).addc (-1)
  ([⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, c⟩], E, [a, b.sub a, c.sub b, R.addc (448 - 178)])
'''
open(os.path.join(outdir, 'EndgameStart.lean'), 'w').write(start)

header = r'''import EndgameStart
open BB6 BB6.Sym

/-! # Subtree checks of the endgame trees (generated by `thm/gen_endgame.py`; assembled in `EndgameTheorem.lean`) -/
'''
mods, load = write_modules(outdir, 'EndgamePieces', header, None, pieces, nmod)

small_defs = '\n'.join(
    f'def egTree{R} : Tree := {skel}\n\n'
    f'theorem egTree{R}_ok : egTree{R}.okNC 448 1000 3 false (startR {R}).1 (startR {R}).2.1 (startR {R}).2.2 = true :=\n'
    f'  {proof}\n'
    for R, skel, proof in small_out)
small_list = ', '.join(f'({R}, egTree{R})' for R, _, _ in small_out)
small_ok = ''.join(f'List.forall_mem_cons.2 ⟨egTree{R}_ok, ' for R, _, _ in small_out) + \
    'fun _ h => nomatch h' + '⟩' * len(small_out)

lean = r'''IMPORTS
open BB6 BB6.Sym

/-! # The endgame as a theorem

The phase-0 pass starts with R ≥ 178 form one class, with R a coordinate (`symStart`); for each even R < 178 outside
the closing set, the pass starts with that R form a class (`startR R`).  A tree of coordinate splits and skews for each
class (built by the untrusted program `ExploreNC.lean`, so it covers the class by construction; `adv` nodes run the
rounds before a split once for the whole subtree) is checked by the proved function `Tree.okNC`, evaluated by the
kernel (`decide +kernel`; no compiler is trusted).  The checks are cut into subtrees with a theorem each, in the
modules `EndgamePieces0`, … (compiled in parallel), and assembled here by `Tree.okNC_node` and `Tree.okNC_skew`.
`endgame_no_close` is the statement for the machine. -/

/-- The tree for every R ≥ 178. -/
def symTree : Tree := SYMSKEL

theorem sym_tree_ok : symTree.okNC 448 1000 4 false symStart.1 symStart.2.1 symStart.2.2 = true :=
  SYMPROOF

SMALLDEFS
/-- The trees for the even R < 178 outside the closing set. -/
def smallTrees : List (Nat × Tree) := [SMALLLIST]

theorem small_trees_ok :
    ∀ p ∈ smallTrees, p.2.okNC 448 1000 3 false (startR p.1).1 (startR p.1).2.1 (startR p.1).2.2 = true :=
  SMALLOK

theorem small_trees_cover :
    ((List.range 88).all fun r => closingSet.contains (2 * (r + 1)) ||
      smallTrees.any fun (p : Nat × Tree) => p.1 == 2 * (r + 1)) = true := by
  decide +kernel

/-- **The endgame, for the machine.**  For every even R ≥ 2 outside the closing set {2, 4, 8, 16, 24, 32, 48, 64,
176}, and every phase-0 pass start — walls at a, b and c = E − R − 1, width E, with a odd, b even, E even and every gap
at least 448 — the machine runs a number of rounds (up to the round at which this start's pass completes, its
end-meeting chain breaks, or it leaves phase 0, per the tree) without halting, reaching a round start (the one
`roundsZ` computes: the mark model covers these rounds), and every end meeting on the way is at distance at least 3:
the run does not close. -/
theorem endgame_no_close (R : Nat) (hR : R % 2 = 0) (hR2 : 2 ≤ R) (hS : closingSet.contains R = false)
    (a b E : Nat) (ha : a % 2 = 1) (hb : b % 2 = 0) (hE : E % 2 = 0)
    (h1 : 448 ≤ a) (h2 : a + 448 ≤ b) (h3 : b + 448 + R + 1 ≤ E) :
    ∃ n kk ms' W', steps kk (roundStart [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E) = some (roundStart ms' W') ∧
      roundsZ 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E = .newRound ms' W' ∧
      ∀ d ∈ meetsRounds 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E, 3 ≤ d := by
  by_cases hR178 : 178 ≤ R
  · -- the tree for every R ≥ 178, at the point (a, b, E, R)
    let y : List Int := [((a : Int) - 1) / 2, (b : Int) / 2, (E : Int) / 2, (R : Int) / 2]
    have hy : inCone symStart.2.2 448 y := by
      intro f hf
      simp only [symStart, List.mem_cons, List.mem_nil_iff, or_false] at hf
      rcases hf with rfl | rfl | rfl | rfl <;>
        simp only [y, YForm.eval, YForm.sub, YForm.add, YForm.neg, YForm.addc, addL, smulL, List.map, dot] <;> omega
    have hs : agL y symStart.1 [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] := by
      refine ⟨⟨rfl, ?_⟩, ⟨rfl, ?_⟩, ⟨rfl, ?_⟩, trivial⟩ <;>
        simp only [agN, y, YForm.eval, YForm.sub, YForm.add, YForm.neg, YForm.addc, addL, smulL, List.map, dot] <;>
        omega
    have hW : agN y symStart.2.1 E := by simp only [agN, y, symStart, YForm.eval, dot]; omega
    exact Tree.soundNC 448 1000 4 symTree false _ _ _ sym_tree_ok y rfl hy _ _ hs hW (fun h => by cases h)
  · -- the tree for R
    have hcov := small_trees_cover
    rw [List.all_eq_true] at hcov
    have hr := hcov (R / 2 - 1) (by simp only [List.mem_range]; omega)
    have e : 2 * (R / 2 - 1 + 1) = R := by omega
    rw [e, hS, Bool.false_or, List.any_eq_true] at hr
    obtain ⟨⟨R', t⟩, hmem, hR'⟩ := hr
    simp only [beq_iff_eq] at hR'
    subst hR'
    have ht := small_trees_ok _ hmem
    simp only at ht
    let y : List Int := [((a : Int) - 1) / 2, (b : Int) / 2, (E : Int) / 2]
    have hy : inCone (startR R').2.2 448 y := by
      intro f hf
      simp only [startR, List.mem_cons, List.mem_nil_iff, or_false] at hf
      rcases hf with rfl | rfl | rfl <;>
        simp only [y, YForm.eval, YForm.sub, YForm.add, YForm.neg, YForm.addc, addL, smulL, List.map, dot] <;> omega
    have hs : agL y (startR R').1 [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R' - 1⟩] := by
      refine ⟨⟨rfl, ?_⟩, ⟨rfl, ?_⟩, ⟨rfl, ?_⟩, trivial⟩ <;>
        simp only [agN, y, YForm.eval, YForm.addc, dot] <;> omega
    have hW : agN y (startR R').2.1 E := by simp only [agN, y, startR, YForm.eval, dot]; omega
    exact Tree.soundNC 448 1000 3 t false _ _ _ ht y rfl hy _ _ hs hW (fun h => by cases h)
'''
lean = (lean.replace('IMPORTS', '\n'.join(f'import {m}' for m in mods))
        .replace('SYMSKEL', sym_skel).replace('SYMPROOF', sym_proof)
        .replace('SMALLDEFS', small_defs).replace('SMALLLIST', small_list).replace('SMALLOK', small_ok))
open(os.path.join(outdir, 'EndgameTheorem.lean'), 'w').write(lean)
print(f'wrote EndgameStart, {", ".join(mods)}, EndgameTheorem: the tree for R >= {RLO} ({leaves(sym)} leaves) and '
      f'{len(small)} trees for R < {RLO} ({sum(leaves(t) for _, t in small)} leaves), {len(pieces)} subtree theorems, '
      f'module costs {load}')
