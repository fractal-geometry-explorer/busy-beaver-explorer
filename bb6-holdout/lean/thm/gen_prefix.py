"""Write the kernel-checked prefix from the checkpoints that PrefixGen.lean prints: PrefixPieces0.lean, … (one theorem
per stretch between consecutive checkpoints, `decide +kernel`, spread over `modules` files that compile in parallel)
and PrefixKernel.lean (the stretches chained: from the first round start to the last checkpoint, a one-marker clean
tape, and from blank tape to it).
usage: gen_prefix.py checkpoints.txt OUTDIR [modules=4]"""
import os
import sys

lines = [l.split() for l in open(sys.argv[1]) if l.strip()]
outdir = sys.argv[2]
nmod = int(sys.argv[3]) if len(sys.argv) > 3 else 4


def marks(toks):
    return '[' + ', '.join('⟨.%s, %s⟩' % (toks[i], toks[i + 1]) for i in range(0, len(toks), 2)) + ']'


cps = [(int(l[0]), int(l[1]), marks(l[2:])) for l in lines]
assert cps[0] == (0, 5, '[]'), cps[0]
last_r, last_W, last_ms = cps[-1]
assert last_ms == '[⟨.M, %d⟩]' % (last_W - 2), cps[-1]
npieces = len(cps) - 1
per = -(-npieces // nmod)
mods = []
for j in range(nmod):
    idx = range(j * per, min(npieces, (j + 1) * per))
    if not idx:
        continue
    out = ['import PrefixBase', '', 'namespace BB6', '',
           '/-! # Stretches of the run from blank tape (generated by `thm/gen_prefix.py`; chained in '
           '`PrefixKernel.lean`) -/', '']
    for i in idx:
        r0, W0, ms0 = cps[i]
        r1, W1, ms1 = cps[i + 1]
        out.append('theorem pfx%d : (roundsZ 1000 %d %s %d).isRound\n    %s %d = true := by decide +kernel'
                   % (i, r1 - r0, ms0, W0, ms1, W1))
    out += ['', 'end BB6', '']
    name = 'PrefixPieces%d' % j
    open(os.path.join(outdir, name + '.lean'), 'w').write('\n'.join(out))
    mods.append(name)

SUP = str.maketrans('0123456789', '⁰¹²³⁴⁵⁶⁷⁸⁹')
width = '{:,}'.format(last_W)
if last_W & (last_W - 1) == 0:
    width = '2%s = %s' % (str(last_W.bit_length() - 1).translate(SUP), width)
body = ['import ' + m for m in mods] + ['', r'''/-!
# From blank tape to the clean tape of width %s, checked by the kernel

Generated by `thm/gen_prefix.py` from the checkpoints of `PrefixGen.lean`.  The mark model, run from the first round
start (`roundStart [] 5`, 17 steps from blank tape), covers %s rounds and arrives at the one-marker clean tape of
width %s.  The run is checked in %d stretches (`pfx0`, …, in `PrefixPieces*.lean`), each by Lean's kernel
(`decide +kernel`: no compiled code is trusted), and `roundsZ_chain` puts them together.  (`thm/Prefix.lean` goes on
to width 2³², 1.2 × 10⁹ rounds, which only `native_decide` can evaluate in reasonable time.)
-/

namespace BB6

/-- The width of the clean tape that the kernel-checked prefix reaches. -/
def kernelPrefixWidth : Nat := %d

/-- The number of mark-model rounds from the first round start to that clean tape. -/
def kernelPrefixRounds : Nat := %d
''' % (width, '{:,}'.format(last_r), width, npieces, last_W, last_r)]
body.append('''theorem kernel_prefix_rounds :
    roundsZ 1000 kernelPrefixRounds [] 5 = .newRound [⟨.M, kernelPrefixWidth - 2⟩] kernelPrefixWidth := by
  have h := PR'.isRound_eq pfx0''')
for i in range(1, npieces):
    body.append("  have h := roundsZ_chain h (PR'.isRound_eq pfx%d)" % i)
body.append('  exact h')
body.append('')
body.append(r'''/-- **From blank tape, the machine reaches the clean tape of width `kernelPrefixWidth`** without halting
on the way; checked by the kernel alone. -/
theorem blank_prefix_kernel :
    ∃ k, steps k ⟨blank, blank, .A⟩ = some (roundStart [⟨.M, kernelPrefixWidth - 2⟩] kernelPrefixWidth) := by
  obtain ⟨k, hk⟩ := blank_rounds 1000 kernelPrefixRounds (by rw [kernel_prefix_rounds]; intro h; cases h)
  rw [kernel_prefix_rounds] at hk
  exact ⟨k, hk⟩

#print axioms blank_prefix_kernel

end BB6
''')
open(os.path.join(outdir, 'PrefixKernel.lean'), 'w').write('\n'.join(body))
print('%d stretches in %d modules; %d rounds to the clean tape of width %d' % (npieces, len(mods), last_r, last_W))
