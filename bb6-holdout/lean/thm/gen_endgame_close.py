"""Write the Lean files of the endgame with end meetings at distance 2 passed from endgame_close.txt (lines
'R tokens...': one tree for each R of `closeTreeRs`, written by `ExploreNC close 448 8,16,24,32,64,176
endgame_close.txt`): EndgameCloseStart.lean (the right ends and their close classes), EndgameClosePieces0.lean, ...
(the subtree theorems, `decide +kernel`, spread over `modules` files that compile in parallel) and
EndgameCloseTheorem.lean (the assembled checks and `endgame_stretch_close`).
usage: gen_endgame_close.py endgame_close.txt OUTDIR [budget=40] [modules=2]"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from treegen import Kind, parse, cut, write_modules, leaves, es_proj

RS = [8, 16, 24, 32, 64, 176]
trees = []
for line in open(sys.argv[1]).read().split('\n'):
    if line.strip():
        toks = line.split()
        trees.append((int(toks[0]), parse(toks[1:])))
outdir = sys.argv[2]
budget = int(sys.argv[3]) if len(sys.argv) > 3 else 40
nmod = int(sys.argv[4]) if len(sys.argv) > 4 else 2
assert [R for R, _ in trees] == RS, f'endgame_close.txt must hold the trees for R = {RS}, in order'

OKENDC = lambda args: Kind('okEndC', args, 'esSplit', 'esSkew', lambda es: es_proj(es) + ' false', 'Tree.okEndC')
pieces = []
out = []
for R, t in trees:
    k = OKENDC(f'448 1000 3 (closeClassC {R})')
    skel, proof, ps = cut(t, k, f'startE {R}', f'egcR{R}P', budget)
    out.append((R, skel, proof))
    pieces += [p + (k,) for p in ps]

start = r'''import EndgameStart
import BB6.EndgameClose
open BB6 BB6.Sym

/-! # The endgame's close classes with end meetings at distance 2 passed (generated by `thm/gen_endgame_close.py`;
see `EndgameCloseTheorem.lean`)

The endgame trees of `EndgameTheorem.lean` stop at every end meeting at a constant distance ≤ 2.  An end meeting at
distance 2 is not a close: the chain puts the next one at distance 0, and when it is anywhere else the run has left
the halving chain.  For the right ends `closeTreeRs`, the trees of `EndgameCloseTheorem.lean` pass such meetings
(`Tree.okEndC`).  Their close leaves, at end meetings at distance 0, need the classes `closeClassesR`: L₁ ≡ 0 mod 32
for R = 8, 0 mod 64 for R = 16 and 0 mod 128 for R = 32.  These are the classes of the closes at width ≡ 0 mod 4 in
`PassHaltClasses.lean`, and R = 24, 64 and 176 do not close at all.  `closeClassC` is the class that a close from
any right end needs. -/

/-- The right ends whose endgame trees pass end meetings at distance 2. -/
def closeTreeRs : List Nat := [8, 16, 24, 32, 64, 176]

/-- Their classes of L₁ that a close needs: (R, m, c) means L₁ % m = c; R = 24, 64 and 176 have none. -/
def closeClassesR : List (Nat × Int × Int) := [(8, 32, 0), (16, 64, 0), (32, 128, 0)]

/-- The class of L₁ (modulus, residue) that a close from right end R needs: from `closeClassesR` for R in
`closeTreeRs`, else `closeClass R`. -/
def closeClassC (R : Nat) : Option (Int × Int) :=
  if closeTreeRs.contains R then (closeClassesR.find? (·.1 == R)).map (·.2) else closeClass R

theorem closeClassC_eq {R : Nat} (h : closeTreeRs.contains R = false) : closeClassC R = closeClass R := by
  unfold closeClassC; simp only [h, Bool.false_eq_true, ite_false]

/-- Each class of `closeClassC` lies in R's class of `closeClass`. -/
theorem closeClassC_sub {R : Nat} {m c L : Int} (h : closeClassC R = some (m, c)) (hL : L % m = c) :
    ∃ m' c', closeClass R = some (m', c') ∧ L % m' = c' := by
  unfold closeClassC at h
  split at h
  · rename_i hR
    have : R = 8 ∨ R = 16 ∨ R = 24 ∨ R = 32 ∨ R = 64 ∨ R = 176 := by simpa [closeTreeRs] using hR
    rcases this with rfl | rfl | rfl | rfl | rfl | rfl <;> simp [closeClassesR] at h
    · obtain ⟨rfl, rfl⟩ := h; exact ⟨8, 0, rfl, by omega⟩
    · obtain ⟨rfl, rfl⟩ := h; exact ⟨32, 0, rfl, by omega⟩
    · obtain ⟨rfl, rfl⟩ := h; exact ⟨64, 0, rfl, by omega⟩
  · exact ⟨m, c, h, hL⟩

/-- The right ends from which a close is left: 2, 4, 8, 16, 32 and 48. -/
theorem closeClassC_closing {R : Nat} {p : Int × Int} (h : closeClassC R = some p) :
    R = 2 ∨ R = 4 ∨ R = 8 ∨ R = 16 ∨ R = 32 ∨ R = 48 := by
  unfold closeClassC at h
  split at h
  · rename_i hR
    have : R = 8 ∨ R = 16 ∨ R = 24 ∨ R = 32 ∨ R = 64 ∨ R = 176 := by simpa [closeTreeRs] using hR
    rcases this with rfl | rfl | rfl | rfl | rfl | rfl <;> simp [closeClassesR] at h <;> omega
  · rename_i hR
    have h1 : R = 2 ∨ R = 4 ∨ R = 8 ∨ R = 16 ∨ R = 24 ∨ R = 32 ∨ R = 48 ∨ R = 64 ∨ R = 176 := by
      simpa [closingSet] using closeClass_closing h
    have h2 : ¬ (R = 8 ∨ R = 16 ∨ R = 24 ∨ R = 32 ∨ R = 64 ∨ R = 176) := by simpa [closeTreeRs] using hR
    omega
'''
open(os.path.join(outdir, 'EndgameCloseStart.lean'), 'w').write(start)

header = r'''import EndgameCloseStart
open BB6 BB6.Sym

/-! # Subtree checks of the endgame trees with end meetings at distance 2 passed (generated by
`thm/gen_endgame_close.py`; assembled in `EndgameCloseTheorem.lean`) -/
'''
mods, load = write_modules(outdir, 'EndgameClosePieces', header, None, pieces, nmod)

defs = '\n'.join(
    f'def egcTree{R} : Tree := {skel}\n\n'
    f'theorem egcTree{R}_ok : egcTree{R}.okEndC 448 1000 3 (closeClassC {R}) false (startE {R}).1.1\n'
    f'    (startE {R}).1.2.1 (startE {R}).1.2.2 (startE {R}).2 0 none false = true :=\n'
    f'  {proof}\n'
    for R, skel, proof in out)
tlist = ', '.join(f'({R}, egcTree{R})' for R, _, _ in out)
tok = ''.join(f'List.forall_mem_cons.2 ⟨egcTree{R}_ok, ' for R, _, _ in out) + 'fun _ h => nomatch h' + '⟩' * len(out)

lean = r'''IMPORTS
open BB6 BB6.Sym

/-! # The endgame with end meetings at distance 2 passed

This file is generated by `thm/gen_endgame_close.py`.  For each right end R of `closeTreeRs`, the untrusted program
`ExploreNC.lean`, in its `close` mode, builds a tree for the pass starts with that R (`startR R`).  The proved function
`Tree.okEndC` (`BB6/EndgameClose.lean`), evaluated by the kernel, checks it.  Every leaf's run ends in one of three
ways: at an end event with every end meeting at distance at least 3; with every end meeting at distance at least 2,
where the run has left phase 0 or the halving chain at a round start that is not three walls; or the leaf shows L₁ in
R's class (`closeClassC`).  The checks are cut into subtrees in the modules `EndgameClosePieces0`, …, and assembled
here.  `endgame_stretch_close` is the statement for the machine for every even R: it uses these trees for R in
`closeTreeRs` and `endgame_stretch` for every other R. -/

DEFS
/-- The trees for the right ends of `closeTreeRs`. -/
def closeTrees : List (Nat × Tree) := [TLIST]

theorem close_trees_ok :
    ∀ p ∈ closeTrees, p.2.okEndC 448 1000 3 (closeClassC p.1) false (startE p.1).1.1 (startE p.1).1.2.1
      (startE p.1).1.2.2 (startE p.1).2 0 none false = true :=
  TOK

theorem close_trees_cover : closeTrees.map (·.1) = closeTreeRs := rfl

/-- **One tree of `closeTrees`, for the machine.**  For the pass starts with right end R — walls at a, b and
c = E − R − 1, width E, with a odd, b even, E even and every gap at least 448 — a tree that `Tree.okEndC` accepts gives
either L₁ in R's class (`closeClassC`), or n rounds of the machine without halting to the round start that `roundsZ`
computes, where the stretch ends as `EndEventC` says. -/
theorem close_tree_stretch {R : Nat} {t : Tree}
    (ht : t.okEndC 448 1000 3 (closeClassC R) false (startE R).1.1 (startE R).1.2.1 (startE R).1.2.2 (startE R).2 0
      none false = true)
    (a b E : Nat) (ha : a % 2 = 1) (hb : b % 2 = 0) (hE : E % 2 = 0)
    (h1 : 448 ≤ a) (h2 : a + 448 ≤ b) (h3 : b + 448 + R + 1 ≤ E) :
    (∃ m c, closeClassC R = some (m, c) ∧ loopL1 b (E - R - 1) E % m = c) ∨
    ∃ n kk ms' W', steps kk (roundStart [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E) = some (roundStart ms' W') ∧
      roundsZ 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E = .newRound ms' W' ∧
      EndEventC E R (loopL1 b (E - R - 1) E) n (meetsRounds 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E)
        ms' W' := by
  let y : List Int := [((a : Int) - 1) / 2, (b : Int) / 2, (E : Int) / 2]
  have hy : inCone (startR R).2.2 448 y := by
    intro f hf
    simp only [startR, List.mem_cons, List.mem_nil_iff, or_false] at hf
    rcases hf with rfl | rfl | rfl <;>
      simp only [y, YForm.eval, YForm.sub, YForm.add, YForm.neg, YForm.addc, addL, smulL, List.map, dot] <;> omega
  have hs : agL y (startR R).1 [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] := by
    refine ⟨⟨rfl, ?_⟩, ⟨rfl, ?_⟩, ⟨rfl, ?_⟩, trivial⟩ <;>
      simp only [agN, y, YForm.eval, YForm.addc, dot] <;> omega
  have hW : agN y (startR R).2.1 E := by simp only [agN, y, startR, YForm.eval, dot]; omega
  have hf : (startE R).2.Ag y E R (loopL1 b (E - R - 1) E) := by
    refine ⟨?_, ?_, ?_⟩
    · simp only [agN, y, startE, YForm.eval, dot]; omega
    · simp [agN, startE, YForm.const, YForm.eval]
    · simp only [startE, eval_L1Form, loopL1]
      simp only [y, YForm.eval, YForm.addc, dot]
      omega
  exact Tree.soundEndC_root 448 1000 ht rfl hy hs hW hf

/-- **The endgame with end meetings at distance 2 passed, for the machine.**  For every even R ≥ 2 and every
phase-0 pass start — walls at a, b and c = E − R − 1, width E, with a odd, b even, E even and every gap at least
448 — either R is one of 2, 4, 8, 16, 32 and 48 and the left countdown L₁ = 147 b + 280 E − 392 c − 578 is in R's
class (`closeClassC`: L₁ even for R = 2 and 4, L₁ ≡ 0 mod 32 for 8, mod 64 for 16, mod 128 for 32 and 48), or the
machine runs n rounds without halting to the round start that `roundsZ` computes.  In the second case the run ends
at an end event with every end meeting at distance at least 3, as in `endgame_stretch`, or with every end meeting at
distance at least 2, where it has left phase 0 or the halving chain at a round start that is not three walls
(`EndEventC`). -/
theorem endgame_stretch_close (R : Nat) (hR : R % 2 = 0) (hR2 : 2 ≤ R)
    (a b E : Nat) (ha : a % 2 = 1) (hb : b % 2 = 0) (hE : E % 2 = 0)
    (h1 : 448 ≤ a) (h2 : a + 448 ≤ b) (h3 : b + 448 + R + 1 ≤ E) :
    (∃ m c, closeClassC R = some (m, c) ∧ loopL1 b (E - R - 1) E % m = c) ∨
    ∃ n kk ms' W', steps kk (roundStart [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E) = some (roundStart ms' W') ∧
      roundsZ 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E = .newRound ms' W' ∧
      EndEventC E R (loopL1 b (E - R - 1) E) n (meetsRounds 1000 n [⟨.W, a⟩, ⟨.W, b⟩, ⟨.W, E - R - 1⟩] E)
        ms' W' := by
  cases hc : closeTreeRs.contains R with
  | true =>
    rw [← close_trees_cover] at hc
    obtain ⟨t, hmem⟩ : ∃ t, (R, t) ∈ closeTrees := by simpa using hc
    exact close_tree_stretch (close_trees_ok _ hmem) a b E ha hb hE h1 h2 h3
  | false =>
    rcases endgame_stretch R hR hR2 a b E ha hb hE h1 h2 h3 with ⟨m, c, hcl, hl⟩ | ⟨n, kk, ms', W', hk, hr, hm, hev⟩
    · exact Or.inl ⟨m, c, by rw [closeClassC_eq hc]; exact hcl, hl⟩
    · exact Or.inr ⟨n, kk, ms', W', hk, hr, Or.inl ⟨hm, hev⟩⟩
'''
lean = (lean.replace('IMPORTS', '\n'.join(['import EndgameTheorem'] + [f'import {m}' for m in mods]))
        .replace('DEFS', defs).replace('TLIST', tlist).replace('TOK', tok))
open(os.path.join(outdir, 'EndgameCloseTheorem.lean'), 'w').write(lean)
print(f'wrote EndgameCloseStart, {", ".join(mods)}, EndgameCloseTheorem: {len(trees)} trees '
      f'({sum(leaves(t) for _, t in trees)} leaves), {len(pieces)} subtree theorems, module costs {load}')
