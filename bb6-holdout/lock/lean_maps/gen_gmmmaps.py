"""Write GmmMaps.lean: the main return pieces of the two-marker state, and the countdowns of those that repeat into
the bulk, as theorems about the proved symbolic model.

Reads `../gmm_pieces.json` (written by `../pieces.py DUMP emit ...` from the route tree's leaves; untrusted: Lean
checks everything it uses).  For each piece the class of starts G 1, M m, M E − 2 is m = km + h·s + x·t,
E = kE + g·t (s, t any integers, both gaps at least Γ); the generated Lean runs the proved symbolic model for the
piece's rounds on that class and checks, by Lean's kernel (`decide +kernel`), that the start is well formed, that every
round is decided, the shapes, and that the round start reached is G 1, M m', M E' − 2 with m', E' the piece's affine
image.  For a piece whose map is m' = m/2^r + b·E + c with b ≠ 0, its countdown L = K·(m − λE − μ) (the scaled
distance to the piece's fixed line m = λE + μ) satisfies 2^r·L(m', E') = L(m, E) and has no integer zero.

usage: python3 gen_gmmmaps.py [Gamma]   (writes GmmMaps.lean next to this script; default Γ = 32, the smallest power
of two for which every piece checks)"""
import json
import os
import sys
from fractions import Fraction as F
from math import lcm

HERE = os.path.dirname(os.path.abspath(__file__))
PIECES = json.load(open(os.path.join(HERE, '..', 'gmm_pieces.json')))
GAMMA = int(sys.argv[1]) if len(sys.argv) > 1 else 32


def form(k, c):
    return '⟨%d, [%s]⟩' % (k, ', '.join(str(v) for v in c))


def name_of(word):
    return 'gmm_' + '_'.join(word.split('.')[1:-1])


def term(coef, var):
    if coef == 0:
        return None
    if coef == 1:
        return var
    if coef == -1:
        return f'-{var}'
    return f'{coef} * {var}'


def affine(parts, const):
    """An Int expression: Σ coef·var + const, written with + and −."""
    s = ''
    for coef, var in parts:
        if coef == 0:
            continue
        mag = abs(coef)
        t = var if mag == 1 else f'{mag} * {var}'
        if not s:
            s = t if coef > 0 else f'-{t}' if mag == 1 else f'-{mag} * {var}'
        else:
            s += f' + {t}' if coef > 0 else f' - {t}'
    if const or not s:
        if not s:
            s = str(const)
        else:
            s += f' + {const}' if const > 0 else f' - {-const}'
    return s


HEADER = '''import BB6.SymSplit
open BB6 BB6.Sym

/-! # The main return pieces of the two-marker state, and their countdowns, as theorems

Generated by `gen_gmmmaps.py` from `../gmm_pieces.json` (the eight largest return pieces of the route tree with loop
entries at 30 digits, `../Pieces.lean` and `../pieces.py`; they carry {MEAS} of the start class's measure, of
the 0.340 that returns to two markers).  For each piece the class of two-marker starts G 1, M m, M E − 2 (both
gaps at least Γ = {G}) is built with positions as forms in its coordinates (s, t); the proved symbolic model
`symRoundsZ` is run for the piece's rounds; `passCheck`, evaluated by Lean's kernel (`decide +kernel`, so no
compiler is trusted), confirms that the start is well formed on the cone, every round is decided, and the round
start reached is G 1, M m', M E' − 2 with m', E' the piece's affine image.  `pass_sound` turns this into a
statement about the machine.

{NH} pieces only halve the marker's gap ({HALV}): repeated, they run the marker into the gap at 1.  Every
other piece moves the marker toward a fixed line m = λE + μ inside the tape, and the scaled distance L to that line
is a never-zero countdown, like the plain loop's L₁: each pass divides L by 2^r, and L has no integer zero
(`*_countdown`, `*_ne_zero`).  So a run of one such piece repeated k times needs 2^(r·k) ≤ |L| at its start
(`countdown_chain`): the piece repeats at most about log₂(E)/r times in a row. -/

namespace BB6.Sym

/-- Coefficientwise equality of forms. -/
def formEqB (f g : YForm) : Bool := f.k == g.k && coeffEq f.c g.c

theorem eval_formEqB {f g : YForm} (h : formEqB f g = true) (y : List Int) : f.eval y = g.eval y := by
  simp only [formEqB, Bool.and_eq_true, beq_iff_eq] at h
  simp only [YForm.eval, h.1, dot_coeffEq _ _ y h.2]

def marksEqB : List SMark → List SMark → Bool
  | [], [] => true
  | s :: ss, t :: tt => decide (s.t = t.t) && formEqB s.p t.p && marksEqB ss tt
  | _, _ => false

theorem agL_marksEqB {y : List Int} : ∀ {ss tt : List SMark} {ms : List Mark}, marksEqB ss tt = true → agL y ss ms →
    agL y tt ms
  | [], [], [], _, _ => trivial
  | s :: ss, t :: tt, m :: ms, h, hs => by
    simp only [marksEqB, Bool.and_eq_true, decide_eq_true_eq] at h
    obtain ⟨⟨h1, h2⟩, h3⟩ := h
    obtain ⟨⟨ht, hp⟩, hr⟩ := hs
    refine ⟨⟨h1 ▸ ht, ?_⟩, agL_marksEqB h3 hr⟩
    unfold agN at hp ⊢; rw [hp, eval_formEqB h2]
  | [], _ :: _, _, h, _ => by simp [marksEqB] at h
  | _ :: _, [], _, h, _ => by simp [marksEqB] at h
  | [], [], _ :: _, _, hs => absurd hs id
  | _ :: _, _ :: _, [], _, hs => absurd hs id

section
variable (ts : List YForm) (Γ : Int)

/-- The check: well-formed start, `n` decided rounds ending at a round start whose marks and width are, as forms,
`tt` and `tW`. (The same check as `PassMaps.lean`.) -/
def passCheck (fuel n : Nat) (ss : List SMark) (sW : YForm) (tt : List SMark) (tW : YForm) : Bool :=
  symRightOK ts Γ (YForm.const 4) false sW ss &&
  (match symRoundsZ ts Γ fuel n ss sW with
   | some (.newRound ss' sW') => marksEqB ss' tt && formEqB sW' tW
   | _ => false)

def shapeOf (ss : List SMark) : String := "G" ++ String.join (ss.map (fun m => match m.t with
  | .G => "G" | .M => "M" | .W => "W" | .B => "B"))

/-- The shapes of the round starts of `n` symbolic rounds (`none` unless every round is decided and ends at a round
start). -/
def symShapes (fuel : Nat) : Nat → List SMark → YForm → Option (List String)
  | 0, _, _ => some []
  | n + 1, ss, sW =>
    match symRoundZ ts Γ fuel [] (YForm.const 1) ss sW with
    | some (.newRound ss' sW') => (symShapes fuel n ss' sW').map (shapeOf ss' :: ·)
    | _ => none

theorem pass_sound (fuel n : Nat) (ss : List SMark) (sW : YForm) (tt : List SMark) (tW : YForm)
    (hc : passCheck ts Γ fuel n ss sW tt tW = true)
    (y : List Int) (hy : inCone ts Γ y) (ms : List Mark) (Wn : Nat) (hs : agL y ss ms) (hW : agN y sW Wn) :
    ∃ k ms' Wn', steps k (roundStart ms Wn) = some (roundStart ms' Wn') ∧ roundsZ fuel n ms Wn = .newRound ms' Wn' ∧
      agL y tt ms' ∧ agN y tW Wn' := by
  simp only [passCheck, Bool.and_eq_true] at hc
  obtain ⟨hwf, hrun⟩ := hc
  cases hr : symRoundsZ ts Γ fuel n ss sW with
  | none => rw [hr] at hrun; cases hrun
  | some r =>
    rw [hr] at hrun
    cases r with
    | newRound ss' sW' =>
      simp only [Bool.and_eq_true] at hrun
      have hag := symRoundsZ_sound ts Γ hy fuel n ss ms sW Wn _ hs hW hr
      have hrwf : roundWF ms Wn := symRightOK_sound ts Γ hy ss _ 4 false sW Wn ms (agN_const y 4) hW hs hwf
      generalize hcr : roundsZ fuel n ms Wn = cr at hag
      cases cr with
      | newRound ms' Wn' =>
        obtain ⟨k, hk, -⟩ := rounds_run fuel n ms Wn hrwf (by rw [hcr]; intro h; cases h)
        rw [hcr] at hk
        refine ⟨k, ms', Wn', hk, rfl, agL_marksEqB hrun.1 hag.1, ?_⟩
        have := hag.2; unfold agN at this ⊢; rw [this, eval_formEqB hrun.2]
      | _ => exact absurd hag id
    | _ => simp at hrun

end

theorem agL_two {y : List Int} {f1 f2 : YForm} {ms : List Mark} (h : agL y [⟨.M, f1⟩, ⟨.M, f2⟩] ms) :
    ∃ v1 v2, ms = [⟨.M, v1⟩, ⟨.M, v2⟩] ∧ agN y f1 v1 ∧ agN y f2 v2 := by
  match ms, h with
  | [⟨t1, p1⟩, ⟨t2, p2⟩], ⟨⟨e1, a1⟩, ⟨e2, a2⟩, _⟩ =>
    simp only at e1 e2
    subst e1 e2
    exact ⟨p1, p2, rfl, a1, a2⟩

/-- A countdown that each step divides by `D` and that is never zero: after `k` steps `L₀ = D^k · L_k`, so
`|D|^k ≤ |L₀|`, and the steps number at most log_|D| |L₀|. -/
theorem countdown_chain (L : Nat → Int) (D : Int) (k : Nat) (hstep : ∀ i, i < k → D * L (i + 1) = L i)
    (hne : L k ≠ 0) : L 0 = D ^ k * L k ∧ D.natAbs ^ k ≤ (L 0).natAbs := by
  have hpow : ∀ j, j ≤ k → L (k - j) = D ^ j * L k := by
    intro j
    induction j with
    | zero => intro _; simp
    | succ j ih =>
      intro hj
      have h1 := hstep (k - (j + 1)) (by omega)
      have h2 : k - (j + 1) + 1 = k - j := by omega
      rw [h2, ih (by omega)] at h1
      rw [← h1, Int.pow_succ]; grind
  have h0 := hpow k (Nat.le_refl k)
  rw [Nat.sub_self] at h0
  refine ⟨h0, ?_⟩
  rw [h0, Int.natAbs_mul, Int.natAbs_pow]
  exact Nat.le_mul_of_pos_right _ (Int.natAbs_pos.mpr hne)

end BB6.Sym

open BB6.Sym
'''


def piece(P):
    w = P['word']
    nm = name_of(w)
    km, h, x, kE, g = P['km'], P['h'], P['x'], P['kE'], P['g']
    a, b, c, e = F(P['a']), F(P['b']), F(P['c']), F(P['e'])
    n = len(w.split('.')) - 1
    shapes = ['G' + s for s in w.split('.')[1:]]
    path = ' → '.join('G ' + s for s in w.split('.'))
    # forms in (s, t): m = km + h s + x t, E = kE + g t
    m0 = (km, [h, x])
    E0 = (kE, [0, g])
    mk = a * km + b * kE + c
    mc = [a * h, a * x + b * g]
    assert mk.denominator == 1 and all(v.denominator == 1 for v in mc), w
    m1 = (int(mk), [int(v) for v in mc])
    assert e.denominator == 1
    E1 = (kE + int(e), [0, g])
    # the map as an integer equation: D m' = A m + B E + C
    D = lcm(a.denominator, b.denominator, c.denominator)
    A, B, C = int(a * D), int(b * D), int(c * D)
    lhs = "m'" if D == 1 else f"{D} * m'"
    rhs = affine([(A, 'm'), (B, 'E')], C)
    hm = affine([(h, 's'), (x, 't')], km) if km else affine([(h, 's'), (x, 't')], 0)
    hE = affine([(g, 't')], kE)
    pct = F(P['measure'])
    G = GAMMA
    out = f'''
/-! ## {path}

Class: m = {km} + {h}·s + {x}·t, E = {kE} + {g}·t (measure {pct} of the two-marker starts); {n} rounds;
{lhs} = {rhs}, E' = E + {e}. -/

def {nm}_m : YForm := {form(*m0)}
def {nm}_E : YForm := {form(*E0)}
def {nm}_ss : List SMark := [⟨.M, {nm}_m⟩, ⟨.M, {nm}_E.addc (-2)⟩]
def {nm}_ts : List YForm := [{nm}_m, {nm}_E.sub {nm}_m]
def {nm}_tt : List SMark := [⟨.M, {form(*m1)}⟩, ⟨.M, {form(E1[0] - 2, E1[1])}⟩]
def {nm}_tW : YForm := {form(*E1)}

theorem {nm}_check : passCheck {nm}_ts {G} 1000 {n} {nm}_ss {nm}_E {nm}_tt {nm}_tW = true := by decide +kernel

theorem {nm}_shapes : symShapes {nm}_ts {G} 1000 {n} {nm}_ss {nm}_E =
    some [{', '.join(f'"{s}"' for s in shapes)}] := by decide +kernel

/-- **The return {path}, for the machine.**  Every two-marker round start G 1, M m, M E − 2 on the piece's
class with both gaps at least {G} runs, without halting, to the two-marker round start G 1, M m', M E' − 2 with
{lhs} = {rhs} and E' = E + {e}; this is also the {n}-round result of the proved zipper model `roundsZ`. -/
theorem {nm}_return (s t : Int) (m E : Nat) (hm : (m : Int) = {hm}) (hE : (E : Int) = {hE})
    (g1 : {G} ≤ m) (g2 : m + {G} ≤ E) :
    ∃ kk m' E', steps kk (roundStart [⟨.M, m⟩, ⟨.M, E - 2⟩] E) = some (roundStart [⟨.M, m'⟩, ⟨.M, E' - 2⟩] E') ∧
      roundsZ 1000 {n} [⟨.M, m⟩, ⟨.M, E - 2⟩] E = .newRound [⟨.M, m'⟩, ⟨.M, E' - 2⟩] E' ∧
      {lhs} = {rhs} ∧ E' = E + {e} := by
  let y : List Int := [s, t]
  have hy : inCone {nm}_ts {G} y := by
    intro f hf
    simp only [{nm}_ts, List.mem_cons, List.mem_nil_iff, or_false] at hf
    rcases hf with rfl | rfl <;>
      simp only [y, {nm}_m, {nm}_E, YForm.eval, YForm.sub, YForm.add, YForm.neg, addL, smulL, List.map, dot] <;> omega
  have hs : agL y {nm}_ss [⟨.M, m⟩, ⟨.M, E - 2⟩] := by
    refine ⟨⟨rfl, ?_⟩, ⟨rfl, ?_⟩, trivial⟩ <;>
      simp only [agN, y, {nm}_m, {nm}_E, YForm.eval, YForm.addc, dot] <;> omega
  have hW : agN y {nm}_E E := by simp only [agN, y, {nm}_E, YForm.eval, dot]; omega
  obtain ⟨kk, ms', Wn', hk, hr, ht, htW⟩ := pass_sound _ _ _ _ _ _ _ _ {nm}_check y hy _ _ hs hW
  obtain ⟨v1, v2, rfl, e1, e2⟩ := agL_two ht
  simp only [agN, y, {nm}_tW, YForm.eval, dot] at e1 e2 htW
  have hv2 : v2 = Wn' - 2 := by omega
  subst hv2
  exact ⟨kk, v1, Wn', hk, hr, by omega, by omega⟩
'''
    lock = ''
    if b != 0:
        lam = b / (1 - a)
        mu = (c - lam * e) / (1 - a)
        K = lcm(lam.denominator, mu.denominator)
        Lm, LE, Lc = K, -int(lam * K), -int(mu * K)
        Lexpr = affine([(Lm, 'm'), (LE, 'E')], Lc)
        Lexpr1 = affine([(Lm, "m'"), (LE, "E'")], Lc)
        r = a.denominator
        assert a.numerator == 1
        lock = f'''
/-- The countdown of {path}: the scaled distance to its fixed line m = {lam}·E + {mu}. -/
theorem {nm}_countdown (m E m' E' : Int) (h1 : {lhs} = {rhs}) (h2 : E' = E + {e}) :
    {r} * ({Lexpr1}) = {Lexpr} := by omega

theorem {nm}_ne_zero (m E : Int) : {Lexpr} ≠ 0 := by omega
'''
    return out + lock, nm, (b != 0)


def main():
    meas = sum(F(P['measure']) for P in PIECES)
    halv = [F(P['a']) for P in PIECES if F(P['b']) == 0 and F(P['c']) == 0]
    words = ['No', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight']
    body = (HEADER.replace('{G}', str(GAMMA)).replace('{MEAS}', f'{meas} ≈ {float(meas):.3f}')
            .replace('{NH}', words[len(halv)]).replace('{HALV}', ', '.join(f"m' = m/{a.denominator}" for a in halv)))
    names = []
    for P in PIECES:
        txt, nm, has_lock = piece(P)
        body += txt
        names.append((nm, has_lock))
    body += '\n'
    for nm, has_lock in names:
        body += f'#print axioms {nm}_return\n'
        if has_lock:
            body += f'#print axioms {nm}_ne_zero\n'
    body += '#print axioms countdown_chain\n'
    open(os.path.join(HERE, 'GmmMaps.lean'), 'w').write(body)
    print('wrote GmmMaps.lean')


if __name__ == '__main__':
    main()
