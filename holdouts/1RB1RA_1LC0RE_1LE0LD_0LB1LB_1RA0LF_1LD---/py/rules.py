"""Generate lean/Rules.lean: rules of 1RB1RA_1LC0RE_1LE0LD_0LB1LB_1RA0LF_1LD---, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB1RA_1LC0RE_1LE0LD_0LB1LB_1RA0LF_1LD---)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RA_1LC0RE_1LE0LD_0LB1LB_1RA0LF_1LD---"

RULES = [
    ('a_r_1', 'L A> (1)^n R', 'L (1)^n A> R',
     'A sweeps right over copies of `1` (1 step a copy).'),
    ('a_r_01001111', 'L A> (01001111)^n R', 'L (01110111)^n A> R',
     'A sweeps right over copies of `01001111` (20 steps a copy).'),
    ('a_r_10100111', 'L A> (10100111)^n R', 'L (10111011)^n A> R',
     'A sweeps right over copies of `10100111` (20 steps a copy).'),
    ('b_l_10100111', 'L (10100111)^n B> 0 R', 'L B> 0 (01001111)^n R',
     'B sweeps left over copies of `10100111` (46 steps a copy).'),
    ('a_r_11010011', 'L A> (11010011)^n R', 'L (11011101)^n A> R',
     'A sweeps right over copies of `11010011` (20 steps a copy).'),
    ('c_l_11010011', 'L (11010011)^n C> 1 R', 'L C> 1 (10100111)^n R',
     'C sweeps left over copies of `11010011` (46 steps a copy).'),
    ('d_l_11101001', 'L (11101001)^n D> 10 R', 'L D> 10 (10100111)^n R',
     'D sweeps left over copies of `11101001` (46 steps a copy).'),
    ('e_r_00111101', 'L 10 E> (00111101)^n R', 'L (01110111)^n 10 E> R',
     'E sweeps right over copies of `00111101` (20 steps a copy).')
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H152108", thms,
                                "Rules of 1RB1RA_1LC0RE_1LE0LD_0LB1LB_1RA0LF_1LD---, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
