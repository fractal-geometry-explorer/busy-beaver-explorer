"""Generate Rules.lean for 1RB1RD_0RC0RD_0LD1LE_1LC0RB_1LF---_1LA0LE: the pieces of a pass, proved along the symbolic
run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`, L and R
are any tape, 0^inf is blank tape.  How the pieces make a pass is in the README ("The pass map").
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools import symtm  # noqa: E402
from bbtools.symtm import prove, rules_file  # noqa: E402

symtm.MAX_CARRY = 6  # the fill rule carries the five-cell word 0 1 1 1 0

M = "1RB1RD_0RC0RD_0LD1LE_1LC0RB_1LF---_1LA0LE"

RULES = [
    ("fill", "L 0^k A> 0 1 1 1 0 R", "L A> 0 1 1 1 0 1^k R",
     "Inside a cycle the word `0 1 1 1 0` travels left through a block of 0s, turning each 0 into a 1 behind it (13 steps a cell)."),
    ("cycle", "L 1 0 (00)^m D> (10)^b+2 R", "L 1 0 1 0 0 (00)^m 0 D> (10)^b R",
     "One cycle of the front: two `10` pairs on the right are eaten, one `10` is added on the left and the 0 block grows by two."),
    ("sweep_left", "0^inf (10)^x+6 (00)^n+1 C> 0^inf", "0^inf F> 1 (10)^x+4 1 1 1 0 (10)^n 1 0 0^inf",
     "The sweep back from the right end: the 0 block becomes `10` pairs and a `11` separator appears after the old pairs."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H161169", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
