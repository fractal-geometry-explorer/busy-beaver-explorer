out = []
for name, doc, a, b in RULES:
    txt, fin = symtm.prove(m, name, a, b, doc=doc, rotate=True, count_first=name.startswith("end"), max_seg=40 if name.startswith("end") else None)
    out.append(txt)
# the halt: x = 0 with m odd
for s in (0, 1):
    start = symtm.Config.parse(K(0, "1 (11)^n", s))
    c = start.copy()
    try:
        symtm.run(m, c, lambda c: False, rotate=True)
    except symtm.Halted:
        pass
    txt, fin = symtm.prove(m, f"toHalt{s}", start, c, rotate=True,
                           doc=f"From (0, 2n+1) with the head on {s} the machine runs into its halting transition A1.")
    out.append(txt)
    out.append(f"/-- ... and halts there. -/\ntheorem halt{s} (n : Nat) : step {symtm.cfg_term(fin)} = none := rfl\n")
doc = (f"Rules of {M} between the samples K(x, m, s) = 1^4 0 (10)^x 1^m with the head in C on s at the right end; "
       "generated by `py/gen_rules.py`; do not edit by hand.")
sys.stdout.write(symtm.rules_file("Machine", NS, out, doc))
