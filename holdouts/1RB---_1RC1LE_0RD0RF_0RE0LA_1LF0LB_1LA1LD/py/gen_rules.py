import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools import symtm
from bbtools.machine import Machine
M = "1RB---_1RC1LE_0RD0RF_0RE0LA_1LF0LB_1LA1LD"
NS = "H26350"
m = Machine.parse(M)


def K(x, w, s):
    """The sample configuration: 1^4 0 (10)^x, then the block w of ones, the head in C on s at the right end."""
    return f"0^inf 1^4 0 (10)^{x} {w} C> {s} 0^inf"


RULES = []
for s in (0, 1):
    RULES += [
        (f"ruleB{s}", f"B (m even, x >= 1), head on {s}: (x+1, 2n) -> (x, 2n+4), the head symbol flips.",
         K("x+1", "(11)^n", s), K("x", "(11)^n+2", 1 - s)),
        (f"ruleR{s}", f"R (m even, x = 0), head on {s}: (0, 2n) -> (n+3, {1 if s == 0 else 3}), head on 0.",
         K(0, "(11)^n", s), K("n+3", "1" if s == 0 else "111", 0)),
        (f"ruleA{s}x1", f"A for x = 1 (m odd), head on {s}: (1, 2n+1) -> (3, 2n+3), the head symbol flips.",
         K(1, "1 (11)^n", s), K(3, "1 (11)^n+1", 1 - s)),
        (f"ruleC{s}n0", f"C for m = 1, head on {s}: (x+3, 1) -> (x, {9 - s}).",
         K("x+3", "1", s), K("x", "1 (11)^4" if s == 0 else "(11)^4", s)),
    ]


