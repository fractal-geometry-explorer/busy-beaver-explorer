"""Generate Rules.lean: the round of the E-zigzag of 1RB0RF_1LC---_1LF1LD_1RE0LD_0RC0RE_1LC1RA, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(11)^n` is n copies of `11`,
`0^inf` is blank tape, L is any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RF_1LC---_1LF1LD_1RE0LD_0RC0RE_1LC1RA"

RULES = [
    ("e_round", "L 1 0 1 0 1 1 E> 0 1 1 (11)^y 0^inf", "L 1 1 E> 0 1 1 1 1 1 1 1 (11)^y 1 0^inf",
     "One round of the E-zigzag: two copies of `10` left of the head are used up, the block of ones at the right "
     "end grows by six, and the tape by two cells."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=16)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H134470", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
