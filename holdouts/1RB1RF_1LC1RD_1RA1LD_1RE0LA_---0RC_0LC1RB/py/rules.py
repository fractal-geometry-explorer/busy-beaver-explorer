"""Generate lean/Rules.lean for 1RB1RF_1LC1RD_1RA1LD_1RE0LA_---0RC_0LC1RB.

The tape consists of two periodic regions, `111010` and `111110` (each read at any phase), with a few defects.
Sweeping right, in every state, the head turns the first into the second one word at a time: `sweepA` ...
`sweepF`, 6 steps a word, for any number of words.  `halt00`: the only halt, D reading 0 with a 0 to its right
(D0 = 1RE, then E0 has no transition).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import prove  # noqa: E402

M = "1RB1RF_1LC1RD_1RA1LD_1RE0LA_---0RC_0LC1RB"
NS = "H110862"
SWEEPS = {"A": ("111010", "111101"), "B": ("101011", "110111"), "C": ("011101", "111110"),
          "D": ("010111", "101111"), "E": ("101110", "011111"), "F": ("110101", "111011")}


def main():
    m = Machine.parse(M)
    out = []
    for s, (w, w2) in SWEEPS.items():
        txt, fin = prove(m, f"sweep{s}", f"L {s}> ({w})^n R", f"L ({w2})^n {s}> R",
                         doc=f"In state {s} moving right, every `{w}` becomes `{w2}`: 6n steps.")
        print(f"-- sweep{s}: {fin} ({fin.steps})", file=sys.stderr)
        out.append(txt)
    txt, fin = prove(m, "halt00", "L D> 0 0 R", "L 1 E> 0 R",
                     doc="D reading 0 with a 0 to its right: one step later E reads 0, which has no transition.")
    out.append(txt)
    cfg = txt.split("= some ", 1)[1].split(" := by", 1)[0]
    out.append(f"/-- ... and there the machine stops. -/\ntheorem halt00_stop (L R : Tape) :\n"
               f"    step {cfg} = none := by\n  simp [step, TM.step, trans]\n")
    head = f"import Machine\n\n/-! Rules of {M} (generated by `py/rules.py`). -/\n\nnamespace {NS}\n\nopen TM\n\n"
    sys.stdout.write(head + "\n".join(out) + f"\nend {NS}\n")


if __name__ == "__main__":
    main()
