"""Shift rules and halting situations of 1RB---_0RC0LA_1LD0RB_1LE1LD_1LF0LC_1LB1RE, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB---_0RC0LA_1LD0RB_1LE1LD_1LF0LC_1LB1RE/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB---_0RC0LA_1LD0RB_1LE1LD_1LF0LC_1LB1RE"
NS = "H24506"
DOC = """# Shift rules of 1RB---_0RC0LA_1LD0RB_1LE1LD_1LF0LC_1LB1RE

The rightward pass of the bouncer: C runs right over the dense half of the tape, turning each block `1^(4n+3) 0`
into the sparse word `(1010)^n 1000`; two 1s cost 4 steps (`pass_pair`); the same pass seen from B crosses `0111`
in 6 steps (`pass_b`).  The halting situations: A on a 0 with a 1 after it, and B on a 1 with a 1 before it, halt
within two steps (`halt_A`, `halt_B`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('pass_pair', 'L C> (11)^n R', 'L (10)^n C> R', 'C turns `1 1` into `1 0`, four steps a pair.'),
    ('pass_block', 'L C> (1111)^n 1 1 1 0 R', 'L (1010)^n 1 0 0 0 C> R', 'A dense block `1^(4n+3) 0` becomes the sparse word `(1010)^n 1000` (left of the head, in tape order).'),
    ('pass_end', 'L C> 1 0 R', 'L 0 0 C> R', 'The last 1 of a block and the 0 after it.'),
    ('pass_b', 'L B> (0111)^n R', 'L (0100)^n B> R', 'The same pass seen from B: each `0111` becomes `0100`, six steps a copy.'),
]

HALTS = [
    ('halt_A', 'A> 0 1', 2, '`A> 0 1` halts: A writes 1, B reads the 1 and steps back left onto it in state A.'),
    ('halt_B', '1 B> 1', 1, '`1 B> 1` halts: B erases its 1 and steps left onto a 1 in state A.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [prove(M, name, a, b, doc=doc, count_first=True)[0] for name, a, b, doc in RULES]
    thms += [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
