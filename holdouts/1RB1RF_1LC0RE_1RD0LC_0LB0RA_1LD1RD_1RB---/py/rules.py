"""Generate lean/Rules.lean: rules of 1RB1RF_1LC0RE_1RD0LC_0LB0RA_1LD1RD_1RB---, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB1RF_1LC0RE_1RD0LC_0LB0RA_1LD1RD_1RB---)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RF_1LC0RE_1RD0LC_0LB0RA_1LD1RD_1RB---"

RULES = [
    ('d_r_1011', 'L D> (1011)^n R', 'L (0101)^n D> R',
     'D sweeps right over copies of `1011` (4 steps a copy).'),
    ('e_r_1101', 'L E> (1101)^n R', 'L (1010)^n E> R',
     'E sweeps right over copies of `1101` (4 steps a copy).'),
    ('b_r_1110', 'L B> (1110)^n R', 'L (0101)^n B> R',
     'B sweeps right over copies of `1110` (4 steps a copy).'),
    ('a_r_0111', 'L A> (0111)^n R', 'L (1010)^n A> R',
     'A sweeps right over copies of `0111` (4 steps a copy).'),
    ('b_l_1', 'L (1)^n B> 10 R', 'L B> 10 (1)^n R',
     'B sweeps left over copies of `1` (3 steps a copy).'),
    ('c_l_1', 'L (1)^n C> 1 R', 'L C> 1 (0)^n R',
     'C sweeps left over copies of `1` (1 step a copy).'),
    ('d_l_1', 'L (1)^n D> 0 R', 'L D> 0 (1)^n R',
     'D sweeps left over copies of `1` (3 steps a copy).'),
    ('b_l_10101', 'L (10101)^n B> 10 R', 'L B> 10 (11011)^n R',
     'B sweeps left over copies of `10101` (13 steps a copy).')
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H40361", thms,
                                "Rules of 1RB1RF_1LC0RE_1RD0LC_0LB0RA_1LD1RD_1RB---, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
