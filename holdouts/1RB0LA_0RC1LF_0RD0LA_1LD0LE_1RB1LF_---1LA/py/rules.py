"""Shift rules and halting situations of 1RB0LA_0RC1LF_0RD0LA_1LD0LE_1RB1LF_---1LA, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LA_0RC1LF_0RD0LA_1LD0LE_1RB1LF_---1LA/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LA_0RC1LF_0RD0LA_1LD0LE_1RB1LF_---1LA"
NS = "H45336"
DOC = """# Shift rules of 1RB0LA_0RC1LF_0RD0LA_1LD0LE_1RB1LF_---1LA

Two of the crossings the run uses most: C, with a 0 behind it, walks right through a block of 1s, three steps a
cell, moving the 0 along (`walk_ones`), and C turns `0111` into `1110` (`shift_0111`).  The halting situations:
only F reading a 0 halts, and `0 B> 1`, `0 E> 1` and `0 1 1 D> 0` lead there (`halt_B`, `halt_E`, `halt_D`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('walk_ones', 'L 0 C> (1)^n R', 'L (1)^n 0 C> R', 'C carries a 0 rightwards through a block of 1s, three steps a cell.'),
    ('shift_0111', 'L C> (0111)^n R', 'L (1110)^n C> R', 'C turns each `0111` into `1110`, ten steps a copy.'),
]

HALTS = [
    ('halt_B', '0 B> 1', 1, '`0 B> 1` halts: B writes 1, steps left onto the 0 in state F.'),
    ('halt_E', '0 E> 1', 1, '`0 E> 1` halts: E steps left onto the 0 in state F.'),
    ('halt_D', '0 1 1 D> 0', 3, '`0 1 1 D> 0` halts: D writes 1 and steps left onto a 1, erases it moving left in state E, and E steps from the next 1 onto the 0 in state F.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [prove(M, name, a, b, doc=doc, count_first=True)[0] for name, a, b, doc in RULES]
    thms += [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
