"""Generate lean/Rules.lean for 1RB1RA_1LC0RB_1LE0LD_0LB1LD_0RA0LF_---0RE: the drain cycle, proved along the symbolic
run of tools/py/bbtools/symtm.py.

usage (from the repo root): python3 holdouts/1RB1RA_1LC0RB_1LE0LD_0LB1LD_0RA0LF_---0RE/py/rules.py > \
           holdouts/1RB1RA_1LC0RB_1LE0LD_0LB1LD_0RA0LF_---0RE/lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RA_1LC0RB_1LE0LD_0LB1LD_0RA0LF_---0RE"
HERE = os.path.dirname(os.path.abspath(__file__))
NS = next(l.split()[1] for l in open(os.path.join(HERE, "..", "lean", "Machine.lean")) if l.startswith("namespace "))

RULES = [
    ("drain", "0^inf E> (011)^4 (010)^a+6 (1)^3 (01011)^b+1 0 1 0^inf",
     "0^inf E> (011)^4 (010)^a+2 (1)^3 (01011)^b+15 0 1 0^inf",
     "The drain phase, one cycle (16 visits of the left end): four pairs `010` go, fourteen words `01011` come."),
    ("split", "0^inf B> 0 0 (110101)^c 1 1 0 1 (100)^d+3 1 0 (1)^3 (01011)^b+1 0 1 0^inf",
     "0^inf B> 0 0 (110101)^c+1 1 1 0 1 (100)^d+1 1 0 (1)^3 (01011)^b+3 0 1 0^inf",
     "The split phase, one cycle (4 visits of the left end): two words `100` go, one goes to the block `110101` on "
     "the left and two words `01011` come on the right."),
    ("copy", "L (01111)^n+2 (010)^m+1 0 1 1 1 1 (00111)^m+1 B> 0^inf",
     "L (01111)^n+1 0 1 (001)^m+1 0 0 1 1 1 1 (00111)^m 0 0 1 1 1 0 0 1 1 1 B> 0^inf",
     "The copy phase, one visit of the right end: one word `01111` of the old final block (rewritten) becomes one word "
     "`010` of a new block and one word `00111` of the new final block (the end configuration is "
     "`L (01111)^(n+1) (010)^(m+2) 0 1 1 1 1 (00111)^(m+2) B> 0^inf` re-bracketed). L is any tape: it is not read."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
