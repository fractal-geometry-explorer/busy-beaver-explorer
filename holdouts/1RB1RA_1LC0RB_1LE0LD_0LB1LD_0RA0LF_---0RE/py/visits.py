"""Generate lean/Visits.lean for 1RB1RA_1LC0RB_1LE0LD_0LB1LD_0RA0LF_---0RE: the pour cycle, visit by visit.

A *visit* runs from one sample (state B on the first blank cell right of the tape) to the next.  The pour cycle is
one of the four cycles `py/closure.py` finds and uses (the others are `copy`, `drain` and `split` of
lean/Rules.lean, seen from the other end of the tape): 20 visits take two words of the block `(001)^d` and add ten
words to the final block `(01110)^a`, with the fixed word `1 (100111)^3` at the left end:

    0^inf 1 (100111)^3 (001)^(d+4) 1 1 1 0 (01110)^(a+2) 0 1 1 1 B> 0^inf   -->   the same with d - 2, a + 10

Each visit is proved by `bbtools.symtm.prove` as its own theorem `pour1` .. `pour20` (for every a and d); the end of
each is the start of the next, as the run writes it.

usage (from the repo root):
  python3 holdouts/1RB1RA_1LC0RB_1LE0LD_0LB1LD_0RA0LF_---0RE/py/visits.py     # writes lean/Visits.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import Blank, Config, prove, rules_file, run  # noqa: E402
from bbtools.machine import Machine  # noqa: E402

M = "1RB1RA_1LC0RB_1LE0LD_0LB1LD_0RA0LF_---0RE"
NS = next(l.split()[1] for l in open(os.path.join(HERE, "..", "lean", "Machine.lean")) if l.startswith("namespace "))
START = "0^inf 1 (100111)^3 (001)^d+4 1 1 1 0 (01110)^a+2 0 1 1 1 B> 0^inf"
NVIS = 20


def is_sample(c):
    return c.state == 1 and not c.steps.is_zero() and len(c.right) == 1 and isinstance(c.right[0], Blank)


def chain():
    m = Machine.parse(M)
    cfgs = [Config.parse(START)]
    for _ in range(NVIS):
        c = Config(cfgs[-1].left, cfgs[-1].state, cfgs[-1].right)
        cfgs.append(run(m, c, is_sample, rotate=True, max_moves=20000))
    return cfgs


def main():
    cfgs = chain()
    ths = []
    for i in range(NVIS):
        a = Config(cfgs[i].left, cfgs[i].state, cfgs[i].right)
        b = Config(cfgs[i + 1].left, cfgs[i + 1].state, cfgs[i + 1].right)
        doc = f"Pour cycle, visit {i + 1} of {NVIS}." + (
            " The end is `0^inf 1 (100111)^3 (001)^(d+2) 1 1 1 0 (01110)^(a+12) 0 1 1 1 B> 0^inf` re-bracketed." if i == NVIS - 1 else "")
        ths.append(prove(M, f"pour{i + 1}", a, b, doc=doc, rotate=True, count_first=True, max_seg=40)[0])
    out = os.path.join(HERE, "..", "lean", "Visits.lean")
    open(out, "w").write(rules_file("Machine", NS, ths, f"The pour cycle of {M} visit by visit, generated by `py/visits.py`; do not edit by hand."))
    print("last:", cfgs[-1], "steps", cfgs[-1].steps)


if __name__ == "__main__":
    main()
