"""Write lean/Rules.lean: rules of 1RB1LC_1LA1RF_0RD1RD_0RA0LE_1LA0LE_0RC--- proved by bbtools.symtm, for all values of their counts.

The tape is long runs of the word d = 110 with a few marks in between. While a hole moves through a run, the head
crosses the runs again and again, re-encoding them (110 -> 010 -> 110, 110 -> 011 -> 001 -> 110); these are the shift
rules of those crossings.

usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/1RB1LC_1LA1RF_0RD1RD_0RA0LE_1LA0LE_0RC---/py/gen_rules.py
"""
import os
from bbtools import symtm
from bbtools.machine import Machine

M = "1RB1LC_1LA1RF_0RD1RD_0RA0LE_1LA0LE_0RC---"
RULES = [
    ("dR", "D crosses 010 words to the right, restoring them to 110", "L 0 D> (010)^n R", "L (110)^n 0 D> R"),
    ("eL", "E crosses 011 words to the left, writing 001", "L (011)^n E> 0 R", "L E> 0 (001)^n R"),
    ("eL2", "E crosses 110 words to the left, writing 010", "L (110)^n E> 1 R", "L E> 1 (010)^n R"),
    ("cR", "C crosses 001 words to the right, restoring them to 110", "L C> (001)^n R", "L (110)^n C> R"),
]


def main():
    m = Machine.parse(M)
    thms = [symtm.prove(m, name, s, e, doc=doc, rotate=True)[0] for name, doc, s, e in RULES]
    out = symtm.rules_file("Machine", "H65980", thms, "Rules of " + M + ", generated by `py/gen_rules.py` with `bbtools.symtm`.")
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lean", "Rules.lean"), "w") as f:
        f.write(out)


if __name__ == "__main__":
    main()
