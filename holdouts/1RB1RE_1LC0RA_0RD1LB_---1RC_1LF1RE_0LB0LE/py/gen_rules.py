"""Write lean/Rules.lean for 1RB1RE_1LC0RA_0RD1LB_---1RC_1LF1RE_0LB0LE: the one-sweep rules, proved by symbolic
simulation (tools/py/bbtools/symtm.py), every one a theorem for all values of its variables.

Configurations (the head at the right end of the visited tape, reading blank):
  W p q r = 0^inf 0 (10)^p 0 (10)^q 1^r E> 0^inf
  X p q   = 0^inf 0 (10)^p 0 (10)^q A> 0^inf
The theorems state the end configuration as the symbolic run writes it; lean/Map.lean restates them with W and X.

usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/<M>/py/gen_rules.py > holdouts/<M>/lean/Rules.lean
"""
from bbtools import symtm

M = '1RB1RE_1LC0RA_0RD1LB_---1RC_1LF1RE_0LB0LE'
RULES = [
    ('l1', 'one sweep: W (p+1) q (r+3) to W p (q+2) (r+2)',
     '0^inf 0 (10)^p+1 0 (10)^q 1^r+3 E> 0^inf', '0^inf 0 (10)^p 0 (10)^q+2 1^r+2 E> 0^inf'),
    ('l1c', 'one sweep: W (p+1) q 2 to W p (q+2) 1',
     '0^inf 0 (10)^p+1 0 (10)^q 1^2 E> 0^inf', '0^inf 0 (10)^p 0 (10)^q+2 1 E> 0^inf'),
    ('l2', 'the last 1 used up: W (p+1) q 1 to X p (q+2)',
     '0^inf 0 (10)^p+1 0 (10)^q 1 E> 0^inf', '0^inf 0 (10)^p 0 (10)^q+2 A> 0^inf'),
    ('l3', 'the middle block turned into ones: X (p+1) (q+2) to W (p+1) 0 (2q+6)',
     '0^inf 0 (10)^p+1 0 (10)^q+2 A> 0^inf', '0^inf 0 (10)^p+1 0 (11)^q+3 E> 0^inf'),
    ('l4', 'both blocks used up: X 0 (q+2) to W 2 0 (2q+5)',
     '0^inf 0 0 (10)^q+2 A> 0^inf', '0^inf 0 (10)^2 0 (11)^q+2 1 E> 0^inf'),
    ('l5', 'the left block used up, the tape grows on the left: W 0 q (r+3) to W (q+2) 0 (r+2)',
     '0^inf 0 0 (10)^q 1^r+3 E> 0^inf', '0^inf 0 (10)^q+2 0 1^r+2 E> 0^inf'),
    ('l5c', 'the same with two ones: W 0 q 2 to W (q+2) 0 1',
     '0^inf 0 0 (10)^q 1^2 E> 0^inf', '0^inf 0 (10)^q+2 0 1 E> 0^inf'),
    ('l6', 'W 0 q 1 reaches the halting configuration (state D reading 0)',
     '0^inf 0 0 (10)^q 1 E> 0^inf', '0^inf 0 1 0 1 0 (10)^q 1 0 D> 0^inf'),
]


def main():
    thms = []
    for name, doc, a, b in RULES:
        text, _ = symtm.prove(M, name, a, b, doc=doc, rotate=True)
        thms.append(text)
    print(symtm.rules_file('Machine', 'H107208', thms,
                           'One-sweep rules of 1RB1RE_1LC0RA_0RD1LB_---1RC_1LF1RE_0LB0LE, generated by py/gen_rules.py '
                           '(symbolic simulation, `tools/py/bbtools/symtm.py`).'), end='')


if __name__ == '__main__':
    main()
