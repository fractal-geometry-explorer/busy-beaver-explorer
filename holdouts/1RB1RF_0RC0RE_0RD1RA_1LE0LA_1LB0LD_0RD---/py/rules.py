"""Writes lean/Rules.lean: the shift rule of the feeding rule of 1RB1RF_0RC0RE_0RD1RA_1LE0LA_1LB0LD_0RD---,
proved by bbtools.symtm from a symbolic trace (shift rules, `rfl`, `omega`).  lean/Phase.lean restates and iterates it.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove

M = "1RB1RF_0RC0RE_0RD1RA_1LE0LA_1LB0LD_0RD---"
NS = "H124060"
RULES = [
    ("feed", "One visit of the right end: `L (01)^(k+1) 1 (01)^m 1 F> 0^inf` becomes `L (01)^k 1 (01)^(m+3) 1 F> 0^inf` "
     "(as the run writes it: `L (01)^k 1 0 1 0 (10)^m 1 0 1 1 F> 0^inf`), in 6m+24 steps: the block on the left "
     "loses one copy of 01, the block at the end gains three.",
     "L (01)^k+1 1 (01)^m 1 F> 0^inf", "L (01)^k 1 (01)^m+3 1 F> 0^inf"),
]


def main():
    out = ["import Machine", "", f"/-! Rules of {M}, generated by `py/rules.py`; do not edit by hand. -/", "",
           f"namespace {NS}", "", "open TM", ""]
    for name, doc, start, end in RULES:
        t, f = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=60)
        out += [t, ""]
    out.append(f"end {NS}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
