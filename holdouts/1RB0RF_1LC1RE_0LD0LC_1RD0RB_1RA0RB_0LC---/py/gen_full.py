"""Write lean/Full.lean for another machine of the family from this folder's lean/Full.lean (written by hand for
1RB0RF_1LC1RE_0LD0LC_1RD0RB_1RA0RB_0LC---): the same definitions and proofs, with the machine's own collision
table (`TABLES` of gen_collide.py) in `coll` and `coll_sound`.  For the 0LC machine itself the output is the file
unchanged.

usage (from the repository root):
  python3 holdouts/1RB0RF_1LC1RE_0LD0LC_1RD0RB_1RA0RB_0LC---/py/gen_full.py MACHINE > holdouts/MACHINE/lean/Full.lean
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_collide import TABLES  # noqa: E402

BASE = "1RB0RF_1LC1RE_0LD0LC_1RD0RB_1RA0RB_0LC---"


def main():
    m = sys.argv[1]
    src = open(os.path.join(HERE, "../lean/Full.lean")).read()
    mach = open(os.path.join(HERE, "../../", m, "lean/Machine.lean")).read()
    ns = re.search(r"^namespace (\w+)", mach, re.M).group(1)
    ns0 = re.search(r"^namespace (\w+)", src, re.M).group(1)
    lines = src.split("\n")
    i0 = next(i for i, l in enumerate(lines) if l.startswith("def coll :")) + 1
    i1 = next(i for i, l in enumerate(lines) if l.startswith("  | _, _, _, _ => none"))
    j0 = next(i for i, l in enumerate(lines) if "zcoll_" in l)
    j1 = max(i for i, l in enumerate(lines) if "zcoll_" in l) + 1
    rows, proofs = [], []
    for (tp, g, U), (C, ap, d) in sorted(TABLES[m].items(), key=lambda kv: (kv[0][0], kv[0][1], not kv[0][2].isdigit(), kv[0][2])):
        crev = " :: ".join(str(c) for c in reversed(C))
        rows.append(f"  | s, {tp}, {g}, {U.replace('+', ' + ')} => some ({crev} :: ones s, {ap.replace('+', ' + ')}, {d})")
        name = f"zcoll_{'e' if tp == 0 else 'o'}{g}_{U.replace('+', '')}"
        u = " _" if "u" in U else ""
        proofs.append(f"  · exact ⟨⟨_, by omega, {name}_blank s{u} L⟩, fun h G => ⟨_, by omega, {name}_gap h s{u} G L⟩⟩")
    out = lines[:i0] + rows + lines[i1:j0] + proofs + lines[j1:]
    if m != BASE:
        # the anomaly with a one-unit counter differs from machine to machine: leave it out of the map
        k0 = out.index("      else if c.a = 1 then")
        k1 = out.index("      else none", k0)
        out[k0:k1 + 1] = ["      else none"]
        p0 = next(i for i, l in enumerate(out) if "qa_two" in l) + 1
        assert out[p0] == "      · rw [ite_f ha] at h", out[p0]
        p1 = out.index("        · rw [ite_f h1] at h; cases h", p0)
        out[p0:p1 + 1] = ["      · rw [ite_f ha] at h; cases h"]
    txt = "\n".join(out).replace(f"namespace {ns0}", f"namespace {ns}").replace(f"end {ns0}", f"end {ns}")
    if m != BASE:
        a, b = txt.index("/-!"), txt.index("-/") + 2
        txt = txt[:a] + f"""/-!
# A partial macro map for {m}

Generated by `py/gen_full.py` in the folder of {BASE} from that machine's Full.lean; do not edit by hand.

`astep` maps a Q configuration `qr W a G` (Abstract.lean: word `W` last block first, counter low part `a`, raw
gaps `G`) to the next one, where a rule proved for this machine applies, and returns `none` elsewhere.  It covers:

* the regular Q-steps (the word goes to `phi (phi W)`, the counter adds one), wide and one-unit;
* the anomaly when the counter's low part is wide enough (word one block with `a >= 1`, or a block and a single 1
  with `a >= 2`);
* the collisions in the rows of `coll` (the rows of `TABLES` in gen_collide.py for this machine).

It does NOT cover the anomaly with a one-unit counter (its rules for this machine are in Collide.lean as
`anomx_*`, on tapes, but they are not part of `astep`), nor the other collisions.  The first Q configuration of the
run from blank tape (`start`, step 27) is already such an anomaly, so `astep start = none`: the statements about
`arun ... start` below are true but say nothing yet.  `astep_sound` (each step the map returns is taken by the
machine, in at least 17 machine steps) is the useful theorem of this file.
-/""" + txt[b:]
    print(txt, end="")


if __name__ == "__main__":
    main()
