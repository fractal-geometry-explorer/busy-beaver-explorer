"""Write lean/Rules.lean for a machine of the family 1RB?RF_1LC1RE_0LD0LC_1RD0RB_1RA0RB_X---: the six regular
Q-steps, each proved by `bbtools.symtm.prove` (rfl steps, the crossing lemmas of tools/lean/TM/Basic.lean and omega).

A Q event is the tape  W 0 1^(3a) B>0 R :  W a word of blocks of 1s separated by single 0s, the head in state B on
the 0 right after a run of 3a ones.  Between two Q events the machine applies the map phi twice to W (phi removes the
last block b and adds 2 to the block before it, then appends (b-1)/2 blocks of one 1) and steps a binary counter
written to the right.  The step depends on W only through its last block b (b >= 5, b = 3, or b = 1 after an odd
block 2i+1) and on the counter only through a (a >= 2, or a = 1 followed by t gaps of length 2 and then at least
three 0s); these are the six theorems.  None of the six machines of the family reads A1 or F0 here, so the same
statements hold for all of them.

usage (from the repository root):
  python3 holdouts/1RB0RF_1LC1RE_0LD0LC_1RD0RB_1RA0RB_0LC---/py/gen_rules.py MACHINE > holdouts/MACHINE/lean/Rules.lean
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

W_CASES = [
    ("big", "L 0 1 (11)^j+2", "the last block of W has 2j+5 ones: phi splits it, the second phi merges the last 1"),
    ("three", "L 0 1 1 1", "the last block of W has 3 ones: the block before it gains 4"),
    ("one", "L 0 1 (11)^i 0 1", "the last block of W is a single 1 after a block of 2i+1: the second phi splits that block"),
]
C_CASES = [
    ("wide", "0 (111)^a+2 B> 0 R", "a run of 3(a+2) ones before the head: the counter's low part splits off a unit"),
    ("unit", "0 1 1 1 B> 0 (001)^t 0 0 0 R",
     "a run of 3 ones, then t gaps of length 2, then at least three 0s: the carry absorbs the t units"),
]
ENDS = {
    ("big", "wide"): "L 1 1 0 (10)^j 1 1 1 0 1 1 1 B> (000)^a+1 1 R",
    ("big", "unit"): "L 1 1 0 (10)^j 1 1 1 0 1 1 (111)^t 1 1 1 1 B> 0 R",
    ("three", "wide"): "L 1 1 1 1 0 1 1 1 B> (000)^a+1 1 R",
    ("three", "unit"): "L 1 1 1 1 0 1 1 (111)^t 1 1 1 1 B> 0 R",
    ("one", "wide"): "L 1 1 0 1 (01)^i 0 1 1 1 B> (000)^a+1 1 R",
    ("one", "unit"): "L 1 1 0 1 (01)^i 0 1 1 (111)^t 1 1 1 1 B> 0 R",
}


def main():
    m = sys.argv[1]
    mach = open(os.path.join(HERE, "../../", m, "lean/Machine.lean")).read()
    ns = re.search(r"^namespace (\w+)", mach, re.M).group(1)
    ths = []
    for wn, w, wd in W_CASES:
        for cn, c, cd in C_CASES:
            t, _ = prove(m, f"q_{wn}_{cn}", f"{w} {c}", ENDS[(wn, cn)], doc=f"Q-step: {wd}; {cd}.",
                         count_first=True, max_seg=40, rotate=True)
            ths.append(t)
    print(rules_file("Machine", ns, ths,
                     f"The regular Q-steps of {m}, generated by "
                     "`py/gen_rules.py` in the folder of 1RB0RF_1LC1RE_0LD0LC_1RD0RB_1RA0RB_0LC--- (the shared scripts of the family); do not edit by hand."),
          end="")


if __name__ == "__main__":
    main()
