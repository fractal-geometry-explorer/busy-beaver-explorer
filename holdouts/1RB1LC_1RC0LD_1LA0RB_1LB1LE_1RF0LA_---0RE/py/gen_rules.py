"""Write lean/Rules.lean: the one-pass rules of 1RB1LC_1RC0LD_1LA0RB_1LB1LE_1RF0LA_---0RE, proved by bbtools.symtm.

Words: a = 10.  Each rule is a theorem for all values of its counts (and every tape in the contexts L, R).
usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/<M>/py/gen_rules.py
"""
import os
from bbtools import symtm
from bbtools.machine import Machine

M = "1RB1LC_1RC0LD_1LA0RB_1LB1LE_1RF0LA_---0RE"
RULES = [
    ("dstart", "doubling, first pass: D at the left end of a^(k+1) 1^(c+2)",
     "0^inf D> (10)^k+1 1^c+2 R", "0^inf 1 0 (10)^k 1 A> 0 0 (1)^c R"),
    ("inner", "doubling, one zigzag: a pair 10 moves from the left block to the right block, two 1s become 10",
     "L (10)^a+1 1 A> 0 0 (10)^b 1^c+2 R", "L (10)^a 1 A> 0 0 1 0 1 (01)^b 0 (1)^c R"),
    ("dend", "doubling, last pass: back at the left end in state D",
     "0^inf 1 A> 0 0 (10)^b 1^c+4 R", "0^inf D> 1 0 1 0 1 0 (10)^b 1 0 (1)^c R"),
    ("p2a", "remainder: the 1s run out while pairs are left on the left",
     "0^inf (10)^a+1 1 A> 0 0 (10)^b 0^inf", "0^inf D> 0 0 1 (01)^a+1 0 (11)^b 1 0^inf"),
    ("p2b", "remainder: the 1s and the left pairs run out together",
     "0^inf 1 A> 0 0 (10)^b 0^inf", "0^inf D> 0 0 1 0 (11)^b 1 0^inf"),
    ("p2c", "remainder: two 1s are left when the left pairs run out",
     "0^inf 1 A> 0 0 (10)^b 1 1 0^inf", "0^inf D> 0 0 1 1 1 1 (11)^b 1 0^inf"),
    ("transfer", "transfer: two 1s become a pair 10, the tape grows by two cells on the left",
     "0^inf D> 0 0 (10)^x 1^y+2 R", "0^inf D> 0 0 1 0 1 (01)^x 0 (1)^y R"),
    ("final", "end of a round: one 1 left, the pairs are unfolded into 1s",
     "0^inf D> 0 0 (10)^x 1 0^inf", "0^inf D> 1 0 1 1 1 1 (11)^x 1 1 0^inf"),
    ("tohalt", "the halting case: no 1s at the start of a doubling",
     "0^inf D> (10)^k+1 0^inf", "0^inf 1 0 (10)^k 1 F> 0^inf"),
]


def main():
    m = Machine.parse(M)
    thms = []
    for name, doc, s, e in RULES:
        t, fin = symtm.prove(m, name, s, e, doc=doc, rotate=True)
        thms.append(t)
    out = symtm.rules_file("Machine", "H167198", thms,
                           "One-pass rules of " + M + ", generated by `py/gen_rules.py` with `bbtools.symtm`.")
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "..", "lean", "Rules.lean"), "w") as f:
        f.write(out)


if __name__ == "__main__":
    main()
