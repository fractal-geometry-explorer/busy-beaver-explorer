"""Write lean/Family.lean for a machine whose frame-A table is the core with E1 = 1RF, F0 = 0LD and D1 = 0LB.

That table, 1RB0LC_0RC0RB_1LD0RE_0LE0LB_1LA1RF_0LD---, is the block-list core of gen_family_lean.py with two
transitions moved: E1 = 1RF followed by F0 = 0LD and D1 = 0LB does what the core's E1 = 0LB does, in 3 steps
instead of 1, whenever the cell right of E is 0 (and F1 is the halt).  bbtools.symtm proves the same seven rules of
a visit for it, with longer step counts (PUSH 6k+17, TAIL1 13, TAIL2..4 19, POP 4q+11; TURN unchanged), so the
round rule `go_spec` and the closed form `go_closed` / `visit_closed` hold with the same lists and a longer `goT`.
This writes the first part of py/family_generic.lean (through `visit_closed`) with those counts, after the
symtm proofs of the rules for this table, and the conjugacy to the machine.

usage: python3 gen_family_e1f.py MACHINE NAMESPACE FRAME START > lean/Family.lean
  (FRAME as in frames.py: A, or G for the mirror image with the states renamed A->B->C->D->E->A; START the
  frame-A start state)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import frames  # noqa: E402
import gen_family_lean as g  # noqa: E402

FA = "1RB0LC_0RC0RB_1LD0RE_0LE0LB_1LA1RF_0LD---"

SUBS = [
    ("steps (6 * k + 15) ⟨L, cons false (rep (2 * k + 3)", "steps (6 * k + 17) ⟨L, cons false (rep (2 * k + 3)"),
    ("    steps 9 ⟨ctxL (q + 1) 1 L,", "    steps 13 ⟨ctxL (q + 1) 1 L,"),
    ("    steps 15 ⟨ctxL (q + 1) 2 L,", "    steps 19 ⟨ctxL (q + 1) 2 L,"),
    ("    steps 15 ⟨ctxL q 3 L,", "    steps 19 ⟨ctxL q 3 L,"),
    ("    steps 15 ⟨ctxL q 4 L,", "    steps 19 ⟨ctxL q 4 L,"),
    ("    steps (4 * q + 9) ⟨ctxL q 5 L,", "    steps (4 * q + 11) ⟨ctxL q 5 L,"),
    ("(3 * b + 6) + goT n l0 + 9 + goT n l1 + 15 + goT n l2 + 15 + goT n l3 + 15 + goT n l4 + (2 * b - 5)",
     "(3 * b + 8) + goT n l0 + 13 + goT n l1 + 19 + goT n l2 + 19 + goT n l3 + 19 + goT n l4 + (2 * b - 3)"),
    ("(6 * (j + 2) + 15) + (goT n l0 + (9 + (goT n l1 + (15 + (goT n l2 + (15 + (goT n l3 + (15 + (goT n l4 + (4 * j + 9))))))))))",
     "(6 * (j + 2) + 17) + (goT n l0 + (13 + (goT n l1 + (19 + (goT n l2 + (19 + (goT n l3 + (19 + (goT n l4 + (4 * j + 11))))))))))"),
    ("/-- Its exact step count. -/", "/-- Its exact step count (this table: every E1 is a three-step detour E1, F0, D1). -/"),
]


def generic_part():
    txt = g.generic()
    cut = txt.index("/-! ## What a clean visit conserves")
    txt = txt[:cut]
    for a, b in SUBS:
        if a not in txt:
            raise SystemExit("template changed: " + a[:60])
        txt = txt.replace(a, b)
    return txt


def file_text(machine, ns, fr, st):
    frames.FAMILY.append((machine, fr, FA, st))
    return f"""import Machine

/-!
# {machine}: the round rule of the nested block counter for every depth

Generated by `py/gen_family_e1f.py` in the folder of the family's first machine
(holdouts/1RB0LC_0RC0RB_1LD0RE_0LE0LF_1LA0LB_0RA---); do not edit by hand.

`FA.trans` is this machine's frame-A conjugate {FA}: the block-list core with E1 = 1RF, F0 = 0LD and
D1 = 0LB.  Where the cell right of E is 0, the detour E1 -> F0 -> D1 does what the core's E1 = 0LB does, in three
steps; so the seven rules of a visit hold as for the core (bbtools.symtm proves them below for this table), only
longer, and so do the round rule `go_spec` and the closed form `visit_closed`.  The run from blank tape starts in
frame-A state {st}.
-/

namespace {ns}
namespace FA

open TM

/-- The frame-A conjugate of {machine}: {FA}. -/
def trans : St → Bool → Option (Bool × Dir × St)
{g.table_rows(FA)}

abbrev steps := TM.steps trans

/-! ## The seven rules as bbtools.symtm proves them -/

{g.raw_rules(FA)}
{generic_part()}
end FA

open TM
{g.conj(machine, fr, st)}
end {ns}
"""


if __name__ == "__main__":
    print(file_text(*sys.argv[1:5]))
