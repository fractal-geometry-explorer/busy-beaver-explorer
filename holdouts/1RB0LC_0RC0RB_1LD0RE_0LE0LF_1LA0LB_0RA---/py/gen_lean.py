"""Write lean/Rules.lean for a machine of the family: the round rules of `rounds.py`, translated to the machine's
frame (frames.py) and proved by bbtools.symtm on the machine itself.

usage: python3 gen_lean.py MACHINE NAMESPACE [MMAX]  > Rules.lean
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import frames, rounds  # noqa: E402
from bbtools.symtm import prove, rules_file  # noqa: E402

DOC = {1: "the last block", 2: "the last two blocks", 3: "the last three blocks"}


def theorems(machine, mmax=2):
    fr, fa, st = frames.info(machine)
    out = []
    for m in range(1, mmax + 1):
        for p in range(1, 5):
            s, e, _ = rounds.configs(m, p)
            s2, e2 = frames.translate(s, fr), frames.translate(e, fr)
            name = f"round_m{m}_p{p}"
            ef = rounds.eff(m)
            if p == 1:
                ef = [ef[0] + 2] + ef[1:]
            doc = (f"A round on {DOC.get(m, f'the last {m} blocks')} from phase {p} to phase {p + 1} "
                   f"(frame {fr}): the blocks change by {ef}.")
            txt, fin = prove(machine, name, s2, e2, rotate=True, count_first=True, max_moves=10 ** 7, doc=doc)
            out.append((txt, fin.steps, s2, e2))
    return out


if __name__ == "__main__":
    machine, ns = sys.argv[1], sys.argv[2]
    mmax = int(sys.argv[3]) if len(sys.argv) > 3 else 2
    ths = theorems(machine, mmax)
    doc = (f"Round rules of {machine}, generated by "
           "`py/gen_lean.py` in the folder of the family's first machine (frame A, F0 = 0RA); do not edit by hand.\n\n"
           "At an event the head turns right on the left edge of a suffix of blocks (10)^y written plainly; the block "
           "on its left is spread as (1000)^q followed by a tail of phase p (10, 1, 1001, 101, 11).  A round runs "
           "the whole suffix once and comes back one phase further, with the block values changed as each "
           "theorem states, for all values above the offsets written and every context L.")
    sys.stdout.write(rules_file("Machine", ns, [t[0] for t in ths], doc))
