"""Generate lean/Rules.lean: the pieces of a round of 1RB0LA_0RC---_0RD0RF_1LD0LE_0LA1LE_0RA0LA, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage (from the repo root):  python3 holdouts/1RB0LA_0RC---_0RD0RF_1LD0LE_0LA1LE_0RA0LA/py/rules.py > \
                                 holdouts/1RB0LA_0RC---_0RD0RF_1LD0LE_0LA1LE_0RA0LA/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(11)^n` is n copies
of `11`, `0^inf` blank tape, L and R any tape.  How the pieces make a round: README.md ("A round").
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LA_0RC---_0RD0RF_1LD0LE_0LA1LE_0RA0LA"

RULES = [
    ("sweep", "L 0 C> (11)^n R", "L (01)^n 0 C> R",
     "The sweep: moving right, B, C, F and A turn each pair `11` into `01` (4 steps a pair)."),
    ("cross", "L 0 C> (11)^n 1 0 1 R", "L (01)^n 0 0 1 0 C> R",
     "The sweep through an odd block: its last 1, the hole and the next 1 become `0 1 0`, a `0 0` mark is left "
     "among the pairs, and the sweep carries on into the next block, one cell in."),
    ("glide", "L 0 0 D> 1^n R", "L 1^n 0 0 D> R",
     "The glider: a pair of 0s moves right through a block of ones, one cell every 5 steps."),
    ("first", "0^inf E> 0 (11)^m+2 0 1^a+3 0 1 R", "0^inf 1 0 (10)^m 1 E> 0 1^a+3 0 1 1 1 1 R",
     "A round from a first block of even length 2m + 4: the sweep turns it into `0 1` pairs, the glider it ends with "
     "crosses the second block and lands on the hole after it, which moves 3 cells left; E returns to the pairs."),
    ("cycle", "L 1 0 1 0 1 E> 0 1^p+2 0 1 R", "L 1 E> 0 1^p+3 0 1 1 1 1 R",
     "One glider of the round: two `0 1` pairs make a new glider, which runs to the hole; the hole moves 3 cells "
     "left, the block before it gains one cell."),
    ("last", "0^inf 1 0 1 E> 0 1^p+2 0 1 R", "0^inf E> 0 1^p+3 0 1 1 1 1 R",
     "The last glider, made from the last pair at the left end: the round ends with E at the left end."),
    ("last2", "0^inf 1 0 1 0 1 E> 0 1^p+4 0 1 R", "0^inf E> 0 1^p+5 0 1 1 1 1 1 1 1 R",
     "The end of a round from a block of length 4k + 2: the last two pairs make a glider, and the two 0s left at "
     "the left end make one more; both move the hole 3 cells left."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H97059", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
