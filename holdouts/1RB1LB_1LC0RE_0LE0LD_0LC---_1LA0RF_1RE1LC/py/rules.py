"""Generate ../lean/Rules.lean: rules of 1RB1LB_1LC0RE_0LE0LD_0LC---_1LA0RF_1RE1LC, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`, repeats re-bracketed
next to the head with `TM.rep_rotate`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.  The left side of the tape is made of segments of the word x = 1110.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LB_1LC0RE_0LE0LD_0LC---_1LA0RF_1RE1LC"

RULES = [
    ('shift_E_0001_l', 'L (0001)^n E> 0 R', 'L E> 0 (0111)^n R',
     'E crosses (0001)^n leftwards in 4*n steps.'),
    ('shift_C_0010_l', 'L (0010)^n C> 0 R', 'L C> 0 (1110)^n R',
     'C crosses (0010)^n leftwards in 4*n steps.'),
    ('shift_D_01_l', 'L (01)^n D> 0 R', 'L D> 0 (00)^n R',
     'D crosses (01)^n leftwards in 2*n steps.'),
    ('shift_F_01_r', 'L F> (01)^n R', 'L (10)^n F> R',
     'F crosses (01)^n rightwards in 2*n steps.'),
    ('shift_B_0100_l', 'L (0100)^n B> 0 R', 'L B> 0 (1101)^n R',
     'B crosses (0100)^n leftwards in 4*n steps.'),
    ('shift_D_0110_l', 'L (0110)^n D> 0 R', 'L D> 0 (0111)^n R',
     'D crosses (0110)^n leftwards in 8*n steps.'),
    ('shift_F_0111_r', 'L F> (0111)^n R', 'L (0010)^n F> R',
     'F crosses (0111)^n rightwards in 12*n steps.'),
    ('shift_C_10_l', 'L (10)^n C> 1 R', 'L C> 1 (00)^n R',
     'C crosses (10)^n leftwards in 2*n steps.'),
    ('shift_E_10_r', 'L E> (10)^n R', 'L (01)^n E> R',
     'E crosses (10)^n rightwards in 2*n steps.'),
    ('shift_A_1000_l', 'L (1000)^n A> 1 R', 'L A> 1 (1011)^n R',
     'A crosses (1000)^n leftwards in 4*n steps.'),
    ('shift_B_1001_l', 'L (1001)^n B> 0 R', 'L B> 0 (1101)^n R',
     'B crosses (1001)^n leftwards in 8*n steps.'),
    ('shift_C_1100_l', 'L (1100)^n C> 1 R', 'L C> 1 (1110)^n R',
     'C crosses (1100)^n leftwards in 8*n steps.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H149506", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
