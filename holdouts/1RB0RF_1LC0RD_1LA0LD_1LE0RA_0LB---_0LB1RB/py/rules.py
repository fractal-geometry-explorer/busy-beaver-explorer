"""Generate ../lean/Rules.lean: the shift rules of the sweep of 1RB0RF_1LC0RD_1LA0LD_1LE0RA_0LB---_0LB1RB, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
L and R any tape.  The bulk of the left side is made of the words x = 10111110 and, while the head runs right
over them, y = 10011001.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RF_1LC0RD_1LA0LD_1LE0RA_0LB---_0LB1RB"

RULES = [
    ("left_end", "0^inf A> 0 1 (10111110)^n+1 R", "0^inf 1 0 0 1 (10011001)^n 0 0 0 F> 1 1 0 R",
     "The turn at the left end: A starts the rightward pass over the leading segment x^(n+1).", True),
    ("right_pass", "L 0 0 0 F> 1 1 0 (10111110)^n R", "L (10011001)^n 0 0 0 F> 1 1 0 R",
     "Going right, F rewrites each word x = 10111110 as y = 10011001, 26 steps a word.", True),
    ("left_pass", "L (10011001)^n B> 0 R", "L B> 0 (01111101)^n R",
     "Going left, B rewrites the words y back, 20 steps a word: the cells `0 (01111101)^n` are `0 0 1 1 1 1 1 0 x^(n-1) 1`.",
     False),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=rot)[0] for name, a, b, doc, rot in RULES]
    sys.stdout.write(rules_file("Machine", "H87181", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
