"""Generate Rules.lean for 1RB1LD_0RC0RF_1LC0LA_0LE1LD_1LA---_0RB0LF: rules proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, L and R are any
tape.  How the rules make a sweep is in the README ("The dealing sweep").
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LD_0RC0RF_1LC0LA_0LE1LD_1LA---_0RB0LF"

RULES = [
    ("c_shift", "L 0 C> 1^n R", "L 1^n 0 C> R",
     "`0 C> 1^n` becomes `1^n 0 C>` in 3n steps: the 0 next to the head travels right through the block "
     "(C1 -> 0LA, A0 -> 1RB, B0 -> 0RC)."),
    ("deal", "L 1 0 0 0 F> 1^n+4 0 R", "L 1 1 0 0 0 F> 1^n 1 0 1 1 R",
     "One deal: the block being dealt loses three ones, one goes to the block on its left (behind `000`) and two "
     "to the block on its right, in 4n + 23 steps."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H68273", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
