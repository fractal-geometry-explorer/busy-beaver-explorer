"""Generate ../lean/Rules.lean: rules of 1RB1LB_1LC0RD_0LE1LA_0RF1RA_1LE0LA_---0RB, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`, repeats re-bracketed
next to the head with `TM.rep_rotate`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.  The left side of the tape is made of the 3-cell words 110 and 111.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LB_1LC0RD_0LE1LA_0RF1RA_1LE0LA_---0RB"

RULES = [
    ('shift_E_0_l', 'L (0)^n E> 0 R', 'L E> 0 (1)^n R',
     'E crosses (0)^n leftwards in n steps.'),
    ('shift_A_011_r', 'L A> (011)^n R', 'L (101)^n A> R',
     'A crosses (011)^n rightwards in 3*n steps.'),
    ('shift_B_011_l', 'L (011)^n B> 0 R', 'L B> 0 (111)^n R',
     'B crosses (011)^n leftwards in 3*n steps.'),
    ('shift_D_011_r', 'L D> (011)^n R', 'L (000)^n D> R',
     'D crosses (011)^n rightwards in 3*n steps.'),
    ('shift_B_101_r', 'L B> (101)^n R', 'L (000)^n B> R',
     'B crosses (101)^n rightwards in 3*n steps.'),
    ('shift_C_101_l', 'L (101)^n C> 1 R', 'L C> 1 (111)^n R',
     'C crosses (101)^n leftwards in 3*n steps.'),
    ('shift_D_101_r', 'L D> (101)^n R', 'L (110)^n D> R',
     'D crosses (101)^n rightwards in 3*n steps.'),
    ('shift_A_110_l', 'L (110)^n A> 1 R', 'L A> 1 (111)^n R',
     'A crosses (110)^n leftwards in 3*n steps.'),
    ('shift_B_110_r', 'L B> (110)^n R', 'L (011)^n B> R',
     'B crosses (110)^n rightwards in 3*n steps.'),
    ('shift_F_110_r', 'L F> (110)^n R', 'L (000)^n F> R',
     'F crosses (110)^n rightwards in 3*n steps.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H696", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
