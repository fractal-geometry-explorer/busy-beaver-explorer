"""Generate Rules.lean for 1RB---_1RC0LF_1RD1RD_1RE1RA_1LF0RC_1LC1LB: the halting context and the shift rules over the words of its tape, proved along the symbolic run of tools/py/bbtools/symtm.py
(single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB---_1RC0LF_1RD1RD_1RE1RA_1LF0RC_1LC1LB"

RULES = [
    ('halt_ctx', 'L C> 0 1 1 R', 'L 1 1 A> 1 R',
     'C on a 0 with 1 1 after it reaches A on a 1 (the halting transition) in two steps.'),
    ("halt_ctx'", 'L C> 1 1 1 R', 'L 1 1 A> 1 R',
     'The same with a 1 under the head: C writes 1 whatever it reads, so only the two cells after it matter.'),
    ('halt_ctx_E', 'L E> 1 0 1 1 R', 'L 0 1 1 A> 1 R',
     'E on a 1 hands over to C one cell right: from E> 1 x 1 1 it halts.'),
    ('run_A_0001', 'L A> (0001)^n R', 'L (1111)^n A> R',
     'A crosses n copies of `0001` to the right in 4n steps, leaving `1111`.'),
    ('back_B_100_11', 'L (100)^n B> 1 1 R', 'L B> 1 1 (010)^n R',
     'B crosses n copies of `100` to the left in 9n steps, leaving `010` (carrying `1 1`).'),
    ('back_B_110_11', 'L (110)^n B> 1 1 R', 'L B> 1 1 (010)^n R',
     'B crosses n copies of `110` to the left in 9n steps, leaving `010` (carrying `1 1`).'),
    ('run_C_001', 'L C> (001)^n R', 'L (110)^n C> R',
     'C crosses n copies of `001` to the right in 3n steps, leaving `110`.'),
    ('run_C_101', 'L C> (101)^n R', 'L (110)^n C> R',
     'C crosses n copies of `101` to the right in 3n steps, leaving `110`.'),
    ('run_D_011', 'L D> (011)^n R', 'L (101)^n D> R',
     'D crosses n copies of `011` to the right in 3n steps, leaving `101`.'),
    ('run_D_101_01', 'L 0 1 D> (101)^n R', 'L (111)^n 0 1 D> R',
     'D crosses n copies of `101` to the right in 11n steps, leaving `111` (carrying `0 1`).'),
    ('run_D_1000', 'L D> (1000)^n R', 'L (1111)^n D> R',
     'D crosses n copies of `1000` to the right in 4n steps, leaving `1111`.'),
    ('run_E_100', 'L E> (100)^n R', 'L (011)^n E> R',
     'E crosses n copies of `100` to the right in 3n steps, leaving `011`.'),
    ('run_E_110', 'L E> (110)^n R', 'L (011)^n E> R',
     'E crosses n copies of `110` to the right in 3n steps, leaving `011`.'),
    ('back_F_001_1', 'L (001)^n F> 1 R', 'L F> 1 (010)^n R',
     'F crosses n copies of `001` to the left in 9n steps, leaving `010` (carrying `1`).'),
    ('back_F_101_1', 'L (101)^n F> 1 R', 'L F> 1 (010)^n R',
     'F crosses n copies of `101` to the left in 9n steps, leaving `010` (carrying `1`).'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H43527", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
