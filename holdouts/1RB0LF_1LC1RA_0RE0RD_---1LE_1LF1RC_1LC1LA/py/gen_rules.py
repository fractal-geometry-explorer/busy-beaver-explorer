"""Cycle rules found and proved by bbtools.cycles on the run from blank tape, as a Lean file.

usage: python3 gen_rules.py MACHINE NAMESPACE K STEPS MAXRULES > Rules.lean
Runs the cycle accelerator (blocks of K cells) for STEPS steps, keeps the first MAXRULES rules with distinct
statements and writes them (renamed rule0, rule1, ...) after `import Machine`."""
import os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.cycles import Accelerator
from bbtools.macro import MacroRun
from bbtools import symtm

def main(m, ns, k, steps, maxr):
    a = Accelerator(MacroRun(m, k)).run(steps)
    seen, keep = set(), []
    for r in a.rules:
        txt = r.lean
        head = txt.split(":= by")[0]
        stmt = re.sub(r"theorem \w+", "theorem X", head)
        stmt = re.sub(r"/--.*?-/", "", stmt, flags=re.S)
        if stmt in seen:
            continue
        seen.add(stmt)
        keep.append(re.sub(r"theorem \w+", f"theorem rule{len(keep)}", txt, count=1))
        if len(keep) >= maxr:
            break
    sys.stderr.write(f"{len(a.rules)} rules, {len(keep)} kept, run at {a.run_.steps} steps\n")
    return symtm.rules_file("Machine", ns, keep, f"Cycle rules of {m}, found and proved by `bbtools.cycles` "
                            f"(blocks of {k} cells) on the run from blank tape; generated by `py/gen_rules.py`.")

if __name__ == "__main__":
    m, ns, k, steps, maxr = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(float(sys.argv[4])), int(sys.argv[5])
    sys.stdout.write(main(m, ns, k, steps, maxr))
