"""Generate Rules.lean: the pieces of one round of 1RB1RC_1LC1LC_1RE0LD_1LB1RF_---1RA_0RD1RD, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right, `S>` is the head in state S on the next cell, `(11)^n` is n copies of `11`.
The two families of tapes (see Macro.lean): the round start P u v = `0^inf C> 0 11 0 (11)^u 0 (11)^v 0^inf` and
Q u v = `0^inf C> 0 11 0 11 0 (11)^u 0 (11)^v 0^inf`; the sweep S = `X 0 1 (11)^y 0 (11)^z D> 0^inf`, where the left
part X is `0^inf (11)^x` (after P) or `0^inf (11)^x 1` (after Q).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine, STATES  # noqa: E402
from bbtools.symtm import Blank, Config, Halted, prove, rules_file, run  # noqa: E402

M = "1RB1RC_1LC1LC_1RE0LD_1LB1RF_---1RA_0RD1RD"
XP, XQ = "0^inf (11)^x", "0^inf (11)^x 1"

RULES = [
    ("blank_start", "0^inf A> 0^inf", "0^inf C> 0 11 0 (11)^3 0^inf",
     "From blank tape the machine reaches the round start P 3 0 in 41 steps."),
    ("entryP", "0^inf C> 0 11 0 (11)^u+3 0 (11)^v+1 0^inf", "0^inf (11)^3 0 1 (11)^u+1 0 (11)^v+1 D> 0^inf",
     "The start of a round from P: the head runs to the right end, the left part becomes six 1s."),
    ("entryQ", "0^inf C> 0 11 0 11 0 (11)^u+3 0 (11)^v+1 0^inf",
     "0^inf (11)^4 1 0 1 (11)^u+1 0 (11)^v+1 D> 0^inf",
     "The start of a round from Q: the left part becomes nine 1s."),
    ("entryP0", "0^inf C> 0 11 0 (11)^u+3 0 0^inf", "0^inf C> 0 11 0 11 0 (11)^3 0 (11)^u+1 0^inf",
     "P with an empty last block: the round goes straight to Q 3 (u+1)."),
    ("entryQ0", "0^inf C> 0 11 0 11 0 (11)^u+3 0 0^inf", "0^inf C> 0 11 0 (11)^5 0 (11)^u+1 0^inf",
     "Q with an empty last block: the round goes straight to P 5 (u+1)."),
]
RULES += [
    ("bounce", "L 0 1 (11)^y+2 0 (11)^z+2 D> 0^inf", "L (11)^3 0 1 (11)^y+1 0 (11)^z+1 D> 0^inf",
     "One bounce: the middle and the last block lose a pair of 1s each, the left part gains three pairs; the head "
     "never goes left of the 0 before the middle block."),
    ("bounce1", "L 0 1 11 0 (11)^z+2 D> 0^inf", "L (11)^3 0 1 0 (11)^z+1 D> 0^inf",
     "The last bounce, from a middle block of three 1s."),
]
for tag, X in (("P", XP), ("Q", XQ)):
    RULES += [
        (f"yexit{tag}", f"{X} 0 1 0 (11)^z+5 D> 0^inf", None,
         "The middle block is used up: the head walks to the left end and the next round starts."),
        (f"yexit3{tag}", f"{X} 0 1 0 (11)^3 D> 0^inf", None, "`yexit` with a last block of six 1s."),
        (f"yexit4{tag}", f"{X} 0 1 0 (11)^4 D> 0^inf", None, "`yexit` with a last block of eight 1s."),
        (f"zexit{tag}", f"{X} 0 1 (11)^y+3 0 11 D> 0^inf", None,
         "The last block is used up: the head walks to the left end and the next round starts."),
        (f"zexit1{tag}", f"{X} 0 1 11 0 11 D> 0^inf", None, "`zexit` with a middle block of three 1s."),
        (f"zexit2{tag}", f"{X} 0 1 (11)^2 0 11 D> 0^inf", None, "`zexit` with a middle block of five 1s."),
    ]
    RULES += [
        (f"halt1{tag}", f"{X} 0 1 0 11 D> 0^inf", "halt", "Middle block used up with a last block of two 1s: the "
         "head runs off the right end in state E, which halts on a 0."),
        (f"halt2{tag}", f"{X} 0 1 0 (11)^2 D> 0^inf", "halt", "The same with a last block of four 1s."),
    ]


def left_end(c):
    return (not c.steps.is_zero() and STATES[c.state] == "C" and len(c.left) == 1 and isinstance(c.left[0], Blank)
            and c.right and c.right[0] == 0)


def before_halt(start):
    """The configuration the run from `start` halts in (head on a cell whose transition is undefined)."""
    m = Machine.parse(M)
    c = Config.parse(start)
    while True:
        prev = c.copy()
        try:
            run(m, c, lambda _: False, max_moves=1, rotate=True)
        except Halted:
            return prev
        except RuntimeError:
            pass


def main():
    m = Machine.parse(M)
    ths = []
    for name, a, b, doc in RULES:
        if b is None:
            b = run(m, Config.parse(a), left_end, rotate=True)
        elif b == "halt":
            b = before_halt(a)
        ths.append(prove(M, name, a, b, doc=doc, rotate=True, max_seg=40)[0])
    sys.stdout.write(rules_file("Machine", "H151747", ths,
                                f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
