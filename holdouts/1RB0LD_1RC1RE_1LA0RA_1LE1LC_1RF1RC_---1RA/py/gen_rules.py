"""Writes lean/Rules.lean for 1RB0LD_1RC1RE_1LA0RA_1LE1LC_1RF1RC_---1RA: the walker sweeps, proved for all tail lengths
by bbtools.symtm.  Run from this folder: python3 py/gen_rules.py > lean/Rules.lean"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB0LD_1RC1RE_1LA0RA_1LE1LC_1RF1RC_---1RA"
RULES = [
    ("walk_down", "L 1 1 1 1 0 (110)^q 1 1 C> 0^inf", "L 1 0 (110)^q+2 1 1 C> 0^inf",
     "The last marked group loses three 1s and the tail gains two groups: `1^m 0 (110)^q 1 1 C>` (m ≥ 4) becomes "
     "`1^(m-3) 0 (110)^(q+2) 1 1 C>`, in 10q + 23 steps."),
    ("walk_left", "L 1 1 0 1 1 1 0 (110)^q 1 1 C> 0^inf", "L 1 1 1 1 1 1 0 (110)^q+1 1 1 C> 0^inf",
     "The walker steps one group left: `110 1110 (110)^q 1 1 C>` becomes `1^6 0 (110)^(q+1) 1 1 C>`, in 10q + 23 steps."),
    ("walk_merge", "L 1 0 1 1 1 0 (110)^q 1 1 C> 0^inf", "L 1 1 1 1 1 0 (110)^q+1 1 1 C> 0^inf",
     "The walker reaches the marked group before it: `1^m 0 1110 (110)^q 1 1 C>` becomes `1^(m+4) 0 (110)^(q+1) 1 1 C>`."),
    ("push", "L 1 1 1 1 1 1 C> 0^inf", "L 1 1 1 0 1 1 0 1 1 C> 0^inf",
     "After a carry that leaves `1^6` at the end: the tail becomes a marked item, `1^6 C>` becomes `1110 110 11 C>`, "
     "in 13 steps."),
]
thms = []
for name, s, e, doc in RULES:
    t, _ = prove(M, name, s, e, doc=doc, rotate=True, count_first=True, max_seg=40)
    thms.append(t)
doc = """# The walker

Generated by `py/gen_rules.py` with `bbtools.symtm.prove`: every theorem is a run of the machine for every tail length
`q` and every tape `L` further left (left tapes are written nearest the head first).  At a sweep start the head is in
state C on the blank cell right of the tape; the tape is groups `1^m 0` and ends with `1 1`.  The end configurations
are written the way the run brackets them (the repeated word `110` re-bracketed as `101` or `011`: the same cells)."""
print(rules_file("Machine", "H41716", thms, doc), end="")
