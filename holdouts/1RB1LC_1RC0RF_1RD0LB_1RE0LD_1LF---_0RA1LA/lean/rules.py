"""Generate Rules.lean: turns at the left end of 1RB1LC_1RC0RF_1RD0LB_1RE0LD_1LF---_0RA1LA, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(1100)^n` is n copies of 1100 (the
word c of ../README.md, also seen as 1001 or 0110 while the head is on it), R is any tape, 0^inf blank tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LC_1RC0RF_1RD0LB_1RE0LD_1LF---_0RA1LA"
END = "0^inf 1 (1001)^n+1 1 0 0 1 B> R"

RULES = [
    ("bounce_c", "0^inf (1100)^n+1 C> 1 1 R", END,
     "The head comes back over the block of n+1 words c in C, bounces off the blank tape and crosses it again.", {"rotate": True}),
    ("bounce_a", "0^inf 1 (1001)^n+1 A> 1 R", END,
     "The same bounce, entered in A.", {"rotate": True}),
    ("start_a", "0^inf A> 0 (1100)^n+1 R", "0^inf (1100)^n+1 1 B> R",
     "From a record in A at the left end, the block is crossed rightwards.", {"rotate": True}),
    ("period", "0^inf B> 0 0 1 (1100)^n (10110110)^m+5 R", "0^inf B> 0 0 1 (1100)^n+31 (10110110)^m R",
     "One period of a phase (84 records at the left end): five words d = 10110110 are traded for 31 words c = 1100, "
     "the junction between the blocks going through its whole cycle; R is never read.", {"rotate": True}),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, count_first=True, max_seg=60, **kw)[0] for name, a, b, doc, kw in RULES]
    out = rules_file("Machine", "H66813", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    out = out.replace("namespace H66813", "set_option maxHeartbeats 4000000\nset_option maxRecDepth 10000\n\nnamespace H66813", 1)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
