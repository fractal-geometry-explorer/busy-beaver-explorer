"""Generate ResetRules.lean: the resets at the end of a phase of 1RB1LC_1RC0RF_1RD0LB_1RE0LD_1LF---_0RA1LA, one rule
per row of the table in ../README.md and parity of n, proved along the symbolic run (tools/py/bbtools/symtm.py, as
rules.py).  Resets.lean restates them in the `cfg` form of Periods.lean.

usage: python3 resets.py > ResetRules.lean

A phase ends at `0^inf B> 0 0 1 (1100)^n (10110110)^r 1 0 (1110)^(t+δ) R` with r < 5; R is any tape, never read.  The
block of n words c = 1100 is written as (11001100)^a (n = 2a) or 1100 (11001100)^a (n = 2a + 1) where the reset
turns pairs of c into words d = 10110110.  The end configurations are stated the way the run writes them.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402
from bbtools.symtm import prove, rules_file  # noqa: E402

# The reset crosses the block with the head zig-zagging over up to 8 cells of the new words: carry words that long.
symtm.MAX_CARRY = 8

M = "1RB1LC_1RC0RF_1RD0LB_1RE0LD_1LF---_0RA1LA"
C, D = "1100", "10110110"


def tape(block, ds, m_rep, tail):
    return f"0^inf B> 0 0 1 {block} {' '.join([D] * ds)} {m_rep} 1 0 (1110)^{tail} R"


EVEN, ODD = "(11001100)^a", f"{C} (11001100)^a"
# name, start, end (as the run writes it), doc
RULES = [
    ("reset0_even_raw", tape(EVEN, 0, "", "t+4"), tape(" ".join([C] * 10), 1, f"({D})^a {D}", "t"),
     "Row r = 0, n = 2a: (2a, 0, t+4) -> new phase (10, a + 2, t)."),
    ("reset0_odd_raw", tape(ODD, 0, "", "t+4"), tape(" ".join([C] * 10), 2, f"({D})^a {D}", "t"),
     "Row r = 0, n = 2a + 1: (2a + 1, 0, t+4) -> new phase (10, a + 3, t)."),
    ("reset1_raw", tape(f"({C})^n", 1, "", "t+1"), tape(" ".join([C] * 11) + " 1 1 (0011)^n 0 0", 0, "", "t"),
     "Row r = 1: (n, 1, t+1) -> (n + 12, 0, t)."),
    ("reset2_raw", tape(f"({C})^n+1", 2, "", "t+4"), tape(" ".join([C] * 32) + f" ({C})^n {C}", 0, "", "t"),
     "Row r = 2: (n + 1, 2, t+4) -> (n + 33, 0, t)."),
    ("reset3_even_raw", tape(EVEN, 3, "", "t+3"), tape(" ".join([C] * 10), 11, f"({D})^a {D}", "t"),
     "Row r = 3, n = 2a: (2a, 3, t+3) -> new phase (10, a + 12, t)."),
    ("reset3_odd_raw", tape(ODD, 3, "", "t+3"), tape(" ".join([C] * 10), 12, f"({D})^a {D}", "t"),
     "Row r = 3, n = 2a + 1: (2a + 1, 3, t+3) -> new phase (10, a + 13, t)."),
    ("reset4_even_raw", tape(EVEN, 4, "", "t+2"), tape(" ".join([C] * 10), 12, f"({D})^a {D}", "t"),
     "Row r = 4, n = 2a: (2a, 4, t+2) -> new phase (10, a + 13, t)."),
    ("reset4_odd_raw", tape(ODD, 4, "", "t+2"), tape(" ".join([C] * 10), 12, f"({D})^a {D}", "t"),
     "Row r = 4, n = 2a + 1: (2a + 1, 4, t+2) -> new phase (10, a + 13, t)."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, count_first=True, max_seg=60, rotate=True, max_moves=10 ** 6)[0]
           for name, a, b, doc in RULES]
    out = rules_file("Machine", "H66813", ths,
                     f"Resets of {M} at the end of a phase, generated by `resets.py`; do not edit by hand.")
    out = out.replace("namespace H66813", "set_option maxHeartbeats 4000000\nset_option maxRecDepth 10000\n\nnamespace H66813", 1)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
