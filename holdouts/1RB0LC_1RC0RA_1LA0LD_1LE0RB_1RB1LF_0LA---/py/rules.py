"""The macro rules of 1RB0LC_1RC0RA_1LA0LD_1LE0RB_1RB1LF_0LA--- between visits of state A, proved with symtm, and
some rounds (left end to left end) that follow from them.  Writes lean/Rules.lean when given a path."""
import sys
import os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../../tools/py'))
from bbtools.symtm import prove
M = '1RB0LC_1RC0RA_1LA0LD_1LE0RB_1RB1LF_0LA---'
rules = [
 # ---- the ten macro rules: from a configuration in state A to the next one (L, R: any tape)
 ('R1', 'L A> 0 1 R', 'L 1 0 A> R', 'A reads 01: flip the pair and go on to the right.'),
 ('R2', 'L A> 0 0 1^k 0 R', 'L 1 0^k A> 1 1 R', 'A reads 00 1^k 0: the ones are erased and the head turns (it now reads a 1).'),
 ('L1', 'L 1 0 A> 1 R', 'L A> 1 1 0 R', 'A reads 1 with 10 on its left: cross the pair to the left.'),
 ('L2', 'L 1 0 1 0 1 A> 1 R', 'L A> 1 0 1 1 0 0 R', 'Left of the head 10101.'),
 ('L3', 'L 1 1 1 A> 1 R', 'L A> 1 1 0 1 R', 'Left of the head 111.'),
 ('L4', 'L 1 1 0 1 A> 1 R', 'L F> 1 1 1 0 0 R', 'Left of the head 1101: four steps later the machine is in state F reading 1 and halts.'),
 ('L5', 'L 0 0 A> 1 R', 'L A> 0 1 0 R', 'Left of the head 00: the head turns to the right (at the left end of the tape this is the start of a round).'),
 ('L6', 'L 0 0 1 0 1 A> 1 R', 'L A> 0 0 1 1 0 0 R', 'Left of the head 00101: turn to the right.'),
 ('L7', 'L 0 1 1 A> 1 R', 'L A> 0 1 0 1 R', 'Left of the head 011: turn to the right.'),
 ('L8', 'L 0 0 1 A> 1 R', 'L 1 0 A> 0 0 R', 'Left of the head 001: turn to the right.'),
 # ---- passes that follow
 ('pass_run', 'L A> (01)^a R', 'L (10)^a A> R', 'The right pass over a run.'),
 ('pass_sep', 'L A> 00110 R', 'L 11010 A> R', 'The right pass over a separator.'),
 ('back_run', 'L (10)^a A> 1 R', 'L A> 1 (10)^a R', 'The left pass over a run.'),
 ('back_sep', 'L 1010 11010 A> 1 R', 'L A> 1 0110 0 1010 R', 'The left pass over a separator: two pairs move from its left to its right.'),
 ('left_end', '0^inf (10)^j A> 1 R', '0^inf A> 0 1 0 (10)^j R', 'The left pass reaches the left end: the first run gains a pair and a new round starts.'),
 # ---- rounds: head in state A at the left end of the tape to the next such moment
 ('round_one', '0^inf A> (01)^m+2 00110 (01)^a 1 R', '0^inf A> (01)^m+1 00110 (01)^a+2 0 R', 'Cursor 1 behind one separator: m | a "1" -> m-1 | a+2 "0".'),
 ('round_zero', '0^inf A> (01)^m+2 00110 (01)^a 0 (01)^b+2 R', '0^inf A> (01)^m+1 00110 (01)^a+4 1 (01)^b R', 'Cursor 0 behind one separator: m | a "0" b -> m-1 | a+4 "1" b-2.'),
 ('first_one', '0^inf A> (01)^m 1 R', '0^inf A> (01)^m+1 0 R', 'Cursor 1 in the first run: m "1" -> m+1 "0".'),
 ('first_zero', '0^inf A> (01)^m+1 0 (01)^b+2 R', '0^inf A> (01)^m+4 1 (01)^b R', 'Cursor 0 in the first run: m "0" b -> m+3 "1" b-2.'),
 ('zero_sep', '0^inf A> (01)^m+1 0 01 00110 R', '0^inf A> (01)^m+5 10 R', 'Cursor 0 one pair before a separator: m "0" 1 | -> m+4 "10".'),
 ('onezero', '0^inf A> (01)^m+1 10 01 R', '0^inf A> (01)^m+2 00 01 R', 'Cursor 10 -> 00.'),
 ('zerozero', '0^inf A> (01)^m+2 00 01 R', '0^inf A> (01)^m+1 00110 01 1 R', 'Cursor 00 becomes a separator and a cursor 1 one pair behind it.'),
 ('zero_at_sep', '0^inf A> (01)^m+2 0 00110 R', '0^inf A> (01)^m+1 00110 01 110 R', 'Cursor 0 right before a separator crosses it.'),
 ('annihilate', '0^inf A> (01)^m+2 00110 (01)^a 11 (01)^b 00110 R', '0^inf A> (01)^m+1 00110 (01)^a+b+3 00110 R', 'Two cursors 1 next to each other vanish.'),
]
out = {}
for nm, s, e, doc in rules:
    try:
        t, f = prove(M, nm, s, e, rotate=True, doc=doc)
        print(nm, 'OK', f.steps)
        out[nm] = t
    except Exception as ex:
        print(nm, 'ERR', ex)
HEAD = '''import Machine

/-!
# The macro rules of 1RB0LC_1RC0RA_1LA0LD_1LE0RB_1RB1LF_0LA---

Generated by `py/rules.py` (`tools/py/bbtools/symtm.py`); do not edit by hand.

`R1`, `R2`, `L1` ... `L8` are the machine seen only when it is in state A: from every configuration in state A
exactly one of them applies (A reads 0: `R1` or `R2`; A reads 1: the cells on its left decide), and `L4` is the only
one that halts.  The `pass_*`, `back_*` and round theorems follow from them and describe the runs of `01`, the
separators `00110` and the cursors of the README.
-/

namespace H37843

open TM

'''
TAIL = '''

/-- The only way to halt: state A reading 1 with `1101` on its left. -/
theorem bad_halts (L R : Tape) :
    Halts trans ⟨cons true (cons false (cons true (cons true L))), cons true R, .A⟩ :=
  ⟨4, _, L4 L R, rfl⟩

end H37843
'''
if len(sys.argv) > 1:
    open(sys.argv[1], 'w').write(HEAD + '\n\n'.join(out[n] for n, _, _, _ in rules) + TAIL)
