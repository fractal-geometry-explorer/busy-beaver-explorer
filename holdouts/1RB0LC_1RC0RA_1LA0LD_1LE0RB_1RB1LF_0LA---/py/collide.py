"""Collisions of two cursors of 1RB0LC_1RC0RA_1LA0LD_1LE0RB_1RB1LF_0LA---, proved with symtm.  Writes
lean/Collide.lean when given a path.

The rounds in which the moving cursor reaches another one, in the notation of the README (m = first run, | = 00110,
runs of 01 as numbers, other cells in quotes):

    merge_zero   m+2 | a "0" 2 "0" R       ->  m+1 | a+4 "10" R              (two cursors 0 merge)
    zero_one     m+2 | a+2 "0" 1 "1" b+1   ->  m+1 | a+2 | 2 "0" b           (a new separator is born)
    one_one      m+2 | a "1" 1 "1" R       ->  m+1 | a+2 "0" 1 "1" R         (the cursor 1 one pair behind a 1)

and a tape of the same form that halts: a cursor 0 one pair before the word 1110 and a separator,

    collide_halt   m+2 | a+2 "0" 1 "1110" |     halts in its first round (2a + 2m + 127 steps, then F reads 1).

The machine's own run never shows the word 1110 at an event (py/scan.py), so this halt is not reached that way; it
shows that the halting question is a question about which collisions occur.
"""
import sys
import os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../../tools/py'))
from bbtools.symtm import prove
M = '1RB0LC_1RC0RA_1LA0LD_1LE0RB_1RB1LF_0LA---'
rules = [
 ('merge_zero', '0^inf A> (01)^m+2 00110 (01)^a 0 (01)^2 0 R', '0^inf A> (01)^m+1 00110 (01)^a+4 10 R',
  'Two cursors 0 two pairs apart merge: m+2 | a "0" 2 "0" R -> m+1 | a+4 "10" R.'),
 ('zero_one', '0^inf A> (01)^m+2 00110 (01)^a+2 0 01 1 (01)^b+1 R',
  '0^inf A> (01)^m+1 00110 (01)^a+2 00110 (01)^2 0 (01)^b R',
  'A cursor 0 one pair behind a cursor 1: m+2 | a+2 "0" 1 "1" b+1 R -> m+1 | a+2 | 2 "0" b R (a new separator).'),
 ('one_one', '0^inf A> (01)^m+2 00110 (01)^a 1 01 1 R', '0^inf A> (01)^m+1 00110 (01)^a+2 0 01 1 R',
  'A cursor 1 one pair behind a cursor 1: m+2 | a "1" 1 "1" R -> m+1 | a+2 "0" 1 "1" R.'),
 ('collide_halt', '0^inf A> (01)^m+2 00110 (01)^a+2 0 01 1110 00110 0^inf',
  '0^inf (10)^m+2 1 1 0 1 (01)^a+2 0 F> 1 1 1 0 0 0 1 1 0 0 1 0 0 1 1 0 0 1 0^inf',
  'A cursor 0 one pair before the word 1110 and a separator: the first round reaches state F reading 1.'),
]
out = {}
for nm, s, e, doc in rules:
    t, f = prove(M, nm, s, e, rotate=True, doc=doc, max_seg=40)
    print(nm, 'OK', f.steps)
    out[nm] = t
HEAD = '''import Rules

/-!
# Collisions of two cursors of 1RB0LC_1RC0RA_1LA0LD_1LE0RB_1RB1LF_0LA---

Generated by `py/collide.py` (`tools/py/bbtools/symtm.py`); do not edit by hand.

Rounds in which the moving cursor reaches a second cursor (`merge_zero`, `zero_one`, `one_one`; `annihilate` is in
`Rules.lean`), and `collide_halts`: a tape of the machine's own form, a first run, a separator, a run, a cursor `0`,
one pair, the word `1110` and a separator, halts in its first round, for every length of the two runs.  So the
halting question is which collisions the run from blank tape produces.
-/

namespace H37843

open TM

'''
TAIL = '''

/-- Two cursors that halt: `m+2 | a+2 "0" 1 "1110" |` halts, for all `m` and `a`. -/
theorem collide_halts (a m : Nat) :
    Halts trans ⟨blank, rep (m + 2) [false, true] (cons false (cons false (cons true (cons true (cons false
      (rep (a + 2) [false, true] (cons false (cons false (cons true (cons true (cons true (cons true (cons false
      (cons false (cons false (cons true (cons true (cons false blank)))))))))))))))))), .A⟩ :=
  ⟨_, _, collide_halt a m, rfl⟩

end H37843
'''
if len(sys.argv) > 1:
    open(sys.argv[1], 'w').write(HEAD + '\n\n'.join(out[n] for n, _, _, _ in rules) + TAIL)
