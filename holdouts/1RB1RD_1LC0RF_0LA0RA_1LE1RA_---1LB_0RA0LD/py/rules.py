"""Generate lean/Rules.lean: rules of 1RB1RD_1LC0RF_0LA0RA_1LE1RA_---1LB_0RA0LD, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB1RD_1LC0RF_0LA0RA_1LE1RA_---1LB_0RA0LD)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RD_1LC0RF_0LA0RA_1LE1RA_---1LB_0RA0LD"

RULES = [
    ('a_r_0101111', 'L A> (0101111)^n R', 'L (1001111)^n A> R',
     'A sweeps right over copies of `0101111` (7 steps a copy).'),
    ('d_r_1010111', 'L D> (1010111)^n R', 'L (1100111)^n D> R',
     'D sweeps right over copies of `1010111` (7 steps a copy).'),
    ('d_r_1110101', 'L D> (1110101)^n R', 'L (1111001)^n D> R',
     'D sweeps right over copies of `1110101` (7 steps a copy).'),
    ('f_r_0111101', 'L F> (0111101)^n R', 'L (0111110)^n F> R',
     'F sweeps right over copies of `0111101` (7 steps a copy).'),
    ('b_r_1011110', 'L B> (1011110)^n R', 'L (0011111)^n B> R',
     'B sweeps right over copies of `1011110` (7 steps a copy).'),
    ('a_r_1101011', 'L A> (1101011)^n R', 'L (1110011)^n A> R',
     'A sweeps right over copies of `1101011` (7 steps a copy).'),
    ('a_r_1111010', 'L A> (1111010)^n R', 'L (1111100)^n A> R',
     'A sweeps right over copies of `1111010` (7 steps a copy).'),
    ('a_r_0011111', 'L A> (0011111)^n R', 'L (0111111)^n A> R',
     'A sweeps right over copies of `0011111` (9 steps a copy).')
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H175040", thms,
                                "Rules of 1RB1RD_1LC0RF_0LA0RA_1LE1RA_---1LB_0RA0LD, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
