"""The pair machine of 1RB1RE_1RC0LD_1LB---_1RA1LD_1RA0RF_1RE0LC.

Read two cells at a time, the tape is a word over four symbols

    0 = 01    1 = 11    a = 10    b = 00   (b is also the blank pair)

and the head is either `X>` (state X on the first cell of the pair to its right) or `<X` (state X on the second cell
of the pair to its left).  From either position the machine stays inside that pair for at most 3 steps and leaves it
on one side, so every (position, state, pair) has one macro move; `table()` computes them from the machine.

After the start-up (the first few hundred visits of the right end) only these occur (counted over 3*10^7 rounds by
`c/psim.c`), and they are the whole machine from then on:

    1 <D  ->  <D 1          0 <D  ->  1 E>
    E> a  ->  0 E>          E> 0  ->  1 E>          E> 1  ->  <B a          E> b  ->  1 B>
    1 <B  ->  <D a          0 <B  ->  1 B>
    B> 1  ->  <D 0          B> a  ->  <D b          B> b  ->  <D 0          B> 0  ->  halt

usage:
    python3 pairs.py table            the macro moves (also the C table of c/tab.h with `ctable`)
    python3 pairs.py check [steps]    the pair machine against the plain machine at every round (default 3*10^6 steps)
    python3 pairs.py lean > ../lean/Pairs.lean
"""
import sys

M = "1RB1RE_1RC0LD_1LB---_1RA1LD_1RA0RF_1RE0LC"
NS = "H151599"
SY = ["01", "11", "10", "00"]
NAME = "01ab"


def machine():
    T = {}
    for i, r in enumerate(M.split("_")):
        for b in (0, 1):
            t = r[3 * b:3 * b + 3]
            T[(i, b)] = None if t[0] == "-" else (int(t[0]), 1 if t[1] == "R" else -1, ord(t[2]) - 65)
    return T


def runpair(T, s, pair, pos):
    """State s on cell `pos` of the pair: (new pair, side it leaves on (1 right), new state, steps), None on a halt."""
    c = [int(pair[0]), int(pair[1])]
    n = 0
    while 0 <= pos <= 1:
        t = T[(s, c[pos])]
        if t is None:
            return None
        c[pos] = t[0]
        pos += t[1]
        s = t[2]
        n += 1
        assert n < 100
    return (SY.index("%d%d" % tuple(c)), 1 if pos == 2 else 0, s, n)


def table():
    T = machine()
    RR = [[runpair(T, s, SY[x], 0) for x in range(4)] for s in range(6)]
    LL = [[runpair(T, s, SY[x], 1) for x in range(4)] for s in range(6)]
    return RR, LL


def ctable():
    RR, LL = table()
    out = ["/* generated by py/pairs.py for %s: sym 0='01' 1='11' 2='10' 3='00'; {pair, side, state, steps} */" % M]
    for name, t in (("RR", RR), ("LL", LL)):
        out.append("static const int %s[6][4][4]={" % name)
        for s in range(6):
            out.append(" {" + ",".join("{-1,0,0,0}" if r is None else "{%d,%d,%d,%d}" % r for r in t[s]) + "},")
        out.append("};")
    return "\n".join(out) + "\n"


def pair_run(L, R, d, s, tables, nmax, stop):
    """Run the pair machine: L, R lists of symbols (nearest the head last), d 1 for X>, 0 for <X."""
    RR, LL = tables
    steps = 0
    for _ in range(nmax):
        if d:
            x = R.pop() if R else 3
            t = RR[s][x]
        else:
            x = L.pop() if L else 3
            t = LL[s][x]
        if t is None:
            return "halt", steps
        (L if t[1] else R).append(t[0])
        d, s = t[1], t[2]
        steps += t[3]
        if stop(L, R, d, s):
            return (L, R, d, s), steps
    return None, steps


def rounds(nsteps):
    """Plain machine: (step, k, region as pairs) at every visit of a new cell on the right in state E."""
    T = machine()
    tape = {}
    p = s = mx = 0
    for st in range(nsteps):
        if p > mx:
            mx = p
            if s == 4:
                lo = min(tape)
                x = "".join(str(tape.get(i, 0)) for i in range(lo, mx))
                if len(x) % 2:
                    x = "0" + x
                bits = "".join(NAME[SY.index(x[i:i + 2])] for i in range(0, len(x), 2))
                yield st, bits
        w, d, ns = T[(s, tape.get(p, 0))]
        tape[p] = w
        p += d
        s = ns


def check(nsteps):
    tabs = table()
    rs = list(rounds(nsteps))
    ok = 0
    for i in range(len(rs) - 1):
        st, w = rs[i]
        st2, w2 = rs[i + 1]
        L = [NAME.index(c) for c in w]
        res, n = pair_run(L, [], 1, 4, tabs, 10 ** 9, lambda L, R, d, s: d == 1 and s == 4 and not R)
        got = "".join(NAME[c] for c in res[0]).lstrip("b")
        assert got == w2.lstrip("b") and n == st2 - st, (i, st)
        ok += 1
    print("pair machine = plain machine on %d rounds (tapes and step counts), to step %d" % (ok, rs[-1][0]))


def lean():
    RR, LL = table()
    cell = lambda c: "true" if c == "1" else "false"
    out = ["import Machine", "",
           "/-! The pair machine of %s: every macro move on a pair of cells (0 = 01, 1 = 11, a = 10, b = 00), for every"
           % M,
           "tape around it. `r_X_s`: state X on the first cell of the pair s to its right; `l_X_s`: state X on the second",
           "cell of the pair s to its left. Written by `py/pairs.py`; each is checked by the kernel by running the steps. -/",
           "", "namespace %s" % NS, "", "open TM", ""]
    for form, t in (("r", RR), ("l", LL)):
        for s in range(6):
            for x in range(4):
                r = t[s][x]
                if r is None:
                    continue
                w, side, g, n = r
                p, q = SY[x], SY[w]
                st, gt = ".%s" % "ABCDEF"[s], ".%s" % "ABCDEF"[g]
                nm = "%s_%s_%s" % (form, "ABCDEF"[s], NAME[x])
                if form == "r":
                    start = "⟨%s, cons %s (cons %s R), %s⟩" % ("L" if side else "cons y L", cell(p[0]), cell(p[1]), st)
                    if side:
                        end = "⟨cons %s (cons %s L), R, %s⟩" % (cell(q[1]), cell(q[0]), gt)
                        args = "(L R : Tape)"
                    else:
                        end = "⟨L, cons y (cons %s (cons %s R)), %s⟩" % (cell(q[0]), cell(q[1]), gt)
                        args = "(y : Bool) (L R : Tape)"
                else:
                    if side:
                        start = "⟨cons %s L, cons %s R, %s⟩" % (cell(p[0]), cell(p[1]), st)
                        end = "⟨cons %s (cons %s L), R, %s⟩" % (cell(q[1]), cell(q[0]), gt)
                        args = "(L R : Tape)"
                    else:
                        start = "⟨cons %s (cons y L), cons %s R, %s⟩" % (cell(p[0]), cell(p[1]), st)
                        end = "⟨L, cons y (cons %s (cons %s R)), %s⟩" % (cell(q[0]), cell(q[1]), gt)
                        args = "(y : Bool) (L R : Tape)"
                out.append("theorem %s %s :\n    steps %d %s = some %s := rfl\n" % (nm, args, n, start, end))
    out.append("end %s" % NS)
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "table"
    if cmd == "table":
        RR, LL = table()
        for form, t in (("X>", RR), ("<X", LL)):
            for s in range(6):
                for x in range(4):
                    r = t[s][x]
                    a = ("%s> %s" % ("ABCDEF"[s], NAME[x])) if form == "X>" else ("%s <%s" % (NAME[x], "ABCDEF"[s]))
                    if r is None:
                        print("%-6s -> halt" % a)
                    else:
                        b = ("%s %s>" % (NAME[r[0]], "ABCDEF"[r[2]])) if r[1] else ("<%s %s" % ("ABCDEF"[r[2]], NAME[r[0]]))
                        print("%-6s -> %-6s (%d steps)" % (a, b, r[3]))
    elif cmd == "ctable":
        print(ctable(), end="")
    elif cmd == "check":
        check(int(float(sys.argv[2])) if len(sys.argv) > 2 else 3000000)
    elif cmd == "lean":
        print(lean(), end="")
