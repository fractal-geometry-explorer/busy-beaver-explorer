"""Generate Rules.lean: shift rules of 1RB0RE_1LC0RA_0LD0LB_1RE0LB_1RF---_0RB0RC, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape, `0^inf` is blank tape.  See README.md for where each rule is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC0RA_0LD0LB_1RE0LB_1RF---_0RB0RC"

RULES = [
    ('wall_right', 'L 0 B> (10)^n 0 R', 'L 0 (01)^n B> 0 R', {},
     'State B runs right across a stretch of `10`s, leaving them shifted by one cell.'),
    ('ones_left', 'L 1 (10)^n C> 1 R', 'L 1 C> 1 (10)^n R', {},
     'State C runs left across a stretch of `10`s unchanged.'),
    ('fill', 'L 0 F> (10)^n 0 R', 'L 0 (11)^n F> 0 R', {},
     'State F runs right across `10`s, filling them to `11`.'),
    ('sweep', 'L 1 1 1 1 (10)^b+2 0 1 0 0 (10)^c+1 A> 0^inf', 'L (10)^b+4 0 1 0 0 (10)^c+2 A> 0^inf', {'rotate': True},
     'One sweep of the active segment: four ones are eaten, the wall before `0 1 0 0` gains two `10`, the end gains one; any tape to the left.'),
    ('sweep_p', 'L 1 1 (10)^b+1 A> 0^inf', 'L (10)^b+3 A> 0^inf', {'rotate': True},
     'One sweep when the active segment ends the tape (no `0 1 0 0` after it): two ones are eaten, its `10` block gains two; any tape to the left.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, **kw)[0] for name, a, b, kw, doc in RULES]
    out = rules_file("Machine", "H98520", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    # the chain of steps in `sweep` needs more than the default heartbeats to elaborate
    out = out.replace("namespace H98520", "set_option maxHeartbeats 3000000\n\nnamespace H98520", 1)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
