"""Writes lean/Sweep.lean: whole long sweeps over lists of blocks of any length, proved with bbtools.seqtm."""
import sys
import os
sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),'../../../tools/py'))
from bbtools import seqtm, symtm
from bbtools.symtm import Blank
from bbtools.machine import Machine
M=Machine.parse('1RB0LF_0LC0RE_0RA1LD_1LB0LD_0RA1RC_1LA---')
def stop(c):
    return (not c.steps.is_zero()) and c.state==1 and len(c.left)==1 and isinstance(c.left[0],Blank)
F=[('carry_even',
   '0^inf B> 0 (1010)^a+2 1 10 1 [ (1010)^t+4 1 ]^ts 10 (1010)^b+4 0 R',
   'A long sweep: the counter carries through any list of even 1-digit blocks (10)^(2t+8) 1 and stops at an odd 0-digit block (10)^(2b+9) 0.')]
out=[]
for name,s,doc in F:
    txt,fin,parts=seqtm.prove(M,name,seqtm.parse(s),stop,doc=doc)
    print(name,fin,file=sys.stderr)
    out.append(txt)
open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'../lean/Sweep.lean'),'w').write(symtm.rules_file('Seq','H129771',out,'Long sweeps over lists of blocks (generated by py/gen_sweep.py with bbtools.seqtm).'))
