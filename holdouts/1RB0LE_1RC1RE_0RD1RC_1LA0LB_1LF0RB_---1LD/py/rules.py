"""Writes lean/Rules.lean: shift rules of this machine's sweeps and the shape of a halt, proved by
tools/py/bbtools/symtm.py (`prove`).  Usage: python3 py/rules.py > lean/Rules.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LE_1RC1RE_0RD1RC_1LA0LB_1LF0RB_---1LD"
NS = "H45924"
RULES = [
    ('blank_to_8', '0^inf A> 0^inf', '0^inf F> 1^8 0^inf',
     'From blank tape, 43 steps reach F at the left end of eight 1s: the first sample.', {}),
    ('e_halve', 'L E> (11)^n R', 'L (01)^n E> R',
     'The first sweep of a phase: rightward, E (through B) turns each pair 11 into 01, 2 steps a pair.', {}),
    ('e_triple', 'L E> (111011101110)^n R', 'L (010111111111)^n E> R',
     'A merging sweep: rightward, E turns every three blocks 1110 1110 1110 into 0101 1111 1111 (20 steps a copy); later sweeps make blocks 1^11 0 out of them, three blocks into one.', {}),
    ('d_triple', 'L 0 D> (111011101110)^n R', 'L (111110101111)^n 0 D> R',
     'The same merging sweep seen from D (with a 0 behind it).', {}),
    ('halt_shape', 'L 0 0 1 D> 0 R', 'L F> 0 1 0 1 R',
     'The only way to a halt: D on a 0 with 1 0 0 to its left reaches F on a 0 (which halts) in 3 steps.', {}),
]
HALT = "F"
HSYM = "0"

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d, **kw)[0] for n, s, e, d, kw in RULES]
    extra = (f"/-- {HALT} reading a {HSYM} halts (the end of `halt_shape`). -/\n"
             f"theorem halt_after_shape (L R : Tape) : step ⟨L, cons false R, .{HALT}⟩ = none := rfl\n")
    print(rules_file("Machine", NS, thms + [extra],
                     f"# {M}: shift rules of the sweeps and the shape of a halt\n\n"
                     "Generated by `py/rules.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `n` and all "
                     "tapes `L`, `R`."))
