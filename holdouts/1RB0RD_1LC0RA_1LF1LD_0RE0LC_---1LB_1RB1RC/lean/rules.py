"""Generate Rules.lean: the wall round trip of 1RB0RD_1LC0RA_1LF1LD_0RE0LC_---1LB_1RB1RC and pieces of the counter
update, proved along the symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by
`TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`, L and R
are any tape, `0^inf` is blank tape.  The counter is the stretch right of the wall: cells `x0 1 x1 1 x2 1 ...`, a
digit on every even cell and a 1 on every odd one, with x0 = 1 (README.md, "The counter").
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RD_1LC0RA_1LF1LD_0RE0LC_---1LB_1RB1RC"

RULES = [
    ("wall_right", "L A> (01)^n R", "L (10)^n A> R", {},
     "State A runs right across the wall, turning each `01` into `10`."),
    ("wall_left", "L (10)^n D> 1 R", "L D> 1 (10)^n R", {},
     "States D, C, F run left across the wall, four steps per `10`."),
    ("left_end", "0^inf D> 1 (10)^n R", "0^inf 1 0 A> 0 (10)^n R", {},
     "At the blank end the wall gains one `10` and A turns back."),
    ("round", "0^inf (10)^n D> 1 R", "0^inf 1 0 (10)^n A> 0 R", {"rotate": True},
     "The whole round trip: from D leaving the counter to A arriving back, 6n + 4 steps, one more `10` in the wall."),
    ("toggle", "L 1 0 A> 1 1 0 1 R", "L D> 1 1 1 1 1 1 R", {},
     "The counter update when x1 = 0: x1 becomes 1 and D leaves (the last `10` of the wall is restored on the way)."),
    ("sweep_toggle", "0^inf (10)^n 1 0 A> 1 1 0 1 R", "0^inf 1 0 (10)^n 1 0 A> 1 1 1 1 R", {"rotate": True},
     "A whole sweep when x1 = 0: x1 is set, the wall grows by one `10`, and A is back at x0."),
    ("zig", "L 1 0 0 D> (111)^n R", "L (110)^n 1 0 0 D> R", {},
     "The carry's zigzag over a stretch of ones (digits 1 and their separators): 7 steps per three cells."),
    # one sweep, digit by digit (lean/Sweep.lean chains them): the forward zigzag of the carry, three head states
    # a = B, b = D, c = A with the previous pair still pending (`0 1`, `0 0`, `1 0`), then the pass back in C
    ("fwd_a1", "L B> 1 1 R", "L 0 0 D> R", {}, "Carry in state a reads digit 1: writes 0, goes on in b."),
    ("fwd_b0", "L 0 0 D> 0 1 R", "L 1 1 0 1 B> R", {}, "Carry in state b reads digit 0: writes 1, goes on in a."),
    ("fwd_b1", "L 0 0 D> 1 1 R", "L 1 0 1 0 A> R", {}, "Carry in state b reads digit 1: writes 0, goes on in c."),
    ("fwd_c1", "L 1 0 A> 1 1 R", "L 1 1 0 1 B> R", {}, "Carry in state c reads digit 1: writes 1, goes on in a."),
    ("fwd_c0", "L A> 0 1 R", "L 1 0 A> R", {}, "Carry in state c reads digit 0: keeps it, stays in c."),
    ("stop0", "L 0 0 1 B> 0 1 R", "L C> 0 1 1 1 1 R", {}, "Carry in state a reads digit 0: writes 1 and turns back (previous separator 0)."),
    ("stop1", "L 1 0 1 B> 0 1 R", "L C> 1 1 1 1 1 R", {}, "The same with previous separator 1."),
    ("back_11_0", "L 0 1 C> 1 R", "L C> 0 0 1 R", {}, "Pass back over a pending pair `1 1`: digit 0."),
    ("back_11_1", "L 1 1 C> 1 R", "L C> 1 0 1 R", {}, "The same, previous separator 1."),
    ("back_01_0", "L 0 0 C> 1 R", "L C> 0 1 1 R", {}, "Pass back over a pending pair `0 1`: digit 1."),
    ("back_01_1", "L 1 0 C> 1 R", "L C> 1 1 1 R", {}, "The same, previous separator 1."),
    ("back_10_0", "L 0 1 C> 0 R", "L C> 0 0 1 R", {}, "Pass back over a pending pair `1 0`: digit 0."),
    ("back_10_1", "L 1 1 C> 0 R", "L C> 1 0 1 R", {}, "The same, previous separator 1."),
    ("back_end", "0^inf (10)^n 1 C> 1 1 1 R", "0^inf (10)^n+2 A> 1 1 R", {"rotate": True},
     "The pass back reaches the wall: across it, one more pair at the blank end, and A arrives at x0."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, **kw)[0] for name, a, b, kw, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H74982", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
