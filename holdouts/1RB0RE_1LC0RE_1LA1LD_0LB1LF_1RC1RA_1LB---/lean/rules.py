"""Generate Rules.lean: shift rules of 1RB0RE_1LC0RE_1LA1LD_0LB1LF_1RC1RA_1LB---, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(10)^n` is n
copies of `10`, `0^inf` is blank tape, L and R are any tape.  What the rules mean is in ../README.md.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC0RE_1LA1LD_0LB1LF_1RC1RA_1LB---"

RULES = [
    ('f_left', 'L 1 (1010)^n F> 0 1 R', 'L 1 F> 0 (1111)^n 1 R',
     'Going left, F (with D, B, C) turns each `1010` into `1111`, eight steps per word: copies of `10` become ones.'),
    ('e_right', 'L 0 E> (1111)^n 1 R', 'L 0 (1010)^n E> 1 R',
     'Going right, E and A turn each `1111` back into `1010`, four steps per word.'),
    ('a_right', 'L 0 A> (11)^n 0 R', 'L 0 (01)^n 1 B> R',
     'A runs right over a block of 2n ones, turning it into `(01)^n`; at the 0 after it B turns back.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=30)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H59536", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
