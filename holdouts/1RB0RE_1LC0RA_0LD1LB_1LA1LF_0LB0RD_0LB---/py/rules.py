"""Generate ../lean/Rules.lean: the shift and macro rules of 1RB0RE_1LC0RA_0LD1LB_1LA1LF_0LB0RD_0LB---, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC0RA_0LD1LB_1LA1LF_0LB0RD_0LB---"

RULES = [
    ('a_right', 'L A> (01)^n R', 'L (10)^n A> R',
     'A runs right over (01)^n.'),
    ('b_right', 'L B> (10)^n R', 'L (01)^n B> R',
     'B runs right over (10)^n.'),
    ('b_left', 'L (01)^n B> 0 R', 'L B> 0 (11)^n R',
     'B runs left over (01)^n, filling it with 1s.'),
    ('c_left', 'L (10)^n C> 1 R', 'L C> 1 (11)^n R',
     'C runs left over (10)^n, filling it with 1s.'),
    ('v_b1', 'L (00100101)^n B> 0 R', 'L B> 0 (01011111)^n R',
     'Leftward, B turns rotations of v = 10100100 into rotations of u = 11111010.'),
    ('v_c1', 'L (00101001)^n C> 0 R', 'L C> 0 (11111010)^n R',
     'Leftward, C turns v into u.'),
    ('v_b2', 'L (01001001)^n B> 0 R', 'L B> 0 (11010111)^n R',
     'Leftward, B turns v into u.'),
    ('v_f', 'L (01001010)^n F> 0 R', 'L F> 0 (10111110)^n R',
     'Leftward, F turns v into u.'),
    ('v_b3', 'L (01010010)^n B> 0 R', 'L B> 0 (11110101)^n R',
     'Leftward, B turns v into u.'),
    ('v_c2', 'L (10010010)^n C> 1 R', 'L C> 1 (10101111)^n R',
     'Leftward, C turns v into u.'),
    ('v_d', 'L (10010100)^n D> 1 R', 'L D> 1 (01111101)^n R',
     'Leftward, D turns v into u.'),
    ('v_c3', 'L (10100100)^n C> 1 R', 'L C> 1 (11101011)^n R',
     'Leftward, C turns v into u.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=20)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H71717", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
