"""Generate lean/Rules.lean for 1RB0RF_1RC0LE_1LD0LC_1RE0RD_1LB0RA_1RC---: the shift rules of its sweeps, proved along symbolic runs
(tools/py/bbtools/symtm.py: single steps by `rfl`, a whole repeat crossed by `TM.cross_r` / `TM.cross_l`).

usage (from the repository root): python3 holdouts/1RB0RF_1RC0LE_1LD0LC_1RE0RD_1LB0RA_1RC---/py/rules.py > holdouts/1RB0RF_1RC0LE_1LD0LC_1RE0RD_1LB0RA_1RC---/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape.  Each rule holds for every n and every tape around it; README.md says where each one is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402

symtm.MAX_CARRY = 8  # some sweeps carry a word of up to 6 cells along with the head

M = "1RB0RF_1RC0LE_1LD0LC_1RE0RD_1LB0RA_1RC---"
NS = "H112382"

RULES = [
    ("l_sea", "L (10)^n C> 10 R", "L C> 10 (01)^n R",
     "Leftward sweep over the sea: C carries 10 and turns each 10 into 01."),
    ("l_101", "L (101)^n C> 1 R", "L C> 1 (001)^n R",
     "Leftward: C turns each 101 into 001."),
    ("r_word", "L D> (010101)^n R", "L (110100)^n D> R",
     "Rightward: D turns each 010101 into 110100."),
    ("l_word", "L (1011010)^n B> 01 R", "L B> 01 (0100101)^n R",
     "Leftward: B, carrying 01, turns each 1011010 into 0100101."),
]


def main():
    ths = [symtm.prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(symtm.rules_file("Machine", NS, ths, f"Sweep rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
