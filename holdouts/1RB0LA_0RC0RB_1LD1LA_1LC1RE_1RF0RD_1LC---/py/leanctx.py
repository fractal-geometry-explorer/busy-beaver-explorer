"""Writes lean/Ctx.lean: for each context c of py/contexts.txt (the contexts the orbit from blank tape uses) the two
rewrites of c by the machine, proved by `bbtools.symtm` for every block length m of the given parity:

    b = 0:  0^inf c   C> 1^(2j+2)   ->  0^inf c0' E> 1^(2j+2+a0)
    b = 1:  0^inf c 1 C> 1^(2j+5)   ->  0^inf c1' E> 1^(2j+5+a1)

(with c', a read from the measured rules, py/rules.json; symtm fails if they are wrong), each restated with the
definitions of lean/Pass.lean (`ctx_<k>_<b>`), and the table `tbl` of all of them with its soundness `tbl_sound`.
usage: python3 leanctx.py > ../lean/Ctx.lean"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
sys.path.insert(0, HERE)
from bbtools.symtm import prove, Rep, Blank, right_term, run, Config, Machine, Halted  # noqa: E402
import emap  # noqa: E402

M = emap.M


def contexts():
    return [l.split()[0] for l in open(os.path.join(HERE, "contexts.txt")) if l.strip() and l[0] != "#"]


def lb(w):
    return "[" + ", ".join("true" if ch == "1" else "false" for ch in w) + "]"


def ones_conv(right):
    """symtm's right tokens 1^p (11)^e 1^q blank -> (Lean term with ones q inside, total expression)"""
    toks = list(right)
    assert isinstance(toks[-1], Blank), toks
    toks = toks[:-1]
    reps = [i for i, t in enumerate(toks) if isinstance(t, Rep)]
    assert len(reps) == 1 and toks[reps[0]].word == (1, 1), toks
    i = reps[0]
    p, q = toks[:i], toks[i + 1:]
    assert all(t == 1 for t in p + q), toks
    e = toks[i].n.lean()
    inner = f"rep ({e}) [true, true] (ones {len(q)})"
    term = inner
    for _ in p:
        term = f"cons true ({term})"
    return term, f"2 * ({e}) + {len(q)} + {len(p)}"


def entry(k, c, b):
    """Lean text for context number k and bit b, and (c', a) or None for a halt"""
    r = 0 if b == 0 else 2
    rr = emap.rule(c, r)
    if rr[0] == "HALT":
        return None, None
    c2, d = rr[:2]
    a = (d - 4) // 2
    if b == 0:
        s = f"0^inf {' '.join(c)} C> (11)^j+1 0^inf"
        N = 2 + a
    else:
        s = f"0^inf {' '.join(c + '1')} C> 1 (11)^j+2 0^inf"
        N = 5 + a
    e = f"0^inf {' '.join(c2)} E> {'1 ' if N % 2 else ''}(11)^j+{N // 2} 0^inf"
    name = f"p_{k}_{b}"
    t, fin = prove(M, name, s, e, doc=f"Context `{c}`, b = {b}: `{s}` to `{e}`.", rotate=True, count_first=True,
                   max_seg=40)
    term, tot = ones_conv(fin.right)
    lhs_m = "2 * j + 2" if b == 0 else "2 * j + 5"
    left0 = f"app ({lb(c)}).reverse blank" if b == 0 else f"cons true (app ({lb(c)}).reverse blank)"
    rstart = "tt_ones' j" if b == 0 else "tt_ones_odd j"
    w = []
    w.append(t)
    w.append("")
    w.append(f"theorem ctx_{k}_{b} (j : Nat) : Reaches (Cn ({left0}) ({lhs_m})) (Ev {lb(c2)} ({lhs_m} + {a})) 0 := by")
    w.append(f"  have h := {name} j")
    w.append(f"  have e : {right_term(fin.right)} = ones ({tot}) := by")
    w.append(f"    show {term} = _")
    w.append(f"    rw [rep_tt_ones]; rfl")
    w.append(f"  rw [e, {rstart}] at h")
    w.append(f"  rw [show {lhs_m} + {a} = {tot} by omega]")
    w.append(f"  exact ⟨_, Nat.zero_le _, h⟩")
    return "\n".join(w), (c2, a)


# the halting rules that carry the halting rate of the Markov model (py/markov.py): context, bit
HALTS = [("11111", 1), ("1111011", 1)]


def halt_entry(c, b):
    """Lean text: from `0^inf c 1 C> 1^(2j+5)` (b = 1) the machine reaches a halting configuration"""
    assert b == 1
    s = f"0^inf {' '.join(c + '1')} C> 1 (11)^j+2 0^inf"
    tr = []
    try:
        run(Machine.parse(M), Config.parse(s), lambda x: False, max_moves=100000, trace=tr, rotate=True)
        raise AssertionError("no halt")
    except Halted:
        pass
    fin = tr[-1][2]
    name = f"h_{c}_{b}"
    t, _ = prove(M, name, s, repr(fin), doc=f"Context `{c}`, b = {b}: `{s}` reaches `{fin}`, F reading 1.",
                 rotate=True, count_first=True, max_seg=40)
    w = [t, "",
         f"theorem halt_{c}_{b} (j : Nat) : Halts trans (Cn (cons true (app ({lb(c)}).reverse blank)) (2 * j + 5)) := by",
         f"  have h := {name} j",
         f"  rw [tt_ones_odd j] at h",
         f"  exact ⟨_, _, h, rfl⟩"]
    return "\n".join(w)


if __name__ == "__main__":
    cs = contexts()
    out = ["import Pass", "",
           "/-! The rewrites of the contexts the orbit from blank tape uses, generated by `py/leanctx.py` with "
           "`bbtools.symtm`; do not edit by hand. -/", "", "namespace H121010", "", "open TM", ""]
    tbl = []
    oks = []
    for k, c in enumerate(cs):
        res = []
        for b in (0, 1):
            txt, r = entry(k, c, b)
            if txt:
                out.append(txt)
                out.append("")
            res.append(r)
        e0 = f"some ({lb(res[0][0])}, {res[0][1]})" if res[0] else "none"
        e1 = f"some ({lb(res[1][0])}, {res[1][1]})" if res[1] else "none"
        tbl.append(f"({lb(c)}, {e0}, {e1})")
        p0 = f"fun c' a h j => by cases h; exact ctx_{k}_0 j" if res[0] else "fun _ _ h => by cases h"
        p1 = f"fun c' a h j => by cases h; exact ctx_{k}_1 j" if res[1] else "fun _ _ h => by cases h"
        oks.append(f"theorem ok_{k} : EntryOK {tbl[-1]} := ⟨{p0}, {p1}⟩")
        print(f"context {k} {c}: {res}", file=sys.stderr)
    out.append("/-- The table: context, then (next context, added length) for b = 0 and b = 1 (`none`: halt). -/")
    out.append("def tbl : List (List Bool × Option (List Bool × Nat) × Option (List Bool × Nat)) := [")
    out.append(",\n".join("  " + t for t in tbl) + "]")
    out.append("")
    out += oks
    out.append("")
    out.append("theorem tbl_sound : ∀ e ∈ tbl, EntryOK e := by")
    out.append("  intro e he")
    out.append("  simp only [tbl, List.mem_cons, List.not_mem_nil, or_false] at he")
    out.append("  rcases he with " + " | ".join("rfl" for _ in tbl))
    out.append("  " + "\n  ".join(f"· exact ok_{k}" for k in range(len(tbl))))
    out.append("")
    for c, b in HALTS:
        out.append(halt_entry(c, b))
        out.append("")
    out.append("end H121010")
    print("\n".join(out))
    emap.save()
