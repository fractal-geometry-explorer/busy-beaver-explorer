"""Writes lean/Rules.lean: the pieces of one E-pass of 1RB0LA_0RC0RB_1LD1LA_1LC1RE_1RF0RD_1LC--- that hold for every
left tape P (every context), each proved by `bbtools.symtm` (single steps by `rfl`, runs by `cross_r` / `cross_l`).
lean/Pass.lean chains them into the E-pass for every n.  usage: python3 leanrules.py > ../lean/Rules.lean"""
import os, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove  # noqa: E402

M = "1RB0LA_0RC0RB_1LD1LA_1LC1RE_1RF0RD_1LC---"
RULES = [
    ("epass_even", "The E-pass over an even block: `P E> 1^(2k)` to `P (01)^k C> 1 1`.",
     "P E> (11)^k 0^inf", "P (01)^k C> 1 1 0^inf"),
    ("epass_odd", "The E-pass over an odd block: `P E> 1^(2k+3)` to `P (01)^(k+1) 1 0 C> 1 1`.",
     "P E> 1 (11)^k+1 0^inf", "P (01)^k+1 1 0 C> 1 1 0^inf"),
    ("pairs", "Two `01` of the halved block become six more 1s: `P 0 1 0 1 C> 1^(2j+2)` to `P C> 1^(2j+8)`.",
     "P 0 1 0 1 C> (11)^j+1 0^inf", "P C> (11)^j+4 0^inf"),
    ("one_pair", "One `01` left: `P 0 1 C> 1^(2j+2)` to `P 1 C> 1^(2j+5)`.",
     "P 0 1 C> (11)^j+1 0^inf", "P 1 C> 1 (11)^j+2 0^inf"),
    ("r_zero", "A 0 at the end of the left word with an even block: `P 0 C> 1^(2j+2)` to `P C> 1^(2j+5)`.",
     "P 0 C> (11)^j+1 0^inf", "P C> 1 (11)^j+2 0^inf"),
    ("r_zoo", "`011` at the end of the left word with an odd block: `P 0 1 1 C> 1^(2j+3)` to `P C> 1^(2j+6)`.",
     "P 0 1 1 C> 1 (11)^j+1 0^inf", "P C> (11)^j+3 0^inf"),
]

if __name__ == "__main__":
    print("import Machine\n")
    print("/-! Rules of " + M + " that hold for every left tape `P`, generated by `py/leanrules.py` with "
          "`bbtools.symtm`; do not edit by hand. -/\n")
    print("namespace H121010\n\nopen TM\n")
    for name, doc, s, e in RULES:
        t, fin = prove(M, name, s, e, doc=doc, rotate=True, count_first=True, max_seg=40)
        print(t)
        print()
        print(f"-- {name} ends at: {fin}", file=sys.stderr)
    print("end H121010")
