"""Writes lean/Rules.lean: the two-sweep rules of the growth phase and of the stall phase, proved by bbtools.symtm.

run from the repository root:  PYTHONPATH=tools/py python3 holdouts/1RB1LD_0RC1RC_1RD0RE_0LA0LF_0RF---_1RA1LA/py/gen_rules.py
"""
import os
from bbtools import symtm
from bbtools.machine import Machine

M = "1RB1LD_0RC1RC_1RD0RE_0LA0LF_0RF---_1RA1LA"
m = Machine.parse(M)
RULES = [
    ("growth_two_sweeps",
     "Growth phase: two sweeps eat four 110-units at the front and add 18 ones behind it (the tape grows by 6 cells).",
     "L (110)^n+4 (111)^j 1 1 0 0 1 A> 0^inf", "L (110)^n (111)^j+6 1 1 0 0 1 A> 0^inf"),
    ("stall_two_sweeps",
     "Stall phase: two sweeps eat four 110-units at the front and add 12 ones behind it (the tape does not grow).",
     "L (110)^n+4 (111)^j 1 1 0 1 1 1 D> 0^inf", "L (110)^n (111)^j+4 1 1 0 1 1 1 D> 0^inf"),
]
thms = []
for name, doc, s, e in RULES:
    t, fin = symtm.prove(m, name, s, e, rotate=True, doc=doc)
    print(name, "->", fin)
    thms.append(t)
out = symtm.rules_file("Machine", "H179721", thms, "Sweep rules of " + M + ", generated by py/gen_rules.py.")
open(os.path.join(os.path.dirname(__file__), "..", "lean", "Rules.lean"), "w").write(out)
