"""Generate ../lean/Rules.lean: the shift and macro rules of 1RB0RE_1RC0RC_1LD---_0LB1LE_1RF0LD_1RA1RF, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1RC0RC_1LD---_0LB1LE_1RF0LD_1RA1RF"

RULES = [
    ('d_v0', 'L (1111)^n D> 0 R', 'L D> 0 (1111)^n R',
     'D runs left over 1111 words (on a 0), leaving them.'),
    ('d_v1', 'L (1111)^n D> 1 R', 'L D> 1 (0101)^n R',
     'D runs left over 1111 words (on a 1), writing 0101.'),
    ('e_v1', 'L (1111)^n E> 1 R', 'L E> 1 (1010)^n R',
     'E runs left over 1111 words, writing 1010.'),
    ('f_v', 'L F> (1111)^n R', 'L (1111)^n F> R',
     'F runs right over 1111 words.'),
    ('e_0101', 'L E> (0101)^n R', 'L (1110)^n E> R',
     'E runs right over 0101, writing 1110.'),
    ('f_0101', 'L F> (0101)^n R', 'L (1011)^n F> R',
     'F runs right over 0101.'),
    ('a_1010', 'L A> (1010)^n R', 'L (0111)^n A> R',
     'A runs right over 1010, writing 0111.'),
    ('f_1010', 'L F> (1010)^n R', 'L (1101)^n F> R',
     'F runs right over 1010.'),
    ('d_0101', 'L (0101)^n D> 0 R', 'L D> 0 (0111)^n R',
     'D runs left over 0101.'),
    ('d_1010', 'L (1010)^n D> 0 R', 'L D> 0 (1011)^n R',
     'D runs left over 1010.'),
    ('e_1010', 'L (1010)^n E> 1 R', 'L E> 1 (1110)^n R',
     'E runs left over 1010.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=20)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H121862", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
