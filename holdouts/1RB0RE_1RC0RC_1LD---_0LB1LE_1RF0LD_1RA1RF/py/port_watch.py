"""Write lean/watch/*.lean: the list-machine proof of 1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF, re-checked for the
"watched" twin of lean/watch/Machine.lean.

The watched twin is the twin's table with one more state G: B on 0 goes to G instead of C, and G acts as C on 0
(1LD) but halts on 1.  So it runs exactly the twin's run, but halts at the twin's breaks with this machine (B with a
1 in one of the two cells ahead, see lean/Twin.lean).  The twin's files are copied unchanged except for the
namespace (H75625 -> H75625W) and the imports; every proof goes through because no lemma there passes B except on
`B> 0 0`, where G does what C does.  Rerun after the twin's files change:  python3 py/port_watch.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
TWIN = os.path.join(HERE, "..", "..", "1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF", "lean")
DST = os.path.join(HERE, "..", "lean", "watch")
FILES = ["Pascal", "Absorb", "Wall", "Crossing", "End", "Race"]
NOTE = ("-- Generated by holdouts/1RB0RE_1RC0RC_1LD---_0LB1LE_1RF0LD_1RA1RF/py/port_watch.py from the file of the same\n"
        "-- name of 1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF, for the watched twin of watch/Machine.lean (namespace\n"
        "-- H75625W); do not edit by hand.\n")


def port(text):
    text = re.sub(r"\bH75625\b", "H75625W", text)
    text = re.sub(r"^import (\w+)$", lambda m: "import watch." + m.group(1), text, flags=re.M)
    return text


os.makedirs(DST, exist_ok=True)
for name in FILES:
    with open(os.path.join(TWIN, name + ".lean")) as f:
        src = f.read()
    out = port(src)
    first, rest = out.split("\n", 1)
    with open(os.path.join(DST, name + ".lean"), "w") as f:
        f.write(first + "\n" + NOTE + rest)
    print("wrote", os.path.join(DST, name + ".lean"))
