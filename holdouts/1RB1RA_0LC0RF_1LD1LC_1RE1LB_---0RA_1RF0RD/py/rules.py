"""Writes lean/Rules.lean: the two trips of the head over the run of 1s at the right end, for every length and
every tape L to its left, each proved by bbtools.symtm (shift rules, `rfl`, `omega`).

* descend: from the visit `L 0 1^(2n) B> 0^inf` the head writes a 0, walks down the run in C and reaches the 0 left
  of it, 2n + 1 steps (odd lengths: `descend_odd`);
* climb: coming back in A at the left end of the run, `L A> 1^(2n) 0^inf`, the head climbs it, adds one 1 at the top
  and is at the next visit in B, 2n + 1 steps (`climb_odd` for odd lengths).

So between two visits the run grows by one, and everything else happens left of it: whatever the head does there,
it can only cross the run to the right in A (the only state that moves right over a 1 and stays the same), so E can
only reach the blank region (which `Edge.lean` shows is necessary and sufficient for a halt) once the run is gone.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB1RA_0LC0RF_1LD1LC_1RE1LB_---0RA_1RF0RD"
NS = "H81504"
RULES = [
    ("descend", "From a visit, B at the right end above a run of 2n+2 ones, down to the 0 below the run in C.",
     "L 0 (11)^n+1 B> 0^inf", "L C> 0 (11)^n+1 0^inf"),
    ("descend_odd", "The same for a run of 2n+1 ones.", "L 0 (11)^n 1 B> 0^inf", "L C> 0 (11)^n 1 0^inf"),
    ("climb", "A at the foot of a run of 2n ones climbs it and adds a 1: the next visit.",
     "L A> (11)^n 0^inf", "L (11)^n 1 B> 0^inf"),
    ("climb_odd", "The same for a run of 2n+1 ones.", "L A> (11)^n 1 0^inf", "L (11)^n 1 1 B> 0^inf"),
]


def main():
    thms = [prove(M, name, s, e, doc=doc, rotate=True, count_first=True, max_seg=60)[0] for name, doc, s, e in RULES]
    print(rules_file("Machine", NS, thms, "The head's trips over the run of ones at the right. Generated by `py/rules.py`."),
          end="")


if __name__ == "__main__":
    main()
