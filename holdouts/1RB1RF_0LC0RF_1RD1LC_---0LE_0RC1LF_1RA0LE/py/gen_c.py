"""gen_c.py: write c/framemap_cases.h, the Lean frame map `next` of lean/Phases.lean as C, with the step count of
each case from its piece theorems in lean/Pieces.lean (both read from the Lean files by `rules.parse_lean`).

    python3 py/gen_c.py && git diff --exit-code c/framemap_cases.h

The cases are tried in the order of `def next`, as Lean's match does.  Every variable is a uint64; every target and
step expression is affine with small coefficients, and c/framemap.c checks the variables stay below 2^60.
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from rules import CASES

KINDS = ['e', 'E', 'f', 'F', 'g', 'h', 'H', 'i', 'I', 'k', 'K']
ARITY = {'e': 3, 'E': 3, 'f': 2, 'F': 2, 'g': 2, 'h': 3, 'H': 3, 'i': 3, 'I': 3, 'k': 2, 'K': 2}
SLOT = ['x0', 'x1', 'x2']


def cexpr(e, env):
    e = re.sub(r'\b([a-z]\w*)\b', lambda m: env[m.group(1)], e)
    return '(' + e + ')'


def main():
    out = ['/* Generated by py/gen_c.py from lean/Phases.lean and lean/Pieces.lean; do not edit. */',
           '#define NKINDS %d' % len(KINDS), '#define NCASES %d' % len(CASES),
           'static const char KNAME[] = "%s";' % ''.join(KINDS),
           'static const int ARITY[] = {%s};' % ', '.join(str(ARITY[k]) for k in KINDS),
           'static const char *CASE_NAME[] = {']
    for n, pats, tgt, st, _ in CASES:
        out.append('  "%s %s",' % (n, ' '.join(pats)))
    out.append('};')
    out.append('/* One frame: kind, x[3].  Returns the case index; sets *halt (case is `none`), the next frame, *dt. */')
    out.append('static inline int lean_next(int *kind, u64 *x, u64 *dt, int *halt) {')
    out.append('  u64 x0 = x[0], x1 = x[1], x2 = x[2]; (void)x2;')
    out.append('  switch (*kind) {')
    for ki, k in enumerate(KINDS):
        out.append('  case %d: /* %s */' % (ki, k))
        for i, (n, pats, tgt, st, _) in enumerate(CASES):
            if n != k: continue
            cond, env = [], {}
            for s, p in zip(SLOT, pats):
                if p.isdigit(): cond.append('%s == %s' % (s, p))
                elif p.startswith('('):
                    v, c = re.match(r'\((\w+) \+ (\d+)\)', p).groups()
                    cond.append('%s >= %s' % (s, c)); env[v] = '(%s - %s)' % (s, c)
                else: env[p] = s
            body = ['*dt = %s;' % cexpr(st, env)]
            if tgt is None: body.append('*halt = 1;')
            else:
                body.append('*halt = 0; *kind = %d;' % KINDS.index(tgt[0]))
                vals = [cexpr(e, env) for e in tgt[1]]
                tmp = ' '.join('u64 n%d = %s;' % (j, v) for j, v in enumerate(vals))
                body.append(tmp + ' ' + ' '.join('x[%d] = n%d;' % (j, j) for j in range(len(vals))))
            out.append('    if (%s) { %s return %d; }' % (' && '.join(cond) or '1', ' '.join(body), i))
        out.append('    break;')
    out.append('  }')
    out.append('  return -1;')
    out.append('}')
    path = os.path.join(HERE, '..', 'c', 'framemap_cases.h')
    open(path, 'w').write('\n'.join(out) + '\n')
    print('wrote', os.path.normpath(path), len(CASES), 'cases')


if __name__ == '__main__':
    main()
