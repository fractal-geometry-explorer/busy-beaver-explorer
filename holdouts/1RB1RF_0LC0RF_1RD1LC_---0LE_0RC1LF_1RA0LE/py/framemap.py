"""framemap.py [table | verify R | real STEPS | run PHASES]

The frame map of 1RB1RF_0LC0RF_1RD1LC_---0LE_0RC1LF_1RA0LE (frames in `spec.py`), fitted from the machine: for every frame and every pattern of
its variables (each a value < T or "big"), the next frame and the step count as affine functions, from runs of the
real machine on a grid of W values per big variable.  `table` prints it; `verify R` compares it with the machine at
every canonical frame with all variables < R; `real STEPS` runs it next to the machine from blank tape, comparing
the whole tape at every frame; `run PHASES` iterates it from the first frame of the run with repeated cycles
batched and prints the frame and step count reached.  The same map, collapsed into cases, is proved in
`lean/Phases.lean` (generated by `pieces.py`)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from spec import M, FR, TURNS, T, W
from fitlib import Fit
MOD = 1
def first_frame():
    tape = {}; p = 0; st = 0
    for n in range(1, 10000):
        t = F.T[(st, tape.get(p, 0))]; tape[p] = t[0]; p += t[1]; st = t[2]
        r = F.match(tape, p, st)
        if r: return r[0], tuple(r[1][v] for v in f.vars_of(r[0])), n
def step(fr):
    return f.predict(*fr)
def cyc(fr, L):
    seq = []; cur = fr; tot = 0
    for _ in range(L):
        p = f.predict(*cur)
        if p is None or p[0] in ('HALT', 'NONE'): return None
        seq.append((cur[0], f.pat_of(cur[1]))); cur = (p[0], p[1]); tot += p[2]
    return seq, cur, tot
def accel(fr):
    n, v = fr
    for L in range(1, 13):
        c0 = cyc(fr, L)
        if c0 is None: return None
        seq, cur, tot = c0
        if cur[0] != n or f.pat_of(cur[1]) != f.pat_of(v): continue
        d = tuple(b - a for a, b in zip(v, cur[1]))
        if not any(d): continue
        k = None
        for vi, di in zip(v, d):
            if di < 0: kk = (vi - f.T) // (-di) + 1; k = kk if k is None else min(k, kk)
        if k is None or k < 3: return None
        while k >= 3:
            last = (n, tuple(a + (k - 1) * b for a, b in zip(v, d)))
            cl = cyc(last, L)
            if cl is not None and cl[0] == seq: break
            k -= 1
        if k < 3: return None
        c1 = cyc((n, tuple(a + b for a, b in zip(v, d))), L)
        g = c1[2] - tot
        return (n, tuple(a + k * b for a, b in zip(v, d))), k * tot + g * k * (k - 1) // 2, k * L
    return None

def realcheck(LIM):
    pass
    T = F.T; tape = bytearray(2 * LIM // 10 + 100000); off = len(tape) // 2; p = off; st = 0; n = 0
    def norm_real():
        nz = [i for i in range(lo, hi + 1) if tape[i]]
        a = min(nz + [p]); b = max(nz + [p])
        return bytes(tape[a:b + 1]), p - a, st
    def norm_frame(fr):
        t, q, s = F.build(fr[0], dict(zip(f.vars_of(fr[0]), fr[1])))
        nz = [i for i, v in t.items() if v]; a = min(nz + [q]); b = max(nz + [q])
        return bytes(t.get(i, 0) for i in range(a, b + 1)), q - a, s
    lo = hi = p; fr = None; target = None; checked = 0
    while n < LIM:
        tr = T[(st, tape[p])]
        if tr is None: print('REAL HALT at', n); break
        tape[p] = tr[0]; p += tr[1]; st = tr[2]; n += 1; lo = min(lo, p); hi = max(hi, p)
        if fr is None:
            r = F.match({i - off: tape[i] for i in range(lo, hi + 1)}, p - off, st)
            if r: fr = (r[0], tuple(r[1][v] for v in f.vars_of(r[0]))); target = n
        if fr is not None and n == target:
            if norm_real() != norm_frame(fr): print('MISMATCH at', n, fr); break
            checked += 1
            pr = f.predict(*fr)
            if pr is None: print('NO CASE', fr); break
            if pr[0] == 'HALT': print('map predicts HALT at', n + pr[2]); fr = None; target = -1; continue
            fr = (pr[0], pr[1]); target = n + pr[2]
    print('frames checked', checked, 'up to step', n)

if __name__ == '__main__':
    f = Fit(M, FR, T, W, MOD, TURNS); F = f.F
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'table'
    if cmd == 'table': f.show()
    elif cmd == 'verify': f.verify(int(sys.argv[2]))
    elif cmd == 'real': realcheck(int(sys.argv[2]))
    elif cmd == 'run':
        N = int(sys.argv[2]); fr = first_frame(); steps = fr[2]; fr = fr[:2]; ph = 0
        print('start', fr, 'at step', steps)
        while ph < N:
            a = accel(fr)
            if a: fr, s, k = a; steps += s; ph += k; continue
            p = f.predict(*fr)
            if p is None: print('NO CASE', fr); break
            if p[0] == 'HALT': print('HALT from', fr, 'at step', steps + p[2]); break
            steps += p[2]; fr = (p[0], p[1]); ph += 1
        print('phases', ph, 'steps', steps, 'frame', fr)
