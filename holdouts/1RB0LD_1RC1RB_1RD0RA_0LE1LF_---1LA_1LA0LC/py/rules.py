"""Shift rules and halting situations of 1RB0LD_1RC1RB_1RD0RA_0LE1LF_---1LA_1LA0LC, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LD_1RC1RB_1RD0RA_0LE1LF_---1LA_1LA0LC/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LD_1RC1RB_1RD0RA_0LE1LF_---1LA_1LA0LC"
NS = "H21414"
DOC = """# Shift rules of 1RB0LD_1RC1RB_1RD0RA_0LE1LF_---1LA_1LA0LC

The sweeps over the `(01)^n` segments: going right, B turns each `1010` into `1101` (`right_B`, four steps a copy);
going left, D with a 1 ahead turns each `1101` into `0101` (`left_D`, six steps a copy).  The halting situations:
only E reading a 0 halts, and `0 D> 0`, `0 0 A> 1` and `0 C> 1 1` lead there.

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('right_B', 'L B> (1010)^n R', 'L (1101)^n B> R', 'Going right, B turns each `1010` into `1101`, four steps a copy.'),
    ('left_D', 'L (1101)^n D> 1 R', 'L D> 1 (0101)^n R', 'Going left, D (with a 1 ahead) turns each `1101` into `0101`, six steps a copy.'),
]

HALTS = [
    ('halt_D', '0 D> 0', 1, '`0 D> 0` halts: D steps left onto a 0 in state E.'),
    ('halt_A', '0 0 A> 1', 2, '`0 0 A> 1` halts after two steps.'),
    ('halt_C', '0 C> 1 1', 3, '`0 C> 1 1` halts after three steps.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [prove(M, name, a, b, doc=doc, count_first=True)[0] for name, a, b, doc in RULES]
    thms += [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
