"""Writes lean/Phases.lean: the two quiet phases of an epoch, as rules for every value of the counts, proved by
bbtools.symtm from a symbolic trace (shift rules, `rfl`, `omega`), with the end tape re-bracketed into the start
form by `tapeeq` (TM.rep_rotate, TM.rep_succ, TM.rep_add).

Letters: a = 10, b = 100, c = 1000 (an isolated 1 and its gap of 0s).  The head is in state D on the first blank
cell right of the tape (the moment the tape grows), L is any tape on the left.

  P1 n m   =  L (baccaaa)^n ba 1 00 (aaaaca)^m aaa (caa)^(m+2) c 1  D>       (first phase of an epoch)
  P2 p q r =  L (bac)^p 1 00 acccb (aaaaac)^q aaaa (caa)^r c 1  D>              (second phase)
  P5 k j   =  L (baccaaa)^k ccb (aaaac)^(j+2) aaa 1 00 aac 1  D>            (last phase of an epoch)

usage: python3 phases.py > ../lean/Phases.lean
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tapeeq
from bbtools import symtm

M = "1RB1RB_0LC0LD_0LE1LD_1LB0RE_1RA0RF_1RD---"
NS = "H181063"
E = {"a": "10", "b": "100", "c": "1000"}


def w(t):
    return "".join(E[x] for x in t)


def P1(n, m):
    return f"L ({w('baccaaa')})^{n} {w('ba')}1 00 ({w('aaaaca')})^{m} {w('aaa')} ({w('caa')})^{m}+2 {w('c')}1 D> 0^inf"


def P2(p, q, r):
    return f"L ({w('bac')})^{p} 1 00 {w('acccb')} ({w('aaaaac')})^{q} {w('aaaa')} ({w('caa')})^{r} {w('c')}1 D> 0^inf"


def P5(k, j):
    return f"L ({w('baccaaa')})^{k} {w('ccb')} ({w('aaaac')})^{j}+2 {w('aaa')}1 00 {w('aac')}1 D> 0^inf"


MACH = symtm.Machine.parse(M)


def visits(start, k):
    """Run k visits of the right end (D on blank tape) symbolically; the final configuration."""
    c = symtm.Config.parse(start)
    for _ in range(k):
        n0 = c.steps
        c = symtm.run(MACH, c, lambda x: x.state == 3 and x.right == [symtm.Blank()] and not (x.steps - n0).is_zero(),
                      rotate=True)
    return c


def rule(name, doc, start, target, k, defname, args_start, args_end):
    fin = visits(start, k)
    lean, fin2 = symtm.prove(MACH, name + "_run", start, fin, rotate=True, count_first=True, max_seg=40,
                             doc=doc + " (the run, as the trace writes the end)")
    tgt = symtm.Config.parse(target)
    assert fin2.right == [symtm.Blank()] and fin2.state == 3
    a, b = tapeeq.outward_left(fin2), tapeeq.outward_left(tgt)
    pf = tapeeq.eq_proof(a, b)
    vs = sorted(symtm.Config.parse(start).vars() | tgt.vars())
    out = [lean]
    out.append(f"/-- {doc} -/")
    out.append(f"theorem {name} ({' '.join(vs)} : Nat) (L : Tape) :")
    out.append(f"    steps ({fin2.steps.lean()}) ({defname} {args_start} L) = some ({defname} {args_end} L) := by")
    out.append(f"  have h := {name}_run {' '.join(vs)} L")
    out.append(f"  rw [show {tapeeq.term(a)} = {tapeeq.term(b)} from")
    out.append(f"    {pf}] at h")
    out.append(f"  exact h")
    return "\n".join(out) + "\n", fin2.steps


def defn(name, doc, cfg, params):
    c = symtm.Config.parse(cfg)
    return (f"/-- {doc} -/\ndef {name} ({' '.join(params)} : Nat) (L : Tape) : Config :=\n"
            f"  ⟨{tapeeq.term(tapeeq.outward_left(c))}, blank, .D⟩\n")


def main():
    parts = [f"import Machine\n\n/-! {__doc__.split(chr(10))[0]}\n\nGenerated by `py/phases.py`; see its docstring. -/\n\n"
             f"namespace {NS}\n\nopen TM\n"]
    parts.append(defn("P1", "First phase: `L (baccaaa)^n ba 1 00 (aaaaca)^m aaa (caa)^(m+2) c 1 D>` (a = 10, b = 100, c = 1000).",
                      P1("n", "m"), ["n", "m"]))
    parts.append(defn("P2", "Second phase: `L (bac)^p 1 00 acccb (aaaaac)^q aaaa (caa)^r c 1 D>`.", P2("p", "q", "r"),
                      ["p", "q", "r"]))
    parts.append(defn("P5", "Last phase: `L (baccaaa)^k ccb (aaaac)^(j+2) aaa 1 00 aac 1 D>`.", P5("k", "j"), ["k", "j"]))
    t1, s1 = rule("p1_visit", "One visit of the first phase: a copy of `baccaaa` becomes `aaaaca` and `caa`, and the tape grows by 3 cells.",
                  P1("n+1", "m"), P1("n", "m+1"), 1, "P1", "(n + 1) m", "n (m + 1)")
    t2, s2 = rule("p2_visit", "One visit of the second phase: a copy of `aaaaac` becomes one more `bac` on the left and one more `caa` on the right.",
                  P2("p", "q+1", "r"), P2("p+1", "q", "r+1"), 1, "P2", "p (q + 1) r", "(p + 1) q (r + 1)")
    t5, s5 = rule("p5_cycle", "Two visits of the last phase: a copy of `aaaac` becomes a copy of `baccaaa`.",
                  P5("k", "j+1"), P5("k+1", "j"), 2, "P5", "k (j + 1)", "(k + 1) j")
    parts += [t1, t2, t5]
    parts.append(ITER)
    parts.append(f"end {NS}\n")
    print("\n".join(parts))


ITER = r'''
/-- A rule that moves one unit from one count to another, applied k times. -/
theorem iterate {f : Nat → Nat → Tape → Config} (h : ∀ n m L, ∃ t, steps t (f (n + 1) m L) = some (f n (m + 1) L)) :
    ∀ k n m L, ∃ t, steps t (f (n + k) m L) = some (f n (m + k) L) := by
  intro k
  induction k with
  | zero => intro n m L; exact ⟨0, rfl⟩
  | succ k ih =>
    intro n m L
    obtain ⟨t1, h1⟩ := h (n + k) m L
    obtain ⟨t2, h2⟩ := ih n (m + 1) L
    have e1 : n + (k + 1) = n + k + 1 := by omega
    have e2 : m + 1 + k = m + (k + 1) := by omega
    rw [e1]; rw [e2] at h2
    exact ⟨t1 + t2, steps_seq trans h1 h2⟩

/-- The whole first phase: from `P1 n 0`, n visits later, `P1 0 n` (every copy of `baccaaa` used up). -/
theorem phase1 (n : Nat) (L : Tape) : ∃ t, steps t (P1 n 0 L) = some (P1 0 n L) := by
  have := iterate (f := P1) (fun n m L => ⟨_, p1_visit (n := n) (m := m) L⟩) n 0 0 L
  simpa using this

/-- The whole second phase: from `P2 p q r`, q visits later, `P2 (p + q) 0 (r + q)`. -/
theorem phase2 (p q r : Nat) (L : Tape) : ∃ t, steps t (P2 p q r L) = some (P2 (p + q) 0 (r + q) L) := by
  have := iterate (f := fun q' p' L => P2 (p + p') q' (r + p') L)
    (fun q' p' L => ⟨_, p2_visit (p := p + p') (q := q') (r := r + p') L⟩) q 0 0 L
  simpa using this

/-- The whole last phase: from `P5 k j`, 2j visits later, `P5 (k + j) 0`. -/
theorem phase5 (k j : Nat) (L : Tape) : ∃ t, steps t (P5 k j L) = some (P5 (k + j) 0 L) := by
  have := iterate (f := fun j k L => P5 k j L) (fun j k L => ⟨_, p5_cycle (k := k) (j := j) L⟩) j 0 k L
  simpa using this
'''

if __name__ == "__main__":
    main()
