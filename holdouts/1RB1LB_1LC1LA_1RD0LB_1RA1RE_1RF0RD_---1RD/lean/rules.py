"""Generate Rules.lean: the rounds and some of the resets of 1RB1LB_1LC1LA_1RD0LB_1RA1RE_1RF0RD_---1RD, proved along
the symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(01)^n` is n copies
of `01` (an "a"), R is any tape, 0^inf blank tape.  The tape is  0^inf 1 B> 1 01 [1^X] [01 or 0101] 1^5 (01)^Y T:
a block of X ones, a marker, the counter Y and the digits T (see ../README.md).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LB_1LC1LA_1RD0LB_1RA1RE_1RF0RD_---1RD"
P = "0^inf 1 B> 1 01 (11)^5*j+7 1 01 "          # the start of a reset: X = 10(j+1)+5 ones, marker 01
Q = "0^inf 1 B> 1 01 0101 1^5 "                  # the start of an epoch: X = 0, marker 0101, then the counter

RULES = [
    ("round_a", "0^inf 1 B> 1 01 (1111111111)^j 0101 1^5 (01)^Y R",
     "0^inf 1 B> 1 01 (1111111111)^j 1^5 01 1^5 (01)^Y R",
     "Round, first half: the block of 10j ones grows by five and the marker `0101` shrinks to `01`.", {}),
    ("round_b", "0^inf 1 B> 1 01 (1111111111)^j 1^5 01 1^5 (01)^Y+2 R",
     "0^inf 1 B> 1 01 (1111111111)^j+1 0101 1^5 (01)^Y R",
     "Round, second half: five more ones, the marker back to `0101`, and two a's of the counter used up.", {}),
    ("reset_even", P + "(1111111111)^k+1 (01)^e+1 R",
     Q + "(01)^5*j+5 1^5 (1111111111)^k+1 (01)^e R",
     "Reset with a first digit (2k+2, e+1): the counter restarts at 5(j+1) and the digit becomes (2k+3, e).",
     {"rotate": True}),
    ("reset_odd3", P + "1^15 (01)^e+3 R",
     Q + "(01)^5*j+10 1^5 (01)^4 1^5 (01)^e+1 R",
     "Reset with a first digit (3, e+3): the counter restarts at 5(j+1)+5, the digit splits into (1,4) (1,e+1).",
     {"rotate": True}),
    ("carry_one", P + "1^5 01 1^5 (01)^e+3 R",
     Q + "(01)^5*j+5 1^10 (01)^2 1^5 (01)^e+1 R",
     "Reset with digits (1,1) (1,e+3): the counter restarts at 5(j+1), digits (2,2) (1,e+1).", {"rotate": True}),
    ("carry_three", P + "1^5 01 1^15 (01)^e+3 R",
     Q + "(01)^5*j+5 1^10 (01)^7 1^5 (01)^e+1 R",
     "Reset with digits (1,1) (3,e+3): the counter restarts at 5(j+1), digits (2,7) (1,e+1).", {"rotate": True}),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, count_first=True, max_seg=60, **kw)[0] for name, a, b, doc, kw in RULES]
    out = rules_file("Machine", "H89641", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    out = out.replace("namespace H89641", "set_option maxHeartbeats 4000000\nset_option maxRecDepth 10000\n\nnamespace H89641", 1)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
