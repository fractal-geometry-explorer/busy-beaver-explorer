"""Writes lean/HaltRule.lean: the last stretch before a halt of 1RB1RF_1LC1LB_1RD1LD_1RE0RA_---0LB_0LF0RC.

With the head at the left end in state D, `0^inf D> 0111011 (011)^n (1011)^p 1110 1 0^inf` (in run lengths:
`3 2^n 3^p 5 1`, the marker 5 in front of the last run) runs 25n+24p+120 steps and stands in state E on a 0: it
halts.  Proved by bbtools.symtm from a symbolic trace for every n and p.  lean/Halt.lean builds the criterion on it.

usage: python3 halt_rule.py > ../lean/HaltRule.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, run, Config, Halted
from bbtools.machine import Machine

M = "1RB1RF_1LC1LB_1RD1LD_1RE0RA_---0LB_0LF0RC"
NS = "H279"
START = "0^inf D> 0 1 1 1 0 1 1 (011)^n (1011)^p 1 1 1 0 1 0^inf"
START2 = "0^inf D> 0 1 1 1 0 1 1 (011)^n (1011)^p 1 0 1 0 1 0^inf"


def to_halt(m, name, start, doc):
    tr = []
    try:
        run(m, Config.parse(start), lambda c: False, max_moves=5000, trace=tr, rotate=True)
    except Halted:
        pass
    return prove(M, name, start, tr[-1][2], doc=doc, rotate=True, count_first=True, max_seg=60)[0]


def main():
    m = Machine.parse(M)
    ts = [to_halt(m, "tail", START, "The last stretch (run lengths `3 2^n 3^p 5 1`): `0^inf D> 0111011 (011)^n (1011)^p "
                  "1110 1 0^inf` reaches a configuration with the head in state E on a 0 (the halting transition)."),
          to_halt(m, "tail2", START2, "The same with the marker 1 and no run left behind it (run lengths "
                  "`3 2^n 3^(p+1) 1 1`): `0^inf D> 0111011 (011)^n (1011)^p 1010 1 0^inf` runs to the halting transition."),
          prove(M, "marker1", "0^inf D> 0 1 1 1 0 1 1 (011)^n (1011)^p 1 0 1 0 1 1 1 0 R",
                "0^inf D> 0 1 1 1 0 1 1 (011)^n+1 (1011)^p+1 1 1 1 0 R",
                doc="The marker 1 takes the next run of 3 and becomes the marker 5 (run lengths `1 3 -> 5`): "
                "`0^inf D> 0111011 (011)^n (1011)^p 1010 1110 R` becomes `0^inf D> 0111011 (011)^(n+1) (1011)^(p+1) 1110 R`.",
                rotate=True, count_first=True, max_seg=60)[0]]
    print("\n".join(["import Machine", "", f"/-! The last stretch before a halt of {M}, generated by `py/halt_rule.py`; "
                     "do not edit by hand. -/", "", f"namespace {NS}", "", "open TM", ""] + [t + "\n" for t in ts]
                    + [f"end {NS}"]))


if __name__ == "__main__":
    main()
