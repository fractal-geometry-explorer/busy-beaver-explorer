"""Generate lean/Rules.lean for 1RB1RE_1LC0RA_1LA0LD_1LB0LF_0RB0LE_0LA---: one-cycle rules of its phases, proved along the symbolic run of
tools/py/bbtools/symtm.py (single steps by `rfl`, shift rules by TM.cross_r/cross_l, re-bracketing by TM.rep_rotate).

usage (from the repo root): python3 holdouts/1RB1RE_1LC0RA_1LA0LD_1LB0LF_0RB0LE_0LA---/py/rules.py > holdouts/1RB1RE_1LC0RA_1LA0LD_1LB0LF_0RB0LE_0LA---/lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RE_1LC0RA_1LA0LD_1LB0LF_0RB0LE_0LA---"
NS = next(l.split()[1] for l in open(os.path.join(HERE, "..", "lean", "Machine.lean")) if l.startswith("namespace "))

RULES = [
    ("traverse",
     "0^inf A> 0 1 1 (010110110)^p+1 (110)^q+1 (010)^r+1 (110)^s+1 (1)^3 (011)^t+6 0 1 0^inf",
     "0^inf A> 0 1 1 (010110110)^p+2 (110)^q+1 (010)^r+1 (110)^s+7 (1)^3 (011)^t 0 1 0^inf",
     "Traverse phase, one cycle (nine visits of the left end): the boundary in the right block moves six words right and the left block gains one word `010110110`."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
