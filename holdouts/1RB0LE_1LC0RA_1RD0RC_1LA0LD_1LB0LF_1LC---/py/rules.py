"""Shift rules and halting situations of 1RB0LE_1LC0RA_1RD0RC_1LA0LD_1LB0LF_1LC---, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LE_1LC0RA_1RD0RC_1LA0LD_1LB0LF_1LC---/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LE_1LC0RA_1RD0RC_1LA0LD_1LB0LF_1LC---"
NS = "H69718"
DOC = """# Shift rules of 1RB0LE_1LC0RA_1RD0RC_1LA0LD_1LB0LF_1LC---

Two erasing runs: C walks right over a block of 1s, erasing it, one step a cell (`erase_C`), and D, with a 1 ahead,
walks left over a block of 1s, erasing it (`erase_D`).  The halting situations: only F reading a 1 halts, and
`1 E> 1`, `1 1 A> 1`, `1 1 1 D> 0` and `1 1 C> 0 0` lead there.

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('erase_C', 'L C> (1)^n R', 'L (0)^n C> R', 'C erases a block of 1s going right, one step a cell.'),
    ('erase_D', 'L (1)^n D> 1 R', 'L D> 1 (0)^n R', 'D, with a 1 ahead, erases a block of 1s going left, one step a cell.'),
]

HALTS = [
    ('halt_E', '1 E> 1', 1, '`1 E> 1` halts: E erases the 1 and steps left onto a 1 in state F.'),
    ('halt_A', '1 1 A> 1', 2, '`1 1 A> 1` halts after two steps.'),
    ('halt_D', '1 1 1 D> 0', 3, '`1 1 1 D> 0` halts after three steps.'),
    ('halt_C', '1 1 C> 0 0', 4, '`1 1 C> 0 0` halts after four steps.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [prove(M, name, a, b, doc=doc, count_first=True)[0] for name, a, b, doc in RULES]
    thms += [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
