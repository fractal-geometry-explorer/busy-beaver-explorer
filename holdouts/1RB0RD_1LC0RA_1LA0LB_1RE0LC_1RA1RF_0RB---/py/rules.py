"""Generate lean/Rules.lean: rules of 1RB0RD_1LC0RA_1LA0LB_1RE0LC_1RA1RF_0RB---, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB0RD_1LC0RA_1LA0LB_1RE0LC_1RA1RF_0RB---)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RD_1LC0RA_1LA0LB_1RE0LC_1RA1RF_0RB---"

RULES = [
    ('a_r_01', 'L A> (01)^n R', 'L (10)^n A> R',
     'A sweeps right over copies of `01` (2 steps a copy).'),
    ('b_l_01', 'L (01)^n B> 0 R', 'L B> 0 (01)^n R',
     'B sweeps left over copies of `01` (2 steps a copy).'),
    ('b_r_10', 'L B> (10)^n R', 'L (01)^n B> R',
     'B sweeps right over copies of `10` (2 steps a copy).'),
    ('c_l_10', 'L (10)^n C> 1 R', 'L C> 1 (10)^n R',
     'C sweeps left over copies of `10` (2 steps a copy).'),
    ('a_r_1010101', 'L A> (1010101)^n R', 'L (0110010)^n A> R',
     'A sweeps right over copies of `1010101` (7 steps a copy).'),
    ('a_r_10101', 'L A> (10101)^n R', 'L (01100)^n A> R',
     'A sweeps right over copies of `10101` (5 steps a copy).'),
    ('a_r_0110101', 'L A> (0110101)^n R', 'L (1001100)^n A> R',
     'A sweeps right over copies of `0110101` (7 steps a copy).'),
    ('b_r_1101010', 'L B> (1101010)^n R', 'L (0011001)^n B> R',
     'B sweeps right over copies of `1101010` (7 steps a copy).')
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H93459", thms,
                                "Rules of 1RB0RD_1LC0RA_1LA0LB_1RE0LC_1RA1RF_0RB---, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
