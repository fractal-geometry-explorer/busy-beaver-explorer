"""Generate lean/Rules.lean: rules of 1RB0RD_1LC0RA_1LA0LB_1RE0LC_1RA1RF_0RB---, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB0RD_1LC0RA_1LA0LB_1RE0LC_1RA1RF_0RB---)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RD_1LC0RA_1LA0LB_1RE0LC_1RA1RF_0RB---"

RULES = [
    ('a_r_01', 'L A> (01)^n R', 'L (10)^n A> R',
     'A sweeps right over copies of `01` (2 steps a copy).'),
    ('b_l_01', 'L (01)^n B> 0 R', 'L B> 0 (01)^n R',
     'B sweeps left over copies of `01` (2 steps a copy).'),
    ('b_r_10', 'L B> (10)^n R', 'L (01)^n B> R',
     'B sweeps right over copies of `10` (2 steps a copy).'),
    ('c_l_10', 'L (10)^n C> 1 R', 'L C> 1 (10)^n R',
     'C sweeps left over copies of `10` (2 steps a copy).'),
    ('a_r_1010101', 'L A> (1010101)^n R', 'L (0110010)^n A> R',
     'A sweeps right over copies of `1010101` (7 steps a copy).'),
    ('a_r_10101', 'L A> (10101)^n R', 'L (01100)^n A> R',
     'A sweeps right over copies of `10101` (5 steps a copy).'),
    ('a_r_0110101', 'L A> (0110101)^n R', 'L (1001100)^n A> R',
     'A sweeps right over copies of `0110101` (7 steps a copy).'),
    ('b_r_1101010', 'L B> (1101010)^n R', 'L (0011001)^n B> R',
     'B sweeps right over copies of `1101010` (7 steps a copy).')
]

# The outer round trip, shared with 1RB0RD_1LC0RA_1LA0LB_1RE0LC_1L{C,D}1RF_0RB--- (E0 is not read in it).  Words:
# c = 1101010, a = 10.  Between two arrivals of the head at the left end (state C, on the leftmost cell) the tape reads
# `11010 w (10)^k 1` with w a word over c and a; one round trip puts a new c at the front of w and takes one a off the
# last block.  Proved for every w with at most four blocks of c's (sweep0 .. sweep3), all exponents symbolic.  The first
# outer phase of this machine starts at step 19276 with w = c^2 a^3 c a^40 c a^8 c a^5 c, five blocks.  The rule for
# five blocks (sweep4) and the 19276-step run from blank tape are generated by the same code, but the kernel check of
# the two did not finish in 50 minutes, so they are left out.
C = "(1101010)"
OUTER = [
    ("sweep0", f"0^inf C> 1 1 0 1 0 {C}^n (10)^k+2 1 0^inf", f"0^inf C> 1 1 0 1 0 {C}^n+1 (10)^k+1 1 0^inf",
     "Outer round trip, w = c^n."),
    ("sweep1", f"0^inf C> 1 1 0 1 0 {C}^n (10)^x+1 {C}^m (10)^k+2 1 0^inf",
     f"0^inf C> 1 1 0 1 0 {C}^n+1 (10)^x+1 {C}^m (10)^k+1 1 0^inf", "Outer round trip, w = c^n a^(x+1) c^m."),
    ("sweep2", f"0^inf C> 1 1 0 1 0 {C}^n (10)^x+1 {C}^m (10)^z+1 {C}^p (10)^k+2 1 0^inf",
     f"0^inf C> 1 1 0 1 0 {C}^n+1 (10)^x+1 {C}^m (10)^z+1 {C}^p (10)^k+1 1 0^inf",
     "Outer round trip, w = c^n a^(x+1) c^m a^(z+1) c^p."),
    ("sweep3", f"0^inf C> 1 1 0 1 0 {C}^n (10)^x+1 {C}^m (10)^z+1 {C}^p (10)^u+1 {C}^q (10)^k+2 1 0^inf",
     f"0^inf C> 1 1 0 1 0 {C}^n+1 (10)^x+1 {C}^m (10)^z+1 {C}^p (10)^u+1 {C}^q (10)^k+1 1 0^inf",
     "Outer round trip, w = c^n a^(x+1) c^m a^(z+1) c^p a^(u+1) c^q."),
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    for name, start, end, doc in OUTER:
        text, _ = prove(M, name, start, end, doc=doc, max_seg=40)
        if name == 'sweep3':
            text = "set_option maxHeartbeats 8000000 in\n" + text
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H93459", thms,
                                "Rules of 1RB0RD_1LC0RA_1LA0LB_1RE0LC_1RA1RF_0RB---, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
