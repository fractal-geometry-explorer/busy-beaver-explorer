"""Generate lean/Rules.lean for 1RB1RD_1LC0LC_0RD0LB_1RF0LE_0RD---_0RA1RC: the shift rules of its sweeps, proved along symbolic runs
(tools/py/bbtools/symtm.py: single steps by `rfl`, a whole repeat crossed by `TM.cross_r` / `TM.cross_l`).

usage (from the repository root): python3 holdouts/1RB1RD_1LC0LC_0RD0LB_1RF0LE_0RD---_0RA1RC/py/rules.py > holdouts/1RB1RD_1LC0LC_0RD0LB_1RF0LE_0RD---_0RA1RC/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape.  Each rule holds for every n and every tape around it; README.md says where each one is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402

symtm.MAX_CARRY = 8  # some sweeps carry a word of up to 6 cells along with the head

M = "1RB1RD_1LC0LC_0RD0LB_1RF0LE_0RD---_0RA1RC"
NS = "H172963"

RULES = [
    ("l_sea", "L (10)^n C> 1 R", "L C> 1 (10)^n R",
     "Leftward sweep over the sea of 10s, 2 steps a pair."),
    ("r_sea", "L 0110 A> (01)^n R", "L (01)^n 0110 A> R",
     "Rightward sweep: the head carries 0110 across the sea, 12 steps a pair."),
    ("r_sea_b", "L 01101 B> (1010)^n R", "L (0101)^n 01101 B> R",
     "The same rightward sweep seen from state B, two pairs at a time."),
    ("l_defect", "L (101110)^n C> 1 R", "L C> 1 (100010)^n R",
     "Leftward sweep: the word 101110 (a defect) becomes 100010."),
]


def main():
    ths = [symtm.prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(symtm.rules_file("Machine", NS, ths, f"Sweep rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
