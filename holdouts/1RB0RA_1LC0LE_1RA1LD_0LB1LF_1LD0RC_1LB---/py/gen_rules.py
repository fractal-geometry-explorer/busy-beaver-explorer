"""Writes ../lean/Rules.lean: the sweep and the two clean phase ends, proved by bbtools.symtm (python3 gen_rules.py)."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB0RA_1LC0LE_1RA1LD_0LB1LF_1LD0RC_1LB---"
P = "0^inf C> 0 1 0 (110)^p 1111"
RULES = [
    ("sweep0", "One sweep with an empty front block: (p, 0, y+3) to (p, 4, y).",
     f"{P} 11100 (100)^y+3 R", f"{P} (110)^4 11100 (100)^y R"),
    ("sweep1", "One sweep with front block 1: (p, 1, y+3) to (p, 5, y).",
     f"{P} 110 11100 (100)^y+3 R", f"{P} (110)^5 11100 (100)^y R"),
    ("sweep2", "One sweep: (p, x+2, y+3) to (p, x+6, y).",
     f"{P} (110)^x+2 11100 (100)^y+3 R", f"{P} (110)^x+6 11100 (100)^y R"),
    ("reset2", "A phase ending with 2 cells of 100 left: the front level is reset and the next level ticks.",
     f"{P} (110)^x+2 11100 (100)^2 (110)^z+2 11100 (100)^w+2 R",
     "0^inf C> 0 1 0 (110)^p+2 1111 11100 (100)^x+4 (110)^z+4 11100 (100)^w R"),
    ("reset0", "A phase ending with no 100 left: the front level is reset and the next level ticks.",
     f"{P} (110)^x+2 11100 (110)^z+2 11100 (100)^w+2 R",
     "0^inf C> 0 1 0 (110)^p+2 1111 11100 (100)^x+2 (110)^z+4 11100 (100)^w R"),
]

if __name__ == "__main__":
    thms = []
    for name, doc, a, b in RULES:
        txt, fin = prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)
        thms.append(txt)
        print(name, fin, file=sys.stderr)
    out = os.path.join(os.path.dirname(__file__), "../lean/Rules.lean")
    with open(out, "w") as f:
        f.write(rules_file("Machine", "H112769", thms, "Sweep and clean phase-end rules, generated by py/gen_rules.py"))
