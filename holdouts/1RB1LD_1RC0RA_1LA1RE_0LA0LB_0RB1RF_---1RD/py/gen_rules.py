"""Writes lean/Rules.lean for 1RB1LD_1RC0RA_1LA1RE_0LA0LB_0RB1RF_---1RD: the register rules, proved by bbtools.symtm.

The tape is always one of
  X(a,b,c) = 0^inf 1^a 0  (10)^b 1 D> 0 1^c 0^inf
  Y(a,b,c) = 0^inf 1^a 00 (10)^b 1 D> 0 1^c 0^inf
  Z(a,c)   = 0^inf 1^a 0 D> 0 1^c 0^inf
and each rule below goes from one of these to the next (the next time the head turns left into state D).
run from the repository root:  PYTHONPATH=tools/py python3 holdouts/1RB1LD_1RC0RA_1LA1RE_0LA0LB_0RB1RF_---1RD/py/gen_rules.py
"""
import os, sys
from bbtools import symtm
from bbtools.machine import Machine

M = "1RB1LD_1RC0RA_1LA1RE_0LA0LB_0RB1RF_---1RD"
m = Machine.parse(M)

def X(a, b, c): return "0^inf (1)^%s 0 (10)^%s 1 D> 0 (1)^%s 0^inf" % (a, b, c)
def Y(a, b, c): return "0^inf (1)^%s 0 0 (10)^%s 1 D> 0 (1)^%s 0^inf" % (a, b, c)
def Z(a, c): return "0^inf (1)^%s 0 D> 0 (1)^%s 0^inf" % (a, c)

# (name, doc, start, number of steps): the end is where the run is after that many steps, as the run writes it
RULES = [
    ("x_bulk", "X(a+4,b,c+2) -> X(a+1,b+2,c+1)", X("a+4", "b", "c+2"), "4*b+13"),
    ("x_three", "X(3,b,c+2) -> X(1,b+1,c+1)", X(3, "b", "c+2"), "4*b+13"),
    ("x_two", "X(2,b,c+2) -> X(2,b+2,c+1): at the left end of the tape", X(2, "b", "c+2"), "4*b+25"),
    ("x_one", "X(1,b,c+2) -> Y(3,b,c+1)", X(1, "b", "c+2"), "4*b+13"),
    ("x_zero0", "X(0,0,c+2) -> Z(3,c+1)", X(0, 0, "c+2"), "9"),
    ("xe_00", "X(0,0,1) -> X(1,0,3) (not reached from blank tape; here so that every state has a rule)", X(0, 0, 1), "25"),
    ("xe_big", "X(a+5,b,1) -> X(a,0,2b+9)", X("a+5", "b", 1), "8*b+37"),
    ("xe_1", "X(1,b,1) -> X(1,0,2b+5)", X(1, "b", 1), "8*b+33"),
    ("xe_2", "X(2,b,1) -> X(0,0,2b+9): the end of a round", X(2, "b", 1), "8*b+49"),
    ("xe_3", "X(3,b,1) -> X(4,0,2b+5)", X(3, "b", 1), "8*b+43"),
    ("xe_4", "X(4,b,1) -> X(4,0,2b+7)", X(4, "b", 1), "8*b+47"),
    ("y_bulk", "Y(a+3,b+1,c+2) -> Y(a+6,b,c+1)", Y("a+3", "b+1", "c+2"), "4*b+13"),
    ("y_zero", "Y(a+3,0,c+2) -> Z(a+6,c+1)", Y("a+3", 0, "c+2"), "9"),
    ("ye", "Y(a+3,b,1) -> X(a+3,1,2b+3)", Y("a+3", "b", 1), "8*b+25"),
    ("z_big", "Z(a+3,c+6) -> X(a+7,0,c+1)", Z("a+3", "c+6"), "11"),
    ("z_1", "Z(a+3,1) -> X(a+3,1,1)", Z("a+3", 1), "17"),
    ("z_3", "Z(a+3,3) -> X(a+3,0,5)", Z("a+3", 3), "29"),
    ("z_4", "Z(a+3,4) -> X(a+5,0,3)", Z("a+3", 4), "21"),
    ("z_5", "Z(a+3,5) -> X(a+5,0,5)", Z("a+3", 5), "27"),
    ("z_halt", "Z(a+3,2): five steps later the head is in F reading 0, which has no transition", Z("a+3", 2), "5"),
]

def end_at(start, nsteps):
    target = symtm.parse_lin(nsteps)
    return symtm.run(m, symtm.Config.parse(start), lambda c: c.steps == target, rotate=True)

only = sys.argv[1:]
thms = []
for name, doc, s, n in RULES:
    if only and name not in only: continue
    try:
        e = end_at(s, n)
        t, fin = symtm.prove(m, name, s, e, rotate=True, doc=doc, max_seg=20)
        print(name, "->", fin)
        thms.append(t)
    except Exception as ex:
        print(name, "FAILED", type(ex).__name__, ex)
if not only:
    out = symtm.rules_file("Machine", "HID", thms, "Register rules of " + M + ", generated by py/gen_rules.py.")
    ns = open(os.path.join(os.path.dirname(__file__), "..", "lean", "Machine.lean")).read().split("namespace ")[1].split()[0]
    out = out.replace("HID", ns)
    open(os.path.join(os.path.dirname(__file__), "..", "lean", "Rules.lean"), "w").write(out)
