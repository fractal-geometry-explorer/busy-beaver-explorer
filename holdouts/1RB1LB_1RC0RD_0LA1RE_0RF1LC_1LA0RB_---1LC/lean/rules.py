"""Generate Rules.lean: the turn at the left end of 1RB1LB_1RC0RD_0LA1RE_0RF1LC_1LA0RB_---1LC, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(1110)^n` is n copies of 1110, R is
any tape, 0^inf blank tape.  Left of the start the tape is a block of x = 1011 words (written 1110 or 0111 depending
on where the head is), then a junction and the binary counter T (see ../README.md).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LB_1RC0RD_0LA1RE_0RF1LC_1LA0RB_---1LC"
C = "0^inf B> 0 1 0 (1011)^n 1 0 1 0 1 0 1 1 "      # a record in B, junction 1010 1011, then the counter
C1 = "0^inf B> 0 1 0 (1011)^n+1 1 0 1 0 1 0 1 1 "

RULES = [
    ("left_turn", "0^inf 0 0 (1110)^n+1 A> 1 0 1 1 R",
     "0^inf 1 1 1 (0111)^n+1 1 1 1 E> R",
     "The turn at the left end: the head in A crosses the whole block of n+1 words leftwards (12 steps a word, "
     "rewriting each 1110 as 1011 behind it), bounces off the blank tape and crosses it rightwards again in E, "
     "whatever n and whatever lies to the right.", {}),
    ("right_sweep", "0^inf B> 0 1 0 (1011)^n R",
     "0^inf 1 1 1 (0111)^n 0 B> R",
     "The other turn at the left end (the record in B): the block of n words is crossed rightwards in E.",
     {"rotate": True}),
    ("inc_even", C + "(111111)^m 1 0 1 0 R", C1 + "(101010)^m 1 1 1 1 R",
     "Two rounds increment the counter when its lowest 0 is at an even digit: m pairs of 1-digits (111111) become "
     "pairs of 0-digits (101010), the 0-digit 1010 becomes 1111, and the block gains a word; R is never read.",
     {"rotate": True}),
    ("inc_odd", C + "(111111)^m 1 1 1 1 1 0 R", C1 + "(101010)^m 1 0 1 0 1 1 R",
     "The same when the lowest 0 is at an odd digit: 1111 10 becomes 1010 11.", {"rotate": True}),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, count_first=True, max_seg=60, **kw)[0] for name, a, b, doc, kw in RULES]
    out = rules_file("Machine", "H166286", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
