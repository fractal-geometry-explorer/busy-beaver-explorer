"""Writes lean/Halt.lean: the start of the accelerated run (the tape at visit 3,040, step 27,172,911, after the
reset of visit 3,006) and the theorems that the machine halts, with the exact step.

The tape is found by a direct run that keeps its cells exactly as Lean's list simulator (TM.fsteps) does; Lean
runs the 27,172,911 steps again (`native_decide`) and compares.  The halting step N is taken from accel.py
(`python3 accel.py`: N + 1 in the bbchallenge count); Lean recomputes it with the verified run of Ladder.lean.

usage: python3 halt_lean.py > ../lean/Halt.lean
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import accel
from words import TABLE, CELLS

START_STEP = 27172911


def direct(nsteps):
    """the left cells (nearest first, down to the leftmost cell the head was on) after nsteps steps"""
    tape, pos, st, lo, hi = {}, 0, 0, 0, 0
    for _ in range(nsteps):
        w, mv, q = TABLE[st, tape.get(pos, 0)]
        tape[pos] = w
        pos += mv
        st = q
        lo = min(lo, pos); hi = max(hi, pos)
    assert st == 0 and pos == hi and pos not in tape
    return [tape.get(p, 0) for p in range(pos - 1, lo - 1, -1)]


def main():
    a = accel.start(accel.START)
    assert a.steps == START_STEP
    cells = direct(START_STEP)
    word = "".join(str(CELLS[ch][1]) + str(CELLS[ch][0]) for ch in a.R)
    s = "".join(map(str, cells))
    assert s.rstrip("0") == word.rstrip("0")
    front = "1111101110"
    assert s.startswith(front)
    tl = s[len(front):]
    runs = []
    for c in tl:
        if runs and runs[-1][0] == c:
            runs[-1][1] += 1
        else:
            runs.append([c, 1])
    b = accel.run()
    n = b.halting_step() - 1
    halt = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../halt.txt")).read().split()
    assert int(halt[halt.index("step") + 1]) == n + 1
    lines, cur = [], "  ["
    for c, k in runs:
        item = "(%s, %d), " % ("true" if c == "1" else "false", k)
        if len(cur) + len(item) > 116:
            lines.append(cur.rstrip())
            cur = "   "
        cur += item
    lines.append(cur.rstrip().rstrip(",") + "]")
    print(TEMPLATE % dict(runs="\n".join(lines), start=START_STEP, n=n, n1=n + 1, visit=accel.START,
                          ncells=len(tl)))


TEMPLATE = """import Ladder

/-!
# 1RB1LE_0LC1RE_---1LD_0RD1LA_0RF1RF_1RA0LB halts

Generated by `py/halt_lean.py`.  Three parts:

* `reach0` (`native_decide`): after %(start)d steps from blank tape (visit %(visit)d, after the last reset) the
  head is in A right of the tape `2 1` + `tl0`;
* `run0` (`native_decide`): the accelerated run of `Ladder.lean` from there returns `haltN`;
* `loop_sound` (kernel; `Ladder.lean`, `Hits.lean`, `Levels.lean`): what that run returns is the number of steps
  before the halt.

So the machine halts from blank tape: `haltN` steps to the halting configuration, `haltN + 1` in the bbchallenge
count.  The two `native_decide` claims trust Lean's compiler and its arbitrary-precision arithmetic; the rest is
checked by the kernel.
-/

namespace H23376

open TM

/-- Runs `(cell, length)` written out as cells. -/
def unrl : List (Bool × Nat) → List Bool
  | [] => []
  | (b, k) :: r => List.replicate k b ++ unrl r

/-- The %(ncells)d cells left of the front at step %(start)d, nearest first, as runs. -/
def tl0 : List Bool := unrl
%(runs)s

/-- The start of the accelerated run. -/
def s0 : S := ⟨.H, [], tl0, %(start)d⟩

theorem fsteps0 : fsteps %(start)d (FCfg.blank .A) = some ⟨fH ++ tl0, [], .A⟩ := by native_decide

theorem reach0 : Reach s0 := by
  have e : (⟨fH ++ tl0, [], .A⟩ : FCfg St).toCfg = s0.cfg := by
    show (⟨app (fH ++ tl0) blank, blank, .A⟩ : Config) = ⟨app fH (app tl0 blank), blank, .A⟩
    rw [app_app]
  exact (blank_reaches trans fsteps0).trans (congrArg some e)

/-- The number of steps from blank tape to the halting configuration. -/
def haltN : Nat :=
  %(n)d

theorem run0 : loop 100000 true s0 = some haltN := by native_decide

/-- The machine reaches a halting configuration after exactly `haltN` steps. -/
theorem halts_in : ∃ c, steps haltN init = some c ∧ step c = none :=
  loop_sound _ _ _ _ reach0 run0

/-- The machine halts from blank tape (at step `haltN + 1` in the bbchallenge count, which counts the halting
transition). -/
theorem halts : HaltsFromBlank :=
  let ⟨c, h, hc⟩ := halts_in
  ⟨haltN, c, h, hc⟩

/-- The bbchallenge step count of the halt. -/
theorem halt_step : haltN + 1 =
    %(n1)d := by
  decide

end H23376
"""

if __name__ == "__main__":
    main()
