"""Write the Coq (busycoq) data files of the non-halting proof of 1RB0RD_1RC0LF_1LA0LB_---1RE_1LB1RA_0LC0RA.

usage (from the repo root):
  python3 holdouts/1RB0RD_1RC0LF_1LA0LB_---1RE_1LB1RA_0LC0RA/py/coq/gen_coq.py OUTDIR      (about 6 minutes)
or, as the copy gen_H11019.py with H11019_engine.py, H11019_replay.py and H11019_cert.json next to it:
  python3 gen_H11019.py OUTDIR

The certificate is the one of the Lean replay: py/closure/cert.json (1,144 classes of round ends and the start
node) and what py/replay/gen.py finds with py/replay/engine.py (8 + 7 shift rules, 6 cycle rules each with the
number of executor moves of its proof run, the number of moves of the arrival and of one round of every class).
This script runs that generator and prints its result as Coq terms for lib/SymExecN.v, the Coq port of the
executor; everything is re-checked there by `vm_compute`.

Writes H11019_Data.v (tables; shift rules and cycle rules checked), H11019_ClassData.v (the classes, in chunks),
H11019_Chunk0.v ... (one evaluation each), H11019_Arrive.v and H11019.v (the theorem).  H11019_Classes.v is
written by hand.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

def load(prefix):
    """The replay generator and its engine: ../replay/{gen,engine}.py in the repository, or the copies
    <prefix>_replay.py and <prefix>_engine.py next to this file."""
    rp = os.path.join(HERE, '..', 'replay')
    if os.path.isdir(rp):
        sys.path.insert(0, rp)
        import gen
        import engine
        return gen, engine, False
    import importlib.util
    mods = {}
    for name, fn in (('engine', prefix + '_engine.py'), ('gen', prefix + '_replay.py')):
        spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, fn))
        mods[name] = sys.modules[name] = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mods[name])
    return mods['gen'], mods['engine'], True


G, _engine, COPY = load("H11019")
fmt = _engine.fmt

M = "H11019"
OUT = None
HEAD = "(* Generated by gen_H11019.py (holdouts/.../py/coq/gen_coq.py); do not edit by hand. *)\n\n"
IMP = "From Coq Require Import Lists.List NArith String. Import ListNotations.\n"
VM = "Proof. vm_cast_no_check (eq_refl true). Qed.\n"
NCHUNK = G.NCHUNK


def w(word):
    return "[" + "; ".join("S1" if b else "S0" for b in word) + "]"


def tmpl(ts):
    out = []
    for t in ts:
        if isinstance(t, int):
            out.append("tcell %s" % ("S1" if t else "S0"))
        elif t[0] == 'f':
            out.append("tfix %s %d" % (w(t[1]), t[2]))
        else:
            out.append("tvar %s %d %d" % (w(t[1]), t[2], t[3]))
    return "[" + ";\n   ".join(out) + "]"


def srules(tab):
    return ["mkS %s %s %d %s %s %d" % ("ABCDEF"[st], w(wd), k, w(u), w(v), c)
            for (st, wd), lst in tab.items() for k, u, v, c in lst]


def put(name, parts):
    open(os.path.join(OUT, name), "w").write("".join(parts))


def write(shR, shL, rules, ka, st, cls, ks):
    n = len(rules)
    d = [HEAD, "(** * 11019: the tables of the executor *)\n\n", IMP,
         "From BusyCoq Require Export %s_Classes.\nSet Default Goal Selector \"!\".\nLocal Open Scope N_scope.\n\n" % M]
    for name, tab, side in (("shR", shR, "right"), ("shL", shL, "left")):
        d.append("(** The shift rules to the %s: state, word, copies, carried word, word left behind, steps. *)\n" % side)
        d.append("Definition %s : list SRule :=\n  [%s].\n\n" % (name, ";\n   ".join(srules(tab))))
    d.append("Lemma shR_chk : forallb (chkR tm) shR = true.\n" + VM + "\n")
    d.append("Lemma shL_chk : forallb (chkL tm) shL = true.\n" + VM + "\n")
    d.append("(** The tables without cycle rules: what the cycle rules themselves are proved with. *)\n")
    d.append("Definition T0 : Tbl := mkT shR shL [].\n\n")
    d.append("Lemma T0_ok : TOK T0.\nProof. exact (shifts_ok tm A shR shL shR_chk shL_chk). Qed.\n\n")
    for i, r in enumerate(rules):
        d.append("(** Cycle rule %d (%d events a cycle, modulus %d): [A> %s], the counts with a variable going %s.\n"
                 "    Proved by a run of %d moves of the executor without cycle rules. *)\n"
                 % (i, r.events, r.M, fmt(r.sym(0)),
                    ", ".join("%d -> %d" % (t[2], t[3]) for t in r.tmpl if not isinstance(t, int) and t[0] == 'v'),
                    r.K))
        d.append("Definition rule%d : CRule := mkR %d\n  %s.\n\n" % (i, r.M, tmpl(r.tmpl)))
        d.append("Lemma rule%d_chk : chkRule tm A thr stratLin T0 %d rule%d = true.\n" % (i, r.K, i) + VM + "\n")
    d.append("(** The tables of the replay. *)\nDefinition T : Tbl := mkT shR shL [%s].\n\n"
             % "; ".join("rule%d" % i for i in range(n)))
    d.append("Lemma T_ok : TOK T.\nProof.\n  apply tbl_ok; [exact T0_ok|].\n")
    for i in range(n):
        d.append("  apply Forall_cons; [exact (chkRule_ok tm A thr stratLin T0 T0_ok _ _ rule%d_chk)|].\n" % i)
    d.append("  apply Forall_nil.\nQed.\n")
    put(M + "_Data.v", d)

    per = (len(cls) + NCHUNK - 1) // NCHUNK
    c_ = [HEAD, "(** * 11019: the %d classes of the closed set (py/closure/cert.json), with the length of their runs\n\n"
          "    [mkCls tail r0 m K to k c]: the round ends [node (r0 + m x) tail]; one machine step and [K] more moves\n"
          "    of the executor take them to [node (k + c x) to]. *)\n\n" % len(cls), IMP,
          "From BusyCoq Require Export %s_Classes.\nLocal Open Scope N_scope.\n\n" % M]
    for j in range(NCHUNK):
        part = list(zip(cls, ks))[j * per:(j + 1) * per]
        c_.append("Definition chunk%d : list Cls := [\n  %s].\n\n" % (j, ";\n  ".join(
            'mkCls (bits "%s") %d %d %d (bits "%s") %d %d' % (c["tail"], c["r0"], c["m"], k - 1, c["to"], c["k"], c["c"])
            for c, k in part)))
    c_.append("Definition classes : list Cls := %s.\n" % " ++ ".join("chunk%d" % j for j in range(NCHUNK)))
    put(M + "_ClassData.v", c_)
    for j in range(NCHUNK):
        put(M + "_Chunk%d.v" % j, [HEAD, IMP, "From BusyCoq Require Export %s_Data %s_ClassData.\n\n" % (M, M),
            "(** Every class of the chunk: one round with the count free ends at the announced round end, and all the\n"
            "    round ends announced are in classes of the list. *)\n"
            "Lemma chunk%d_ok : forallb (fun d => andb (clsRun T d) (covers classes d)) chunk%d = true.\n" % (j, j), VM])
    put(M + "_Arrive.v", [HEAD, "(** * 11019: the run from blank tape *)\n\n", IMP,
        "From BusyCoq Require Export %s_Data %s_ClassData.\nLocal Open Scope N_scope.\n\n" % (M, M),
        "(** The tail of the round end the run from blank tape is at when the big block first has 20000 words. *)\n",
        'Definition startTail : list sym := bits "%s".\n\n' % st["tail"],
        "(** %d moves of the executor from blank tape end at [node %d startTail]. *)\n" % (ka, st["B"]),
        "Lemma arrive_ok : arrives T %d %d startTail = true.\n" % (ka, st["B"]), VM,
        "\nLemma start_ok : inSetB classes %d startTail = true.\n" % st["B"], VM])
    put(M + ".v", ['''(** * 1RB0RD_1RC0LF_1LA0LB_---1RE_1LB1RA_0LC0RA (bbchallenge 11019) does not halt

    Generated by gen_H11019.py (the text is fixed; only the number of chunks is filled in).

    A round end is [node B T = A> 01001000 (01)^B T].  The run from blank tape reaches the round end
    [node %d startTail] ([arrive_ok]), which is in the set of round ends of the %d classes of
    [H11019_ClassData.v] ([start_ok]); and every round end of that set reaches a round end of that set in at least
    one step ([chunk0_ok], ...: one round of the verified symbolic executor of [SymExecN.v] for each class, the
    count of the big block free, and the coverage of what it announces).  All of these are evaluations by
    [vm_compute]; [nonhalt_of_closed] ([H11019_Classes.v]) turns them into the theorem through the soundness of
    the executor. *)

From Coq Require Import Lists.List NArith. Import ListNotations.
From BusyCoq Require Import %s_Arrive %s.
Set Default Goal Selector "!".

Lemma classes_ok : forallb (fun d => andb (clsRun T d) (covers classes d)) classes = true.
Proof.
  change (forallb (fun d => andb (clsRun T d) (covers classes d)) (%s) = true).
  rewrite !forallb_app.
%s  reflexivity.
Qed.

(** The run from blank tape reaches a round end of the set. *)
Lemma reach_set : exists B Tl, InSet classes B Tl /\\ c0 -[ tm ]->* node B Tl.
Proof.
  exists %d%%N, startTail. split; [exact (inSetB_sound _ _ _ start_ok) | exact (arrives_sound T T_ok _ _ _ arrive_ok)].
Qed.

(** Every round end of the set reaches a round end of the set, in at least one step. *)
Lemma closed_set : forall B Tl, InSet classes B Tl ->
  exists B' Tl', InSet classes B' Tl' /\\ node B Tl -[ tm ]->+ node B' Tl'.
Proof. exact (closed_of_checks T T_ok classes classes_ok). Qed.

(** The machine does not halt from blank tape. *)
Theorem nonhalt : ~ halts tm c0.
Proof. exact (nonhalt_of_closed T T_ok classes classes_ok _ _ _ arrive_ok start_ok). Qed.

Print Assumptions nonhalt.
''' % (st["B"], len(cls), M, " ".join("%s_Chunk%d" % (M, j) for j in range(NCHUNK)),
       " ++ ".join("chunk%d" % j for j in range(NCHUNK)),
       "  rewrite %s.\n" % ", ".join("chunk%d_ok" % j for j in range(NCHUNK)), st["B"])])


if __name__ == "__main__":
    OUT = sys.argv[1]
    del sys.argv[1:]
    G.write = write
    if COPY:
        G.CERT = os.path.join(HERE, "H11019_cert.json")
    G.main()
