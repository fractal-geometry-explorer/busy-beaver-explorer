"""Generate lean/Rules.lean for 1RB0RD_1RC0LF_1LA0LB_---1RE_1LB1RA_0LC0RA: one-cycle rules of its phases, proved along the symbolic run of
tools/py/bbtools/symtm.py (single steps by `rfl`, shift rules by TM.cross_r/cross_l, re-bracketing by TM.rep_rotate).

usage (from the repo root): python3 holdouts/1RB0RD_1RC0LF_1LA0LB_---1RE_1LB1RA_0LC0RA/py/rules.py > holdouts/1RB0RD_1RC0LF_1LA0LB_---1RE_1LB1RA_0LC0RA/lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RD_1RC0LF_1LA0LB_---1RE_1LB1RA_0LC0RA"
NS = next(l.split()[1] for l in open(os.path.join(HERE, "..", "lean", "Machine.lean")) if l.startswith("namespace "))

RULES = [
    ("f_left",
     "L (01)^n F> 0 R",
     "L F> 0 (01)^n R",
     "Going left, F crosses the pairs `01` of the long left block without changing them, zigzagging (8 steps per pair)."),
    ("b_right",
     "L 1 B> (101100)^n R",
     "L (010110)^n 1 B> R",
     "Going right, B crosses the words `101100` of the long right block (in its sweep phase), turning each into `010110`, zigzagging (42 steps per word)."),
    ("e_right",
     "L E> (101100)^n R",
     "L (100101)^n E> R",
     "Going right, E crosses the same words, turning each into `100101` (12 steps per word)."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
