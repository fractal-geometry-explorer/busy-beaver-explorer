"""Find the tables of the Lean replay with `engine.py` and write the generated Lean files.

usage (from the repo root):
  python3 holdouts/1RB0RD_1RC0LF_1LA0LB_---1RE_1LB1RA_0LC0RA/py/replay/gen.py [--check]      (about 6 minutes)

Input: the certificate py/closure/cert.json (1,144 classes: tail, r0, m -> to, k, c; the start node).
Two passes.  Discovery: the engine runs from blank tape to the start node and then one round from one member of
every class (x = 1000), finding shift rules (plain simulation between walls) and cycle rules (a shape seen three
times at equal distance, then a symbolic run).  Static: with the tables fixed, every cycle rule is re-proved
without cycle rules, the arrival is repeated, and every class is run with x free: it must end at the node the
certificate says.  The static pass is what Lean replays, move for move.

Writes lean/ExecData.lean (tables), lean/ClassData.lean (the classes with their move counts, in chunks),
lean/Chunk0.lean ... (one `native_decide` each), lean/Arrive.lean, lean/Replay.lean.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from engine import Engine, Rule, EV, canon, cst, prove_rule, fmt  # noqa: E402

LEAN = os.path.join(HERE, '..', '..', 'lean')
CERT = os.path.join(HERE, '..', 'closure', 'cert.json')
PRE = [0, 1, 0, 0, 1, 0, 0, 0]
NCHUNK = 8
XDISC = 1000


def node(cnt, tail):
    return PRE + [((0, 1), cnt)] + [int(c) for c in tail]


def run_to(e, target, limit):
    """Move until an event whose tape is the target (at least one move)."""
    while True:
        ev = e.ev
        e.move()
        if e.ev != ev and e.st == EV and not e.L and canon(e.toks()) == target:
            return
        assert e.moves < limit, "target not reached"


def start(e, cnt, tail):
    e.st = EV
    e.R = list(reversed(node(cnt, tail)))


def main():
    cert = json.load(open(CERT))
    cls = cert["classes"]
    st = cert["start"]
    log = lambda *a: (print(*a), sys.stdout.flush())
    # discovery
    e = Engine(discover=True)
    run_to(e, canon(node(cst(st["B"]), st["tail"])), 10 ** 7)
    assert e.ev == st["event"]
    shR, shL, rules0 = e.shiftR, e.shiftL, e.rules
    for i, c in enumerate(cls):
        d = Engine(shR, shL, rules0, True)
        start(d, cst(c["r0"] + c["m"] * XDISC), c["tail"])
        run_to(d, canon(node(cst(c["k"] + c["c"] * XDISC), c["to"])), 3 * 10 ** 6)
        if i % 200 == 0:
            log("discovery: class %d, %d cycle rules" % (i, len(rules0)))
    # static
    rules = []
    for r in rules0:
        q = Rule(r.M, r.tmpl, r.events)
        assert prove_rule(q, shR, shL, False)
        assert all(isinstance(t, int) or t[0] == 'f' or (t[2] - t[3]) % q.M == 0 for t in q.tmpl)
        rules.append(q)
    a = Engine(shR, shL, rules, False)
    run_to(a, canon(node(cst(st["B"]), st["tail"])), 10 ** 7)
    assert a.ev == st["event"]
    ks = []
    for i, c in enumerate(cls):
        assert c["kind"] == "node" and c["r0"] % c["m"] == c["r"] and c["m"] > 0
        s = Engine(shR, shL, rules, False)
        start(s, (c["r0"], (c["m"],)), c["tail"])
        run_to(s, canon(node((c["k"], (c["c"],)), c["to"])), 3 * 10 ** 6)
        ks.append(s.moves)
        if i % 200 == 0:
            log("static: class %d" % i)
    log("shift rules: %d right, %d left; cycle rules: %d (moduli %s, proof runs of %s moves)"
        % (sum(map(len, shR.values())), sum(map(len, shL.values())), len(rules), [r.M for r in rules],
           [r.K for r in rules]))
    log("arrival: %d moves (event %d); classes: %d, %d moves in all, longest %d"
        % (a.moves, a.ev, len(cls), sum(ks), max(ks)))
    if '--check' not in sys.argv:
        write(shR, shL, rules, a.moves, st, cls, ks)
        log("written: lean/ExecData.lean, ClassData.lean, Chunk*.lean, Arrive.lean, Replay.lean")


# ---------------------------------------------------------------- Lean text
def lb(w):
    return "[" + ", ".join("true" if b else "false" for b in w) + "]"


def ltmpl(tmpl):
    out = []
    for t in tmpl:
        if isinstance(t, int):
            out.append(".cell %s" % ("true" if t else "false"))
        elif t[0] == 'f':
            out.append(".fix %s %d" % (lb(t[1]), t[2]))
        else:
            out.append(".var %s %d %d" % (lb(t[1]), t[2], t[3]))
    return "[" + ",\n    ".join(out) + "]"


def srules(tab):
    out = []
    for (st, w), lst in tab.items():
        for k, u, v, c in lst:
            out.append("⟨.%s, %s, %d, %s, %s, %d⟩" % ("ABCDEF"[st], lb(w), k, lb(u), lb(v), c))
    return out


HEAD = "/-! Generated by `py/replay/gen.py`; do not edit by hand. -/\n\nnamespace H11019\n\nopen TM\n\n"


def put(name, parts):
    open(os.path.join(LEAN, name), "w").write("".join(parts))


def write(shR, shL, rules, ka, st, cls, ks):
    o = ["import Exec\n\n", HEAD]
    for name, ok, tab in (("shR", "OKR", shR), ("shL", "OKL", shL)):
        rs = srules(tab)
        for i, r in enumerate(rs):
            o.append("def %s%d : SRule := %s\n" % (name, i, r))
            o.append("theorem %s%d_ok : %s%d.%s := fun _ _ => rfl\n" % (name, i, name, i, ok))
        o.append("\n/-- The shift rules to the %s. -/\ndef %sTbl : List SRule := [%s]\n\n"
                 % ("right" if name == "shR" else "left", name, ", ".join("%s%d" % (name, i) for i in range(len(rs)))))
        o.append("theorem %sTbl_ok : ∀ r ∈ %sTbl, r.%s := by\n  intro r hr\n" % (name, name, ok))
        o.append("  simp only [%sTbl, List.mem_cons, List.mem_nil_iff, or_false] at hr\n" % name)
        o.append("  rcases hr with %s\n" % " | ".join(["rfl"] * len(rs)))
        for i in range(len(rs)):
            o.append("  · exact %s%d_ok\n" % (name, i))
        o.append("\n")
    o.append("/-- The tables without cycle rules: what the cycle rules themselves are proved with. -/\n")
    o.append("def T0 : Tbl := ⟨shRTbl, shLTbl, []⟩\n\n")
    o.append("theorem T0_ok : T0.OK := ⟨shRTbl_ok, shLTbl_ok, fun _ h => absurd h List.not_mem_nil⟩\n\n")
    for i, r in enumerate(rules):
        o.append("/-- Cycle rule %d (%d events a cycle, modulus %d): `A> %s`, the counts with a variable going %s. -/\n"
                 % (i, r.events, r.M, fmt(r.sym(0)),
                    ", ".join("%d -> %d" % (t[2], t[3]) for t in r.tmpl if not isinstance(t, int) and t[0] == 'v')))
        o.append("def rule%d : CRule := ⟨%d,\n   %s⟩\n\n" % (i, r.M, ltmpl(r.tmpl)))
        o.append("theorem rule%d_ok : RuleOK rule%d := ruleOK_of_run T0_ok %d (by native_decide)\n\n" % (i, i, r.K))
    n = len(rules)
    o.append("/-- The tables of the replay. -/\ndef T : Tbl := ⟨shRTbl, shLTbl, [%s]⟩\n\n"
             % ", ".join("rule%d" % i for i in range(n)))
    o.append("theorem T_ok : T.OK := by\n  refine ⟨shRTbl_ok, shLTbl_ok, ?_⟩\n  intro t ht\n")
    o.append("  simp only [T, List.mem_cons, List.mem_nil_iff, or_false] at ht\n")
    o.append("  rcases ht with %s\n" % " | ".join(["rfl"] * n))
    for i in range(n):
        o.append("  · exact ⟨rule%d_ok, by decide⟩\n" % i)
    o.append("\nend H11019\n")
    put("ExecData.lean", o)

    per = (len(cls) + NCHUNK - 1) // NCHUNK
    d = ["import Classes\n\n", HEAD]
    for j in range(NCHUNK):
        part = list(zip(cls, ks))[j * per:(j + 1) * per]
        d.append("def chunk%d : List Cls := [\n  %s]\n\n" % (j, ",\n  ".join(
            '⟨bits "%s", %d, %d, %d, bits "%s", %d, %d⟩' % (c["tail"], c["r0"], c["m"], k - 1, c["to"], c["k"], c["c"])
            for c, k in part)))
    d.append("/-- The %d classes of the closed set (`py/closure/cert.json`), with the length of their runs. -/\n" % len(cls))
    d.append("def classes : List Cls := %s%s\n\nend H11019\n"
             % (" ++ (".join("chunk%d" % j for j in range(NCHUNK)), ")" * (NCHUNK - 1)))
    put("ClassData.lean", d)
    for j in range(NCHUNK):
        put("Chunk%d.lean" % j, ["import ExecData\nimport ClassData\n\n", HEAD,
            "/-- Every class of the chunk: one round with the count free ends at the announced round end, and all the\n"
            "round ends announced are in classes of the list. -/\n"
            "theorem chunk%d_ok : chunk%d.all (fun c => clsRun T c && covers classes c) = true := by\n  native_decide\n\n"
            "end H11019\n" % (j, j)])
    put("Arrive.lean", ["import ExecData\nimport ClassData\n\n", HEAD,
        "/-- The tail of the round end the run from blank tape is at when the big block first has 20000 words. -/\n"
        'def startTail : List Bool := bits "%s"\n\n' % st["tail"],
        "/-- %d moves of the executor from blank tape end at `node %d startTail`. -/\n" % (ka, st["B"]),
        "theorem arrive_ok : arrives T %d %d startTail = true := by\n  native_decide\n\n" % (ka, st["B"]),
        "theorem start_ok : inSetB classes %d startTail = true := by\n  native_decide\n\nend H11019\n" % st["B"]])
    r = ["import Arrive\n" + "".join("import Chunk%d\n" % j for j in range(NCHUNK)), '''
/-!
# 1RB0RD_1RC0LF_1LA0LB_---1RE_1LB1RA_0LC0RA does not halt

Generated by `py/replay/gen.py` (the text is fixed; only the number of chunks is filled in).

The two hypotheses of `nonhalting_of_closed_set` (`Closed.lean`), for the set `InSet classes` of round ends, from
runs of the verified executor of `Exec.lean` evaluated by `native_decide`: the arrival from blank tape
(`arrive_ok`), one round with the big count free for each of the classes and the coverage of what it announces
(`chunk0_ok`, ...), through the soundness theorems `run_sound` and `closed_of_checks`.
-/

namespace H11019

open TM

theorem classes_ok : ∀ c ∈ classes, (clsRun T c && covers classes c) = true := by
  intro c hc
  simp only [classes, List.mem_append] at hc
  rcases hc with %s
%s
/-- The run from blank tape reaches a round end of the set. -/
theorem reach_set : ∃ n B Tl, InSet classes B Tl ∧ steps n init = some (node B Tl) := by
  obtain ⟨n, hn⟩ := arrives_sound T_ok arrive_ok
  exact ⟨n, _, _, inSetB_sound start_ok, hn⟩

/-- Every round end of the set reaches a round end of the set, in at least one step. -/
theorem closed_set : ∀ B Tl, InSet classes B Tl →
    ∃ n B' T', 0 < n ∧ InSet classes B' T' ∧ steps n (node B Tl) = some (node B' T') :=
  closed_of_checks T_ok classes_ok

/-- **The machine does not halt from blank tape.** -/
theorem nonhalt : ¬ HaltsFromBlank := nonhalting_of_closed_set (InSet classes) reach_set closed_set

end H11019
''' % (" | ".join(["hc"] * NCHUNK) if NCHUNK > 1 else "hc",
       "".join("  · exact List.all_eq_true.1 chunk%d_ok c hc\n" % j for j in range(NCHUNK)))]
    put("Replay.lean", r)


if __name__ == "__main__":
    main()
