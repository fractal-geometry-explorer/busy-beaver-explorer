def index_rows(triage, known, spec_by):
    rows = []
    ext = external()
    for r in triage:
        M = r["machine"]
        k = known.get(M)
        s = spec_by.get(M, {})
        if M in STUDIED:
            status, expl = STUDIED_PAGES[STUDIED[M]]
            folder = STUDIED[M]
            studied = True
        else:
            status, expl = f"{M}/proof-status.html", f"{M}/explainer.html"
            folder = f"holdouts/{M}"
            studied = not s.get("generated", True)
        rows.append({
            "id": r["id"], "m": M, "c": r["class"], "al": r["alpha_l"], "ar": r["alpha_r"],
            "w": r["width"], "o": r["ones"], "d": r["density"], "n": k[0] if k else "",
            "k": k[1] if k else "", "x": expl, "p": status, "f": folder, "s": studied,
            "dec": s.get("decision", "open"), "sum": s.get("summary", ""), "g": s.get("group", ""),
        })
        e = ext["machines"].get(M, {})
        rows[-1].update({
            "st": standing(M, rows[-1]["dec"]), "tc": e.get("tracker", {}).get("class", ""),
            "cr": 1 if e.get("tracker", {}).get("cryptid") else 0, "coq": 1 if M in ext["coq_here"] else 0,
            "pr": [[p["n"], p["claim"]] for p in e.get("prs", [])],
        })
    return rows


