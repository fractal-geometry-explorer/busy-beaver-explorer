def specs():
    for name in sorted(os.listdir(HERE)):
        p = os.path.join(HERE, name, "status.json")
        if os.path.isfile(p):
            with open(p) as f:
                yield name, json.load(f)


def verdict_level(spec):
    """The strongest claim about halting itself: 'open' unless a claim marked decisive says otherwise."""
    return spec.get("decision", "open")


def build_machine_pages(name, spec):
    d = os.path.join(PAGES, name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "explainer.html"), "w") as f:
        f.write(build_explainer.build(spec, spec.get("home", "../index.html")))
    with open(os.path.join(d, "proof-status.html"), "w") as f:
        f.write(build_status.build(spec, spec.get("home", "../index.html")))


