def wiki_entry(M):
    """The "elsewhere" label from holdouts/known.json: the machine's wiki page, name and who first reported it."""
    k = known().get(M)
    if not k:
        return None
    name, desc, meta = (k + [{}])[:3]
    if meta.get("page"):
        where = f"The bbchallenge wiki's page {wiki_link(meta['page'])}"
        if meta.get("edited"):
            where += f" (last edited {meta['edited']})"
        text = where + (f" lists it as <b>{html.escape(name)}</b>: " if name else ": ") + html.escape(desc) + "."
    else:
        on = meta.get("mentioned_on", [])
        text = ("The bbchallenge wiki has no page for this machine; it is mentioned on the page"
                + ("s " if len(on) > 1 else " ") + ", ".join(wiki_link(x) for x in on) + ".")
    if meta.get("credit") and meta.get("page"):
        text += f" The work on it was {CREDIT.get(meta['credit'], html.escape(meta['credit']))}."
    text += " Read from an export of the wiki of 17 November 2026. These are the community's labels, not results."
    return {"kind": "label", "title": "On the bbchallenge wiki", "text": text}


def elsewhere(M, decision="open"):
    """The "elsewhere" entries of a machine: [{kind, title, text}], kind "proof" (checked here), "report" (a proof
    outside this repository that was not compiled here) or "label" (a heuristic name)."""
    ext = external()
    e = ext["machines"].get(M, {})
    out = []
    c = ext["coq_here"].get(M)
    if c:
        stmt = c.get("statement", "~ halts tm c0")
        text = (f"{'The proof' if c.get('only') else 'A second proof assistant checks the same result'}: <code>{c['theorem']} : {html.escape(stmt)}</code>, "
                f"stated on busycoq's own definitions of a Turing machine and of halting, in "
                f"<code>{html.escape(c['dir'])}</code>. Coq {c.get('coq', '8.18')} compiles it and "
                "<code>Print Assumptions</code> reports no axioms; the build log is next to the files.")
        if c.get("note"):
            text += " " + c["note"]
        if c.get("shorter"):
            text += (f" A shorter proof of the same theorem ({c['shorter']}) is on a branch of our fork of busycoq, "
                     f"ready to be proposed upstream: "
                     f"<a href=\"{c['branch']}\">{html.escape(c['branch'].rsplit('/', 1)[1])}</a>.")
        elif c.get("branch"):
            text += (f" The same files are on a branch of our fork of busycoq, ready to be proposed upstream: "
                     f"<a href=\"{c['branch']}\">{html.escape(c['branch'].rsplit('/', 1)[1])}</a>.")
        out.append({"kind": "proof", "title": "Proved in Coq" if c.get("only") else "Also proved in Coq", "text": text})
    if e.get("merged"):
        g = e["merged"]
        out.append({"kind": "report", "title": f"Proved outside this repository: it {CLAIM[g['claim']]}",
                    "text": f"A Rocq proof that this machine {CLAIM[g['claim']]} is merged in {g['where']} "
                            f"(<a href=\"{ext['busycoq']}\">ccz181078/busycoq</a>, commit <code>{g['commit']}</code>, "
                            f"{g['date']}), and the community's list of holdouts no longer includes it. It was not "
                            "compiled here, so the ledger below, which holds only what this repository checked, still "
                            "lists halting as open."})
    for pr in e.get("prs", []):
        meta = ext["prs"][str(pr["n"])]
        dmc = e.get("deepmind", {}).get("compiled") and e["deepmind"]["kind"] == decision
        same = (" It agrees with the verdict on this page, which rests on DeepMind's Lean proof." if dmc and decision == pr["claim"] else
                " It agrees with the proof here." if decision == pr["claim"] else
                " The verdict on this page does not rely on it." if decision == "open" else
                " <b>It disagrees with the result here.</b>")
        c = pr.get("compiled")
        if c:
            ax = ("<code>Print Assumptions</code> reports no axioms" if not c.get("axioms") else
                  "it rests only on " + ", ".join(html.escape(a) if " " in a else f"<code>{html.escape(a)}</code>" for a in c["axioms"]))
            out.append({"kind": "proof", "title": f"An outside Rocq proof, compiled here: it {CLAIM[pr['claim']]}",
                        "text": f"<a href=\"{ext['busycoq']}/pull/{pr['n']}\">busycoq pull request {pr['n']}</a> "
                                f"({html.escape(meta['author'])}, {meta['date']}) contains a Rocq proof that this machine "
                                f"{CLAIM[pr['claim']]} (<code>{html.escape(pr['file'])}</code>). The pull request is open: "
                                "not merged and not reviewed by the maintainer. We compiled the file on busycoq's BB6 branch "
                                f"(commit <code>{c['base']}</code>) with Coq {c['coq']} on {c['date']}, in {c['seconds']} s: "
                                f"the theorem <code>{html.escape(c['theorem'])}</code> is stated on busycoq's own definitions "
                                f"of a machine and of halting, {ax}, and the file's transition table is this machine. "
                                + (html.escape(c["note"]) + " " if c.get("note") else "") +
                                "It is their proof, not one written in this repository. " +
                                ("The verdict on this page rests on this proof." if decision == pr["claim"] and not dmc
                                 else same.strip())})
            continue
        out.append({"kind": "report", "title": f"An outside proof is waiting for review: it {CLAIM[pr['claim']]}",
                    "text": f"<a href=\"{ext['busycoq']}/pull/{pr['n']}\">busycoq pull request {pr['n']}</a> "
                            f"({html.escape(meta['author'])}, {meta['date']}) contains a Rocq proof that this machine "
                            f"{CLAIM[pr['claim']]} (<code>{html.escape(pr['file'])}</code>). As of {ext['asof']} it "
                            "was open: not merged, not reviewed by the maintainer, and not compiled here unless the "
                            f"ledger below says so.{same}" +
                            (f" Partly checked here on {pr['spot_checked']['date']} with Coq {pr['spot_checked']['coq']}: "
                             + html.escape(pr['spot_checked']['what']) if pr.get("spot_checked") else "")})
    w = e.get("wiki_solved")
    if w:
        out.append({"kind": "report", "title": f"Reported on the wiki: it {CLAIM[w['claim']]}",
                    "text": f"The bbchallenge wiki lists this machine as proved to {'halt' if w['claim'] == 'halts' else 'never halt'} "
                            f"by {html.escape(w['by'])} ({w['date']}). That proof is the one in busycoq pull request 60; "
                            "it was not compiled here."})
    if e.get("deepmind"):
        out.append(deepmind_entry(M, e["deepmind"], decision))
    k = wiki_entry(M)
    if k:
        out.append(k)
    t = e.get("tracker")
    if t:
        cls = f"the machine's class is <b>{html.escape(t['class'])}</b>" if t.get("class") else "the machine has no class"
        cry = (" Its 3 November 2026 edition lists the machine as a <b>cryptid</b>: its halting is thought to come "
               "down to a Collatz-like question that no known method decides." if t.get("cryptid") else "")
        out.append({"kind": "label", "title": "Community label",
                    "text": f"In the community's BB(6) tracker {cls}.{cry} These are labels read off the run by "
                            "others, not results."})
    return out


STANDING = {
    "open": ("Open", "Nobody has proved whether this machine halts. Everything below is what is known so far."),
    "cryptid": ("Open: a cryptid", "Its halting is thought to come down to a Collatz-like question that no known "
                "method decides (the community's label, not a result)."),
}
RELATION = {"run": "the same run from another table", "slow": "a slowed-down copy", "tapes": "the same tapes at another pace",
            "table": "the same table, another start"}
_RELATED = None


def compare(M):
    """The related machines of M for the side-by-side section: [{machine, relation, mirror}], at most 8."""
    global _RELATED
    if _RELATED is None:
        import related
        _RELATED = related.data()[1]
    out, seen = [], set()
    for kind, rec, i in _RELATED.get(M, []):
        if kind == "table":
            other = rec["to"] if i == 0 else rec["from"]
        elif kind == "slow":
            other = rec["fast"] if i == 0 else rec["slow"]
        else:
            other = rec["machines"][1 - i]
        if other in seen or other == M:
            continue
        seen.add(other)
        out.append({"machine": other, "relation": RELATION[kind], "mirror": bool(rec.get("mirror", False))})
    return out[:8]


def standing_line(M, decision, level="lean"):
    """{kind, label, text}: the one line under a page's title."""
    kind = standing(M, decision, level)
    e = external()["machines"].get(M, {})
    if kind == "here" and level == "coq":
        return {"kind": kind, "label": f"Decided: it {CLAIM[decision]}",
                "text": "Proved in this repository, checked by Coq on busycoq's own definitions of a machine and of "
                        "halting (there is no Lean proof of the whole run). The ledger below says what each part rests on."}
    if kind == "here":
        both = " and by Coq" if M in external()["coq_here"] else ""
        return {"kind": kind, "label": f"Decided: it {CLAIM[decision]}",
                "text": f"Proved in this repository, checked by Lean{both}. The ledger below says what each part rests on."}
    if kind == "outside" and outside_by(M, decision) == "rocq":
        ps = [p for p in e.get("prs", []) if p.get("compiled") and p["claim"] == decision]
        n = [p["n"] for p in ps]
        axl = ps[0]["compiled"].get("axioms") or []
        ax = ("with no axioms beyond Coq's own" if not axl else
              "with no axioms beyond functional extensionality from Coq's standard library"
              if all("xtensionality" in a for a in axl) else
              "with no axioms beyond the standard ones for Coq's machine integers (PrimInt63)")
        return {"kind": "merged", "label": f"Decided by an outside Rocq proof: it {CLAIM[decision]}",
                "text": f"A Rocq proof in busycoq pull request {n[0]} (open, not yet reviewed by the maintainer) was "
                        f"compiled here, on busycoq's own definitions, {ax}. It is their proof, "
                        "not one written in this repository; the ledger below says what this repository checked on its own."}
    if kind == "outside":
        k = CLAIM[e["deepmind"]["kind"]]
        return {"kind": "merged", "label": f"Decided by an outside Lean proof: it {k}",
                "text": "DeepMind's cryptids repository proves it in Lean, and the proof was compiled here with only the "
                        "standard axioms. It is their proof, on their definitions, not one written in this repository; "
                        "the ledger below says what this repository checked on its own."}
    if kind == "computed":
        return {"kind": kind, "label": f"Computed, not proved: it {CLAIM[decision]}",
                "text": "An exact accelerated computation in this repository finds this. It is not a Lean proof of "
                        "the whole run; the ledger below says what each part rests on."}
    if kind == "merged":
        return {"kind": kind, "label": f"Proved elsewhere: it {CLAIM[e['merged']['claim']]}",
                "text": "A Rocq proof is merged in busycoq. It was not compiled here, so this page's own ledger still "
                        "treats halting as open."}
    if kind == "pr":
        claims = sorted({CLAIM[p["claim"]] for p in e["prs"]})
        dm = e.get("deepmind", {}).get("kind") in CLAIM
        dmc = bool(e.get("deepmind", {}).get("compiled"))
        return {"kind": kind, "label": "Open here; an outside proof awaits review",
                "text": f"A Rocq proof that it {' / '.join(claims)} is in an open busycoq pull request, not merged "
                        "and not compiled here" + (("; DeepMind's cryptids repository has a Lean proof of the same, " +
                                                    ("compiled here" if dmc else "also not compiled here")) if dm else "") +
                        ". This page's own ledger treats halting as open."}
    label, text = STANDING[kind]
    return {"kind": kind, "label": label, "text": text}


def page_spec(spec):
    """The spec a machine's pages are built from: its status.json plus the standing line, the "elsewhere" box and
    the related machines to draw side by side."""
    M, dec = spec["machine"], spec.get("decision", "open")
    out = dict(spec, standing=standing_line(M, dec, spec.get("decision_level", "lean")))
    e = elsewhere(M, dec)
    if e:
        out["elsewhere"] = e
    c = compare(M)
    if c:
        out["compare"] = c
    return out


def outside_by(M, decision):
    """Which outside proof an "outside" verdict rests on: "lean" (DeepMind's Lean file, compiled here), "rocq" (a Rocq
    proof in an open busycoq pull request, compiled here) or "" (none)."""
    e = external()["machines"].get(M, {})
    dm = e.get("deepmind", {})
    if dm.get("compiled") and dm.get("kind") == decision:
        return "lean"
    if any(p.get("compiled") and p["claim"] == decision for p in e.get("prs", [])):
        return "rocq"
    return ""


def standing(M, decision, level="lean"):
    """One word for the index: here (decided in this repository by a Lean proof), computed (a verdict from a trusted
    computation, "decision_level": "trusted" in status.json, not a Lean proof), outside (an outside Lean proof compiled
    here, "decision_level": "outside"; "coq" for a proof here in Coq only), merged, pr, cryptid or open."""
    e = external()["machines"].get(M, {})
    if decision != "open":
        return {"trusted": "computed", "outside": "outside"}.get(level, "here")
    if e.get("merged"):
        return "merged"
    if e.get("prs"):
        return "pr"
    if e.get("tracker", {}).get("cryptid"):
        return "cryptid"
    return "open"


def verdict_level(spec):
    """The strongest claim about halting itself: 'open' unless a claim marked decisive says otherwise."""
    return spec.get("decision", "open")


def build_machine_pages(name, spec):
    spec = page_spec(spec)
    d = os.path.join(PAGES, name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "explainer.html"), "w") as f:
        f.write(build_explainer.build(spec, spec.get("home", "../index.html")))
    with open(os.path.join(d, "proof-status.html"), "w") as f:
        f.write(build_status.build(spec, spec.get("home", "../index.html")))


