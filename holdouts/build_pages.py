"""Build the pages of the holdouts: one explainer and one proof-status page per machine, and the index.

usage: python3 holdouts/build_pages.py [--index-only] [MACHINE ...]     (machines given: only their pages, and the index)

Every holdouts/M/status.json (generated by gen.py or edited by hand) gives pages/holdouts/M/explainer.html and
proof-status.html; holdouts/triage.json, holdouts/known.json and each status.json's "summary" (optional, a short
text for the index) give pages/holdouts/index.html, a filterable map of all 608 machines.

holdouts/external.json holds what is known from outside a machine's own ledger: Rocq proofs in open busycoq pull
requests, a proof merged upstream, the community tracker's class and cryptid label, and the Coq proofs kept in this
repository. `page_spec` adds it to a machine's spec as "elsewhere", a box on both of its pages, and the index shows
it as the machine's standing. It lives in one file so that updating it never touches a machine folder.
"""
