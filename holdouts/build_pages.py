def build_index():
    with open(os.path.join(HERE, "triage.json")) as f:
        triage = json.load(f)
    with open(os.path.join(HERE, "known.json")) as f:
        known = {k: v for k, v in json.load(f).items() if not k.startswith("_")}
    spec_by = {s["machine"]: s for _, s in specs()}
    rows = index_rows(triage, known, spec_by)
    data = json.dumps(rows, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    os.makedirs(PAGES, exist_ok=True)
    with open(os.path.join(PAGES, "index.html"), "w") as f:
        f.write(INDEX.replace("__N__", str(len(rows))).replace("__DATA__", data))


def main(argv):
    want = {a for a in argv if not a.startswith("--")}
    if "--index-only" not in argv:
        for name, spec in specs():
            if not want or name in want:
                build_machine_pages(name, spec)
    build_index()


if __name__ == "__main__":
    main(sys.argv[1:])
