"""Writes lean/Rules.lean: the left-going pass of 1RB0RB_1LC1RA_0LF0LD_1LE1RB_1RA1LC_---1LA and the ways it can end,
proved from the symbolic trace by bbtools.symtm.  Run from the machine folder: python3 py/gen_rules.py > lean/Rules.lean"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB0RB_1LC1RA_0LF0LD_1LE1RB_1RA1LC_---1LA"
RULES = [
    ("halt_e", "L 0 0 E> 1 R", "L F> 0 0 1 R",
     "E on a 1 with `0 0` to its left halts two steps later (F reads 0)."),
    ("halt_a", "L 0 A> 1 0 R", "L F> 0 0 1 R",
     "So does A on `1 0` with a 0 to its left (this pattern does not occur after the start)."),
    ("sweep_d", "L A> (11)^n R", "L (01)^n A> R",
     "The right sweep: A crosses `11` pairs, turning each into `01`."),
    ("sweep_b", "L A> (01)^n R", "L (11)^n A> R",
     "...and `01` pairs into `11`."),
    ("c_run", "L 0 (1)^n C> 1 R", "L D> 0 0 (1)^n R",
     "The left pass over a block: C, B, C, D... walk left one cell per three steps; `0 1^(n+1)` with C on its "
     "right end becomes `0 0 1^n` with D on the first 0."),
    ("c_shift", "L 0 (1)^k 1 1 0 (1)^n C> 1 R", "L D> 0 0 (1)^k 1 1 0 (1)^n R",
     "A block of length k+2 >= 2 left of the pass is shifted one cell right and the pass goes on into the next "
     "separator."),
    ("c_stop", "L 1 0 1 0 (1)^n C> 1 R", "L F> 1 0 1 1 0 (1)^n R",
     "A block of length 1 stops the pass: it grows to `1 1` and F turns the head around on the 1 left of it."),
    ("c_halt", "0^inf 1 0 (1)^n C> 1 R", "0^inf F> 0 0 1 1 0 (1)^n R",
     "If that block of length 1 is the leftmost block of the tape, F reads 0: the machine halts."),
    ("c_lead", "0^inf (1)^n C> 1 R", "0^inf 1 1 1 1 A> (1)^n R",
     "A pass that runs into the leftmost block (of any length n+1) turns right and the tape grows on the left."),
]

thms = []
for name, s, e, doc in RULES:
    t, _ = prove(M, name, s, e, doc=doc)
    thms.append(t)
doc = """# The left-going pass

Generated by `py/gen_rules.py` with `bbtools.symtm.prove`: every theorem is a run of the machine for all values of
the variables and every tape `L`, `R`, proved by `rfl` steps and the shift rules `cross_l`, `cross_r`.
Left tapes are written nearest the head first, so `(10)^k` on the page is `rep k [false, true]` here."""
print(rules_file("Machine", "H157503", thms, doc), end="")
