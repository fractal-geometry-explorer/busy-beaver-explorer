"""Writes lean/Rules.lean: the left-going pass of 1RB0RB_1LC1RA_0LE1LD_0RE1LF_---1LA_1LD0LC and the ways it can end,
proved from the symbolic trace by bbtools.symtm.  Run from the machine folder: python3 py/gen_rules.py > lean/Rules.lean"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB0RB_1LC1RA_0LE1LD_0RE1LF_---1LA_1LD0LC"
RULES = [
    ("halt_c", "L 0 C> 0 R", "L E> 0 0 R",
     "C on a 0 with a 0 to its left: E reads 0, the halting transition."),
    ("halt_d", "L D> 0 0 R", "L 0 E> 0 R",
     "D on `0 0`: E reads 0."),
    ("sweep_d", "L A> (11)^n R", "L (01)^n A> R",
     "The right sweep: A crosses `11` pairs, turning each into `01`."),
    ("sweep_b", "L A> (01)^n R", "L (11)^n A> R",
     "...and `01` pairs into `11`."),
    ("pass", "L (111)^n C> 1 R", "L C> 1 (011)^n R",
     "The left pass: C, D, F walk left through 1s, writing a 0 every third cell."),
    ("stop_1", "L 0 (111)^n C> 1 R", "L 1 1 A> (011)^n R",
     "A block of length 3n+1 stops the pass: the head turns right (and the separator left of the block becomes 1)."),
    ("cont_2", "L 1 0 1 (111)^n C> 1 R", "L D> 1 1 1 1 (011)^n R",
     "A block of length 3n+2 does not stop it: the pass goes on into the block to the left, in state D."),
    ("stop_3", "L 1 0 1 1 (111)^n C> 1 R", "L E> 1 0 0 1 1 (011)^n R",
     "A block of length 3n+3 with a 1 left of its separator: C reads the separator, E the 1, and the pass ends (A next)."),
    ("halt_3", "L 0 0 1 1 (111)^n C> 1 R", "L E> 0 0 0 1 1 (011)^n R",
     "...but with `0 0` left of it (the leftmost block of the tape) E reads 0: the machine halts."),
]

thms = []
for name, s, e, doc in RULES:
    t, _ = prove(M, name, s, e, doc=doc)
    thms.append(t)
doc = """# The left-going pass

Generated by `py/gen_rules.py` with `bbtools.symtm.prove`: every theorem is a run of the machine for all values of
the variables and every tape `L`, `R`, proved by `rfl` steps and the shift rules `cross_l`, `cross_r`.
Left tapes are written nearest the head first, so `(10)^k` on the page is `rep k [false, true]` here."""
print(rules_file("Machine", "H157319", thms, doc), end="")
