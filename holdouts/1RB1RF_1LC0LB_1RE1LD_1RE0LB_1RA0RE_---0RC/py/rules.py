"""Writes lean/Rules.lean: the shift rule of the two sweeps across the long block of 1RB1RF_1LC0LB_1RE1LD_1RE0LB_1RA0RE_---0RC,
proved by bbtools.symtm from a symbolic trace (shift rules, `rfl`, `omega`).  

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove

M = "1RB1RF_1LC0LB_1RE1LD_1RE0LB_1RA0RE_---0RC"
NS = "H154101"
RULES = [
    ("back", "The sweep back from the right end across the long block: `L (1011)^n 1 0 C> 0^inf` becomes "
     "`L C> 1 (1001)^n 1 0 0 1 1 0^inf` in 4n+8 steps (the head reaches the counter region L).",
     "L (1011)^n 1 0 C> 0^inf", "L C> 1 (1001)^n 1 0 0 1 1 0^inf"),
    ("forth", "The sweep out again: `L 1 F> (1001)^n 10011 0^inf` becomes `L 1 (0111)^n 01110 C> 0^inf`, that is "
     "`L (1011)^(n+1) 110 C> 0^inf`, in 4n+5 steps.",
     "L 1 F> (1001)^n 1 0 0 1 1 0^inf", "L 1 (0111)^n 0 1 1 1 0 C> 0^inf"),
]


def main():
    out = ["import Machine", "", f"/-! Rules of {M}, generated by `py/rules.py`; do not edit by hand. -/", "",
           f"namespace {NS}", "", "open TM", ""]
    for name, doc, start, end in RULES:
        t, f = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=60)
        out += [t, ""]
    out.append(f"end {NS}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
