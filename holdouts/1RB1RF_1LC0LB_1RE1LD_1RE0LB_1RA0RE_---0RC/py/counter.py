"""The counter of 1RB1RF_1LC0LB_1RE1LD_1RE0LB_1RA0RE_---0RC, as words, and Lean proofs of its steps (bbtools.symtm).

At the moments the head stands in state C on the blank cell right of the tape (a *visit*), the tape is, left to right,

    0^inf  [1]  U(b_top) ... U(b_1)  b_0 0 1  M(t)  I(i)  1 (0111)^m 0  C>0

* U(b) = b 0 1 1 0 1 is one binary digit of a counter V (b_top first); the leading lone 1 is there in phase B and
  absent in phase A, where the top digit is always 1;
* M(t) is a fixed 45-cell word with one bit t (cell 11): `MA[t]` below;
* I(i) = U(i2) U(i1) i0 0 1 is a 3-bit counter of the visits (`I(i)` below);
* 1 (0111)^m 0 = (1011)^m 1 0 is the long block, one copy longer at every visit.

A visit with i < 7 (*shallow*) only adds 1 to i.  A visit with i = 7 (*deep*) sets i = 0, flips t and adds 39
(t = 0) or 42 (t = 1) to V.  When V overflows, phase A becomes phase B (same number of digits) and phase B becomes
phase A one digit wider, after a short transient (see README).  Each sweep is: `back` across the block (lean/Rules.lean),
a *middle* part that never touches the block, `forth` across the block.  This file proves the middle parts with
symtm: every shallow one, and every deep one that does not reach the left end, for all lengths of the run of 1-digits
that the carry crosses (the theorems quantify over the tape L left of the first 0-digit and R right of the head).

usage: python3 counter.py lean > ../lean/Counter.lean      the Lean file
       python3 counter.py check                            the symbolic runs, with the predicted results
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools import symtm
from bbtools.machine import Machine

MS = "1RB1RF_1LC0LB_1RE1LD_1RE0LB_1RA0RE_---0RC"
NS = "H154101"
M = Machine.parse(MS)
MA = {0: "110110111010011101110111011011101110111011101", 1: "110110111011011101110111011011101110111011101"}
ADD = {0: 39, 1: 42}


def sp(s):
    return " ".join(s)


def U(b):
    return f"{b} 0 1 1 0 1"


def I(i):
    return f"{(i >> 2) & 1} 0 1 1 0 1 {(i >> 1) & 1} 0 1 1 0 1 {i & 1} 0 1"


def low(lo):
    """the five low digits of V, b_4 .. b_0 (b_0 is the short digit b_0 0 1)"""
    bits = [(lo >> j) & 1 for j in range(4, -1, -1)]
    return " ".join(U(b) for b in bits[:4]) + f" {bits[4]} 0 1"


def stop_F(c):
    return c.state == 5 and isinstance(c.right[0], symtm.Ctx) and not c.steps.is_zero()


def middle_cases():
    """(name, doc, start, predicted end) of every middle part proved here."""
    out = []
    for i in range(7):
        out.append((f"shallow{i}", f"A shallow visit, inner counter {i} -> {i + 1}: the head turns inside I (and the "
                    f"last 6 cells of M).", f"L 0 1 1 1 0 1 {I(i)} C> 1 R", f"L 0 1 1 1 0 1 {I(i + 1)} 1 F> R"))
    for t in (0, 1):
        c = ADD[t] - 32
        for lo in range(32):
            s = lo + c
            lo2, car = s % 32, s >= 32
            for b5 in ((0, 1) if car else (None,)):
                m5 = (U(b5) + " ") if b5 is not None else ""
                tag = f"{t}_{lo}" + (f"_{b5}" if b5 is not None else "")
                for j in ("0", "k+1"):
                    ones = f"(101101)^{j} " if j != "0" else ""
                    zeros = f"(001101)^{j} " if j != "0" else ""
                    name = f"deep_{tag}_" + ("z" if j == "0" else "s")
                    doc = (f"A deep visit with t = {t}, low digits {lo:05b}" + (f", digit 5 = {b5}" if b5 is not None else "")
                           + f": V + {ADD[t]}, the carry crossing " + ("no" if j == "0" else "k+1") + " 1-digits.")
                    out.append((name, doc, f"L 0 0 1 1 0 1 {ones}{m5}{low(lo)} {sp(MA[t])} {I(7)} C> 1 R",
                                f"L 1 0 1 1 0 1 {zeros}{m5}{low(lo2)} {sp(MA[1 - t])} {I(0)} 1 F> R"))
    return out


def inst(seq, env):
    out = []
    for t in seq:
        if isinstance(t, symtm.Rep):
            out += list(t.word) * t.n.subs(env)
        elif isinstance(t, int):
            out.append(t)
        else:
            out.append(repr(t))
    return out


def same(f, g):
    """equal as tapes for several values of the variables (the Lean proof is the real check)"""
    vs = sorted(f.vars() | g.vars())
    for vals in [(1,) * len(vs), (2,) * len(vs), tuple(range(3, 3 + len(vs))), tuple(range(5, 5 + 3 * len(vs), 3))]:
        env = dict(zip(vs, vals))
        if f.state != g.state or inst(f.left, env) != inst(g.left, env) or inst(f.right, env) != inst(g.right, env):
            return False
    return True


def lean():
    out = ["import Machine", "", f"/-! Middle parts of the visits of {MS}, generated by `py/counter.py`; do not edit "
           "by hand.  Each theorem holds for every tape `L` left of the part shown and `R` right of the head. -/", "",
           f"namespace {NS}", "", "open TM", "", "set_option maxRecDepth 100000", ""]
    for name, doc, start, end in middle_cases():
        fin = symtm.run(M, symtm.Config.parse(start), stop_F, max_moves=100000, rotate=True)
        assert same(fin, symtm.Config.parse(end)), name
        t, _ = symtm.prove(M, name, start, fin, doc=doc, rotate=True, count_first=True, max_seg=60)
        out += [t]
    out.append(f"end {NS}")
    return "\n".join(out) + "\n"


def check():
    bad = 0
    for name, doc, start, end in middle_cases():
        fin = symtm.run(M, symtm.Config.parse(start), stop_F, max_moves=100000, rotate=True)
        ok = same(fin, symtm.Config.parse(end))
        bad += not ok
        print(name, fin.steps, "ok" if ok else "DIFFERS")
    print("all as predicted" if not bad else f"{bad} differ")


if __name__ == "__main__":
    {"lean": lambda: sys.stdout.write(lean()), "check": check}[sys.argv[1]]()
