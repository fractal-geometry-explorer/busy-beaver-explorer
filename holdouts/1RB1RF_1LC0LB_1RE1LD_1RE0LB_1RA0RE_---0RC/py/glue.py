"""The rest of the Lean proof of 1RB1RF_1LC0LB_1RE1LD_1RE0LB_1RA0RE_---0RC: the A-overflow middles, and the glue that
turns the middle parts into one step of the visit dynamics.

usage: python3 glue.py overflow > ../lean/Overflow.lean   the A-overflow middles (bbtools.symtm), 81 theorems
       python3 glue.py transients                         every B-overflow, run symbolically up to its exit visit
       python3 glue.py steps > ../lean/Steps.lean         every visit of a steady configuration (see lean/Visit.lean)
       python3 glue.py check                              the A-overflow middles against the rule (symbolic runs)

An *A-overflow* is a deep visit in phase A whose carry runs through all digits to the blank tape on the left:

    0^inf (U(1))^(k+1) [U(b5)] low(lo) M(t) I(7) C> 1 R   ->   0^inf 1 (U(0))^(k+1) [U(b5)] low(lo') M(1-t) I(0) 1 F> R

(phase B, same width, V + c - 2^w).  `Steps.lean` states every visit of the `Steady` configurations of
`lean/Visit.lean` (shallow, deep without overflow, A-overflow) as one theorem each, from the theorems of
`Counter.lean` and `Overflow.lean`, and dispatches on the digits: `steady_step`.
"""
import os
import re
import sys

import counter as C
from bbtools import symtm

HERE = os.path.dirname(os.path.abspath(__file__))
B = {0: "false", 1: "true"}


def bits(lo):
    return [(lo >> j) & 1 for j in range(5)]          # b0 .. b4


def ov_cases():
    out = []
    for t in (0, 1):
        c = C.ADD[t] - 32
        for lo in range(32):
            s = lo + c
            lo2, car = s % 32, s >= 32
            for b5 in ((0, 1) if car else (None,)):
                m5 = (C.U(b5) + " ") if b5 is not None else ""
                tag = f"{t}_{lo}" + (f"_{b5}" if b5 is not None else "")
                doc = (f"An A-overflow with t = {t}, low digits {lo:05b}" + (f", digit 5 = {b5}" if b5 is not None else "")
                       + f": V + {C.ADD[t]} - 2^w, the carry crossing all k+1 higher digits to the blank tape; phase B "
                       "follows (a lone 1 in front).")
                out.append((f"ovA_{tag}", doc, f"0^inf (101101)^k+1 {m5}{C.low(lo)} {C.sp(C.MA[t])} {C.I(7)} C> 1 R",
                            f"0^inf 1 (001101)^k+1 {m5}{C.low(lo2)} {C.sp(C.MA[1 - t])} {C.I(0)} 1 F> R"))
    return out


def overflow():
    out = ["import Machine", "", "/-! A-overflow middles of 1RB1RF_1LC0LB_1RE1LD_1RE0LB_1RA0RE_---0RC, generated by "
           "`py/glue.py overflow`; do not edit by hand. -/", "", f"namespace {C.NS}", "", "open TM", "",
           "set_option maxRecDepth 100000", ""]
    for name, doc, start, end in ov_cases():
        fin = symtm.run(C.M, symtm.Config.parse(start), C.stop_F, max_moves=100000, rotate=True)
        assert C.same(fin, symtm.Config.parse(end)), name
        t, _ = symtm.prove(C.M, name, start, fin, doc=doc, rotate=True, count_first=True, max_seg=60)
        out += [t]
    out.append(f"end {C.NS}")
    return "\n".join(out) + "\n"


def check():
    bad = 0
    for name, doc, start, end in ov_cases():
        fin = symtm.run(C.M, symtm.Config.parse(start), C.stop_F, max_moves=100000, rotate=True)
        ok = C.same(fin, symtm.Config.parse(end))
        bad += not ok
        print(name, fin.steps, "ok" if ok else "DIFFERS")
    print("all as predicted" if not bad else f"{bad} differ")


def counts(path):
    """theorem name -> step count expression, read from a generated file"""
    txt = open(path).read()
    return {m.group(1): m.group(2) for m in re.finditer(r"^theorem (\S+) [^\n]*:\n    steps \(([^)]*)\)", txt, re.M)}


def ds_term(bs, b5, mid):
    """b1 :: b2 :: b3 :: b4 :: [b5 ::] mid"""
    s = " :: ".join(B[b] for b in bs[1:5])
    if b5 is not None:
        s += f" :: {B[b5]}"
    return f"{s} :: ({mid})"


def steps_file():
    cc = counts(os.path.join(HERE, "../lean/Counter.lean"))
    co = counts(os.path.join(HERE, "../lean/Overflow.lean"))
    L = ["import Visit", "import Counter", "import Overflow", "",
         "/-! Every visit of a steady configuration of 1RB1RF_1LC0LB_1RE1LD_1RE0LB_1RA0RE_---0RC, generated by "
         "`py/glue.py steps`; do not edit by hand.",
         "",
         "* `vs_i`: a shallow visit, i -> i + 1 (`shallow<i>` of Counter.lean);",
         "* `vd_<t>_<lo>[_<b5>]_<z|s>`: a deep visit that does not overflow (`deep_...` of Counter.lean);",
         "* `va_<t>_<lo>[_<b5>]`: an A-overflow (`ovA_...` of Overflow.lean);",
         "* `deep_case_<t>_<lo>`: the deep visit for the low digits lo, by cases on the higher digits;",
         "* `steady_step`: a steady visit that is not a B-overflow leads to a steady visit. -/", "",
         f"namespace {C.NS}", "", "open TM", "", "set_option maxRecDepth 100000", "set_option linter.unusedSimpArgs false", "",
         "/-- `0 (011010)^n` is `(001101)^n 0` (left to right), nearest cell first. -/",
         "theorem rot0 (n : Nat) (S : Tape) :",
         "    rep n [false, true, false, true, true, false] (cons false S) = cons false (rep n (Ur false) S) := by",
         "  have := rep_rotate n [false] (Ur false) [false, true, false, true, true, false] rfl S",
         "  simpa using this.symm", ""]
    SIMP = "simp only [Xv, digs_cons, digs_rep, digs_rep_nil, app_cons, app_nil]"
    # shallow
    for i in range(7):
        a = [B[(i >> j) & 1] for j in range(3)]
        b = [B[((i + 1) >> j) & 1] for j in range(3)]
        L += [f"theorem vs_{i} (m : Nat) (pre : Tape) (b0 : Bool) (ds : List Bool) (t : Bool) :",
              f"    steps (8 * m + 12 + {cc[f'shallow{i}']} + 1) (vis m (Xv pre b0 ds t {' '.join(a)}))",
              f"      = some (vis (m + 1) (Xv pre b0 ds t {' '.join(b)})) := by",
              f"  refine visit m {cc[f'shallow{i}']} _ _ (fun R => ?_)",
              "  simp only [Xv, app_cons, app_nil]",
              f"  exact shallow{i} _ R", ""]
    # deep, no overflow
    for t in (0, 1):
        c = C.ADD[t] - 32
        for lo in range(32):
            s = lo + c
            lo2, car = s % 32, s >= 32
            bs, bs2 = bits(lo), bits(lo2)
            for b5 in ((0, 1) if car else (None,)):
                tag = f"{t}_{lo}" + (f"_{b5}" if b5 is not None else "")
                for z in ("z", "s"):
                    J = "0" if z == "z" else "(k + 1)"
                    n = cc[f"deep_{tag}_{z}"]
                    kb = "(k m : Nat)" if z == "s" else "(m : Nat)"
                    karg = "k " if z == "s" else ""
                    st = ds_term(bs, b5, f"List.replicate {J} true ++ false :: rest")
                    en = ds_term(bs2, b5, f"List.replicate {J} false ++ true :: rest")
                    L += [f"theorem vd_{tag}_{z} {kb} (rest : List Bool) (pre : Tape) :",
                          f"    steps (8 * m + 12 + ({n}) + 1) (vis m (Xv pre {B[bs[0]]} ({st}) {B[t]} true true true))",
                          f"      = some (vis (m + 1) (Xv pre {B[bs2[0]]} ({en}) {B[1 - t]} false false false)) := by",
                          f"  refine visit m ({n}) _ _ (fun R => ?_)",
                          f"  have h := deep_{tag}_{z} {karg}(digs rest pre) R",
                          "  try rw [rot0] at h",
                          f"  {SIMP}",
                          "  exact h", ""]
                n = co[f"ovA_{tag}"]
                st = ds_term(bs, b5, "List.replicate (k + 1) true")
                en = ds_term(bs2, b5, "List.replicate (k + 1) false")
                L += [f"theorem va_{tag} (k m : Nat) :",
                      f"    steps (8 * m + 12 + ({n}) + 1) (vis m (Xv blank {B[bs[0]]} ({st}) {B[t]} true true true))",
                      f"      = some (vis (m + 1) (Xv preB {B[bs2[0]]} ({en}) {B[1 - t]} false false false)) := by",
                      f"  refine visit m ({n}) _ _ (fun R => ?_)",
                      f"  have h := ovA_{tag} k R",
                      "  try rw [rot0] at h",
                      f"  {SIMP}",
                      "  exact h", ""]
    # dispatch per (t, lo)
    LEN = "(by simp only [List.length_append, List.length_replicate, List.length_cons]; omega)"
    for t in (0, 1):
        c = C.ADD[t] - 32
        for lo in range(32):
            car = lo + c >= 32
            bs = bits(lo)
            tag = f"{t}_{lo}"
            head = f"(Xv pre {B[bs[0]]} ({' :: '.join(B[b] for b in bs[1:5])} :: hi) {B[t]} true true true)"
            L += [f"theorem deep_case_{tag} (m : Nat) (pre : Tape) (hi : List Bool) (hp : pre = blank ∨ pre = preB)",
                  "    (hl : 2 ≤ hi.length) (hm : hi.length + 5 ≤ m)",
                  f"    (hb : ¬ BStart (vis m {head})) :",
                  f"    ∃ n c', steps (n + 1) (vis m {head}) = some c' ∧ Steady c' := by"]
            wit = f"⟨{B[bs[0]]}, {', '.join(B[b] for b in bs[1:5])}"
            if not car:
                L += ["  rcases split_ones hi with ⟨j, rest, rfl⟩ | hall",
                      "  · simp only [List.length_append, List.length_replicate, List.length_cons] at hl hm",
                      "    cases j with",
                      f"    | zero => exact ⟨_, _, vd_{tag}_z m rest pre, steady_mk hp {LEN} {LEN}⟩",
                      f"    | succ k => exact ⟨_, _, vd_{tag}_s k m rest pre, steady_mk hp {LEN} {LEN}⟩",
                      "  · rcases hp with rfl | rfl",
                      "    · obtain ⟨k, hk⟩ : ∃ k, hi.length = k + 1 := ⟨hi.length - 1, by omega⟩",
                      "      rw [hall, hk]",
                      f"      exact ⟨_, _, va_{tag} k m, steady_mk (Or.inr rfl) {LEN} {LEN}⟩",
                      f"    · exact absurd {wit}, hi, {B[t]}, m, rfl, hall⟩ hb", ""]
            else:
                L += ["  cases hi with",
                      "  | nil => simp at hl",
                      "  | cons b5 hi' =>",
                      "    simp only [List.length_cons] at hl hm",
                      "    rcases split_ones hi' with ⟨j, rest, rfl⟩ | hall",
                      "    · simp only [List.length_append, List.length_replicate, List.length_cons] at hl hm",
                      "      cases b5 <;> cases j",
                      f"      · exact ⟨_, _, vd_{tag}_0_z m rest pre, steady_mk hp {LEN} {LEN}⟩",
                      f"      · exact ⟨_, _, vd_{tag}_0_s _ m rest pre, steady_mk hp {LEN} {LEN}⟩",
                      f"      · exact ⟨_, _, vd_{tag}_1_z m rest pre, steady_mk hp {LEN} {LEN}⟩",
                      f"      · exact ⟨_, _, vd_{tag}_1_s _ m rest pre, steady_mk hp {LEN} {LEN}⟩",
                      "    · rcases hp with rfl | rfl",
                      "      · obtain ⟨k, hk⟩ : ∃ k, hi'.length = k + 1 := ⟨hi'.length - 1, by omega⟩",
                      "        rw [hall, hk]",
                      "        cases b5",
                      f"        · exact ⟨_, _, va_{tag}_0 k m, steady_mk (Or.inr rfl) {LEN} {LEN}⟩",
                      f"        · exact ⟨_, _, va_{tag}_1 k m, steady_mk (Or.inr rfl) {LEN} {LEN}⟩",
                      f"      · exact absurd {wit}, b5 :: hi', {B[t]}, m, rfl, b5, hi', rfl, hall⟩ hb", ""]
    # the dispatcher
    L += ["/-- A steady visit that is not a B-overflow leads, in at least one step, to a steady visit. -/",
          "theorem steady_step {c : Config} (hs : Steady c) (hb : ¬ BStart c) :",
          "    ∃ n c', steps (n + 1) c = some c' ∧ Steady c' := by",
          "  obtain ⟨pre, b0, ds, t, i0, i1, i2, m, hp, hl, hm, rfl⟩ := hs",
          "  cases i0 <;> cases i1 <;> cases i2"]
    for i0 in (0, 1):
        for i1 in (0, 1):
            for i2 in (0, 1):
                i = i0 + 2 * i1 + 4 * i2
                if i < 7:
                    L.append(f"  · exact ⟨_, _, vs_{i} m pre b0 ds t, steady_mk hp hl (by omega)⟩")
                else:
                    L += ["  · rcases ds with _ | ⟨b1, _ | ⟨b2, _ | ⟨b3, _ | ⟨b4, hi⟩⟩⟩⟩ <;>",
                          "      simp only [List.length_cons, List.length_nil] at hl hm <;> try omega",
                          "    cases t <;> cases b0 <;> cases b1 <;> cases b2 <;> cases b3 <;> cases b4"]
                    for t in (0, 1):
                        for lo_bits in range(32):
                            # goal order: b0 outermost after t, then b1 .. b4; false first
                            b = [(lo_bits >> (4 - j)) & 1 for j in range(5)]      # b0..b4
                            lo = sum(b[j] << j for j in range(5))
                            L.append(f"    · exact deep_case_{t}_{lo} m pre hi hp (by omega) (by omega) hb")
    L += ["", f"end {C.NS}"]
    return "\n".join(L) + "\n"


def transients():
    """Each of the 81 B-overflows (t, low digits, digit 5 when the low digits carry), from the visit
    `0^inf 1 (U(1))^(k+3) [U(b5)] low M(t) I(7) (1011)^(m+40) 1 0 C> 0^inf`, for symbolic k and m: the visits of the
    transient, until the run needs to split the count of the zero digits (the inner counter of the exit visit
    carries into them).  Prints the number of transient visits before the exit visit and how the run stopped."""
    for t in (0, 1):
        c = C.ADD[t] - 32
        for lo in range(32):
            car = lo + c >= 32
            for b5 in ((0, 1) if car else (None,)):
                m5 = (C.U(b5) + " ") if b5 is not None else ""
                st = f"0^inf 1 (101101)^k+3 {m5}{C.low(lo)} {C.sp(C.MA[t])} {C.I(7)} (1011)^m+40 1 0 C> 0^inf"
                vis = [0]

                def stop(cc):
                    if (cc.state == 2 and len(cc.right) == 1 and isinstance(cc.right[0], symtm.Blank)
                            and not cc.steps.is_zero()):
                        vis[0] += 1
                    return vis[0] >= 100
                try:
                    symtm.run(C.M, symtm.Config.parse(st), stop, max_moves=3000000, rotate=True)
                    res = "100 visits, no exit"
                except symtm.NeedSplit as e:
                    res = f"exit visit: split needed on {e}"[:60]
                except Exception as e:
                    res = f"{type(e).__name__}: {e}"[:60]
                print(f"t={t} lo={lo:2d} b5={b5}: {vis[0]:2d} transient visits; {res}")


if __name__ == "__main__":
    {"overflow": lambda: sys.stdout.write(overflow()), "steps": lambda: sys.stdout.write(steps_file()),
     "check": check, "transients": transients}[sys.argv[1]]()
