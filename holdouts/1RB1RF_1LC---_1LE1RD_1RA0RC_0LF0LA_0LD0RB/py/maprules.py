"""Generate lean/MapRules.lean: every row of the left-end map (py/emap.py) of
1RB1RF_1LC---_1LE1RD_1RA0RC_0LF0LA_0LD0RB as a rule proved by `bbtools.symtm` for all values of the counts.

Left-end states:  A(n, k) = `0^inf A> 0 0 T`,  D(n, k) = `0^inf D> 0 0 0 T`  with T = `1^n (01)^k 111` (k = 0: `1^n`).
The doubling stage goes through the configurations

    Q(L; a, m, k) = L (10)^a 1 1 D> 1 (11)^m (01)^k 111        (L = `0^inf` from A, `0^inf 1` from D)

and one turn of its loop is `qstep`: Q(L; a+1, m, k+1) -> Q(L; a, m+2, k)  (L is not looked at).  The induction over
the loop and the gluing into the map are hand-written, in lean/Map.lean.

usage: python3 maprules.py > ../lean/MapRules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import prove  # noqa: E402

M = "1RB1RF_1LC---_1LE1RD_1RA0RC_0LF0LA_0LD0RB"
A, D = "0^inf A> 0 0", "0^inf D> 0 0 0"
QA, QD = "0^inf", "0^inf 1"

RULES = [
    # n even: the drain
    ("evA2", f"{A} (11)^j (01)^k+2 1 1 1 0^inf", f"{D} 1 1 1 1 (11)^j (01)^k+1 1 1 1 0^inf", "A(2j, k+2) -> D(2j+4, k+1)"),
    ("evD2", f"{D} (11)^j (01)^k+2 1 1 1 0^inf", f"{A} 1 1 1 1 (11)^j (01)^k+1 1 1 1 0^inf", "D(2j, k+2) -> A(2j+4, k+1)"),
    ("evA1", f"{A} (11)^j 0 1 1 1 1 0^inf", f"{D} 1 1 1 1 1 1 1 (11)^j 0^inf", "A(2j, 1) -> D(2j+7, 0)"),
    ("evD1", f"{D} (11)^j 0 1 1 1 1 0^inf", f"{A} 1 1 1 1 1 1 1 (11)^j 0^inf", "D(2j, 1) -> A(2j+7, 0)"),
    ("evA0", f"{A} (11)^j 0^inf", f"{D} 1 1 1 (11)^j 0^inf", "A(2j, 0) -> D(2j+3, 0)"),
    ("evD0", f"{D} (11)^j 0^inf", f"{A} 1 1 1 (11)^j 0^inf", "D(2j, 0) -> A(2j+3, 0)"),
    # n odd, k = 0: the conversion
    ("cvA", f"{A} 1 (11)^j 0^inf", f"{D} 1 (01)^j+1 1 1 1 0^inf", "A(2j+1, 0) -> D(1, j+1)"),
    ("cvD", f"{D} 1 (11)^j 0^inf", f"{D} 1 1 1 (01)^j+1 1 1 1 0^inf", "D(2j+1, 0) -> D(3, j+1)"),
    # n odd, k = 1: the halt (B on a 1)
    ("hA", f"{A} 1 (11)^j 0 1 1 1 1 0^inf", "0^inf (10)^j+1 1 1 1 0 B> 1 1 0^inf", "A(2j+1, 1) -> B on a 1"),
    ("hD", f"{D} 1 (11)^j 0 1 1 1 1 0^inf", "0^inf 1 (10)^j+1 1 1 1 0 B> 1 1 0^inf", "D(2j+1, 1) -> B on a 1"),
    # n odd, k >= 2: into the doubling loop
    ("inA1", f"{A} 1 (01)^k+2 1 1 1 0^inf", "0^inf 1 1 D> 1 (11)^2 (01)^k 1 1 1 0^inf", "A(1, k+2) -> Q(0^inf; 0, 2, k)"),
    ("inD1", f"{D} 1 (01)^k+2 1 1 1 0^inf", "0^inf 1 1 1 D> 1 (11)^2 (01)^k 1 1 1 0^inf", "D(1, k+2) -> Q(0^inf 1; 0, 2, k)"),
    ("inA", f"{A} 1 (11)^a+1 (01)^k+2 1 1 1 0^inf", "0^inf (10)^a+1 1 1 D> 1 (11)^2 (01)^k 1 1 1 0^inf",
     "A(2a+3, k+2) -> Q(0^inf; a+1, 2, k)"),
    ("inD", f"{D} 1 (11)^a+1 (01)^k+2 1 1 1 0^inf", "0^inf 1 (10)^a+1 1 1 D> 1 (11)^2 (01)^k 1 1 1 0^inf",
     "D(2a+3, k+2) -> Q(0^inf 1; a+1, 2, k)"),
    ("qstep", "L (10)^a+1 1 1 D> 1 (11)^m (01)^k+1 1 1 1 0^inf", "L (10)^a 1 1 D> 1 (11)^m+2 (01)^k 1 1 1 0^inf",
     "Q(L; a+1, m, k+1) -> Q(L; a, m+2, k)"),
    # out of the loop with the ones doubled (a = 0)
    ("outA2", "0^inf 1 1 D> 1 (11)^m (01)^k+2 1 1 1 0^inf", f"{A} 1 1 1 1 (11)^m (01)^k+1 1 1 1 0^inf",
     "Q(0^inf; 0, m, k+2) -> A(2m+4, k+1)"),
    ("outD2", "0^inf 1 1 1 D> 1 (11)^m (01)^k+2 1 1 1 0^inf", f"{D} 1 1 1 1 1 (11)^m (01)^k+1 1 1 1 0^inf",
     "Q(0^inf 1; 0, m, k+2) -> D(2m+5, k+1)"),
    ("outA1", "0^inf 1 1 D> 1 (11)^m 0 1 1 1 1 0^inf", f"{A} 1 1 1 1 1 1 1 (11)^m 0^inf",
     "Q(0^inf; 0, m, 1) -> A(2m+7, 0)"),
    ("outD1", "0^inf 1 1 1 D> 1 (11)^m 0 1 1 1 1 0^inf", f"{D} 1 1 1 1 1 1 1 1 (11)^m 0^inf",
     "Q(0^inf 1; 0, m, 1) -> D(2m+8, 0)"),
    # out of the loop with no pair left (k = 0): the pairs are doubled instead
    ("failA", "0^inf (10)^a 1 1 D> 1 (11)^m 1 1 1 0^inf", f"{D} 1 1 1 (11)^a (01)^m+2 1 1 1 0^inf",
     "Q(0^inf; a, m, 0) -> D(2a+3, m+2)"),
    ("failD", "0^inf 1 (10)^a 1 1 D> 1 (11)^m 1 1 1 0^inf", f"{A} 1 1 1 (11)^a (01)^m+2 1 1 1 0^inf",
     "Q(0^inf 1; a, m, 0) -> A(2a+3, m+2)"),
]


def main():
    m = Machine.parse(M)
    ns = open(os.path.join(HERE, "..", "lean", "Machine.lean")).read().split("namespace ", 1)[1].split()[0]
    out = []
    for name, start, end, doc in RULES:
        txt, fin = prove(m, name, start, end, doc=doc, rotate=True, count_first=True)
        print(f"-- {name}: {start} ==> {fin} ({fin.steps})", file=sys.stderr)
        out.append(txt)
    head = (f"import Machine\n\n/-! The rows of the left-end map of {M} as rules (generated by `py/maprules.py`). -/\n\n"
            f"namespace {ns}\n\nopen TM\n\n")
    sys.stdout.write(head + "\n".join(out) + f"\nend {ns}\n")


if __name__ == "__main__":
    main()
