"""Generate lean/Rules.lean for 1RB1RF_1LC---_1LE1RD_1RA0RC_0LF0LA_0LD0RB.

* `drain`: from the left end in state A, `A> 0 0 1^(2n+4) (01)^(k+2) 111` goes to `A> 0 0 1^(2n+12) (01)^k 111`:
  two trips, each turning one 01 of the middle into four 1s at the left (exact step count).
* `halt_even`: the sweep in state D over an even block of 1s that ends in `0 111` stops: the head reaches B on a 1
  (no transition) in 2n+3 steps, whatever lies further right.
* `pass_odd`: the same sweep over an odd block of 1s ending in `0 1111` reaches the right end in state D.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import prove  # noqa: E402

M = "1RB1RF_1LC---_1LE1RD_1RA0RC_0LF0LA_0LD0RB"


def main():
    m = Machine.parse(M)
    ns = open(os.path.join(HERE, "..", "lean", "Machine.lean")).read().split("namespace ", 1)[1].split()[0]
    out = []
    rules = [
        ("drain", "0^inf A> 0 0 (11)^n+2 (01)^k+2 1 1 1 0^inf", "0^inf A> 0 0 1 1 1 1 1 1 (11)^n+2 1 1 (01)^k 1 1 1 0^inf",
         "Two drain trips from the left end: `A> 0 0 1^(2n+4) (01)^(k+2) 111` becomes `A> 0 0 1^(2n+12) (01)^k 111`, in "
         "12n+58 steps."),
        ("halt_even", "0^inf 1 1 D> (11)^n 0 1 1 1 R", "0^inf 1 1 (01)^n 1 1 0 B> 1 R",
         "The sweep in D over an even block of 1s ending in `0 111`: after 2n+3 steps the head is in B on a 1, which has "
         "no transition."),
        ("pass_odd", "0^inf 1 1 D> 1 (11)^n 0 1 1 1 1 0^inf", "0^inf 1 0 1 0 (10)^n 1 0 1 0 1 D> 0^inf",
         "The same sweep over an odd block of 1s ending in `0 1111` reaches the right end in D, in 8n+18 steps."),
    ]
    for name, start, end, doc in rules:
        txt, fin = prove(m, name, start, end, doc=doc, rotate=True)
        print(f"-- {name}: {start} ==> {fin} ({fin.steps})", file=sys.stderr)
        out.append(txt)
        if name == "halt_even":
            cfg = txt.split("= some ", 1)[1].split(" := by", 1)[0]
            out.append(f"/-- ... and there the machine stops. -/\ntheorem {name}_stop (n : Nat) (R : Tape) :\n"
                       f"    step {cfg} = none := by\n  simp [step, TM.step, trans]\n")
    head = (f"import Machine\n\n/-! Rules of {M} (generated by `py/rules.py`). -/\n\nnamespace {ns}\n\nopen TM\n\n")
    sys.stdout.write(head + "\n".join(out) + f"\nend {ns}\n")


if __name__ == "__main__":
    main()
