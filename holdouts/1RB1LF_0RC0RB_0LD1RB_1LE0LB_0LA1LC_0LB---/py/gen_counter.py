"""Write lean/Counter.lean: the two rules of the binary counter at the left end of
1RB1LF_0RC0RB_0LD1RB_1LE0LB_0LA1LC_0LB---, proved for every count n and every tape L, R around it (bbtools.symtm).

The counter: digits of four cells, `1 0 1 0` = 0 and `1 0 0 0` = 1, least significant digit on the right, followed by
`1 0`; the head arrives in E on the 0 after the last 1.
  incr      L 1010 (1000)^n 1 E>0 R  ->  L 1000 (1010)^n 1 0 C> R        10 n + 7 steps
            (the lowest 0-digit becomes 1, the n ones below it become 0; C leaves to the right)
  overflow  0^inf (1000)^n 1 E>0 R   ->  0^inf (1010)^(n+1) 1 0 C> R
            (10 n + 13 steps; all digits 1: the counter becomes n + 1 zero digits, one longer; the head visits a new cell on the left
            in state F on the way, the left-end visit of the README)

usage: python3 py/gen_counter.py > lean/Counter.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M, NS = "1RB1LF_0RC0RB_0LD1RB_1LE0LB_0LA1LC_0LB---", "H57056"
RULES = [
    ("incr", "L 1 0 1 0 (1000)^n 1 E> 0 R", "L 1 0 0 0 1 (0101)^n 0 C> R",
     "Increment: the carry crosses the n one-digits `1000` (turning them into `1010`) and sets the first zero "
     "digit; C leaves to the right."),
    ("overflow", "0^inf (1000)^n 1 E> 0 R", "0^inf 1 0 1 0 1 (0101)^n 0 C> R",
     "Overflow: with every digit 1 the carry runs off the left end; the counter becomes n + 1 zero digits."),
]


def main():
    ths = [prove(M, name, s, e, doc=doc)[0] for name, s, e, doc in RULES]
    print(rules_file("Machine", NS, ths,
                     f"The binary counter at the left end of {M}, generated by `py/gen_counter.py` "
                     "(bbtools.symtm); do not edit by hand."))


if __name__ == "__main__":
    main()
