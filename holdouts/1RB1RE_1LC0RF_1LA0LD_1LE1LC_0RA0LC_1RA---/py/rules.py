"""Generate lean/Rules.lean for 1RB1RE_1LC0RF_1LA0LD_1LE1LC_0RA0LC_1RA---: the sweep rules of the base-4 counter.

At the start of a sweep the head is at the left end of the tape in state C, on

    C> a^n0 s(d1) a^n1 s(d2) a^n2 ... s(dk) a^nk END        a = 001, s(0)=0, s(1)=011, s(2)=00, s(3)=0101

One sweep adds one to the base-4 number d1 d2 ... (d1 the lowest digit): the digits 3 at the bottom become 0 and the
next digit goes up by one; every block left of that digit gains one `a`, and the block right of it loses one when
the digit goes 0->1 or 2->3.  The theorems below prove it for every n0 >= 2, every block >= 1 and every number of
carries (the carried digits are a list `ts` of any length: `bbtools.seqtm`, lean/Seq.lean); `step_d` give the exact
step count when there is no carry (8 n0 + 6).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools import seqtm  # noqa: E402
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Blank, prove  # noqa: E402

M = "1RB1RE_1LC0RF_1LA0LD_1LE1LC_0RA0LC_1RA---"
S = {0: "0", 1: "0 1 1", 2: "0 0", 3: "0 1 0 1"}
NS = "H175626"


def at_left_end(c):
    return c.state == 2 and len(c.left) == 1 and isinstance(c.left[0], Blank) and not c.steps.is_zero()


def main():
    m = Machine.parse(M)
    out = []
    # no carry, exact step counts
    for d in range(3):
        start = f"0^inf C> 0 0 1 0 0 1 (001)^p {S[d]} (001)^q+1 R"
        end = {0: f"0^inf C> 0 0 1 0 0 1 0 0 1 (001)^p {S[1]} (001)^q R",
               1: f"0^inf C> 0 0 1 0 0 1 0 0 1 (001)^p {S[2]} (001)^q+1 R",
               2: f"0^inf C> 0 0 1 0 0 1 0 0 1 (001)^p {S[3]} (001)^q R"}[d]
        txt, _ = prove(m, f"step{d}", start, end,
                       doc=f"A sweep without carry, lowest digit {d} -> {d + 1}: `C> a^(p+2) s({d}) a^(q+1)` goes to "
                           f"`C> a^(p+3) s({d + 1}) ...`, in 8(p+2)+6 steps.")
        out.append(txt)
    # any number of carries: the digits 3 at the bottom are the list ts, each with its block (001)^(x+1)
    for d in range(3):
        start = seqtm.parse(f"0^inf C> 0 0 1 0 0 1 (001)^p [ {S[3]} 0 0 1 (001)^x ]^ts {S[d]} (001)^q+1 R")
        txt, fin, _ = seqtm.prove(m, f"sweep{d}", start, at_left_end,
                                  doc=f"A sweep with any number of carries (the list ts of digits 3, each followed by "
                                      f"its block `a^(x+1)`), the first digit below 3 being {d}: every digit 3 becomes 0 and its "
                                      f"block gains one `a`, the digit {d} becomes {d + 1}.")
        out.append(txt)
        print(f"-- sweep{d}: {start}  ==>  {fin}", file=sys.stderr)
    head = (f"import Machine\nimport Seq\n\n/-! The sweep rules of {M} (generated by `py/rules.py`).\n\n"
            "A configuration at the start of a sweep: `C> a^n0 s(d1) a^n1 ... s(dk) a^nk END` with `a = 001`, "
            "`s(0) = 0`, `s(1) = 011`, `s(2) = 00`, `s(3) = 0101`: a base-4 counter, lowest digit first.  "
            "One sweep adds one to it. -/\n\nnamespace " + NS + "\n\nopen TM\n\n")
    sys.stdout.write(head + "\n".join(out) + f"\nend {NS}\n")


if __name__ == "__main__":
    main()
