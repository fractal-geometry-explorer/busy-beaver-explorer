"""Generate ../lean/Rules.lean: the shift and macro rules of 1RB0RE_1LC0RA_1LD0LC_0LE0LB_1RA1RF_0LC---, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC0RA_1LD0LC_0LE0LB_1RA1RF_0LC---"

RULES = [
    ('c_cd', 'L (001)^n C> 0 R', 'L C> 0 (101)^n R',
     'Going left in state C, every c = 100 becomes d = 101.'),
    ('d_cc', 'L (001)^n D> 0 R', 'L D> 0 (100)^n R',
     "Going left in state D, the c's are left as they are."),
    ('b_l', 'L (010)^n B> 0 R', 'L B> 0 (011)^n R',
     'B runs left over (010)^n.'),
    ('c_l2', 'L (010)^n C> 0 R', 'L C> 0 (001)^n R',
     'C runs left over (010)^n.'),
    ('c_l3', 'L (100)^n C> 1 R', 'L C> 1 (010)^n R',
     'C runs left over (100)^n.'),
    ('d_l3', 'L (100)^n D> 1 R', 'L D> 1 (110)^n R',
     'D runs left over (100)^n.'),
    ('d_pair', 'L (001101)^n D> 0 R', 'L D> 0 (110101)^n R',
     'D runs left over pairs c d.'),
    ('e_pair', 'L E> (001101)^n R', 'L (110010)^n E> R',
     'E runs right over pairs.'),
    ('e_pair2', 'L E> (010011)^n R', 'L (101100)^n E> R',
     'E runs right over pairs (other phase).'),
    ('a_pair', 'L A> (011010)^n R', 'L (100101)^n A> R',
     'A runs right over pairs.'),
    ('a_pair2', 'L A> (100110)^n R', 'L (011001)^n A> R',
     'A runs right over pairs.'),
    ('a_pair3', 'L A> (101001)^n R', 'L (010110)^n A> R',
     'A runs right over pairs.'),
    ('b_tail', 'L B> (110100)^n R', 'L (001011)^n B> R',
     'B runs right over the tail word 110100.'),
    ('b_tail_l', 'L (110100)^n B> 0 R', 'L B> 0 (010111)^n R',
     'B runs left over the tail word.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=20)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H45361", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
