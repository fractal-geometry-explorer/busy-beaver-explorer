"""Write lean/Rules.lean: rules of 1RB1LD_0LC1RC_1RA1RD_1LE0RB_---1LF_0LC0LA proved by bbtools.symtm, for all values of their counts.

The left zone of the tape is a run of blocks 0 1^5, taken here in pairs (011111011111). Each visit of the head to the
gadget right of it sweeps across the whole zone several times, and each sweep re-encodes the pairs in another
12-cell word; these are the seven shift rules of those sweeps.

usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/1RB1LD_0LC1RC_1RA1RD_1LE0RB_---1LF_0LC0LA/py/gen_rules.py
"""
import os
from bbtools import symtm
from bbtools.machine import Machine

M = "1RB1LD_0LC1RC_1RA1RD_1LE0RB_---1LF_0LC0LA"
RULES = [
    ("bR_f", "B crosses the pairs of 5-blocks to the right, re-encoding each as 101011011011",
     "L 0 B> (011111011111)^a R", "L (101011011011)^a 0 B> R"),
    ("dL", "D crosses 011011011101 words to the left, re-encoding each as 101111101111",
     "L (011011011101)^a D> 0 R", "L D> 0 (101111101111)^a R"),
    ("cR", "C crosses 111101111101 words to the right, re-encoding each as 010110110111",
     "L 1 1 C> (111101111101)^a R", "L (010110110111)^a 1 1 C> R"),
    ("aL", "A crosses 110110111010 words to the left, restoring the pairs of 5-blocks",
     "L (110110111010)^a A> 1 R", "L A> 1 (011111011111)^a R"),
    ("dR", "D crosses 111011111011 words to the right, re-encoding each as 010110110111",
     "L 1 1 1 D> (111011111011)^a R", "L (010110110111)^a 1 1 1 D> R"),
    ("fL", "F crosses 010110110111 words to the left, re-encoding each as 111011111011",
     "L (010110110111)^a F> 0 R", "L F> 0 (111011111011)^a R"),
    ("bR", "B crosses 111011111011 words to the right, re-encoding each as 111010110110",
     "L 0 B> (111011111011)^a R", "L 0 (111010110110)^a B> R"),
]


def main():
    m = Machine.parse(M)
    thms = [symtm.prove(m, name, s, e, doc=doc, rotate=True)[0] for name, doc, s, e in RULES]
    out = symtm.rules_file("Machine", "H176216", thms, "Rules of " + M + ", generated by `py/gen_rules.py` with `bbtools.symtm`.")
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lean", "Rules.lean"), "w") as f:
        f.write(out)


if __name__ == "__main__":
    main()
