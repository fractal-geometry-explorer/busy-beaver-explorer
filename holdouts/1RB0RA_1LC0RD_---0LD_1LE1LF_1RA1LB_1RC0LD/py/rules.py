"""Generate lean/Rules.lean for 1RB0RA_1LC0RD_---0LD_1LE1LF_1RA1LB_1RC0LD: the sweep rules described in README.md, each proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, runs of a repeated word by `TM.cross_r` / `TM.cross_l`).

usage (from the repository root):  python3 holdouts/1RB0RA_1LC0RD_---0LD_1LE1LF_1RA1LB_1RC0LD/py/rules.py > holdouts/1RB0RA_1LC0RD_---0LD_1LE1LF_1RA1LB_1RC0LD/lean/Rules.lean

Each rule is given by its start configuration only; the end is where the symbolic run stops, just before the head
would read a cell of an unknown context (`L`, `R`) or the run needs to know whether a repeat count is 0.  Tapes are
written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w, `0^inf` blank
tape, `L` and `R` any tape.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, NeedSplit, TouchContext, prove, rules_file, step, try_cross, try_rotate  # noqa: E402


def run_to_edge(machine, start, max_moves=20000):
    """The configuration the symbolic run reaches from `start` just before it would need an unknown cell."""
    m = Machine.parse(machine)
    c = Config.parse(start)
    for _ in range(max_moves):
        last = c.copy()
        try:
            if try_cross(m, c) is None:
                c2 = c.copy()
                if try_rotate(c2) is not None and try_cross(m, c2) is not None:
                    c = c2
                    continue
                step(m, c)
        except (TouchContext, NeedSplit):
            return last
    raise RuntimeError(f"{start}: no edge after {max_moves} moves")


def main(machine, rules, doc, max_carry=3):
    symtm.MAX_CARRY = max_carry
    here = os.path.dirname(os.path.abspath(__file__))
    ns = re.search(r"^namespace (\S+)", open(os.path.join(here, "..", "lean", "Machine.lean")).read(), re.M).group(1)
    ths = []
    for name, start, text in rules:
        end = run_to_edge(machine, start)
        ths.append("set_option maxRecDepth 100000 in\n" + prove(machine, name, start, end, doc=f"{text}  `{start}` to `{end}`.", rotate=True,
                         count_first=True, max_seg=200)[0])
    sys.stdout.write(rules_file("Machine", ns, ths, doc))


MACHINE = '1RB0RA_1LC0RD_---0LD_1LE1LF_1RA1LB_1RC0LD'

RULES = [
    ('block',
     '0^inf D> (001)^n+2 R',
     'Left end and the uniform block: D enters at the left end, adds a cell and crosses the block `(001)^(n+2)`, which becomes `1 0 (110)^(n+1) 1 0` (5 steps a word).'),
    ('right_A',
     'L A> (010)^n R',
     'Rightward sweep: A turns `010` into `110`.'),
    ('left_D',
     'L (011)^n D> 1 R',
     'Leftward sweep: D turns `011` into `001`.'),
    ('left_F',
     'L (101)^n F> 1 R',
     'Leftward sweep: F turns `101` into `100`.'),
    ('left_D2',
     'L (110)^n D> 1 R',
     'Leftward sweep: D turns `110` into `010`.'),
    ('ones',
     'L A> 1^n R',
     'A erases a block of ones (A1 = 0RA).'),
]

if __name__ == "__main__":
    main(MACHINE, RULES, f"Sweep rules of {MACHINE}, generated by `py/rules.py`; do not edit by hand.", max_carry=3)
