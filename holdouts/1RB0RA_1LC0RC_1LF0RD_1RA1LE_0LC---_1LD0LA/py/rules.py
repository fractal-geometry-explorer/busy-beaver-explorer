"""Sweep rules and the halting situation of 1RB0RA_1LC0RC_1LF0RD_1RA1LE_0LC---_1LD0LA, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0RA_1LC0RC_1LF0RD_1RA1LE_0LC---_1LD0LA/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RA_1LC0RC_1LF0RD_1RA1LE_0LC---_1LD0LA"
NS = "H26127"
DOC = """# Sweep rules of 1RB0RA_1LC0RC_1LF0RD_1RA1LE_0LC---_1LD0LA

Going right, D and A take turns crossing the blocks `011`, each turned into `100`, three steps a block (`walk_DA`).
Two whole sweeps of the separator counter, for every length of the first two blocks and every tape beyond them:
with an even first block and the separator `1`, the sweep lengthens the first block by one and turns the separator
into `01` (`sweep_1`); with an odd first block and the separator `01`, it lengthens the first block by two, turns
the separator into `111` and takes one block from the second run (`sweep_01`).  These are four of the eight sweeps of
the first level's cycle.  The halting situation: E reads a 1 only right after D read a 1 with a 1 on its left
(`halt_D`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('walk_DA', 'L D> (011011)^n R', 'L (100100)^n D> R',
     'Going right, D and A take turns: each pair of blocks `011 011` becomes `100 100`, six steps a pair.'),
    ('sweep_1', '0^inf D> (011011)^k+1 1 (011)^m+2 R', '0^inf D> (011011)^k+1 011 0 1 (011)^m+2 R',
     'A sweep from the left end with first block of even length 2k+2 and separator `1`: the block gains one `011` and the separator becomes `01`.'),
    ('sweep_01', '0^inf D> (011011)^k 011 0 1 (011)^m+1 R', '0^inf D> (011011)^k+1 011 1 1 1 (011)^m R',
     'A sweep from the left end with first block of odd length 2k+1 and separator `01`: the block gains two, the separator becomes `111` and the next block loses one.'),
]

HALTS = [
    ('halt_D', '1 D> 1', 1, '`1 D> 1` halts: D writes 1 and moves left onto the 1 in state E, which has no transition on 1.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [prove(M, name, a, b, doc=doc, count_first=True, max_seg=20)[0] for name, a, b, doc in RULES]
    thms += [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
