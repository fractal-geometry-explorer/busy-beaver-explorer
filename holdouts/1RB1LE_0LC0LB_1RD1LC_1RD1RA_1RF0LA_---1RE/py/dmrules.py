"""Generate lean/DMRules.lean: the tape rules behind the halts-iff map of 1RB1LE_0LC0LB_1RD1LC_1RD1RA_1RF0LA_---1RE
(DeepMind's map, lean/DeepMindMap.lean), proved along the symbolic run (tools/py/bbtools/symtm.py).

usage: python3 dmrules.py > ../lean/DMRules.lean

A-configurations are `0^inf 1^a A> (10)^c 1^(d+1) 0^inf`.  A pass of the A(1, c, d) cases eats `0101` and adds six
1s on the left (`round`); the other rules are the short runs of DeepMind's `next`, case by case.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, Halted, prove, rules_file, run  # noqa: E402

M = "1RB1LE_0LC0LB_1RD1LC_1RD1RA_1RF0LA_---1RE"

RULES = [
    ("blank_A", "0^inf A> 0^inf", "0^inf 1 1 A> 1 1 0^inf", "From blank tape to A(2, 0, 1)."),
    ("sA", "L 1 1 A> 1 R", "L A> 1 0 1 R", "A(a + 2, c, d) to A(a, c + 1, d): A turns `1 1` into `1 0` on its right."),
    ("runD", "0^inf (1)^n D> 0^inf", "0^inf (1)^n 1 D> 0^inf", "D runs right on blank tape."),
    ("h00", "0^inf A> 1 0^inf", "halt", "A(0, 0, 0) halts."),
    ("h0c", "0^inf A> (10)^c+1 1 0^inf", "halt", "A(0, c + 1, 0) halts."),
    ("a0c1_0", "0^inf A> 1 1 0^inf", "0^inf 1 A> 1 0 0^inf", "A(0, 0, 1) to A(1, 0, 0)."),
    ("a0c1", "0^inf A> 1 0 (10)^c 1 1 0^inf", "0^inf 1 1 (11)^c 1 A> 1 0 0^inf", "A(0, c + 1, 1) to A(2c + 3, 0, 0)."),
    ("a0d_0", "0^inf A> 1 1 1 (1)^d 0^inf", "0^inf 1 A> 1 0 1 (1)^d 0^inf", "A(0, 0, d + 2) to A(1, 1, d)."),
    ("a0d", "0^inf A> 1 0 (10)^c 1 1 1 (1)^d 0^inf", "0^inf 1 1 (11)^c 1 A> 1 0 1 (1)^d 0^inf",
     "A(0, c + 1, d + 2) to A(2c + 3, 1, d)."),
    ("a1_00", "0^inf 1 A> 1 0^inf", "0^inf 1 D> 0 0 0 0 0 0^inf", "A(1, 0, 0) to D running right on blank tape."),
    ("a1_01", "0^inf 1 A> 1 1 0^inf", "0^inf 1 1 A> 1 1 1 1 1 1 1 0 0^inf", "A(1, 0, 1) to A(2, 0, 6)."),
    ("a1_0d", "0^inf 1 A> 1 1 1 (1)^d 0^inf", "0^inf 1 1 1 1 1 1 1 A> 1 (1)^d 0^inf", "A(1, 0, d + 2) to A(7, 0, d)."),
    ("p1", "0^inf 1 A> 1 0 R", "0^inf 1 1 A> 0 1 0 R", "A(1, c + 1, d) starts: the first `10` becomes `0 1 0`."),
    ("round", "0^inf (1)^n A> 0 1 0 1 R", "0^inf 1 1 1 (1)^n 1 1 1 A> R", "One pass: `0101` eaten, six more 1s."),
    ("e0", "0^inf (1)^n A> 0 1 0^inf", "0^inf 1 1 1 (1)^n D> 0 0^inf", "Even c, d = 0: D runs right on blank tape."),
    ("e1", "0^inf (1)^n A> 0 1 1 0^inf", "0^inf 1 1 A> 1 1 1 (1)^n 1 1 0 0^inf", "Even c, d = 1: A(2, 0, n + 4)."),
    ("e2", "0^inf (1)^n A> 0 1 1 1 (1)^d 0^inf", "0^inf 1 1 1 (1)^n 1 1 A> 1 (1)^d 0^inf", "Even c, d + 2: A(n + 5, 0, d)."),
    ("o0", "0^inf (1)^n A> 0 1 0 1 0^inf", "0^inf 1 1 A> 1 1 1 (1)^n 1 1 1 0 0^inf", "Odd c, d = 0: A(2, 0, n + 5)."),
]


def before_halt(start):
    m = Machine.parse(M)
    c = Config.parse(start)
    while True:
        prev = c.copy()
        try:
            run(m, c, lambda _: False, max_moves=1, rotate=True)
        except Halted:
            return prev
        except RuntimeError:
            pass


def main():
    ths = []
    for name, a, b, doc in RULES:
        if b == "halt":
            b = before_halt(a)
        ths.append(prove(M, name, a, b, doc=doc, rotate=True, max_seg=40)[0])
    ns = "H" + open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lean", "Machine.lean")).read().split(
        "namespace H")[1].split()[0]
    sys.stdout.write(rules_file("Machine", ns, ths, f"Rules of {M}, generated by `py/dmrules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
