"""Generate lean/Rules.lean: shift rules (a state crossing a repeated word) of 1RB1LF_0LC0RE_1LA1RD_0LB1LB_1RC1RD_0LD---, proved with
tools/py/bbtools/symtm.py for every number of copies and any tapes L, R around them.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, prove, rules_file, run  # noqa: E402

M = "1RB1LF_0LC0RE_1LA1RD_0LB1LB_1RC1RD_0LD---"
NS = "H" + open(os.path.join(HERE, "..", "lean", "Machine.lean")).read().split("namespace H")[1].split()[0]
RULES = [
    ('c_right', 'L C> (110)^n R',
     'C runs right over pairs `110`, turning each into `001`.'),
    ('c_right10', 'L C> (10)^n R',
     'C runs right over `10`, turning each into `01`.'),
    ('d_left', 'L (100)^n 1 0 D> 0 R',
     'D runs left over copies of `100`, turning them into `011`.'),
]


def after_cross(start):
    """The configuration right after the first crossing of a repeat."""
    m = Machine.parse(M)
    cfg = Config.parse(start)
    trace = []
    run(m, cfg, lambda c: any(t[0] == "cross" for t in trace), max_moves=100, trace=trace, rotate=True)
    return cfg


def main():
    ths = []
    for name, start, doc in RULES:
        th, _ = prove(M, name, start, after_cross(start), doc=doc, rotate=True)
        ths.append(th)
    sys.stdout.write(rules_file("Machine", NS, ths, f"Shift rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
