"""Shift rules of 1RB1RA_0LC0RE_1LF1LD_1LA0LA_1LC1RB_---1LC, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB1RA_0LC0RE_1LF1LD_1LA0LA_1LC1RB_---1LC/py/rules.py     writes lean/Rules.lean (checked by lean/check.sh)

The rules are the building blocks of the odometer (`py/model.py`).  Between two visits
`S(c, a, b) = 0^inf (10)^c 1^a 0 (10)^b 1 B> 0^inf` the machine works through the inner configurations

    R(x, q, z) = ... 1^x [A> 1] 0 1^q 0 (10)^z 1^4 0^inf        (q = 1, 5, 9, ...)

Syntax of `bbtools.symtm.Config.parse`: `L 1 A> 1 0 R` is the head in state A on the first cell after `A>`; `(w)^n`
is the word w repeated n times; L and R are unknown tape, `0^inf` blank tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RA_0LC0RE_1LF1LD_1LA0LA_1LC1RB_---1LC"
NS = "H50923"
DOC = """# The building blocks of the odometer of 1RB1RA_0LC0RE_1LF1LD_1LA0LA_1LC1RB_---1LC

Between two visits `S(c, a, b) = 0^inf (10)^c 1^a 0 (10)^b 1 B> 0^inf` of the right end the machine works through
the inner configurations `R(x, q, z) = ... 1^x [A> 1] 0 1^q 0 (10)^z 1^4 0^inf` (q = 1, 5, 9, ...).  Each theorem is
one move of the odometer, for every value of its parameters and every tape in the contexts `L`, `R`:

* `start`, `start0`: from `S(c, a, n+1)` to `R(a-2, 1, n)`; from `S(c, a, 0)` to `S(c, a, 1)`;
* `round`: a round takes two 1s from the pool and one `10` from the right block, and adds four 1s to the middle
  block: `R(x, q, z) -> R(x-2, q+4, z-1)`;
* `final`: the right block is used up: `R(x, 4n+1, 0)` becomes the visit `S(c, x, 2n+3)` (the doubled block);
* `carry`: the pool is empty and a `10` of the left block is next: that `10` and the middle block become the new
  pool (`1^(q+3)`), and the next round starts;
* `reset`: the pool is empty and so is the left block: the middle block becomes the new left block `(10)^((q+3)/2)`
  and the pool is `1^2`;
* `halt_run`, `halt_R`: pool, left block and right block all empty: `R(0, 4n+1, 0)` on blank tape runs into the
  undefined transition (F reading 0).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l`, re-bracketings and `omega`, checked by Lean's kernel."""

RULES = [
    ('start', 'L 1 1 1 1 0 (10)^n 1 0 1 B> 0^inf', 'L 1 1 A> 1 0 1 0 1 (01)^n 1 1 1 0^inf',
     '`S(c, a, n+1)` to `R(a-2, 1, n)` (the tail `0 1 (01)^n 1 1 1` is `0 (10)^n 1^4`).'),
    ('start0', 'L 1 1 0 1 B> 0^inf', 'L 1 1 0 1 0 1 B> 0^inf', '`S(c, a, 0)` to `S(c, a, 1)`.'),
    ('round', 'L 1 1 A> 1 0 1 (1111)^n 0 1 0 R', 'L A> 1 0 1 1 1 (1111)^n 1 1 0 R',
     '`R(x, 4n+1, z) -> R(x-2, 4n+5, z-1)`.'),
    ('final', 'L 1 1 1 1 A> 1 0 1 (1111)^n 0 1 1 1 1 0^inf', 'L 1 1 1 1 (0101)^n 0 1 0 1 0 1 0 1 B> 0^inf',
     '`R(x, 4n+1, 0)` to the visit `S(c, x, 2n+3)`.'),
    ('carry', 'L 1 0 A> 1 0 1 (1111)^n 0 1 0 1 0 R', 'L 1 1 (1111)^n 1 1 A> 1 0 1 1 1 1 R',
     'Pool empty, a `10` of the left block on the left: the new pool is `1^(4n+4)`.'),
    ('reset', '0^inf A> 1 0 1 (1111)^n 0 1 0 R', '0^inf 1 0 (1010)^n 1 0 1 1 A> 1 0 R',
     'Pool and left block empty: the middle block becomes the left block `(10)^(2n+2)`, the pool is `1^2`.'),
    ('halt_run', '0^inf A> 1 0 1 (1111)^n 0 1 1 1 1 0^inf', '0^inf F> 0 1 1 1 1 1 1 1 (1111)^n 1 1 1 1 1 0^inf',
     'Pool, left block and right block empty: the run reaches F on a 0, the tape all 1s.'),
]

EXTRA = """/-- `R(0, 4n+1, 0)` on blank tape halts, for every n: the reset that finds the right block used up exactly. -/
theorem halt_R (n : Nat) :
    TM.Halts trans ⟨blank, cons true (cons false (cons true (rep (n) [true, true, true, true]
      (cons false (cons true (cons true (cons true (cons true (blank))))))))), .A⟩ :=
  ⟨_, _, halt_run n, rfl⟩
"""


def main():
    thms = []
    for name, a, b, doc in RULES:
        try:
            thms.append(prove(M, name, a, b, doc=doc, rotate=True)[0])
        except Exception as e:  # noqa: BLE001
            print("FAILED", name, type(e).__name__, str(e)[:200])
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
