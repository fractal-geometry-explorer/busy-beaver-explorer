"""Generate Rules.lean for 1RB1LE_1LC1RE_1LE1LD_1LC0LA_1RF0LA_---0RA: shift rules (one copy of a word crossed by the head in a state, so a whole run of
copies is crossed at once), each proved along a symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`,
shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, prove, rules_file, run  # noqa: E402

M = "1RB1LE_1LC1RE_1LE1LD_1LC0LA_1RF0LA_---0RA"
NS = "H144438"

# (name, start, doc): the end is the configuration right after the run of copies is crossed
RULES = [
    ('e_left',
     'L (111110)^n E> 1 R',
     'E runs left over 111110, turning each copy into 101011: the leftward sweep over the period-6 background.'),
    ('a_left',
     'L (111101)^n A> 1 R',
     'The same sweep in phase A over the rotation 111101, which becomes 010111.'),
    ('d_left',
     'L (101111)^n D> 1 R',
     'The same sweep in phase D over 101111, which becomes 111010.'),
    ('c_left',
     'L (011111)^n C> 1 R',
     'The same sweep in phase C over 011111, which becomes 110101.'),
]

DOC = """Shift rules of the leftward sweep over the period-6 background 111110 (all rotations occur: the walls of the tape are phase shifts). Generated by py/rules.py (tools/py/bbtools/symtm.py); do not edit by hand."""


def after_cross(start):
    trace = []
    run(Machine.parse(M), Config.parse(start), lambda c: any(t[0] == "cross" for t in trace), trace=trace)
    return next(t[2] for t in trace if t[0] == "cross")


def main():
    ths = []
    for name, start, doc in RULES:
        ths.append(prove(M, name, start, after_cross(start), doc=doc)[0])
    sys.stdout.write(rules_file("Machine", NS, ths, DOC))


if __name__ == "__main__":
    main()
