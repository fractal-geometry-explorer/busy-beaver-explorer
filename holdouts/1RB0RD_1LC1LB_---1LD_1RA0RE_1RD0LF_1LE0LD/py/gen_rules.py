"""Generate lean/Rules.lean for 1RB0RD_1LC1LB_---1LD_1RA0RE_1RD0LF_1LE0LD (run from the repository root): shift rules the sweeps use.
Each rule is proved by bbtools.symtm for all values of its variables and every tape L (or R) the run does not
look at."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools import symtm
from bbtools.machine import Machine
M = "1RB0RD_1LC1LB_---1LD_1RA0RE_1RD0LF_1LE0LD"
NS = "H180739"
m = Machine.parse(M)
RULES = [
    ('shiftD', 'Shift rule: D crosses (10)^n to the right, leaving (01)^n (2 steps per pair).',
     'L D> (10)^n R', 'L (01)^n D> R'),
    ('shiftE', 'Shift rule: E crosses (01)^n to the right, leaving (10)^n.',
     'L E> (01)^n R', 'L (10)^n E> R'),
    ('shiftA', 'Shift rule: A crosses (10)^n to the right, leaving (01)^n.',
     'L A> (10)^n R', 'L (01)^n A> R'),
]
out = []
for name, doc, a, b in RULES:
    txt, fin = symtm.prove(m, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=30)
    out.append(txt)
sys.stdout.write(symtm.rules_file("Machine", NS, out, f"Rules of {M}; generated by `py/gen_rules.py`; do not edit by hand."))
