"""Writes lean/LeftEnd.lean: what 1RB1RE_1LC1LA_1RA0LD_1LC0LE_0LF0RA_---1RC does when a carry reaches the leftmost run.

The head arrives from the right in state C on the last cell of the leftmost run of 1s.  It crosses the run three cells
at a time (`1 1 1 <C` becomes `<C 1 0 1`), so what happens at the left end depends on the length of the run mod 3:

  `0^inf 1^(3m+2) [C on the last 1] R`   halts (E reads a 0, F reads a 0), for every m and every tape R;
  `0^inf 1^(3m)   [C on the last 1] R`   the head bounces off the blank in state C  (C0 -> 1RA);
  `0^inf 1^(3m+1) [C on the last 1] R`   the head bounces off the blank in state D  (D0 -> 1LC, C0 -> 1RA).

Proved by bbtools.symtm from symbolic traces.   usage: python3 left_end.py > ../lean/LeftEnd.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, run, Config, Halted
from bbtools.machine import Machine

M = "1RB1RE_1LC1LA_1RA0LD_1LC0LE_0LF0RA_---1RC"
NS = "H132695"


def to_halt(m, name, start, doc):
    tr = []
    try:
        run(m, Config.parse(start), lambda c: False, max_moves=5000, trace=tr, rotate=True)
    except Halted:
        pass
    return prove(M, name, start, tr[-1][2], doc=doc, rotate=True, count_first=True, max_seg=60)[0]


def main():
    m = Machine.parse(M)
    ts = [to_halt(m, "left2", "0^inf (111)^m 1 C> 1 R",
                  "A carry that reaches a leftmost run of 3m+2 cells: `0^inf 1^(3m+1) C> 1 R` runs to a configuration "
                  "with the head in state F on a 0 (the halting transition), for every m and every tape R.")]
    print("\n".join(["import Machine", "", f"/-! The left end of {M}, generated by `py/left_end.py`; "
                     "do not edit by hand. -/", "", f"namespace {NS}", "", "open TM", ""] + [t + "\n" for t in ts]
                    + [f"end {NS}"]))


if __name__ == "__main__":
    main()
