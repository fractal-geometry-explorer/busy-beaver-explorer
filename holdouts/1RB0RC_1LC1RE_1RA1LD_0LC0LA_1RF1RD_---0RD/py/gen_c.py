"""gen_c.py: write c/fcases.h, the 78 cases of `next` (lean/Phases.lean) with their step counts (lean/Pieces.lean)
as C, read by rules.py's parser of the Lean files.  python3 py/gen_c.py && git diff --exit-code c/fcases.h"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from rules import CASES

TAGS = 'zywuZYWU'
out = ['/* generated by py/gen_c.py from lean/Phases.lean (next) and lean/Pieces.lean (step counts); do not edit */',
       '/* fc_step(t, v): one case of next.  Returns the case index (0..77), -1-index for a halting case.  On a non-halting',
       '   case v and *t become the target and *st the machine steps; on a halting case *st is the steps to the halt. */',
       'static int fc_step(int *t, I v[3], W *st) {', '    I a = v[0], b = v[1], c = v[2]; (void)a; (void)b; (void)c;',
       '    switch (*t) {']
for ti, tag in enumerate(TAGS):
    out.append('    case %d: /* %s */' % (ti, tag))
    for idx, (cn, pats, tgt, st, _) in enumerate(CASES):
        if cn != tag: continue
        conds, binds = [], []
        for p, x in zip(pats, 'abc'):
            if p.isdigit(): conds.append('%s == %s' % (x, p))
            else:
                m = re.match(r'\((\w+) \+ (\d+)\)', p)
                if m:
                    conds.append('%s >= %s' % (x, m.group(2))); binds.append('I %s = %s - %s;' % (m.group(1), x, m.group(2)))
                else:
                    binds.append("I %s = %s; (void)%s;" % (p, x, p))
        cond = ' && '.join(conds) or '1'
        body = ' '.join(binds)
        sexpr = st
        if tgt is None:
            body += ' *st = (W)(%s); return %d;' % (sexpr, -1 - idx)
        else:
            nt = TAGS.index(tgt[0])
            body += ' *st = (W)(%s); I n0 = %s, n1 = %s, n2 = %s; v[0] = n0; v[1] = n1; v[2] = n2; *t = %d; return %d;' % (
                st, tgt[1][0], tgt[1][1], tgt[1][2], nt, idx)
        out.append('        if (%s) { %s } /* %s %s */' % (cond, body, cn, ' '.join(pats)))
    out.append('        break;')
out += ['    }', '    return -1000;', '}', '#define FC_NCASES %d' % len(CASES)]
names = ['"%s %s"' % (cn, ' '.join(pats)) for cn, pats, *_ in CASES]
out.append('static const char *fc_name[FC_NCASES] = {%s};' % ', '.join(names))
open(os.path.join(HERE, '..', 'c', 'fcases.h'), 'w').write('\n'.join(out) + '\n')
