"""page_close.py: the explainer section "closed" of status.json (the closed pass map, lean/Close.lean, and the long run
of c/crun.c), plus the claims, facts, verdict and summary that rest on them.

    python3 py/page_close.py && python3 holdouts/build_pages.py 1RB0RC_1LC1RE_1RA1LD_0LC0LA_1RF1RD_---0RD

Sources: lean/Close.lean (the near classes and orb_frames) and c/run_crun.txt (the log of `crun run`: lines
"at P frames steps tag a j r ...", "close pass P tag(a,j,r) d D").
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from page_jumps import sci

ROOT = os.path.join(HERE, '..')


def load_run():
    checks, close = [], []
    for line in open(os.path.join(ROOT, 'c', 'run_crun.txt')):
        p = line.split()
        if not p:
            continue
        if p[0] == 'close':
            a, j, r = (int(v) for v in p[3][2:-1].split(','))
            close.append((int(p[2]), p[3][0], a, j, r, int(p[5])))
        elif p[0] in ('at', 'END'):
            checks.append((int(p[1]), int(p[2]), int(p[3]), p[4], int(p[5]), int(p[6]), int(p[7])))
    return checks, sorted(set(close))


def lean_info():
    s = open(os.path.join(ROOT, 'lean', 'Close.lean')).read()
    nthm = len(re.findall(r'^theorem near_[yY]', s, re.M))
    m = re.search(r'theorem orb_frames : orb \(\.y 3 0 5\) (\d+) = some \((.*), (\d+)\) :=', s)
    t, a, j, r = m.group(2).lstrip('.').split()
    return nthm, int(m.group(1)), f'{t}({int(a):,}, {int(j):,}, {int(r):,})', int(m.group(3))


def build():
    checks, close = load_run()
    nthm, NO, st, FO = lean_info()
    P, F, S = checks[-1][0], checks[-1][1], checks[-1][2]
    pick = [c for c in checks if c[0] // 10 ** 10 in (1, 10, 100, 1000, 10000) and c[0] % 10 ** 10 < 10 ** 9] + [checks[-1]]
    seen, rows = set(), ''
    for p, f, s, t, a, j, r in pick:
        if p in seen:
            continue
        seen.add(p)
        rows += f'<tr><td>{p:,}</td><td>{sci(f)}</td><td>{sci(s)}</td><td><code>{t}({a:,}, {j:,}, {r:,})</code></td></tr>'
    near_rows = ''.join(f'<tr><td>{p:,}</td><td><code>{t}({a:,}, {b:,}, {r:,})</code></td><td>{d:+d}</td></tr>'
                        for p, t, a, b, r, d in close if abs(d) <= 2)
    sec = {
        'id': 'closed', 'eyebrow': 'Macro structure', 'heading': 'The closed pass map',
        'html': [
            '<p>The 13 cases of the section above leave out the passes within 6 of the line <code>r = q</code>. '
            f'<code>lean/Close.lean</code> closes the map: for each tag (y or Y), each <code>e = a mod 3</code>, each '
            'parity of <code>j</code> and each <code>&delta; = r &minus; q</code> from 0 to 6 the pass is again one '
            'chain of zigzags, sweeps and single frames, the same for all sizes (one exception splits off the sizes '
            f'<code>q = 1</code>). That is {nthm} more theorems, generated by <code>py/gen_close.py</code> from the '
            'jumps of <code>c/prun.c</code> and checked by Lean for all <code>q</code> and <code>j</code>. Exactly '
            'five classes do not reach a next zigzag start: they are the five halting rows.</p>',
            '<p>So <code>cpass</code>, the pass map with these cases, is defined on every zigzag start and gives either '
            'the next zigzag start with its frame count or a halt (<code>cpass_total</code>, <code>cpass_go</code>, '
            '<code>cpass_halt</code>). Every case maps an even alternating block to an even one '
            '(<code>cpass_even</code>), and the run from blank tape reaches its first zigzag start '
            '<code>y(3, 0, 5)</code> after 6 frames, so the three rows with odd <code>j</code> can never be met. '
            'Lean then proves the reduction:</p>',
            '<p class="callout"><b><code>halts_iff_row</code>.</b> The machine halts from blank tape if and only if the '
            'orbit of <code>y(3, 0, 5)</code> under the closed pass map reaches <code>y(a, j, r)</code> with '
            '<code>a &equiv; 1 (mod 3)</code> and <code>r = &lfloor;a/3&rfloor; + 2</code>, or '
            '<code>Y(a, j, r)</code> with <code>a &equiv; 1 (mod 3)</code> and <code>r = &lfloor;a/3&rfloor; + 3</code>.</p>',
            f'<p>This replaces the frame map, the jumps and the near-boundary fallback with one total map on three '
            f'numbers and a target set of two lines. <code>orb_frames</code> runs {NO:,} closed passes by '
            f'<code>native_decide</code> (ending at <code>{st}</code>, {FO:,} frames after the first zigzag start) '
            'and <code>no_row</code> follows: none of them is on a row.</p>',
            '<p><b>Growth runs in one step.</b> A growth pass sends <code>a = 3q + e</code> to <code>4q + c</code> with '
            '<code>c</code> fixed by the tag and <code>e</code>, so <code>k</code> growth passes in a row depend only on '
            '<code>a mod 3<sup>k</sup></code>: with <code>a = 3<sup>k</sup>Q + &rho;</code> the end state, the frames '
            'and the steps are polynomials in <code>Q</code> (degrees 1, 1 and 2), and the <code>k</code> passes are '
            'all growth passes iff <code>r</code> is at least a linear function of <code>Q</code> (the margin '
            '<code>r &minus; q &minus; 7</code> shrinks every pass, so the last one decides). <code>c/crun.c</code> '
            'builds these tables for <code>k &le; 7</code> at start-up from the single-pass formulas, by exact '
            'interpolation checked on further points and at the edge of the condition, and takes each growth run '
            'with the deepest table that applies; a drain is one step and the rare near passes go by jumps. It '
            'agrees with the pass-by-pass iteration (state, frames and steps) at every one of the 8.6&middot;10<sup>9</sup> '
            'table steps of the first 2&middot;10<sup>10</sup> passes (<code>crun check</code>), and runs about '
            '8.5&middot;10<sup>7</sup> passes a second, 2.6 times <code>prun</code> on the same core. A halt can only '
            'come from a near pass, which is never inside a table, and every start with <code>|d| &le; 3</code> is '
            'a drain or a near pass, so the close calls below are complete.</p>',
            f'<p><b>The run.</b> {P:,} passes from blank tape, {sci(F)} frames, <b>{sci(S)} machine steps</b>, no '
            'halt (steps are kept exactly, past 2<sup>128</sup>):</p>',
            '<div style="overflow-x:auto"><table class="tbl"><thead><tr><th>passes</th><th>frames</th><th>steps</th>'
            '<th>zigzag start</th></tr></thead><tbody>' + rows + '</tbody></table></div>',
            '<p>Zigzag starts within 2 of a halting row:</p>'
            '<div style="overflow-x:auto"><table class="tbl"><thead><tr><th>pass</th><th>zigzag start</th><th>d</th>'
            '</tr></thead><tbody>' + near_rows + '</tbody></table></div>',
        ]}
    return sec, (P, F, S, NO, FO, nthm)


def claims(P, F, S, NO, FO, nthm):
    return [
        {'level': 'kernel', 'title': 'The closed pass map', 'text':
         f'Every pass from a zigzag start within 6 of the boundary is one of {nthm} affine cases or one of the five '
         'halting rows, for all sizes; with the 13 cases of <code>lean/Pass.lean</code> the pass map <code>cpass</code> '
         'is total on zigzag starts (<code>cpass_total</code>), sound (<code>cpass_go</code>, <code>cpass_halt</code>), '
         'keeps <code>j</code> even (<code>cpass_even</code>) and halts exactly on the two rows with <code>j</code> even '
         '(<code>cpass_halt_iff</code>).', 'where': '<code>lean/Close.lean</code> (generated by <code>py/gen_close.py</code>)'},
        {'level': 'kernel', 'title': 'Halting is landing on one of two lines', 'text':
         '<code>halts_iff_row</code>: the machine halts from blank tape iff the orbit of <code>y(3, 0, 5)</code> under '
         'the closed pass map reaches <code>y(a, j, r)</code> with <code>a &equiv; 1 (mod 3)</code>, <code>r = &lfloor;a/3&rfloor; + 2</code> '
         'or <code>Y(a, j, r)</code> with <code>a &equiv; 1 (mod 3)</code>, <code>r = &lfloor;a/3&rfloor; + 3</code>.',
         'where': '<code>lean/Close.lean</code>'},
        {'level': 'native', 'title': f'No row in the first {NO:,} closed passes', 'text':
         f'<code>orb_frames</code>, by <code>native_decide</code>: the orbit is defined for {NO:,} passes ({FO:,} frames); '
         '<code>no_row</code>: none of them is on a row.', 'where': '<code>lean/Close.lean</code>'},
        {'level': 'trusted', 'title': f'No halt in the first {sci(S)} steps (the closed map, growth runs as one step)',
         'text': f'<code>c/crun.c</code> takes whole growth runs by residue tables mod 3<sup>k</sup>, checked step by '
         f'step against the pass-by-pass map on 2&middot;10<sup>10</sup> passes: {P:,} passes, {sci(F)} frames, '
         f'{sci(S)} machine steps, no halt.', 'where': '<code>c/crun.c</code>, <code>c/run_crun.txt</code>'},
    ]


if __name__ == '__main__':
    sec, nums = build()
    P, F, S, NO, FO, nthm = nums
    p = os.path.join(ROOT, 'status.json')
    st = json.load(open(p))
    ex = st['explainer']
    secs = [s for s in ex['sections'] if s['id'] != 'closed']
    i = next(k for k, s in enumerate(secs) if s['id'] == 'passes') + 1
    secs[i:i] = [sec]
    ex['sections'] = secs
    new = claims(*nums)
    cl = [c for c in st['claims'] if 'Close.lean' not in c['where'] and 'crun.c' not in c['where']]
    cl = [c for c in cl if c['title'] != 'Every small halt goes through a halting row']
    k = next(i for i, c in enumerate(cl) if c['level'] == 'heuristic' and 'expected' in c['title'])
    cl[k:k] = new
    st['claims'] = cl
    facts = [f for f in ex['facts'] if 'crun' not in f['text'] and 'halts_iff_row' not in f['value']]
    facts[0:0] = [{'level': 'trusted', 'value': f'{sci(S)} steps', 'text':
                   f'No halt in {sci(P)} passes of the closed pass map (<code>c/crun.c</code>, growth runs as one step).'},
                  {'level': 'kernel', 'value': '<code>halts_iff_row</code>', 'text':
                   'It halts iff the orbit of the closed pass map lands on one of two lines (<code>lean/Close.lean</code>).'}]
    ex['facts'] = facts
    v = st['verdict']
    v[0] = v[0].split(', and the closed pass map in C')[0].rstrip('.') + f', and the closed pass map in C none in the first {sci(S)}.'
    tail = (' <code>lean/Close.lean</code> closes the pass map: every pass near the boundary is one of '
            f'{nthm} more affine cases or a halting row, so <b>the machine halts iff the orbit of <code>y(3, 0, 5)</code> under '
            'one total map on three numbers lands on <code>y(a, j, a/3 + 2)</code> or <code>Y(a, j, a/3 + 3)</code> with '
            '<code>a &equiv; 1 mod 3</code></b> (<code>halts_iff_row</code>).')
    v[1] = v[1].split(' <code>lean/Close.lean</code> closes')[0]
    v[1] = v[1].replace(' Whether the orbit ever does is open.', '') + tail + ' Whether it ever does is open.'
    st['summary'] = st['summary'].split(' Closed pass map:')[0] + f' Closed pass map: no halt in {S:.3g} steps.'.replace('e+', 'e')
    json.dump(st, open(p, 'w'), indent=1, ensure_ascii=False)
    open(p, 'a').write('\n')
    print('passes %d frames %d steps %d; orb %d frames %d; %d near theorems' % nums)
