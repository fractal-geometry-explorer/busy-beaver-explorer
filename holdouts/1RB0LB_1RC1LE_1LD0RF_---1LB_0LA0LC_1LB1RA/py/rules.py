"""Shift rules and halting situations of 1RB0LB_1RC1LE_1LD0RF_---1LB_0LA0LC_1LB1RA, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LB_1RC1LE_1LD0RF_---1LB_0LA0LC_1LB1RA/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LB_1RC1LE_1LD0RF_---1LB_0LA0LC_1LB1RA"
NS = "H154458"
DOC = """# Shift rules of 1RB0LB_1RC1LE_1LD0RF_---1LB_0LA0LC_1LB1RA

Two crossings that the run uses: A, with a 1 behind it, turns `01` into `10` going right (`walk_A`), and B, with
`11` ahead, turns `0101` into `1010` going left (`walk_B`).  The halting situations: only D reading a 0 halts, and
`0 C> 0`, `0 0 E> 1`, `0 0 1 B> 1` and `0 0 A> 0 1` lead there.

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('walk_A', 'L 1 A> (01)^n R', 'L (10)^n 1 A> R', 'A, carrying a 1, turns each `01` into `10`, eight steps a copy.'),
    ('walk_B', 'L (0101)^n B> 1 1 R', 'L B> 1 1 (1010)^n R', 'B, with `11` ahead, turns each `0101` into `1010` going left, 22 steps a copy.'),
]

HALTS = [
    ('halt_C', '0 C> 0', 1, '`0 C> 0` halts: C writes 1 and steps left onto the 0 in state D.'),
    ('halt_E', '0 0 E> 1', 2, '`0 0 E> 1` halts: E steps left in state C onto a 0, then D reads the next 0.'),
    ('halt_B', '0 0 1 B> 1', 3, '`0 0 1 B> 1` halts after three steps.'),
    ('halt_A', '0 0 A> 0 1', 4, '`0 0 A> 0 1` halts after four steps.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [prove(M, name, a, b, doc=doc, count_first=True)[0] for name, a, b, doc in RULES]
    thms += [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
