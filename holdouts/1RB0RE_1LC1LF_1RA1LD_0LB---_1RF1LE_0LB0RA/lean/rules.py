"""Generate Rules.lean: shift rules of 1RB0RE_1LC1LF_1RA1LD_0LB---_1RF1LE_0LB0RA, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(10)^n` is n
copies of `10`, `0^inf` is blank tape, L and R are any tape.  What the rules mean is in ../README.md.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC1LF_1RA1LD_0LB---_1RF1LE_0LB0RA"

RULES = [
    ('sweep_left', 'L 1 (001)^n B> 0 R', 'L 1 B> 0 (011)^n R',
     'Leftward, B turns a block of `100` words into `110` words, three steps per word.'),
    ('sweep_right', 'L 0 0 A> (110)^n+1 1 0 R', 'L 0 0 (100)^n 1 0 0 0 1 F> R',
     'Rightward, A and E turn a block of n+1 words `110` back into `100` words, seven steps per word.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=30)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H129533", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
