"""The ends of the branch table that `Branch.lean` left open: the right phases that end with an odd run of
`1111011` (two runs, `gendo`; three runs, `g3endo`), the odd-type right phase that ends with an even run of
`1111110` (`rende`), and the odd-type round trip with no `10` left (`ozero`).

usage: python3 holdouts/1RB0LE_1RC---_1RD1RE_1LA0RF_0RC0LA_0LC0RB/py/ends.py     writes lean/Ends.lean
                                                                                 (needs lean/Branch.lean)

Same method as `py/branch.py`: each rule is a symbolic run (`bbtools.symtm.prove`) followed by the proof that its end
tape is the stated form (`py/tapeeq.py`).  The step counts are the ones `py/macro.py` uses.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import rules_file, parse_lin  # noqa: E402
from tapeeq import defn, rule  # noqa: E402
from branch import FORMS, LG, LG3, term  # noqa: E402
import macro  # noqa: E402

NS = "H113677"
ODD = "1 1 1 1 0 1 1 1 0 0 1"   # the last unpaired 1111011 and the 1001 after it
FORMS = dict(FORMS)
FORMS.update({
    "RG2o": lambda a, x, q, m: (f"0^inf (1110)^{a} {LG} (10)^{x} (11110111111011)^{q} {ODD} (10)^{m} 1 E> 0^inf"),
    "RG3o": lambda a, x, y, q, m: (f"0^inf (1110)^{a} {LG3} (10)^{x} 1 1 1 0 0 1 (10)^{y} (11110111111011)^{q} "
                                   f"{ODD} (10)^{m} 1 E> 0^inf"),
    "RF2e": lambda a, q, m: f"0^inf (1110)^{a} (11111101111110)^{q} 1 1 1 0 0 1 (10)^{m} 1 E> 0^inf",
})
NEW = {
    "RG2o": (["a", "x", "q", "m"], "`RG a x (2q+1) m` with the run of `1111011` in pairs and one left over."),
    "RG3o": (["a", "x", "y", "q", "m"], "`RG3 a x y (2q+1) m` with the run of `1111011` in pairs and one left over."),
    "RF2e": (["a", "q", "m"], "`RF a (2q) m` with the run of `1111110` in pairs."),
}
DOCS = {
    "gendo": "The end of a two-run right phase with an odd run of `1111011`: a round trip with five `0010`-runs' "
             "worth of words, the old left run now the `0010` run.",
    "g3endo": "The end of a three-run right phase with an odd run of `1111011`.",
    "rende": "The end of an odd-type right phase with an even run of `1111110`: an odd-type round trip with no `10`.",
    "ozero": "An odd-type round trip with no `10`: it turns into the 5-visit cycle form with no runs, which is `S1`.",
}
NAMES = ["gendo", "g3endo", "rende", "ozero"]

DOC = """# The ends of the branch table

`RG2o`, `RG3o` write an odd run of `1111011` as pairs and one left over; `RF2e` writes an even run of `1111110` in
pairs.  `gendo` (two-run right phase, odd run), `g3endo` (three-run right phase, odd run) and `rende` (odd-type right
phase, even run) are the ends that `Branch.lean` left open, and `ozero` the odd-type round trip they lead to when it
has no `10` (via `rende`).  `gendo'`, `g3endo'`, `rende'` state them on `RG`, `RG3`, `RF`; `t3_s1` says a `T3` with
no runs is an `S1`.  With these the table has a rule for every configuration the run reaches through 10^300 steps
(`py/macro.py`).

Generated by `py/ends.py`."""

LEMMAS = """/-- An odd run of `1111011` in a two-run right phase, written as pairs and one left over. -/
theorem rg_odd (a x q m : Nat) : RG a x (2 * q + 1) m = RG2o a x q m := by
  simp only [RG, RG2o, rep_succ, rep_double, List.cons_append, List.nil_append]
  rfl

/-- An odd run of `1111011` in a three-run right phase, written as pairs and one left over. -/
theorem rg3_odd (a x y q m : Nat) : RG3 a x y (2 * q + 1) m = RG3o a x y q m := by
  simp only [RG3, RG3o, rep_succ, rep_double, List.cons_append, List.nil_append]
  rfl

/-- An even run of `1111110` in an odd-type right phase, written as pairs. -/
theorem rf_even (a q m : Nat) : RF a (2 * q) m = RF2e a q m := by
  simp only [RF, RF2e, rep_double, List.cons_append, List.nil_append]

/-- The end of a two-run right phase whose run of `1111011` has odd length 2q+7. -/
theorem gendo' (a x q : Nat) :
    ∃ n, steps n (RG (a + 3) (x + 6) (2 * q + 7) 1) = some (T3 1 6 a 11 (x + 14) (q + 1)) := by
  rw [show 2 * q + 7 = 2 * (q + 3) + 1 by omega, rg_odd]
  exact ⟨_, gendo a q x⟩

/-- The end of a three-run right phase whose run of `1111011` has odd length 2q+7. -/
theorem g3endo' (a x y q : Nat) :
    ∃ n, steps n (RG3 (a + 7) (x + 10) (y + 2) (2 * q + 7) 1) = some (T3 5 14 a 15 (x + y + 17) (q + 1)) := by
  rw [show 2 * q + 7 = 2 * (q + 3) + 1 by omega, rg3_odd]
  exact ⟨_, g3endo a q x y⟩

/-- The end of an odd-type right phase whose run of `1111110` has even length 2q. -/
theorem rende' (a q : Nat) : ∃ n, steps n (RF a (2 * q) 1) = some (O a 0 (q + 1)) := by
  rw [rf_even]
  exact ⟨_, rende a q⟩

/-- A 5-visit cycle form with no runs is the 4-visit cycle form. -/
theorem t3_s1 (a z c : Nat) : T3 a 0 0 0 z c = S1 a z c := rfl
"""


def nozero(s):
    """Drop runs written with count 0 (`rep 0 w s` is `s` by definition, so the stated form is unchanged)."""
    return re.sub(r"\([01]+\)\^0 ", "", s)


def main():
    parts = ["set_option maxRecDepth 100000\n"]
    for f, (args, doc) in NEW.items():
        parts.append(defn(f, args, FORMS[f], doc))
    for name in NAMES:
        f, args, tf, targs, _steps = macro.RULES[name]
        vs = sorted({v for a in args for v in parse_lin(a).c})
        lhs = f"{f} " + " ".join(term(a) for a in args)
        rhs = f"{tf} " + " ".join(term(a) for a in targs)
        parts += rule(name, nozero(FORMS[f](*args)), nozero(FORMS[tf](*targs)), vs, lhs, rhs, DOCS[name])
    parts.append(LEMMAS)
    with open(os.path.join(HERE, "..", "lean", "Ends.lean"), "w") as fh:
        fh.write(rules_file("Branch", NS, parts, DOC))


if __name__ == "__main__":
    main()
