"""Shift rules of 1RB0LE_1RC---_1RD1RE_1LA0RF_0RC0LA_0LC0RB, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LE_1RC---_1RD1RE_1LA0RF_0RC0LA_0LC0RB/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L 1 0 C> (10)^n R` is the head
in state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LE_1RC---_1RD1RE_1LA0RF_0RC0LA_0LC0RB"
NS = "H113677"
DOC = """# Shift rules of 1RB0LE_1RC---_1RD1RE_1LA0RF_0RC0LA_0LC0RB

The passes of the machine over the regular parts of its tape: C moving right over `10` (`pass_10_right`), A moving
left over `01` (`pass_10_left`), F and B moving right turn `1000`/`0001` into `1110` (`fill_F`, `fill_B`), A moving
left turns `0111` into `0010` (`clear_A`).  The only halt is B reading a 1; B is entered from A reading a 0 and
from F reading a 1, both stepping right, so `A> 0 1` and `F> 1 1` halt after two steps (`halt_A`, `halt_F`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

# Lean options put before the first theorem (the long words need a deeper recursion limit)
OPTIONS = ''

RULES = [
    ('pass_10_right',
     'L C> (10)^n R',
     'L (10)^n C> R',
     'C moving right over the alternating part, one step a cell.'),
    ('pass_10_left',
     'L (01)^n A> 1 0 R',
     'L A> 1 0 (01)^n R',
     'A moving left over the alternating part, eight steps a copy of `01`.'),
    ('fill_F',
     'L F> (1000)^n R',
     'L (1110)^n F> R',
     'F moving right turns each `1000` into `1110`, ten steps a copy.'),
    ('fill_B',
     'L 0 B> (0001)^n R',
     'L (1110)^n 0 B> R',
     'B moving right turns each `0001` into `1110`, ten steps a copy.'),
    ('clear_A',
     'L (0111)^n A> 1 R',
     'L A> 1 (0010)^n R',
     'A moving left turns each `0111` into `0010`, ten steps a copy.')
]

# hand-written statements appended to the file (the halting situations), proved by `rfl`
EXTRA = """/-- `A> 0 1` halts: A writes a 1 and steps right in state B onto a 1, which has no transition. -/
theorem halt_A (L R : Tape) :
    ∃ c, steps 1 ⟨L, cons false (cons true R), .A⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩

/-- `F> 1 1` halts: F writes a 0 and steps right in state B onto a 1. -/
theorem halt_F (L R : Tape) :
    ∃ c, steps 1 ⟨L, cons true (cons true R), .F⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩
"""


def main():
    thms = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    thms[0] = OPTIONS + thms[0]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
