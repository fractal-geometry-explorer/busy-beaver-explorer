"""Write lean/Rules.lean for 1RB1RE_0RC0RF_1LC1RD_1RA0LE_0RA0LD_0RA---: the rightward sweep over the b-block,
proved by symbolic simulation (tools/py/bbtools/symtm.py) for all lengths and any tapes L, R.

  b = 111010.  b_right: L 0 A> b^n R -> L (010111)^n 0 A> R  in 10n steps, i.e. the block is crossed unchanged
  (0 b^n = (010111)^n 0), the head carrying the 0 along.

usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/<M>/py/gen_rules.py > holdouts/<M>/lean/Rules.lean
"""
import os
import re

from bbtools import symtm

M = '1RB1RE_0RC0RF_1LC1RD_1RA0LE_0RA0LD_0RA---'
RULES = [
    ('b_right', 'the rightward sweep over the b-block: crossed unchanged in 10 steps per b',
     'L 0 A> (111010)^n R', 'L (010111)^n 0 A> R'),
]


def main(ID):
    thms = [symtm.prove(M, n, a, b, doc=d, rotate=True)[0] for n, d, a, b in RULES]
    print(symtm.rules_file('Machine', 'H' + ID, thms, f'Rules of {M}, generated by py/gen_rules.py (symbolic '
                           'simulation, `tools/py/bbtools/symtm.py`).'), end='')


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    main(re.search(r'namespace H(\d+)', open(os.path.join(here, '..', 'lean', 'Machine.lean')).read()).group(1))
