"""Writes lean/DMRules.lean: the pieces of the halts-iff map of 1RB1RD_1LC0RD_1RF1RB_1LE0RA_0LB0LE_---0RC on
C(k, a, b) = 0^inf (10101)^k C> 0 1 0 1^a 0 1^b 0^inf, the map DeepMind's cryptids proves in Mathlib Lean.  Each piece
is proved by `bbtools.symtm`; lean/DMMap.lean chains them.  usage: python3 dmrules.py > ../lean/DMRules.lean"""
import os, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, Halted, prove, rules_file, run, step  # noqa: E402

M = "1RB1RD_1LC0RD_1RF1RB_1LE0RA_0LB0LE_---0RC"
# (name, doc, start, end); X is any left tape, R any right tape, n a count
RULES = [
    ("sw_b1", "E sweeps left over a `1`: one more 1 on the right.", "X 1 E> 0 1 R", "X E> 0 1 1 R"),
    ("sw_b01", "E sweeps left over `01`: two more 1s.", "X 1 0 E> 0 1 R", "X E> 0 1 1 1 R"),
    ("sw_b5", "E sweeps left over `10101`: five more 1s.", "X 1 0 1 0 1 E> 0 1 R", "X E> 0 1 1 1 1 1 1 R"),
    ("sw_nil", "E reaches `00`: the next C-configuration.", "X 0 0 E> 0 1 R", "X C> 0 1 0 1 R"),
    ("shA", "A crosses `11`, leaving `01`.", "X A> 1 1 R", "X 1 0 A> R"),
    ("bB", "B starts a bounce on `11`.", "X B> 1 1 R", "X 0 0 A> R"),
    ("aE0", "A at the right end.", "X A> 0^inf", "X E> 0 1 1 0 0^inf"),
    ("aE3", "A before `1110`.", "X A> 1 1 1 0 R", "X E> 0 1 0 1 R"),
    ("aB", "A before a 0 inside the tape: B on the next block.", "X A> 0 R", "X 1 B> R"),
    ("cA", "C before four 1s: push `10101`, A starts crossing.", "X C> 0 1 0 1 1 1 1 R", "X 1 0 1 0 1 0 0 A> R"),
    ("b0", "Drain of 0 ones.", "X 1 B> 0^inf", "X E> 0 1 1 0 0^inf"),
    ("b1", "Drain of 1 one.", "X 1 B> 1 0^inf", "X E> 0 1 1 0 0^inf"),
    ("b3", "Drain of 3 ones.", "X 1 B> 1 1 1 0^inf", "X E> 0 1 1 0 1 0^inf"),
    ("c2", "C with a = 2, b = 0.", "X C> 0 1 0 1 1 0 0^inf", "X 1 0 1 0 1 E> 0 1 0 0^inf"),
    ("c2_2", "C with a = 2, b = 2.", "X C> 0 1 0 1 1 0 1 1 0^inf", "X 1 0 1 0 1 E> 0 1 0 1 0^inf"),
    ("c2b", "C with a = 2, b >= 1.", "X C> 0 1 0 1 1 0 1 R", "X 1 0 1 0 1 B> 1 1 R"),
    ("c3", "C with a = 3.", "X C> 0 1 0 1 1 1 0 1^n 0^inf", "X 1 0 1 0 1 E> 0 1 1^n 0 0^inf"),
    ("c5", "C with a = 5.", "X C> 0 1 0 1 1 1 1 1 0 R", "X 1 0 1 0 1 E> 0 1 0 1 R"),
    ("c1", "C with a = 1, b >= 2.", "X C> 0 1 0 1 0 1 1 R", "X 1 0 1 0 1 0 1 B> R"),
    ("blank_C", "From blank tape to C(0, 2, 0).", "0^inf A> 0^inf", "0^inf C> 0 1 0 1 1 0 0^inf"),
]
HALTS = [
    ("halt_b5", "Drain of 5 ones: the machine halts.", "X 1 B> 1 1 1 1 1 0^inf"),
    ("halt_a0", "C with a = 0: the machine halts.", "X C> 0 1 0 0 R"),
    ("halt_a1b0", "C with a = 1, b = 0: the machine halts.", "X C> 0 1 0 1 0 0^inf"),
    ("halt_a1b1", "C with a = 1, b = 1: the machine halts.", "X C> 0 1 0 1 0 1 0^inf"),
]


def halt_end(start):
    """The configuration just before the halting transition."""
    m = Machine.parse(M)
    cfg = Config.parse(start)
    for _ in range(100000):
        c2 = cfg.copy()
        try:
            step(m, c2)
        except Halted:
            return cfg
        run(m, cfg, lambda c, n=[0]: (n.__setitem__(0, n[0] + 1) or n[0] > 1), max_moves=2, rotate=True)
    raise RuntimeError("no halt")


def main():
    ths = []
    for name, doc, s, e in RULES:
        th, fin = prove(M, name, s, e, doc=doc, rotate=True, count_first=True, max_seg=40)
        print(f"-- {name}: {fin}", file=sys.stderr)
        ths.append(th)
    for name, doc, s in HALTS:
        end = halt_end(s)
        th, fin = prove(M, name, s, end, doc=doc, rotate=True, count_first=True, max_seg=40)
        print(f"-- {name}: {fin}", file=sys.stderr)
        ths.append(th)
    sys.stdout.write(rules_file("Machine", "H135376", ths,
                                f"Pieces of the halts-iff map of {M}, generated by `py/dmrules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
