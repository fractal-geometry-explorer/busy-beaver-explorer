"""Generate Rules.lean: rules of 1RB1RD_1LC0RD_1RF1RB_1LE0RA_0LB0LE_---0RC, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right, `S>` is the head in state S on the next cell.  A round starts at
`0^inf B> 0 0 1^n ...` (the head at the left end).  For even n the round is a sweep: the start turns `(11)^(p+2)` into
`10101 0 (01)^p 0 A>`, each `pass` turns one `01` into one `10101`, and `end1` (or `end0`) turns the `10101`s back
into 1s: n = 2p + 4 becomes 5p + 11 = 5n/2 + 1 (Macro.lean).  The other rules are the first rounds from blank tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine, STATES  # noqa: E402
from bbtools.symtm import Blank, Config, Halted, prove, rules_file, run  # noqa: E402

M = "1RB1RD_1LC0RD_1RF1RB_1LE0RA_0LB0LE_---0RC"

RULES = [
    ("blank_start", "0^inf A> 0^inf", "0^inf B> 0 0 11 0^inf", "From blank tape: the round start with n = 2."),
    ("round2", "0^inf B> 0 0 11 0^inf", "0^inf B> 0 0 (1)^6 0^inf", "The round from n = 2: n = 6."),
    ("round41", "0^inf B> 0 0 (1)^41 0^inf", "0^inf B> 0 0 (1)^36 0 (1)^7 0^inf",
     "The round from n = 41 (odd): two blocks, 36 and 7."),
    ("round36_7", "0^inf B> 0 0 (1)^36 0 (1)^7 0^inf", "0^inf B> 0 0 (1)^106 0^inf",
     "The round from the two blocks 36, 7: n = 106."),
    ("entry", "0^inf B> 0 0 (11)^p+2 0^inf", "0^inf 10101 0 (01)^p 0 A> 0^inf",
     "An even round starts: the head runs right, leaving one `10101` and `p` copies of `01`."),
    ("pass", "0^inf (10101)^j 0 (01)^k+2 0 A> 0^inf", "0^inf (10101)^j+1 0 (01)^k+1 0 A> 0^inf",
     "One sweep: a `01` becomes a `10101`."),
    ("end1", "0^inf (10101)^j 0 01 0 A> 0^inf", "0^inf B> 0 0 1111 (11111)^j 1111111 0^inf",
     "The last `01`: the `10101`s become 1s and the next round starts."),
    ("end0", "0^inf (10101)^j 0 0 A> 0^inf", "0^inf B> 0 0 1111 (11111)^j 11 0^inf",
     "The same with no `01` left (n = 4)."),
    ("odd_sweep", "L C> 0 1 0 1 (11)^m+3 0 (1)^y+1 0 R", "L 10101 C> 0 1 0 1 (11)^m 0 1 (1)^y+1 0 R",
     "One sweep on an odd block (README, rule T1): `w^i C> 0 1 0 1^x 0 1^y` with x = 2m + 7 loses six 1s, a `10101` "
     "appears on its left and the next block grows by one.  Any tape on both sides."),
    ("odd_sweep_new", "L C> 0 1 0 1 (11)^m+3 0 0 R", "L 10101 C> 0 1 0 1 (11)^m 0 1 0 R",
     "The same when no block follows: a new block of one 1 appears."),
    ("end3", "0^inf (10101)^i C> 0 1 0 111 0 (1)^y+1 0 R", "0^inf B> 0 0 1 1 1 1 (11111)^i 1 1 (1)^y+1 0 R",
     "End of a round with three 1s left: everything up to the end of the next block becomes one block of "
     "5i + 6 + (y+1) ones."),
    ("end3_new", "0^inf (10101)^i C> 0 1 0 111 0 0 R", "0^inf B> 0 0 1 1 1 1 (11111)^i 1 1 0 R",
     "The same with no next block: 5i + 6 ones."),
    ("end5", "0^inf (10101)^i C> 0 1 0 11111 0 (1)^y+1 0 R", "0^inf B> 0 0 1 1 1 1 (11111)^i 1 1 0 1 (1)^y+1 0 R",
     "End of a round with five 1s left: a block of 5i + 6 ones, and the next block grows by one."),
    ("end5_new", "0^inf (10101)^i C> 0 1 0 11111 0 0 R", "0^inf B> 0 0 1 1 1 1 (11111)^i 1 1 0 1 0 R",
     "The same with no next block: blocks 5i + 6 and 1."),
    ("end2", "0^inf (10101)^i C> 0 1 0 11 0^inf", "0^inf B> 0 0 1 1 1 1 (11111)^i 1 1 0^inf",
     "End of a round with two 1s left and nothing after: 5i + 6 ones."),
    ("halt1", "0^inf (10101)^i C> 0 1 0 1 0^inf", "halt",
     "One 1 left and nothing after: the machine reaches the halting transition F0."),
]


def before_halt(start):
    """The configuration the run from `start` halts in (head on a cell whose transition is undefined)."""
    m = Machine.parse(M)
    c = Config.parse(start)
    while True:
        prev = c.copy()
        try:
            run(m, c, lambda _: False, max_moves=1, rotate=True)
        except Halted:
            return prev
        except RuntimeError:
            pass


def main():
    ths = []
    for name, a, b, doc in RULES:
        if b == "halt":
            b = before_halt(a)
        ths.append(prove(M, name, a, b, doc=doc, rotate=True, max_seg=40)[0])
    ns = "H" + open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "Machine.lean")).read().split(
        "namespace H")[1].split()[0]
    sys.stdout.write(rules_file("Machine", ns, ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
