"""Generate lean/Rules.lean for 1RB1RA_1LC0RD_1LD1LB_1LE0LF_0RA---_0LB0LF: sweep rules for all n, each proved by a symbolic run of bbtools.symtm.

L and R are arbitrary tapes the sweep does not look at.

usage: python3 py/gen_rules.py > lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "..", "tools", "py"))
from bbtools import symtm  # noqa: E402

M = "1RB1RA_1LC0RD_1LD1LB_1LE0LF_0RA---_0LB0LF"
NS = "H123029"
RULES = [
    ('sweep_l_B_10', '`L (10)^n 1 B> 0 R` to `L C> 1 (11)^n 1 R` in 2*n+1 steps.',
     'L (10)^n 1 B> 0 R',
     'L C> 1 (11)^n 1 R'),
    ('sweep_l_B_110', '`L (110)^n 1 1 B> 0 R` to `L B> 1 1 (100)^n 1 R` in 5*n+2 steps.',
     'L (110)^n 1 1 B> 0 R',
     'L B> 1 1 (100)^n 1 R'),
    ('sweep_l_C_01', '`L (01)^n 0 C> 1 R` to `L B> 0 (11)^n 1 R` in 2*n+1 steps.',
     'L (01)^n 0 C> 1 R',
     'L B> 0 (11)^n 1 R'),
    ('sweep_r_A_1', '`L A> (1)^n R` to `L (1)^n A> R` in n steps.',
     'L A> (1)^n R',
     'L (1)^n A> R'),
    ('sweep_l_F_1', '`L (1)^n  F> 1 R` to `L F> 1 (0)^n R` in n steps.',
     'L (1)^n  F> 1 R',
     'L F> 1 (0)^n R'),
    ('sweep_l_C_011', '`L (011)^n 0 1 C> 1 R` to `L B> 0 (001)^n 0 0 R` in 5*n+4 steps.',
     'L (011)^n 0 1 C> 1 R',
     'L B> 0 (001)^n 0 0 R'),
    ('sweep_r_B_100', '`L B> (100)^n R` to `L (011)^n B> R` in 5*n steps.',
     'L B> (100)^n R',
     'L (011)^n B> R'),
    ('sweep_r_A_11', '`L A> (11)^n R` to `L (11)^n A> R` in 2*n steps.',
     'L A> (11)^n R',
     'L (11)^n A> R'),
    ('sweep_l_D_11', '`L (11)^n 1 D> 1 R` to `L F> 1 (00)^n 0 R` in 2*n+1 steps.',
     'L (11)^n 1 D> 1 R',
     'L F> 1 (00)^n 0 R'),
    ('sweep_l_F_11', '`L (11)^n 1 F> 1 R` to `L F> 1 (00)^n 0 R` in 2*n+1 steps.',
     'L (11)^n 1 F> 1 R',
     'L F> 1 (00)^n 0 R'),
]

if __name__ == "__main__":
    ts = []
    for name, doc, start, end in RULES:
        t, _ = symtm.prove(M, name, start, end, count_first=True, doc=doc)
        ts.append(t)
    print(symtm.rules_file("Machine", NS, ts, "Sweep rules of " + M + ", generated by `py/gen_rules.py` (do not edit)."), end="")
