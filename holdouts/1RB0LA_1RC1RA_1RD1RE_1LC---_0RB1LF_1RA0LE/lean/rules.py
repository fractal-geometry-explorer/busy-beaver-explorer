"""Generate Rules.lean for 1RB0LA_1RC1RA_1RD1RE_1LC---_0RB1LF_1RA0LE: the halting context and the shift rules over the words of its tape, proved along the symbolic run of tools/py/bbtools/symtm.py
(single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LA_1RC1RA_1RD1RE_1LC---_0RB1LF_1RA0LE"

RULES = [
    ('halt_ctx_B', 'L B> 0 0 1 R', 'L 1 1 D> 1 R',
     'B on `0 0 1`: B and C write 1s and D reads the 1 (the halting transition).'),
    ('halt_ctx_A', 'L A> 0 0 0 1 R', 'L 1 1 1 D> 1 R',
     'A on `0 0 0 1`: A, B and C write 1s and D reads the 1 (the halting transition).'),
    ('halt_ctx_B1', 'L 0 B> 1 1 1 R', 'L 1 1 1 D> 1 R',
     'B on `1 1 1` after a 0: A erases the two 1s, turns on the 0 and B meets `0 0 1`.'),
    ('halt_ctx_F', 'L 0 F> 0 1 1 R', 'L 1 1 1 D> 1 R',
     'F on `0 1 1` after a 0: as `halt_ctx_B1`.'),
    ('halt_ctx', 'L C> 0 1 R', 'L 1 D> 1 R',
     'C on a 0 with a 1 after it hands D a 1 (the halting transition).'),
    ('run_A_01', 'L A> (01)^n R', 'L (11)^n A> R',
     'A crosses n copies of `01` to the right in 2n steps, leaving `11`.'),
    ('back_A_1_1', 'L (1)^n A> 1 R', 'L A> 1 (0)^n R',
     'A crosses n copies of `1` to the left in 1n steps, leaving `0` (carrying `1`).'),
    ('run_B_10', 'L B> (10)^n R', 'L (11)^n B> R',
     'B crosses n copies of `10` to the right in 2n steps, leaving `11`.'),
    ('run_C_100', 'L C> (100)^n R', 'L (101)^n C> R',
     'C crosses n copies of `100` to the right in 3n steps, leaving `101`.'),
    ('back_E_100_10', 'L (100)^n E> 1 0 R', 'L E> 1 0 (101)^n R',
     'E crosses n copies of `100` to the left in 13n steps, leaving `101` (carrying `1 0`).'),
    ('run_E_001', 'L E> (001)^n R', 'L (011)^n E> R',
     'E crosses n copies of `001` to the right in 3n steps, leaving `011`.'),
    ('back_F_001_1', 'L (001)^n F> 1 R', 'L F> 1 (101)^n R',
     'F crosses n copies of `001` to the left in 13n steps, leaving `101` (carrying `1`).'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H124869", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
