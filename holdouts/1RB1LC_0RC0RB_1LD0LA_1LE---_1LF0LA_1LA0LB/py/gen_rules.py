"""Write lean/Rules.lean: the tick rules of the two counters, for every header the run uses (found by running
counters.py for a while), proved along the symbolic run of tools/py/bbtools/symtm.py.

usage: python3 gen_rules.py MACHINE NAMESPACE [STEPS] > ../../MACHINE/lean/Rules.lean
"""
import sys
from counters import make, HERE
sys.path.insert(0, HERE)
from bbtools.symtm import prove, rules_file

M, ns = sys.argv[1], sys.argv[2]
steps = float(sys.argv[3]) if len(sys.argv) > 3 else 1e9
c = make(M, log=lambda *a: None)
c.run(steps, max_direct=10 ** 10)
keys = sorted(c.headers)
D0, D1, P0, P1, S = c.D0, c.D1, c.P0, c.P1, c.Sn
ths = []
for n, (G, H) in enumerate(keys):
    Hs = H[0] + " " + H[1:]
    for nm, s, e, doc in [
        (f"tick{n}_odd", f"L {D0} ({D1})^j {G} {S}> {Hs} {P1} R", f"L {D1} ({D0})^j {G} {S}> {Hs} {P0} R",
         f"Tick (gap `{G}`, header `{H}`), V odd: U = x0 1^j becomes x1 0^j (j carries), V loses its lowest 1."),
        (f"tick{n}_even", f"L {D0} ({D1})^j {G} {S}> {Hs} ({P0})^i+1 {P1} R",
         f"L {D1} ({D0})^j {G} {S}> {Hs} ({P1})^i+1 {P0} R",
         f"Tick (gap `{G}`, header `{H}`), V with i+1 trailing zeros: U + 1 with j carries, V - 1 with i+1 borrows.")]:
        t, _ = prove(M, nm, s, e, doc=doc, rotate=True, max_seg=30)
        ths.append(t)
doc = ("The tick rules of the two counters (generated by the family's py/gen_rules.py).\n\n"
       f"Left of the head: the counter U, digits `{D0}` (0) and `{D1}` (1), least significant next to the gap; right of "
       f"the header: the counter V, pairs `{P0}` (0) and `{P1}` (1), least significant first. Every tick adds 1 to U "
       "and takes 1 from V, for every number of carries j and borrows i + 1, and every tape L, R beyond them.")
print(rules_file("Machine", ns, ths, doc), end="")
