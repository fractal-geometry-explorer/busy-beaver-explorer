"""Lean theorems for the short rebuilds: the residue classes of N mod 2^j for which the rebuild after V = 0 only
reads the lowest j digits of the up-counter.

For such a class, with header H and down-counter length n (symbolic),

    L  d_{j-1} ... d_0  G  S>  H  (P0)^(n+k)  1  0^inf   -->   L  G  S>  H'  w  (P1)^(n+e)  1  0^inf

where d_i are the digit words of r (r = N mod 2^j), L is any tape (the rest of the counter: N >> j), and w the
digits of 2^m - delta: the new down-counter is 2^(n+k+c) - delta.  The classes and (H', c, delta) are found with
rebuild.py on sample values; the theorem is then proved for every n and every L by bbtools.symtm (symbolic run,
shift rules, Lean proof by rfl steps), so the sampling only chooses what to prove.

usage: python3 gen_rebuild_rules.py MACHINE NAMESPACE JMAX [MAXCLASSES] > lean/Rebuild.lean
"""
import os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, ProofError
from rebuild import Rebuilder


def classes(rb, H, jmax):
    """(j, r, H', c, delta): residues r mod 2^j whose rebuild gives N' = N >> j, the same (H', c, delta) on three
    samples, and no shorter class covers r"""
    out = []
    for j in range(1, jmax + 1):
        for r in range(1 << j):
            if any(r % (1 << jj) == rr for (jj, rr, *_ ) in out): continue
            outs = set(); ok = True
            for a in (5, 9, 12):
                N = (a << j) | r
                N |= 1 << (N.bit_length() + 3)
                N = rb.value("1", N.bit_length() - 1, N - (1 << (N.bit_length() - 1))) if rb.forms[0] == "1" else N
                n = N.bit_length()
                res = rb.rebuild(H, n, N)
                if res[0] != "OK": ok = False; break
                H2, n2, N2, V2, f2, L2 = res[2]
                if N2 != N >> j: ok = False; break
                outs.add((H2, n2 - n, (1 << n2) - V2))
            if ok and len(outs) == 1:
                H2, c, d = outs.pop()
                out.append((j, r, H2, c, d))
    return out


def rule_text(rb, H, j, r, H2, c, d):
    m = d.bit_length()
    k = max(1, m - c + 1)
    e = k + c - m
    digs = " ".join(rb.D1 if (r >> i) & 1 else rb.D0 for i in reversed(range(j)))
    w = " ".join(rb.P1 if ((1 << m) - d) >> i & 1 else rb.P0 for i in range(m))
    Hs = H[0] + " " + H[1:]
    H2s = H2[0] + " " + H2[1:]
    start = f"L {digs} {rb.G} {rb.S}> {Hs} ({rb.P0})^n+{k} 1 0^inf"
    end = f"L {rb.G} {rb.S}> {H2s} {w} ({rb.P1})^n+{e} 1 0^inf"
    return start, end, k, e


def main():
    M, ns, jmax = sys.argv[1], sys.argv[2], int(sys.argv[3])
    maxc = int(sys.argv[4]) if len(sys.argv) > 4 else 10 ** 9
    rb = Rebuilder(M)
    thms = []; done = []
    for H in rb.hdr:
        for (j, r, H2, c, d) in classes(rb, H, jmax)[:maxc]:
            start, end, k, e = rule_text(rb, H, j, r, H2, c, d)
            name = f"rebuild_{H}_{j}_{r}"
            doc = (f"Header {H}, N = {r} (mod 2^{j}): the rebuild reads only the lowest {j} digits and gives header "
                   f"{H2}, up-counter N >> {j} (the tape L), down-counter 2^(n+{k + c}) - {d} of n + {k + c} digits. "
                   f"`{start}` --> `{end}` ")
            try:
                t, f = prove(M, name, start, end, doc=doc, rotate=True, max_seg=30)
            except ProofError as ex:
                print(f"-- {name}: not proved ({ex})", file=sys.stderr); continue
            thms.append(t)
            done.append((H, j, r, H2, c, d))
            print(f"-- {name}: proved", file=sys.stderr)
    print(f"import Machine\n\n/-! Rebuild rules of {M}, generated by py/gen_rebuild_rules.py: {len(thms)} theorems.\n"
          f"Classes (header, j, N mod 2^j, new header, extra digits c, delta):\n" +
          "\n".join(f"  {x}" for x in done) + "\n-/\n\nset_option maxRecDepth 8192\n\nopen TM\n\nnamespace " + ns + "\n")
    for t in thms: print(t + "\n")
    print(f"end {ns}")


if __name__ == "__main__":
    main()
