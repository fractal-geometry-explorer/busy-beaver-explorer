"""Write lean/Rules.lean for 1RB1RE_0LC0LF_0LA0LD_1LE1LC_1RA0LB_---0RE: the two left-end rules, proved by symbolic
simulation (tools/py/bbtools/symtm.py), each a theorem for all values of its variables and any tapes L, R.

Words a = 10, x = 1000.
  ra: 0^inf E> 0 a^(p+1) 0 x^(q+1) R  ->  0^inf E> 0 a^(p+4) 0 x^q R      (4p + 26 steps)
  ri: L a 1 E> 0 a^k 0 x^(q+1) R      ->  L 1 E> 0 a^(k+3) 0 x^q R        (4k + 24 steps)
(the ends are written as the run reaches them: 0 1 0 1 (01)^k 0 1 0 0 = 0 (10)^(k+3) 0).

usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/<M>/py/gen_rules.py > holdouts/<M>/lean/Rules.lean
"""
import os
import re

from bbtools import symtm

M = '1RB1RE_0LC0LF_0LA0LD_1LE1LC_1RA0LB_---0RE'
RULES = [
    ('ra', 'one sweep at the left end: one x becomes three pairs a',
     '0^inf E> 0 (10)^p+1 0 (1000)^q+1 R', '0^inf E> 0 (10)^p+4 0 (1000)^q R'),
    ('ri', 'the same sweep against a stack of pairs a on the left: one a of the stack and one x become three a',
     'L 1 0 1 E> 0 (10)^k 0 (1000)^q+1 R', 'L 1 E> 0 (10)^k+3 0 (1000)^q R'),
]


def main(ID):
    thms = [symtm.prove(M, n, a, b, doc=d, rotate=True)[0] for n, d, a, b in RULES]
    print(symtm.rules_file('Machine', 'H' + ID, thms, f'Rules of {M}, generated by py/gen_rules.py (symbolic '
                           'simulation, `tools/py/bbtools/symtm.py`).'), end='')


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    main(re.search(r'namespace H(\d+)', open(os.path.join(here, '..', 'lean', 'Machine.lean')).read()).group(1))
