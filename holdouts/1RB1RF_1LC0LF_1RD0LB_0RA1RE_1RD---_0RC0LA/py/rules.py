"""Generate lean/Rules.lean for 1RB1RF_1LC0LF_1RD0LB_0RA1RE_1RD---_0RC0LA.

The tape consists of two regions, one made of the word `00100101` (with defects) and one of `11111010` read at
other phases; these rules are the sweeps that turn one into the other:

* `sweepE`: in state E moving right, `(00100101)^n` becomes `(10101111)^n`, 8n steps;
* `sweepD`: in state D moving right, `(10100100)^n` becomes `(11110101)^n`, 8n steps;
* `halt11`: the only halt, D reading 1 followed by a 1 (D1 = 1RE, then E1 has no transition).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import prove  # noqa: E402

M = "1RB1RF_1LC0LF_1RD0LB_0RA1RE_1RD---_0RC0LA"
NS = "H89727"


def main():
    m = Machine.parse(M)
    out = []
    rules = [
        ("sweepE", "L E> (00100101)^n R", "L (10101111)^n E> R",
         "In state E moving right, every `00100101` becomes `10101111`: 8n steps."),
        ("sweepD", "L D> (10100100)^n R", "L (11110101)^n D> R",
         "In state D moving right, every `10100100` becomes `11110101`: 8n steps."),
        ("halt11", "L D> 1 1 R", "L 1 E> 1 R",
         "D reading 1 with a 1 to its right: one step later E reads 1, which has no transition."),
    ]
    for name, start, end, doc in rules:
        txt, fin = prove(m, name, start, end, doc=doc)
        print(f"-- {name}: {start} ==> {fin} ({fin.steps})", file=sys.stderr)
        out.append(txt)
    cfg = out[-1].split("= some ", 1)[1].split(" := by", 1)[0]
    out.append(f"/-- ... and there the machine stops. -/\ntheorem halt11_stop (L R : Tape) :\n"
               f"    step {cfg} = none := by\n  simp [step, TM.step, trans]\n")
    head = f"import Machine\n\n/-! Rules of {M} (generated by `py/rules.py`). -/\n\nnamespace {NS}\n\nopen TM\n\n"
    sys.stdout.write(head + "\n".join(out) + f"\nend {NS}\n")


if __name__ == "__main__":
    main()
