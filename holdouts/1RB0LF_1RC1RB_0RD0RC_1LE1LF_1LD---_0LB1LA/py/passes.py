"""Writes lean/Passes.lean: the whole trip of the head through the long block, from where it leaves the counter to
where it comes back, for every block length.  Proved by tools/py/bbtools/symtm.py (`prove`).
Usage: python3 py/passes.py > lean/Passes.lean

The block is (10)^(k+1) (11)^(2j+2), then blank tape: k+1 pairs that the counter's last visit left as 10, then
4j+4 ones (in the sample tape `w 1^K 0^Z` of py/phasemap.py these are K and Z).  The head leaves the counter
rightward in one of two ways (`pass_d`, `pass_c`), crosses the block and the blank tape, turns, and comes back to
the counter, F or A on the block's first cell.  The counter part `L` is never read, the block keeps its shape and
gains 4 ones (j+1), and the step count is linear in k and j.  With an odd number of ones instead (`pass_d_halt`,
`pass_c_halt`) the same trip halts at the far end: the count of ones stays even (it only ever gains 4), and that is
what keeps the right end safe."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LF_1RC1RB_0RD0RC_1LE1LF_1LD---_0LB1LA"
NS = "H116372"
RULES = [
    ('pass_d', 'L 0 0 D> (10)^k+1 (11)^2*j+2 0^inf', 'L F> 1 (01)^k+1 1 1 1 1 (11)^2*j+1 1 0^inf',
     'Leaving the counter as `0 0 D>`: across the block and back, F on its first cell; 4 more ones.'),
    ('pass_c', 'L 1 0 C> 0 (10)^k+1 (11)^2*j+2 0^inf', 'L A> 1 1 (01)^k+1 1 1 1 1 (11)^2*j+1 1 0^inf',
     'Leaving the counter as `1 0 C>`: across the block and back, A on its first cell; 4 more ones.'),
    ('pass_d_halt', 'L 0 0 D> (10)^k+1 1 (11)^2*j+2 0^inf', 'L (11)^k+1 1 E> 1 1 1 (11)^2*j+2 1 0^inf',
     'With an odd number of ones (4j+5) the trip of `pass_d` ends with E on a 1, a halt.'),
    ('pass_c_halt', 'L 1 0 C> 0 (10)^k+1 1 (11)^2*j+2 0^inf', 'L 1 (11)^k+1 1 E> 1 1 1 (11)^2*j+2 1 0^inf',
     'With an odd number of ones (4j+5) the trip of `pass_c` ends with E on a 1, a halt.'),
]

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d, count_first=True)[0] for n, s, e, d in RULES]
    print(rules_file("Machine", NS, thms,
                     f"# {M}: the trip through the long block\n\n"
                     "Generated by `py/passes.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `k`, `j` "
                     "and every tape `L`."))
