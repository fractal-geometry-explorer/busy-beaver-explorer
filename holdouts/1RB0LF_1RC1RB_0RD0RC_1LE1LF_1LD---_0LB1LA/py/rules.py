"""Writes lean/Rules.lean: shift rules of this machine's sweeps and the shape of a halt, proved by
tools/py/bbtools/symtm.py (`prove`).  Usage: python3 py/rules.py > lean/Rules.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LF_1RC1RB_0RD0RC_1LE1LF_1LD---_0LB1LA"
NS = "H116372"
RULES = [
    ('d_run', 'L (00)^n D> 0 R', 'L D> 0 (11)^n R',
     'Leftward, D and E fill the zeros at the right with ones, 2 steps a pair.', {}),
    ('a_run', 'L (11)^n A> 1 R', 'L A> 1 (10)^n R',
     'Leftward, A and F turn the block of ones into (10)^n, 2 steps a pair.', {}),
    ('d_zigzag', 'L 0 0 D> (10)^n R', 'L (11)^n 0 0 D> R',
     'Rightward, a short zigzag turns each 10 back into 11, 10 steps a pair.', {}),
    ('b_run', 'L B> (11)^n R', 'L (11)^n B> R',
     'Rightward, B crosses ones unchanged.', {}),
    ('c_run', 'L C> (11)^n R', 'L (00)^n C> R',
     'Rightward, C turns ones into zeros (the ones written by D and E become zeros again).', {}),
    ('halt_shape', 'L 1 D> 0 R', 'L E> 1 1 R',
     'The only way to a halt: D on a 0 with a 1 to its left puts E on that 1, which halts.', {}),
]
HALT = "E"
HSYM = "1"

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d, **kw)[0] for n, s, e, d, kw in RULES]
    extra = (f"/-- {HALT} reading a {HSYM} halts (the end of `halt_shape`). -/\n"
             f"theorem halt_after_shape (L R : Tape) : step ⟨L, cons true R, .{HALT}⟩ = none := rfl\n")
    print(rules_file("Machine", NS, thms + [extra],
                     f"# {M}: shift rules of the sweeps and the shape of a halt\n\n"
                     "Generated by `py/rules.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `n` and all "
                     "tapes `L`, `R`."))
