"""Writes lean/Corner.lean for 1RB0LC_0LC1RF_1LE1RD_0RC1RC_0LA1LA_---1RA: the corner of the A-event map that the
formulas leave to direct simulation, odd a < 15 and b < 30 (420 events), as a table checked by Lean's kernel.

Each event U/V(a, b) of the corner reaches a next event (none halts), found here by direct simulation and checked
against `emap.direct`.  Lean runs each entry on the list simulator of tools/lean/TM/Fin.lean
(`decide +kernel`, in chunks) and `nextCorner_sound` turns the table into statements about the machine.

usage: python3 gen_corner.py
"""
import importlib.util
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("emap13743", os.path.join(HERE, "emap.py"))
emap = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(emap)

T = {("A", 0): (1, 1, "B"), ("A", 1): (0, -1, "C"), ("B", 0): (0, -1, "C"), ("B", 1): (1, 1, "F"),
     ("C", 0): (1, -1, "E"), ("C", 1): (1, 1, "D"), ("D", 0): (0, 1, "C"), ("D", 1): (1, 1, "C"),
     ("E", 0): (0, -1, "A"), ("E", 1): (1, -1, "A"), ("F", 1): (1, 1, "A")}
PRE = {"U": [0, 1, 1, 0, 1, 1], "V": [1, 1, 1, 0]}


def run(F, a, b, maxs=10 ** 6):
    """the next U/V-event (F', a', b', steps) or ('HALT', steps)"""
    t = dict(enumerate(PRE[F] + [1] * a + [0] + [1] * b))
    pos, st, n = 0, "A", 0
    while n < maxs:
        s = t.get(pos, 0)
        if (st, s) not in T:
            return ("HALT", n)
        w, d, st = T[(st, s)]
        t[pos] = w
        pos += d
        n += 1
        if st == "A" and pos <= min(k for k, v in t.items() if v):
            word = "".join(str(t.get(i, 0)) for i in range(pos, max(t) + 1)).rstrip("0")
            for nm, pat in (("U", r"011011(1*)0(1*)"), ("V", r"1110(1*)0(1*)")):
                m = re.fullmatch(pat, word)
                if m:
                    return (nm, len(m.group(1)), len(m.group(2)), n)
    raise SystemExit(f"no event from {F}({a}, {b})")


LEAN_HEAD = r"""import Map

/-!
# The corner odd a < 15, b < 30 of the A-event map, as a checked table

Generated by `py/gen_corner.py`; do not edit by hand.  all NGO events of the corner reach a next event (none halts),
listed in `cornerList` with the step count.  Every entry is run on the list simulator
(`fsteps`, proved to agree with `steps`) and checked by the kernel.  The tape a run ends on is compared with the
expected event up to blank cells at the ends (`sameCfg`).
-/

namespace H13743

open TM

/-- The cells left of the `1^a` block, as a list. -/
def preL : Tag → List Bool
  | .U => [false, true, true, false, true, true]
  | .V => [true, true, true, false]

/-- The event `Ev F a b` as a list configuration. -/
def evF (F : Tag) (a b : Nat) : FCfg St :=
  ⟨[], preL F ++ (List.replicate a true ++ false :: List.replicate b true), .A⟩

theorem app_replicate_true (n : Nat) (X : Tape) : app (List.replicate n true) X = rep n [true] X := by
  induction n with
  | zero => rfl
  | succ n ih => rw [List.replicate_succ, app_cons, ih, rep_succ]; rfl

theorem evF_toCfg (F : Tag) (a b : Nat) : (evF F a b).toCfg = Ev F a b := by
  cases F <;>
  · simp only [evF, FCfg.toCfg, Ev, pre, preL, ← app_app, app_replicate_true, app_cons, app_nil]

/-- The same tape up to blank cells at the far ends. -/
def padEq (u v : List Bool) : Bool :=
  u ++ List.replicate (v.length - u.length) false == v ++ List.replicate (u.length - v.length) false

def sameCfg (c d : FCfg St) : Bool := padEq c.l d.l && padEq c.r d.r && c.st == d.st

theorem sameCfg_toCfg {c d : FCfg St} (h : sameCfg c d = true) : c.toCfg = d.toCfg := by
  obtain ⟨cl, cr, cs⟩ := c
  obtain ⟨dl, dr, ds⟩ := d
  simp only [sameCfg, padEq, Bool.and_eq_true, beq_iff_eq] at h
  obtain ⟨⟨h1, h2⟩, h3⟩ := h
  simp only [FCfg.toCfg]
  rw [app_blank_eq _ _ h1, app_blank_eq _ _ h2, h3]

/-- An entry `(F, a, b, F', a', b', t)`: from `Ev F a b` the machine is at `Ev F' a' b'` after `t` steps. -/
def goOk (e : Tag × Nat × Nat × Tag × Nat × Nat × Nat) : Bool :=
  match fsteps e.2.2.2.2.2.2 (evF e.1 e.2.1 e.2.2.1) with
  | some c => sameCfg c (evF e.2.2.2.1 e.2.2.2.2.1 e.2.2.2.2.2.1)
  | none => false

"""

TAIL = r"""/-- The map on the corner: the next event and the number of steps, from the table. -/
def nextCorner (F : Tag) (a b : Nat) : Option (Tag × Nat × Nat × Nat) :=
  (cornerList.find? (fun e => e.1 == F && e.2.1 == a && e.2.2.1 == b)).map (fun e => e.2.2.2)

theorem goOk_sound (e : Tag × Nat × Nat × Tag × Nat × Nat × Nat) (h : goOk e = true) :
    steps e.2.2.2.2.2.2 (Ev e.1 e.2.1 e.2.2.1) = some (Ev e.2.2.2.1 e.2.2.2.2.1 e.2.2.2.2.2.1) := by
  unfold goOk at h
  rw [← evF_toCfg, ← evF_toCfg, show ∀ n c, steps n (FCfg.toCfg c) = (fsteps n c).map FCfg.toCfg from FCfg.steps_eq trans]
  cases e2 : fsteps e.2.2.2.2.2.2 (evF e.1 e.2.1 e.2.2.1) with
  | none => rw [e2] at h; cases h
  | some c => rw [e2] at h; simp only [Option.map_some]; rw [sameCfg_toCfg h]

/-- **The corner table is sound.** -/
theorem nextCorner_sound (F : Tag) (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : nextCorner F a b = some r) :
    steps r.2.2.2 (Ev F a b) = some (Ev r.1 r.2.1 r.2.2.1) := by
  unfold nextCorner at h
  cases e : cornerList.find? (fun e => e.1 == F && e.2.1 == a && e.2.2.1 == b) with
  | none => rw [e] at h; cases h
  | some q =>
    rw [e] at h
    simp only [Option.map_some, Option.some.injEq] at h
    subst h
    have hp := List.find?_some e
    simp only [Bool.and_eq_true, beq_iff_eq] at hp
    obtain ⟨⟨h1, h2⟩, h3⟩ := hp
    have hm := List.mem_of_find?_eq_some e
    have hk := (List.all_eq_true.1 cornerList_ok) q hm
    have := goOk_sound q hk
    rw [h1, h2, h3] at this
    exact this

/-- The corner is covered: the table has every odd `a < 15` with `b < 30`. -/
theorem nextCorner_isSome (F : Tag) (a b : Nat) (h2 : a % 2 = 1) (ha : a < 15) (hb : b < 30) :
    (nextCorner F a b).isSome = true := by
  cases F with
  | U =>
    have : ∀ a < 15, ∀ b < 30, a % 2 = 1 → (nextCorner .U a b).isSome = true := by decide +kernel
    exact this a ha b hb h2
  | V =>
    have : ∀ a < 15, ∀ b < 30, a % 2 = 1 → (nextCorner .V a b).isSome = true := by decide +kernel
    exact this a ha b hb h2

end H13743
"""

go = []
for F in "UV":
    for a in range(1, 15, 2):
        for b in range(30):
            r = run(F, a, b)
            d = emap.direct(F, a, b)
            if r[0] == "HALT":
                raise SystemExit(f"{F}({a}, {b}) halts: not expected")
            assert d == tuple(r[:3]), (F, a, b, r, d)
            go.append((F, a, b) + r)

CH = 30
chunks = [go[i:i + CH] for i in range(0, len(go), CH)]
out = [LEAN_HEAD.replace("NGO", str(len(go)))]


def tag(F):
    return f".{F}"


for j, ch in enumerate(chunks):
    rows = ",\n  ".join(f"({tag(F)}, {a}, {b}, {tag(F2)}, {a2}, {b2}, {t})" for F, a, b, F2, a2, b2, t in ch)
    out.append(f"def corner{j} : List (Tag × Nat × Nat × Tag × Nat × Nat × Nat) := [\n  {rows}]\n")
    out.append(f"theorem corner{j}_ok : corner{j}.all goOk = true := by decide +kernel\n")
names = [f"corner{j}" for j in range(len(chunks))]
out.append("/-- The corner events with their next events. -/\ndef cornerList : List (Tag × Nat × Nat × Tag × Nat × Nat × Nat) :=\n  "
           + " ++ ".join(names) + "\n")
out.append("theorem cornerList_ok : cornerList.all goOk = true := by\n  simp only [cornerList, List.all_append, "
           + ", ".join(f"{n}_ok" for n in names) + ", Bool.and_self]\n")
out.append(TAIL)
open(os.path.join(HERE, "..", "lean", "Corner.lean"), "w").write("\n".join(out))
print(len(go), "events,", len(chunks), "chunks")
