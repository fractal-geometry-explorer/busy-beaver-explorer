"""Writes lean/Map.lean from lean/cases.json (made by gen_map.py): the events `Ev F a b`, the map `next` (for even
a) as a Lean function giving the next event and the number of steps, and `next_sound`: wherever `next` is defined,
the machine goes from `Ev F a b` to the event `next` gives, in exactly the steps it gives.

`next F a b` tries the cases in order: a case is a family F(A(x, y), B(x, y)); its x, y are recovered from a, b by
division and the case applies when A, B give back a, b.

usage: python3 gen_mapdef.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "1RB---_1LC0LD_0RF0LD_0LE0RA_0LC1RA_1RC1RD", "py"))
import chain as C  # noqa: E402

NS = "H13743"
cases = json.load(open(os.path.join(HERE, "..", "lean", "cases.json")))


def L(s, env):
    """the Lin string s as a Lean term with its variables replaced by the Lean terms env"""
    lin = C.S.parse_lin(s)
    parts = []
    for v, a in sorted(lin.c.items()):
        parts.append(f"{a} * ({env[v]})" if a != 1 else f"({env[v]})")
    if lin.k or not parts:
        parts.append(str(lin.k))
    return " + ".join(parts)


def inverse(c):
    """Lean terms for the case's variables in terms of a and b"""
    la, lb = C.S.parse_lin(c["a"]), C.S.parse_lin(c["b"])
    env = {}
    todo = list(c["vars"])
    while todo:
        for nm, ln in (("a", la), ("b", lb)):
            un = [v for v in ln.c if v not in env]
            if len(un) == 1:
                v = un[0]
                rest = " - ".join([nm] + ([str(ln.k)] if ln.k else []) +
                                  [f"{a} * ({env[u]})" if a != 1 else f"({env[u]})" for u, a in sorted(ln.c.items())
                                   if u != v])
                env[v] = f"({rest}) / {ln.c[v]}" if ln.c[v] != 1 else f"({rest})"
                todo.remove(v)
                break
        else:
            raise SystemExit(f"cannot invert {c}")
    return env


def args(c, env):
    return " ".join(f"({env[v]})" for v in c["vars"])


def leaf(cs, c, ind):
    """the proof that the if-chain of cs is some at a point of case c's region"""
    k = cs.index(c)
    return [ind + "rw [" + "".join("if_neg (by omega), " for _ in range(k)) + "if_pos (by omega)]; rfl"]


def family(cs, pre, var, ind):
    """leaves for the cases of one family (name prefix pre): concrete values of var, then the generic case"""
    fam = [c for c in cs if c["name"].startswith(pre + "_")]
    conc = [c for c in fam if "_g" not in c["name"]]
    gen = [c for c in fam if "_g" in c["name"]]
    assert len(gen) == 1, pre
    g = gen[0]
    T = C.S.parse_lin(g[var]).k
    vals = [int(c[var]) for c in conc]
    if not vals:
        return leaf(cs, g, ind)
    alts = " ∨ ".join([f"{var} = {v}" for v in vals] + [f"{T} ≤ {var}"])
    out = [ind + f"rcases (by omega : {alts}) with " + " | ".join(["h"] * (len(vals) + 1))]
    for c in conc + [g]:
        out.append(ind + "· " + leaf(cs, c, "")[0])
    return out


def domain_tree(F, cs):
    return ["  rcases Nat.mod_two_eq_zero_or_one b with hb2 | hb2",
            "  · rcases (by omega : a + 4 ≤ b ∨ b + 2 ≤ a ∨ b = a ∨ b = a + 2) with hr | hr | hr | hr",
            "    · skip"] + family(cs, f"C{F}", "a", "      ") + \
           ["    · skip"] + family(cs, f"D{F}", "b", "      ") + \
           ["    · skip"] + family(cs, f"E{F}0", "a", "      ") + \
           ["    · skip"] + family(cs, f"E{F}2", "a", "      ") + \
           ["  · rcases (by omega : a % 4 = 2 ∨ a % 4 = 0) with ha4 | ha4",
            "    · skip"] + family(cs, f"A{F}", "a", "      ") + \
           ["    · rcases (by omega : b = 3 ∨ b = 5 ∨ 7 ≤ b) with hb3 | hb3 | hb3",
            "      · skip"] + family(cs, f"B{F}3", "a", "        ") + \
           ["      · skip"] + family(cs, f"B{F}5", "a", "        ") + \
           ["      · skip"] + family(cs, f"B{F}", "a", "        ")


out = []
w = out.append
w(f"""import Cases

/-!
# The A-event map of 1RB0LC_0LC1RF_1LE1RD_0RC1RC_0LA1LA_---1RA (even a)

Generated by `py/gen_mapdef.py` from `cases.json`; do not edit by hand.

An event is `Ev F a b`: the head in state A at the left end of `011011 1^a 0 1^b` (F = U) or `1110 1^a 0 1^b`
(F = V), blank elsewhere.  `next F a b` is the next event and the number of steps to it, for every even `a ≥ 2`
and every `b ≥ 1` except the halting events (a = 0 mod 4, b = 1); `next_sound` proves it: each branch is one of the
theorems of `Cases.lean`.
-/

namespace {NS}

open TM

/-- The two kinds of event. -/
inductive Tag where
  | U
  | V
  deriving DecidableEq, Repr

/-- The cells left of the `1^a` block. -/
def pre : Tag → Tape → Tape
  | .U, X => cons false (cons true (cons true (cons false (cons true (cons true X)))))
  | .V, X => cons true (cons true (cons true (cons false X)))

/-- The event `A> pre 1^a 0 1^b`. -/
def Ev (F : Tag) (a b : Nat) : Config := ⟨blank, pre F (rep a [true] (cons false (rep b [true] blank))), .A⟩

""")

for c in cases:
    bs = f" ({' '.join(c['vars'])} : Nat)" if c["vars"] else ""
    w(f"/-- Steps of case `{c['name']}`. -/\ndef T_{c['name']}{bs} : Nat := {c['total']}\n")
w("")

for F in "UV":
    cs = [c for c in cases if c["F"] == F]
    lines = [f"/-- The map from `{F}` events: the next kind, a, b and the number of steps. -/",
             f"def next{F} (a b : Nat) : Option (Tag × Nat × Nat × Nat) :="]
    proof = [f"theorem next{F}_sound (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : next{F} a b = some r) :",
             f"    steps r.2.2.2 (Ev .{F} a b) = some (Ev r.1 r.2.1 r.2.2.1) := by",
             f"  simp only [next{F}] at h"]
    for c in cs:
        env = inverse(c)
        cond = f"a = {L(c['a'], env)} ∧ b = {L(c['b'], env)}"
        res = f"some (.{c['F2']}, {L(c['a2'], env)}, {L(c['b2'], env)}, T_{c['name']} {args(c, env)})"
        lines.append(f"  if {cond} then {res} else")
        proof += [f"  by_cases hc : {cond}",
                  "  · rw [if_pos hc] at h",
                  "    cases h",
                  f"    rw [show Ev .{F} a b = Ev .{F} ({L(c['a'], env)}) ({L(c['b'], env)}) from (congrArg (Ev .{F} a) hc.2).trans (congrArg (fun z => Ev .{F} z ({L(c['b'], env)})) hc.1)]",
                  f"    exact {c['name']} {args(c, env)}",
                  "  rw [if_neg hc] at h"]
    lines.append("  none")
    proof.append("  cases h")
    dom = [f"/-- `next{F}` is defined at every even `a ≥ 2` and `b ≥ 1` except the halting events (a = 0 mod 4, b = 1). -/",
           f"theorem next{F}_isSome (a b : Nat) (h2 : a % 2 = 0) (ha : 2 ≤ a) (hb : 1 ≤ b) (hh : ¬(a % 4 = 0 ∧ b = 1)) :",
           f"    (next{F} a b).isSome = true := by",
           f"  simp only [next{F}]"]
    dom += domain_tree(F, cs)
    pos = [f"theorem next{F}_pos (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : next{F} a b = some r) : 1 ≤ r.2.2.2 := by",
           f"  simp only [next{F}] at h"]
    for c in cs:
        env = inverse(c)
        cond = f"a = {L(c['a'], env)} ∧ b = {L(c['b'], env)}"
        pos += [f"  by_cases hc : {cond}",
                "  · rw [if_pos hc] at h",
                "    cases h",
                f"    show 1 ≤ T_{c['name']} {args(c, env)}",
                f"    unfold T_{c['name']}",
                "    omega",
                "  rw [if_neg hc] at h"]
    pos.append("  cases h")
    dom += pos
    w("\n".join(lines) + "\n")
    w("\n".join(proof) + "\n")
    w("\n".join(dom) + "\n")

w(f"""/-- The A-event map (even a): the next kind, a, b and the number of steps; `none` at the halting events and for
odd a or a = 0, which the run never reaches. -/
def next : Tag → Nat → Nat → Option (Tag × Nat × Nat × Nat)
  | .U, a, b => nextU a b
  | .V, a, b => nextV a b

/-- **The map is sound**: wherever `next` is defined, the machine goes from the event `Ev F a b` to the one `next`
gives, in exactly the number of steps it gives. -/
theorem next_sound (F : Tag) (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : next F a b = some r) :
    steps r.2.2.2 (Ev F a b) = some (Ev r.1 r.2.1 r.2.2.1) := by
  cases F with
  | U => exact nextU_sound a b r h
  | V => exact nextV_sound a b r h

/-- Every pass takes at least one step. -/
theorem next_pos (F : Tag) (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : next F a b = some r) : 1 ≤ r.2.2.2 := by
  cases F with
  | U => exact nextU_pos a b r h
  | V => exact nextV_pos a b r h

/-- Where the map is defined: at every event with `a` even, `a ≥ 2` and `b ≥ 1`, except the halting events. -/
theorem next_isSome (F : Tag) (a b : Nat) (h2 : a % 2 = 0) (ha : 2 ≤ a) (hb : 1 ≤ b)
    (hh : ¬(a % 4 = 0 ∧ b = 1)) : (next F a b).isSome = true := by
  cases F with
  | U => exact nextU_isSome a b h2 ha hb hh
  | V => exact nextV_isSome a b h2 ha hb hh

end {NS}
""")
open(os.path.join(HERE, "..", "lean", "Map.lean"), "w").write("\n".join(out))
print("wrote Map.lean")
