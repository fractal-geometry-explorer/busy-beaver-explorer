"""Writes lean/HaltCases.lean for 1RB0LC_0LC1RF_1LE1RD_0RC1RC_0LA1LA_---1RA: the halting events U(a, 1), V(a, 1)
with a = 0 mod 4 reach the halting configuration `1^n F> 0` (blank elsewhere), as Lean theorems for every a.

Uses the loops and helpers of gen_map.py (run the same way: a regroup, one `lb` loop of `Cases.lean`, symbolic
runs).

usage: python3 gen_halt.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_map as G  # noqa: E402

C, S, Lin = G.C, G.S, G.Lin
N0 = len(G.lib.thms)   # the loops of gen_map.py, already in Cases.lean

# the halting configuration after U(4x+4, 1) is 1^(6x+14) F> 0; after V(4x+4, 1) it is 1^(6x+15) F> 0
HALT_C = {"U": 14, "V": 15}


def attempt(name, F, a, n, ga, vs):
    """the halting event F(a, 1) (a a Lin string, = 0 mod 4) runs to 1^n F> 0 (blank elsewhere); metadata or None"""
    mark, names = len(G.lib.thms), set(G.lib.names)
    c = C.Case(G.lib, name, G.ev(F, a, "1"))
    try:
        c.regroup(G.evg(F, ga, "1"))
        fl = G.find_loop(c.cur) if vs else None
        if fl:
            lp, env = fl
            c.loop(lp, env["x"].__repr__(), "0", env["i"].__repr__(), L=env["L"],
                   **({"y": env["y"].__repr__()} if "y" in env else {}))
        binders = f"({' '.join(vs)} : Nat)" if vs else ""
        end = C.P(f"0^inf (1)^{n} F> 0^inf")
        for _ in range(12):
            if G.unstick(c, end):
                break
        total = c.emit(end, binders)
    except Exception as ex:
        print("  fail", name, type(ex).__name__, str(ex)[:300], file=sys.stderr, flush=True)
        del G.lib.thms[mark:]
        G.lib.names = names
        return None
    md = dict(name=name, F=F, a=a, vars=vs, n=n, total=total)
    print("OK", md, flush=True)
    return md


if __name__ == "__main__":
    CASES = []
    for F in "UV":
        for K in range(6):
            md = attempt(f"H{F}_g{K}", F, f"4*x+{4 * K + 4}", f"6*x+{6 * K + HALT_C[F]}", f"(1111)^x+{K + 1}", ["x"])
            if md:
                break
        else:
            raise SystemExit("no generic case " + F)
        CASES.append(md)
        for k in range(K):
            md = attempt(f"H{F}_a{4 * k + 4}", F, str(4 * k + 4), str(6 * k + HALT_C[F]), G.ones(4 * k + 4), [])
            assert md
            CASES.append(md)
    del G.lib.thms[:N0]
    out = C.lean_file(G.lib, ["Cases"],
                      "The halting events U(4x+4, 1), V(4x+4, 1), generated by `py/gen_halt.py` with "
                      "`../1RB---_1LC0LD_0RF0LD_0LE0RA_0LC1RA_1RC1RD/py/chain.py`; do not edit by hand.")
    open(os.path.join(HERE, "..", "lean", "HaltCases.lean"), "w").write(out)
    json.dump(CASES, open(os.path.join(HERE, "..", "lean", "haltcases.json"), "w"), indent=1)
    print(len(CASES), "cases")
