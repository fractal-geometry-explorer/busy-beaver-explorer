"""Writes lean/MapOdd.lean from lean/oddcases.json (made by gen_odd.py): the odd-a part of the A-event map,
`nextOdd`, with `nextOdd_sound` and `nextOdd_isSome` (defined at every odd a >= 15, and at every odd a < 15 with
b >= 30), and `nextFull`, the whole table (even a from Map.lean, odd a from here) with `nextFull_sound`.

usage: python3 gen_odddef.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "1RB---_1LC0LD_0RF0LD_0LE0RA_0LC1RA_1RC1RD", "py"))
import chain as C  # noqa: E402

NS = "H13743"
cases = json.load(open(os.path.join(HERE, "..", "lean", "oddcases.json")))


def L(s, env):
    """the Lin string s as a Lean term with its variables replaced by the Lean terms env"""
    lin = C.S.parse_lin(s)
    parts = []
    for v, a in sorted(lin.c.items()):
        parts.append(f"{a} * ({env[v]})" if a != 1 else f"({env[v]})")
    if lin.k or not parts:
        parts.append(str(lin.k))
    return " + ".join(parts)


def inverse(c):
    """Lean terms for the case's variables in terms of a and b"""
    la, lb = C.S.parse_lin(c["a"]), C.S.parse_lin(c["b"])
    env = {}
    todo = list(c["vars"])
    while todo:
        for nm, ln in (("a", la), ("b", lb)):
            un = [v for v in ln.c if v not in env]
            if len(un) == 1:
                v = un[0]
                rest = " - ".join([nm] + ([str(ln.k)] if ln.k else []) +
                                  [f"{a} * ({env[u]})" if a != 1 else f"({env[u]})" for u, a in sorted(ln.c.items())
                                   if u != v])
                env[v] = f"({rest}) / {ln.c[v]}" if ln.c[v] != 1 else f"({rest})"
                todo.remove(v)
                break
        else:
            raise SystemExit(f"cannot invert {c}")
    return env


def args(c, env):
    return " ".join(f"({env[v]})" for v in c["vars"])


def leaf(cs, c, ind):
    """the proof that the if-chain of cs is some at a point of case c's region"""
    k = cs.index(c)
    return [ind + "rw [" + "".join("if_neg (by omega), " for _ in range(k)) + "if_pos (by omega)]; rfl"]


def family(cs, pre, var, ind):
    """leaves for the cases of one family (name prefix pre): concrete values of var, then the generic case"""
    fam = [c for c in cs if c["name"].startswith(pre + "_")]
    conc = [c for c in fam if "_g" not in c["name"]]
    gen = [c for c in fam if "_g" in c["name"]]
    assert len(gen) == 1, pre
    g = gen[0]
    T = C.S.parse_lin(g[var]).k
    vals = [int(c[var]) for c in conc]
    if not vals:
        return leaf(cs, g, ind)
    alts = " ∨ ".join([f"{var} = {v}" for v in vals] + [f"{T} ≤ {var}"])
    out = [ind + f"rcases (by omega : {alts}) with " + " | ".join(["h"] * (len(vals) + 1))]
    for c in conc + [g]:
        out.append(ind + "· " + leaf(cs, c, "")[0])
    return out


def by_name(cs, nm):
    return [c for c in cs if c["name"] == nm][0]


def domain_tree(F, cs):
    out = ["  rcases (by omega : 15 ≤ a ∨ a < 15) with hA | hA",
           "  · rcases Nat.mod_two_eq_zero_or_one b with hb2 | hb2",
           "    · rcases (by omega : a ≤ b + 7 ∨ b = 0 ∨ (2 ≤ b ∧ b + 13 ≤ a) ∨ b + 11 = a ∨ b + 9 = a) with hr | hr | hr | hr | hr"]
    for tag in ("OE", "O0", "OD", "O11", "O9"):
        out.append("      · " + leaf(cs, by_name(cs, f"{tag}{F}_g0"), "")[0])
    out += ["    · rcases (by omega : a % 4 = 1 ∨ a % 4 = 3) with ha4 | ha4",
            "      · skip"] + family(cs, f"O1{F}", "a", "        ") + \
           ["      · skip"] + family(cs, f"O3{F}", "a", "        ")
    out.append("  · rcases (by omega : " + " ∨ ".join(f"a = {a}" for a in range(1, 15, 2)) + ") with " +
               " | ".join(["ha"] * 7))
    for a in range(1, 15, 2):
        out += [f"    · rcases Nat.mod_two_eq_zero_or_one b with hb2 | hb2",
                "      · " + leaf(cs, by_name(cs, f"S{F}_a{a}_e"), "")[0],
                "      · " + leaf(cs, by_name(cs, f"S{F}_a{a}_o"), "")[0]]
    return out


out = []
w = out.append
w(f"""import Map
import OddCases

/-!
# The A-event map of 1RB0LC_0LC1RF_1LE1RD_0RC1RC_0LA1LA_---1RA for odd a

Generated by `py/gen_odddef.py` from `oddcases.json`; do not edit by hand.

`nextOdd F a b` is the next event after `Ev F a b` and the number of steps to it, for every odd `a ≥ 15` (any b)
and every odd `a < 15` with `b ≥ 30`; `nextOdd_sound` proves it from the theorems of `OddCases.lean`.  The run
from blank tape never meets odd a (the even-a map keeps a even), so this part of the table does not bear on
halting; it completes the table of the README in Lean.  `nextFull` is the whole map.
-/

namespace {NS}

open TM

""")
for c in cases:
    bs = f" ({' '.join(c['vars'])} : Nat)" if c["vars"] else ""
    w(f"/-- Steps of case `{c['name']}`. -/\ndef T_{c['name']}{bs} : Nat := {c['total']}\n")
w("")
for F in "UV":
    cs = [c for c in cases if c["F"] == F]
    lines = [f"/-- The odd-a map from `{F}` events: the next kind, a, b and the number of steps. -/",
             f"def nextOdd{F} (a b : Nat) : Option (Tag × Nat × Nat × Nat) :="]
    proof = [f"theorem nextOdd{F}_sound (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : nextOdd{F} a b = some r) :",
             f"    steps r.2.2.2 (Ev .{F} a b) = some (Ev r.1 r.2.1 r.2.2.1) := by",
             f"  simp only [nextOdd{F}] at h"]
    pos = [f"theorem nextOdd{F}_pos (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : nextOdd{F} a b = some r) : 1 ≤ r.2.2.2 := by",
           f"  simp only [nextOdd{F}] at h"]
    for c in cs:
        env = inverse(c)
        cond = f"a = {L(c['a'], env)} ∧ b = {L(c['b'], env)}"
        res = f"some (.{c['F2']}, {L(c['a2'], env)}, {L(c['b2'], env)}, T_{c['name']} {args(c, env)})"
        lines.append(f"  if {cond} then {res} else")
        proof += [f"  by_cases hc : {cond}",
                  "  · rw [if_pos hc] at h",
                  "    cases h",
                  f"    rw [show Ev .{F} a b = Ev .{F} ({L(c['a'], env)}) ({L(c['b'], env)}) from (congrArg (Ev .{F} a) hc.2).trans (congrArg (fun z => Ev .{F} z ({L(c['b'], env)})) hc.1)]",
                  f"    exact {c['name']} {args(c, env)}",
                  "  rw [if_neg hc] at h"]
        pos += [f"  by_cases hc : {cond}",
                "  · rw [if_pos hc] at h",
                "    cases h",
                f"    show 1 ≤ T_{c['name']} {args(c, env)}",
                f"    unfold T_{c['name']}",
                "    omega",
                "  rw [if_neg hc] at h"]
    lines.append("  none")
    proof.append("  cases h")
    pos.append("  cases h")
    dom = [f"/-- `nextOdd{F}` is defined at every odd `a ≥ 15`, and at every odd `a < 15` with `b ≥ 30`. -/",
           f"theorem nextOdd{F}_isSome (a b : Nat) (h2 : a % 2 = 1) (hd : 15 ≤ a ∨ 30 ≤ b) :",
           f"    (nextOdd{F} a b).isSome = true := by",
           f"  simp only [nextOdd{F}]"] + domain_tree(F, cs)
    w("\n".join(lines) + "\n")
    w("\n".join(proof) + "\n")
    w("\n".join(pos) + "\n")
    w("\n".join(dom) + "\n")

w(f"""/-- The A-event map for odd a. -/
def nextOdd : Tag → Nat → Nat → Option (Tag × Nat × Nat × Nat)
  | .U, a, b => nextOddU a b
  | .V, a, b => nextOddV a b

/-- **The odd-a map is sound.** -/
theorem nextOdd_sound (F : Tag) (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : nextOdd F a b = some r) :
    steps r.2.2.2 (Ev F a b) = some (Ev r.1 r.2.1 r.2.2.1) := by
  cases F with
  | U => exact nextOddU_sound a b r h
  | V => exact nextOddV_sound a b r h

theorem nextOdd_pos (F : Tag) (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : nextOdd F a b = some r) :
    1 ≤ r.2.2.2 := by
  cases F with
  | U => exact nextOddU_pos a b r h
  | V => exact nextOddV_pos a b r h

/-- Where the odd-a map is defined: every odd `a ≥ 15`, and every odd `a < 15` with `b ≥ 30`. -/
theorem nextOdd_isSome (F : Tag) (a b : Nat) (h2 : a % 2 = 1) (hd : 15 ≤ a ∨ 30 ≤ b) :
    (nextOdd F a b).isSome = true := by
  cases F with
  | U => exact nextOddU_isSome a b h2 hd
  | V => exact nextOddV_isSome a b h2 hd

/-- The whole table: `next` for even a, `nextOdd` for odd a. -/
def nextFull (F : Tag) (a b : Nat) : Option (Tag × Nat × Nat × Nat) :=
  if a % 2 = 0 then next F a b else nextOdd F a b

/-- **The whole table is sound**: wherever `nextFull` is defined the machine goes from `Ev F a b` to the event
it gives, in exactly the steps it gives. -/
theorem nextFull_sound (F : Tag) (a b : Nat) (r : Tag × Nat × Nat × Nat) (h : nextFull F a b = some r) :
    steps r.2.2.2 (Ev F a b) = some (Ev r.1 r.2.1 r.2.2.1) := by
  unfold nextFull at h
  by_cases e : a % 2 = 0
  · rw [if_pos e] at h; exact next_sound F a b r h
  · rw [if_neg e] at h; exact nextOdd_sound F a b r h

/-- Where the whole table is defined: every event except the halting ones `a ≡ 0 (mod 4), b = 1`, the events
with `a = 0` or (a even and `b = 0`), and the finite corner odd `a < 15`, `b < 30`. -/
theorem nextFull_isSome (F : Tag) (a b : Nat)
    (hd : (a % 2 = 0 ∧ 2 ≤ a ∧ 1 ≤ b ∧ ¬(a % 4 = 0 ∧ b = 1)) ∨ (a % 2 = 1 ∧ (15 ≤ a ∨ 30 ≤ b))) :
    (nextFull F a b).isSome = true := by
  unfold nextFull
  rcases hd with ⟨h2, ha, hb, hh⟩ | ⟨h2, h⟩
  · rw [if_pos h2]; exact next_isSome F a b h2 ha hb hh
  · rw [if_neg (by omega)]; exact nextOdd_isSome F a b h2 h

end {NS}
""")
open(os.path.join(HERE, "..", "lean", "MapOdd.lean"), "w").write("\n".join(out))
