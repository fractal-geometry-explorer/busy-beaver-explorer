"""Generate ../lean/Rules.lean: the shift and macro rules of 1RB0RE_1LC0LE_---1LD_1LE1LB_1RA0LF_0RD1LA, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC0LE_---1LD_1LE1LB_1RA0LF_0RD1LA"

RULES = [
    ('e_w', 'L E> (0111111)^n R', 'L (1111110)^n E> R',
     'E runs right over 0111111 words, rewriting them as w = 1111110.'),
    ('a_w', 'L A> (1111110)^n R', 'L (1111101)^n A> R',
     'A runs right over w = 1111110 (12 steps a word).'),
    ('e_x', 'L E> (011111)^n R', 'L (111110)^n E> R',
     'E runs right over 011111 words, rewriting them as x = 111110.'),
    ('a_x', 'L A> (111110)^n R', 'L (111101)^n A> R',
     'A runs right over x = 111110.'),
    ('c_l', 'L (1101111)^n C> 1 R', 'L C> 1 (1111011)^n R',
     'C runs left over 1101111 words.'),
    ('d_l', 'L (1110111)^n D> 1 R', 'L D> 1 (1111101)^n R',
     'D runs left over 1110111 words.'),
    ('b_l', 'L (1111011)^n B> 1 R', 'L B> 1 (1111110)^n R',
     'B runs left over 1111011 words, leaving w = 1111110.'),
    ('e_l', 'L (1111101)^n E> 1 R', 'L E> 1 (0111111)^n R',
     'E runs left over 1111101 words.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H39050", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
