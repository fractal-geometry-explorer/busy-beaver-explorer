"""Writes lean/Rules.lean: shift rules of this machine's sweeps and the shape of a halt, proved by
tools/py/bbtools/symtm.py (`prove`).  Usage: python3 py/rules.py > lean/Rules.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LE_1RC1RF_1RD0RA_1LE0RC_1LC0LD_0RD---"
NS = "H4608"
RULES = [
    ('c_run', 'L C> (01)^n R', 'L (10)^n C> R',
     'Rightward over the (10)^n part, C shifts each 01 to 10.', {}),
    ('d_run', 'L D> (10)^n R', 'L (01)^n D> R',
     'Rightward, D shifts each 10 to 01 (C and D alternate the phase).', {}),
    ('d_back', 'L (01)^n D> 0 R', 'L D> 0 (01)^n R',
     'Leftward, D runs over (01)^n.', {}),
    ('e_back', 'L (10)^n E> 1 R', 'L E> 1 (10)^n R',
     'Leftward, E runs over (10)^n.', {}),
    ('d_blocks', 'L D> (1101010)^n R', 'L (0011001)^n D> R',
     'Rightward over the counter blocks a = 1101010, D rewrites each one as 0011001 ...', {}),
    ('d_blocks_back', 'L (0011001)^n D> 0 R', 'L D> 0 (0101101)^n R',
     '... leftward D rewrites it as 0101101 ...', {}),
    ('f_blocks', 'L F> (0101101)^n R', 'L (0010011)^n F> R',
     '... and rightward F rewrites it again: the blocks cycle through a few phases as the head crosses them.', {}),
    ('halt_shape', 'L C> 1 0 1 1 R', 'L 0 1 1 F> 1 R',
     'The only way to a halt: C on 1 0 1 1 reaches F on a 1 (which halts) in 3 steps.', {}),
]
HALT = "F"
HSYM = "1"

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d, **kw)[0] for n, s, e, d, kw in RULES]
    extra = (f"/-- {HALT} reading a {HSYM} halts (the end of `halt_shape`). -/\n"
             f"theorem halt_after_shape (L R : Tape) : step ⟨L, cons true R, .{HALT}⟩ = none := rfl\n")
    print(rules_file("Machine", NS, thms + [extra],
                     f"# {M}: shift rules of the sweeps and the shape of a halt\n\n"
                     "Generated by `py/rules.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `n` and all "
                     "tapes `L`, `R`."))
