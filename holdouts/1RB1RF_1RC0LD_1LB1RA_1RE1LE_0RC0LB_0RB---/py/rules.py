"""Generate Rules.lean for 1RB1RF_1RC0LD_1LB1RA_1RE1LE_0RC0LB_0RB---: shift rules (one copy of a word crossed by the head in a state, so a whole run of
copies is crossed at once), each proved along a symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`,
shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, prove, rules_file, run  # noqa: E402

M = "1RB1RF_1RC0LD_1LB1RA_1RE1LE_0RC0LB_0RB---"
NS = "H65352"

# (name, start, doc): the end is the configuration right after the run of copies is crossed
RULES = [
    ('c_right',
     'L C> (100)^n R',
     'C runs right over triples 100, turning each into 111 (C1 → 1RA, A0 → 1RB, B0 → 1RC), 3 steps a triple.'),
    ('a_right',
     'L A> (001)^n R',
     'The same rightward sweep in phase A: 001 becomes 111.'),
    ('b_right',
     'L B> (010)^n R',
     'The same rightward sweep in phase B: 010 becomes 111.'),
    ('d_left',
     'L (111)^n D> 1 R',
     'D runs left over triples 111, turning each into 001 (D1 → 1LE, E1 → 0LB, B1 → 0LD), 3 steps a triple.'),
    ('e_left',
     'L (111)^n E> 1 R',
     'The same leftward sweep in phase E: 111 becomes 100.'),
    ('b_left',
     'L (111)^n B> 1 R',
     'The same leftward sweep in phase B: 111 becomes 010.'),
    ('zig_d',
     'L 0 1 1 (111)^m+1 D> 1 0^inf',
     'L 1 1 1 1 0 1 1 (111)^m 1 B> 1 1 0^inf',
     'One bounce of the marker zig-zag, read at the right end: the marker (the 0) moves 4 cells right, the gap from it to the head shrinks by 2.'),
]

DOC = """Shift rules of the two sweeps. Generated by py/rules.py (tools/py/bbtools/symtm.py); do not edit by hand. A sweep to the right turns the triples 100 / 001 / 010 (depending on its phase) into 111, a sweep to the left turns 111 back into 001 / 100 / 010: the tape is a run of 1s with a few 0s, written in two encodings. The last theorem is one bounce of the marker zig-zag."""


def after_cross(start):
    trace = []
    run(Machine.parse(M), Config.parse(start), lambda c: any(t[0] == "cross" for t in trace), trace=trace)
    return next(t[2] for t in trace if t[0] == "cross")


def main():
    ths = []
    for r in RULES:
        name, start, doc = r[0], r[1], r[-1]
        end = r[2] if len(r) == 4 else after_cross(start)
        ths.append(prove(M, name, start, end, doc=doc)[0])
    sys.stdout.write(rules_file("Machine", NS, ths, DOC))


if __name__ == "__main__":
    main()
