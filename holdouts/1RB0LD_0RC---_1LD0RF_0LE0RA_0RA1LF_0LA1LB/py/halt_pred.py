#!/usr/bin/env python3
"""Generate a Lean file proving which configurations halt after exactly k more steps.

usage: python3 halt_pred.py MACHINE K [K ...] > lean/HaltPred.lean

For each K it enumerates, by a decision tree over the cells the head reads (first read of each cell = a branch),
every configuration that runs K steps and then stops, and writes

  theorem halt_pred_K (c c' : Config) (h : steps K c = some c') (hn : step c' = none) : W_1 c ∨ ... ∨ W_m c

where each W_i fixes the state and the cells read on that branch (a cell left of the head is `c.l i`, i = 0 next to
the head; the head's cell and those right of it are `c.r i`). The proof follows the same decision tree: one `cases`
per branching cell, then `simp_all` evaluates the K + 1 steps with the library's own `step`. The windows of one K
are disjoint and together they are exactly the configurations that halt after K steps.

It also writes `halts_blank_pred_K`: if the machine halts from blank tape, some configuration of the run matches one
of the windows (the run makes at least 10,000 steps, `blank_runs_kernel`, so the configuration K steps before the
halt exists). The Lean namespace is read from lean/Machine.lean next to the output.
"""
import os
import re
import sys


def parse(m):
    T = {}
    for i, s in enumerate(m.split('_')):
        for b in (0, 1):
            t = s[3 * b:3 * b + 3]
            T[('ABCDEF'[i], b)] = None if t[2] == '-' else (int(t[0]), t[1], t[2])
    return T


def tree(T, q, k):
    """Decision tree of the run from state q: ('br', pos, t0, t1) | ('leaf', fixed, outcome) with outcome
    'halt' (stops after exactly k steps), 'early' (stops before) or 'runs' (step k+1 exists)."""
    def go(state, head, written, fixed, n):
        if head in written:
            return go_read(state, head, written, fixed, n, written[head])
        if head in fixed:
            return go_read(state, head, written, fixed, n, fixed[head])
        sub = []
        for b in (0, 1):
            f2 = dict(fixed); f2[head] = b
            sub.append(go_read(state, head, written, f2, n, b))
        return ('br', head, sub[0], sub[1])

    def go_read(state, head, written, fixed, n, b):
        x = T[(state, b)]
        if x is None:
            return ('leaf', fixed, 'halt' if n == k else 'early')
        if n == k:
            return ('leaf', fixed, 'runs')
        w2 = dict(written); w2[head] = x[0]
        return go(x[2], head + (1 if x[1] == 'R' else -1), w2, fixed, n + 1)
    return go(q, 0, {}, {}, 0)


def leaves(t):
    if t[0] == 'leaf':
        yield t
    else:
        yield from leaves(t[2]); yield from leaves(t[3])


def cell(p):
    return f'c.r {p}' if p >= 0 else f'c.l {-p - 1}'


def cellv(p):
    return f'r {p}' if p >= 0 else f'l {-p - 1}'


def window(q, fixed):
    parts = [f'c.st = .{q}'] + [f'{cell(p)} = {"true" if fixed[p] else "false"}' for p in sorted(fixed)]
    return '(' + ' ∧ '.join(parts) + ')'


def show(q, fixed):
    lo = min([0] + list(fixed)); hi = max([0] + list(fixed))
    s = []
    for p in range(lo, hi + 1):
        v = str(fixed[p]) if p in fixed else 'x'
        s.append(f'{q}> {v}' if p == 0 else v)
    return ' '.join(s)


SIMP = 'simp_all [steps, step, TM.steps, TM.step, trans, TM.tail]'
EV = '[steps, step, TM.steps, TM.step, trans, TM.tail'


def proof(t, ind, names):
    pad = ' ' * ind
    if t[0] == 'leaf':
        hs = ''.join(', ' + n for n in names)
        return [pad + f'simp only {EV}{hs}, TM.cons_zero, TM.cons_succ, Option.some.injEq] at h <;> (try subst h) <;> {SIMP}']
    p = t[1]; h = f'h{len(names)}'
    out = [pad + f'cases {h} : {cellv(p)}']
    for sub in (t[2], t[3]):
        out.append(pad + '· ' + proof(sub, ind + 2, names + [h])[0].strip())
        out += proof(sub, ind + 2, names + [h])[1:]
    return out


def gen(m, ks, ns):
    T = parse(m)
    out = ['import Machine', 'import Blank', '',
           f'/-! Every configuration of {m} that halts after exactly k more steps, for the k below.',
           'Generated by `holdouts/1RB0LD_0RC---_1LD0RF_0LE0RA_0RA1LF_0LA1LB/py/halt_pred.py`; do not edit by hand.',
           'Each theorem is the converse of the `halt_ctx` lemmas: the listed windows are all the ways to halt. -/', '',
           f'namespace {ns}', '', 'open TM', '', 'set_option linter.unusedSimpArgs false', '',
           '/-- A run of a + b steps goes through the configuration after a steps. -/',
           'theorem steps_split : ∀ (a b : Nat) (c c\'\' : Config), TM.steps trans (a + b) c = some c\'\' →',
           '    ∃ c\', TM.steps trans a c = some c\' ∧ TM.steps trans b c\' = some c\'\'',
           '  | 0, b, c, c\'\', h => ⟨c, rfl, by simpa using h⟩',
           '  | a + 1, b, c, c\'\', h => by',
           '    rw [show a + 1 + b = (a + b) + 1 by omega] at h',
           '    cases hs : TM.step trans c with',
           '    | none => simp [steps, TM.steps, hs] at h',
           '    | some d =>',
           '      rw [TM.steps_succ_of_step trans (a + b) hs] at h',
           '      obtain ⟨c\', h1, h2⟩ := steps_split a b d c\'\' h',
           '      exact ⟨c\', by rw [TM.steps_succ_of_step trans a hs]; exact h1, h2⟩', '']
    summary = []
    for k in ks:
        trees = {q: tree(T, q, k) for q in 'ABCDEF'}
        wins = [(q, lf[1]) for q in 'ABCDEF' for lf in leaves(trees[q]) if lf[2] == 'halt']
        disj = ' ∨\n      '.join(window(q, f) for q, f in wins) if wins else 'False'
        shown = ', '.join(f'`{show(q, f)}`' for q, f in wins)
        summary.append((k, [show(q, f) for q, f in wins]))
        out.append(f'/-- The configurations that halt after exactly {k} more steps: {shown}. -/')
        out.append(f'theorem halt_pred_{k} (c c\' : Config) (h : steps {k} c = some c\') (hn : step c\' = none) :')
        out.append(f'    {disj} := by')
        out.append('  obtain ⟨l, r, s⟩ := c')
        out.append('  cases s')
        for q in 'ABCDEF':
            body = proof(trees[q], 4, [])
            out.append(f'  case {q} =>')
            out += body
        out.append('')
        out.append(f'/-- Both directions: a configuration halts after exactly {k} more steps if and only if it matches one '
                   f'of the windows of `halt_pred_{k}`. -/')
        out.append(f'theorem halt_iff_{k} (c : Config) : (∃ c\', steps {k} c = some c\' ∧ step c\' = none) ↔')
        out.append(f'    ({disj.replace(chr(10), " ").replace("      ", "")}) := by')
        out.append('  constructor')
        out.append(f'  · rintro ⟨c\', h, hn⟩; exact halt_pred_{k} c c\' h hn')
        out.append('  · obtain ⟨l, r, s⟩ := c')
        out.append('    intro hw')
        pats = ['⟨' + ', '.join(['hs'] + [f'w{i}' for i in range(len(f))]) + '⟩' for q, f in wins]
        if wins:
            out.append('    rcases hw with ' + ' | '.join(pats))
            for q, f in wins:
                ws = ' '.join(f'w{i}' for i in range(len(f)))
                out.append(f'    · simp only at hs {ws}; subst hs')
                out.append(f'      simp [steps, step, TM.steps, TM.step, trans, TM.tail, {", ".join(f"w{i}" for i in range(len(f)))}]')
        else:
            out.append('    exact hw.elim')
        out.append('')
        out.append(f'/-- If the machine halts from blank tape, the run passes through one of the windows of '
                   f'`halt_pred_{k}`. -/')
        out.append(f'theorem halts_blank_pred_{k} (hh : HaltsFromBlank) :')
        out.append(f'    ∃ n c, steps n init = some c ∧ ({disj.replace(chr(10), " ").replace("      ", "")}) := by')
        out.append('  obtain ⟨n, c\', h1, h2⟩ := hh')
        out.append('  obtain ⟨c0, h0⟩ := blank_runs_kernel')
        out.append(f'  have hn : {k} ≤ n := by')
        out.append('    refine Nat.le_of_not_lt (fun hlt => ?_)')
        out.append(f'    have := TM.steps_halt trans h1 h2 (10000 - n - 1)')
        out.append('    rw [show n + (10000 - n - 1 + 1) = 10000 by omega] at this')
        out.append('    simp_all')
        out.append(f'  obtain ⟨c, hc, hc\'⟩ := steps_split (n - {k}) {k} init c\' '
                   f'(by rw [show n - {k} + {k} = n by omega]; exact h1)')
        out.append(f'  exact ⟨n - {k}, c, hc, halt_pred_{k} c c\' hc\' h2⟩')
        out.append('')
    out.append(f'end {ns}')
    return '\n'.join(out) + '\n', summary


if __name__ == '__main__':
    m = sys.argv[1]; ks = [int(a) for a in sys.argv[2:]]
    here = os.path.dirname(os.path.abspath(__file__))
    mach = os.path.join(here, '..', '..', m, 'lean', 'Machine.lean')
    ns = re.search(r'^namespace (\S+)', open(mach).read(), re.M).group(1)
    text, summary = gen(m, ks, ns)
    sys.stdout.write(text)
    for k, ws in summary:
        print(f'k={k}: {len(ws)} windows: ' + '; '.join(ws), file=sys.stderr)
