"""Generate Rules.lean for 1RB0LD_0RC---_1LD0RF_0LE0RA_0RA1LF_0LA1LB: the halting context and the shift rules over the words of its tape, proved along the symbolic run of tools/py/bbtools/symtm.py
(single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LD_0RC---_1LD0RF_0LE0RA_0RA1LF_0LA1LB"

RULES = [
    ('halt_ctx', 'L A> 0 1 R', 'L 1 B> 1 R',
     'A on a 0 with a 1 after it hands B a 1 (the halting transition).'),
    ('halt_ctx_F', 'L 1 F> 1 R', 'L B> 1 1 R',
     'F on a 1 with a 1 on its left moves left onto it in state B (the halting transition).'),
    ('back_A_100_10', 'L (100)^n A> 1 0 R', 'L A> 1 0 (101)^n R',
     'A crosses n copies of `100` to the left in 9n steps, leaving `101` (carrying `1 0`).'),
    ('run_C_10', 'L C> (10)^n R', 'L (10)^n C> R',
     'C crosses n copies of `10` to the right in 4n steps, leaving `10`.'),
    ('run_C_110', 'L C> (110)^n R', 'L (010)^n C> R',
     'C crosses n copies of `110` to the right in 7n steps, leaving `010`.'),
    ('back_D_0001_00', 'L (0001)^n D> 0 0 R', 'L D> 0 0 (0101)^n R',
     'D crosses n copies of `0001` to the left in 14n steps, leaving `0101` (carrying `0 0`).'),
    ('run_F_01_0', 'L 0 F> (01)^n R', 'L (10)^n 0 F> R',
     'F crosses n copies of `01` to the right in 4n steps, leaving `10` (carrying `0`).'),
    ('run_F_1_0', 'L 0 F> (1)^n R', 'L (0)^n 0 F> R',
     'F crosses n copies of `1` to the right in 3n steps, leaving `0` (carrying `0`).'),
    ('run_F_100_00', 'L 0 0 F> (100)^n R', 'L (101)^n 0 0 F> R',
     'F crosses n copies of `100` to the right in 17n steps, leaving `101` (carrying `0 0`).'),
    ('run_F_011_0', 'L 0 F> (011)^n R', 'L (100)^n 0 F> R',
     'F crosses n copies of `011` to the right in 7n steps, leaving `100` (carrying `0`).'),
    ('back_F_001_0', 'L (001)^n F> 0 R', 'L F> 0 (101)^n R',
     'F crosses n copies of `001` to the left in 9n steps, leaving `101` (carrying `0`).'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H2336", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
