"""Generate Rules.lean for 1RB0LF_1RC1RB_1LD0RA_1LA0LE_0LC1LC_1LE---: shift rules (one copy of a word crossed by the head in a state, so a whole run of
copies is crossed at once), each proved along a symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`,
shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, prove, rules_file, run  # noqa: E402

M = "1RB0LF_1RC1RB_1LD0RA_1LA0LE_0LC1LC_1LE---"
NS = "H12600"

# (name, start, doc): the end is the configuration right after the run of copies is crossed
RULES = [
    ('b_right',
     'L B> (01001111)^n R',
     'B runs right over the period-8 word 01001111, turning each copy into 01110111: the rightward sweep turns the left-sweep form of the background into the right-sweep form (the period-4 word 0111 twice).'),
    ('c_right',
     'L 1 C> (10011110)^n R',
     'The same sweep in phase C, carrying a 1.'),
    ('d_left',
     'L (11010011)^n D> 1 R',
     'D runs left over 11010011 (a rotation of the period-8 word), turning each copy into 10100111.'),
    ('c_left',
     'L (10100111)^n C> 0 R',
     'C runs left over 10100111, turning each copy into 01001111: the leftward sweep.'),
]

DOC = """Shift rules of the sweeps over the period-8 background 01001111 (left-sweep form) / (0111)^2 (right-sweep form). Generated by py/rules.py (tools/py/bbtools/symtm.py); do not edit by hand."""


def after_cross(start):
    trace = []
    run(Machine.parse(M), Config.parse(start), lambda c: any(t[0] == "cross" for t in trace), trace=trace)
    return next(t[2] for t in trace if t[0] == "cross")


def main():
    ths = []
    for name, start, doc in RULES:
        ths.append(prove(M, name, start, after_cross(start), doc=doc)[0])
    sys.stdout.write(rules_file("Machine", NS, ths, DOC))


if __name__ == "__main__":
    main()
