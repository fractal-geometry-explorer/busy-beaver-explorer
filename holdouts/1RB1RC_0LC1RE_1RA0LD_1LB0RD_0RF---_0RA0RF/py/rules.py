"""Writes lean/Rules.lean: the lowest step of the counter, proved by bbtools.symtm (shift rules, `rfl`, `omega`).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "../../../tools/py"))
from bbtools.symtm import prove
from crossgen import generic_cross

M = "1RB1RC_0LC1RE_1RA0LD_1LB0RD_0RF---_0RA0RF"
NS = "H1965"
RULES = [
    ("dec_last", "The counter's lowest digit 1 -> 0: the last gap 000 becomes 00 and the block before it gains 3 cells "
     "(last block of even length 2y+2; the head at the right end in state A).",
     "L 0 1^x 0 0 0 (11)^y 1 1 A> 0^inf", "L 0 1^x+3 0 0 (11)^y 1 1 A> 0^inf"),
    # The pieces of a visit of the right end (composed in Decrement.lean).
    ("p_start", "At the right end, A writes a 1 and turns: the leftward sweep starts on that 1.",
     "L A> 0^inf", "L C> 1 0^inf"),
    ("p_pass", "The sweep crosses an odd block whose gap on the left is 00 (the block before is nonempty): "
     "it is left in the sparse form 0 1 0 (01)^w and the sweep goes on in the block before.",
     "L 1 0 0 (11)^w C> 1 R", "L C> 1 0 1 0 (01)^w R"),
    ("p_stop_odd", "The sweep stops at an odd block whose gap on the left is 000: a 1 is written in the gap and A turns right.",
     "L 0 0 0 (11)^w C> 1 R", "L 1 A> 0 1 0 (01)^w R"),
    ("p_stop_even", "The sweep stops at an even block (any gap of at least one 0 on its left): A turns right.",
     "L 0 1 (11)^w C> 1 R", "L 1 A> 0 1 (01)^w R"),
    ("p_halt", "The only way the sweep can halt: an odd block whose gap on the left is a single 0 (state E then reads a 1).",
     "L 1 0 (11)^w C> 1 R", "L 1 E> 1 0 (01)^w R"),
    ("p_fill_first", "Refilling, first segment: 0 1 0 0 1 (01)^w becomes 1 1 0 0 (11)^w (the old 000 gap is now 00).",
     "L A> 0 1 0 0 1 (01)^w R", "L 1 1 0 0 (11)^w A> 1 R"),
    ("p_fill_two", "Refilling across a segment boundary: 1 0 1 0 becomes 1 1 1 1.",
     "L A> 1 0 1 0 R", "L 1 1 1 1 A> R"),
    ("p_fill_mid", "Refilling a later segment: (01)^(v+3) becomes 1 1 0 0 0 (11)^v and a 1 (the old 00 gap is now 000).",
     "L A> 0 1 0 1 0 1 (01)^v R", "L 1 1 0 0 0 (11)^v A> 1 R"),
    ("p_fill_end", "The last 1 before blank tape: A comes back to the right end.",
     "L A> 1 0^inf", "L 1 1 A> 0^inf"),
]


def main():
    out = ["import Machine", "", f"/-! Rules of {M}, generated by `py/rules.py`; do not edit by hand. -/", "",
           "set_option maxRecDepth 20000", "set_option maxHeartbeats 10000000", "", f"namespace {NS}", "", "open TM", ""]
    for name, doc, start, end in RULES:
        t, f = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=60)
        out += [generic_cross(t), ""]
    out.append(f"end {NS}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
