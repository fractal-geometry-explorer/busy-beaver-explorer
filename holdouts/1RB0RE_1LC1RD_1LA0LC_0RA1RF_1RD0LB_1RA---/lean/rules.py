"""Generate Rules.lean: shift rules of 1RB0RE_1LC1RD_1LA0LC_0RA1RF_1RD0LB_1RA---, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(10)^n` is n
copies of `10`, `0^inf` is blank tape, L and R are any tape.  What the rules mean is in ../README.md.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC1RD_1LA0LC_0RA1RF_1RD0LB_1RA---"

RULES = [
    ('b_right', 'L B> (100)^n R', 'L (101)^n B> R',
     'Going right, B turns every `100` into `101`, three steps per word.'),
    ('b_left', 'L 0 (101)^n B> 0 R', 'L 0 B> 0 (001)^n R',
     'Going left, B turns a block of `101` words into `100` words, read one cell further on.'),
    ('a_right', 'L A> (100)^n R', 'L (010)^n A> R',
     'Going right, A shifts a block of `100` words by one cell.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=30)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H152969", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
