"""Generate lean/Rules.lean for 1RB0RC_0LA0RA_0LD0RA_1LE---_0LF1LB_1LA1LD: the shift rules of its sweeps, proved along symbolic runs
(tools/py/bbtools/symtm.py: single steps by `rfl`, a whole repeat crossed by `TM.cross_r` / `TM.cross_l`).

usage (from the repository root): python3 holdouts/1RB0RC_0LA0RA_0LD0RA_1LE---_0LF1LB_1LA1LD/py/rules.py > holdouts/1RB0RC_0LA0RA_0LD0RA_1LE---_0LF1LB_1LA1LD/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape.  Each rule holds for every n and every tape around it; README.md says where each one is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402

symtm.MAX_CARRY = 8  # some sweeps carry a word of up to 6 cells along with the head

M = "1RB0RC_0LA0RA_0LD0RA_1LE---_0LF1LB_1LA1LD"
NS = "H87199"

RULES = [
    ("r_sea", "L A> (01)^n R", "L (10)^n A> R",
     "Rightward sweep over the sea: each pair 01 becomes 10 (and a pair 11 becomes 00, rule r_defect)."),
    ("r_defect", "L A> (11)^n R", "L (00)^n A> R",
     "Rightward sweep: a defect pair 11 becomes 00."),
    ("l_sea", "L (10)^n A> 110110 R", "L A> 110110 (10)^n R",
     "Leftward sweep: the head carries the word 110110 left across the sea, 12 steps a pair."),
    ("l_sea_f", "L (01)^n F> 00110 R", "L F> 00110 (10)^n R",
     "The same leftward sweep, seen from state F."),
]


def main():
    ths = [symtm.prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(symtm.rules_file("Machine", NS, ths, f"Sweep rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
