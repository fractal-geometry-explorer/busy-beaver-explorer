#!/usr/bin/env python3
"""Local path lemmas of the four machines of the (100)^n / 6k+1 family, proved by bbtools.symtm, written to
holdouts/<M>/lean/Paths.lean (one script for the four folders; `--check` compares instead of writing).

The four tables share the core A, B, C, D (in a2's names) and differ only on the paths the core leaves through:
  * B> 0 1 1 0  (the 'F-event', two per trip of the second phase): a2, a3, a4 turn it into 1 0 0 0 A>, a1 into
    1 1 1 1 B>;
  * B> 0 1 1 1  halts a1, a2, a4 (a3 runs on);  B> 0 0 1 halts a3 (the others run on);
  * B> 0 1 0    is where a2 and a4 would part (never seen in a run);
  * A> 1 bounces and the C0 step, done by other states / with a detour in a3 and a4 but with the same result.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'py'))
from bbtools.symtm import prove

A1 = '1RB0LC_1RC1RA_1LD0RE_1LA1LD_0RA0RF_0LD---'
A2 = '1RB0LC_1RC1RA_1LD0RE_1LA1LD_0RA1RF_0LC---'
A3 = '1RB0LC_1RC1RA_1RD0RF_0LE---_1LA1LE_0RA0RF'
A4 = '1RB0LE_1RC1RA_1LD0RE_1LA1LD_1LD0RF_0RA---'
NS = {A1: 'H155900', A2: 'H72859', A3: 'H123915', A4: 'H66704'}

# (name, start, end, doc) per machine
COMMON_BOUNCE = [
    ('bounce_on_1', 'L 1 A> 1 R', 'L 0 0 A> R',
     'A reading a 1 with a 1 on its left turns both into 0 and goes on right in A (a2: A1 C1 E0; a4: A1 E1 F0).'),
]
LEMMAS = {
    A2: COMMON_BOUNCE + [
        ('bounce_on_0', 'L x 0 A> 1 R', 'L D> x 1 0 R', 'A reading a 1 with a 0 on its left: A1 then C0, D reads the cell beyond.'),
        ('fevent', 'L B> 0 1 1 0 R', 'L 1 0 0 0 A> R', 'The F-event: B reads 0 1 1 0; B0 C1 E1 F0 C1 E0 give 1 0 0 0 and A on the right.'),
        ('fevent_halt', 'L B> 0 1 1 1 R', 'L 1 0 1 F> 1 R', 'The only way to halt: B reading 0 1 1 1 brings F onto a 1 (F1 is the halting transition).'),
        ('b_010', 'L B> 0 1 0 R', 'L 1 0 0 A> R', 'B reading 0 1 0 (never seen in a run): B0 C1 E0.'),
        ('b_00', 'L x B> 0 0 R', 'L D> x 1 1 R', 'B reading 0 0 (only at the right end of the tape): B0 C0 D1.'),
    ],
    A4: COMMON_BOUNCE + [
        ('bounce_on_0', 'L x 0 A> 1 R', 'L D> x 1 0 R', 'A reading a 1 with a 0 on its left: A1 then E0 (= a2 C0), D reads the cell beyond.'),
        ('fevent', 'L B> 0 1 1 0 R', 'L 1 0 0 0 A> R', 'The F-event: B0 C1 E1 F0 give 1 0 0 0 and A on the right, the same as a2 in 4 steps instead of 6.'),
        ('fevent_halt', 'L B> 0 1 1 1 R', 'L 1 0 0 F> 1 R', 'The only way to halt: B reading 0 1 1 1 brings F onto a 1 (F1 is the halting transition).'),
        ('b_010', 'L B> 0 1 0 R', 'L A> 1 1 1 R', 'B reading 0 1 0 (never seen in a run): here a4 parts from a2 (E0 = 1LD instead of 0RA).'),
        ('b_00', 'L x B> 0 0 R', 'L D> x 1 1 R', 'B reading 0 0 (only at the right end of the tape): B0 C0 D1, as in a2.'),
    ],
    A3: [
        ('bounce_on_1', 'L 1 A> 1 R', 'L 0 0 A> R', 'A reading a 1 with a 1 on its left: A1 C1 F0, the same as a2 (C1 E0).'),
        ('bounce_on_0', 'L x 0 A> 1 R', 'L E> x 1 0 R', 'A reading a 1 with a 0 on its left: A1, then the detour C0 D0 E1 (= a2 C0, with E for a2 D), E reads the cell beyond.'),
        ('fevent', 'L B> 0 1 1 0 R', 'L 1 0 0 0 A> R', 'The F-event: B0 C1 F1 F0 give 1 0 0 0 and A on the right, as in a2.'),
        ('fevent_on', 'L B> 0 1 1 1 0 R', 'L 1 0 0 0 0 A> R', 'B reading 0 1 1 1 (where a2 halts) does not halt here: F erases the 1s and goes on.'),
        ('b_001_halt', 'L B> 0 0 1 R', 'L 1 1 D> 1 R', 'The only way to halt: B reading 0 0 1 brings D onto a 1 (D1 is the halting transition).'),
        ('b_000', 'L x B> 0 0 0 R', 'L E> x 1 1 0 R', 'B reading 0 0 0 (only at the right end of the tape): B0 C0 D0 E1, the same tape as a2 (B0 C0 D1).'),
    ],
    A1: COMMON_BOUNCE + [
        ('bounce_on_0', 'L x 0 A> 1 R', 'L D> x 1 0 R', 'A reading a 1 with a 0 on its left: A1 then C0.'),
        ('fevent', 'L B> 0 1 1 0 R', 'L 1 1 1 1 B> R', 'The F-event of a1: B0 C1 E1 F0 D0 A0 B1 A0 write 1 1 1 1 and leave B on the right (a2 writes 1 0 0 0 and leaves A).'),
        ('fevent_halt', 'L B> 0 1 1 1 R', 'L 1 0 0 F> 1 R', 'The only way to halt: B reading 0 1 1 1 brings F onto a 1 (F1 is the halting transition).'),
        ('b_00', 'L x B> 0 0 R', 'L D> x 1 1 R', 'B reading 0 0 (only at the right end of the tape): B0 C0 D1.'),
    ],
}

def gen(m):
    out = ['import Machine', '',
           f'/-! Local paths of {m.replace('---', '(halt)')}: how the core leaves and re-enters, and the halting paths.',
           '    Generated by py/gen_paths.py in the folder of the machine 1RB0LC_1RC1RA_1LD0RE_1LA1LD_0RA1RF_0LC (H72859); do not edit by hand. -/', '',
           f'namespace {NS[m]}', '', 'open TM', '']
    for name, a, b, doc in LEMMAS[m]:
        # a cell written x stands for either symbol: one lemma per value (symtm has no symbolic single cell)
        cases = [(name, a, b)] if ' x ' not in a else [
            (f'{name}_{v}', a.replace(' x ', f' {v} '), b.replace(' x ', f' {v} ')) for v in '01']
        for nm, a1, b1 in cases:
            txt, fin = prove(m, nm, a1, b1, doc=doc)
            out.append(txt.rstrip()); out.append('')
    out.append(f'end {NS[m]}')
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    check = '--check' in sys.argv
    bad = 0
    for m in LEMMAS:
        p = os.path.join(ROOT, 'holdouts', m, 'lean', 'Paths.lean')
        t = gen(m)
        if check:
            if not os.path.exists(p) or open(p).read() != t:
                print('differs:', p); bad = 1
        else:
            open(p, 'w').write(t); print('wrote', p)
    sys.exit(bad)
