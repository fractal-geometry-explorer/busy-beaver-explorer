"""Writes lean/Rules.lean: the trip and the generic epoch-end rules of 1RB0LD_0RC1RA_1RD1RE_1LA0LE_0RA0RF_1RC---.

usage: python3 py/gen_rules.py > lean/Rules.lean   (from the machine's folder)
Each rule is proved by tools/py/bbtools/symtm.py (single steps by `rfl`, runs by `TM.cross_l` / `TM.cross_r`,
re-bracketings by `TM.rep_rotate`); `trips` iterates `trip` by induction."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', '..', 'tools', 'py'))
from bbtools.symtm import prove

M = "1RB0LD_0RC1RA_1RD1RE_1LA0LE_0RA0RF_1RC---"
RULES = [
    ("trip", "L 1 1 1 (01)^m+1 C> 0^inf", "L (01)^m+6 C> 0^inf",
     "A trip: `1^3 (01)^(m+1) C>` at the right end becomes `(01)^(m+6) C>` in 6m + 45 steps."),
    ("zero_blank", "0^inf (01)^m+4 C> 0^inf", "0^inf (11)^m 1^14 (01)^3 C> 0^inf",
     "End of an epoch with no ones left and blank tape beyond: `(01)^M` becomes `1^(2M+6) (01)^3` (M = m + 4)."),
    ("zero_dec", "L 0 1 0 (01)^m+4 C> 0^inf", "L 0 (11)^m 1^15 (01)^3 C> 0^inf",
     "End of an epoch with no ones left, next level ending in `01`: that `01` is used up and `(01)^M` becomes `1^(2M+7) (01)^3`."),
    ("zero_merge", "L 0 1^p 0 (01)^m+4 C> 0^inf", "L 0 1^p (11)^m 1^14 (01)^3 C> 0^inf",
     "End of an epoch with no ones left, next level `1^p` with no `01`: it joins, giving `1^(p+2M+6) (01)^3`."),
    ("two_blank", "0^inf 1 1 (01)^m+12 C> 0^inf", "0^inf 1^4 (01)^6 0 (11)^m 1^16 (01)^3 C> 0^inf",
     "End of an epoch with two ones left and blank tape beyond: a new level `1^4 (01)^6 0` is pushed and `(01)^M` becomes `1^(2M-8) (01)^3` (M = m + 12)."),
    ("two_trip", "L 1 1 1 (01)^q 0 1 1 (01)^m+6 C> 0^inf", "L (01)^q+7 0 (11)^m 1^8 (01)^3 C> 0^inf",
     "Two ones left, level 2 is `1^(n+3) (01)^q`: level 2 makes one trip, to `1^n (01)^(q+7)`, and `(01)^M` becomes `1^(2M-4) (01)^3` (M = m + 6)."),
    ("two_dec", "L 0 1 0 (01)^q+4 0 1 1 (01)^m+12 C> 0^inf", "L 0 (11)^q 1^13 (01)^6 0 (11)^m 1^16 (01)^3 C> 0^inf",
     "Two ones left, level 2 is `(01)^Q` with no ones, level 3 ends in `01`: level 2 becomes `1^(2Q+5) (01)^6`, level 3 loses its `01`, and `(01)^M` becomes `1^(2M-8) (01)^3` (Q = q + 4, M = m + 12)."),
    ("two_merge", "L 0 1^p 0 (01)^q+4 0 1 1 (01)^m+12 C> 0^inf", "L 0 1^p (11)^q 1^12 (01)^6 0 (11)^m 1^16 (01)^3 C> 0^inf",
     "Two ones left, level 2 is `(01)^Q`, level 3 is `1^p`: they join as `1^(p+2Q+4) (01)^6`, and `(01)^M` becomes `1^(2M-8) (01)^3`."),
]
out = []
for name, a, b, doc in RULES:
    text, _ = prove(M, name, a, b, rotate=True, doc=doc)
    out.append(text)
body = "\n\n".join(out)
start, _ = prove(M, "start_run", "0^inf A> 0^inf", "0^inf (01)^9 C> 0^inf", max_seg=20)

