"""Generate Rules.lean for 1RB0RA_1RC1RD_1LD1LB_0RF1LE_1LE0LC_---1RA: shift rules (one copy of a word crossed by the head in a state, so a whole run of
copies is crossed at once), each proved along a symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`,
shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, prove, rules_file, run  # noqa: E402

M = "1RB0RA_1RC1RD_1LD1LB_0RF1LE_1LE0LC_---1RA"
NS = "H60575"

# (name, start, doc): the end is the configuration right after the run of copies is crossed
RULES = [
    ('e_left4',
     'L (0111)^n E> 1 R',
     'E runs left over 0111, turning each copy into 1010 (the leftward sweep turns the period-4 background into pairs 10).'),
    ('e_left2',
     'L (01)^n E> 1 R',
     'E runs left over pairs 01, turning each into 10.'),
    ('c_left2',
     'L (10)^n C> 1 R',
     'C runs left over pairs 10, turning each into 01.'),
    ('e_left10',
     'L (0100110111)^n E> 0 R',
     'E runs left over the period-10 word 0100110111 of the right part of the tape, turning each copy into 1101010101.'),
]

DOC = """Shift rules of the leftward sweeps. Generated by py/rules.py (tools/py/bbtools/symtm.py); do not edit by hand."""


def after_cross(start):
    trace = []
    run(Machine.parse(M), Config.parse(start), lambda c: any(t[0] == "cross" for t in trace), trace=trace)
    return next(t[2] for t in trace if t[0] == "cross")


def main():
    ths = []
    for name, start, doc in RULES:
        ths.append(prove(M, name, start, after_cross(start), doc=doc)[0])
    sys.stdout.write(rules_file("Machine", NS, ths, DOC))


if __name__ == "__main__":
    main()
