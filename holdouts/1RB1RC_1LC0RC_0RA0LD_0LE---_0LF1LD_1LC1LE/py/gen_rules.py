"""Generate lean/Rules.lean for 1RB1RC_1LC0RC_0RA0LD_0LE---_0LF1LD_1LC1LE: sweep rules for all n, each proved by a symbolic run of bbtools.symtm.

L and R are arbitrary tapes the sweep does not look at.

usage: python3 py/gen_rules.py > lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "..", "tools", "py"))
from bbtools import symtm  # noqa: E402

M = "1RB1RC_1LC0RC_0RA0LD_0LE---_0LF1LD_1LC1LE"
NS = "H34590"
RULES = [
    ('sweep_r_A_10', '`L A> (10)^n R` to `L (10)^n A> R` in 2*n steps.',
     'L A> (10)^n R',
     'L (10)^n A> R'),
    ('sweep_l_D_10', '`L (10)^n 1 D> 0 R` to `L E> 1 (01)^n 0 R` in 2*n+1 steps.',
     'L (10)^n 1 D> 0 R',
     'L E> 1 (01)^n 0 R'),
    ('sweep_l_E_10', '`L (10)^n 1 E> 0 R` to `L F> 1 (01)^n 0 R` in 2*n+1 steps.',
     'L (10)^n 1 E> 0 R',
     'L F> 1 (01)^n 0 R'),
    ('sweep_r_C_01', '`L C> (01)^n R` to `L (01)^n C> R` in 2*n steps.',
     'L C> (01)^n R',
     'L (01)^n C> R'),
    ('sweep_l_C_01', '`L (01)^n 0 C> 1 R` to `L D> 0 (10)^n 0 R` in 2*n+1 steps.',
     'L (01)^n 0 C> 1 R',
     'L D> 0 (10)^n 0 R'),
    ('sweep_l_E_01', '`L (01)^n 0 E> 1 R` to `L D> 0 (10)^n 1 R` in 2*n+1 steps.',
     'L (01)^n 0 E> 1 R',
     'L D> 0 (10)^n 1 R'),
    ('sweep_l_F_01', '`L (01)^n 0 F> 1 R` to `L E> 0 (10)^n 1 R` in 2*n+1 steps.',
     'L (01)^n 0 F> 1 R',
     'L E> 0 (10)^n 1 R'),
    ('sweep_r_B_100', '`L B> (100)^n R` to `L (001)^n B> R` in 3*n steps.',
     'L B> (100)^n R',
     'L (001)^n B> R'),
    ('sweep_r_C_001', '`L C> (001)^n R` to `L (010)^n C> R` in 3*n steps.',
     'L C> (001)^n R',
     'L (010)^n C> R'),
]

if __name__ == "__main__":
    ts = []
    for name, doc, start, end in RULES:
        t, _ = symtm.prove(M, name, start, end, count_first=True, doc=doc)
        ts.append(t)
    print(symtm.rules_file("Machine", NS, ts, "Sweep rules of " + M + ", generated by `py/gen_rules.py` (do not edit)."), end="")
