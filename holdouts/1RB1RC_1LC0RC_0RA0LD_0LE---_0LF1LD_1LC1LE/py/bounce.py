"""Generate lean/Bounce.lean for 1RB1RC_1LC0RC_0RA0LD_0LE---_0LF1LD_1LC1LE: one whole bounce of the head between
the left end of the tape and the first wall, for every list of blocks in between.

Notation: a = 10.  Between the left end and the first *wall* (two separators side by side, written `0 0` or
`0 1` depending on its phase) the tape is  a^x 0 a^p1 0 a^q1 0 a^p2 0 a^q2 ... 0 a^y  followed by the wall: blocks
of a's split by single 0s.  At the start of a bounce the head is in state A at the left end.  One bounce runs right
to the wall and back to the left end; it moves every odd-numbered separator one a to the right, leaves the
even-numbered ones in place and toggles the wall (`0 0` -> `0 1` -> `0 0 ...` one a further on).  The list of
middle pairs [0 a^p 0 a^q] is a `seqtm` sequence `ts` of any length with its own p, q in each element, so each
theorem covers every list (proved with `lean/Seq.lean`).  The end configuration is stated the way the run writes
it, re-bracketed: e.g. `1 0 1 (01)^(x+3)` followed by `0 0 1 ...` is a^(x+5) 0 ..., so the theorem says
x -> x+2, p -> p-1, q -> q+1 for every pair, y -> y-1 and the wall toggled (wall 00), or the block after the
wall loses one a (wall 01).  With an even number of single separators before the wall (`bounce_even_*`) the
bounce instead writes a new block a^1 at the left end and the roles swap: x stays, p -> p+1, q -> q-1, y -> y+1,
u -> u-1 (the last block before the wall), the wall toggled as before.

usage: python3 py/bounce.py > lean/Bounce.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools import seqtm  # noqa: E402
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Blank  # noqa: E402

M = "1RB1RC_1LC0RC_0RA0LD_0LE---_0LF1LD_1LC1LE"
NS = "H34590"


def at_left_A(c):
    return (c.state == 0 and isinstance(c.left[0], Blank) and all(t == 0 for t in c.left[1:])
            and not c.steps.is_zero())


RULES = [
    ("bounce_w00", "0^inf A> (10)^x+3 [ 0 (10)^p+3 0 (10)^q+3 ]^ts 0 (10)^y+3 0 0 (10)^z+3 R",
     "A bounce against a wall in phase `0 0`: from the left end in state A back to the left end in state A, "
     "for every list `ts` of pairs of blocks; the wall becomes `0 1`."),
    ("bounce_w01", "0^inf A> (10)^x+3 [ 0 (10)^p+3 0 (10)^q+3 ]^ts 0 (10)^y+3 0 1 (10)^z+3 R",
     "A bounce against a wall in phase `0 1`: the wall becomes `0 0` one a further right, eating one a of the "
     "block after it."),
]


def main():
    m = Machine.parse(M)
    out = []
    for name, start, doc in RULES:
        st = seqtm.parse(start)
        txt, fin, _ = seqtm.prove(m, name, st, at_left_A, doc=doc)
        print(f"-- {name}: {start} ==> {fin}", file=sys.stderr)
        out.append(txt)
    head = (f"import Machine\nimport Seq\n\n/-! Whole bounces of {M} between the left end and the first wall, "
            f"for every list of blocks (generated by `py/bounce.py`). -/\n\nnamespace {NS}\n\nopen TM\n\n")
    sys.stdout.write(head + "\n".join(out) + f"\nend {NS}\n")


if __name__ == "__main__":
    main()
