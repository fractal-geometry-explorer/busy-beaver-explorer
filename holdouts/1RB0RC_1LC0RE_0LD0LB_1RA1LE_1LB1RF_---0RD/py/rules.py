"""Generate lean/Rules.lean: the rewriting rules of the token model of 1RB0RC_1LC0RE_0LD0LB_1RA1LE_1LB1RF_---0RD
(README.md, "The token model"), each proved for all values of its parameters and all surrounding tapes along a
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, runs of a repeated word by `TM.cross_r`/`cross_l`).

usage (from the repository root):
  python3 holdouts/1RB0RC_1LC0RE_0LD0LB_1RA1LE_1LB1RF_---0RD/py/rules.py [twin] > .../lean/Rules.lean

With `twin` the same rules are generated for 1RB1LE_1RC0RD_1LD0RE_0LA0LC_1LC1RF_---0RA (the same machine with the
states renamed; its state A is this machine's D).

Tapes are written left to right; `S>` is the head in state S on the next cell, `(11)^k` is k copies of `11`, L and R
are any tapes.  In the token model the cells left of the head are read in pairs, `11` = 1, `00` = 0 and
`0101` = X, the head is on the first cell of a `00`, and the cells after it are read in pairs `11` = 1, `10` = 0.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M, S, NS = "1RB0RC_1LC0RE_0LD0LB_1RA1LE_1LB1RF_---0RD", "D", "H145349"
TWIN = ("1RB1LE_1RC0RD_1LD0RE_0LA0LC_1LC1RF_---0RA", "A")

RULES = [
    ("carry", "L 0 0 (11)^k S> 0 0 1 0 R", "L S> 0 0 1 1 (11)^k 1 1 R",
     "R1, carry: `L 0 1^k | 0 r -> L | 1^(k+2) r`.  The ones at the top of the left word, the 0 under them and the "
     "first 0 of the right word become a block of k + 2 ones on the right."),
    ("unwind", "L 0 0 0 1 0 1 (110101)^j (11)^k S> 0 0 1 0 R", "L S> 0 0 1 0 1 0 1 1 (101011)^j (11)^k 1 1 R",
     "R4, carry through marks: `L 0 X (1 X)^j 1^k | 0 r -> L | 0 0 (1 0 0)^j 1^(k+2) r`."),
    ("push1", "L S> 0 0 1 1 1 0 1 0 R", "L 1 1 0 1 0 1 S> 0 0 R",
     "R2 for a block of one 1: `L | 1 0 0 r -> L 1 X | r`."),
    ("push", "L S> 0 0 (11)^d+2 1 0 1 0 R", "L 1 1 0 0 (00)^d 0 1 0 1 S> 0 0 R",
     "R2, a block followed by two 0s goes to the left word with a mark: `L | 1^d 0 0 r -> L 1 0^(d-1) X | r` "
     "(here for d + 2 ones)."),
    ("load2", "L S> 0 0 1 1 1 1 1 0 1 1 R", "L 1 1 S> 0 0 1 0 1 0 1 0 R",
     "R3 for a block of two 1s: `L | 1 1 0 1 r -> L 1 | 0 0 0 r`."),
    ("load", "L S> 0 0 (11)^d+3 1 0 1 1 R", "L 1 1 0 0 (00)^d S> 0 0 1 0 1 0 1 0 R",
     "R3, a block followed by `0 1` goes to the left word as a counter: `L | 1^d 0 1 r -> L 1 0^(d-2) | 0 0 0 r` "
     "(here for d + 3 ones)."),
    ("drop", "L 0 0 S> 0 0 1 1 1 0 1 1 R", "L S> 0 0 1 1 1 0 1 0 1 0 R",
     "R5a: `L 0 | 1 0 1 r -> L | 1 0 0 0 r`."),
    ("dropx", "L 0 0 0 1 0 1 (110101)^j S> 0 0 1 1 1 0 1 1 R", "L S> 0 0 1 0 1 0 1 1 (101011)^j 1 0 1 0 1 0 R",
     "R5: `L 0 X (1 X)^j | 1 0 1 r -> L | 0 0 (1 0 0)^j 1 0 0 0 r`."),
]


def main():
    m, s, ns = M, S, NS
    if len(sys.argv) > 1 and sys.argv[1] == "twin":
        (m, s), ns = TWIN, sys.argv[2] if len(sys.argv) > 2 else "TWIN"
    ths = [prove(m, name, a.replace("S>", s + ">"), b.replace("S>", s + ">"), doc=doc, rotate=True)[0]
           for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", ns, ths, f"Rules of the token model of {m}, generated by `py/rules.py`; "
                                "do not edit by hand."))


if __name__ == "__main__":
    main()
