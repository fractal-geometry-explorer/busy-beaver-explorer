"""Writes lean/Rules.lean: the shift rule of the growth phase of 1RB1RE_1RC0RF_0LD---_1LE1LD_1RA0LB_0RE1LC,
proved by bbtools.symtm from a symbolic trace (shift rules, `rfl`, `omega`).  

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove

M = "1RB1RE_1RC0RF_0LD---_1LE1LD_1RA0LB_0RE1LC"
NS = "H157718"
RULES = [
    ("eat", "Two cycles of the growth phase (six visits of the left end): "
     "`0^inf B> 0 (011)^(n+2) 0 011 011 (01)^(m+1) (01101)^(q+1) 011 111 R` becomes "
     "`0^inf B> 0 (011)^(n+3) 0 011 011 (01)^(m+4) (01101)^(q+1) 011 R`, written as the run re-brackets it "
     "(`0 011 011 011 0 (110)^n 011 011 01 01 0 (10)^(m+1) 1 0 (11010)^(q+1) 1 1 R`), in 10m+20n+20q+204 steps: "
     "three 1s of the run of ones beyond are eaten, the block (011)^n gains one copy and (01)^m three.",
     "0^inf B> 0 (011)^n+2 0 0 1 1 0 1 1 (01)^m+1 (01101)^q+1 0 1 1 1 1 1 R",
     "0^inf B> 0 (011)^n+3 0 0 1 1 0 1 1 (01)^m+4 (01101)^q+1 0 1 1 R"),
]


def main():
    out = ["import Machine", "", f"/-! Rules of {M}, generated by `py/rules.py`; do not edit by hand. -/", "",
           f"namespace {NS}", "", "open TM", ""]
    for name, doc, start, end in RULES:
        t, f = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=60)
        out += [t, ""]
    out.append(f"end {NS}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
