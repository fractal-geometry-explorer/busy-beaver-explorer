"""Writes lean/Rules.lean: shift rules of this machine's sweeps and the shape of a halt, proved by
tools/py/bbtools/symtm.py (`prove`).  Usage: python3 py/rules.py > lean/Rules.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LF_1LC0RB_0LD1LA_0RA1LE_0LA0RA_1LA---"
NS = "H9146"
RULES = [
    ('b_run', 'L 0 0 B> (01)^n R', 'L (01)^n 0 0 B> R',
     'Rightward, B (with 00 behind it) crosses (01)^n, 6 steps a pair.', {}),
    ('f_run', 'L (01)^n F> 0 R', 'L F> 0 (01)^n R',
     'Leftward, F crosses (01)^n, 2 steps a pair.', {}),
    ('a_run', 'L (01)^n A> 0 1 0 R', 'L A> 0 1 0 (01)^n R',
     'Leftward, A (with 010 ahead) crosses (01)^n, 8 steps a pair.', {}),
    ('sweep', '0^inf A> (10)^a+1 1 1 0 (10)^b+2 1 0 0 1 0 (110)^c+1 R', '0^inf A> (10)^a+4 1 1 0 (10)^b 1 0 0 1 0 (110)^c+2 R',
     'One sweep of the counting phase, for all a, b, c and every tape R beyond: (a, b, c) -> (a+3, b-2, c+1) in 14a + 8b + 83 steps.', {}),
    ('halt_shape', 'L 1 A> 1 R', 'L F> 1 0 R',
     'The only way to a halt: A on a 1 with a 1 to its left reaches F on a 1 (which halts) in 1 step.', {}),
]
HALT = "F"
HSYM = "1"

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d, **kw)[0] for n, s, e, d, kw in RULES]
    extra = (f"/-- {HALT} reading a {HSYM} halts (the end of `halt_shape`). -/\n"
             f"theorem halt_after_shape (L R : Tape) : step ⟨L, cons true R, .{HALT}⟩ = none := rfl\n")
    print(rules_file("Machine", NS, thms + [extra],
                     f"# {M}: shift rules of the sweeps and the shape of a halt\n\n"
                     "Generated by `py/rules.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `n` and all "
                     "tapes `L`, `R`."))
