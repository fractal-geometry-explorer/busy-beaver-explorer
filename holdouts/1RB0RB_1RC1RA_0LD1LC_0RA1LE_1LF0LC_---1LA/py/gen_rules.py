"""Writes lean/Rules.lean: the left-going pass of 1RB0RB_1RC1RA_0LD1LC_0RA1LE_1LF0LC_---1LA, the way it halts, and the two
runs across a block of `111110` words, proved from the symbolic trace by bbtools.symtm.
Run from the machine folder: python3 py/gen_rules.py > lean/Rules.lean"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB0RB_1RC1RA_0LD1LC_0RA1LE_1LF0LC_---1LA"
P = "C"          # the state of the pass when it stands on a separator
RULES = [
    ("halt_pass", f"L 0 0 1 {P}> 0 R", "L F> 0 1 1 0 R",
     "The pass on the separator right of a block of length 1 that has `0 0` on its left: three steps later F reads "
     "0, the halting transition."),
    ("pass_split", f"L 0 (1)^k 1 1 1 {P}> 0 R", f"L {P}> 0 (1)^k 1 0 1 0 R",
     "The pass over a block of length k+3: the block is cut into k+1 and 1 and the pass stands on the next "
     "separator."),
    ("pass_stop", f"L 1 0 1 {P}> 0 R", "L F> 1 1 1 0 R",
     "A block of length 1 with a 1 two cells to its left stops the pass: the separator left of it is filled and F, "
     "on a 1, turns the head around."),
    ("cross_left", f"L (011111)^n {P}> 0 R", f"L {P}> 0 (111010)^n R",
     "The pass across n words `111110`: each becomes `1110 10`, six steps a word, in the same state."),
    ("cross_right", "L A> (110101)^n R", "L (011111)^n A> R",
     "The sweep back: A turns the same cells, read one cell later, back into words `111110`, six steps a word."),
]

thms = []
for name, s, e, doc in RULES:
    t, _ = prove(M, name, s, e, doc=doc)
    thms.append(t)
doc = """# The left-going pass and the block of `111110` words

Generated by `py/gen_rules.py` with `bbtools.symtm.prove`: every theorem is a run of the machine for all values of
the variables and every tape `L`, `R`, proved by `rfl` steps and the shift rules `cross_l`, `cross_r`.
Left tapes are written nearest the head first, so `(011111)^n` on the page is `rep n [true, true, true, true, true, false]` here."""
print(rules_file("Machine", "H25821", thms, doc), end="")
