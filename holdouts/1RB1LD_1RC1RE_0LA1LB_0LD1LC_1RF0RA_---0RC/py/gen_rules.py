"""Writes lean/Rules.lean for 1RB1LD_1RC1RE_0LA1LB_0LD1LC_1RF0RA_---0RC: the pieces of one round, proved by bbtools.symtm.

A round goes from  E(m, k) = 0^inf D> 110 (10)^m (110)^k 0^inf  to E(m', k').  Words: W = 101010 (three 10s).
run from the repository root:  PYTHONPATH=tools/py python3 holdouts/1RB1LD_1RC1RE_0LA1LB_0LD1LC_1RF0RA_---0RC/py/gen_rules.py
"""
import os
from bbtools import symtm
from bbtools.machine import Machine, STATES

M = "1RB1LD_1RC1RE_0LA1LB_0LD1LC_1RF0RA_---0RC"
m = Machine.parse(M)
RULES = [
    ("sweep", "One sweep of the bouncer: three 10s of the left block become four 10s of the right block.",
     "0^inf B> 1 1 1 0 (101010)^u+1 1 0 1 1 0 (10)^y (110)^k 0^inf",
     "0^inf B> 1 1 1 0 (101010)^u 1 0 1 1 0 (10)^y+4 (110)^k 0^inf"),
    ("finish", "The last sweep: the left block is a single 10; the round ends at the left end in D.",
     "0^inf B> 1 1 1 0 1 0 1 1 0 (10)^y (110)^k 0^inf",
     "0^inf D> 1 1 0 (10)^y+4 (110)^k 0^inf"),
    ("start1", "Round start for m = 3t+1: the counter gets two more 110s (one is the separator).",
     "0^inf D> 1 1 0 (101010)^t 1 0 (110)^k 0^inf",
     "0^inf B> 1 1 1 0 (101010)^t 1 0 (110)^k+2 0^inf"),
    ("start2", "Round start for m = 3t+5 and k >= 1.",
     "0^inf D> 1 1 0 (101010)^t+1 1 0 1 0 (110)^k+1 0^inf",
     "0^inf B> 1 1 1 0 (101010)^t+1 1 0 1 1 0 1 0 (110)^k+2 0^inf"),
    ("start2_small", "Round start for m = 2 and k >= 1.",
     "0^inf D> 1 1 0 1 0 1 0 (110)^k+1 0^inf",
     "0^inf B> 1 1 1 0 1 0 1 1 0 1 0 (110)^k+2 0^inf"),
    ("start0", "Round start for m = 3t+3 and k >= 1: the counter loses one 110.",
     "0^inf D> 1 1 0 (101010)^t+1 (110)^k+1 0^inf",
     "0^inf B> 1 1 1 0 (101010)^t 1 0 1 1 0 (10)^4 (110)^k 0^inf"),
    ("start0z", "Round start for m = 3t+6 and k = 0: the counter stays empty.",
     "0^inf D> 1 1 0 (101010)^t+2 0^inf",
     "0^inf B> 1 1 1 0 (101010)^t+1 1 0 1 1 0 (10)^4 0^inf"),
    ("start0z_small", "Round start for m = 3 and k = 0.",
     "0^inf D> 1 1 0 1 0 1 0 1 0 0^inf",
     "0^inf B> 1 1 1 0 1 0 1 1 0 (10)^4 0^inf"),
    ("to_halt", "m = 3t+2 and k = 0: the run reaches F reading 0, the halting transition.",
     "0^inf D> 1 1 0 (101010)^t 1 0 1 0 0^inf",
     "0^inf 1 1 0 1 1 (111011)^t 1 1 1 0 1 1 1 F> 0^inf"),
]
thms = []
for name, doc, s, e in RULES:
    t, fin = symtm.prove(m, name, s, e, rotate=True, doc=doc, max_seg=20)
    print(name, "->", fin)
    thms.append(t)
out = symtm.rules_file("Machine", "H" + "ID", thms, "Round pieces of " + M + ", generated by py/gen_rules.py.")
import json
ns = open(os.path.join(os.path.dirname(__file__), "..", "lean", "Machine.lean")).read().split("namespace ")[1].split()[0]
out = out.replace("HID", ns)
open(os.path.join(os.path.dirname(__file__), "..", "lean", "Rules.lean"), "w").write(out)
