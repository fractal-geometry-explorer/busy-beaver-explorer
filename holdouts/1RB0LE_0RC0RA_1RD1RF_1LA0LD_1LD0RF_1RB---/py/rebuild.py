"""One rebuild of 1RB0LE_0RC0RA_1RD1RF_1LA0LD_1LD0RF_1RB---, proved in Lean for every length of the last block.

usage: python3 holdouts/1RB0LE_0RC0RA_1RD1RF_1LA0LD_1LD0RF_1RB---/py/rebuild.py     writes lean/Rebuild.lean

The tick at step 22,986 of the run from blank reaches the left end: in block notation it turns
`3|3|12|15|1.48.94` into `88|6|2|13|21|94` (step 39,846).  `rebuild_3_3_12_15_1_48` is that tick with the last block
any even length 2v+4: `3|3|12|15|1.48.(2v+4)` -> `88|6|2|13|21|(2v+4)` in 8v + 16500 steps.  The run is a symbolic
trace (`bbtools.symtm.prove`, single steps in `rfl` pieces of at most 100 steps, the crossing lemmas for the last
block).  The rebuild reads the block 48 cell by cell, so 48 cannot be made a variable this way, and with more blocks
right of 48 the rebuild returns to the right in a configuration that depends on them; general rebuild rules are
open.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LE_0RC0RA_1RD1RF_1LA0LD_1LD0RF_1RB---"
NS = "H103746"


def blocks(ns, seps):
    out = []
    for i, n in enumerate(ns):
        out.append(" ".join(["1 0"] * n))
        if i < len(seps):
            out.append("1" if seps[i] == "|" else "0")
    return " ".join(out)


START = "0^inf " + blocks([3, 3, 12, 15, 1, 48], "||||.") + " 0 (1010)^v+2 A> 1 1 0^inf"
END = "0^inf " + blocks([88, 6, 2, 13, 21], "||||") + " 1 1 (0101)^v+1 0 1 0 A> 1 1 0^inf"

DOC = """# One rebuild, for every length of the last block

In block notation (README): the tick at step 22,986 of the run from blank, `3|3|12|15|1.48.94` ->
`88|6|2|13|21|94`, reaches the left end and rebuilds the front of the list.  `rebuild_3_3_12_15_1_48` proves it with
the last block of any even length 2v+4 (v = 45 in the run), in 8v + 16500 steps.  Generated by `py/rebuild.py`
(a symbolic trace of `tools/py/bbtools/symtm.py`)."""


def main():
    txt, fin = prove(M, "rebuild_3_3_12_15_1_48", START, END, rotate=True, count_first=True, max_seg=100,
                     doc="`3|3|12|15|1.48.(2v+4)` becomes `88|6|2|13|21|(2v+4)`, from one right-end turn to the next.")
    opts = "set_option maxRecDepth 100000\nset_option maxHeartbeats 4000000\n\n"
    with open(os.path.join(HERE, "..", "lean", "Rebuild.lean"), "w") as f:
        f.write(rules_file("Machine", NS, [opts + txt], DOC))


if __name__ == "__main__":
    main()
