"""Shift rules of 1RB0LE_0RC0RA_1RD1RF_1LA0LD_1LD0RF_1RB---, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LE_0RC0RA_1RD1RF_1LA0LD_1LD0RF_1RB---/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L 1 0 C> (10)^n R` is the head
in state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LE_0RC0RA_1RD1RF_1LA0LD_1LD0RF_1RB---"
NS = "H103746"
DOC = """# Shift rules of 1RB0LE_0RC0RA_1RD1RF_1LA0LD_1LD0RF_1RB---

The sweeps of the machine: moving left, A, E and D rewrite an alternating stretch `1010...` four cells at a time,
complementing it (`sweep_left`); moving right, B and A complement it two cells at a time (`sweep_right`).  A
defect (two equal cells side by side) is where the sweeps turn or change phase.  One tick of the counter is proved
whole: when the last separator is a 1 and the last block has even length, the round trip turns that separator into
a 0 and lengthens the last block by two (`tick_last`); a second tick pattern is proved the same way (`tick_oo`, in
the block notation of `c/blocks.c`).  Longer patterns (`py/ticks.py`) give proofs too long for the kernel's default
limits and are left to the symbolic simulator.  The only halt is F reading a 1, reached from `C> 1 1` or
`E> 1 1` (`halt_C`, `halt_E`); `lean/Route.lean` shows that only the first can occur, as `B> 0 1 1`.

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('sweep_left',
     'L (1010)^n A> 1 R',
     'L A> 1 (1010)^n R',
     'A crosses `1010` leftwards in four steps (A, E, D, D) and complements it: `1010...10 1` becomes `1 1010...10`.'),
    ('sweep_right',
     'L B> (10)^n R',
     'L (01)^n B> R',
     'B crosses `10` rightwards in two steps (B, A) and complements it.'),
    ('tick_last',
     'L 1 (1010)^k A> 1 1 0^inf',
     'L 0 1 (0101)^k 0 1 0 A> 1 1 0^inf',
     'One tick at the right end: `x 1 (10)^(2k) A> 1 1` becomes `x 0 (10)^(2k+2) A> 1 1` (the last separator 1 becomes a 0, the last block grows by two), back at the next right-end turn.'),
    ('tick_oo',
     'L 1 1 0 (1010)^a 1 0 1 0 1 1 0 (1010)^b 1 0 1 0 A> 1 1 0^inf',
     'L 0 1 0 1 (0101)^a 0 1 0 1 0 1 1 (0101)^b 0 1 0 1 0 1 0 A> 1 1 0^inf',
     'One tick, in blocks: `| 2a+3 | 2b+3` becomes `. 2a+4 | 2b+4` (two odd blocks after separators 1).')
]

# hand-written statements appended to the file (the halting situations), proved by `rfl`
EXTRA = """/-- `C> 1 1` halts: C keeps the 1 and moves right in state F, which reads a 1. -/
theorem halt_C (L R : Tape) : ∃ c, steps 1 ⟨L, cons true (cons true R), .C⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩

/-- `E> 1 1` halts: E erases its 1 and moves right in state F, which reads a 1. -/
theorem halt_E (L R : Tape) : ∃ c, steps 1 ⟨L, cons true (cons true R), .E⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩
"""


def main():
    thms = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
