"""The 6 left-end ticks of the first 10^10 steps that no front rule takes (at most one block after the front, too
few for the passes): each as a concrete run in Lean, from its right-end turn to the next one.

    python3 py/early.py      # writes lean/Early.lean

A right-end turn is the head in state A on the first of the last two 1s of the tape (`… A> 1 1 0^inf`).  The
configurations are read off a plain simulator from blank tape and checked by the kernel (`decide +kernel` on the
list simulator of tools/lean/TM/Fin.lean, proved to agree with `steps`).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
T = {'A': [(1, 1, 'B'), (0, -1, 'E')], 'B': [(0, 1, 'C'), (0, 1, 'A')], 'C': [(1, 1, 'D'), (1, 1, 'F')],
     'D': [(1, -1, 'A'), (0, -1, 'D')], 'E': [(1, -1, 'D'), (0, 1, 'F')], 'F': [(1, 1, 'B'), None]}
# (step of the turn before the tick, block list before, block list after), from classify.txt
TICKS = [(4, "1", "4"), (18, "4", "3|5"), (54, "3|5", "3|3|6"), (140, "3|3.8", "2|5|9"),
         (1402, "15|9.18", "14|11|19"), (274716, "259|119.192", "258|121|193")]


def run(upto):
    tape, h, s = bytearray(4_000_000), 2_000_000, 'A'
    turns, snaps = [], {}
    want = {t for t, _, _ in TICKS}
    for t in range(upto):
        if s == 'A' and tape[h] == 1 and tape[h + 1] == 1 and not any(tape[h + 2:h + 40]):
            turns.append(t)
            if t in want or (turns[-2:-1] and turns[-2] in want):
                snaps[t] = (bytes(tape), h)
        w, d, n = T[s][tape[h]]
        tape[h] = w
        h += d
        s = n
    return turns, snaps


def fcfg(snap):
    tape, h = snap
    nz = [i for i, b in enumerate(tape) if b]
    lo, hi = nz[0], nz[-1]
    left = [bool(tape[i]) for i in range(h - 1, lo - 1, -1)]
    right = [bool(tape[i]) for i in range(h, hi + 1)]
    return left, right


def blist(bits):
    return "[" + ", ".join("true" if b else "false" for b in bits) + "]"


def main():
    turns, snaps = run(TICKS[-1][0] + 20000)
    out = ["import Machine\n", '/-!\n# The 6 left-end ticks without a front rule\n\n' + __doc__.split("\n\n", 1)[1].split("\n\n")[1]
           + "\n\nGenerated by `py/early.py`.\n-/\n", "namespace H103746\n", "open TM\n"]
    for k, (t0, a, b) in enumerate(TICKS):
        t1 = turns[turns.index(t0) + 1]
        l0, r0 = fcfg(snaps[t0])
        l1, r1 = fcfg(snaps[t1])
        assert r0 == [True, True] and r1 == [True, True]
        tac = "decide +kernel"
        out.append(f"""/-- The left-end tick `{a} -> {b}` at step {t0:,}: {t1 - t0} steps from the right-end turn to the next. -/
theorem early_{k} : steps {t1 - t0} (FCfg.toCfg ⟨{blist(l0)}, [true, true], .A⟩) =
    some (FCfg.toCfg ⟨{blist(l1)}, [true, true], .A⟩) := by
  have h : TM.fsteps trans {t1 - t0} ⟨{blist(l0)}, [true, true], .A⟩ =
      some ⟨{blist(l1)}, [true, true], .A⟩ := by {tac}
  exact (FCfg.steps_eq trans {t1 - t0} _).trans (congrArg (Option.map FCfg.toCfg) h)
""")
    out.append("end H103746\n")
    with open(os.path.join(HERE, "..", "lean", "Early.lean"), "w") as f:
        f.write("\n".join(out))
    print("wrote lean/Early.lean")


if __name__ == "__main__":
    main()
