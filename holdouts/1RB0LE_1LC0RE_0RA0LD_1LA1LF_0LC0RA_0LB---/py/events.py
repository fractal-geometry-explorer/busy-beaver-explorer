"""Generate lean/Events.lean for a machine of the two-word sweeper family.

Usage (from the repository root): python3 holdouts/1RB0LE_1LC0RE_0RA0LD_1LA1LF_0LC0RA_0LB---/py/events.py MACHINE NAMESPACE > holdouts/MACHINE/lean/Events.lean

An *event* is the head in state A on a 0, just right of the base-3 counter N:

    0^inf 1 0 [N] A> 0 [M] 1 [R] ...

- N: base 3, 3-cell digits 100 = 0, 110 = 1, 010 = 2, most significant first (least significant next to the head);
- M: binary, 4-cell digits 0010 = 0, 1010 = 1, least significant first (next to the head), any width >= 1;
- R: binary, 4-cell digits 1000 = 0, 1010 = 1, least significant first.

Each rule takes one event to the next: N + 1 (with its carry; when N = 2...2 it wraps to 0...0 with one digit
more), M + 1 (with its carry), and when M wraps from 1...1 to 0...0, R + 3 (four cases of R's two low bits, a carry
over j ones).  Every rule holds for every value of the counts (k, i, j) and every tape left of N's changing digits
(L) and right of R's changing digits (R); when M does not wrap, R is not read at all.  Proved by
bbtools.symtm.prove (symbolic run, shift rules crossed by induction, re-bracketings by TM.rep_rotate).
"""
import sys
import os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'tools', 'py'))
from bbtools.symtm import prove, ProofError, rules_file
D3={0:"1 0 0",1:"1 1 0",2:"0 1 0"}
MD={0:"0 0 1 0",1:"1 0 1 0"}
RD={0:"1 0 0 0",1:"1 0 1 0"}
def nparts():
    # (name, start-left, end-left, doc)
    out=[]
    for x in (0,1):
        out.append((f"n{x}t0", f"L {D3[x]}", f"L {D3[x+1]}", f"N's lowest digit {x} becomes {x+1}"))
        out.append((f"n{x}t1", f"L {D3[x]} {D3[2]}", f"L {D3[x+1]} {D3[0]}", f"N ends in {x}2: becomes {x+1}0"))
        out.append((f"n{x}tk", f"L {D3[x]} (010)^k {D3[2]} {D3[2]}", f"L {D3[x+1]} (100)^k {D3[0]} {D3[0]}", f"N ends in {x} and k+2 digits 2: carry"))
    out.append(("nov1", f"0^inf 1 0 {D3[2]}", f"0^inf 1 0 {D3[0]} {D3[0]}", "N = 2: wraps to 00 (one digit more)"))
    out.append(("nov2", f"0^inf 1 0 {D3[2]} {D3[2]}", f"0^inf 1 0 {D3[0]} {D3[0]} {D3[0]}", "N = 22: wraps to 000"))
    out.append(("novk", f"0^inf 1 0 (010)^k {D3[2]} {D3[2]}", f"0^inf 1 0 {D3[0]} {D3[0]} (100)^k {D3[0]}", "N = 2...2 (k+2 digits): wraps to k+3 zeros"))
    return out
def mparts():
    out=[]
    out.append(("m0", f"0 {MD[0]} R", f"0 {MD[1]} R", "M's lowest digit 0 becomes 1"))
    out.append(("mk", f"0 {MD[1]} (1010)^i {MD[0]} R", f"0 {MD[0]} (0010)^i {MD[1]} R", "M ends in i+1 ones: carry"))
    W0,W1=f"0 {MD[1]} (1010)^i 1", f"0 {MD[0]} (0010)^i 1"
    out.append(("w00", f"{W0} {RD[0]} {RD[0]} R", f"{W1} {RD[1]} {RD[1]} R", "M = 1...1 (i+1 digits) wraps to 0...0; R = ..00 gets 3"))
    for (r0,r1),(s0,s1),nm in (((1,0),(0,0),"w10"),((0,1),(1,0),"w01"),((1,1),(0,1),"w11")):
        out.append((nm+"k", f"{W0} {RD[r0]} {RD[r1]} (1010)^j {RD[0]} R", f"{W1} {RD[s0]} {RD[s1]} (1000)^j {RD[1]} R",
                    f"M = 1...1 (i+1 digits) wraps; R (low bits {r0}{r1}, then j ones) gets 3"))
    return out
def rules(M, quiet=False):
    res=[]
    for nn,ns,ne,nd in nparts():
        for mn,ms,me,md in mparts():
            s=f"{ns} A> {ms}"; e=f"{ne} A> {me}"
            name=f"ev_{nn}_{mn}"
            try:
                t,_=prove(M,name,s,e,doc=f"{nd}; {md}.",rotate=True,count_first=True,max_seg=40)
                res.append((name,t,s,e))
                if not quiet: print('OK',name,t.split('\n')[2].split('⟨')[0].strip(),file=sys.stderr)
            except ProofError as ex:
                print('FAIL',name,ex,file=sys.stderr)
    return res
if __name__=="__main__":
    M, NS = sys.argv[1], sys.argv[2]
    ths = [t for _, t, _, _ in rules(M, quiet=True)]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Event rules of {M} (the two-word sweeper engine), generated by "
                                "`py/events.py` of `holdouts/1RB0LE_1LC0RE_0RA0LD_1LA1LF_0LC0RA_0LB---`; do not edit by hand."))
