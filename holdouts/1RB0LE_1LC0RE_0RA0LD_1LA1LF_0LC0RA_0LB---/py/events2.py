"""Event rules of the cascade layout  0^inf 1 0 [N] A> 0 [Z] 1 1 [C] 0 1 [R] ...  (two-word sweeper family).

Z: binary, 4-cell digits 0010 = 0, 1010 = 1 (the counter called M in the first regime), lowest digit first;
C: binary, 4-cell digits 0001 = 0, 0101 = 1, lowest first, closed by 0 1;
R: binary, 4-cell digits 1000 = 0, 1010 = 1, lowest first.
One event to the next: N + 1, Z + 1; when Z wraps C + 3; when C wraps R + 3.
Usage (from the repository root): python3 holdouts/1RB0LE_1LC0RE_0RA0LD_1LA1LF_0LC0RA_0LB---/py/events2.py MACHINE NAMESPACE > holdouts/MACHINE/lean/Cascade.lean"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'tools', 'py'))
from bbtools.symtm import prove, ProofError, rules_file
D3={0:"1 0 0",1:"1 1 0",2:"0 1 0"}
ZD={0:"0 0 1 0",1:"1 0 1 0"}
CD={0:"0 0 0 1",1:"0 1 0 1"}
RD={0:"1 0 0 0",1:"1 0 1 0"}
def nparts():
    out=[]
    for x in (0,1):
        out.append((f"n{x}t0", f"L {D3[x]}", f"L {D3[x+1]}", f"N's lowest digit {x} becomes {x+1}"))
        out.append((f"n{x}t1", f"L {D3[x]} {D3[2]}", f"L {D3[x+1]} {D3[0]}", f"N ends in {x}2: becomes {x+1}0"))
        out.append((f"n{x}tk", f"L {D3[x]} (010)^k {D3[2]} {D3[2]}", f"L {D3[x+1]} (100)^k {D3[0]} {D3[0]}", f"N ends in {x} and k+2 digits 2: carry"))
    out.append(("nov1", f"0^inf 1 0 {D3[2]}", f"0^inf 1 0 {D3[0]} {D3[0]}", "N = 2: wraps to 00 (one digit more)"))
    out.append(("nov2", f"0^inf 1 0 {D3[2]} {D3[2]}", f"0^inf 1 0 {D3[0]} {D3[0]} {D3[0]}", "N = 22: wraps to 000"))
    out.append(("novk", f"0^inf 1 0 (010)^k {D3[2]} {D3[2]}", f"0^inf 1 0 {D3[0]} {D3[0]} (100)^k {D3[0]}", "N = 2...2 (k+2 digits): wraps to k+3 zeros"))
    return out
def cplus3():
    # (name, start C part, end C part, doc); C part followed by context X (no wrap) 
    return [("c00", f"{CD[0]} {CD[0]}", f"{CD[1]} {CD[1]}", "C's two low bits 00 become 11"),
            ("c10", f"{CD[1]} {CD[0]} (0101)^j {CD[0]}", f"{CD[0]} {CD[0]} (0001)^j {CD[1]}", "C (low bits 10, then j ones, then a 0) gets 3"),
            ("c01", f"{CD[0]} {CD[1]} (0101)^j {CD[0]}", f"{CD[1]} {CD[0]} (0001)^j {CD[1]}", "C (low bits 01, then j ones, then a 0) gets 3"),
            ("c11", f"{CD[1]} {CD[1]} (0101)^j {CD[0]}", f"{CD[0]} {CD[1]} (0001)^j {CD[1]}", "C (low bits 11, then j ones, then a 0) gets 3")]
def cwrap():
    return [("w10", f"{CD[1]} {CD[0]} (0101)^j", f"{CD[0]} {CD[0]} (0001)^j", "C = 1 0 1...1 wraps"),
            ("w01", f"{CD[0]} {CD[1]} (0101)^j", f"{CD[1]} {CD[0]} (0001)^j", "C = 0 1 1...1 wraps"),
            ("w11", f"{CD[1]} {CD[1]} (0101)^j", f"{CD[0]} {CD[1]} (0001)^j", "C = 1...1 wraps")]
def rplus3():
    return [("r00", f"{RD[0]} {RD[0]}", f"{RD[1]} {RD[1]}", "R's low bits 00 become 11"),
            ("r10", f"{RD[1]} {RD[0]} (1010)^l {RD[0]}", f"{RD[0]} {RD[0]} (1000)^l {RD[1]}", "R (10, l ones, 0) gets 3"),
            ("r01", f"{RD[0]} {RD[1]} (1010)^l {RD[0]}", f"{RD[1]} {RD[0]} (1000)^l {RD[1]}", "R (01, l ones, 0) gets 3"),
            ("r11", f"{RD[1]} {RD[1]} (1010)^l {RD[0]}", f"{RD[0]} {RD[1]} (1000)^l {RD[1]}", "R (11, l ones, 0) gets 3")]
def zparts():
    out=[("z0", f"0 {ZD[0]} R", f"0 {ZD[1]} R", "Z's lowest digit 0 becomes 1"),
         ("zk", f"0 {ZD[1]} (1010)^i {ZD[0]} R", f"0 {ZD[0]} (0010)^i {ZD[1]} R", "Z ends in i+1 ones: carry")]
    W0,W1=f"0 {ZD[1]} (1010)^i 1 1", f"0 {ZD[0]} (0010)^i 1 1"
    for cn,cs,ce,cd in cplus3():
        out.append((cn, f"{W0} {cs} R", f"{W1} {ce} R", f"Z = 1...1 (i+1 digits) wraps; {cd}"))
    for wn,ws,we,wd in cwrap():
        for rn,rs,re_,rd in rplus3():
            out.append((wn+rn, f"{W0} {ws} 0 1 {rs} R", f"{W1} {we} 0 1 {re_} R", f"Z = 1...1 wraps; {wd}; {rd}"))
    return out
def rules(M, quiet=False, only=None):
    res=[]
    for nn,ns,ne,nd in nparts():
        for zn,zs,ze,zd in zparts():
            name=f"cv_{nn}_{zn}"
            if only and name not in only: continue
            s=f"{ns} A> {zs}"; e=f"{ne} A> {ze}"
            try:
                t,_=prove(M,name,s,e,doc=f"{nd}; {zd}.",rotate=True,count_first=True,max_seg=40)
                res.append((name,t,s,e))
                if not quiet: print('OK',name,t.split('\n')[2].split('⟨')[0].strip(),file=sys.stderr)
            except ProofError as ex:
                print('FAIL',name,ex,file=sys.stderr)
    return res
if __name__=="__main__":
    M, NS = sys.argv[1], sys.argv[2]
    only=set(sys.argv[3].split(',')) if len(sys.argv)>3 else None
    ths=[t for _,t,_,_ in rules(M, only=only)]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Cascade event rules of {M} (the layout N | Z | 11 | C | 01 | R of the later eras), generated by `py/events2.py`; do not edit by hand."))
