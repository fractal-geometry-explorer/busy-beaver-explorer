"""Writes lean/Rules.lean: the rules of the run-list rewriting, each proved by bbtools.symtm from a symbolic trace.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from autoprove import auto, at_right, has_rep, prove

M = "1RB1RE_1LC0LE_1RD0LB_0RA1RC_0RC0RF_1RA---"
NS = "H116343"
built = lambda c: at_right("A")(c) and has_rep((1, 1))(c)

# (name, doc, start, end or None for "until A is back at the right end with the new run built")
RULES = [
    ("cycle", "The basic cycle: the last long run loses 3 cells and 5 units appear after it.",
     "L 1^a+3 (01)^b+1 A> 0^inf", "L 1^a (01)^b+6 A> 0^inf"),
    ("cycle0", "The first cycle after a new run is built (head one 0 past it).",
     "L 1^a+3 0 A> 0^inf", "L 1^a 0 1 0 1 0 1 A> 0^inf"),
    ("q2_long", "Active run 2 after a long run x+3: the long run loses 3, 7 units join the units before the 2, and the units after it become one run of 2B-1 (B = b+12).",
     "L 0 1^x+3 (01)^p 0 1 1 (01)^b+12 A> 0^inf", None),
    ("q2_zero", "Active run 2 after an empty run: the empty run and the p+1 units before the 2 become a run of 2p+6, then 6 units, then a run of 2B-5.",
     "L 0 0 (01)^p+1 0 1 1 (01)^b+12 A> 0^inf", None),
    ("q2_blank", "Active run 2 with only units (p+2 of them) and blank tape to its left: the same as after an empty run.",
     "0^inf (10)^p+2 1 1 (01)^b+12 A> 0^inf", None),
    ("q0_unit", "Active run empty (two adjacent 0s) after a unit: the unit is eaten and the units after become a run of 2B+11.",
     "L 0 1 (01)^p 0 (01)^b+12 A> 0^inf", None),
    ("q0_long", "Active run empty after a run x+1: that run loses one cell and merges with the new run 2B+11.",
     "L 0 1^x+1 0 (01)^b+12 A> 0^inf", None),
    ("units_blank", "Only units, blank tape to the left: they become one run of 2B+11.",
     "0^inf (01)^b+12 A> 0^inf", None),
]

def main():
    out = ["import Machine", "", f"/-! Rules of {M}, generated by `py/rules.py`; do not edit by hand.",
           "", "A configuration with the head in state A just right of the last cell is read as a list of runs of 1s",
           "separated by single 0s (two adjacent 0s are an empty run); a run of length 1 is a *unit*. -/", "",
           f"namespace {NS}", "", "open TM", ""]
    for name, doc, start, end in RULES:
        if end is None:
            t, e, st = auto(M, name, start, built, doc=doc, count_first=True)
        else:
            t, f = prove(M, name, start, end, doc=doc, rotate=True, count_first=True)
        out.append(t)
        out.append("")
    out.append(f"end {NS}")
    print("\n".join(out))

if __name__ == "__main__":
    main()
