"""Generate Rules.lean for 1RB1LD_0LC0RA_1RA1LC_1RE0LC_---1RF_0RD0RB: the two sweeps across the block of 10s at the right end, proved along the symbolic run (tools/py/bbtools/symtm.py:
single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean        (L and R are any tape)
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LD_0LC0RA_1RA1LC_1RE0LC_---1RF_0RD0RB"

RULES = [
    ("zig", "L (10)^n 1 0 C> 1 R", "L C> (10)^n 1 0 1 R",
     "Going left, the head zigzags across the block of 10s in states C and A, two cells every four steps."),
    ("run_right", "L B> (10)^n R", "L (01)^n B> R",
     "Going right, the head runs across the block in states B and A, one cell a step, rewriting each 10 as 01."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H726", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
