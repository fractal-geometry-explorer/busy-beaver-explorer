#!/usr/bin/env python3
"""Lean proofs of the generic counter sweep of 1RB---_0RC0LA_1LD0RB_1LE0LF_1RC1LF_0LC0LB (c1), the mirror image of
1RB0LD_1RC0RF_1LA1RF_0LA0RE_1LD---_0RA0RD (c2), for EVERY number of carry digits; written to c1's lean/Chain.lean
(24 November 2026).

In the digit model (py/cdigits.py) a sweep is one increment of a ternary counter at the bouncing end: the carry
passes the T digits next to the head and stops on the first Z or O digit.  The sweep is cut into pieces at the digit
boundaries, each proved for all run lengths by `bbtools.symtm.prove` on the machine itself:

  startT  from the sample, over the last run z, to the bottom T digit        4z + 13 steps
  fwdT    over one T digit of r blocks, leftwards                             4r + 16
  stopZ   the carry stops on a Z digit (the top T digit, a blocks, gains 1)   6a + 6
  stopO   the carry stops on an O digit (which loses a block)                  6a + 6
  retT    back over one T digit of b blocks, which becomes a Z digit           6b + 12
  endT    back to the next sample, the last run gains one                      6z + 35

and two induction theorems over the list of carry digits (`fwdChain`, `retChain`) put them together into `sweepZ`
and `sweepO`: 10 steps per block of the chain and of the last run, 28 per chain digit, plus 42, the rule used by
py/oacc.py.  The hand-written part is chain_lean.lean.in (the induction, modelled on the b machines' file).

    python3 py/chain_lean.py            write the Lean file
    python3 py/chain_lean.py --check    compare with the file
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'py'))
from bbtools import symtm  # noqa: E402
from bbtools.symtm import Config  # noqa: E402

M = '1RB---_0RC0LA_1LD0RB_1LE0LF_1RC1LF_0LC0LB'
NS = 'H49413'
PIECES = [
    ('startT', 'X 1 0 0 0 0 0 (1000)^z 1 0 0 B> 0^inf', 'X 1 0 0 0 0 0 1 0 C> 0 (0111)^z 1 1 1 0^inf',
     'From the sample with last run `z` to the bottom T digit.'),
    ('fwdT', 'X (1000)^r 1 0 0 0 0 0 1 0 C> 0 R', 'X 1 0 C> 0 (0111)^r 1 1 1 1 1 1 R',
     'Crossing one T digit of `r` blocks, leftwards.'),
    ('stopZ', 'X 1 0 1 0 1 0 1 0 C> 0 (0111)^a 1 1 1 1 1 1 R', 'X 1 0 1 0 0 0 (1000)^a C> 1 1 1 1 1 1 1 1 1 R',
     'The carry stops on a Z digit: Z becomes O and the top T digit (`a` blocks) gains one.'),
    ('stopO', 'X (1000)^s+1 1 0 1 0 C> 0 (0111)^a 1 1 1 1 1 1 R', 'X (1000)^s+1 0 0 (1000)^a C> 1 1 1 1 1 1 1 1 1 R',
     'The carry stops on an O digit of `s + 1` blocks: it becomes a T digit of `s` blocks.'),
    ('retT', 'X C> 1 1 1 1 1 1 1 1 1 (0111)^b 1 1 1 1 1 1 R', 'X 1 0 1 0 1 0 (1000)^b C> 1 1 1 1 1 1 1 1 1 R',
     'On the way back, one more T digit becomes a Z digit with the same run.'),
    ('endT', 'X C> 1 1 1 1 1 1 1 1 1 (0111)^z 1 1 1 0^inf', 'X 1 0 1 0 1 0 (1000)^z 1 0 0 0 1 0 0 B> 0^inf',
     'Back to the next sample; the last run gains one.'),
]


def main():
    thms = []
    for name, a, b, doc in PIECES:
        text, fin = symtm.prove(M, name, Config.parse(a), Config.parse(b), doc=doc, rotate=True,
                                count_first=True, max_seg=400)
        thms.append(text)
    hand = open(os.path.join(HERE, 'chain_lean.lean.in')).read()
    head = ('The generic counter sweep of %s, the mirror image of 1RB0LD_1RC0RF_1LA1RF_0LA0RE_1LD---_0RA0RD '
            '(py/cdigits.py), proved for every number of carry digits and all run lengths.  Generated by '
            '`py/chain_lean.py` in the folder of 1RB0LD_1RC0RF_1LA1RF_0LA0RE_1LD---_0RA0RD; do not edit by hand.' % M)
    out = symtm.rules_file('Machine', NS, thms, head)
    end = 'end %s' % NS
    assert out.rstrip().endswith(end)
    out = out.rstrip()[:-len(end)] + hand.replace('NAMESPACE', NS)
    path = os.path.join(ROOT, 'holdouts', M, 'lean', 'Chain.lean')
    if '--check' in sys.argv:
        same = os.path.exists(path) and open(path).read() == out
        print('Chain.lean', 'current' if same else 'DIFFERS')
        sys.exit(0 if same else 1)
    open(path, 'w').write(out)
    print('wrote', path)


if __name__ == '__main__':
    main()
