"""Shift rules of 1RB---_0RC0LA_1LD0RB_1LE0LB_1LF0LC_1LB1RE, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB---_0RC0LA_1LD0RB_1LE0LB_1LF0LC_1LB1RE/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L 1 0 C> (10)^n R` is the head
in state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB---_0RC0LA_1LD0RB_1LE0LB_1LF0LC_1LB1RE"
NS = "H55079"
DOC = """# Shift rules of 1RB---_0RC0LA_1LD0RB_1LE0LB_1LF0LC_1LB1RE

The rightward pass of the bouncer: C runs right over the dense half of the tape, turning each block `1^(4n+3) 0`
into the sparse word `(1010)^n 1000`; two 1s cost 4 steps (`pass_pair`).  The halting situations: A on a 0 with a
1 after it, and B on a 1 with a 1 before it, halt within two steps (`halt_A`, `halt_B`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('pass_pair',
     'L C> (11)^n R',
     'L (10)^n C> R',
     'C turns `1 1` into `1 0` (as written, nearest first: the left word `(10)^n`), four steps a pair.'),
    ('pass_block',
     'L C> (1111)^n 1 1 1 0 R',
     'L (1010)^n 1 0 0 0 C> R',
     'A dense block `1^(4n+3) 0` becomes the sparse word `(1010)^n 1000` (left of the head, in tape order).'),
    ('pass_end',
     'L C> 1 0 R',
     'L 0 0 C> R',
     'The last 1 of a block and the 0 after it.')
]

# hand-written statements appended to the file (the halting situations), proved by `rfl`
EXTRA = """/-- `A> 0 1` halts: A writes 1, B reads the 1 and steps back left onto it, and A reads a 1. -/
theorem halt_A (L R : Tape) : ∃ c, steps 2 ⟨L, cons false (cons true R), .A⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩

/-- `1 B> 1` halts: B erases its 1 and steps left onto a 1 in state A. -/
theorem halt_B (L R : Tape) : ∃ c, steps 1 ⟨cons true L, cons true R, .B⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩
"""


def main():
    thms = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
