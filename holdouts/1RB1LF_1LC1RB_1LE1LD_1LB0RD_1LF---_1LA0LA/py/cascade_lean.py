"""Writes lean/Cascade.lean: the cascade, the one rule behind every shifted event and every halt.

A pass of the head to the left (F and A alternating) reads the tape in pairs (A-cell, F-cell): F flips its cell,
A goes on over a 1 and turns right on a 0.  If the F-cell of the turning pair held a 0 (the pair was blank, O = 00),
this is the clean turn of a wall visit.  If it held a 1 (the pair was 01) the head runs a *cascade* instead, and
what the cascade does depends only on the number m of blank cells left of the turning pair:

  m = 0   L 1 0 F> 1 R          ->  L 0 0 0 D> R           as the hit  L 1 1 B> 1 0 R -> L 1 0 0 0 D> R
  m = 1   L 1 0 0 F> 1 R        ->  L 1 1 1 1 B> R          the head turns right, as at a wall visit
  m = 2   L 1 0^3 F> 1 R        ->  L C> 1 1 1 1 1 R        C on the 1: then D steps into L
  m = 3   L 1 0^4 F> 1 R        halts (E reads the 1), for every L and R
  m = 4   L 1 0^5 F> 1 R        ->  L F> 1 1 1 1 1 1 R      F on the 1: the pass goes on to the left
  m = 5   L 1 0^6 F> 1 R        ->  L A> 1 1 1 1 1 1 1 R    A on the 1: the pass goes on to the left
  m >= 6  L 0^7 F> 1 R          ->  L 0 F> 0 1 1 1 1 1 1 R  a wall visit 7 cells to the left, word Y Y Y R

for every tape L to the left and R to the right.  A right-end event with a last digit b <= 10 sends the head home
in the other pair grid, so it ends in a cascade (shift<b> in Events.lean is the case m >= 6).

usage: python3 cascade_lean.py > ../lean/Cascade.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file, cfg_term, Config
from bbtools.machine import Machine

M = "1RB1LF_1LC1RB_1LE1LD_1LB0RD_1LF---_1LA0LA"
NS = "H34090"


def local_run(left, right, state):
    """run on the literal window left|right (head on right[0]) until the head leaves it or halts"""
    m = Machine.parse(M)
    tape = {i - len(left): c for i, c in enumerate(left)}
    tape.update({i: c for i, c in enumerate(right)})
    lo, hi = -len(left), len(right) - 1
    p, s, n = 0, "ABCDEF".index(state), 0
    while p <= hi:
        tr = m.table[s][tape[p]]
        if tr is None:
            return n, None
        if p == lo and tr[1] < 0:
            break                     # the next step reads L: stop on the last cell of the window
        tape[p] = tr[0]; p += tr[1]; s = tr[2]; n += 1
    L = " ".join(str(tape[q]) for q in range(lo, min(p, hi + 1)))
    R = " ".join(str(tape[q]) for q in range(max(p, lo), hi + 1))
    st = "ABCDEF"[s]
    return n, ("L %s %s> R" % (L, st) if p > hi else "L %s> %s R" % (st, R)).replace("  ", " ")


CASES = [(0, [1, 0], "the pair to the left is a Y (here the 1 and the turning cell): the cascade is the hit "
                      "L 1 1 B> 1 0 R, D erasing into R"),
         (1, [1, 0, 0], "the head turns right as at a wall visit, B running into R"),
         (2, [1, 0, 0, 0], "C on the 1, D next steps into L"),
         (4, [1] + [0] * 5, "F on the 1, the pass goes on into L"),
         (5, [1] + [0] * 6, "A on the 1, the pass goes on into L"),
         (6, [0] * 7, "a wall visit 7 cells to the left with the word Y Y Y R, whatever L is (m >= 6)")]


def main():
    thms = []
    for m, left, what in CASES:
        n, end = local_run(left, [1], "F")
        start = "L %s F> 1 R" % " ".join(map(str, left))
        if m == 6:
            n, end = 7, "L 0 F> 0 1 1 1 1 1 1 R"
        t, fin = prove(M, "cascade%d" % m, start, end, doc="Cascade with m = %d blank cells: %s (%d steps), for every "
                       "L and R." % (m, what, n), cross=False, count_first=True, max_seg=60)
        thms.append(t)
    start = "L 1 0 0 0 0 F> 1 R"
    n, end = local_run([1, 0, 0, 0, 0], [1], "F")
    assert end is None
    hend = "L E> 1 1 1 1 1 1 R"
    t, fin = prove(M, "cascade3_run", start, hend, doc="Cascade with m = 3 blank cells: %d steps to E on a 1, for every "
                   "L and R." % n, cross=False, count_first=True, max_seg=60)
    thms.append(t)
    thms.append("/-- The cascade with m = 3 blank cells halts the machine, for every tape L and R: a pass of the head "
                "that reads `1 0 0 0 0 F> 1` stops it. -/\n"
                "theorem cascade3_halts (L R : Tape) : ∃ c, steps (%d) %s = some c ∧ step c = none :=\n"
                "  ⟨_, cascade3_run L R, rfl⟩" % (n, cfg_term(Config.parse(start))))
    out = rules_file("Machine", NS, thms, "The cascade: what a pass of the head does when it turns on a pair 01, by the "
                     "number of blank cells to its left. Generated by `py/cascade_lean.py`.")
    print(out, end="")


if __name__ == "__main__":
    main()
