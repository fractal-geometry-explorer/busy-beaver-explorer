"""The sweep rules of 1RB0LC_1RC0RA_1LA0LD_1LE0RB_1LC1LF_0LA--- as Lean theorems (lean/Rules.lean).

Right phase: blocks (10)^n separated by single 1s; each sweep from the right end ("B> 0" on blank) to the next takes
one 10 off the first block and appends a block (10)^3 1 at the right end.  `(1010101)` is the block (10)^3 1.
Left phase: blocks (01)^n separated by `0 0 1 1 0`, a single `0` marker inside; the head bounces between the left end
("C> 0") and the marker: two bounces add four 01 to the first block and take two from the block after the marker.

usage: python3 py/gen_rules.py            (rewrites lean/Rules.lean)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHARED = os.path.join(HERE, "..", "..", "1RB---_1RC0RA_1LD0RB_0LE0LC_1RE1LF_0RD0RB", "py")
sys.path.insert(0, SHARED)
from rulegen import sym, at_end, write_rules  # noqa: E402

M = "1RB0LC_1RC0RA_1LA0LD_1LE0RB_1LC1LF_0LA---"

STARTS = [
    ("sweep_tail", "0^inf (10)^a+2 1 (1010101)^n+1 B> 0 0^inf", at_end("R", "B"),
     "Right phase with only blocks of three behind the first: one 10 less in front, one more block of three."),
    ("sweep_mid", "0^inf (10)^a+2 1 (10)^b+2 1 (1010101)^n+1 B> 0 0^inf", at_end("R", "B"),
     "The same with one more block in between, which the sweep leaves as it was."),
    ("left_a", "0^inf C> 0 (01)^x+2 0 (01)^y+3 0 0 1 1 0 R", at_end("L", "C", 0),
     "Left phase, marker `0`: the first block gains three 01, the block after the marker loses two."),
    ("left_b", "0^inf C> 0 (01)^x+5 1 (01)^y+2 0 0 1 1 0 R", at_end("L", "C", 0),
     "Left phase, marker `1`: the first block gains one 01 and the marker turns back into `0`."),
]


def rules():
    out = []
    for name, start, stop, doc in STARTS:
        res, c = sym(M, start, stop)
        assert res == "stop", (name, res, c)
        out.append((name, start, repr(c), doc + f" ({c.steps} steps)"))
    return out


if __name__ == "__main__":
    rs = rules()
    for name, s, e, d in rs:
        print(name, ":", s, "->", e, "|", d)
    n = write_rules(M, None, rs, os.path.join(HERE, "..", "lean", "Rules.lean"),
                    f"Sweep rules of {M}, generated by `py/gen_rules.py`; do not edit by hand.")
    print(n, "theorems")
