"""Generate lean/Rules.lean: the pieces of the E phase (and of the A phase, for the machines in START_A); usage: gen_rules.py [MACHINE NAMESPACE]."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools import symtm
from bbtools.machine import Machine
M = sys.argv[1] if len(sys.argv) > 1 else "1RB1RD_0LC1RA_0RA1LC_1RA1LE_1RF0LD_---0RE"
NS = sys.argv[2] if len(sys.argv) > 2 else "H113619"
m = Machine.parse(M)
# the start of the A phase is where the two machines differ (their C rows)
START_A = {
    "1RB1RD_0LC1RA_0RA1LC_1RA1LE_1RF0LD_---0RE":
    ("startA", "A phase, start: A(x+2, 2n+4) reaches Q(x, 1, 2n+2) (the ones written as (11)^n+2).",
     "0^inf (10)^x+2 (11)^n+2 A> 0 0^inf", "0^inf (10)^x 1 D> 0 0 1 0 1 0 1 1 (11)^n 0^inf"),
    "1RB1RD_0LC1RA_1LA1LC_1RA1LE_1RF0LD_---0RE":
    ("startA", "A phase, start: A(x+3, 2n+4) reaches Q(x, 1, 2n+4) (the ones written as (11)^n+2).",
     "0^inf (10)^x+3 (11)^n+2 A> 0 0^inf", "0^inf (10)^x 1 D> 0 0 1 0 1 0 1 1 (11)^n+1 0^inf"),
}
# the state of the bounce frame Q (the one that reads the first 0 of `0 0`)
QS = {"1RB1LE_1RC1RA_0LD1RB_1LE1LD_1RF0LA_---0RE": "A"}.get(M, "D")
RULES = [
    ("startE", "E phase, start: E(x+1, s+5) reaches Q(x, 1, s+1).",
     "0^inf E> 0 (10)^x+1 1^s+5 0^inf", "0^inf (10)^x 1 D> 0 0 1 0 1 0 1 1^s 0^inf"),
    ("loopQ", "E phase, one bounce: Q(m+1, j, r+3) reaches Q(m, j+1, r+1), for any tape L to the left.",
     "L 1 0 1 D> 0 0 (1010)^j 1^r+3 0^inf", "L 1 D> 0 0 1 0 1 (0101)^j 0 1 1^r 0^inf"),
] + ([START_A[M],
    ("endA", "A phase, end: Q(m, j, 2) reaches A(m, 4j+6), for any tape L to the left of the bounce frame's 1.",
     "L 1 D> 0 0 (1010)^j 1 1 0^inf", "L 1 1 (1111)^j 1 1 1 1 A> 0^inf"),
] if M in START_A else []) + [
    ("endQ", "E phase, end: Q(0, j, s+5) reaches E(2j+4, s+1).",
     "0^inf 1 D> 0 0 (1010)^j 1^s+5 0^inf", "0^inf E> 0 1 0 1 0 1 0 1 (0101)^j 0 1 1^s 0^inf"),
]
RULES = [(n, d, a.replace("D>", QS + ">"), b.replace("D>", QS + ">")) for n, d, a, b in RULES]
out = []
for name, doc, a, b in RULES:
    txt, fin = symtm.prove(m, name, a, b, doc=doc, rotate=True)
    out.append(txt)
    print("--", name, fin, fin.steps, file=sys.stderr)
doc = (f"Pieces of the E and A phases of {M}: E(x, z) = `E>0 (10)^x 1^z`, A(x, y) = `(10)^x 1^y A>0` and the bounce frame Q(m, j, t) = "
       "`(10)^m 1 D>0 0 (1010)^j 1^t`, blank tape around; generated by `py/gen_rules.py`; do not edit by hand.")
sys.stdout.write(symtm.rules_file("Machine", NS, out, doc))
