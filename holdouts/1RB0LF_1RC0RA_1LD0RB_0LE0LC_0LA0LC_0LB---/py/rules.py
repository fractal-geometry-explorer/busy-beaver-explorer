"""Writes lean/Rules.lean: shift rules of this machine's sweeps and the shape of a halt, proved by
tools/py/bbtools/symtm.py (`prove`).  Usage: python3 py/rules.py > lean/Rules.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LF_1RC0RA_1LD0RB_0LE0LC_0LA0LC_0LB---"
NS = "H92633"
RULES = [
    ('a_run', 'L A> (01)^n R', 'L (10)^n A> R',
     'Rightward, A crosses (01)^n turning it into (10)^n, 2 steps a pair (A and B alternate).', {}),
    ('b_run', 'L 0 B> (1000)^n R', 'L (0001)^n 0 B> R',
     'Rightward, B (with a 0 behind it) crosses the 1000 blocks, 8 steps a block.', {}),
    ('a_run4', 'L 0 A> (0001)^n R', 'L (0010)^n 0 A> R',
     'Rightward, A (with a 0 behind it) crosses 0001 blocks, 8 steps a block.', {}),
    ('c_run', 'L (01)^n C> 0 R', 'L C> 0 (01)^n R',
     'Leftward, C crosses (01)^n unchanged, 2 steps a pair.', {}),
    ('d_run', 'L (10)^n D> 1 R', 'L D> 1 (10)^n R',
     'Leftward, D crosses (10)^n unchanged, 2 steps a pair.', {}),
    ('halt_shape', 'L 1 1 E> 0 R', 'L F> 1 0 0 R',
     'The only way to a halt: E on a 0 with 1 1 to its left reaches F on a 1 (which halts) in 2 steps.', {}),
]
HALT = "F"
HSYM = "1"

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d, **kw)[0] for n, s, e, d, kw in RULES]
    extra = (f"/-- {HALT} reading a {HSYM} halts (the end of `halt_shape`). -/\n"
             f"theorem halt_after_shape (L R : Tape) : step ⟨L, cons true R, .{HALT}⟩ = none := rfl\n")
    print(rules_file("Machine", NS, thms + [extra],
                     f"# {M}: shift rules of the sweeps and the shape of a halt\n\n"
                     "Generated by `py/rules.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `n` and all "
                     "tapes `L`, `R`."))
