"""Write lean/Rules.lean for 1RB1RE_1LC0RC_1RA1LD_1RB0LA_0LC1RF_---1RD: the digit rules of the left-end counter,
proved by symbolic simulation (tools/py/bbtools/symtm.py), each a theorem for all values of its variables and for
any tape R to the right.

Words: a = 10, b = 1110, so ba = 111010 and ab = 101110 (b (ab)^n = (ba)^n b).  At the left end the tape is
    0^inf D> 0 b (ba)^n1 s1 (ba)^n2 s2 ...       separators s_i in {a, b, ab, bb}
and one excursion of the head from the left end (D> 0 ... back to D> 0 ...) increments the first separator:
    c1: a  -> b
    c2: b (ba)^(m+1) -> ba ab (ba)^m            (the block on the left gains a pair ba, the block on the right loses one)
    c1 also covers ab -> bb (R = b ...)
    c4, c5: bb -> ba a, and the carry goes on to the next separator (shown for a next separator a or b)

usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/<M>/py/gen_rules.py > holdouts/<M>/lean/Rules.lean
"""
import os
import re

from bbtools import symtm

M = '1RB1RE_1LC0RC_1RA1LD_1RB0LA_0LC1RF_---1RD'
B, A, BA = '1 1 1 0', '1 0', '(111010)'
RULES = [
    ('c1', 'separator a becomes b (any tape R to the right)',
     f'0^inf D> 0 {B} {BA}^n+1 {A} R', f'0^inf D> 0 {B} {B} (101110)^n+1 R'),
    ('c2', 'separator b becomes ab, one pair ba moving from the right block to the left block',
     f'0^inf D> 0 {B} {BA}^n+1 {B} {BA}^m+1 R', f'0^inf D> 0 {B} {B} (101110)^n+1 {A} {A} {B} {BA}^m R'),
    ('c4', 'separator bb becomes a with the left block one longer; the carry turns the next separator a into b',
     f'0^inf D> 0 {B} {BA}^n+1 {B} {B} {BA}^m+1 {A} R',
     f'0^inf D> 0 {B} {B} (101110)^n+1 {A} {A} {B} (101110)^m+1 R'),
    ('c5', 'separator bb becomes a; the carry turns the next separator b into ab',
     f'0^inf D> 0 {B} {BA}^n+1 {B} {B} {BA}^m+1 {B} {BA}^k+1 R',
     f'0^inf D> 0 {B} {B} (101110)^n+1 {A} {A} {B} (101110)^m+1 {A} {A} {B} {BA}^k R'),
]


def main(ID):
    thms = []
    for name, doc, a, b in RULES:
        text, _ = symtm.prove(M, name, a, b, doc=doc, rotate=True, count_first=True)
        thms.append(text)
    print(symtm.rules_file('Machine', 'H' + ID, thms,
                           f'Rules of {M}, generated by py/gen_rules.py (symbolic simulation, '
                           '`tools/py/bbtools/symtm.py`).'), end='')


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    ID = re.search(r'namespace H(\d+)', open(os.path.join(here, '..', 'lean', 'Machine.lean')).read()).group(1)
    main(ID)
