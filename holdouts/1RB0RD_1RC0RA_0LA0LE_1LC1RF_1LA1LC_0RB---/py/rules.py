"""Generate ../lean/Rules.lean: the shift and macro rules of 1RB0RD_1RC0RA_0LA0LE_1LC1RF_1LA1LC_0RB---, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RD_1RC0RA_0LA0LE_1LC1RF_1LA1LC_0RB---"

RULES = [
    ('b_right', 'L B> (10)^n R', 'L (01)^n B> R',
     'B runs right across (10)^n, shifting it one cell: every 10 becomes 01.'),
    ('a_right', 'L A> (01)^n R', 'L (10)^n A> R',
     'A runs right across (01)^n, turning it back into (10)^n.'),
    ('c_glider', 'L (1010)^n C> 0 1 R', 'L C> 0 1 (1010)^n R',
     'C runs left through (10)^(2n) carrying a `0 1` defect (10 steps per 4 cells); the body is unchanged.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H16554", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
