"""Generate ../lean/Rules.lean: rules of 1RB1LC_1LA0RD_0LB1LF_1RE1LC_1LC0RB_0LA---, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`, repeats re-bracketed
next to the head with `TM.rep_rotate`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.  The left side of the tape is a block of ones and a block of the word 110.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LC_1LA0RD_0LB1LF_1RE1LC_1LC0RB_0LA---"

RULES = [
    ('shift_A_001_l', 'L (001)^n A> 1 R', 'L A> 1 (111)^n R',
     'A crosses (001)^n leftwards in 5*n steps.'),
    ('shift_B_001_l', 'L (001)^n B> 0 R', 'L B> 0 (011)^n R',
     'B crosses (001)^n leftwards in 3*n steps.'),
    ('shift_C_010_l', 'L (010)^n C> 0 R', 'L C> 0 (110)^n R',
     'C crosses (010)^n leftwards in 3*n steps.'),
    ('shift_D_010_r', 'L D> (010)^n R', 'L (110)^n D> R',
     'D crosses (010)^n rightwards in 5*n steps.'),
    ('shift_F_010_l', 'L (010)^n F> 0 R', 'L F> 0 (111)^n R',
     'F crosses (010)^n leftwards in 5*n steps.'),
    ('shift_D_011_r', 'L D> (011)^n R', 'L (100)^n D> R',
     'D crosses (011)^n rightwards in 3*n steps.'),
    ('shift_F_011_l', 'L (011)^n F> 0 R', 'L F> 0 (110)^n R',
     'F crosses (011)^n leftwards in 3*n steps.'),
    ('shift_A_100_l', 'L (100)^n A> 1 R', 'L A> 1 (101)^n R',
     'A crosses (100)^n leftwards in 3*n steps.'),
    ('shift_C_100_l', 'L (100)^n C> 1 R', 'L C> 1 (111)^n R',
     'C crosses (100)^n leftwards in 5*n steps.'),
    ('shift_E_100_r', 'L E> (100)^n R', 'L (101)^n E> R',
     'E crosses (100)^n rightwards in 5*n steps.'),
    ('shift_A_101_l', 'L (101)^n A> 1 R', 'L A> 1 (011)^n R',
     'A crosses (101)^n leftwards in 3*n steps.'),
    ('shift_B_101_r', 'L B> (101)^n R', 'L (010)^n B> R',
     'B crosses (101)^n rightwards in 3*n steps.'),
    ('shift_C_110_l', 'L (110)^n C> 1 R', 'L C> 1 (101)^n R',
     'C crosses (110)^n leftwards in 3*n steps.'),
    ('shift_E_110_r', 'L E> (110)^n R', 'L (001)^n E> R',
     'E crosses (110)^n rightwards in 3*n steps.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H65944", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
