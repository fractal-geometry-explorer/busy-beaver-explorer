"""Shift rules of 1RB0LC_1LC0RB_0LE0LD_1LC---_0RA1LF_1LA1LF, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LC_1LC0RB_0LE0LD_1LC---_0RA1LF_1LA1LF/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L 1 0 C> (10)^n R` is the head
in state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LC_1LC0RB_0LE0LD_1LC---_0RA1LF_1LA1LF"
NS = "H25358"
DOC = """# Shift rules of 1RB0LC_1LC0RB_0LE0LD_1LC---_0RA1LF_1LA1LF

The four passes of the machine over the two regular parts of its tape: B moving right over the six-cell word
`011101` (`pass_right_b`) and over `1001` (`pass_right_a`), C moving left over `000101` (`pass_left_b`) and E moving
left over `1010` (`pass_left_a`).  The only halt is D reading a 1; D is entered only from C reading a 1, so `1 C> 1`
halts after two steps (`halt_C`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

# Lean options put before the first theorem (the long words need a deeper recursion limit)
OPTIONS = ''

RULES = [
    ('pass_right_b',
     'L 0 0 B> (011101)^n R',
     'L (010001)^n 0 0 B> R',
     'Moving right over the periodic right part, 14 steps a word: `011101` becomes `010001`.'),
    ('pass_left_b',
     'L (000101)^n C> 0 R',
     'L C> 0 (101110)^n R',
     'Moving left over the right part, 10 steps a word: `000101` becomes `101110`.'),
    ('pass_right_a',
     'L 0 0 B> (1001)^n R',
     'L (1010)^n 0 0 B> R',
     'Moving right over the `0011` blocks of the left part, 20 steps a word.'),
    ('pass_left_a',
     'L (1010)^n E> 1 R',
     'L E> 1 (0011)^n R',
     'Moving left over the left part, E turns each `1010` back into `0011`.')
]

# hand-written statements appended to the file (the halting situations), proved by `rfl`
EXTRA = """/-- `1 C> 1` halts: C writes a 0 and steps left in state D onto a 1, which has no transition. -/
theorem halt_C (L R : Tape) :
    ∃ c, steps 1 ⟨cons true L, cons true R, .C⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩
"""


def main():
    thms = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    thms[0] = OPTIONS + thms[0]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
