"""Generate ../lean/Rules.lean: rules of 1RB1LA_0LC0RC_1LE1RD_1RE1RC_1LF0LA_---1LE, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(w)^t` the word w
repeated t times, L and R any tape.  The sample configuration is K(p, q) = `0^inf A> 0 1^p 0 1^q 0^inf`.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LA_0LC0RC_1LE1RD_1RE1RC_1LF0LA_---1LE"

RULES = [
    ("start", "0^inf A> 0^inf", "0^inf A> 0 0 1 1 0^inf", "From blank tape to K(0, 2) in 7 steps."),
    ("inner_odd", "L A> 0 1 1 1 (11)^k+1 0 R", "L 1 A> 0 1 1 1 (11)^k 0 1 R",
     "Odd block: one pass moves the 0 after the block two cells left and puts a 1 on each side."),
    ("inner_even", "L A> 0 1 1 (11)^k 0 1 R", "L 1 A> 0 1 1 (11)^k 0 R",
     "Even block: one pass moves the block one cell right, eating a 1 of the second block."),
    ("end_odd0", "0^inf A> 0 1 1 1 0 1^q 0^inf", "0^inf A> 0 0 1^q+4 0^inf", "K(3, q) -> K(0, q + 4)."),
    ("end_odd", "0^inf 1^j+1 A> 0 1 1 1 0 1^q 0^inf", "0^inf A> 0 1^j+1 0 1^q+4 0^inf",
     "The odd block is down to 3 cells with j + 1 ones to its left: K(j + 1, q + 4)."),
    ("end_zero", "0^inf A> 0 0 1 1^q 0^inf", "0^inf A> 0 1 1 0 1^q 0^inf", "K(0, q + 1) -> K(2, q)."),
    ("end_even", "L A> 0 1 1 (11)^k+1 0^inf", "L 1 A> 0 1 1 (11)^k 0 1 1 0^inf",
     "Even block at the blank end: the last two ones of the block move past a 0 to the right."),
    ("end_even0", "L A> 0 1 1 0^inf", "L 1 A> 0 0 1 1 0^inf", "Even block of two ones at the blank end."),
    ("end_fin", "0^inf 1^n A> 0 0 1 1 0^inf", "0^inf A> 0 1 1^n 1 0 1 0^inf",
     "End of the even case: 1^n A> 0 0 1 1 is K(n + 2, 1)."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H31371", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
