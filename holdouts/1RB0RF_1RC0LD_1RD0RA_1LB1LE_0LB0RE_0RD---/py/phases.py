def bump(s, k):
    """add k to the constant of every block whose count has a variable"""
    def f(mt):
        v, c = mt.group(1), mt.group(2)
        return ')^%s+%d' % (v, int(c or 0) + k)
    return re.sub(r'\)\^(x\d+)(?:\+(\d+))?', f, s)


def prove_bumped(name, a, b, doc):
    """symtm's run re-brackets differently from accel.py and may need a little more of some block: raise all
    thresholds by k (the rule then holds for fewer configurations, still for every large count)"""
    for k in (0, 1, 2, 3, 4, 6, 8, 12):
        try:
            return prove(M, name, bump(a, k), bump(b, k), doc=doc, rotate=True, count_first=True, max_seg=40)[0]
        except ProofError as e:
            err = e
    raise err


# one Lean file per group, so that no single Lean process needs too much memory
GROUPS = [("Phases", ["cross6", "absorb2", "cross12"]), ("PhasesDrain", ["drain11"]), ("PhasesFeed", ["feed30", "cross12b"])]


def main():
    out = os.path.join(HERE, "..", "lean")
    for fname, names in GROUPS:
        ths = []
        for name, a, b, doc in RULES:
            if name in names:
                # long runs exceed the default elaboration budget
                ths.append("set_option maxHeartbeats 4000000 in\nset_option maxRecDepth 20000 in\n" + prove_bumped(name, a, b, doc))
        with open(os.path.join(out, fname + ".lean"), "w") as f:
            f.write(rules_file("Machine", NS, ths, f"Phase rules of {M}, generated by `py/phases.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
