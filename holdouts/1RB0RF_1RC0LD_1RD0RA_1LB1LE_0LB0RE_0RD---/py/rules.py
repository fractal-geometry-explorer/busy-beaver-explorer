"""Generate lean/Rules.lean for 1RB0RF_1RC0LD_1RD0RA_1LB1LE_0LB0RE_0RD---: one-cycle rules of its phases, proved along the symbolic run of
tools/py/bbtools/symtm.py (single steps by `rfl`, shift rules by TM.cross_r/cross_l, re-bracketing by TM.rep_rotate).

usage (from the repo root): python3 holdouts/1RB0RF_1RC0LD_1RD0RA_1LB1LE_0LB0RE_0RD---/py/rules.py > holdouts/1RB0RF_1RC0LD_1RD0RA_1LB1LE_0LB0RE_0RD---/lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RF_1RC0LD_1RD0RA_1LB1LE_0LB0RE_0RD---"
NS = next(l.split()[1] for l in open(os.path.join(HERE, "..", "lean", "Machine.lean")) if l.startswith("namespace "))

RULES = [
    ("absorb",
     "0^inf D> 0 0 0 (100)^a (010)^b+2 1 R",
     "0^inf D> 0 0 0 (100)^a+4 (010)^b 1 R",
     "Absorb phase, three visits of the left end in state D: the second block loses two words `010` and the left block gains four `100` (the tape R past the next `1` is not read)."),
    ("traverse",
     "L (101)^x+6 (110)^y 1 0 (011)^n+1 (010011011)^k+1 (010)^3 1 1 D> 0^inf",
     "L (101)^x (110)^y+6 1 0 (011)^n+1 (010011011)^k+2 (010)^3 1 1 D> 0^inf",
     "Traverse phase, one cycle at the right end: the boundary between `101` and `110` inside the left block moves six words right and the final block gains one word `010011011` (the tape L is not read)."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
