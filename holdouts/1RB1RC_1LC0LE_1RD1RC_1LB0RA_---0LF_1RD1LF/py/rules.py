"""Writes lean/Rules.lean: the building blocks of the carry wave, each proved by bbtools.symtm from a symbolic trace
(shift rules, `rfl`, `omega`).  `lean/Wave.lean` (by hand) composes them.  The twin of 1RB1RA_1LC0RC_1RE0LD_0RE0LF_1RA---_1RB1LF: the same tapes, other states.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "../../../tools/py"))
from bbtools.symtm import prove, Config, run, Halted, step
from bbtools.machine import Machine, STATES
from crossgen import generic_cross

M = "1RB1RC_1LC0LE_1RD1RC_1LB0RA_---0LF_1RD1LF"
NS = "H41157"
TAIL = "1^14 0 1^7 0 1^6 0 1^4 0 1^2 0^inf"

RULES = [
    ("start", "From blank tape to the first cycle start S0 [26, 13, 9, 6] in 6053 steps.",
     "0^inf A> 0^inf", "0^inf 1^6 0 1^9 0 1^13 0 1^26 0 1^14 0 1^7 0 1^6 0 1^4 0 A> 1 0^inf"),
    ("cycle", "One cycle of the low digits: from S0 with last digit x to the wave W (x+61) with the tail T.",
     "L 0 1^x 0 1^14 0 1^7 0 1^6 0 1^4 0 A> 1 0^inf", "L 0 1^x+61 B> 1 1 0 " + TAIL),
    ("w2z", "The wave meets a digit: W (q+2) becomes the zigzag Z (y+1) q 1.",
     "L 0 1^y 0 1^q+2 B> 1 1 0 R", "L 0 1^y+1 0 A> 1^q 0 0 1 0 R"),
    ("zigA", "One zigzag: Z p (q+3) r becomes Z (p+1) (q+1) (r+1).",
     "L 0 1^i 0 A> 1^q+3 0 0 1^j 0 R", "L 0 1^i+1 0 A> 1^q+1 0 0 1^j+1 0 R"),
    ("zigB", "One zigzag: Z p 2 r becomes Z (p+1) 0 (r+1).",
     "L 0 1^i 0 A> 1 1 0 0 1^j 0 R", "L 0 1^i+1 0 A> 0 0 1^j+1 0 R"),
    ("zend1", "End of the zigzag on an odd digit: the wave moves one digit to the left.",
     "L 0 1^i 0 A> 1 0 0 1^j 0 R", "L 0 1^i B> 1 1 0 1^j+1 0 R"),
    ("zend0", "End of the zigzag on an even digit: the wave stops and the head runs right in state C.",
     "L 0 1^i 0 A> 0 0 1^j 0 R", "L 0 1^i 0 1^j+2 C> 0 R"),
    ("cs", "The run to the right crosses one digit.",
     "L C> 0 1^d+2 0 R", "L 1 0 1^d+1 C> 0 R"),
    ("cfin", "The run reaches the fixed tail: back to S0.",
     "L C> 0 " + TAIL, "L 1 0 1^14 0 1^7 0 1^6 0 1^4 0 A> 1 0^inf"),
    ("halt1", "W 1 at the left end of the tape: E reads a 0 next (a halt).",
     "0^inf 1 B> 1 1 0 1^g+2 0 R", "HALT"),
]


def halt_cfg(start):
    m = Machine.parse(M)
    c = Config.parse(start)
    last = None
    while True:
        last = c.copy()
        try:
            c = run(m, c, lambda c: False, max_moves=1)
        except RuntimeError:
            pass
        except Halted:
            return last


def cfg_str(c):
    from bbtools.symtm import Rep, canon
    def tok(t):
        if isinstance(t, Rep):
            return f"({''.join(map(str, t.word))})^{t.n}".replace(' ', '')
        return str(t)
    return ' '.join(map(tok, canon(c.left))) + f" {STATES[c.state]}> " + ' '.join(map(tok, canon(c.right)))


def main():
    out = ["import Machine", "", f"/-! Rules of {M}, generated by `py/rules.py`; do not edit by hand. -/", "", "set_option maxRecDepth 20000", "set_option maxHeartbeats 10000000", "",
           f"namespace {NS}", "", "open TM", ""]
    for name, doc, start, end in RULES:
        if end == "HALT":
            end = cfg_str(halt_cfg(start))
        t, f = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=60)
        out += [generic_cross(t), ""]
    out.append(f"end {NS}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
