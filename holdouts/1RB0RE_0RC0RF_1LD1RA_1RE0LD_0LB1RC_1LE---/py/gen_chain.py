"""Write lean/Chain.lean: the run from blank tape proved rebuild after rebuild.

The run is a sequence of segments, each a theorem `run_i : ∃ n, steps n init = some (enc q D l us)`, from the third
single block (`Transient.lean`) on:

* an *advance*: as many sub-rounds of `W` with the counter as the counter can make before it meets a small gap of
  the zone (or the whole collapse, to the next single block).  `gfast` (`Counter.lean`) advances the counter and
  `advance_to` (`Advance.lean`) gives the digits after it from the time left alone, `T D' + M = T D`;
* a *pass*: the sub-rounds where the counter is stuck (a small gap, or a single block and its rebuild), evaluated
  by the kernel with the pass machine (`subs`, `General.lean`), up to the first configuration `enc q D l us`
  from which the counter can move again.

The kernel evaluates `T`, `gfast` and `subs`; no machine step is evaluated.

usage: python3 py/gen_chain.py [REBUILDS] > lean/Chain.lean
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import passm  # noqa: E402
sys.set_int_max_str_digits(0)


def gpop(us, n):
    i = 0
    while True:
        if i == len(us): return (4 * n + 5, [])
        u = us[i]
        if u == 3: i += 1; n += 1; continue
        if u >= 4: return (4 * n + 5, [u - 4] + us[i + 1:])
        if u == 0 and i + 1 == len(us): return (4 * n + 4, [])
        if u == 0 and us[i + 1] >= 2: return (4 * n + 4, [us[i + 1] - 2] + us[i + 2:])
        return None


def gstep(x):
    l, us = x
    if l >= 2: return (1, [l - 2] + us)
    if l == 1: return gpop(us, 0)
    return None


def pick(N, t):
    while t > 0 and 2 ** t > N: t -= 1
    return t


def gfast(N, x, fuel=100000):
    """lean/Counter.lean's gfast: (result, jumps) or None"""
    for f in range(fuel):
        if N == 0: return x, f + 1
        s = pick(N, (x[0] - 1) // 4)
        y = gstep((x[0] - 4 * s, x[1]))
        if y is None: return None
        N -= 2 ** s; x = (y[0] + 4 * s, y[1])
    return None


def T(D):
    t = 0
    for x in reversed(D): t = 2 ** x * (1 + 2 * t)
    return t


def as_enc(bs):
    """(q, D) if bs = encBlocks q D"""
    if not bs or bs[-1] % 3: return None
    if any(b % 3 != 2 for b in bs[:-1]): return None
    return bs[-1] // 3, [(b - 2) // 3 for b in bs[:-1]]


def lst(x):
    return "[" + ", ".join(map(str, x)) + "]"


def gmax(N, x):
    """the largest M <= N such that the counter makes M steps from x, and where it is then"""
    M = 0
    while N > 0:
        s = pick(N, (x[0] - 1) // 4)
        while True:
            y = gstep((x[0] - 4 * s, x[1]))
            if y is not None or s == 0: break
            s -= 1
        if y is None: break
        N -= 2 ** s; M += 2 ** s; x = (y[0] + 4 * s, y[1])
    return M, x


def Tinv(n):
    D = []
    while n:
        x = (n & -n).bit_length() - 1; D.append(x); n = (n >> x) // 2
    return D


def lmass(D):
    return sum(d + 1 for d in D)


def segments(q, D, l, us, R):
    """segments from enc q D l us until the single block of rebuild R (counting the start as rebuild 3)"""
    out = []; reb = 3
    while reb < R:
        M = gmax(T(D), (l, us))[0] if D else 0
        if M > 0:
            y, jumps = gfast(M, (l, us))
            m = q + lmass(D); D2 = Tinv(T(D) - M); q2 = m - lmass(D2)
            out.append(dict(kind="adv", q=q, D=D, l=l, us=us, M=M, q2=q2, D2=D2, y=y, jumps=jumps))
            q, D, (l, us) = q2, D2, y
            if not D: reb += 1
            continue
        bs, ll, uu, N, steps = [3 * d + 2 for d in D] + [3 * q], l, list(us), 0, 0
        while True:
            r = passm.sub_fast(bs, ll, uu)
            if r[0] != "moment": raise SystemExit(f"rebuild {reb}: {r[0]}")
            _, bs, ll, uu, n = r; N += 1; steps += n
            e = as_enc(bs)
            if e and e[1] and gstep((ll, uu)) is not None: break
        out.append(dict(kind="pass", q=q, D=D, l=l, us=us, N=N, steps=steps, q2=e[0], D2=e[1], y=(ll, list(uu))))
        q, D, l, us = e[0], e[1], ll, list(uu)
    return out


