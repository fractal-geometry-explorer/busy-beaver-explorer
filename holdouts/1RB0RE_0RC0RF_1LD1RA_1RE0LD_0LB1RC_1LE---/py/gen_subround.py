"""Write lean/Subround.lean: the regular sub-round as three machine rules for all sizes, proved with
`tools/py/bbtools/symtm.py` (only `rfl` steps, the crossing lemmas and `omega`).

A sub-round runs from the head in C on a 0 just right of a block of 1s to the next such moment.  In `glong` and
`gshort` the last interior block is 3a + 2 and the tape further left (L) is never read past the 0 in front of it: W
adds 3 to the block before (or to the first block) and leaves a blocks of 2.  The counter part:
  glong   last block l = b + 2 >= 2:  l becomes 1, a new first zone gap of b + 1 cells (R right of the head is untouched).
  gshort  l = 1, zone 0 (0001)^n 0000 R:  the n leading gaps of 3 are removed, l = 4n + 5, the next gap loses 4.
  gzero   l = 1, zone 0 (0001)^n 1 00 R:  the gaps of 3 are removed, the gap of 0 too, l = 4n + 4, the next gap loses 2.
  single  a single block 3(k + 1) (blank tape on its left) with l = b + 5: it becomes 3 2^k, l = 5, new gap b + 1.
  singleone  the same with l = 1 and a first gap of at least 3: 3 2^k, l = 4, the first gap loses 2.

usage: python3 py/gen_subround.py > lean/Subround.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove  # noqa: E402

M, NS = "1RB0RE_0RC0RF_1LD1RA_1RE0LD_0LB1RC_1LE---", "H4320"
RULES = [
    ("glong", "L 0 (111)^a 1 1 0 1^b+2 C> 0 R", "L 1 1 1 (011)^a 0 1 C> 0^b+1 1 R",
     "Sub-round with last block b + 2 >= 2: W on the interior; the last block becomes 1 and a new zone gap b + 1."),
    ("gshort", "L 0 (111)^a 1 1 0 1 C> 0 (0001)^n 0 0 0 0 R", "L 1 1 1 (011)^a 0 1 1 (1111)^n 1 1 1 C> 0 R",
     "Sub-round with last block 1: W on the interior; the counter removes n + 1 segments of 4 and takes 4 cells "
     "from the next segment, which has at least 5 (R is anything, blank tape too)."),
    ("gzero", "L 0 (111)^a 1 1 0 1 C> 0 (0001)^n 1 0 0 R", "L 1 1 1 (011)^a 0 1 1 (1111)^n 1 1 C> 0 R",
     "Sub-round with last block 1 whose carry meets a gap of 0 (two 1s side by side) followed by a gap of at least 2: "
     "W on the interior; l = 4n + 4 and the next gap loses 2."),
    ("single", "0^inf (111)^k+1 0 1^b+5 C> 0 R", "0^inf 1 1 1 (011)^k+1 1 1 1 C> 0^b+1 1 R",
     "Sub-round from a single block 3(k + 1) with last block b + 5 >= 5: the block becomes 3 2^k, the last block 5, "
     "and a new zone gap b + 1."),
    ("singleone", "0^inf (111)^k+1 0 1 C> 0 0 0 R", "0^inf 1 1 1 (011)^k+1 1 1 C> 0 R",
     "Sub-round from a single block 3(k + 1) with last block 1 and a first zone gap of at least 3 cells: the block "
     "becomes 3 2^k, the last block 4, and the first gap loses 2."),
]
if __name__ == "__main__":
    print(f"""import Machine

/-!
# {M}: the regular sub-round, for all sizes

Generated by `py/gen_subround.py` (`tools/py/bbtools/symtm.py`); do not edit by hand.  Each theorem is about every
value of its variables and every tape `L`, `R`.  `lean/Collapse.lean` puts them together.
-/

namespace {NS}

open TM
""")
    for nm, s, e, doc in RULES:
        t, f = prove(M, nm, s, e, doc=doc, rotate=True, max_seg=40, count_first=True)
        print(t + "\n")
    print(f"end {NS}")
