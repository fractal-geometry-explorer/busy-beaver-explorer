"""Write lean/Pass.lean: the moves of the pass machine, each proved for all sizes with `tools/py/bbtools/symtm.py`
(only `rfl` steps, the crossing lemmas and `omega`).

Every sub-round (from the head in C on a 0 just right of a 1 to the next such moment) is one left sweep and one
right sweep.  The left sweep (`start`) erases the last block, moves the block before it one cell to the right, adds 3
to the block before that and leaves the head in A in front of the moved block.  The right sweep reads the tape in
one of three phases A, E, C (the state) with an *open block* (the 1s just left of the head):

  aone, eone, cone   on a 1: A writes 0 (the open block is closed, a new empty one opens), E and C keep the 1;
                     the phase goes A -> E -> C -> A.  `conv`: three cells at once, 111 -> 011 from A.
  czero              C on a 0 next to a 0 (empty open block): the two cells become 11, still C.
  ezero              E on a 0 next to a 0: the same (5 steps).
  eshift             E on a 0 after an open block of o + 1: the block moves one cell right, the block before it
                     grows by 3 and A starts again in front of the moved block (now o cells to read).
  a000               A on 000: 111, then C.
  a001               A on 001: 101, then A (the open block closes at the middle 0).
  a010               A on 010 after an open block of o: as eshift, with o + 1 cells to read.
  (A on 011 halts: `a011` in lean/Pass.lean is written by hand.)
  C on a 0 after a non-empty open block is the next moment: the open block is the new last block.

lean/General.lean puts the moves together into the function `pass` and proves it sound.

usage: python3 py/gen_pass.py > lean/Pass.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove  # noqa: E402

M, NS = "1RB0RE_0RC0RF_1LD1RA_1RE0LD_0LB1RC_1LE---", "H4320"
RULES = [
    ("start", "L 0 1^p+1 0 1^l+1 C> 0 R", "L 1 1 1 A> 1^p+1 0^l 1 R",
     "The left sweep: the last block (l + 1) is erased, the block before it (p + 1) moves one cell right, the block "
     "before that grows by 3 (3 new cells if `L` is blank), and A starts in front of the moved block."),
    ("aone", "L A> 1 R", "L 0 E> R", "A on a 1 writes 0."),
    ("eone", "L E> 1 R", "L 1 C> R", "E on a 1."),
    ("cone", "L C> 1 R", "L 1 A> R", "C on a 1."),
    ("conv", "L A> (111)^a R", "L (011)^a A> R", "A over 3a ones: `(011)^a`, still A."),
    ("czero", "L 0 C> 0 R", "L 1 1 C> R", "C on a 0 with a 0 on its left: both become 1."),
    ("ezero", "L 0 E> 0 R", "L 1 1 C> R", "E on a 0 with a 0 on its left: both become 1, then C."),
    ("eshift", "L 0 1^o+1 E> 0 R", "L 1 1 1 A> 1^o R",
     "E on a 0 after an open block of o + 1: the block moves one cell right, the block before it grows by 3."),
    ("azzz", "L A> 0 0 0 R", "L 1 1 1 C> R", "A on 000."),
    ("azzo", "L A> 0 0 1 R", "L 1 0 1 A> R", "A on 001: the open block closes at the middle cell."),
    ("azoz", "L 0 1^o A> 0 1 0 R", "L 1 1 1 A> 1^o+1 R",
     "A on 010 after an open block of o: the block moves right, the block before it grows by 3."),
]
if __name__ == "__main__":
    print(f"""import Machine

/-!
# {M}: the moves of the pass machine, for all sizes

Generated by `py/gen_pass.py` (`tools/py/bbtools/symtm.py`) except `a011`; do not edit by hand.  Each theorem is
about every value of its variables and every tape `L`, `R`.  `lean/General.lean` puts them together.
-/

namespace {NS}

open TM
""")
    for nm, s, e, doc in RULES:
        t, f = prove(M, nm, s, e, doc=doc, rotate=True, max_seg=40, count_first=True)
        print(t + "\n")
    print(f"""/-- A on 011 halts: two steps, then F reads a 1. -/
theorem a011 (L R : Tape) :
    steps 2 ⟨L, cons false (cons true (cons true R)), .A⟩ = some ⟨cons false (cons true L), cons true R, .F⟩ ∧
      step ⟨cons false (cons true L), cons true R, .F⟩ = none := ⟨rfl, rfl⟩

end {NS}""")
