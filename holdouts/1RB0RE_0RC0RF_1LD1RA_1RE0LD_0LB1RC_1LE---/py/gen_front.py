"""Lean statements and proofs for the frontier cases of py/sym_law.py that are pure moves of the pass machine.

For each shape and group value whose cases have no moment (or end the transient at the first moment) and do not touch
the history, it writes a theorem: from the frontier, for every value of the parameters, every list X beyond the front
and every bit list bs above the group, the machine reaches the next frontier (`Reach`) or the moment where the
transient ends (`ReachM`).  The proof is the chain of pass machine moves, each checked by `rfl`.

usage: python3 py/gen_front.py > lean/FrontCases.lean
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sym_law import FAM, frontier, name, explore
from sym_lin import Lin

PH = {"A": ".A", "C": ".C", "E": ".E"}


def lin(x):
    """an affine form as a Lean term (variables first, so that `rfl` sees successors)"""
    x = x if isinstance(x, Lin) else Lin(x)
    parts = [(f"{c} * {v}" if c != 1 else v) for v, c in sorted(x.c.items()) if c]
    if x.k or not parts: parts.append(str(x.k))
    t = " + ".join(parts)
    return f"({t})" if len(parts) > 1 or " " in t else t


def lst(items, tail):
    out = []
    for it in items:
        assert it[0] == 'b', it
        out.append(lin(it[1]))
    return " :: ".join(out + [tail])


def zone(us, bs="bs"):
    """the engine's zone: closed gaps, then the open last gap"""
    vals = [lin(it[1]) for it in us]
    return " :: ".join(vals[:-1] + [f"openZ {vals[-1]} {bs}"])


def bits3(v):
    return " :: ".join("true" if (v >> i) & 1 else "false" for i in range(3)) + " :: bs"


def cases():
    out = []
    for t in FAM:
        for v in range(8):
            res = explore(frontier(t, v))
            if len(res) != 1: continue
            why, s, path = res[0]
            if s.ops or path: continue
            if not (s.sub == 0 or (why == "end" and s.sub == 1)): continue
            out.append((t, v, why, s))
    return out


def theorem(t, v, why, s):
    s0 = frontier(t, v)
    a, b = FAM[t]
    vars_ = sorted(set(a.c) | (set(b.c) if b is not None else set()))
    front = [a] + ([b] if b is not None else [])
    src = f"⟨{' :: '.join(lin(x) for x in front)} :: X, {PH[t[0]]}, 0, openZ {t[1]} ({bits3(v)})⟩"
    tn = f"{name(t).replace('+', 'p')}_{v}" if t != ("C", 0, 4, 3) else f"C43_{v}"
    binders = " ".join(f"({x} : Nat)" for x in vars_)
    if why == "block":
        tail = [it for it in s.lb if it[0] != 'H']
        assert s.lb[-1] == ('H', 0) and s.us[-1][0] == 'b'
        dst = f"⟨{lst(tail, 'X')}, {PH[s.ph]}, 0, {zone(s.us)}⟩"
        stmt = f"Reach {src}\n      {dst}"
        fin = "exact Reach.refl _"
        nxt = "Reach.next"
    else:
        tail = [it for it in s.F if it[0] != 'H']
        assert s.F[-1] == ('H', 0)
        stmt = f"ReachM {src}\n      ({lst(tail, 'X')}) {lin(s.l)} ({zone(s.us)})"
        fin = "exact ReachM.done (by rfl)"
        nxt = "ReachM.next"
    return f"""/-- {name(t)} on the group {v} -/
theorem front_{tn} {binders} (X : List Nat) (bs : List Bool) :
    {stmt} := by
  obtain ⟨g, gs, hz⟩ := openZ_eq bs
  simp only [openZ_false, openZ_true, hz]
  repeat refine {nxt} (by rfl) ?_
  {fin}
"""


def main():
    cs = cases()
    print(f"""import Front

/-!
# 1RB0RE_0RC0RF_1LD1RA_1RE0LD_0LB1RC_1LE---: the frontier cases that are pure pass moves

Generated by `py/gen_front.py`; do not edit by hand.  {len(cs)} of the 516 cases of `py/sym_law.py cases`.
-/

namespace H4320

open TM

set_option linter.unusedSimpArgs false
""")
    for c in cs: print(theorem(*c))
    print("end H4320")


if __name__ == "__main__":
    main()
