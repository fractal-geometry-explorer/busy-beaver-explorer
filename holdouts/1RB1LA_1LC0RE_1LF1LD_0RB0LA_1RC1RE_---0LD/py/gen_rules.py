"""Write lean/Rules.lean: the shift rules of Space Needle, each proved by `bbtools.symtm.prove` (rfl steps and the
crossing lemmas of tools/lean/TM/Basic.lean).  Run from this folder: python3 py/gen_rules.py > lean/Rules.lean"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB1LA_1LC0RE_1LF1LD_0RB0LA_1RC1RE_---0LD"
RULES = [
    ("r_init", "0^inf A> 0^inf", "0^inf A> 0 1 1 1 0 0 1 0^inf", "From blank tape to (b, c) = (3, 1) in 45 steps."),
    ("r_halt", "0^inf A> 0 1 0 0 R", "0^inf F> 0 1 1 1 1 1 R", "(1, c): F reads a 0 after 12 steps, which halts."),
    ("r_start", "0^inf A> 0 1^m+1 0 0 R", "0^inf 1 0 1^m+1 C> 0 R", "A writes a 1 left of the block and moves it one cell right."),
    ("r_cyc", "L 0 1^m+3 C> 0 R", "L 1 0 1^m+1 C> 0 1 R", "One bounce: the middle block loses 2, each side gains 1."),
    ("r_endE", "0^inf 1^n+2 0 1 1 C> 0 R", "0^inf A> 0 1^n+1 0 1 1 0 1 R", "End of the bouncer, even block."),
    ("r_endE0", "0^inf 1 0 1 1 C> 0 R", "0^inf A> 0 0 1 1 0 1 R", "End of the bouncer, even block, smallest case."),
    ("r_endO", "0^inf 1^n+3 0 1 C> 0 R", "0^inf A> 0 1^n+1 0 0 1 1 1 R", "End of the bouncer, odd block."),
    ("r_endO0", "0^inf 1 1 0 1 C> 0 R", "0^inf A> 0 0 0 1 1 1 R", "End of the bouncer, odd block, smallest case."),
    ("r_zig", "L A> 0 1^r+2 0 1 R", "L 1 A> 0 1^r+1 0 1 R", "One zig-zag: a 1 moves from the right of the block to its left."),
    ("r_zig0", "L A> 0 1 0 1 R", "L 1 A> 0 0 1 R", "One zig-zag, block of one."),
    ("r_send", "0^inf 1^r+2 A> 0 0 1 R", "0^inf A> 0 1^r+1 0 1 1 1 R", "End of a shift: the block moves one cell left, the next grows by 2."),
    ("r_send0", "0^inf 1 A> 0 0 1 R", "0^inf A> 0 0 1 1 1 R", "End of a shift, block of one."),
    ("r_dmid", "0^inf A> 0 0 1^m+1 0 1 R", "0^inf A> 0 1^m+2 0 1 R", "An empty first block: the second absorbs the gap."),
    ("r_dend", "0^inf A> 0 0 1^m+2 0^inf", "0^inf A> 0 1^m+2 0 0 1 0^inf", "The last block alone: back to (m + 2, 1)."),
    ("r_zero", "0^inf A> 0 0 0 1^c+1 0^inf", "0^inf A> 0 0 1^c+3 0^inf", "(0, c + 1): the gap is absorbed."),
]


def main():
    ths = []
    for name, s, e, doc in RULES:
        t, _ = prove(M, name, s, e, doc=doc)
        ths.append(t)
    print(rules_file("Machine", "H101957", ths,
                     "Shift rules of Space Needle, generated by `py/gen_rules.py` with `tools/py/bbtools/symtm.py`; "
                     "do not edit by hand."), end="")


if __name__ == "__main__":
    main()
