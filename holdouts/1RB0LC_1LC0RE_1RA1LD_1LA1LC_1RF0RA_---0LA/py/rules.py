"""Shift rules and halting situations of 1RB0LC_1LC0RE_1RA1LD_1LA1LC_1RF0RA_---0LA, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LC_1LC0RE_1RA1LD_1LA1LC_1RF0RA_---0LA/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LC_1LC0RE_1RA1LD_1LA1LC_1RF0RA_---0LA"
NS = "H149962"
DOC = """# Shift rules of 1RB0LC_1LC0RE_1RA1LD_1LA1LC_1RF0RA_---0LA

Three crossings that the run uses: A turns `011` into `100` going right (`walk_A`); C, with a 1 ahead, moves left
through `01` blocks unchanged (`walk_C01`) and turns `110` into `011` (`walk_C110`).  The halting situations: only
F reading a 0 halts, and `E> 0 0`, `B> 1 0 0` and `A> 0 1 0 0` lead there.

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('walk_A', 'L A> (011)^n R', 'L (100)^n A> R', 'A turns each `011` into `100`, three steps a copy.'),
    ('walk_C01', 'L (01)^n C> 1 R', 'L C> 1 (01)^n R', 'C, with a 1 ahead, crosses `01` blocks leftwards and leaves them as they were, four steps a copy.'),
    ('walk_C110', 'L (110)^n C> 1 R', 'L C> 1 (011)^n R', 'C, with a 1 ahead, turns each `110` into `011` going left, three steps a copy.'),
]

HALTS = [
    ('halt_E', 'E> 0 0', 1, '`E> 0 0` halts: E writes 1 and moves right onto the 0 in state F.'),
    ('halt_B', 'B> 1 0 0', 2, '`B> 1 0 0` halts after two steps.'),
    ('halt_A', 'A> 0 1 0 0', 3, '`A> 0 1 0 0` halts after three steps.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [prove(M, name, a, b, doc=doc, count_first=True)[0] for name, a, b, doc in RULES]
    thms += [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
