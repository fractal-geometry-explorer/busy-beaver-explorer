"""Generate lean/Rules.lean: two shift rules of 1RB0LA_1LC1RF_---1LD_1RE0LA_1RA0RB_1RE0RF, proved along the symbolic
run (tools/py/bbtools/symtm.py).

usage (from the repo root):  python3 holdouts/1RB0LA_1LC1RF_---1LD_1RE0LA_1RA0RB_1RE0RF/py/rules.py > \
                                 holdouts/1RB0LA_1LC1RF_---1LD_1RE0LA_1RA0RB_1RE0RF/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(110)^n` is n copies of `110`.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LA_1LC1RF_---1LD_1RE0LA_1RA0RB_1RE0RF"
NS = "H169745"

RULES = [
    ("sweep", "L E> (110)^n R", "L (011)^n E> R",
     "The rightward sweep: E, B, F turn each word `110` into `011` (3 steps a word)."),
    ("carry", "L (011)^n A> 0 0 R", "L A> 0 0 (011)^n R",
     "The leftward zigzag: a gap `0 0` under A moves left through a run of `011`, 5 steps a word, so the run moves "
     "3 cells right."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
