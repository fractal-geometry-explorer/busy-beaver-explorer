"""Generate Rules.lean: the pieces of one round of 1RB1RC_1LC1LE_1RA1RD_0RF0RE_1LA0LB_---1RA, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right, `S>` is the head in state S on the next cell, `(01)^n` is n copies of `01`, R is
any tape.  A round starts at `0^inf A> 0 11 (01)^n R`; within the round the head sweeps between the left end and the
first `0 11` it meets, `0^inf C> (01)^k 0 11 (01)^j R`, each sweep taking two `01` from the right and adding three on
the left (see Macro.lean).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine, STATES  # noqa: E402
from bbtools.symtm import Blank, Config, Halted, prove, rules_file, run  # noqa: E402

M = "1RB1RC_1LC1LE_1RA1RD_0RF0RE_1LA0LB_---1RA"

RULES = [
    ("blank_start", "0^inf A> 0^inf", "0^inf A> 0 11 01 0^inf",
     "From blank tape the machine reaches the round start Z 1 in 10 steps."),
    ("entry", "0^inf A> 0 11 (01)^n R", "0^inf C> 01 0 11 (01)^n R",
     "The start of a round: the head turns at the `11` and comes back to the left end in state C."),
    ("pass", "0^inf C> (01)^k 0 11 (01)^j+2 R", "0^inf C> (01)^k+3 0 11 (01)^j R",
     "One sweep: two copies of `01` right of the `11` become three left of it."),
    ("endEven", "0^inf C> (01)^k 0 11 0 11 (01)^m 0^inf", "0^inf A> 0 11 (01)^k+1 0 11 (01)^m+2 0^inf",
     "No copy left: the two `11` merge into the next round start, the counter gains two copies."),
    ("endOdd", "0^inf C> (01)^k 0 11 01 0 11 (01)^m+1 0^inf", "0^inf A> 0 11 (01)^k+4 0 11 (01)^m 0^inf",
     "One copy left: the next round start, the counter loses one copy."),
    ("endOdd0", "0^inf C> (01)^k 0 11 01 0 11 0^inf", "0^inf A> 0 11 (01)^k+5 0^inf",
     "One copy left and an empty counter: the second `11` is used up (a round start Z)."),
    ("zOdd", "0^inf C> (01)^k 0 11 01 0^inf", "0^inf A> 0 11 (01)^k+1 0 11 01 0^inf",
     "Z, one copy left: a new counter of one copy."),
    ("zEven", "0^inf C> (01)^k 0 11 0^inf", "halt",
     "Z, no copy left: the head runs off the right end in state F, which halts on a 0."),
]


def before_halt(start):
    """The configuration the run from `start` halts in (head on a cell whose transition is undefined)."""
    m = Machine.parse(M)
    c = Config.parse(start)
    while True:
        prev = c.copy()
        try:
            run(m, c, lambda _: False, max_moves=1, rotate=True)
        except Halted:
            return prev
        except RuntimeError:
            pass


def main():
    ths = []
    for name, a, b, doc in RULES:
        if b == "halt":
            b = before_halt(a)
        ths.append(prove(M, name, a, b, doc=doc, rotate=True, max_seg=40)[0])
    ns = "H" + open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "Machine.lean")).read().split(
        "namespace H")[1].split()[0]
    sys.stdout.write(rules_file("Machine", ns, ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
