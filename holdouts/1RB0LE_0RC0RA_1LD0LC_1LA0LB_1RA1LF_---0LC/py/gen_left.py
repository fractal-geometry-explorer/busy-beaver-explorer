"""Write lean/LeftRules.lean: the carries into the irregular left part of 1RB0LE_0RC0RA_1LD0LC_1LA0LB_1RA1LF_---0LC,
proved for every length of the counter and of the wall by tools/py/bbtools/symtm.py.

The left parts L_0 .. L_17 (py/left_parts.json, left to right) are what the carries out of the 50-unit counter make
of the 28 cells left of it, in the run from blank tape: each carry into L_k (k < 17) turns L_k into L_{k+1}
(`fe_run k`); the carry into L_17 reaches the left end of the tape (`s1_run`): the counter becomes 24 blocks
`1^9 0 1 0` and the wall becomes a new counter of 2p+3 units.  `fo_run k` are the first carries into the new left
part L1 = P (1^9 0 1 0)^24 Q, with an odd counter; they only touch Q and the cells next to it (P B^24 is a context).

usage (from the repository root): python3 holdouts/<M>/py/gen_left.py   (writes lean/LeftRules.lean, lean/LeftParts.lean)"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../../../tools/py"))
from bbtools import symtm
from bbtools.machine import Machine

MS = "1RB0LE_0RC0RA_1LD0LC_1LA0LB_1RA1LF_---0LC"
M = Machine.parse(MS)
D = json.load(open(os.path.join(HERE, "left_parts.json")))
LS = D["even"]          # L_0 .. L_17, left to right
ODDQ = D["odd_q"]       # Q_0 .. Q_k: the right ends of L1 after 0..k carries (left of them: the context PB)

def probe(start, narr):
    c = symtm.Config.parse(start)
    cnt = [0]
    def stop(cfg):
        if cfg.state == 1 and cfg.right and isinstance(cfg.right[0], symtm.Blank) and not cfg.steps.is_zero():
            cnt[0] += 1
            return cnt[0] >= narr
        return False
    return symtm.run(M, c, stop, max_moves=400000)

def lit(s):
    return " ".join(s)

def rule(name, doc, start, narr):
    fin = probe(start, narr)
    t, _ = symtm.prove(M, name, start, fin, doc=doc, max_seg=30, count_first=True)
    return t, fin

def main():
    out = []
    infos = []
    for k in range(17):
        st = "0^inf %s (111110111011)^j+1 111110 10111 (010111)^n+1 B> 0^inf" % lit(LS[k])
        t, fin = rule("fe_run_%d" % k, "The carry out of an all-ones counter of 2j+2 units into L_%d." % k, st, 3)
        out.append(t); infos.append((k, str(fin), str(fin.steps)))
    st = "0^inf %s (111110111011)^j+1 111110 10111 (010111010111)^p+1 B> 0^inf" % lit(LS[17])
    t, fin = rule("s1_run", "The carry into L_17 runs to the left end of the tape: five sweeps.", st, 5)
    out.append(t); infos.append(("s1", str(fin), str(fin.steps)))
    for k in range(len(ODDQ) - 1):
        st = "PB %s 111011 (111110111011)^q+1 111110 10111 (010111)^n+1 B> 0^inf" % lit(ODDQ[k])
        t, fin = rule("fo_run_%d" % k, "Carry %d into L1, with an odd counter of 2q+3 units: only the cells of Q and "
                      "next to it change." % k, st, 3)
        out.append(t); infos.append(("o%d" % k, str(fin), str(fin.steps)))
    txt = symtm.rules_file("Machine", "H136111", out,
        "# The carries into the left part\n\nGenerated by `py/gen_left.py` with `tools/py/bbtools/symtm.py`; do not "
        "edit.  Every rule holds for all values of its variables (and every tape `PB`).")
    open(os.path.join(HERE, "../lean/LeftRules.lean"), "w").write(txt)
    for i in infos:
        print(i, file=sys.stderr)
    # the left parts as Lean lists, nearest the head first
    def nf(s):
        return "[" + ", ".join("true" if c == "1" else "false" for c in reversed(s)) + "]"
    L1 = D["L1"]
    P, Q, B = L1[:48], L1[-10:], L1[48:60]
    assert L1 == P + B * 24 + Q and B == "111111111010"
    parts = ["import Machine", "", "/-! # The left parts, as lists of cells nearest the counter first", "",
             "Generated by `py/gen_left.py` from `py/left_parts.json`; do not edit. -/", "", "namespace H136111", "",
             "/-- `L_k`, k = 0..17: the 28 to 36 cells left of the 50-unit counter after k carries into them. -/",
             "def lk : Nat → List Bool"]
    for k, l in enumerate(LS):
        parts.append("  | %d => %s" % (k, nf(l)))
    parts.append("  | _ => []")
    parts += ["", "/-- After the carry into L_17: L1 = P (1^9 0 1 0)^24 Q (here P, B = 1^9 0 1 0, Q). -/",
              "def pP : List Bool := " + nf(P), "def bB : List Bool := " + nf(B), "def qQ : List Bool := " + nf(Q), "",
              "/-- The right ends of L1 after 0..%d carries into it. -/" % (len(ODDQ) - 1), "def qk : Nat → List Bool"]
    for k, q in enumerate(ODDQ):
        parts.append("  | %d => %s" % (k, nf(q)))
    parts += ["  | _ => []", "", "end H136111", ""]
    open(os.path.join(HERE, "../lean/LeftParts.lean"), "w").write("\n".join(parts))

if __name__ == "__main__":
    main()
