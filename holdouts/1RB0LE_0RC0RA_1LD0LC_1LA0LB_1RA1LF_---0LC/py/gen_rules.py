"""Write lean/Rules.lean: the three sweeps of 1RB0LE_0RC0RA_1LD0LC_1LA0LB_1RA1LF_---0LC, proved for all lengths of the
wall and of the carry by tools/py/bbtools/symtm.py (single steps by `rfl`, runs of a repeated word by `TM.cross_l` /
`TM.cross_r`).

Units of six cells: X0 = 111110, X1 = 111011 (a bit), Y0 = 111011, Y1 = 111010, Y2 = 111111, Y3 = 111110 (two bits).
The wall: (101011)^n 1 B>0 (phase P), (111010)^n 111 B>0 (phase Q), (101110)^n 10111 B>0 (phase R), with the unit
next to it 111011 / 101010 / 111110.

usage (from the repository root): python3 holdouts/<M>/py/gen_rules.py > holdouts/<M>/lean/Rules.lean"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools import symtm

M = "1RB0LE_0RC0RA_1LD0LC_1LA0LB_1RA1LF_---0LC"
X0, X1 = "111110", "111011"
Y = ["111011", "111010", "111111", "111110"]
WR = "10111 (010111)^n B> 0^inf"           # phase R: the wall, nearest unit 111110 left of it
WR1 = "10111 (010111)^n 010111 B> 0^inf"   # the same wall one unit longer
RULES = [
    ("sweep_PQ", "Phase P to phase Q (one sweep): the head turns inside the unit next to the wall; nothing left of "
     "it changes.", "L 111011 (101011)^n 1 B> 0^inf", "L 101010 (111010)^n 111 B> 0^inf"),
    ("sweep_QR", "Phase Q to phase R (one sweep), the same.",
     "L 101010 (111010)^n 111 B> 0^inf", "L 111110 (101110)^n 10111 B> 0^inf"),
    ("cyc_x0", "Three sweeps from phase R to phase R when bit 0 is 0: `X0` becomes `X1`; the wall gains a unit.",
     "L %s 111110 %s" % (X0, WR), "L %s 111110 %s" % (X1, WR1)),
] + [
    ("cyc_y%d" % v, "Three sweeps from phase R to phase R with a carry over a last `X1` and `j` pairs `Y3 X1`, "
     "stopping at `Y%d`, which becomes `Y%d`; the passed units become `X0` and `Y0 X0`." % (v, v + 1),
     "L %s (%s%s)^j %s 111110 %s" % (Y[v], X1, Y[3], X1, WR), "L %s (%s%s)^j %s 111110 %s" % (Y[v + 1], X0, Y[0], X0, WR1))
    for v in range(3)
] + [
    ("cyc_x", "Three sweeps from phase R to phase R with a carry stopping at an `X0` above bit 0: it becomes `X1`; "
     "the passed `Y3`, the `j` pairs `X1 Y3` and the last `X1` become `Y0`, `X0 Y0` and `X0`.",
     "L %s %s (%s%s)^j %s 111110 %s" % (X0, Y[3], X1, Y[3], X1, WR), "L %s %s (%s%s)^j %s 111110 %s" % (X1, Y[0], X0, Y[0], X0, WR1)),
]

def arith_first(t):
    """Move the step-count arithmetic (`omega`) to the start of the proof, before the large hypotheses about tapes:
    `omega` scans every hypothesis in context, and with twenty configurations there it takes over a minute."""
    import re
    m = re.search(r"exact steps_congr trans \(a := (.*?)\) \(by omega\) ", t)
    if not m:
        return t
    total = re.search(r"theorem [^\n]*\n    steps \((.*?)\) ⟨", t).group(1)
    t = t.replace(m.group(0), "exact steps_congr trans (a := %s) harith " % m.group(1))
    return t.replace(":= by\n", ":= by\n  have harith : %s = %s := by omega\n" % (m.group(1), total), 1)

def main():
    thms = []
    for name, doc, a, b in RULES:
        t, fin = symtm.prove(M, name, a, b, doc=doc, max_seg=30)
        thms.append(arith_first(t))
    out = symtm.rules_file("Machine", "H136111", thms,
        "# The sweeps and the three-sweep cycles\n\nGenerated by `py/gen_rules.py` with `tools/py/bbtools/symtm.py`; do not "
        "edit.  Every rule holds for all values of its variables and every tape `L` left of it.")
    print(out)

if __name__ == "__main__":
    main()
