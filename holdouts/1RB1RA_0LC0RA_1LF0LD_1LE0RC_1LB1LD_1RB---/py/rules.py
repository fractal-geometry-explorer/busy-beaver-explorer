"""Generate lean/Rules.lean for 1RB1RA_0LC0RA_1LF0LD_1LE0RC_1LB1LD_1RB---: the shift rules of its sweeps, proved along symbolic runs
(tools/py/bbtools/symtm.py: single steps by `rfl`, a whole repeat crossed by `TM.cross_r` / `TM.cross_l`).

usage (from the repository root): python3 holdouts/1RB1RA_0LC0RA_1LF0LD_1LE0RC_1LB1LD_1RB---/py/rules.py > holdouts/1RB1RA_0LC0RA_1LF0LD_1LE0RC_1LB1LD_1RB---/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape.  Each rule holds for every n and every tape around it; README.md says where each one is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402

symtm.MAX_CARRY = 8  # some sweeps carry a word of up to 6 cells along with the head

M = "1RB1RA_0LC0RA_1LF0LD_1LE0RC_1LB1LD_1RB---"
NS = "H54596"

RULES = [
    ("a_1101", "L A> (1101)^n R", "L (1110)^n A> R",
     "Rightward: A turns each 1101 into 1110."),
    ("d_1101", "L (1101)^n D> 0 R", "L D> 0 (0111)^n R",
     "Leftward: D turns each 1101 into 0111."),
    ("a_110111", "L A> (110111)^n R", "L (111011)^n A> R",
     "Rightward: A turns each 110111 into 111011."),
    ("d_110111", "L (110111)^n D> 0 R", "L D> 0 (011101)^n R",
     "Leftward: D turns each 110111 into 011101."),
    ("d_11", "L (11)^n D> 0 R", "L D> 0 (01)^n R",
     "Leftward: D turns each 11 into 01."),
    # the words of the two periodic zones, written as pairs with the 0s on the left cell of a pair
    ("a_w0", "L A> (01011101011111011111)^n R", "L (10101110101111101111)^n A> R",
     "Rightward over the left zone (blocks 1 3 1 5 5): every 0 moves one cell right."),
    ("d_w0", "L (01011101011111011111)^n D> 0 R", "L D> 0 (11110111110101110101)^n R",
     "Leftward over the left zone: blocks 1 3 1 5 5 become 5 5 1 3 1 (pairs 01 -> 11, 11 -> 10)."),
    ("a_w1", "L A> (011101011101011101111101111101110111110111110111010111010111)^n R",
     "L (101110101110101110111110111110111011111011111011101011101011)^n A> R",
     "Rightward over the second zone (15 blocks 3 1 3 1 3 5 5 3 5 5 3 1 3 1 3): every 0 moves one cell right."),
    ("d_w1", "L (011101011101011101111101111101110111110111110111010111010111)^n D> 0 R",
     "L D> 0 (110111110111110111010111010111011101011101011101111101111101)^n R",
     "Leftward over the second zone: pairs 01 -> 11, 11 -> 10."),
    # single events
    ("a_zero", "L A> 0 1 R", "L 1 0 A> R",
     "Rightward: a single 0 moves one cell right."),
    ("a_z2", "L 1 A> 0 0 R", "L 1 0 A> 0 R",
     "Rightward: the head steps over the first of two 0s (7 steps, nothing changes)."),
    ("a_turn", "L 1 1 A> 0 0 0 R", "L 1 E> 1 1 0 0 R",
     "Right turn at three 0s (the right end of the tape, or three 0s inside it): the block grows by one cell."),
    ("e_bounce", "L 1 E> 0 R", "L 0 A> 1 R",
     "Defect, pair 10: it becomes 01 and the head turns right."),
    ("e_z2_pass", "L 0 1 0 E> 0 R", "L D> 0 0 0 1 R",
     "Defect, pairs 01 00: they become 10 01 (after D's next step) and the left sweep goes on."),
    ("e_z2_bounce", "L 1 1 0 E> 0 R", "L 1 0 1 0 A> R",
     "Defect, pairs 11 00: they become 10 10 and the head turns right."),
    ("e_end", "L 0 0 0 E> 0 R", "L 1 0 1 0 A> R",
     "Pairs 00 00 (the left end of the tape): they become 10 10 and the head turns right."),
    ("e_prehalt", "L 1 0 0 E> 0 R", "L F> 1 1 0 1 R",
     "Pairs 10 00: three steps later F reads a 1, the halting transition."),
]

DEEP = ("a_w1", "d_w1")


def main():
    ths = [symtm.prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    # the one-word runs of the 60-cell zone word are long `rfl` proofs: give the elaborator room
    ths = [("set_option maxRecDepth 20000 in\n" + t) if name in DEEP else t for t, (name, _, _, _) in zip(ths, RULES)]
    sys.stdout.write(symtm.rules_file("Machine", NS, ths, f"Sweep rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
