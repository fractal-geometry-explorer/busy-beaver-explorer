"""Event rules of 1RB0LD_1RC0RB_1RD1RF_1LE0LD_1RB1LA_---0RE, proved for all sizes
(python3 py/events.py lean > lean/Events.lean;  python3 py/events.py cov > c/rules.txt).

Event: the head in state E on cell 135 (cells counted from the start cell).  HAND (py/hand.py) are the rules written
by hand, MINED (py/mined.txt) the rules found by the batch's py/miner.py from the unmatched events of a run, each
proved for the sizes its repeats stand for.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "1RB---_1LC1RF_0LE0RD_0RB0LC_1RD0LD_0RC0RA", "py"))
from autoev import cov_line  # noqa: E402
from bbtools.symtm import prove, rules_file  # noqa: E402
from hand import HAND  # noqa: E402

M = "1RB0LD_1RC0RB_1RD1RF_1LE0LD_1RB1LA_---0RE"


def mined():
    out = []
    for ln in open(os.path.join(HERE, "mined.txt")):
        p = ln.rstrip("\n").split("|")
        if len(p) >= 4:
            out.append((p[0], p[1], p[2], f"Mined rule ({p[4] if len(p) > 4 else ''}): {p[3]} steps."))
    return out


def theorems():
    return [prove(M, "t_" + n, s, e, doc=d, rotate=True, count_first=True, max_seg=40, max_moves=200000)[0]
            for n, s, e, d in HAND + mined()]


if __name__ == "__main__":
    if sys.argv[1:] == ["cov"]:
        for n, s, e, d in HAND + mined():
            print(cov_line(n, s))
    else:
        sys.stdout.write(rules_file("Machine", "H18358", theorems(),
                                    f"Event rules of {M}, generated by `py/events.py`; do not edit by hand."))
