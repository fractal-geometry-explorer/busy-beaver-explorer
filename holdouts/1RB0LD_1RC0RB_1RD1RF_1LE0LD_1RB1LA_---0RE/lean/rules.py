"""Generate Rules.lean for 1RB0LD_1RC0RB_1RD1RF_1LE0LD_1RB1LA_---0RE: the halting context and the shift rules over the words of its tape, proved along the symbolic run of tools/py/bbtools/symtm.py
(single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LD_1RC0RB_1RD1RF_1LE0LD_1RB1LA_---0RE"

RULES = [
    ('halt_ctx', 'L C> 1 0 R', 'L 1 F> 0 R',
     'C on a 1 with a 0 after it hands F a 0 (the halting transition).'),
    ('back_A_110_1', 'L (110)^n A> 1 R', 'L A> 1 (110)^n R',
     'A crosses n copies of `110` to the left in 3n steps, leaving `110` (carrying `1`).'),
    ('run_B_1', 'L B> (1)^n R', 'L (0)^n B> R',
     'B crosses n copies of `1` to the right in 1n steps, leaving `0`.'),
    ('back_D_1_1', 'L (1)^n D> 1 R', 'L D> 1 (0)^n R',
     'D crosses n copies of `1` to the left in 1n steps, leaving `0` (carrying `1`).'),
    ('back_D_011_0', 'L (011)^n D> 0 R', 'L D> 0 (011)^n R',
     'D crosses n copies of `011` to the left in 3n steps, leaving `011` (carrying `0`).'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H18358", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
