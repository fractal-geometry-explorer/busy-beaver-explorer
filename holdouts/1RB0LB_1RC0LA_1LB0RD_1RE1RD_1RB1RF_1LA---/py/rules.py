#!/usr/bin/env python3
"""Shift rules (the sweeps across a run of one repeated word) of the eight G01 machines of worker group 1, proved in
Lean by `bbtools.symtm.prove`, written to holdouts/<M>/lean/Rules.lean.  Shared by the eight folders:

    python3 holdouts/1RB0LB_1RC0LA_1LB0RD_1RE1RD_1RB1RF_1LA---/py/rules.py          # rewrite all eight files
    python3 holdouts/1RB0LB_1RC0LA_1LB0RD_1RE1RD_1RB1RF_1LA---/py/rules.py --check  # compare with the files

For each machine and each rotation of the words its tape is made of, every state and every short word u that travels
with the head is tried: if one copy of the word takes the head across in the same state (`symtm.try_cross`), the rule
"the head crosses (w)^(n+1)" is proved for every n and every surrounding tape.  These are the steps every sweep of the
machine is built from (see each README)."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'py'))
from bbtools.symtm import Config, try_cross, prove
from bbtools.machine import Machine

MACHINES = {
    # family (a): tape (100)^n then runs 1^(6k+1) separated by 00
    '1RB0LC_1RC1RA_1LD0RE_1LA1LD_0RA0RF_0LD---': '10,100,110,1',
    '1RB0LC_1RC1RA_1LD0RE_1LA1LD_0RA1RF_0LC---': '10,100,110,1',
    '1RB0LC_1RC1RA_1RD0RF_0LE---_1LA1LE_0RA0RF': '10,100,110,1',
    '1RB0LE_1RC1RA_1LD0RE_1LA1LD_1LD0RF_0RA---': '10,100,110,1',
    # family (b): one machine, two start states; tape = runs of three 1s separated by single 0s, with markers
    '1RB0LB_1RC0LA_1LB0RD_1RE1RD_1RB1RF_1LA---': '0111,1000',
    '1RB0LC_1LA0RD_1RA0LA_1RE1RD_1RA1RF_1LC---': '0111,1000',
    # family (c): one machine, two start states, mirrored
    '1RB---_0RC0LA_1LD0RB_1LE0LF_1RC1LF_0LC0LB': '0111,1000',
    '1RB0LD_1RC0RF_1LA1RF_0LA0RE_1LD---_0RA0RD': '0111,1000',
}
TRAVEL = ['', '0', '1', '00', '01', '10', '11', '000', '001', '010', '011', '100', '101', '110', '111']


def rotations(w):
    return sorted(set(w[i:] + w[:i] for i in range(len(w))))


def find_rules(m, words):
    mach = Machine.parse(m)
    seen, rules = set(), []
    for w0 in words.split(','):
        for w in rotations(w0):
            for s in 'ABCDEF':
                for side in 'RL':
                    if (side, s, w) in seen:
                        continue
                    for u in TRAVEL:
                        us = ' '.join(u)
                        start = f"L {us} {s}> ({w})^n+1 R" if side == 'R' else f"L ({w})^n+1 {s}> {us} R"
                        c = Config.parse(' '.join(start.split()))
                        try:
                            x = try_cross(mach, c)
                        except Exception:
                            x = None
                        if x is None:
                            continue
                        seen.add((side, s, w))
                        rules.append((side, s, w, ' '.join(start.split()), repr(c).strip()))
                        break
    return rules


def lean_file(m):
    mf = open(os.path.join(ROOT, 'holdouts', m, 'lean', 'Machine.lean')).read()
    ns = re.search(r'^namespace (\S+)', mf, re.M).group(1)
    out = ['import Machine', '',
           f'/-! Shift rules of {m}: the head crossing a run of one repeated word.',
           'Generated by `py/rules.py` in the folder of the machine 1RB0LB_1RC0LA_1LB0RD_1RE1RD_1RB1RF_1LA (b1); do not edit by hand. -/', '',
           f'namespace {ns}', '', 'open TM', '']
    for i, (side, s, w, start, end) in enumerate(find_rules(m, MACHINES[m])):
        name = f"sweep_{'r' if side == 'R' else 'l'}_{s}_{w}"
        doc = (f"State {s} crosses (w)^(n+1), w = {w}, moving {'right' if side == 'R' else 'left'}: "
               f"`{start}` reaches `{end}`.")
        text, _ = prove(m, name, start, end, doc=doc)
        out.append(text)
        out.append('')
    out.append(f'end {ns}')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    check = '--check' in sys.argv
    bad = 0
    for m in MACHINES:
        path = os.path.join(ROOT, 'holdouts', m, 'lean', 'Rules.lean')
        text = lean_file(m)
        if check:
            if not os.path.exists(path) or open(path).read() != text:
                print('differs:', path); bad += 1
        else:
            open(path, 'w').write(text)
            print('wrote', path, text.count('theorem '), 'theorems')
    sys.exit(1 if bad else 0)
