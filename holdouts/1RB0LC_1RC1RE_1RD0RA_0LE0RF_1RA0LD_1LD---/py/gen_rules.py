"""Write lean/Rules.lean: the pieces of one sweep of 1RB0LC_1RC1RE_1RD0RA_0LE0RF_1RA0LD_1LD---, proved by
tools/py/bbtools/symtm.py (single steps by `rfl`, runs of a repeated word by `TM.cross_l` / `TM.cross_r`).
usage (from the repository root): python3 holdouts/<M>/py/gen_rules.py > holdouts/<M>/lean/Rules.lean"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools import symtm

M = "1RB0LC_1RC1RE_1RD0RA_0LE0RF_1RA0LD_1LD---"
RULES = [
    ("tail_left", "The sweep starts at the right end: `0 1 B>0` (blank beyond) becomes `D>0 0 0 1 0`, D on the "
     "separator of the last block.", "L 0 1 B> 0^inf", "L D> 0 0 0 1 0 0^inf"),
    ("left_odd", "Moving left over a block of `2n+1` ones: D on its right separator goes to its left separator; "
     "the block and the right separator become `0 0 (1 0)^n`.", "L 0 1 (11)^n D> 0 R", "L D> 0 0 0 (10)^n R"),
    ("left_even", "Moving left over a block of `2n+2` ones: E stops on the left separator, the block becomes "
     "`0 1 (0 1)^n 0`.", "L 0 (11)^n 11 D> 0 R", "L E> 0 0 1 (01)^n 0 R"),
    ("turn_zero", "The turn at a digit 0 (`1^2`): E writes 1 on the separator (merging with the block on its left) "
     "and A starts moving right with `1 1 1` in hand.", "L E> 0 0 1 0 R", "L 1 1 1 1 A> R"),
    ("turn_even", "The turn at a digit `2i+2` (`1^(6i+8)`): it becomes `1 1 1 0`, then `2i+1` blocks `1 1 0`, and "
     "A moves on with `1 1 1` in hand.", "L E> 0 0 1 010101 (010101)^i 0 R", "L 1110 110 (110110)^i 111 A> R"),
    ("right_odd", "Moving right over a block left by `left_odd` with `n = 3k+2` (digit `2k+1`): `1 1 1` in hand "
     "becomes `1 1 1 1 1 0`, then `2k` blocks `1 1 0`, and `1 1 1` in hand again.",
     "L 111 A> 0 0 1010 (101010)^k R", "L 111110 (110110)^k 111 A> R"),
    ("tail_right", "The right end again: `1 1 1` in hand and `0 0 1` becomes `1 1 1 1 1 0 1 B>0`.",
     "L 111 A> 0 0 1 0^inf", "L 11111 0 1 B> 0^inf"),
    ("carry3", "The left pass reaches the left end with the leftmost block `1^3` and a first digit `2k+1`: three cells "
     "are added on the left, the tape becomes `1^3` and `2k+2` zeros, and A moves right with `1 1 1` in hand.",
     "0^inf 111 D> 0 0 0 1010 (101010)^k R", "0^inf 111 0 110 110 (110110)^k 111 A> R"),
    ("carry9", "The left pass reaches the left end with the leftmost block `1^(6j+9)`: it becomes `1^3` and `2j+3` "
     "zeros, and A moves right with `1 1 1` in hand.",
     "0^inf 111111111 (111111)^j D> 0 R", "0^inf 111 0 11 0 11 0 11 0 (110110)^j 111 A> R"),
    ("phase2", "The other phase of the right end (`0 1^4 B>0`, after a carry at a leftmost block of even length): "
     "the last digit 1 becomes `2 0`.", "L 0 11111 0 1111 B> 0^inf", "L 0 11111111 0 11 0 1 B> 0^inf"),
]

def main():
    thms = []
    for name, doc, a, b in RULES:
        t, fin = symtm.prove(M, name, a, b, doc=doc, max_seg=30)
        thms.append(t)
    print(symtm.rules_file("Machine", "H115779", thms,
        "# The pieces of a sweep\n\nGenerated by `py/gen_rules.py` with `tools/py/bbtools/symtm.py`; do not edit.  "
        "Every rule holds for all values of its variables and all tapes `L`, `R` around it."))

if __name__ == "__main__":
    main()
