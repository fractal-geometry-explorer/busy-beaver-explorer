"""Generate lean/Rules.lean: rules of 1RB0RA_1RC0RF_1RD1LE_1RE---_1LF1LE_1RA0LE, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB0RA_1RC0RF_1RD1LE_1RE---_1LF1LE_1RA0LE)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RA_1RC0RF_1RD1LE_1RE---_1LF1LE_1RA0LE"

RULES = [
    ('e_l_01', 'L (01)^n E> 0 R', 'L E> 0 (01)^n R',
     'E sweeps left over copies of `01` (2 steps a copy).'),
    ('f_l_10', 'L (10)^n F> 1 R', 'L F> 1 (10)^n R',
     'F sweeps left over copies of `10` (2 steps a copy).'),
    ('f_l_1010101', 'L (1010101)^n F> 1 R', 'L F> 1 (1010110)^n R',
     'F sweeps left over copies of `1010101` (7 steps a copy).'),
    ('a_r_10101', 'L A> (10101)^n R', 'L (01010)^n A> R',
     'A sweeps right over copies of `10101` (5 steps a copy).'),
    ('f_l_10101', 'L (10101)^n F> 1 R', 'L F> 1 (10110)^n R',
     'F sweeps left over copies of `10101` (5 steps a copy).'),
    ('a_r_0101010', 'L A> (0101010)^n R', 'L (1010101)^n A> R',
     'A sweeps right over copies of `0101010` (7 steps a copy).'),
    ('f_l_101', 'L (101)^n F> 1 R', 'L F> 1 (110)^n R',
     'F sweeps left over copies of `101` (3 steps a copy).'),
    ('a_r_1', 'L A> (1)^n R', 'L (0)^n A> R',
     'A sweeps right over copies of `1` (1 step a copy).')
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H111043", thms,
                                "Rules of 1RB0RA_1RC0RF_1RD1LE_1RE---_1LF1LE_1RA0LE, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
