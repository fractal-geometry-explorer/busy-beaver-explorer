"""Generate lean/Rules.lean: the pieces of a round of 1RB1LF_1LC0RD_---1LA_0LA0RE_1LA1RA_1LB0LD, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right, `S>` the head in state S on the next cell, `1^n` n ones, `(0111)^k` k copies of
`0111`, `R` any tape, `0^inf` blank tape.

* `start`: a round starts at `D> 0 0 111 0 1^n T` at the left end of the tape; 60 steps later the sweeps start.
* `sweep0`, `sweep`: one sweep (the head runs to the block of ones on the right, takes three ones from it, and comes
  back; the tape grows one cell on the left).  The blocks `1110` (written `111 (0111)^k 0`) count the sweeps.
* `end_<t><c>`: the block of ones is down to c = 1, 2 or 3 and the tail is T = <t> (e: empty, a: 011, b: 010111):
  the head turns the counting blocks into ones and the next round starts with 4k + const ones.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LF_1LC0RD_---1LA_0LA0RE_1LA1RA_1LB0LD"
X = "0^inf A> 0 11 0 11 0 111 (0111)^k 0"
TAILS = {"e": "", "a": "011", "b": "010111"}

RULES = [
    ("start", "0^inf D> 0 0 111 0 1^n R", "0^inf A> 0 11 0 11 0 1^n+3 R",
     "A round starts: the head at the left end in state D, then 60 steps to the first sweep."),
    ("sweep0", "0^inf A> 0 11 0 11 0 1^m+4 R", f"0^inf A> 0 11 0 11 0 111 0 1 1^m R",
     "The first sweep: three ones of the block move into the first counting block `1110`."),
    ("sweep", f"{X} 1^m+4 R", "0^inf A> 0 11 0 11 0 111 (0111)^k+1 0 1 1^m R",
     "A sweep: three ones of the block become one more counting block; the tape grows by one cell on the left."),
]
for t, w in TAILS.items():
    for c in (1, 2, 3):
        RULES.append((f"end_{t}{c}", f"{X} {'1' * c} {w} 0^inf", None,
                      f"The end of a round: c = {c} ones left, tail `{w or 'empty'}`."))


def main():
    from bbtools.symtm import Config, run
    from bbtools.machine import Machine
    m = Machine.parse(M)
    ths = []
    for name, a, b, doc in RULES:
        if b is None:
            def stop(x):
                return (not x.steps.is_zero()) and x.state == 3 and len(x.left) == 1 and x.right[:5] == [0, 0, 1, 1, 1]
            fin = run(m, Config.parse(a), stop, max_moves=100000, rotate=True)
            b = fin
        ths.append(prove(M, name, a, b, doc=doc, rotate=True, count_first=True)[0])
    sys.stdout.write(rules_file("Machine", "H176107", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
