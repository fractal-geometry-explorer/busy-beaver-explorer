"""Generate lean/Rules.lean for 1RB1LE_1RC1LF_0RD1RD_1LE0RE_0LA0LB_---1LE: rounds proved along the symbolic run (tools/py/bbtools/symtm.py), for all
values of the counts and any tape R on the right that the round never reads.

usage: python3 rules.py > ../lean/Rules.lean

A round starts with the head in state E on the blank cell at the left end of the tape and ends the next time
the head is there in that state.  `(w)^n` is n copies of the word w.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Blank, Config, STATES, prove, rules_file, run  # noqa: E402

M = "1RB1LE_1RC1LF_0RD1RD_1LE0RE_0LA0LB_---1LE"
S = "E"
NS = "H" + open(os.path.join(HERE, "..", "lean", "Machine.lean")).read().split("namespace H")[1].split()[0]


def run_to(start, count=1):
    m = Machine.parse(M)
    cfg = Config.parse(start)
    left, first = [count], [True]

    def stop(c):
        if first[0]:
            first[0] = False
            return False
        if c.state == STATES.index(S) and len(c.left) == 1 and isinstance(c.left[0], Blank):
            left[0] -= 1
            return left[0] == 0
        return False

    run(m, cfg, stop, max_moves=200000, rotate=True)
    return cfg


RULES = [
    ('inc0', '0^inf E> 0 (110)^n+3 1 0 (110)^m+3 R',
     'Digit 0 (`10`) becomes digit 1 (`1`); the run of pairs before it gains one.'),
    ('inc1', '0^inf E> 0 (110)^n+3 1 (110)^m+3 R',
     'Digit 1 (`1`) becomes digit 2 (`101`); the pairs before it gain one, the pairs after it lose one.'),
    ('inc2', '0^inf E> 0 (110)^n+3 1 0 1 (110)^m+3 R',
     'Digit 2 (`101`) becomes digit 3 (`11`).'),
    ('carry0', '0^inf E> 0 (110)^n+3 1 1 (110)^m+3 1 0 (110)^p+3 R',
     'Digit 3 (`11`) wraps to 0 and the next digit, 0, becomes 1.'),
    ('carry1', '0^inf E> 0 (110)^n+3 1 1 (110)^m+3 1 (110)^p+3 R',
     'Digit 3 wraps to 0 and the next digit, 1, becomes 2.'),
    ('carry2', '0^inf E> 0 (110)^n+3 1 1 (110)^m+3 1 0 1 (110)^p+3 R',
     'Digit 3 wraps to 0 and the next digit, 2, becomes 3.'),
]


def main():
    ths = []
    for name, start, doc in RULES:
        end = run_to(start)
        th, _ = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=40)
        ths.append(th)
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rounds of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
