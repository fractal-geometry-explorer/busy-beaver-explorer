"""Generate lean/Chain.lean for 1RB1LE_1RC1LF_0RD1RD_1LE0RE_0LA0LB_---1LE: the E-chain, the only way to the halting
transition F0.

usage: python3 chain.py > ../lean/Chain.lean

With the head in state E on the last 1 of a run of c ones, E1 -> 0LB, B1 -> 1LF, F1 -> 1LE turn each 111 (read from
the right) into 110 in 3 steps.  What happens when the run is used up depends on c mod 3: c = 3k+3 ends in E on the
0 before the run (then E0 -> 0LA), c = 3k+4 ends with B on that 0 (B0 -> 1RC), and c = 3k+5 ends with F on that 0,
which is the halting transition (see `step_none_iff` in Blank.lean).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LE_1RC1LF_0RD1RD_1LE0RE_0LA0LB_---1LE"
NS = "H" + open(os.path.join(HERE, "..", "lean", "Machine.lean")).read().split("namespace H")[1].split()[0]

RULES = [
    ('chain0', 'L 0 (111)^k 1 1 E> 1 R', 'L E> 0 1 1 0 (110)^k R',
     'A run of 3k+3 ones: the chain ends in state E on the 0 before it (E0 -> 0LA follows).'),
    ('chain1', 'L 0 1 (111)^k 1 1 E> 1 R', 'L B> 0 0 1 1 0 (110)^k R',
     'A run of 3k+4 ones: the chain ends in state B on the 0 before it (B0 -> 1RC follows).'),
    ('chain2', 'L 0 1 1 (111)^k 1 1 E> 1 R', 'L F> 0 1 0 1 1 0 (110)^k R',
     'A run of 3k+5 ones: the chain ends in state F on the 0 before it, which halts.'),
]


def main():
    ths = []
    for name, start, end, doc in RULES:
        th, _ = prove(M, name, start, end, doc=doc)
        ths.append(th)
    sys.stdout.write(rules_file("Machine", NS, ths, f"The E-chain of {M}, generated by `py/chain.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
