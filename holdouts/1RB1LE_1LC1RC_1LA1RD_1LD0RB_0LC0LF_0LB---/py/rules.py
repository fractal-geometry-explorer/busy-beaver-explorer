"""Generate lean/Rules.lean: the sub-rounds of 1RB1LE_1LC1RC_1LA1RD_1LD0RB_0LC0LF_0LB---, proved along the symbolic
run (tools/py/bbtools/symtm.py), for all values of the counts and any tape R on the right.

usage: python3 rules.py > ../lean/Rules.lean

A sub-round starts with the head in state B on the blank cell left of `0 0 1^X 0 ...` and ends the next time
the head is there in state B.  `(w)^n` is n copies of the word w; R is any tape (the run never looks at it).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Blank, Config, STATES, prove, rules_file, run  # noqa: E402

M = "1RB1LE_1LC1RC_1LA1RD_1LD0RB_0LC0LF_0LB---"


def run_to(start, count):
    m = Machine.parse(M)
    cfg = Config.parse(start)
    left, first = [count], [True]

    def stop(c):
        if first[0]:
            first[0] = False
            return False
        if c.state == STATES.index("B") and len(c.left) == 1 and isinstance(c.left[0], Blank):
            left[0] -= 1
            return left[0] == 0
        return False

    run(m, cfg, stop, max_moves=200000, rotate=True)
    return cfg


RULES = [
    ("absorb", "0^inf B> 0 0 0 (111)^x+3 1 1 0 (110)^k+3 R", 1,
     "Absorption: `1^X 0 (110)^k` with X = 3x + 11 becomes `1^(X+9) 0 (110)^(k-2)`."),
    ("convert", "0^inf B> 0 0 0 (111)^x+3 0 R", 2,
     "Conversion, X = 3x + 9: the block of ones becomes `1^4 0 1 (101)^(x+3) 1 1`, i.e. pairs `110` to absorb."),
]


def main():
    ths = []
    for name, start, count, doc in RULES:
        end = run_to(start, count)
        th, _ = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=40)
        ths.append(th)
    sys.stdout.write(rules_file("Machine", NS, ths, f"Sub-rounds of {M}, generated by `py/rules.py`; do not edit by hand."))


NS = "H" + open(os.path.join(HERE, "..", "lean", "Machine.lean")).read().split("namespace H")[1].split()[0]

if __name__ == "__main__":
    main()
