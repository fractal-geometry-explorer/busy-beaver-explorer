"""Writes lean/Rules.lean: the shift rule of the feeding rules of 1RB1RF_1RC0RE_1LD0RB_1RE0LC_1RA0LE_0RC---,
proved by bbtools.symtm from a symbolic trace (shift rules, `rfl`, `omega`).  lean/Phase.lean restates and iterates it.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove

M = "1RB1RF_1RC0RE_1LD0RB_1RE0LC_1RA0LE_0RC---"
NS = "H75404"
RULES = [
    ("feed0", "One visit of the right end with cursor 0: `L (01)^(k+1) 0 (01)^m 0 B> 0^inf` becomes "
     "`L (01)^k 1 (01)^(m+2) 0 B> 0^inf` (as the run writes it: `L (01)^k 1 0 1 0 (10)^m 1 0 B> 0^inf`), in 4m+18 steps.",
     "L (01)^k+1 0 (01)^m 0 B> 0^inf", "L (01)^k 1 (01)^m+2 0 B> 0^inf"),
    ("feed1", "The same with cursor 1: `L (01)^(k+1) 1 (01)^m 0 B> 0^inf` becomes `L (01)^k 0 (01)^(m+2) 0 B> 0^inf` "
     "(as the run writes it: `L (01)^k 0 0 1 0 (10)^m 1 0 B> 0^inf`), in 4m+10 steps.",
     "L (01)^k+1 1 (01)^m 0 B> 0^inf", "L (01)^k 0 (01)^m+2 0 B> 0^inf"),
]


def main():
    out = ["import Machine", "", f"/-! Rules of {M}, generated by `py/rules.py`; do not edit by hand. -/", "",
           f"namespace {NS}", "", "open TM", ""]
    for name, doc, start, end in RULES:
        t, f = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=60)
        out += [t, ""]
    out.append(f"end {NS}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
