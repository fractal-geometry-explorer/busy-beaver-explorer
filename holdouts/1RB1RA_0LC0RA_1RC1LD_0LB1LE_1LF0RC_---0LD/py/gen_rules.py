"""Generate lean/Rules.lean for 1RB1RA_0LC0RA_1RC1LD_0LB1LE_1LF0RC_---0LD: sweep rules for all n, each proved by a symbolic run of bbtools.symtm.

L and R are arbitrary tapes the sweep does not look at.

usage: python3 py/gen_rules.py > lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "..", "tools", "py"))
from bbtools import symtm  # noqa: E402

M = "1RB1RA_0LC0RA_1RC1LD_0LB1LE_1LF0RC_---0LD"
NS = "H152765"
RULES = [
    ('sweep_r_B_110', '`L B> (110)^n R` to `L (011)^n B> R` in 3*n steps.',
     'L B> (110)^n R',
     'L (011)^n B> R'),
    ('sweep_l_B_110', '`L (110)^n 1 1 B> 0 R` to `L D> 1 (011)^n 1 0 R` in 3*n+2 steps.',
     'L (110)^n 1 1 B> 0 R',
     'L D> 1 (011)^n 1 0 R'),
    ('sweep_l_E_110', '`L (110)^n 1 1 E> 0 R` to `L D> 1 (011)^n 0 1 R` in 3*n+2 steps.',
     'L (110)^n 1 1 E> 0 R',
     'L D> 1 (011)^n 0 1 R'),
    ('sweep_l_D_100', '`L (100)^n 1 0 D> 0 R` to `L C> 1 (001)^n 0 0 R` in 3*n+2 steps.',
     'L (100)^n 1 0 D> 0 R',
     'L C> 1 (001)^n 0 0 R'),
    ('sweep_l_B_010', '`L (010)^n 0 1 B> 0 R` to `L D> 0 (100)^n 1 0 R` in 3*n+2 steps.',
     'L (010)^n 0 1 B> 0 R',
     'L D> 0 (100)^n 1 0 R'),
    ('sweep_l_E_010', '`L (010)^n 0 1 E> 0 R` to `L D> 0 (100)^n 0 1 R` in 3*n+2 steps.',
     'L (010)^n 0 1 E> 0 R',
     'L D> 0 (100)^n 0 1 R'),
    ('sweep_r_A_011', '`L A> (011)^n R` to `L (101)^n A> R` in 3*n steps.',
     'L A> (011)^n R',
     'L (101)^n A> R'),
    ('sweep_l_C_011', '`L (011)^n 0 1 C> 1 R` to `L E> 0 (101)^n 1 1 R` in 3*n+2 steps.',
     'L (011)^n 0 1 C> 1 R',
     'L E> 0 (101)^n 1 1 R'),
    ('sweep_l_F_011', '`L (011)^n 0 1 F> 1 R` to `L E> 0 (101)^n 1 0 R` in 3*n+2 steps.',
     'L (011)^n 0 1 F> 1 R',
     'L E> 0 (101)^n 1 0 R'),
    ('sweep_r_A_1', '`L A> (1)^n R` to `L (1)^n A> R` in n steps.',
     'L A> (1)^n R',
     'L (1)^n A> R'),
    ('sweep_r_B_10', '`L B> (10)^n R` to `L (01)^n B> R` in 2*n steps.',
     'L B> (10)^n R',
     'L (01)^n B> R'),
    ('sweep_r_A_01', '`L A> (01)^n R` to `L (10)^n A> R` in 2*n steps.',
     'L A> (01)^n R',
     'L (10)^n A> R'),
]

if __name__ == "__main__":
    ts = []
    for name, doc, start, end in RULES:
        t, _ = symtm.prove(M, name, start, end, count_first=True, doc=doc)
        ts.append(t)
    print(symtm.rules_file("Machine", NS, ts, "Sweep rules of " + M + ", generated by `py/gen_rules.py` (do not edit)."), end="")
