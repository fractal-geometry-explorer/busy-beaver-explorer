"""The marker period of 1RB1RA_0LC0RA_1RC1LD_0LB1LE_1LF0RC_---0LD, checked by a symbolic run of bbtools.symtm.

Words: a = 110, b = 100.  In the second phase of a round the tape is

    0^inf D> 0 b 1 0 1 a b^k 1 0 a^x 1 a 0 a^y 0^inf

(the marker `1 a 0` = 11100 between the two runs of a's).  `period`: from x + 27 the machine reaches the same shape
with k + 3, x, y + 27, for all k, x, y (the end configuration is written as the run reaches it; the a's are
re-bracketed, `TM.rep_rotate`).

The symbolic run (for all k, x, y) succeeds and gives 324k + 162x + 3629 steps.  `--lean` prints the Lean
theorem it produces (about 940 KB); that file does not yet check: the kernel hits a deterministic timeout even
with the first 6 of the 27 a's alone, so it is not part of lean/check.sh (see README, For later).

usage: python3 py/gen_period.py            # symbolic check
       python3 py/gen_period.py --lean     # print the (unchecked) Lean file
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "..", "tools", "py"))
from bbtools import symtm  # noqa: E402

M = "1RB1RA_0LC0RA_1RC1LD_0LB1LE_1LF0RC_---0LD"
START = "0^inf D> 0 1 0 0 1 0 1 1 1 0 (100)^k 1 0 (110)^x+27 1 1 1 0 0 (110)^y 0^inf"
END = "0^inf D> 0 1 0 0 1 0 1 1 1 0 (100)^k+3 1 0 (110)^x 1 1 1 0 0 (110)^y+27 0^inf"

if __name__ == "__main__":
    t, fin = symtm.prove(M, "period", START, END, rotate=True, count_first=True, max_seg=25, max_moves=200000,
                         doc="The marker period: 27 a's pass the marker and three b's are added at the left end.")
    if "--lean" in sys.argv:
        print(symtm.rules_file("Machine", "H152765", [t], "The marker period of " + M + ", generated by `py/gen_period.py`."), end="")
    else:
        print("period: symbolic run from", START)
        print("     reaches", fin)
        print("       steps", fin.steps)
