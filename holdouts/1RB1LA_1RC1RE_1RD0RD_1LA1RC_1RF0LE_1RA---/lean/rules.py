"""Generate Rules.lean: the crossings of the blocks of 1RB1LA_1RC1RE_1RD0RD_1LA1RC_1RF0LE_1RA---, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(101011)^n` is n copies of the
word u = 101011 of ../README.md, L and R are any tapes.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LA_1RC1RE_1RD0RD_1LA1RC_1RF0LE_1RA---"

RULES = [
    ("cross_u", "L D> (101011)^n R", "L (111110)^n D> R",
     "A block of n words u is crossed rightwards in D, 6 steps a word, each u becoming 111110.", {}),
    ("cross_u'", "L D> (111110)^n R", "L (101011)^n D> R",
     "And back: the next crossing in D restores the words u.", {}),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, count_first=True, max_seg=60, **kw)[0] for name, a, b, doc, kw in RULES]
    out = rules_file("Machine", "H60438", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
