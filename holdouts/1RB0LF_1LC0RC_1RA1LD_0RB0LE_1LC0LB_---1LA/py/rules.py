"""Writes lean/Rules.lean: shift rules of this machine's sweeps and the shape of a halt, proved by
tools/py/bbtools/symtm.py (`prove`).  Usage: python3 py/rules.py > lean/Rules.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LF_1LC0RC_1RA1LD_0RB0LE_1LC0LB_---1LA"
NS = "H153488"
RULES = [
    ('a_right', 'L 0 1 A> (110110)^n R', 'L (110110)^n 0 1 A> R',
     'Rightward, A (with 01 behind it) crosses the 110 sea two triples at a time, 16 steps per 6 cells.', {}),
    ('d_left', 'L (110)^n D> 1 R', 'L D> 1 (110)^n R',
     'Leftward, D crosses (110)^n, 3 steps a triple.', {}),
    ('c_left', 'L (101)^n C> 1 R', 'L C> 1 (101)^n R',
     'Leftward, C crosses the same sea in the other phase.', {}),
    ('e_left', 'L (011)^n E> 0 R', 'L E> 0 (011)^n R',
     'Leftward, E crosses it in the third phase.', {}),
    ('halt_shape', 'L 0 1 F> 1 R', 'L F> 0 0 1 R',
     'The only way to a halt: F on a 1 with 1 0 to its left reaches F on a 0 (which halts) in 2 steps.', {}),
]
HALT = "F"
HSYM = "0"

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d, **kw)[0] for n, s, e, d, kw in RULES]
    extra = (f"/-- {HALT} reading a {HSYM} halts (the end of `halt_shape`). -/\n"
             f"theorem halt_after_shape (L R : Tape) : step ⟨L, cons false R, .{HALT}⟩ = none := rfl\n")
    print(rules_file("Machine", NS, thms + [extra],
                     f"# {M}: shift rules of the sweeps and the shape of a halt\n\n"
                     "Generated by `py/rules.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `n` and all "
                     "tapes `L`, `R`."))
