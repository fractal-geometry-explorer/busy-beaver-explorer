"""Write lean/Rules.lean: rules of 1RB1LC_1LC0RD_0LE1LA_---1RA_1RF0LA_0RF0RB proved by bbtools.symtm, for all values of their counts.

usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/1RB1LC_1LC0RD_0LE1LA_---1RA_1RF0LA_0RF0RB/py/gen_rules.py
"""
import os
from bbtools import symtm
from bbtools.machine import Machine

M = "1RB1LC_1LC0RD_0LE1LA_---1RA_1RF0LA_0RF0RB"
RULES = [
    ("left", "left-end transfer: C at the left end of 1^(2k+4) 0 0 1^b moves two 1s of the left block into three of the right one",
     "0^inf C> (11)^k+2 0 0 1^b R", "0^inf C> 1 1 (11)^k 0 0 1 1 1 1^b R"),
    ("sweep", "one sweep of the hole: the middle block 1^(2w+5) loses four 1s, the left block gains one, the right block three",
     "L 0 0 0 1 A> (11)^w+2 0 0 R", "L 1 0 0 0 1 A> (11)^w 0 0 1 1 1 R"),
    ("end3", "the middle block is down to three 1s: the hole closes, the left block gains two 1s and the right one three",
     "L 0 0 0 1 A> 1 1 0 0 R", "L 1 1 0 0 B> 0 1 1 1 R"),
    ("walk", "the travelling hole: the pair 0 1 ahead of state A moves right through a block of 1s, five steps a cell",
     "L 0 1 A> 1^n 1 R", "L 1^n 0 1 A> 1 R"),
    ("e_g2", "state E at a 00 hole with at least four 1s after it: one 1 goes to the left block and the hole starts to travel",
     "L E> 0 0 1 1 1 1 R", "L 1 0 0 A> 0 1 1 R"),
    ("e_one", "state E at a 00 hole followed by a single 1: the 1 and the next block merge, the left block gains two",
     "L E> 0 0 1 0 0 1 1 R", "L 1 1 E> 0 0 1 1 1 R"),
    ("e_three", "state E at a 00 hole followed by three 1s: the left block is closed by a single 0, and the three 1s join the next block",
     "L E> 0 0 1 1 1 0 0 1 R", "L 1 0 E> 0 0 1 1 1 1 R"),
    ("g2_odd", "the hole has reached the end of an odd block next to a 00 gap: the head returns to the gap as state E; three 1s are added on the right",
     "L 0 0 (11)^k 1 A> 0 1 1 0 0 R", "L E> 0 0 (11)^k 1 0 0 1 1 1 R"),
    ("halt_start", "a round start whose block is a single 1 runs into the halting transition D0 after 8 steps",
     "0^inf A> 0 0 0 1 0 0 R", "0^inf 1 0 1 1 0 D> 0 0 R"),
    ("halt_a", "state A on a 0 followed by an isolated 1: two steps to the halting transition D0",
     "L A> 0 1 0 R", "L 1 0 D> 0 R"),
    ("halt_f", "state F on a block of exactly two 1s: two steps to the halting transition D0",
     "L F> 1 1 0 R", "L 0 0 D> 0 R"),
]


def main():
    m = Machine.parse(M)
    thms = [symtm.prove(m, name, s, e, doc=doc, rotate=True)[0] for name, doc, s, e in RULES]
    out = symtm.rules_file("Machine", "H96840", thms, "Rules of " + M + ", generated by `py/gen_rules.py` with `bbtools.symtm`.")
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lean", "Rules.lean"), "w") as f:
        f.write(out)


if __name__ == "__main__":
    main()
