"""Generate Rules.lean: the rules of 1RB0RE_1LC1LD_0RA0LD_1LB0LA_1RF1RA_---1LB, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(01)^n` is n copies
of `01`, `0^inf` blank tape, R any tape.  In the README:
  D(k, y, z) = 0^inf (01)^(k+1) D> 1^(y+1) (10)^z 1 0^inf
  A(m, z)    = 0^inf A> 1^m (10)^z 1 0^inf
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC1LD_0RA0LD_1LB0LA_1RF1RA_---1LB"

RULES = [
    ("start", "0^inf A> 0^inf", "0^inf 0 1 D> 1 (10)^5 1 0^inf",
     "From blank tape the run reaches D(0, 0, 5) after 136 steps."),
    ("d_step", "0^inf (01)^k+2 D> 1^y+2 0 R", "0^inf (01)^k+1 D> 1^y+5 0 R",
     "D(k+1, y, z) -> D(k, y+3, z): one `01` of the left block is traded for three ones on the right."),
    ("d_zero", "0^inf 0 1 D> 1^y+2 0 R", "0^inf A> 1^y+4 0 R",
     "D(0, y, z) -> A(y+3, z): the left block is used up and A starts at the left end."),
    ("a_odd", "0^inf A> (11)^k 1 (10)^z+2 1 0^inf", "0^inf (01)^k+1 D> 1 (10)^z+1 1 0^inf",
     "A(2k+1, z+2) -> D(k, 0, z+1): A halves the block of ones; one `10` of fuel is used."),
    ("a_odd_one", "0^inf A> (11)^k 1 1 0 1 0^inf", "0^inf (01)^k+1 D> 1 1 0^inf",
     "A(2k+1, 1) -> D(k, 0, 0)."),
    ("a_even", "0^inf A> (11)^k+1 (10)^z+3 1 0^inf", "0^inf (01)^k+3 D> 1 (10)^z+1 1 0^inf",
     "A(2k+2, z+2) -> D(k+2, 0, z) (shown for z >= 1)."),
    ("a_even_two", "0^inf A> (11)^k+1 1 0 1 0 1 0^inf", "0^inf (01)^k+3 D> 1 1 0^inf",
     "A(2k+2, 2) -> D(k+2, 0, 0)."),
    ("reset_odd", "0^inf A> (11)^k 1 1 0^inf", "0^inf 0 1 D> 1 (10)^k+1 1 0^inf",
     "A(2k+1, 0) -> D(0, 0, k+1): out of fuel with an odd block: the block becomes the new fuel."),
    ("reset_even", "0^inf A> (11)^k+1 1 0 1 0^inf", "0^inf 0 1 D> 1 (10)^k+3 1 0^inf",
     "A(2k+2, 1) -> D(0, 0, k+3): one `10` of fuel left with an even block: the block becomes the new fuel."),
    ("halt_even", "0^inf A> (11)^k+1 1 0^inf", "0^inf (01)^k+2 F> 0^inf",
     "A(2k+2, 0) reaches F on a 0, the halting transition: out of fuel with an even block, the machine halts."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=30)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H48709", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
