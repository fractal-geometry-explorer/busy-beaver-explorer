"""Generate lean/Rules.lean: the pieces of a round of 1RB0LA_0RC---_0RD0RF_1LD0LE_0LA1LE_1RA0RE, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage (from the repo root):  python3 holdouts/1RB0LA_0RC---_0RD0RF_1LD0LE_0LA1LE_1RA0RE/py/rules.py > \
                                 holdouts/1RB0LA_0RC---_0RD0RF_1LD0LE_0LA1LE_1RA0RE/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(11)^n` is n copies
of `11`, `0^inf` blank tape, L and R any tape.  How the pieces make a round: README.md ("A round").
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LA_0RC---_0RD0RF_1LD0LE_0LA1LE_1RA0RE"

RULES = [
    ("start", "0^inf E> 0 1 1 1 R", "0^inf 1 0 A> 0 0 1 R",
     "A round starts: the first two ones of the first block become the pair of 0s that the sweep pushes along."),
    ("pair", "L A> 0 0 1 1 1 R", "L 1 0 A> 0 0 1 R",
     "One step of the sweep: the pair of 0s moves two cells right and leaves `1 0` behind (6 steps). The run looks "
     "at the cell after the pair, so the sweep over many pairs is proved by induction (`sweep` in Round.lean)."),
    ("endodd", "L A> 0 0 1 0 1^a+3 0 1 R", "L 1 E> 0 1^a+2 0 1 1 1 1 R",
     "The sweep reaches the end of an odd block: F fills the hole, the pair of 0s becomes a glider, which crosses "
     "the second block and moves the next hole 3 cells left; E returns to the pairs."),
    ("glide", "L 0 0 D> 1^n R", "L 1^n 0 0 D> R",
     "The glider: a pair of 0s moves right through a block of ones, one cell every 5 steps."),
    ("cycle", "L 1 0 1 0 1 E> 0 1^p+2 0 1 R", "L 1 E> 0 1^p+3 0 1 1 1 1 R",
     "One glider of the round: two `1 0` pairs make a new glider, which runs to the hole; the hole moves 3 cells "
     "left, the block before it gains one cell."),
    ("last", "0^inf 1 0 1 E> 0 1^p+2 0 1 R", "0^inf E> 0 1^p+3 0 1 1 1 1 R",
     "The last glider, made from the last pair at the left end: the round ends with E at the left end."),
    ("last2", "0^inf 1 0 1 0 1 E> 0 1^p+4 0 1 R", "0^inf E> 0 1^p+5 0 1 1 1 1 1 1 1 R",
     "The end of a round with an odd number of pairs: the last pairs make a glider, and the two 0s left at "
     "the left end make one more; both move the hole 3 cells left."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H25624", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
