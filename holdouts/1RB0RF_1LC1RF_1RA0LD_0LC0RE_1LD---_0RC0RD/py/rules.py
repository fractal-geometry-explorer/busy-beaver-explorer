"""Generate lean/Rules.lean: rules of 1RB0RF_1LC1RF_1RA0LD_0LC0RE_1LD---_0RC0RD, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB0RF_1LC1RF_1RA0LD_0LC0RE_1LD---_0RC0RD)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RF_1LC1RF_1RA0LD_0LC0RE_1LD---_0RC0RD"

RULES = [
    ('f_r_0001', 'L F> (0001)^n R', 'L (0111)^n F> R',
     'F sweeps right over copies of `0001` (4 steps a copy).'),
    ('c_r_0010', 'L C> (0010)^n R', 'L (1110)^n C> R',
     'C sweeps right over copies of `0010` (4 steps a copy).'),
    ('a_r_0100', 'L A> (0100)^n R', 'L (1101)^n A> R',
     'A sweeps right over copies of `0100` (4 steps a copy).'),
    ('b_r_1000', 'L B> (1000)^n R', 'L (1011)^n B> R',
     'B sweeps right over copies of `1000` (4 steps a copy).'),
    ('d_l_1101', 'L (1101)^n D> 0 R', 'L D> 0 (1000)^n R',
     'D sweeps left over copies of `1101` (6 steps a copy).'),
    ('c_l_1110', 'L (1110)^n C> 1 R', 'L C> 1 (0100)^n R',
     'C sweeps left over copies of `1110` (6 steps a copy).'),
    ('c_l_0111', 'L (0111)^n C> 1 R', 'L C> 1 (0100)^n R',
     'C sweeps left over copies of `0111` (18 steps a copy).'),
    ('d_l_0111', 'L (0111)^n D> 0 R', 'L D> 0 (0010)^n R',
     'D sweeps left over copies of `0111` (6 steps a copy).')
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H58767", thms,
                                "Rules of 1RB0RF_1LC1RF_1RA0LD_0LC0RE_1LD---_0RC0RD, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
