"""Generate lean/Rules.lean for 1RB0RF_1RC1RE_0LD---_1LE1LD_1RF0RF_0RA0LB: the shift rules of its sweeps, proved along symbolic runs
(tools/py/bbtools/symtm.py: single steps by `rfl`, a whole repeat crossed by `TM.cross_r` / `TM.cross_l`).

usage (from the repository root): python3 holdouts/1RB0RF_1RC1RE_0LD---_1LE1LD_1RF0RF_0RA0LB/py/rules.py > holdouts/1RB0RF_1RC1RE_0LD---_1LE1LD_1RF0RF_0RA0LB/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape.  Each rule holds for every n and every tape around it; README.md says where each one is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402

symtm.MAX_CARRY = 8  # some sweeps carry a word of up to 6 cells along with the head

M = "1RB0RF_1RC1RE_0LD---_1LE1LD_1RF0RF_0RA0LB"
NS = "H143478"

RULES = [
    ("f_ones", "L 1 F> (1)^n R", "L (1)^n 1 F> R",
     "Rightward: F crosses a block of ones (3 steps a cell)."),
    ("d_ones", "L (1)^n D> 1 R", "L D> 1 (1)^n R",
     "Leftward: D crosses a block of ones."),
    ("f_01", "L F> (01)^n R", "L (00)^n F> R",
     "Rightward: F erases the ones of a run of 01."),
    ("d_1110", "L (1110)^n D> 1 R", "L D> 1 (1101)^n R",
     "Leftward: D turns each 1110 into 1101."),
    ("f_0111", "L 0 F> (0111)^n R", "L (1110)^n 0 F> R",
     "Rightward: F, a 0 behind it, turns each 0111 into 1110."),
]


def main():
    ths = [symtm.prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(symtm.rules_file("Machine", NS, ths, f"Sweep rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
