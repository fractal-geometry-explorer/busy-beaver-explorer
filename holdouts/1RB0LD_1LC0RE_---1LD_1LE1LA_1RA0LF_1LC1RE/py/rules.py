"""Shift rules of 1RB0LD_1LC0RE_---1LD_1LE1LA_1RA0LF_1LC1RE, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LD_1LC0RE_---1LD_1LE1LA_1RA0LF_1LC1RE/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L 1 0 C> (10)^n R` is the head
in state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LD_1LC0RE_---1LD_1LE1LA_1RA0LF_1LC1RE"
NS = "H152404"
DOC = """# Shift rules of 1RB0LD_1LC0RE_---1LD_1LE1LA_1RA0LF_1LC1RE

Two fast moves of the machine over the alternating background `1010...` of its tape: A moving right turns each
`0101` into `1101` (`fill_A`), B moving right turns each `1010` into `1011` (`fill_B`), eight steps a copy.  The only
halt is C reading a 0; C is entered from B and from F reading a 0, writing a 1 and stepping left, so `0 B> 0` and
`0 F> 0` halt after two steps (`halt_B`, `halt_F`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

# Lean options put before the first theorem (the long words need a deeper recursion limit)
OPTIONS = ''

RULES = [
    ('fill_A',
     'L A> (0101)^n R',
     'L (1101)^n A> R',
     'A moving right over the alternating background, eight steps a copy.'),
    ('fill_B',
     'L B> (1010)^n R',
     'L (1011)^n B> R',
     'B moving right over the alternating background, eight steps a copy.')
]

# hand-written statements appended to the file (the halting situations), proved by `rfl`
EXTRA = """/-- `0 B> 0` halts: B writes a 1 and steps left in state C onto a 0, which has no transition. -/
theorem halt_B (L R : Tape) :
    ∃ c, steps 1 ⟨cons false L, cons false R, .B⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩

/-- `0 F> 0` halts the same way. -/
theorem halt_F (L R : Tape) :
    ∃ c, steps 1 ⟨cons false L, cons false R, .F⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩
"""


def main():
    thms = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    thms[0] = OPTIONS + thms[0]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
