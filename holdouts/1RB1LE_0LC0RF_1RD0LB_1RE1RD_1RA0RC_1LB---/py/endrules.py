"""Generate lean/EndRules.lean for 1RB1LE_0LC0RF_1RD0LB_1RE1RD_1RA0RC_1LB---: what the rightward sweep does at each kind of
defect of the group form, and the halting pattern of the end layer (README.md, "The right-end layer").

usage (from the repository root):
  python3 holdouts/1RB1LE_0LC0RF_1RD0LB_1RE1RD_1RA0RC_1LB---/py/endrules.py > holdouts/1RB1LE_0LC0RF_1RD0LB_1RE1RD_1RA0RC_1LB---/lean/EndRules.lean

The tape just before a rightward sweep is in group form: groups `1 (01)^(m-1)` of m single 1s, normally followed by
`000`.  The sweep meets a group in state E (first slot of a pair) or A (second slot; the cells `0111` it wrote just
before are then on its left).  `Sweep.lean` has the normal case, m odd and `000` after it.  The rules here are the other
cases, each for every n: an even group, a group followed by only `00`, and a group touching the next one (`1 1`).
Each start configuration is given; the end is where the symbolic run (tools/py/bbtools/symtm.py) stops, just before
it would read an unknown cell.  `halt_even_touch` is proved from its rule and one more step by `rfl`.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, Halted, NeedSplit, TouchContext, prove, rules_file, step, try_cross, try_rotate  # noqa: E402
from rules import MACHINE, run_to_edge  # noqa: E402

RULES = [
    ('even_E',
     'L E> 1 (0101)^n 0 1 0 0 0 R',
     'An even group (2n+2 ones) read in E: the sweep turns back (B, going left).'),
    ('even_A',
     'L 0 1 1 1 A> 1 (0101)^n 0 1 0 0 0 R',
     'An even group read in A: it joins the block behind, and the sweep goes on in E, two cells off the 4-cell grid.'),
    ('gap2_E',
     'L E> 1 (0101)^n 0 0 R',
     'An odd group followed by only `00`, read in E: the sweep goes on in E, one cell off the grid, leaving a block `11`.'),
    ('gap2_A',
     'L 0 1 1 1 A> 1 (0101)^n 0 0 R',
     'An odd group followed by only `00`, read in A: the sweep turns back.'),
    ('touch_E',
     'L E> 1 (0101)^n 1 R',
     'An odd group touching the next group (`... 1 1 ...`), read in E: the sweep turns back.'),
    ('touch_A',
     'L 0 1 1 1 A> 1 (0101)^n 1 R',
     'An odd group touching the next group, read in A: the sweep goes on, the next group is read in C.'),
    ('even_block_B',
     'L 0 1 1 (11)^n B> 0 R',
     'Leftward sweep at a block of even length (made by `gap2_E`): B turns right again, in D.'),
]

HALT_START = 'L E> 1 (0101)^n 0 1 0 0 0 1 1 R'


def run_to_halt(machine, start, max_moves=20000):
    """The configuration of the symbolic run from `start` just before its halting step."""
    m = Machine.parse(machine)
    c = Config.parse(start)
    for _ in range(max_moves):
        last = c.copy()
        try:
            if try_cross(m, c) is None:
                c2 = c.copy()
                if try_rotate(c2) is not None and try_cross(m, c2) is not None:
                    c = c2
                    continue
                step(m, c)
        except Halted:
            return last
    raise RuntimeError(f"{start}: no halt after {max_moves} moves")


def main():
    symtm.MAX_CARRY = 3
    ns = re.search(r"^namespace (\S+)", open(os.path.join(HERE, "..", "lean", "Machine.lean")).read(), re.M).group(1)
    ths = []
    for name, start, text in RULES:
        end = run_to_edge(MACHINE, start)
        ths.append("set_option maxRecDepth 100000 in\n" + prove(MACHINE, name, start, end, doc=f"{text}  `{start}` to `{end}`.",
                                                               rotate=True, count_first=True, max_seg=200)[0])
    last = run_to_halt(MACHINE, HALT_START)
    th, fin = prove(MACHINE, "even_touch_run", HALT_START, last, doc=f"The run of `halt_even_touch`: `{HALT_START}` to `{last}`.",
                    rotate=True, count_first=True, max_seg=200)
    ths.append("set_option maxRecDepth 100000 in\n" + th)
    n_steps = fin.steps.lean()
    ths.append(f"""/-- The halting pattern of the end layer: an even group (2n+2 ones) read in E, followed after its `000` by a single
1 that touches the next group, halts for every n (F reads a 1).  `{HALT_START}`. -/
theorem halt_even_touch (n : Nat) (L R : Tape) :
    ∃ c, steps ({n_steps}) {symtm.cfg_term(Config.parse(HALT_START))} = some c ∧ step c = none :=
  ⟨_, even_touch_run n L R, rfl⟩
""")
    doc = (f"Rules of {MACHINE} at the defects of the group form and the halting pattern of the end layer, "
           "generated by `py/endrules.py`; do not edit by hand.")
    sys.stdout.write(rules_file("Machine", ns, ths, doc))


if __name__ == "__main__":
    main()
