"""Generate lean/Sweep.lean for 1RB1LE_0LC0RF_1RD0LB_1RE1RD_1RA0RC_1LB---: the three macro rules behind the
round-trip rewrite of the list of 4k+3 blocks (README.md, "The round trip as a CA rule").  Proved along the symbolic
run (tools/py/bbtools/symtm.py), like py/rules.py.

usage (from the repository root):  python3 holdouts/1RB1LE_0LC0RF_1RD0LB_1RE1RD_1RA0RC_1LB---/py/ca.py > holdouts/1RB1LE_0LC0RF_1RD0LB_1RE1RD_1RA0RC_1LB---/lean/Sweep.lean
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402
from bbtools.symtm import prove, rules_file  # noqa: E402

MACHINE = '1RB1LE_0LC0RF_1RD0LB_1RE1RD_1RA0RC_1LB---'

# (name, start, end, doc).  A group is G_n = 1 (0101)^n 0 0 0: 2n+1 single 1s and the 000 after them.
RULES = [
    ('group_E', 'L E> 1 (0101)^n 0 0 0 R', 'L (0111)^n 0 1 1 1 A> R',
     'Rightward sweep, a group read in E: G_n becomes (0111)^(n+1) and the head goes on in A.'),
    ('group_A', 'L 0 1 1 1 A> 1 (0101)^n 0 0 0 R', 'L 1 1 (1111)^n 1 1 0 1 1 1 E> R',
     'Rightward sweep, a group read in A: the 0 four cells back becomes 1, G_n becomes (1111)^n 0111, and the head goes on in E.'),
    ('block_B', 'L 0 1 1 1 (1111)^n B> 0 R', 'L B> 0 0 0 1 0 (1010)^n R',
     'Leftward sweep: a block 0 1^(4n+3) becomes 0 0 0 1 (01)^(2n), the 000 and G_n of the next rightward sweep.'),
]


def main():
    symtm.MAX_CARRY = 3
    here = os.path.dirname(os.path.abspath(__file__))
    ns = re.search(r"^namespace (\S+)", open(os.path.join(here, "..", "lean", "Machine.lean")).read(), re.M).group(1)
    ths = []
    for name, start, end, text in RULES:
        ths.append("set_option maxRecDepth 100000 in\n" + prove(MACHINE, name, start, end, doc=f"{text}  `{start}` to `{end}`.",
                                                                rotate=True, count_first=True, max_seg=200)[0])
    sys.stdout.write(rules_file("Machine", ns, ths, f"Macro rules of the round trip of {MACHINE}, generated by `py/ca.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
