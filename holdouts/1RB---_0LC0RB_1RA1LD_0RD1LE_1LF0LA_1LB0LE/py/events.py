"""Generate lean/Events.lean for a G11-X machine (usage: python3 py/events.py [M] > lean/Events.lean;
`python3 py/events.py [M] --coverage STEPS [SHOW]` matches every engine visit of the run against the rule starts).

Words: a = 1000, b = 1100, c = 1110, i = 11000, e = 110, g = 11110, and two more digit words of the left counter,
z = 0000 and v = 0100.  An engine visit (event) is the head in state A on the 0 of `d` = 10 in

    L' x_L  i e x i 1 A> 0  R

L' x_L ... is the left counter (lowest digit next to `i e`), x its lowest digit, R the right counter.  The left
counter counts down: x = b -> a; x = a -> b with a borrow into L', where the lowest digits a (0) become b and the
first other digit drops one step: b -> a, z -> b, v -> z (a digit of value 3, 2, 1, 0 = v, z, b, a; borrowing
from an a gives a b, as in binary).  The right counter counts up, lowest first, digits b = 0, c = 1, in three pieces
separated by S1 = e c g b e g and S2 = e c g c; a carry crosses a separator and leaves it unchanged.

Each rule is one whole event (borrow and carry included), proved for every size by `bbtools.symtm.prove`.
"""
import collections
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

X1 = "1RB---_0LC0RB_1RA1LD_0RD1LE_1LF0LA_1LB0LE"
X2 = "1RB---_0LC0RB_1RA1LD_1LE1LF_1LB0LF_0RC0LA"
NS = {X1: "H130321", X2: "H128426"}
W = dict(a="1 0 0 0", b="1 1 0 0", c="1 1 1 0", i="1 1 0 0 0", e="1 1 0", g="1 1 1 1 0", z="0 0 0 0", v="0 1 0 0")
a, b, c, i, e, g, z, v = (W[k] for k in "abciegzv")
S1 = f"{e} {c} {g} {b} {e} {g}"
S2 = f"{e} {c} {g} {c}"
LEFTS = [
    ("b", f"L {i} {e} {b} {i} 1 A> 0", f"L {i} {e} {a} {i} 1 A> 0", "x = b becomes a (no borrow)"),
    ("ab", f"L {b} (1000)^m {i} {e} {a} {i} 1 A> 0", f"L {a} (1100)^m {i} {e} {b} {i} 1 A> 0",
     "x = a: borrow over m digits a, then b -> a"),
    ("az", f"L {z} (1000)^m {i} {e} {a} {i} 1 A> 0", f"L {b} (1100)^m {i} {e} {b} {i} 1 A> 0",
     "x = a: borrow over m digits a, then z -> b"),
    ("av", f"L {v} (1000)^m {i} {e} {a} {i} 1 A> 0", f"L {z} (1100)^m {i} {e} {b} {i} 1 A> 0",
     "x = a: borrow over m digits a, then v -> z"),
]
RIGHTS = [
    ("r", f"(1110)^k {b} R", f"(1100)^k {c} R", "R gets 1, carry over k ones"),
    ("s1", f"(1110)^j {S1} (1110)^k {b} R", f"(1100)^j {S1} (1100)^k {c} R",
     "R gets 1, the carry crosses j ones, the separator S1 and k ones"),
    ("s2", f"(1110)^j {S1} (1110)^h {S2} (1110)^k {b} R", f"(1100)^j {S1} (1100)^h {S2} (1100)^k {c} R",
     "R gets 1, the carry crosses j ones, S1, h ones, S2 and k ones"),
]
RULES = [(ln + "_" + rn, ls + " " + rs, le + " " + re_, f"One engine visit: {ld}; {rd}.")
         for ln, ls, le, ld in LEFTS for rn, rs, re_, rd in RIGHTS]


def theorems(m):
    return [prove(m, "x_" + n, s, t, doc=d, rotate=True, count_first=True, max_seg=40)[0] for n, s, t, d in RULES]


def _re(toks):
    out = []
    for t in toks:
        mm = re.fullmatch(r"\((\w+)\)\^\w+", t)
        out.append("(?:" + mm.group(1) + ")*" if mm else t)
    return "".join(out)


def coverage(m, steps, show=0):
    pats = []
    for r in RULES:
        toks = r[1].split()
        k = next(j for j, t in enumerate(toks) if t.endswith(">"))
        pats.append((r[0], re.compile(".*" + _re(toks[1:k]) + "$"), re.compile(_re(toks[k + 1:-1]))))
    tool = os.path.join(tempfile.gettempdir(), "g11x-xdump")
    if not os.path.exists(tool):
        subprocess.check_call(["gcc", "-O2", "-o", tool, os.path.join(HERE, "..", "c", "xdump.c")])
    p = subprocess.Popen([tool, m, str(steps)], stdout=subprocess.PIPE, text=True)
    cnt = collections.Counter()
    for line in p.stdout:
        if not line.startswith("EV"):
            continue
        _, n, t, pos, tp = line.split()
        L, R = tp.split("|")
        L, R = "0" * 8 + L, R + "0" * 60  # blank cells beyond the visited part
        hit = next((nm for nm, lp, rp in pats if rp.match(R) and lp.match(L)), None)
        cnt[hit] += 1
        if hit is None and cnt[None] <= show:
            print("unmatched", n, t, pos, L[-70:], R[:90])
    tot = sum(cnt.values())
    print(f"events {tot}: " + ", ".join(f"{k} {v}" for k, v in cnt.most_common() if k) +
          f"; not covered {cnt[None]} ({100 * cnt[None] / max(tot, 1):.3f}%)")


if __name__ == "__main__":
    args = sys.argv[1:]
    m = args.pop(0) if args and args[0] in NS else X1
    if args and args[0] == "--coverage":
        coverage(m, int(args[1]), int(args[2]) if len(args) > 2 else 0)
    else:
        sys.stdout.write(rules_file("Machine", NS[m], theorems(m),
                                    f"Engine visits of {m}, generated by `py/events.py`; do not edit by hand."))
