"""Generate lean/Rules.lean: pieces of a step of 1RB1LF_1LC1RD_1RA1LA_0RA0RE_0RC---_1RF0LC, proved along the
symbolic run (tools/py/bbtools/symtm.py).

usage: python3 rules.py > ../lean/Rules.lean

Tapes left to right, `S>` the head in state S on the next cell, `(110)^n` n copies of the word b = 110, `L` any
tape, `0^inf` blank tape.

* `sweep`: the transfer loop.  With the wall L 1 on the left, two copies of b leave the block on the left of the
  junction `111 F>` and three join the block on its right: x + 2, y + 1 becomes x, y + 4.
* `first`: the start of a step from the wall `1`: `1 A> 0 b^(n+6) 1` reaches the first junction.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LF_1LC1RD_1RA1LA_0RA0RE_0RC---_1RF0LC"

RULES = [
    ("sweep", "L 1 (110)^x+2 111 F> (110)^y+1 1 0^inf",
     "L 1 (110)^x 1 1 1 F> 1 1 0 1 1 0 1 1 (011)^y 0 1 1 0 1 0^inf",
     "One sweep: two b leave the left block, three join the right block (written `(110)^(y+4) 1` re-bracketed)."),
    ("first", "0^inf 1 A> 0 (110)^n+6 1 0^inf",
     "0^inf 1 1 1 (011)^n+5 1 1 1 F> 1 1 0 1 1 0 1 0^inf",
     "From the wall `1`, the start of a step: the head crosses the block and builds the first junction."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H" + open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "..", "lean", "Machine.lean")).read().split("namespace H")[1].split()[0], ths,
                     f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
