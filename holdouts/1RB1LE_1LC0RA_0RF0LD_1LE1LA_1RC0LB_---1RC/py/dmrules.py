"""Generate lean/DMRules.lean: the tape rules behind DeepMind's halts-iff map of 1RB1LE_1LC0RA_0RF0LD_1LE1LA_1RC0LB_---1RC,
each proved along a symbolic run (tools/py/bbtools/symtm.py, with the near-side rotations of tools/deepmind/dmproof.py).

usage: python3 py/dmrules.py > lean/DMRules.lean      (from holdouts/1RB1LE_1LC0RA_0RF0LD_1LE1LA_1RC0LB_---1RC)

A(a, b) is `0^inf C> 0 (10)^a 110 (10)^b 0^inf` and B(a, b, c) is `0^inf C> 0 (10)^a 110 (10)^b 110 (1010)^c 0^inf`.
A pass (`round`) moves one `10` from the left counter to the middle and one from the right counter, doubled; the
two loops (`round`, `zloop`) are inductions in lean/DMMap.lean, the other rules are the pieces between them.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "deepmind"))
import dmproof  # noqa: E402
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, rules_file  # noqa: E402

M = "1RB1LE_1LC0RA_0RF0LD_1LE1LA_1RC0LB_---1RC"

RULES = [
    ("blank_A", "0^inf A> 0^inf", "0^inf C> 0 1 0 1 0 1 1 0 0^inf", "From blank tape to A(2, 0)."),
    ("entry0", "0^inf C> 0 1 1 0 R", "0^inf 1 C> 1 0 R", "A pass starts (left counter 0)."),
    ("entryS", "0^inf C> 0 1 0 (10)^a 1 1 0 R", "0^inf 1 0 (10)^a 1 C> 1 0 R", "A pass starts."),
    ("round", "L 1 0 1 C> 1 (1010)^k 0 1 0 R", "L 1 C> 1 (1010)^k 1 0 1 0 0 R",
     "One round: a `10` from each side, two into the middle."),
    ("exitlt", "0^inf 1 C> 1 (1010)^k 0 1 0 R", "0^inf C> 0 (1010)^k 1 0 1 0 1 1 0 R",
     "Left counter used up first: the next A or B state."),
    ("haltA", "0^inf 1 C> 1 (1010)^k 0 0^inf", "halt", "Both counters used up together in A: halt."),
    ("gt1", "0^inf (10)^k 1 0 1 C> 1 (1010)^b 0 R", "0^inf (10)^k 0 A> (0101)^b 0 1 0 1 R",
     "Right counter used up first."),
    ("e1a0", "0^inf A> (0101)^b 0 1 0 1 0^inf", "0^inf A> 0 1 0 0 (1010)^b 1 0 1 0 1 0^inf", "A, left part empty."),
    ("e1as", "0^inf (10)^j 1 0 0 A> (0101)^b 0 1 0 1 0^inf",
     "0^inf A> (01)^j 0 1 0 1 0 0 (1010)^b 1 0 1 0 1 0^inf", "A, left part `(10)^(j+1)`."),
    ("fin_odd", "0^inf A> (0101)^j 0 1 0 0 (1010)^b 1 0 1 0 1 0^inf",
     "0^inf C> 0 (1010)^j 1 0 1 0 1 1 0 (1010)^b 1 0 1 0 0^inf", "Odd: A(2j + 2, 2b + 2)."),
    ("fin_even", "0^inf A> (0101)^j 0 1 0 1 0 0 (1010)^b 1 0 1 0 1 0^inf",
     "0^inf C> 0 1 0 1 0 1 1 0 (1010)^j 1 0 1 1 0 (1010)^b 1 0 1 0 0^inf", "Even: B(2, 2j + 1, b + 1)."),
    ("beq1", "0^inf 1 C> 1 (1010)^a 0 1 1 0 (1010)^c 0^inf", "0^inf (1010)^a 1 0 A> 0 0 1 1 0 (1010)^c 0^inf",
     "B, both counters used up together."),
    ("beq2", "0^inf (1010)^a 1 0 A> 0 0 1 1 0 (1010)^c 0^inf", "0^inf (1010)^a 1 0 1 A> (0101)^c 0 1 0 1 0^inf",
     "B, both counters used up: the tail turned into `(01)^(2c + 2)`."),
    ("bgtpre0", "0^inf A> (0101)^b 0 1 0 1 1 1 0 (1010)^c 0^inf", "0^inf A> (0101)^b (0101)^c 0 1 0 1 0 1 0 1 0^inf",
     "B, right counter used up first, left part empty."),
    ("bgtpre", "0^inf (10)^k 1 0 0 A> (0101)^b 0 1 0 1 1 1 0 (1010)^c 0^inf",
     "0^inf (10)^k 1 A> (0101)^b (0101)^c 0 1 0 1 0 1 0 1 0^inf", "B, right counter used up first."),
    ("zloop", "L 1 0 1 A> (0101)^m 0 1 0 1 0^inf", "L 1 A> (0101)^m 0 1 0 1 0 1 0 1 0^inf",
     "A `10` from the left becomes `0101` on the right."),
    ("zfin", "0^inf 1 A> (0101)^m 0 1 0 1 0^inf", "0^inf A> (0101)^m 0 1 0 1 0 1 0 1 0^inf", "The last one."),
    ("e2a", "0^inf A> (0101)^p 0 1 0 1 0^inf", "0^inf C> 0 1 0 1 0 1 1 0 (1010)^p 1 0 1 0 0^inf", "A(2, 2p + 2)."),
]


def main():
    m = Machine.parse(M)
    ths = []
    for name, a, b, doc in RULES:
        if b == "halt":
            b = str(dmproof.before_halt(m, Config.parse(a)))
        ths.append(dmproof.prove_any(M, name, a, b, doc)[0])
    sys.stdout.write(rules_file("Machine", "H113170", ths, f"Rules of {M} for DeepMind's map, generated by "
                                "`py/dmrules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
