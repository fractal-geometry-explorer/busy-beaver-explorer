"""Generate lean/Rules.lean: rules of 1RB1LE_1LC0RA_0RF0LD_1LE1LA_1RC0LB_---1RC, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB1LE_1LC0RA_0RF0LD_1LE1LA_1RC0LB_---1RC)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LE_1LC0RA_0RF0LD_1LE1LA_1RC0LB_---1RC"

RULES = [
    ('d_run', 'L (01)^n D> 1 R', 'L D> 1 (01)^n R',
     'D runs left over pairs, carrying the marker cell along: the doubling pass, 4 steps a pair.'),
    ('a_run', 'L A> (01)^n R', 'L (10)^n A> R',
     'A runs right over pairs `01`, shifting them.'),
    ('b_run', 'L B> (10)^n R', 'L (01)^n B> R',
     'B runs right over pairs `10`, shifting them.'),
    ('a_left', 'L (10)^n A> 1 R', 'L A> 1 (10)^n R',
     'A runs left over pairs `10`, 4 steps a pair.')
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H113170", thms,
                                "Rules of 1RB1LE_1LC0RA_0RF0LD_1LE1LA_1RC0LB_---1RC, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
