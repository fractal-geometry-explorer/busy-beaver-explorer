"""Generate lean/Law.lean: the block-level law of this machine, one kernel-checked theorem per rule.

usage (from the repository root):  python3 holdouts/MACHINE/py/law_rules.py > holdouts/MACHINE/lean/Law.lean

The three machines 1RB0RC_1LC1LA_1RD0LB_1RE1RC_1RA0RF_1RC--- (the reference), 1RB0RF_1RC0RD_1LD1LB_1RE0LC_1RA1RD_1RD---
(the same table with the states renamed) and 1RB1RE_1LC0RA_1LD1LB_1LE0LF_1LA0LB_1LB--- (its mirror image with the states
renamed) follow the same law; this script is the same in the three folders and picks the state names and the
orientation from the folder name.  The rules are stated in the reference orientation: closed blocks of 1s on the
left of the head ("stack L", nearest first), gaps of 0s on the right ("stack G", nearest first).  For the mirror
machine the two sides of the tape are swapped in the encodings and nothing else changes.

Every theorem is proved by evaluating the machine (`rfl`) on a tape whose far parts are variables, so it holds for all
block and gap sizes and all tapes beyond the cells that are read; where the right part is blank the proof also uses
`cons false blank = blank`.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MACHINE = os.path.basename(os.path.dirname(HERE))
# roles: the state names of the reference machine, and what they are called here
ROLES = {
    "1RB0RC_1LC1LA_1RD0LB_1RE1RC_1RA0RF_1RC---": dict(B="B", C="C", D="D", F="F", mirror=False),
    "1RB0RF_1RC0RD_1LD1LB_1RE0LC_1RA1RD_1RD---": dict(B="C", C="D", D="E", F="F", mirror=False),
    "1RB1RE_1LC0RA_1LD1LB_1LE0LF_1LA0LB_1LB---": dict(B="A", C="B", D="C", F="F", mirror=True),
}[MACHINE]
MIRROR = ROLES["mirror"]
# the start: (k, n) = after n steps from blank tape the head is in the return state on blank tape with k ones behind it
START = {"1RB0RC_1LC1LA_1RD0LB_1RE1RC_1RA0RF_1RC---": (1, 1), "1RB0RF_1RC0RD_1LD1LB_1RE0LC_1RA1RD_1RD---": (2, 2),
         "1RB1RE_1LC0RA_1LD1LB_1LE0LF_1LA0LB_1LB---": (0, 0)}[MACHINE]


def st(role):
    return "." + ROLES[role]


def header(ns):
    side = ("the mirror orientation: the blocks are on the right of the head, the gaps on the left" if MIRROR
            else "the blocks are on the left of the head, the gaps on the right")
    if MIRROR:
        rc = "⟨tail (zeros g (cons true (gaps G Y))), cons ((zeros g (cons true (gaps G Y))) 0) (ones o (blocks L X)), q⟩"
        rce = "⟨blank, cons false (ones o (blocks L X)), q⟩"
        bc = "⟨zeros z (cons true (gaps G Y)), ones o (blocks L X), %s⟩" % st("B")
        bce = "⟨blank, ones o (blocks L X), %s⟩" % st("B")
    else:
        rc = "⟨ones o (blocks L X), zeros g (cons true (gaps G Y)), q⟩"
        rce = "⟨ones o (blocks L X), blank, q⟩"
        bc = "⟨tail (ones o (blocks L X)), cons ((ones o (blocks L X)) 0) (zeros z (cons true (gaps G Y))), %s⟩" % st("B")
        bce = "⟨tail (ones o (blocks L X)), cons ((ones o (blocks L X)) 0) blank, %s⟩" % st("B")
    return f"""import Machine

/-!
# The block-level law of {MACHINE}

Generated by `py/law_rules.py`; do not edit by hand.

Between two turns of the head the tape has two parts.  Behind the head (where it came from on its way out) the tape
is *blocks*: runs of 1s separated by single 0s; a block `1^b 0` is written as the number `b`.  Ahead of it the tape
is *gaps*: runs of 0s separated by single 1s; a gap `0^g 1` is written as the number `g`.  Here {side}.  A
configuration is a list `L` of closed blocks (nearest the head first), the length `o` of the open block next to the
head, the gap under the head, and the list `G` of the gaps after it; `X` and `Y` are the tape beyond the two lists
(any tape, or blank tape at the ends).

* `rc q L o g G X Y`: the head moves away from the blocks in state `q`, on the first cell of the gap `g`.
* `bc L o z G X Y`: the head moves back in state `{ROLES['B']}`, on the last cell of the open block (on the separator
  of the block `L.head` when `o = 0`); `z` zeros lie between it and the next 1.
* `rce`, `bce`: the same at the end of the tape, with only blank tape ahead (the gap is infinite).

Each theorem below is one rule of the law, with its exact number of machine steps.  Together they cover every
configuration of these four shapes; the only one without a successor is `halt`: state `{ROLES['F']}` on a gap of
length 0, that is, on two adjacent 1s.
-/

namespace {ns}

open TM

/-- `n` ones in front of a stream. -/
def ones (n : Nat) (T : Tape) : Tape := rep n [true] T

/-- `n` zeros in front of a stream. -/
def zeros (n : Nat) (T : Tape) : Tape := rep n [false] T

/-- Closed blocks, nearest the head first: the separator 0, then `b` ones. -/
def blocks : List Nat → Tape → Tape
  | [], T => T
  | b :: bs, T => cons false (ones b (blocks bs T))

/-- Gaps, nearest the head first: `g` zeros, then a 1. -/
def gaps : List Nat → Tape → Tape
  | [], T => T
  | g :: gs, T => zeros g (cons true (gaps gs T))

/-- Outward phase: state `q` on the first cell of the gap `g`; open block `o`, closed blocks `L`, further gaps `G`. -/
def rc (q : St) (L : List Nat) (o g : Nat) (G : List Nat) (X Y : Tape) : Config :=
  {rc}

/-- Outward phase at the end of the tape: only blank tape ahead. -/
def rce (q : St) (L : List Nat) (o : Nat) (X : Tape) : Config :=
  {rce}

/-- Return phase: state `{ROLES['B']}` on the last cell of the open block `o` (on the separator of `L.head` if `o = 0`),
`z` zeros between the head and the next 1, then the gaps `G`. -/
def bc (L : List Nat) (o z : Nat) (G : List Nat) (X Y : Tape) : Config :=
  {bc}

/-- Return phase with only blank tape on the gap side. -/
def bce (L : List Nat) (o : Nat) (X : Tape) : Config :=
  {bce}
"""


def bform(T, rt):
    """explicit return-phase configuration: head on the first cell of the stream T, the stream rt on the other side"""
    if MIRROR:
        return f"(⟨{rt}, {T}, {st('B')}⟩ : Config)"
    return f"(⟨tail ({T}), cons (({T}) 0) ({rt}), {st('B')}⟩ : Config)"


RULES = []


def rule(name, doc, vars_, src, n, tgt, proof="rfl"):
    RULES.append((name, doc, vars_, src, n, tgt, proof))


def fix_blank(actual):
    """proof: the machine reaches `actual`, which is the target after `cons false blank = blank`"""
    return ("by\n  have h : steps {n} ({src}) = some {actual} := rfl\n  rw [cons_false_blank] at h\n  exact h").replace("{actual}", actual)


def unfix_blank(actual, shown):
    """proof: the machine reaches `actual`; the target is `shown`, equal to it by `cons false blank = blank`"""
    return ("by\n  have h : steps {n} ({src}) = some {actual} := rfl\n  have e : {actual} = {tgt} := by\n    show {actual} = {shown}\n    rw [cons_false_blank]\n  rw [e] at h\n  exact h"
            ).replace("{actual}", actual).replace("{shown}", shown)


B, C, D, F = st("B"), st("C"), st("D"), st("F")
TL = "ones o (blocks L X)"
# ---- return phase, finite z
V = "(L : List Nat) (o z : Nat) (G : List Nat) (X Y : Tape)"
Vb = "(L : List Nat) (b z : Nat) (G : List Nat) (X Y : Tape)"
Ve = "(z : Nat) (G : List Nat) (Y : Tape)"
rule("b_triple", "Return, open block of 3 or more: three of its cells `1 1 1` become `0 1 0`, a gap `z + 1` is closed.", V,
     "bc L (o + 3) z G X Y", 5, "bc L o 1 ((z + 1) :: G) X Y")
rule("b_turn2", "Return, open block of 2: the head turns; the open block joins the block behind it.", Vb,
     "bc (b :: L) 2 z G X Y", 7, f"rc {D} L (b + 3) z G X Y")
rule("b_turn2_end", "The same at the end of the blocks (blank tape behind).", Ve,
     "bc [] 2 z G blank Y", 7, f"rc {D} [] 3 z G blank Y")
rule("b_one", "Return, open block of 1 and a nonempty block behind: `1 0 1` becomes `0 1 0`, the head enters that block.", Vb,
     "bc ((b + 1) :: L) 1 z G X Y", 7, "bc L b 1 ((z + 1) :: G) X Y")
rule("b_turn1", "Return, open block of 1 and an empty block behind: the head turns.", Vb,
     "bc (0 :: b :: L) 1 z G X Y", 9, f"rc {D} L (b + 3) z G X Y")
rule("b_turn1_end", "The same with blank tape behind the empty block.", Ve,
     "bc [0] 1 z G blank Y", 9, f"rc {D} [] 3 z G blank Y")
rule("b_turn1_end'", "The same with blank tape behind the open block.", Ve,
     "bc [] 1 z G blank Y", 9, f"rc {D} [] 3 z G blank Y")
rule("b_zero", "Return, head on the separator of a nonempty block: `1 0` becomes `0 1`, a gap `z` is closed.", Vb,
     "bc ((b + 1) :: L) 0 z G X Y", 2, "bc L b 1 (z :: G) X Y")
rule("b_turn0", "Return, head on the separator of an empty block: the head turns.", Vb,
     "bc (0 :: b :: L) 0 z G X Y", 3, f"rc {C} L (b + 2) z G X Y")
rule("b_turn0_end", "The same with blank tape behind the empty block.", Ve,
     "bc [0] 0 z G blank Y", 3, f"rc {C} [] 2 z G blank Y")
rule("b_turn0_end'", "The same on blank tape.", Ve,
     "bc [] 0 z G blank Y", 3, f"rc {C} [] 2 z G blank Y")
# ---- return phase, blank ahead
W = "(L : List Nat) (o : Nat) (X : Tape)"
Wb = "(L : List Nat) (b : Nat) (X : Tape)"
rule("b_triple_inf", "`b_triple` with only blank tape on the gap side: no gap is closed.", W,
     "bce L (o + 3) X", 5, "bc L o 1 [] X blank",
     fix_blank(bform("ones o (blocks L X)", "cons false (cons true (cons false blank))")))
rule("b_turn2_inf", "`b_turn2` with only blank tape on the gap side.", Wb, "bce (b :: L) 2 X", 7, f"rce {D} L (b + 3) X")
rule("b_turn2_end_inf", "`b_turn2_end` with only blank tape on the gap side.", "", "bce [] 2 blank", 7, f"rce {D} [] 3 blank")
rule("b_one_inf", "`b_one` with only blank tape on the gap side.", Wb,
     "bce ((b + 1) :: L) 1 X", 7, "bc L b 1 [] X blank",
     fix_blank(bform("ones b (blocks L X)", "cons false (cons true (cons false blank))")))
rule("b_turn1_inf", "`b_turn1` with only blank tape on the gap side.", Wb, "bce (0 :: b :: L) 1 X", 9, f"rce {D} L (b + 3) X")
rule("b_turn1_end_inf", "`b_turn1_end` with only blank tape on the gap side.", "", "bce [0] 1 blank", 9, f"rce {D} [] 3 blank")
rule("b_turn1_end_inf'", "`b_turn1_end'` with only blank tape on the gap side.", "", "bce [] 1 blank", 9, f"rce {D} [] 3 blank")
rule("b_zero_inf", "`b_zero` with only blank tape on the gap side.", Wb, "bce ((b + 1) :: L) 0 X", 2, "bc L b 1 [] X blank")
rule("b_turn0_inf", "`b_turn0` with only blank tape on the gap side.", Wb, "bce (0 :: b :: L) 0 X", 3, f"rce {C} L (b + 2) X")
rule("b_turn0_end_inf", "`b_turn0_end` with only blank tape on the gap side.", "", "bce [0] 0 blank", 3, f"rce {C} [] 2 blank")
rule("b_turn0_end_inf'", "The start of the mirror twin: the head on blank tape.", "", "bce [] 0 blank", 3, f"rce {C} [] 2 blank")
# ---- outward phase
R = "(L : List Nat) (o g : Nat) (G : List Nat) (X Y : Tape)"
RL = "(L : List Nat) (o : Nat) (X : Tape)"


def both(name, doc, role, gap, n, tgt_role, tgt_L, tgt_o):
    """a rule that consumes the gap `gap` and moves on to the next gap in state tgt_role"""
    rule(name, doc, R, f"rc {st(role)} L o {gap} (g :: G) X Y", n, f"rc {st(tgt_role)} {tgt_L} {tgt_o} g G X Y")
    rule(name + "_last", f"`{name}` on the last gap: blank tape follows.", RL,
         f"rc {st(role)} L o {gap} [] X blank", n, f"rce {st(tgt_role)} {tgt_L} {tgt_o} X")


rule("c_turn0", f"Outward in {ROLES['C']}, gap 0 (a 1 under the head): the head turns, the 1 is erased and joins the next gap.", R,
     f"rc {C} L o 0 (g :: G) X Y", 1, "bc L o (g + 1) G X Y")
rule("c_turn0_last", "`c_turn0` on the last gap.", RL, f"rc {C} L o 0 [] X blank", 1, "bce L o X",
     fix_blank(bform("ones o (blocks L X)", "cons false blank")))
both("c_gap1", f"Outward in {ROLES['C']}, gap 1: `0 1` becomes `1 1`, the open block grows by 2.", "C", 1, 2, "C", "L", "(o + 2)")
both("c_gap2", f"Outward in {ROLES['C']}, gap 2: `0 0 1` becomes `1 1 0`, the block `o + 2` is closed, state {ROLES['F']}.", "C", 2, 3, "F", "((o + 2) :: L)", "0")
both("c_gap3", f"Outward in {ROLES['C']}, gap 3: `0 0 0 1` becomes `1 1 1 0`, the block `o + 3` is closed.", "C", 3, 4, "C", "((o + 3) :: L)", "0")
rule("c_turn4", f"Outward in {ROLES['C']}, gap 4: four 1s are written and the head turns on the 1 that ends the gap.", R,
     f"rc {C} L o 4 (g :: G) X Y", 4, "bc L (o + 5) g G X Y")
rule("c_turn4_last", "`c_turn4` on the last gap.", RL, f"rc {C} L o 4 [] X blank", 4, "bce L (o + 5) X")
rule("c_turn5", f"Outward in {ROLES['C']}, gap of 5 or more: four 1s are written and the head turns on the fifth 0.", R,
     f"rc {C} L o (g + 5) G X Y", 4, "bc ((o + 4) :: L) 0 g G X Y")
if MIRROR:
    rule("c_end", f"Outward in {ROLES['C']} at the end of the tape: four new 1s, then the head turns.", RL,
         f"rce {C} L o X", 4, "bce ((o + 4) :: L) 0 X")
else:
    rule("c_end", f"Outward in {ROLES['C']} at the end of the tape: four new 1s, then the head turns.", RL,
         f"rce {C} L o X", 4, "bce ((o + 4) :: L) 0 X",
         unfix_blank(f"(⟨ones (o + 4) (blocks L X), blank, {B}⟩ : Config)", f"(⟨ones (o + 4) (blocks L X), cons false blank, {B}⟩ : Config)"))
rule("f_step", f"Outward in {ROLES['F']}, gap of 1 or more: its first 0 becomes a 1 that opens a new block, state {ROLES['C']}.", R,
     f"rc {F} L o (g + 1) G X Y", 1, f"rc {C} L (o + 1) g G X Y")
rule("f_end", f"Outward in {ROLES['F']} at the end of the tape.", RL, f"rce {F} L o X", 1, f"rce {C} L (o + 1) X")
both("d_gap0", f"Outward in {ROLES['D']}, gap 0: the 1 joins the open block.", "D", 0, 1, "C", "L", "(o + 1)")
both("d_gap1", f"Outward in {ROLES['D']}, gap 1: `0 1` becomes `1 0`, the block `o + 1` is closed, state {ROLES['F']}.", "D", 1, 2, "F", "((o + 1) :: L)", "0")
both("d_gap2", f"Outward in {ROLES['D']}, gap 2: `0 0 1` becomes `1 1 0`, the block `o + 2` is closed.", "D", 2, 3, "C", "((o + 2) :: L)", "0")
rule("d_turn3", f"Outward in {ROLES['D']}, gap 3: three 1s are written and the head turns on the 1 that ends the gap.", R,
     f"rc {D} L o 3 (g :: G) X Y", 3, "bc L (o + 4) g G X Y")
rule("d_turn3_last", "`d_turn3` on the last gap.", RL, f"rc {D} L o 3 [] X blank", 3, "bce L (o + 4) X")
rule("d_turn4", f"Outward in {ROLES['D']}, gap of 4 or more: three 1s are written and the head turns on the fourth 0.", R,
     f"rc {D} L o (g + 4) G X Y", 3, "bc ((o + 3) :: L) 0 g G X Y")
if MIRROR:
    rule("d_end", f"Outward in {ROLES['D']} at the end of the tape: three new 1s, then the head turns.", RL,
         f"rce {D} L o X", 3, "bce ((o + 3) :: L) 0 X")
else:
    rule("d_end", f"Outward in {ROLES['D']} at the end of the tape: three new 1s, then the head turns.", RL,
         f"rce {D} L o X", 3, "bce ((o + 3) :: L) 0 X",
         unfix_blank(f"(⟨ones (o + 3) (blocks L X), blank, {B}⟩ : Config)", f"(⟨ones (o + 3) (blocks L X), cons false blank, {B}⟩ : Config)"))


# ---- composite rules: how the words S = gap 1, P = gaps 2 2, Q = gaps 4 2 and their images are crossed
COMPOSITE_FROM = len(RULES)
Rg = "(L : List Nat) (o g : Nat) (G : List Nat) (X Y : Tape)"
Rb = "(L : List Nat) (b g : Nat) (G : List Nat) (X Y : Tape)"
Bz = "(L : List Nat) (b z : Nat) (G : List Nat) (X Y : Tape)"
rule("pair_c", f"Outward in {ROLES['C']} over the word P (gaps 2 2): the open block is closed with 2 more cells and a new one of 3 is opened; "
     "with `o = 3` the block is a 5 (`c_gap2`, `f_step`, `c_gap1`).", Rg,
     f"rc {C} L o 2 (2 :: g :: G) X Y", 6, f"rc {C} ((o + 2) :: L) 3 g G X Y")
rule("pair_f", f"Outward in {ROLES['F']} over the word P: a block 5 (`f_step`, `c_gap1`, `c_gap2`).", "(L : List Nat) (g : Nat) (G : List Nat) (X Y : Tape)",
     f"rc {F} L 0 2 (2 :: g :: G) X Y", 6, f"rc {F} (5 :: L) 0 g G X Y")
rule("long_f", f"Outward in {ROLES['F']} over the word Q (gaps 4 2): the blocks 4 and 2 (`f_step`, `c_gap3`, `c_gap2`).", "(L : List Nat) (g : Nat) (G : List Nat) (X Y : Tape)",
     f"rc {F} L 0 4 (2 :: g :: G) X Y", 8, f"rc {F} (2 :: 4 :: L) 0 g G X Y")
rule("short_f", f"Outward in {ROLES['F']} on the word S (gap 1) followed by a gap 2: the head turns, and the two gaps and the 1 between them "
     "become one gap 4, so S P becomes Q (`f_step`, `c_turn0`, `b_one`).", "(L : List Nat) (b : Nat) (G : List Nat) (X Y : Tape)",
     f"rc {F} ((b + 1) :: L) 0 1 (2 :: G) X Y", 9, "bc L b 1 (4 :: G) X Y")
rule("long_c", f"Outward in {ROLES['C']} (open block 3) on the word Q: the head turns on it, comes back three cells into the block `b` behind, "
     "turns again and goes on outward, leaving the blocks `b + 4` and 6 where `b`, the open 3 and Q were "
     "(`c_turn4`, `b_triple` twice, `b_turn2`, `d_gap1`, `f_step`, `c_gap1`, `c_gap3`).", Rb,
     f"rc {C} (b :: L) 3 4 (2 :: g :: G) X Y", 30, f"rc {C} (6 :: (b + 4) :: L) 0 g G X Y")
rule("wall", "Return onto a block 6 (the mark left by `long_c`): the head turns inside it, the 6 joins the block behind, and the head "
     f"goes out again in {ROLES['F']} (`b_one`, `b_triple`, `b_turn2`, `d_gap1`).", "(L : List Nat) (b : Nat) (G : List Nat) (X Y : Tape)",
     "bc (6 :: b :: L) 1 1 G X Y", 21, f"rc {F} ((b + 4) :: L) 0 2 (2 :: G) X Y")
rule("back_5", "Return over a block 5: two gaps (`b_one`, `b_triple`); with `z = 1` they are the word P.", "(L : List Nat) (z : Nat) (G : List Nat) (X Y : Tape)",
     "bc (5 :: L) 1 z G X Y", 12, "bc L 1 1 (2 :: (z + 1) :: G) X Y")
rule("back_7", "Return over a block 7: gaps 1 2 2, the words S P (`b_one`, `b_triple` twice, `b_zero`).", Bz,
     "bc (7 :: (b + 1) :: L) 1 z G X Y", 19, "bc L b 1 (1 :: 2 :: 2 :: (z + 1) :: G) X Y")
rule("back_13", "Return over a block 13 (a 9 and a 6 joined by `wall`): gaps 1 2 2 2 2 2 (`b_one`, `b_triple` four times, `b_zero`).", Bz,
     "bc (13 :: (b + 1) :: L) 1 z G X Y", 29, "bc L b 1 (1 :: 2 :: 2 :: 2 :: 2 :: (z + 1) :: G) X Y")
rule("back_4_2", "Return over the blocks 4 and 2 (the image of Q under `long_f`): gaps 1 2 2 (`b_one` twice, `b_triple`, `b_zero`).", Bz,
     "bc (2 :: 4 :: (b + 1) :: L) 1 z G X Y", 21, "bc L b 1 (1 :: 2 :: 2 :: (z + 1) :: G) X Y")


def main():
    ns = re.search(r"^namespace (\S+)", open(os.path.join(HERE, "..", "lean", "Machine.lean")).read(), re.M).group(1)
    out = [header(ns)]
    for i, (name, doc, vars_, src, n, tgt, proof) in enumerate(RULES):
        if i == COMPOSITE_FROM:
            out.append("/-! ## Composite rules\n\nThe rules above, chained over the patterns that fill the tape in the run from blank tape: the words\n"
                       "S (gap 1), P (gaps 2 2) and Q (gaps 4 2) on the gap side, and the blocks they turn into.  Proved by evaluation like the others. -/\n")
        pf = proof.replace("{n}", str(n)).replace("{src}", src).replace("{tgt}", tgt)
        sep = " " if vars_ else ""
        pre = "set_option maxRecDepth 100000 in\n" if i >= COMPOSITE_FROM else ""
        body = f"{pre}/-- {doc} -/\ntheorem {name}{sep}{vars_} :\n    steps {n} ({src}) = some ({tgt}) := "
        body += pf if pf.startswith("by") else pf
        out.append(body + "\n")
    out.append(f"/-- The only configuration with no successor: state `{ROLES['F']}` on a gap of length 0 (two adjacent 1s). -/\n"
               f"theorem halt (L : List Nat) (o : Nat) (G : List Nat) (X Y : Tape) :\n    step (rc {F} L o 0 G X Y) = none := rfl\n")
    k, n0 = START
    if MIRROR:
        out.append(f"/-- The run from blank tape starts in the return phase on blank tape. -/\n"
                   f"theorem start : steps {n0} init = some (bce [] 0 blank) := rfl\n")
    else:
        out.append(f"/-- After {n0} step{'s' if n0 > 1 else ''} from blank tape the machine is in the return phase with a block of {k} behind the head and blank tape ahead. -/\n"
                   f"theorem start : steps {n0} init = some (bce [{k}] 0 blank) := by\n"
                   f"  have h : steps {n0} init = some (⟨ones {k} blank, blank, {B}⟩ : Config) := rfl\n"
                   f"  have e : (⟨ones {k} blank, blank, {B}⟩ : Config) = bce [{k}] 0 blank := by\n"
                   f"    show (⟨ones {k} blank, blank, {B}⟩ : Config) = (⟨ones {k} blank, cons false blank, {B}⟩ : Config)\n"
                   f"    rw [cons_false_blank]\n"
                   f"  rw [e] at h\n  exact h\n")
    out.append(f"end {ns}\n")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
