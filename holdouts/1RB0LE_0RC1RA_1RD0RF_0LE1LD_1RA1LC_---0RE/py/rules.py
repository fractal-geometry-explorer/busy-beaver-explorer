"""Generate Rules.lean for 1RB0LE_0RC1RA_1RD0RF_0LE1LD_1RA1LC_---0RE: shift rules (one copy of a word crossed by the head in a state, so a whole run of
copies is crossed at once), each proved along a symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`,
shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, prove, rules_file, run  # noqa: E402

M = "1RB0LE_0RC1RA_1RD0RF_0LE1LD_1RA1LC_---0RE"
NS = "H160345"

# (name, start, doc): the end is the configuration right after the run of copies is crossed
RULES = [
    ('e_left',
     'L (100)^n E> 1 R',
     'E runs left over triples 100, turning each into 011 (the left part of the tape, the run of 100 next to the left end).'),
    ('d_left',
     'L (001)^n D> 0 R',
     'The same leftward sweep in phase D: 001 becomes 110.'),
    ('a_right',
     'L A> (011)^n R',
     'A runs right over triples 011, turning each into 001: a rightward sweep over the left part.'),
    ('b_right',
     'L 1 B> (110)^n R',
     'The rightward sweep in phase B, carrying one 1: 110 becomes 001.'),
]

DOC = """Shift rules of the sweeps over the period-3 left part of the tape. Generated by py/rules.py (tools/py/bbtools/symtm.py); do not edit by hand."""


def after_cross(start):
    trace = []
    run(Machine.parse(M), Config.parse(start), lambda c: any(t[0] == "cross" for t in trace), trace=trace)
    return next(t[2] for t in trace if t[0] == "cross")


def main():
    ths = []
    for name, start, doc in RULES:
        ths.append(prove(M, name, start, after_cross(start), doc=doc)[0])
    sys.stdout.write(rules_file("Machine", NS, ths, DOC))


if __name__ == "__main__":
    main()
