"""Generate lean/Rules.lean for 1RB0RC_1LC0RB_1LD0LD_1RA1LE_---0LF_1LB1LF: the shift rules of its sweeps, proved along symbolic runs
(tools/py/bbtools/symtm.py: single steps by `rfl`, a whole repeat crossed by `TM.cross_r` / `TM.cross_l`).

usage (from the repository root): python3 holdouts/1RB0RC_1LC0RB_1LD0LD_1RA1LE_---0LF_1LB1LF/py/rules.py > holdouts/1RB0RC_1LC0RB_1LD0LD_1RA1LE_---0LF_1LB1LF/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape.  Each rule holds for every n and every tape around it; README.md says where each one is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402

symtm.MAX_CARRY = 8  # some sweeps carry a word of up to 6 cells along with the head

M = "1RB0RC_1LC0RB_1LD0LD_1RA1LE_---0LF_1LB1LF"
NS = "H173393"

RULES = [
    ("b_erase", "L B> (1)^n R", "L (0)^n B> R",
     "Rightward sweep: B erases a block of ones."),
    ("f_ones", "L (1)^n F> 1 R", "L F> 1 (1)^n R",
     "Leftward: F runs left over a block of ones, keeping them."),
    ("b_word", "L B> (1101111)^n R", "L (1110000)^n B> R",
     "Rightward: B crosses the word 1101111 (a block 1^4 after 1^2) and leaves 1110000."),
    ("b_word2", "L 0 B> (101111)^n R", "L (111000)^n 0 B> R",
     "Rightward: B, with a 0 behind it, crosses 101111 and leaves 111000."),
]


def main():
    ths = [symtm.prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(symtm.rules_file("Machine", NS, ths, f"Sweep rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
