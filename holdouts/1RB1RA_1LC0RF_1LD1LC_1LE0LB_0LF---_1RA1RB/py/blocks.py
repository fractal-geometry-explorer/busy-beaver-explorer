"""Writes lean/Blocks.lean: the four block rules of the machine, proved by bbtools.symtm for all sizes and every
tape L, R around them.  The tape is a row of blocks of 1s split by single 0s; C sweeps left, A sweeps right.

  pass    L 1 0 1 0 1^c <C         ->  L <C 1 1 0 1^(c+2)        C passes a single 1: both neighbours grow by one
  bounce  L 1 1 0 1^c <C           ->  L 0 1 1 A> 1^(c+1)        C meets a block of two or more: the 0 moves two
                                                                  cells left and the head turns round in A
  shred   L A> 1^a 0 1^(2k+1) 0 R  ->  L 1^(a+1) 0 (1 0)^k 1 A> R   A shreds an odd block into single 1s, goes on
  turn    L A> 1^a 0 1^(2k+2) 0 R  ->  L 1^(a+1) (0 1)^k 0 <C 1 1 R  an even block: the head turns round in C
  halt_pattern   L 1 0 0 1^c <C    ->  E on the 1 (the halting transition)

usage: python3 blocks.py > ../lean/Blocks.lean      (python3 blocks.py check: the same rules by direct simulation)
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB1RA_1LC0RF_1LD1LC_1LE0LB_0LF---_1RA1RB"
NS = "H7085"

RULES = [
    ("pass", "C, sweeping left, passes a single 1: the block it leaves and the block it enters both grow by one cell.",
     "L 1 0 1 0 1^c C> 1 R", "L C> 1 1 0 1^c 1 1 R"),
    ("bounce", "C meets a block of at least two 1s: the block loses two cells, the 0 moves two cells left, and the head "
     "turns round in A.",
     "L 1 1 0 1^c C> 1 R", "L 0 1 1 A> 1^c 1 R"),
    ("shred", "A, sweeping right, turns the next block, of odd length 2k+1, into k single 1s and goes on in A.",
     "L A> 1^a 0 1 (11)^k 0 R", "L 1^a 1 0 (10)^k 1 A> R"),
    ("turn", "The next block has even length 2k+2: k single 1s, and the head turns round in C.",
     "L A> 1^a 0 (11)^k+1 0 R", "L 1^a 1 (01)^k 0 C> 1 1 R"),
    ("halt_pattern", "A double 0 with a 1 on its left, met by C from the right: E reads the 1, the halting transition.",
     "L 1 0 0 1^c C> 1 R", "L E> 1 1 1 1^c 1 R"),
]


def check():
    T = {}
    for s in range(6):
        for b in range(2):
            t = M[s * 7 + b * 3:s * 7 + b * 3 + 3]
            if t[0] != '-':
                T[(s, b)] = (int(t[0]), 1 if t[1] == 'R' else -1, ord(t[2]) - 65)
    A, C, E = 0, 2, 4

    def run(cells, p, s, stop):
        cells = list(cells)
        for _ in range(100000):
            w, d, s2 = T[(s, cells[p])]
            cells[p] = w; p += d; s = s2
            if stop(p, s):
                return cells, p
        raise RuntimeError

    def blocks(*xs):
        out = []
        for x in xs:
            out += [1] * x + [0]
        return out[:-1]
    n = 0
    for e in range(1, 9):
        for c in range(1, 9):
            r = run([0] + blocks(e, 1, c) + [0], e + c + 3, C, lambda p, s: s == C and p == e)
            assert r[0] == [0] + [1] * (e + 1) + [0] + [1] * (c + 1) + [0]; n += 1
    for d in range(2, 10):
        for c in range(1, 9):
            r = run([0] + blocks(d, c) + [0], d + c + 1, C, lambda p, s: s == A)
            assert r == ([0] + [1] * (d - 2) + [0] + [1] * (c + 2) + [0], d + 1); n += 1
    for a in range(1, 7):
        for b1 in range(1, 12):
            for b2 in range(1, 5):
                t = [0] + blocks(a, b1, b2) + [0, 0]
                if b1 % 2:
                    r = run(t, 1, A, lambda p, s: s == A and p == a + b1 + 3)
                    assert r[0] == [0] + [1] * (a + 1) + [0, 1] * ((b1 - 1) // 2) + [0] + [1] * (b2 + 1) + [0, 0]
                else:
                    r = run(t, 1, A, lambda p, s: s == C)
                    assert r == ([0] + [1] * (a + 1) + [0, 1] * ((b1 - 2) // 2) + [0] + [1] * (b2 + 2) + [0, 0], a + b1 + 1)
                n += 1
    for c in range(1, 9):
        t = [0, 1, 0, 0] + [1] * c + [0]; p = len(t) - 2; s = C
        while (s, t[p]) in T:
            w, d, s2 = T[(s, t[p])]; t[p] = w; p += d; s = s2
        assert (s, t[p]) == (E, 1); n += 1
    print("block rules: all", n, "cases agree with the machine")


def main():
    thms = []
    for name, doc, start, end in RULES:
        t, _ = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=40)
        thms.append(t)
    print(rules_file("Machine", NS, thms,
                     "The block rules: how the two sweeps rewrite a row of blocks of 1s split by single 0s, for all "
                     "block sizes and every tape around them. Generated by `py/blocks.py`."), end="")


if __name__ == "__main__":
    check() if len(sys.argv) > 1 else main()
