"""Port the Pascal/Lucas/Absorb/Wall/Crossing/End/Race proofs of 1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF to its two
mirrored relatives, 1RB1RA_1LC0RF_1LD1LC_1LE0LB_0LF---_1RA1RB and 1RB1RC_1RC1RB_1LD0RA_1LE1LD_1LF0LC_0LA---.

Both are that machine's table read in a mirror with the states renamed, started in another state (D and C of the
Pascal table).  Instead of rewriting every proof with the tape sides exchanged, the Pascal machine's Lean files are
copied unchanged into `lean/P75625/` (only the imports are renamed, so that they can be compiled next to this folder's
own `Machine.lean`), and `lean/Mirror.lean` carries every theorem over with the mirror lemmas of
`tools/lean/TM/Insert.lean`.

usage: python3 py/port_mirror.py      (rewrites lean/P75625/*.lean and lean/Mirror.lean in both
                                       folders, and copies lean/Fail.lean of this folder to the other)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
HOLD = os.path.normpath(os.path.join(HERE, "..", ".."))
HOME = "1RB1RA_1LC0RF_1LD1LC_1LE0LB_0LF---_1RA1RB"
PASCAL = "1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF"
FILES = ["Machine", "Pascal", "Lucas", "Absorb", "Wall", "Crossing", "End", "Race", "Window"]
NOTE = ("-- Copied by holdouts/1RB1RA_1LC0RF_1LD1LC_1LE0LB_0LF---_1RA1RB/py/port_mirror.py from\n"
        "-- holdouts/" + PASCAL + "/lean/{name}.lean, imports renamed; do not edit by hand.\n")

# Each machine: its id, the Pascal state it starts in, phi (Pascal state -> this machine's state), and the first
# right turn of the Pascal table started there: (step, zone W nearest letter first, prefix p).  The first right
# turn was found with py/mirror_run.py; Lean checks it (`start`).
MACHINES = {
    "1RB1RA_1LC0RF_1LD1LC_1LE0LB_0LF---_1RA1RB": dict(
        id=7085, start="D", phi=dict(A="D", B="E", C="F", D="A", E="B", F="C"),
        turn=(46, [True, False, True, False, False, False], False)),
    "1RB1RC_1RC1RB_1LD0RA_1LE1LD_1LF0LC_0LA---": dict(
        id=144803, start="C", phi=dict(A="E", B="F", C="A", D="B", E="C", F="D"),
        turn=(26, [True, False, True, False], True)),
}


def lb(b):
    return "true" if b else "false"


def lst(w):
    return "[" + ", ".join(lb(b) for b in w) + "]"


MIRROR = r'''import Machine
import P75625.Race
import P75625.Lucas

/-!
# {name} is the table of 1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF in a mirror, started in {start}

Generated by `py/port_mirror.py` in the folder of 1RB1RA_1LC0RF_1LD1LC_1LE0LB_0LF---_1RA1RB; do not edit by hand.

Read 1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF (bbchallenge 75625, namespace `H75625`, its Lean files copied
unchanged into `P75625/`) in a mirror and rename its states A, B, C, D, E, F to {phis}: the result is this
machine's table, halting transition included (`is_mirror`).  The blank tape is its own mirror image, so the run of
this machine from blank tape is, cell for cell in the mirror, the run of the Pascal table started in state {start}
(`halts_iff`).  Every theorem of that folder is about the table and holds for any surrounding tape, so it holds here
with the two sides of the tape exchanged (`mirror_steps`):

* `bounce`: at a right turn of the Pascal table, which here is a *left* turn in {E}, one bounce maps the zone (now
  right of the head) to the next row of Pascal's triangle mod 2; `closed_form` (Lucas' theorem) is a statement about
  lists and is used as it stands;
* `halts_of_odd`, `halts_of_odd_wall`: an odd frozen block (now left of the head) followed by `0 1` halts, whatever
  the zone, clean or walled;
* `start`: the first such turn of this run, step {n}, is the list state `EO {W} none {p}` of `P75625/End.lean`;
* `not_halts_of_arun`: if the list machine `arun` of `P75625/End.lean` never fails from that state, this machine
  never halts.  So this holdout is the same list program as the Pascal machine, started in another state.
-/

namespace TM

section
variable {{Q₁ Q₂ : Type}} {{δ₁ : Q₁ → Bool → Option (Bool × Dir × Q₁)}} {{δ₂ : Q₂ → Bool → Option (Bool × Dir × Q₂)}}
  {{φ : Q₂ → Q₁}} [DecidableEq Q₂]

theorem mirror_steps (hδ : ∀ q b, δ₁ (φ q) b = (δ₂ q b).map (fun t => (t.1, t.2.1.flip, φ t.2.2)))
    (n : Nat) (c : Cfg Q₂) : steps δ₁ n (mirrorCfg φ c) = (steps δ₂ n c).map (mirrorCfg φ) := by
  induction n generalizing c with
  | zero => rfl
  | succ n ih =>
    rw [steps, steps, step_mirrorCfg δ₂ δ₁ φ hδ c]
    cases step δ₂ c with
    | none => rfl
    | some c' => exact ih c'

end

end TM

namespace H{id}

open TM

/-- Pascal-table states to this machine's states. -/
def φ : H75625.St → St
{phidef}

/-- **The mirror.**  This machine's table is the Pascal table read in a mirror, states renamed by `φ`. -/
theorem is_mirror (q : H75625.St) (b : Bool) :
    trans (φ q) b = (H75625.trans q b).map (fun t => (t.1, t.2.1.flip, φ t.2.2)) := by
  cases q <;> cases b <;> rfl

/-- A mirror image of a Pascal-table configuration: the Pascal tape `⟨L, cons a R, q⟩` is `⟨R, cons a L, φ q⟩` here. -/
theorem mirror_cons (L R : Tape) (a : Bool) (q : H75625.St) :
    mirrorCfg φ (⟨L, cons a R, q⟩ : H75625.Config) = ⟨R, cons a L, φ q⟩ := rfl

/-- Runs of the Pascal table are runs of this machine in the mirror. -/
theorem mirror_steps (n : Nat) (c : H75625.Config) :
    steps n (mirrorCfg φ c) = (H75625.steps n c).map (mirrorCfg φ) :=
  TM.mirror_steps is_mirror n c

theorem halts_mirror (c : H75625.Config) : Halts H75625.trans c ↔ Halts trans (mirrorCfg φ c) :=
  halts_of_map H75625.trans trans (mirrorCfg φ) (step_mirrorCfg H75625.trans trans φ is_mirror) c

/-- **Same halting question as the Pascal table started in {start}.** -/
theorem halts_iff : HaltsFromBlank ↔ Halts H75625.trans (blankCfg .{start}) := by
  rw [halts_mirror]
  show Halts trans (blankCfg .A) ↔ Halts trans (mirrorCfg φ (blankCfg .{start}))
  rw [mirrorCfg_blank]; rfl

/-- **One bounce** (`H75625.bounce`, mirrored).  Zone `ws` right of the head, frozen tape `1 1 1 L` left of it. -/
theorem bounce (ws : List Bool) (p : Bool) (L : Tape) :
    steps (1 + 4 * ws.length + H75625.lsteps p (H75625.par true ws) + 4 * ws.length + 2)
      ⟨cons true (cons true L), cons true (H75625.zl ws (H75625.pre p)), .{E}⟩ =
      some ⟨L, cons true (H75625.zl (H75625.tmap ws) (H75625.pre (H75625.npre p ws))), .{E}⟩ := by
  have h := mirror_steps (1 + 4 * ws.length + H75625.lsteps p (H75625.par true ws) + 4 * ws.length + 2)
    ⟨H75625.zl ws (H75625.pre p), cons true (cons true (cons true L)), .E⟩
  rw [H75625.bounce] at h
  exact h

/-- `k` bounces against a frozen block of `2k + 1` cells (`H75625.bounces`, mirrored). -/
theorem bounces (k : Nat) (ws : List Bool) (p : Bool) (L : Tape) : ∃ n p',
    steps n ⟨rep k [true, true] L, cons true (H75625.zl ws (H75625.pre p)), .{E}⟩ =
      some ⟨L, cons true (H75625.zl (H75625.titer k ws) (H75625.pre p')), .{E}⟩ := by
  obtain ⟨n, p', h⟩ := H75625.bounces k ws p L
  refine ⟨n, p', ?_⟩
  have h' := mirror_steps n ⟨H75625.zl ws (H75625.pre p), cons true (rep k [true, true] L), .E⟩
  rw [h] at h'
  exact h'

/-- **An odd frozen block followed by `0 1` halts**, whatever the zone (`H75625.halts_of_odd`, mirrored). -/
theorem halts_of_odd (k : Nat) (ws : List Bool) (p : Bool) (L : Tape) :
    Halts trans ⟨rep k [true, true] (cons false (cons true L)), cons true (H75625.zl ws (H75625.pre p)), .{E}⟩ :=
  (halts_mirror _).mp (H75625.halts_of_odd k ws p L)

/-- The same with a wall `1 0` between the head and the zone (`H75625.halts_of_odd_wall`, mirrored). -/
theorem halts_of_odd_wall (k : Nat) (ws : List Bool) (p : Bool) (L : Tape) :
    Halts trans ⟨rep k [true, true] (cons false (cons true L)),
      cons true (app [false, true] (H75625.zl ws (H75625.pre p))), .{E}⟩ :=
  (halts_mirror _).mp (H75625.halts_of_odd_wall k ws p L)

/-- The first right turn of the Pascal table started in {start}: step {n}, E on the last 1, zone `{W}`, prefix {p}. -/
theorem start_pascal : H75625.steps {n} (blankCfg .{start}) = some (H75625.cfg (.EO {W} none {p})) := by
  rfl

/-- The same moment in this machine's run: step {n}, {E} on the last 1 at the left end, zone to its right. -/
theorem start : steps {n} init = some (mirrorCfg φ (H75625.cfg (.EO {W} none {p}))) := by
  have h := mirror_steps {n} (blankCfg .{start})
  rw [start_pascal, mirrorCfg_blank] at h
  exact h

/-- **The holdout as a list question.**  If the list machine of `P75625/End.lean` never fails from
`EO {W} none {p}`, this machine never halts from blank tape. -/
theorem not_halts_of_arun (h : ∀ k, (H75625.arun k (.EO {W} none {p})).isSome) : ¬ HaltsFromBlank := by
  rw [halts_iff]
  intro hh
  rw [halts_iff_of_steps' H75625.trans start_pascal] at hh
  exact H75625.not_halts_of_astep _ h hh

end H{id}
'''


def main():
    src = os.path.join(HOLD, PASCAL, "lean")
    for name, m in MACHINES.items():
        dst = os.path.join(HOLD, name, "lean", "P75625")
        os.makedirs(dst, exist_ok=True)
        for f in FILES:
            with open(os.path.join(src, f + ".lean")) as fh:
                text = fh.read()
            text = re.sub(r"^import (?!TM\b)(\w+)$", r"import P75625.\1", text, flags=re.M)
            with open(os.path.join(dst, f + ".lean"), "w") as fh:
                fh.write(NOTE.format(name=f) + text)
        phi = m["phi"]
        n, W, p = m["turn"]
        out = MIRROR.format(
            name=name, id=m["id"], start=m["start"], E=phi["E"], n=n, W=lst(W), p=lb(p),
            phis=", ".join(phi[s] for s in "ABCDEF"),
            phidef="\n".join("  | .%s => .%s" % (s, phi[s]) for s in "ABCDEF"))
        with open(os.path.join(HOLD, name, "lean", "Mirror.lean"), "w") as fh:
            fh.write(out)
        if name != HOME:
            with open(os.path.join(HERE, "..", "lean", "Fail.lean")) as fh:
                text = fh.read()
            with open(os.path.join(HOLD, name, "lean", "Fail.lean"), "w") as fh:
                fh.write("-- Copied by holdouts/" + HOME + "/py/port_mirror.py from that folder's lean/Fail.lean; "
                         "do not edit by hand.\n" + text)
        print("wrote", name)


if __name__ == "__main__":
    main()
