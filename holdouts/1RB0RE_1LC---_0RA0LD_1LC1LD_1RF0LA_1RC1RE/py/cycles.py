"""Generate lean/Cycles.lean: the particle rules, each one full cycle of the head (left end -> first runner -> left end).

usage (from the repo root):  python3 holdouts/MACHINE/py/cycles.py        writes lean/Cycles.lean
                             python3 holdouts/MACHINE/py/cycles.py show   prints the rules in block notation

Block notation.  Cut the tape into blocks 1^k 0 and write each block as its k.  The background (1110)^n is n 3-blocks,
written D^n; every other block is a particle (or a pair of particles in contact): 1 and 5 are walls (jump 2),
2 is a runner (jump 3), 0 = runner + 1-wall, 4 = runner + 5-wall.  At the start of a sweep the head is in the
rightward state on the second cell of the leftmost block, and that block is the left gadget (4 when idle).

Each rule is a configuration at the start of a sweep, for all gap sizes a, b, c >= 0 and every tape R to the right
(the frozen part, which the cycle never reads), and the configuration at the start of the next sweep.  The end is
found by symbolic simulation (tools/py/bbtools/symtm.py), the Lean proof is generated by `symtm.prove` (single steps
by `rfl`, the background crossed in one go by `TM.cross_r` / `TM.cross_l`).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
M = os.path.basename(os.path.dirname(HERE))
LEAN = os.path.join(HERE, "..", "lean")
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools import symtm  # noqa: E402
from bbtools.symtm import Blank, Config, prove, rules_file, run  # noqa: E402

# The rules are written for 1RB0RE_1LC---_0RA0LD_1LC1LD_1RF0LA_1RC1RE (rightward state F); the twin is the same
# table with the states renamed, so its rules are these with the names mapped.
BASE = "1RB0RE_1LC---_0RA0LD_1LC1LD_1RF0LA_1RC1RE"
RENAME = {"1RB1RF_0RC0LE_1RD0RF_1LB---_1LB1LE_1RA0LC": dict(zip("ABCDEF", "CDBEFA"))}
NS = {BASE: "H135173", "1RB1RF_0RC0LE_1RD0RF_1LB---_1LB1LE_1RA0LC": "H42815"}

G = "0^inf 0 0 1 F>"     # the sweep start: blank, then the gadget block whose first 1 is left of the head
RULES = [
    # name, start (after G), block notation before -> after, what it says
    ("runner_step", "(1110)^a+1 110 (1110)^b+1 R", "4 D^a 2 D^(b+1)", "4 D^(a+1) 2 D^b",
     "The runner moves one block to the right per cycle."),
    ("wall1_step", "(1110)^a+1 10 (1110)^c+1 110 (1110)^b+1 R", "4 D^a 1 D^(c+1) 2 D^(b+1)",
     "4 D^(a-1) 5 D^(c+2) 2 D^b  (a = 0: 6 D^(c+2) 2 D^b)",
     "A wall left of the runner flips from 1 to 5 and moves one block left (into the gadget when a = 0)."),
    ("wall5_step", "(1110)^a+1 111110 (1110)^c+1 110 (1110)^b+1 R", "4 D^a 5 D^(c+1) 2 D^(b+1)",
     "4 D^a 1 D^(c+3) 2 D^b", "A wall left of the runner flips from 5 to 1 and stays."),
    ("runner_hits_1", "(1110)^a+1 110 10 (1110)^b+1 R", "4 D^a 2 1 D^(b+1)", "4 D^(a+1) 0 D^(b+1)",
     "The runner reaches a 1-wall: they fuse into a 0-block."),
    ("runner_leaves_1", "(1110)^a+1 0 (1110)^b+1 R", "4 D^a 0 D^(b+1)",
     "4 D^(a-1) 5 2 D^b  (a = 0: 6 2 D^b)", "The runner leaves the wall behind it (now a 5)."),
    ("runner_hits_5", "(1110)^a+1 110 111110 (1110)^b+1 R", "4 D^a 2 5 D^(b+1)", "4 D^(a+1) 4 D^(b+1)",
     "The runner reaches a 5-wall: they fuse into a 4-block."),
    ("runner_leaves_5", "(1110)^a+1 11110 (1110)^b+1 R", "4 D^a 4 D^(b+1)", "4 D^a 1 D 2 D^b",
     "The runner leaves the wall behind it (now a 1)."),
    ("runners_merge", "(1110)^a+1 110 110 (1110)^b+1 R", "4 D^a 2 2 D^(b+1)", "4 D^(a+1) 1 D^(b+1)",
     "The runner reaches a resting runner: the two become one 1-wall."),
    ("gadget_6", "111110 (1110)^c+1 110 (1110)^b+1 R", "6 D^(c+1) 2 D^(b+1)", "2 D^(c+3) 2 D^b",
     "Absorbing a wall at the left end, step 2 of 3."),
    ("gadget_2", "10 (1110)^c+1 110 (1110)^b+1 R", "2 D^(c+1) 2 D^(b+1)", "3 D^(c+2) 2 D^b",
     "Absorbing a wall at the left end, step 3 of 3."),
    ("gadget_emit", "110 (1110)^c+1 110 (1110)^b+1 R", "3 D^(c+1) 2 D^(b+1)", "4 2 D^c 2 D^(b+1)",
     "The left end emits a new runner (the old one rests from now on)."),
]


def rename(s, mp):
    return " ".join(mp[p[0]] + ">" if len(p) == 2 and p[1] == ">" else p for p in s.split())


def cycle_end(m, start, fstate):
    c = Config.parse(start)

    def stop(c):
        return (c.state == fstate and not c.steps.is_zero() and len(c.left) == 4 and isinstance(c.left[0], Blank)
                and c.left[1:] == [0, 0, 1])
    return run(m, c, stop, max_moves=5000)


def main(argv):
    mp = RENAME.get(M, {s: s for s in "ABCDEF"})
    m = symtm.Machine.parse(M)
    fstate = "ABCDEF".index(mp["F"])
    ths, rows = [], []
    for name, tail, before, after, doc in RULES:
        start = rename(G, mp) + " " + tail
        fin = cycle_end(m, start, fstate)
        end = str(fin)
        rows.append((name, before, after, str(fin.steps), doc))
        if argv[:1] == ["show"]:
            continue
        th, _ = prove(M, name, start, end, doc=f"{doc} Blocks: `{before}` ⟶ `{after}`. `{start}` ⟶ `{end}`.",
                      count_first=True)
        ths.append(th)
    if argv[:1] == ["show"]:
        for r in rows:
            print("%-16s %-28s -> %-44s %s" % r[:4])
        return
    with open(os.path.join(LEAN, "Cycles.lean"), "w") as f:
        f.write(rules_file("Machine", NS[M], ths,
                           f"One-cycle particle rules of {M}, generated by `py/cycles.py`; do not edit by hand.  Each "
                           "theorem holds for every gap size and every tape `R` right of the runner, which the cycle "
                           "never reads."))
    print("wrote Cycles.lean (%d rules)" % len(ths))


if __name__ == "__main__":
    main(sys.argv[1:])
