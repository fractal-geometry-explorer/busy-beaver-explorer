"""Generate lean/Rules.lean (the background words that a sweep crosses whole) and lean/Halt.lean (what a halt needs).

usage (from the repo root):  python3 holdouts/MACHINE/py/rules.py      writes both files

Rules.lean: each rule is proved along the symbolic run of tools/py/bbtools/symtm.py (single steps by `rfl`, the copies
crossed at once by `TM.cross_r` / `TM.cross_l`), for every n and every tape L, R.  Tapes are written left to right,
`S>` is the head in state S on the next cell, `(w)^n` is n copies of w.

Halt.lean: a case analysis on every configuration (state and the few cells near the head), then the run from blank.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
M = os.path.basename(os.path.dirname(HERE))
LEAN = os.path.join(HERE, "..", "lean")
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools import symtm  # noqa: E402
from bbtools.symtm import Config, Ctx, prove, rules_file, run  # noqa: E402

NS = "H135173"
RULES = [
 [
  "cross_r_1110",
  "r",
  "L F> (1110)^n R",
  "Rightward, F crosses the background: each `1110` becomes `0111`."
 ],
 [
  "cross_r_1011",
  "r",
  "L F> (1011)^n R",
  "Rightward, F over another phase of the background."
 ],
 [
  "cross_r_0111",
  "r",
  "L E> (0111)^n R",
  "Rightward, E over another phase of the background."
 ],
 [
  "cross_l_1110",
  "l",
  "L (1110)^n D> 1 R",
  "Leftward, D crosses the background, moving each 0 one cell left."
 ],
 [
  "cross_l_1101",
  "l",
  "L (1101)^n D> 1 R",
  "Leftward, D over another phase."
 ],
 [
  "cross_l_1011",
  "l",
  "L (1011)^n C> 1 R",
  "Leftward, C over another phase."
 ],
 [
  "cross_l_0111",
  "l",
  "L (0111)^n D> 0 R",
  "Leftward, D over another phase."
 ]
]
HALT = (3, [('F', [('r', 0, 0), ('r', 1, 0), ('r', 2, 0), ('r', 3, 1)])], 'The only way to the halt (B reading 1) is F reading `0 0 0 1`: F writes 1 and C, A, B follow on the next three cells.')


def end_of(start, side):
    m = symtm.Machine.parse(M)

    def stop(c):
        if side == "r":
            return isinstance(c.right[0], Ctx) and not c.steps.is_zero()
        return len(c.left) == 1 and isinstance(c.left[0], Ctx) and not c.steps.is_zero()
    return run(m, Config.parse(start), stop, max_moves=400)


def halt_file(k, pats, doc):
    def one(state, conds):
        return " ∧ ".join([f"s = .{state}"] + [f"{sd} {i} = {'true' if v else 'false'}" for sd, i, v in conds])
    concl = " ∨ ".join(f"({one(*p)})" for p in pats) if len(pats) > 1 else one(*pats[0])
    allc = [c for p in pats for c in p[1]]
    rcells = max(max([i for sd, i, v in allc if sd == "r"] + [0]) + 1, k + 1)
    lcells = max(max([i for sd, i, v in allc if sd == "l"] + [-1]) + 1, k)
    splits = " <;> ".join([f"cases e{i} : r {i}" for i in range(rcells)] + [f"cases f{i} : l {i}" for i in range(lcells)])
    pat = re.sub(r"\b([rl]) (\d)", r"c.\1 \2", concl).replace("s = ", "c.st = ")
    return f"""import Machine
import Blank

/-!
# What a halt needs

Generated by `py/rules.py`; do not edit by hand.

{doc}

`halt_pred` is about every configuration, reachable or not: a case analysis on the state and the cells near the
head.  `halt_needs_pattern` applies it to the run from blank tape (the first steps are covered by
`blank_runs_kernel`).  Kernel only.
-/

namespace {NS}

open TM

/-- A configuration whose run is defined for {k} steps but not for {k + 1} (it halts at step {k + 1}) has this shape. -/
theorem halt_pred (l r : Tape) (s : St)
    (h3 : steps {k} ⟨l, r, s⟩ ≠ none) (h4 : steps {k + 1} ⟨l, r, s⟩ = none) :
    {concl} := by
  cases s <;> {splits} <;>
    simp_all [TM.steps, TM.step, trans, TM.cons, TM.tail]

theorem steps_split (a b : Nat) (c c'' : Config) (h : TM.steps trans (a + b) c = some c'') :
    ∃ c', TM.steps trans a c = some c' ∧ TM.steps trans b c' = some c'' := by
  induction a generalizing c with
  | zero => exact ⟨c, rfl, by simpa using h⟩
  | succ a ih =>
    have e : a + 1 + b = (a + b) + 1 := by omega
    rw [e] at h
    cases hs : TM.step trans c with
    | none => simp [TM.steps, hs] at h
    | some d =>
      rw [TM.steps_succ_of_step trans (a + b) hs] at h
      obtain ⟨c', h1, h2⟩ := ih d h
      exact ⟨c', by rw [TM.steps_succ_of_step trans a hs]; exact h1, h2⟩

/-- If the machine halts from blank tape, the run passes through a configuration of this shape. -/
theorem halt_needs_pattern (h : HaltsFromBlank) :
    ∃ n c, steps n init = some c ∧ ({pat}) := by
  obtain ⟨n, c', h1, h2⟩ := h
  obtain ⟨c0, hc0⟩ := blank_runs_kernel
  by_cases hn : n < {k + 1}
  · exfalso
    have hz := TM.steps_halt trans h1 h2 ({k} - n)
    have e : n + ({k} - n + 1) = {k + 1} := by omega
    rw [e] at hz
    have e2 : (10000 : Nat) = {k + 1} + {10000 - k - 1} := by omega
    rw [e2] at hc0
    obtain ⟨c5, h5⟩ := TM.steps_le trans hc0
    rw [hz] at h5
    cases h5
  · obtain ⟨m, rfl⟩ : ∃ m, n = m + {k} := ⟨n - {k}, by omega⟩
    obtain ⟨c, hc, hk⟩ := steps_split m {k} init c' h1
    refine ⟨m, c, hc, ?_⟩
    obtain ⟨l, r, s⟩ := c
    have hk1 : steps {k + 1} ⟨l, r, s⟩ = none := by
      have := TM.steps_halt trans hk h2 0
      simpa using this
    exact halt_pred l r s (by show TM.steps trans {k} _ ≠ none; rw [hk]; simp) hk1

end {NS}
"""


def main():
    ths = []
    for name, side, start, doc in RULES:
        fin = end_of(start, side)
        ths.append(prove(M, name, start, fin, doc=f"{doc} `{start}` ⟶ `{fin}`.")[0])
    with open(os.path.join(LEAN, "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, ths,
                           f"Sweeps of {M} across its background words, generated by `py/rules.py`; do not edit by hand."))
    k, pats, doc = HALT
    with open(os.path.join(LEAN, "Halt.lean"), "w") as f:
        f.write(halt_file(k, pats, doc))
    print("wrote Rules.lean (%d rules) and Halt.lean" % len(ths))


if __name__ == "__main__":
    main()
