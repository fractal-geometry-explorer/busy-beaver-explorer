"""Writes lean/Rules.lean: the moves an excursion of 1RB0RB_0LC1RA_1RD1LC_1LA1LE_1LF0LD_---0LA is made of, proved
from the symbolic trace by bbtools.symtm.  Run from the machine folder: python3 py/gen_rules.py > lean/Rules.lean"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB0RB_0LC1RA_1RD1LC_1LA1LE_1LF0LD_---0LA"
RULES = [
    ("halt_00", "L 0 0 D> 1 R", "L F> 0 1 1 R",
     "The only way to halt: D on a 1 with `0 0` to its left; two steps later F reads 0 (`step_none_iff`)."),
    ("sweep_d", "L A> (11)^n R", "L (01)^n A> R",
     "The right sweep: A crosses `11` pairs, turning each into `01`."),
    ("sweep_b", "L A> (01)^n R", "L (11)^n A> R",
     "...and `01` pairs into `11`."),
    ("tail_odd", "L 1 0 (11)^a 1 0 1 1 B> 0^inf", "L F> 1 1 1 (01)^a 0 1 1 0 0^inf",
     "At the right end, an odd last block `1^(2a+1)` is crossed by the D/E pass, which ends in F on the 1 to its left."),
    ("tail_even", "L 0 (11)^a 1 1 0 1 1 B> 0^inf", "L D> 0 0 (10)^a 1 0 1 1 0 0^inf",
     "An even last block `1^(2a+2)` ends the pass in D on the 0 to its left."),
    ("de_pass", "L 0 1 (11)^n D> 1 R", "L D> 0 0 1 (01)^n R",
     "The D/E pass inside the tape: `0 1^(2n+2)` with D on its right end becomes `0 0 1 (01)^n`, D on the 0."),
    ("lead_odd", "0^inf (11)^a D> 1 R", "0^inf F> 0 1 1 (01)^a R",
     "A pass that reaches the leftmost block when it is odd (`1^(2a+1)` next to blank tape) halts: F reads 0."),
    ("lead_even", "L 0 0 1 (11)^a D> 1 R", "L 1 1 1 1 (11)^a A> R",
     "When the block next to `0 0` is even the pass turns into a right sweep instead, and the tape grows by two 1s."),
    ("zig_1", "L 0 1 0 1 0 1 (11)^j A> 0 0 R", "L A> 0 0 1 1 0 1 1 (11)^j 0 R",
     "A left-going round: `0101 01 1^(2j)` with A on `00` becomes `00 1101 1^(2j) 10`; the head moves 2j+6 cells left."),
    ("zig_2", "L 0 1 0 1 (11)^j 0 1 A> 0 0 R", "L A> 0 0 1 1 0 (10)^j 1 1 0 R",
     "The other left-going round: `0101 1^(2j) 01` with A on `00` becomes `00 1101 (01)^j 10`."),
    ("ret_d", "L A> 1 1 1 1 (11)^i 1 0 R", "L 0 1 0 1 (01)^i 0 1 A> R",
     "A right-going round: `1111 (11)^i 10` becomes `0101 (01)^i 01` (the A/B sweep with a carry)."),
    ("ret_b", "L A> 1 1 1 1 (01)^i 1 0 R", "L 0 1 0 1 (11)^i 0 1 A> R",
     "...and `1111 (01)^i 10` becomes `0101 (11)^i 01`."),
]

thms = []
for name, s, e, doc in RULES:
    t, _ = prove(M, name, s, e, doc=doc)
    thms.append(t)
doc = """# The moves of an excursion

Generated by `py/gen_rules.py` with `bbtools.symtm.prove`: every theorem is a run of the machine for all values of
the variables and every tape `L`, `R`, proved by `rfl` steps and the shift rules `cross_l`, `cross_r`.
Left tapes are written nearest the head first, so `(10)^k` on the page is `rep k [false, true]` here."""
print(rules_file("Machine", "H77294", thms, doc), end="")
