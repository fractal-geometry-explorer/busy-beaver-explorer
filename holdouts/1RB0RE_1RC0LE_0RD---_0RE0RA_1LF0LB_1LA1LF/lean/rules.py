"""Generate Rules.lean: shift rules of 1RB0RE_1RC0LE_0RD---_0RE0RA_1LF0LB_1LA1LF, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(10)^n` is n
copies of `10`, `0^inf` is blank tape, L and R are any tape.  What the rules mean is in ../README.md.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1RC0LE_0RD---_0RE0RA_1LF0LB_1LA1LF"

RULES = [
    ('e_right', 'L 0 E> (10)^n 0 R', 'L (10)^n 0 E> 0 R',
     'E runs right over a block of `10` words, moving the 0 in front of it to its far side.'),
    ('d_right', 'L 0 D> (110)^n 0 R', 'L (101)^n 0 D> 0 R',
     'D runs right over a block of `110` words, shifting it by one cell.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=30)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H96519", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
