"""Generate Rules.lean for 1RB---_1RC1RF_1LD1RE_1LB1LD_0RB0RC_1RA0LF: the halting context and the shift rules over the words of its tape, proved along the symbolic run of tools/py/bbtools/symtm.py
(single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB---_1RC1RF_1LD1RE_1LB1LD_0RB0RC_1RA0LF"

RULES = [
    ('halt_ctx', 'L B> 1 0 1 R', 'L 1 1 A> 1 R',
     'B on a 1 with 0 1 after it: F reads the 0, writes 1 and hands A a 1 (the halting transition).'),
    ('run_B_100', 'L B> (100)^n R', 'L (111)^n B> R',
     'B crosses n copies of `100` to the right in 3n steps, leaving `111`.'),
    ('run_B_1110_0', 'L 0 B> (1110)^n R', 'L (1111)^n 0 B> R',
     'B crosses n copies of `1110` to the right in 8n steps, leaving `1111` (carrying `0`).'),
    ('run_C_100', 'L C> (100)^n R', 'L (101)^n C> R',
     'C crosses n copies of `100` to the right in 3n steps, leaving `101`.'),
    ('run_C_1000_0', 'L 0 C> (1000)^n R', 'L (1111)^n 0 C> R',
     'C crosses n copies of `1000` to the right in 14n steps, leaving `1111` (carrying `0`).'),
    ('back_D_1_1', 'L (1)^n D> 1 R', 'L D> 1 (1)^n R',
     'D crosses n copies of `1` to the left in 1n steps, leaving `1` (carrying `1`).'),
    ('run_E_001', 'L E> (001)^n R', 'L (011)^n E> R',
     'E crosses n copies of `001` to the right in 3n steps, leaving `011`.'),
    ('run_E_0001_01', 'L 0 1 E> (0001)^n R', 'L (1111)^n 0 1 E> R',
     'E crosses n copies of `0001` to the right in 14n steps, leaving `1111` (carrying `0 1`).'),
    ('run_E_1110', 'L E> (1110)^n R', 'L (1111)^n E> R',
     'E crosses n copies of `1110` to the right in 12n steps, leaving `1111`.'),
    ('run_E_0111', 'L E> (0111)^n R', 'L (1111)^n E> R',
     'E crosses n copies of `0111` to the right in 8n steps, leaving `1111`.'),
    ('back_F_1_1', 'L (1)^n F> 1 R', 'L F> 1 (0)^n R',
     'F crosses n copies of `1` to the left in 1n steps, leaving `0` (carrying `1`).'),
    ('run_F_001', 'L F> (001)^n R', 'L (111)^n F> R',
     'F crosses n copies of `001` to the right in 3n steps, leaving `111`.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H98843", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
