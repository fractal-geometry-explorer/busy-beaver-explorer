"""Generate Rules.lean: shift rules of 1RB0RE_1RC0RA_0LD0LB_0LA1LE_1LC1LF_0LA---, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(10)^n` is n
copies of `10`, `0^inf` is blank tape, L and R are any tape.  What the rules mean is in ../README.md.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1RC0RA_0LD0LB_0LA1LE_1LC1LF_0LA---"

RULES = [
    ('left_end', '0^inf A> 1 0 0 (10)^n+2 1 1 R', '0^inf (10)^n+5 1 0 0 E> R',
     'The bounce at the left end: the first block `1 0 0 (10)^(n+2) 1 1` is rewritten as `(10)^(n+5) 1 0 0` on the way right.'),
    ('left_block', 'L 1 (10)^n+5 D> 1 0 1 R', 'L D> 1 0 1 (01)^n+2 1 1 0 1 1 0 1 R',
     'The leftward pass crosses one block `(10)^(n+5)` from the separator on its right to the one on its left, re-encoding it.'),
    ('right_end', 'L 1 (10)^n+5 1 B> 0 0^inf', 'L D> 1 0 1 (01)^n+4 1 1 0 0^inf',
     'The bounce at the right end: the last block is re-encoded and the leftward pass starts.'),
    ('pass_start', '0^inf A> 1 0 0 R', '0^inf 1 0 1 0 1 0 A> 0 R',
     'A pass starts: the head leaves the left end and stands before the first block.'),
    ('pass_right', 'L A> 0 (10)^n 1 1 1 0 1 R', 'L (10)^n 1 1 0 1 0 A> 0 R',
     'The rightward pass crosses one block `(10)^n 1 1 1 0 1`, re-encoding its separator as `1 1 0 1 0`.'),
    ('pass_front', 'L A> 0 (10)^p+3 1 (10)^q+3 1 1 1 0 R', 'L A> 1 0 (01)^p+3 0 1 (10)^q+2 1 1 1 0 R',
     'The turn at the frontier `(10)^(p+3) 1 (10)^(q+3)`: one copy of `10` moves from the second block towards the first.'),
    ('pass_sep', 'L 1 1 0 1 0 A> 1 0 R', 'L D> 1 0 1 0 1 0 1 R',
     'The leftward pass crosses a re-encoded separator.'),
    ('pass_left', 'L (10)^n+3 D> 1 0 1 0 1 0 1 R', 'L A> 1 0 (01)^n 1 1 0 1 1 0 1 0 1 0 1 R',
     'The leftward pass crosses one block `(10)^(n+3)`.'),
    ('pass_end', '0^inf 1 0 1 0 1 0 A> 1 0 R', '0^inf A> 1 0 0 1 0 1 0 1 R',
     'The pass ends at the left end; the first block has lost one copy of `10`.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=30)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H8754", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
