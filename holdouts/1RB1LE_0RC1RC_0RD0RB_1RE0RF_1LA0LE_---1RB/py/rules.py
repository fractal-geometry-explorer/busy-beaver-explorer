"""Writes lean/Rules.lean, proved by bbtools.symtm (shift rules, `rfl`, `omega`) for all counts and every tape L.

The two steady visit-to-visit rules at the right end (E> on the blank cell right of the tape):

  P(a, b) = L 1^(2j) 0 0 1 1 0 (10)^(a+1) 0 0 (10)^b 1 E>   ->  Q = L 1^(2j) 0 0 1 1 0 (10)^(a+1) 1 1 0 (10)^(b+1) 1 E>
  Q                                                             ->  L 1^(2j+2) 0 0 1 1 0 (10)^a 0 0 (10)^(b+3) 1 E>

The end of a countdown (a = 0): three more visits (`exit1`, `exit2`, `exit3`), then the *erase sweep* (`erase`): E
goes left, turns the whole (10) run into 1s and the whole run of 1s into 0s, and arrives left of it in A; with a
countdown one level up to the left (`outer_step`) that one makes its step and the head enters the erased gap in D.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file, run, Config, Blank, Rep
from bbtools.machine import Machine

M = "1RB1LE_0RC1RC_0RD0RB_1RE0RF_1LA0LE_---1RB"
NS = "H2090"

RULES = [
    ("visit_p", "P(a, b): the 0 0 between the two (10) runs becomes 1 1 0, the right run gains one 10.",
     "L 0 (11)^j 0 0 1 1 0 (10)^a+1 0 0 (10)^b 1 E> 0^inf", "visit"),
    ("visit_q", "Q: the 1 1 run on the left gains two 1s, the middle run loses one 10, the right run gains two.",
     "L 0 (11)^j 0 0 1 1 0 (10)^a+1 1 1 0 (10)^b 1 E> 0^inf", "visit"),
    ("exit1", "The countdown at a = 0, first visit.",
     "L 0 (11)^j+1 0 0 1 1 0 0 0 (10)^b+1 1 E> 0^inf", "visit"),
    ("exit2", "The countdown at a = 0, second visit.",
     "L 0 (11)^j+1 0 0 1 1 0 1 (10)^b+1 1 E> 0^inf", "visit"),
    ("exit3", "The countdown at a = 0, third visit.",
     "L 0 (11)^j+1 0 0 1 0 0 (10)^b+1 1 E> 0^inf", "visit"),
    ("erase", "The erase sweep: from the visit `0 0 1^(2j+4) 0 0 1 1 (10)^(b+1) 1 E>` the head goes left, turns the "
     "(10) run into 1s and the 1s into 0s, and stands in A left of the gap.",
     "L 0 0 (11)^j+2 0 0 1 1 (10)^b+1 1 E> 0^inf", "left"),
    ("outer_step", "The same with a countdown one level up to the left: its (10) run loses two copies, its run of "
     "1s gains two 1s, and the head enters the gap of 0s in D.",
     "L 0 1 1 0 0 1 (10)^c+2 0 (11)^j+3 0 0 1 1 (10)^b+1 1 E> 0^inf", "gap"),
]


def end_of(start, kind="visit"):
    m = Machine.parse(M)
    c = Config.parse(start)
    first = [True]

    def stop(cc):
        if first[0]:
            first[0] = False
            return False
        if kind == "left":
            return cc.state == 0 and len(cc.left) == 1
        if kind == "gap":
            return cc.state == 3 and isinstance(cc.right[0], Rep) and cc.right[0].word == (0, 0)
        return cc.state == 4 and len(cc.right) == 1 and isinstance(cc.right[0], Blank)
    run(m, c, stop, rotate=True)
    return c


def main(show=False):
    thms = []
    for name, doc, start, kind in RULES:
        fin = end_of(start, kind)
        if show:
            print(name, start, '->', fin, file=sys.stderr)
            continue
        t, _ = prove(M, name, start, fin, doc=doc, rotate=True, count_first=True, max_seg=60)
        thms.append(t)
    if not show:
        print(rules_file("Machine", NS, thms,
                         "The countdown at the right end, its last visits and the erase sweep. Generated by `py/rules.py`."), end="")


if __name__ == "__main__":
    main(len(sys.argv) > 1)
