"""Write lean/InnerRules.lean: the end pieces of the inner sweeps of a nested run (the two phases X and Y of the
moving right end, the frontier) and the start of a nested run, proved by tools/py/bbtools/symtm.py.
usage (from the repository root): python3 holdouts/<M>/py/gen_inner.py > holdouts/<M>/lean/InnerRules.lean"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools import symtm

M = "1RB0LE_1RC0LD_1RD1RA_1RE0RB_0LA0RF_1LE---"
NS = "H23154"
# the rules are written with the state names of the other machine of the pair, 1RB0LC_1RC1RE_1RD0RA_0LE0RF_1RA0LD_1LD---,
# whose table is this one with the states renamed A->B, B->C, C->D, D->E, E->A (`REN` maps them here)
REN = {'A': 'B', 'B': 'C', 'C': 'D', 'D': 'E', 'E': 'A'}
RULES = [
    ("x_left", "Phase X of the inner right end (`0 1 1 A>1 0` here, the frontier right of it): the left pass starts, D "
     "on the separator of the last block.", "L 0 11 E> 1 R", "L D> 0 0 0 1 R"),
    ("y_left", "Phase Y of the inner right end (`0 1 1 1 0 F>0 1 0`): the left pass starts.",
     "L 0 111 0 F> 0 1 0 R", "L D> 0 0 0 1 0 1 1 0 R"),
    ("x_right", "The right pass comes back to an X end and eats one passed digit 1 (`0 0 1 0 1 0`) of the frontier: "
     "the block in hand is closed (`1^5`) and the end is now in phase Y.",
     "L 111 A> 0 0 1 0 0 0 1 0 1 0 R", "L 11111 0 111 0 F> 0 1 0 R"),
    ("y_right", "The right pass comes back to a Y end: the block in hand is closed and the end is in phase X again.",
     "L 111 A> 0 0 1 0 1 1 0 R", "L 11111 0 11 E> 1 0 R"),
    ("nest_start", "The left pass reaches a leftmost block `1^(6j+6)` (even) with a digit 1 after it: the block "
     "becomes `1^3` and `2j+1` digits 0, and the inner run starts with its right end in phase Y.",
     "0^inf 111111 (111111)^j D> 0 0 0 1 0 1 0 R", "0^inf 111 (011011)^j 011 0111 0 F> 0 1 0 R"),
]

def ren(p):
    if not REN: return p
    out = []
    for tok in p.split(" "):
        if len(tok) == 2 and tok[1] == ">" and tok[0] in REN: tok = REN[tok[0]] + ">"
        out.append(tok)
    return " ".join(out)

def main():
    thms = []
    for name, doc, a, b in RULES:
        t, fin = symtm.prove(M, name, ren(a), ren(b), doc=doc, max_seg=30)
        thms.append(t)
    print(symtm.rules_file("Machine", NS, thms,
        "# The end pieces of an inner sweep\n\nGenerated by `py/gen_inner.py` with `tools/py/bbtools/symtm.py`; do "
        "not edit.  Every rule holds for all values of its variables and all tapes `L`, `R` around it."))

if __name__ == "__main__":
    main()
