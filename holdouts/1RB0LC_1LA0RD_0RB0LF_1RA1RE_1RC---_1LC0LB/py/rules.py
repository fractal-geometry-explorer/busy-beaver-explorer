"""Generate lean/Rules.lean: rules of 1RB0LC_1LA0RD_0RB0LF_1RA1RE_1RC---_1LC0LB, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB0LC_1LA0RD_0RB0LF_1RA1RE_1RC---_1LC0LB)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LC_1LA0RD_0RB0LF_1RA1RE_1RC---_1LC0LB"

RULES = [
    ('d_r_001', 'L D> (001)^n R', 'L (110)^n D> R',
     'D sweeps right over copies of `001` (3 steps a copy).'),
    ('a_r_010', 'L A> (010)^n R', 'L (101)^n A> R',
     'A sweeps right over copies of `010` (3 steps a copy).'),
    ('b_r_100', 'L B> (100)^n R', 'L (011)^n B> R',
     'B sweeps right over copies of `100` (3 steps a copy).'),
    ('d_r_1011011', 'L 0 D> (1011011)^n R', 'L (1011011)^n 0 D> R',
     'D sweeps right over copies of `1011011` (23 steps a copy).'),
    ('b_r_1101101', 'L B> (1101101)^n R', 'L (1011011)^n B> R',
     'B sweeps right over copies of `1101101` (23 steps a copy).'),
    ('c_r_0010', 'L C> (0010)^n R', 'L (1011)^n C> R',
     'C sweeps right over copies of `0010` (6 steps a copy).'),
    ('b_r_0100', 'L 0 B> (0100)^n R', 'L (1011)^n 0 B> R',
     'B sweeps right over copies of `0100` (6 steps a copy).'),
    ('a_l_1011', 'L (1011)^n A> 1 R', 'L A> 1 (1000)^n R',
     'A sweeps left over copies of `1011` (4 steps a copy).')
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H102105", thms,
                                "Rules of 1RB0LC_1LA0RD_0RB0LF_1RA1RE_1RC---_1LC0LB, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
