"""Write lean/FarEnd.lean: what lean/Lockstep.lean needs generated.

* The far end of the tape.  Two tapes that differ only by k periods `1010` at the left end (just left of the leftmost
  1) behave alike everywhere except when the head steps onto that leftmost 1.  There the head is in one of five
  states (those a left move leads to).  In C and D it crosses the k periods and comes back out with the same cells as
  for k = 0: `far_C_run`, `far_D_run` (k + 1 periods) and `far_D0_run` (none), symbolic runs of
  tools/py/bbtools/symtm.py for every k.  In F it halts at once in both; A and B are the excluded case.
* The tables of the three other machines that share this machine's table up to renaming and mirroring, generated by
  tools/py/bbtools/leangen.py (in sub-namespaces, since every folder calls its own file `Machine`).

usage (from the repo root):
  python3 holdouts/1RB0RA_1LC0RE_0LD0LB_1LA1LF_1RA0LF_1LC---/py/farend.py > holdouts/1RB0RA_1LC0RE_0LD0LB_1LA1LF_1RA0LF_1LC---/lean/FarEnd.lean
  python3 holdouts/1RB0RA_1LC0RE_0LD0LB_1LA1LF_1RA0LF_1LC---/py/farend.py check     # the far-end table by simulation
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))

M = "1RB0RA_1LC0RE_0LD0LB_1LA1LF_1RA0LF_1LC---"
SISTERS = [("M40600", "1RB1RF_1LC0LB_1RE0LD_1LB0RF_0RA0RC_1RE---"),
           ("M103746", "1RB0LE_0RC0RA_1RD1RF_1LA0LD_1LD0RF_1RB---"),
           ("M131976", "1RB0LF_1RC0RB_1LD0RA_0LE0LC_1LB1LF_1LD---")]
RUNS = [("far_C_run", "0^inf (1010)^k C> 1 X", "0^inf (1010)^k 1 0 1 0 1 B> X",
         "C on the leftmost 1, k periods `1010` and blank tape to its left: it crosses them and comes back out in B."),
        ("far_D_run", "0^inf (1010)^k+1 D> 1 X", "0^inf (1010)^k+1 1 0 1 0 0 A> X",
         "D on the leftmost 1, k + 1 periods `1010` and blank tape to its left: it crosses them and comes back out in A."),
        ("far_D0_run", "0^inf D> 1 X", "0^inf 1 0 1 0 0 A> X",
         "D on the leftmost 1, blank tape to its left: it comes back out in A with the cells of `far_D_run`.")]


def table():
    T = {}
    for s, part in enumerate(M.split("_")):
        for r in range(2):
            x = part[3 * r:3 * r + 3]
            T[(s, r)] = None if x[2] == "-" else (int(x[0]), 1 if x[1] == "R" else -1, ord(x[2]) - 65)
    return T


def excursion(T, left, q):
    """Head in state q on a 1 at cell 0, `left` (nearest first) to its left, blank beyond; run until the head is on
    cell 1.  Returns ('halt',) or (state, cells from cell 0 leftwards up to the last 1)."""
    cells = {0: 1}
    for i, b in enumerate(left):
        cells[-1 - i] = b
    pos, st, n = 0, q, 0
    while pos < 1:
        t = T[(st, cells.get(pos, 0))]
        if t is None:
            return ("halt",)
        cells[pos] = t[0]
        pos += t[1]
        st = t[2]
        n += 1
        assert n < 10 ** 5
    E = [cells.get(i, 0) for i in range(0, min(cells) - 1, -1)]
    while E and E[-1] == 0:
        E.pop()
    return ("ABCDEF"[st], E, n)


def check():
    """For each state a left move leads to: k = 0 against k = 1, 2, 3 periods."""
    T = table()
    ok = True
    for q in (0, 1, 2, 3, 5):
        outs = [excursion(T, [0, 1, 0, 1] * k, q) for k in range(4)]
        if outs[0][0] == "halt":
            same = all(o[0] == "halt" for o in outs)
        else:
            same = all(o[0] == outs[0][0] and o[1] == outs[0][1] + [0, 1, 0, 1] * k and o[2] == outs[0][2] + 8 * k
                       for k, o in enumerate(outs))
        print("%s on the leftmost 1: %s  k = 0: %s" % ("ABCDEF"[q], "same for every k" if same else "DIFFERS", outs[0]))
        if q in (2, 3, 5) and not same:
            ok = False
    print("ALL CHECKS PASS (C, D and F agree for k = 0..3; A and B are the excluded case)" if ok else "FAILED")
    return ok


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "check":
        sys.exit(0 if check() else 1)
    from bbtools.symtm import prove
    from bbtools.leangen import machine_lean
    out = ["import Machine", "", "/-!", "# The far end of the tape, and the three sister tables", "",
           "Generated by `py/farend.py`; do not edit by hand.  See `Lockstep.lean`.", "-/", "",
           "namespace H32883", "", "open TM", ""]
    for name, start, end, doc in RUNS:
        out.append(prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=40)[0])
        out.append("")
    for ns, text in SISTERS:
        s = machine_lean(text, ns)
        body = s[s.index("/-- The states"):s.index("abbrev Config")].rstrip() + "\n"
        out += ["namespace %s" % ns, "", body, "end %s" % ns, ""]
    out.append("end H32883")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
