"""Generate lean/Rules.lean for 1RB0RA_1LC0RE_0LD0LB_1LA1LF_1RA0LF_1LC---: one-cycle rules of its phases, proved along the symbolic run of
tools/py/bbtools/symtm.py (single steps by `rfl`, shift rules by TM.cross_r/cross_l, re-bracketing by TM.rep_rotate).

usage (from the repo root): python3 holdouts/1RB0RA_1LC0RE_0LD0LB_1LA1LF_1RA0LF_1LC---/py/rules.py > holdouts/1RB0RA_1LC0RE_0LD0LB_1LA1LF_1RA0LF_1LC---/lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RA_1LC0RE_0LD0LB_1LA1LF_1RA0LF_1LC---"
NS = next(l.split()[1] for l in open(os.path.join(HERE, "..", "lean", "Machine.lean")) if l.startswith("namespace "))

RULES = [
    ("a_right",
     "L A> (0101)^n R",
     "L (1010)^n A> R",
     "Going right, A flips every pair: `01 01` becomes `10 10` (4 steps per word)."),
    ("b_left",
     "L (01)^n B> 0 R",
     "L B> 0 (01)^n R",
     "Going left, B crosses pairs `01` without changing them."),
    ("c_left",
     "L (10)^n C> 1 R",
     "L C> 1 (10)^n R",
     "Going left, C crosses pairs `10` without changing them."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
