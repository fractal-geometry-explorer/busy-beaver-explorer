#!/usr/bin/env python3
"""Write the generated Coq files of the busycoq proof of bbchallenge 32641 from the output of macro37.

usage: gen37.py --bounds           prints the arguments for macro37 (K J T t1 ... t15)
       gen37.py K J macro37-output OUTDIR
Writes H32641_Data.v (block size, keys, tables), H32641_Bound.v (the macro configurations at the chunk
boundaries), H32641_Chunk<i>.v (one vm_compute check per chunk) and H32641_Reach.v (the chain).  Nothing here
is trusted: Coq recomputes every table entry and every chunk.

The hand-written files H32641.v, H32641_Sim.v and H32641_Period.v go with K = 16, J = 6 and 16 chunks
(H32641.v names cfg16 and the blank block 2^6 of cfg0).  J = 6 puts the head of the target configuration
(cell -311 at step 16,730,681,219) on the last cell of a block, so that the target is a block crossing."""
import sys, os

TFINAL, NCHUNK = 16730681219, 16
if sys.argv[1] == '--bounds':
    print(16, 6, TFINAL, ' '.join(str(TFINAL * i // NCHUNK) for i in range(1, NCHUNK)))
    sys.exit(0)

K, J, src, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3], sys.argv[4]
cfgs, keys, maxin = [], {}, None
lines = open(src).read().split('\n')
i = 0
while i < len(lines):
    w = lines[i].split()
    if w and w[0] == 'CFG':
        L = lines[i + 1].split()[1:]; R = lines[i + 2].split()[1:]
        cfgs.append(dict(cross=int(w[1]), t=int(w[2]), pos=int(w[3]), q=w[4], f=int(w[5]), L=L, R=R))
        i += 3; continue
    if w and w[0] == 'KEY':
        keys.setdefault((w[1], int(w[2])), []).append(int(w[3]))
    if w and w[0] == 'MAXIN': maxin = int(w[1])
    i += 1
assert maxin is not None and maxin < 4000
HDR = "(* Generated by gen/gen37.py from the output of gen/macro37.c (K = %d, J = %d). Do not edit. *)\n" % (K, J)

def plist(xs, ind='  '):
    if not xs: return '[]'
    rows, row = [], []
    for x in xs:
        row.append(str(x))
        if len(row) == 16: rows.append('; '.join(row)); row = []
    if row: rows.append('; '.join(row))
    return '[' + (';\n' + ind + ' ').join(rows) + ']'

B = lambda f: 'true' if f else 'false'
with open(os.path.join(out, 'H32641_Data.v'), 'w') as o:
    o.write("(** * bbchallenge 32641: the block table for blocks of %d cells\n\n" % K)
    o.write("    [keys q f] are the blocks that the run from blank tape meets in state [q] entering from the left\n"
            "    ([f = true]) or from the right ([f = false]), as proposed by the C simulator.  The tables are\n"
            "    computed from them in Coq ([build], evaluated by [vm_compute]); [T_ok] holds by [build_ok]. *)\n")
    o.write(HDR)
    o.write("From Coq Require Import Lists.List PArith FMapPositive. Import ListNotations.\n"
            "From BusyCoq Require Export H32641_Sim.\nSet Default Goal Selector \"!\".\nLocal Open Scope positive_scope.\n\n")
    o.write("Definition FUEL : nat := 4000%nat.\n")
    o.write("(** A blank block of %d cells. *)\nDefinition bl : positive := %d.\n\n" % (K, 1 << K))
    for q in 'ABCDEF':
        for f in (1, 0):
            ks = sorted(keys.get((q, f), []))
            o.write("Definition keys_%s%d : list positive :=\n  %s.\n" % (q, f, plist(ks)))
            o.write("Definition tbl_%s%d : PositiveMap.t Ent := Eval vm_compute in build FUEL %s %s keys_%s%d.\n\n" % (q, f, q, B(f), q, f))
    for nm, pre in (('keys', 'keys_'), ('T', 'tbl_')):
        ty = 'list positive' if nm == 'keys' else 'PositiveMap.t Ent'
        o.write("Definition %s (q : state) (f : bool) : %s :=\n  match q, f with\n" % (nm, ty))
        for q in 'ABCDEF':
            o.write("  | %s, true => %s%s1 | %s, false => %s%s0\n" % (q, pre, q, q, pre, q))
        o.write("  end.\n\n")
    o.write("""Lemma T_ok : forall q f b e, PositiveMap.find b (T q f) = Some e -> mkEntry FUEL q f b = Some e.
Proof.
  intros q f. assert (E : T q f = build FUEL q f (keys q f)) by (destruct q, f; vm_compute; reflexivity).
  rewrite E. apply build_ok.
Qed.

Lemma bl_ok : forallb (fun s => match s with S0 => true | S1 => false end) (dec bl) = true.
Proof. vm_compute. reflexivity. Qed.

(** One macro step, and [n] of them. *)
Definition ms : MC -> MC := mstep FUEL T bl.
Definition run (n : positive) (c : MC) : MC := Pos.iter ms c n.

Lemma run_ok : forall n c c', run n c = c' -> msem c -->* msem c'.
Proof. exact (mrun_to FUEL T bl T_ok bl_ok). Qed.
""")

def cfg(c):
    return "mkM\n  %s\n  %s\n  %s %s" % (plist(c['L']), plist(c['R']), c['q'], B(c['f']))
with open(os.path.join(out, 'H32641_Bound.v'), 'w') as o:
    o.write("(** * bbchallenge 32641: the macro configurations at the chunk boundaries\n\n"
            "    [cfg i] is the configuration after [cross] block crossings (step [t] of the machine), as proposed\n"
            "    by the C simulator; the chunk files check that each one leads to the next. *)\n")
    o.write(HDR)
    o.write("From Coq Require Import Lists.List PArith. Import ListNotations.\n"
            "From BusyCoq Require Export H32641_Data.\nLocal Open Scope positive_scope.\n\n")
    o.write("(** Blank tape: the head on the first cell of a block%s. *)\n" % (", with a blank block of %d cells on its left" % J if J else ""))
    o.write("Definition cfg0 : MC := mkM %s [] A true.\n\n" % ('[%d]' % (1 << J) if J else '[]'))
    for i, c in enumerate(cfgs):
        o.write("(** After %d crossings, step %d, head at cell %d. *)\n" % (c['cross'], c['t'], c['pos']))
        o.write("Definition cfg%d : MC := %s.\n\n" % (i + 1, cfg(c)))
prev = 0
for i, c in enumerate(cfgs):
    n = c['cross'] - prev; prev = c['cross']
    with open(os.path.join(out, 'H32641_Chunk%d.v' % (i + 1)), 'w') as o:
        o.write("(** * bbchallenge 32641: chunk %d of the run from blank tape, %d block crossings *)\n" % (i + 1, n))
        o.write(HDR)
        o.write("From Coq Require Import PArith.\nFrom BusyCoq Require Import H32641_Bound.\n\n")
        o.write("Lemma chunk%d : run %d%%positive cfg%d = cfg%d.\nProof. vm_cast_no_check (eq_refl cfg%d). Qed.\n" % (i + 1, n, i, i + 1, i + 1))
n = len(cfgs)
with open(os.path.join(out, 'H32641_Reach.v'), 'w') as o:
    o.write("(** * bbchallenge 32641: the run from blank tape, chunk by chunk\n\n"
            "    [cfg0] is the blank tape and [cfg%d] the macro configuration after %s block crossings\n"
            "    (step %s of the machine).  Each chunk is one [vm_compute] of the macro simulator. *)\n"
            % (n, format(cfgs[-1]['cross'], ','), format(cfgs[-1]['t'], ',')))
    o.write(HDR)
    o.write("From BusyCoq Require Export H32641_Bound.\nFrom BusyCoq Require Import")
    for i in range(1, n + 1): o.write(("\n " if i % 6 == 1 and i > 1 else "") + " H32641_Chunk%d" % i)
    o.write(".\nSet Default Goal Selector \"!\".\n\nTheorem reach : msem cfg0 -->* msem cfg%d.\nProof.\n" % n)
    for i in range(1, n): o.write("  eapply evstep_trans; [exact (run_ok _ _ _ chunk%d) |].\n" % i)
    o.write("  exact (run_ok _ _ _ chunk%d).\nQed.\n" % n)
print(len(cfgs), 'chunks;', sum(len(v) for v in keys.values()), 'keys')
