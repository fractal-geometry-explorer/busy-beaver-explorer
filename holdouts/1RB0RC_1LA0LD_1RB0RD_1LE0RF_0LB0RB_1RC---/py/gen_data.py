"""Write lean/Data.lean: the stretch X of the bouncer phase, from the tape at step 16,730,681,219.

usage: gcc -O2 -o dumpT py/dumpT.c && ./dumpT 1RB0RC_1LA0LD_1RB0RD_1LE0RF_0LB0RB_1RC--- 16730681219 | python3 py/gen_data.py
The dump line is `t pos state lo hi cells(lo..hi)`; the head is on the left end in state A and the cells are
0 (1010001000100)^7 X.  X is written to Lean as a hex string (4 cells per digit, the last digit padded with 0s).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
t, pos, st, lo, hi, cells = sys.stdin.read().split()
assert t == "16730681219" and pos == lo and st == "A", (t, pos, lo, st)
ACCB = "1010001000100"
pre = "0" + ACCB * 7
assert cells.startswith(pre)
X = cells[len(pre):]
assert X.endswith("1")
pad = X + "0" * (-len(X) % 4)
hx = "".join("%x" % int(pad[i:i + 4], 2) for i in range(0, len(pad), 4))
body = f'  "{hx}"'
out = f"""import Machine

/-!
# The stretch X of the bouncer phase

Generated by `py/gen_data.py` from the tape at step 16,730,681,219 (C simulator `py/dumpT.c`); {len(X):,} cells,
written in hex, four cells per digit.  Only `native_decide` ever evaluates it.
-/

namespace H32641

/-- Hex digits to cells, most significant bit first. -/
def hexBits (s : String) : List Bool :=
  s.toList.flatMap fun c =>
    let v := if c.toNat ≤ 57 then c.toNat - 48 else c.toNat - 87
    [v / 8 % 2 == 1, v / 4 % 2 == 1, v / 2 % 2 == 1, v % 2 == 1]

def Xhex : String :=
{body}

/-- X: the tape right of the blocks, {len(X):,} cells, ending with a 1. -/
@[irreducible] def X : List Bool := (hexBits Xhex).take {len(X)}

end H32641
"""
open(os.path.join(HERE, "../lean/Data.lean"), "w").write(out)
print(len(X), len(hx))
