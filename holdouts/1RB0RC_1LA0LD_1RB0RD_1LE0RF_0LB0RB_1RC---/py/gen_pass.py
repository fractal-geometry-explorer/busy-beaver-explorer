"""Write lean/Pass.lean: the three symbolic passes of one period of the bouncer phase (bbtools.symtm.prove).

C k = 0^inf A> 0 (1010001000100)^k X 0^inf.  With R an unknown tape on the right:
  pass1: 0^inf A> 0 (1010001000100)^(n+1) R   ->  0^inf (0101010010001)^(n+1) 1 B> R          (rightward)
  pass2: 0^inf (0101010010001)^(n+1) E> 0 R   ->  0^inf (0101010010001)^(n+1) 0 1 1 B> R      (left and back)
  pass3: 0^inf (0101010010001)^(n+1) E> 0 R   ->  0^inf A> 0 1 0 (1000100010010)^(n+1) R      (leftward, to the end)
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../../../tools/py"))
from bbtools import symtm as S

M = "1RB0RC_1LA0LD_1RB0RD_1LE0RF_0LB0RB_1RC---"
V = "(0101010010001)^n+1"
RULES = [
    ("pass1", "0^inf A> 0 (1010001000100)^n+1 R", f"0^inf {V} 1 B> R",
     "From the left end, the head crosses the `n+1` blocks `1010001000100` to the right (37 steps each)."),
    ("pass2", f"0^inf {V} E> 0 R", f"0^inf {V} 0 1 1 B> R",
     "Back from the window: across the blocks to the left end, two cells more there, and across them again."),
    ("pass3", f"0^inf {V} E> 0 R", "0^inf A> 0 1 0 (1000100010010)^n+1 R",
     "Back from the window the second time: across the blocks to the left end, where the period ends."),
]
thms = []
for name, a, b, doc in RULES:
    txt, fin = S.prove(M, name, a, b, doc=doc, rotate=True)
    print(name, fin, fin.steps)
    thms.append(txt)
out = S.rules_file("Machine", "H32641", thms,
                   "Generated by `py/gen_pass.py` with `bbtools.symtm.prove`: the three symbolic passes of one "
                   "period of the bouncer phase. Kernel only.")
open(os.path.join(HERE, "../lean/Pass.lean"), "w").write(out)
