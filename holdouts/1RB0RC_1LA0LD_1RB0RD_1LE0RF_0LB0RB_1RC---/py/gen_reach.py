"""Write the Lean files of the reach of C 7 from blank tape: lean/Bound.lean (the configurations at the chunk
boundaries, as block lists), lean/Chunk1.lean .. lean/Chunk8.lean (one native_decide check each) and lean/Reach.lean.

usage: gcc -O2 -o dumpT py/dumpT.c
       ./dumpT 1RB0RC_1LA0LD_1RB0RD_1LE0RF_0LB0RB_1RC--- $(python3 py/gen_reach.py --bounds) | python3 py/gen_reach.py
The run of T = 16,730,681,219 steps is cut at T*i/8 (i = 1..7); each boundary is the tape dumped by the C
simulator there, cut into blocks of 16 cells at the head (`MC` with side = true, see lean/Block.lean).  The C
simulator only supplies the boundaries: each chunk is checked by Lean (`chkF`, `native_decide`).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.join(HERE, "../lean")
T = 16730681219
N = 8
BOUNDS = [T * i // N for i in range(1, N)]
if sys.argv[1:] == ["--bounds"]:
    print(" ".join(map(str, BOUNDS)))
    sys.exit()


def blocks_R(cells):
    cells = cells + "0" * (-len(cells) % 16)
    return "".join("%04x" % sum(int(cells[i + j]) << j for j in range(16)) for i in range(0, len(cells), 16))


def blocks_L(nf):          # nearest-first cells; a block's cells left to right are the chunk reversed
    nf = nf + "0" * (-len(nf) % 16)
    out = []
    for i in range(0, len(nf), 16):
        c = nf[i:i + 16][::-1]
        out.append("%04x" % sum(int(c[j]) << j for j in range(16)))
    return "".join(out)


lines = [l for l in sys.stdin.read().splitlines() if l.strip()]
assert len(lines) == N - 1
ms = []
for k, line in enumerate(lines):
    t, pos, st, lo, hi, cells = line.split()
    assert int(t) == BOUNDS[k]
    p = int(pos) - int(lo)
    ms.append((st, blocks_L(cells[:p][::-1]), blocks_R(cells[p:])))

hdr = "import Block\n\n"
body = ["/-!\n# The configurations at the chunk boundaries of the reach\n\nGenerated by `py/gen_reach.py` from the "
        "tape dumped by `py/dumpT.c` at steps T*i/8 (T = 16,730,681,219); blocks of 16 cells, four hex digits each, "
        "the head on the first cell of the first right block.\n-/\n\nnamespace H32641\n\nopen TM\n",
        "/-- Blank tape. -/\ndef m0 : MC := ⟨[], [], .A, true⟩\n"]
for k, (st, L, R) in enumerate(ms, 1):
    body.append(f"/-- The configuration at step {BOUNDS[k-1]:,}. -/\n@[irreducible] def m{k} : MC :=\n"
                f"  ⟨hexBlocks \"{L}\",\n   hexBlocks \"{R}\", .{st}, true⟩\n")
body.append("end H32641\n")
open(os.path.join(LEAN, "Bound.lean"), "w").write(hdr + "\n".join(body))

ts = [0] + BOUNDS + [T]
for i in range(1, N + 1):
    d = ts[i] - ts[i - 1]
    tgt = f"(toF m{i})" if i < N else "finalF"
    imp = "import Bound\n" + ("import Final\n" if i == N else "")
    open(os.path.join(LEAN, f"Chunk{i}.lean"), "w").write(
        f"{imp}\n/-! Chunk {i} of {N} of the reach (generated by `py/gen_reach.py`): steps {ts[i-1]:,} to {ts[i]:,}, "
        f"by the block simulator, evaluated with `native_decide`. -/\n\nnamespace H32641\n\nopen TM\n\n"
        f"theorem chunk{i} : chkF tbl m{i-1} {d} {tgt} = true := by native_decide\n\nend H32641\n")

reach = ["import TblOk\n" + "".join(f"import Chunk{i}\n" for i in range(1, N + 1)),
         "/-!\n# The run from blank tape reaches C 7\n\nGenerated by `py/gen_reach.py`: the eight chunks chained. "
         "With `nonhalt_of_reach` (lean/Period.lean) this closes the proof that the machine never halts.\n-/\n",
         "namespace H32641\n\nopen TM\n"]
for i in range(1, N + 1):
    d = ts[i] - ts[i - 1]
    if i < N:
        reach.append(f"theorem reach{i} : steps {d} (sem m{i-1}) = some (sem m{i}) := by\n"
                     f"  have h := chkF_ok tblOk chunk{i}\n  rw [toF_ok] at h\n  exact h\n")
    else:
        reach.append(f"theorem reach{i} : steps {d} (sem m{i-1}) = some (C 7) := by\n"
                     f"  have h := chkF_ok tblOk chunk{i}\n  rw [finalF_ok] at h\n  exact h\n")
chain = f"reach{N}"
for i in range(N - 1, 0, -1):
    chain = f"steps_seq trans reach{i} ({chain})"
reach.append("/-- **The reach**: 16,730,681,219 steps from blank tape end at `C 7`. -/\n"
             f"theorem reach_C7 : steps {T} init = some (C 7) := by\n"
             f"  have h := {chain}\n  rw [show sem m0 = init from sem_m0] at h\n  exact steps_congr trans (by omega) h\n")
reach.append("/-- **The machine never halts from blank tape.** -/\n"
             "theorem nonhalting : ¬ HaltsFromBlank := nonhalt_of_reach (m := 6) reach_C7\n")
reach.append("end H32641\n")
open(os.path.join(LEAN, "Reach.lean"), "w").write("\n".join(reach))
print("ok", [len(L) + len(R) for _, L, R in ms])
