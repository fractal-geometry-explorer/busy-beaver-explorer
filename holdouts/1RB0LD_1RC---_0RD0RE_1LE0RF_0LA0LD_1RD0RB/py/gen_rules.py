"""Generate lean/Rules.lean for 1RB0LD_1RC---_0RD0RE_1LE0RF_0LA0LD_1RD0RB (run from the repository root): the two cycle rules of the right-end counter.
Each rule is proved by bbtools.symtm for all values of its variables and every tape L (or R) the run does not
look at."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools import symtm
from bbtools.machine import Machine
M = "1RB0LD_1RC---_0RD0RE_1LE0RF_0LA0LD_1RD0RB"
NS = "H122390"
m = Machine.parse(M)
RULES = [
    ('cycA', 'One cycle at the right end: L (11)^(n+1) (01)^(p+1) D> turns one 11 into two 01.',
     'L (11)^n+1 (01)^p+1 D> 0^inf', 'L (11)^n (01)^p+3 D> 0^inf'),
    ('cycB', 'One cycle at the right end: L (11)^(n+2) (01)^(p+1) 0 0 1 0 (01)^(q+1) D> turns two 11 into two 01 and one more 01 at the end.',
     'L (11)^n+2 (01)^p+1 0 0 1 0 (01)^q+1 D> 0^inf', 'L (11)^n (01)^p+3 0 0 1 0 (01)^q+2 D> 0^inf'),
]
out = []
for name, doc, a, b in RULES:
    txt, fin = symtm.prove(m, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=30)
    out.append(txt)
sys.stdout.write(symtm.rules_file("Machine", NS, out, f"Rules of {M}; generated by `py/gen_rules.py`; do not edit by hand."))
