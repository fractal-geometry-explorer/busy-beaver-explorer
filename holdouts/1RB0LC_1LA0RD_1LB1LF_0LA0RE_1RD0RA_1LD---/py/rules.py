"""Generate Rules.lean for 1RB0LC_1LA0RD_1LB1LF_0LA0RE_1RD0RA_1LD---: shift rules (one copy of a word crossed by the head in a state, so a whole run of
copies is crossed at once), each proved along a symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`,
shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, prove, rules_file, run  # noqa: E402

M = "1RB0LC_1LA0RD_1LB1LF_0LA0RE_1RD0RA_1LD---"
NS = "H105641"

# (name, start, doc): the end is the configuration right after the run of copies is crossed
RULES = [
    ('a_left',
     'L (100)^n A> 1 R',
     'A runs left over triples 100, turning each into 110 (A1 → 0LC, C0 → 1LB, B0 → 1LA): the leftward sweep that turns the right-sweep form 100 of the background into its left-sweep form 110.'),
    ('b_left',
     'L (001)^n B> 0 R',
     'The same sweep entered in phase B: each 001 becomes 101.'),
    ('c_left',
     'L (010)^n C> 0 R',
     'The same sweep entered in phase C: each 010 becomes 011.'),
]

DOC = """Shift rules of the leftward sweep. Generated by py/rules.py (tools/py/bbtools/symtm.py); do not edit by hand. The background of the tape is the period-3 word 100 (as the head leaves it after a sweep to the right) or 110 (after a sweep to the left); these rules cross a whole run of copies at once."""


def after_cross(start):
    trace = []
    run(Machine.parse(M), Config.parse(start), lambda c: any(t[0] == "cross" for t in trace), trace=trace)
    return next(t[2] for t in trace if t[0] == "cross")


def main():
    ths = []
    for name, start, doc in RULES:
        ths.append(prove(M, name, start, after_cross(start), doc=doc)[0])
    sys.stdout.write(rules_file("Machine", NS, ths, DOC))


if __name__ == "__main__":
    main()
