"""Write lean/Tables.lean, the tables of the non-halting certificate, from cert_data.json.

phases (from "regimes.py phases"): the left-end turn configurations of one round of each regime R0-R3.
ends: for each template, the phase and the [k, j] reached at the end of an epoch (found by running the
symbolic checker on template t at [0, j+200] and matching the configuration it stops at).
usage: python3 cert.py        (rewrites ../lean/Tables.lean)
"""
import json, os
HERE=os.path.dirname(os.path.abspath(__file__))
data=json.load(open(os.path.join(HERE,'cert_data.json')))
ph=data['phases']; ends=data['ends']; fuel=data['startFuel']
BOFF=6
REGS=['R0','R1','R2','R3']
def lits(s): return ['.b %s'%('true' if ch=='1' else 'false') for ch in s]
def lin(c,a): return '⟨%d, [%s]⟩'%(c,', '.join(map(str,a)))
def toks(d):
    out=lits('00')+['.r ft %s'%lin(4,[3])]+lits(d['sep'])+['.r ft %s'%lin(d['B']%3+BOFF,[0,3])]
    for x in d['rest']:
        out+= ['.r ft %s'%lin(x,[])] if isinstance(x,int) else lits(x)
    return '[' + ', '.join(out) + ']'
tpl=[]; nxt=[]; dj=[]; starts=[]
for R in REGS:
    P=ph[R]; p=len(P); base=len(tpl); starts.append(base)
    for i,d in enumerate(P):
        tpl.append((R,i,d))
        if i+1<p: B2=P[i+1]['B']; n=base+i+1
        else: B2=P[0]['B']+ph[R+'_dB']; n=base
        nxt.append(n)
        d0=d['B']-d['B']%3-BOFF; d1=B2-B2%3-BOFF
        dj.append((d1-d0)//3)
starts.append(len(tpl))
m=[0]*len(tpl)
for a,b in zip(starts,starts[1:]):
    for i in range(a,b-1): m[i+1]=m[i]+2-dj[i]
pot=[x-min(m) for x in m]
assert min(pot)>=0
eT=[ends[str(t)][1] for t in range(len(tpl))]
e1=[ends[str(t)][2] for t in range(len(tpl))]
e2=[ends[str(t)][3] for t in range(len(tpl))]
L=lambda xs: '[' + ', '.join(map(str,xs)) + ']'
names=['%s_%d'%(R,i) for R,i,d in tpl]
out=f"""import SymCheck
import Machine

/-! # Tables of the non-halting certificate (generated by `py/cert.py`)

The 62 phase templates of the four regimes R0–R3 ({', '.join(names[a] for a in starts[:-1])} start them), in the
variables `[k, j]`: `B> 00 (01)^(3k+4) 000 (01)^(3j+β) rest` with `rest` and `β` fixed per phase. -/

namespace H36670

open TM TM.Sym

def ft : List Bool := [false, true]

def tpl : List (MC St) := [
""" + ',\n'.join('  ⟨[], %s, .B⟩'%toks(d) for (R,i,d) in tpl) + f"""]

def nT : Nat := {len(tpl)}

def tplAt (t : Nat) : MC St := tpl.getD t ⟨[], [], .A⟩

/-- The phase after a round. -/
def nxt : List Nat := {L(nxt)}

/-- The increment of `j` in a round. -/
def dj : List Nat := {L(dj)}

/-- The potential offset of each phase. -/
def potL : List Nat := {L(pot)}

def pot (t : Nat) : Nat := potL.getD t 0

/-- End of an epoch: the phase reached, and `k`, `j` there (`k = j + endC1`, `j = endC2`). -/
def endT : List Nat := {L(eT)}
def endC1 : List Nat := {L(e1)}
def endC2 : List Nat := {L(e2)}

def startFuel : Nat := {fuel}

end H36670
"""
open(os.path.join(HERE,'..','lean','Tables.lean'),'w').write(out)
print('ok')
