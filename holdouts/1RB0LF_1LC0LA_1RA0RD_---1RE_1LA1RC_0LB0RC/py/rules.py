"""Shift rules and halting situations of 1RB0LF_1LC0LA_1RA0RD_---1RE_1LA1RC_0LB0RC, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LF_1LC0LA_1RA0RD_---1RE_1LA1RC_0LB0RC/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LF_1LC0LA_1RA0RD_---1RE_1LA1RC_0LB0RC"
NS = "H36670"
DOC = """# Shift rules of 1RB0LF_1LC0LA_1RA0RD_---1RE_1LA1RC_0LB0RC

The two sweeps of the bouncer: going right, B (with a 1 behind it) turns each `010101` into `011001`
(`sweep_right`, 14 steps a copy); going left, C (with `110` ahead) turns each `011001` back into `010101`
(`sweep_left`, 22 steps a copy).  The halting situations: only D reading a 0 halts, and `C> 1 0`, `E> 1 1 0`,
`F> 1 1 0` and `D> 1 1 1 0` lead there.

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('sweep_right', 'L 1 B> (010101)^n R', 'L (011001)^n 1 B> R', 'The rightward sweep: B, with a 1 behind it, turns each `010101` into `011001`, 14 steps a copy.'),
    ('sweep_left', 'L (011001)^n C> 1 1 0 R', 'L C> 1 1 0 (010101)^n R', 'The leftward sweep: C, with `110` ahead of it, turns each `011001` back into `010101`, 22 steps a copy.'),
]

HALTS = [
    ('halt_C', 'C> 1 0', 1, '`C> 1 0` halts: C erases the 1 and moves right onto the 0 in state D.'),
    ('halt_E', 'E> 1 1 0', 2, '`E> 1 1 0` halts: E moves right in state C and the previous case applies.'),
    ('halt_F', 'F> 1 1 0', 2, '`F> 1 1 0` halts: F erases the 1, moves right in state C, and C> 1 0 follows.'),
    ('halt_D', 'D> 1 1 1 0', 3, '`D> 1 1 1 0` halts after three steps.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [prove(M, name, a, b, doc=doc, count_first=True)[0] for name, a, b, doc in RULES]
    thms += [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
