"""Generate Rules.lean for 1RB0LF_1LC1RC_0RA0LD_0LE1RE_0RF0LC_1RC---: the halting context and the shift rules over the words of its tape, proved along the symbolic run of tools/py/bbtools/symtm.py
(single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LF_1LC1RC_0RA0LD_0LE1RE_0RF0LC_1RC---"

RULES = [
    ('halt_ctx', 'L 1 C> 1 1 R', 'L 1 0 F> 1 R',
     'C on a 1 between two 1s: D, E and F follow and F reads a 1 (the halting transition).'),
    ('halt_ctx_A', 'L 1 A> 1 R', 'L F> 1 0 R',
     'A on a 1 with a 1 on its left hands F that 1 (the halting transition).'),
    ('halt_ctx_E', 'L E> 0 1 R', 'L 0 F> 1 R',
     'E on a 0 with a 1 after it hands F a 1 (the halting transition).'),
    ('run_A_1_0', 'L 0 A> (1)^n R', 'L (1)^n 0 A> R',
     'A crosses n copies of `1` to the right in 3n steps, leaving `1` (carrying `0`).'),
    ('run_B_100', 'L B> (100)^n R', 'L (101)^n B> R',
     'B crosses n copies of `100` to the right in 3n steps, leaving `101`.'),
    ('run_C_10_1', 'L 1 C> (10)^n R', 'L (10)^n 1 C> R',
     'C crosses n copies of `10` to the right in 4n steps, leaving `10` (carrying `1`).'),
    ('back_C_110_1', 'L (110)^n C> 1 R', 'L C> 1 (000)^n R',
     'C crosses n copies of `110` to the left in 3n steps, leaving `000` (carrying `1`).'),
    ('run_C_001', 'L C> (001)^n R', 'L (011)^n C> R',
     'C crosses n copies of `001` to the right in 3n steps, leaving `011`.'),
    ('back_D_01_0', 'L (01)^n D> 0 R', 'L D> 0 (01)^n R',
     'D crosses n copies of `01` to the left in 6n steps, leaving `01` (carrying `0`).'),
    ('back_D_011_0', 'L (011)^n D> 0 R', 'L D> 0 (000)^n R',
     'D crosses n copies of `011` to the left in 3n steps, leaving `000` (carrying `0`).'),
    ('back_E_10_10', 'L (10)^n E> 1 0 R', 'L E> 1 0 (01)^n R',
     'E crosses n copies of `10` to the left in 6n steps, leaving `01` (carrying `1 0`).'),
    ('run_F_01', 'L F> (01)^n R', 'L (10)^n F> R',
     'F crosses n copies of `01` to the right in 4n steps, leaving `10`.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H83189", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
