def fmt(n):
    if n < 10 ** 6:
        return f"{n:,}"
    e = int(math.floor(math.log10(n)))
    c = n / 10 ** e
    if abs(c - round(c)) > 0.05:
        return f"{c:.1f}·10^{e}"
    return f"10^{e}" if round(c) == 1 else f"{round(c)}·10^{e}"


def fmt_html(n):
    s = fmt(n)
    if "^" in s:
        a, e = s.split("^")
        return f"{a.replace('·', '&middot;')}<sup>{e}</sup>"
    return s


def growth_svg(row):
    """Log-log plot of the cells visited on each side against the step count."""
    cp = [c for c in row["cp"] if c[0] >= 16]
    if len(cp) < 2:
        return ""
    W, H, P = 560, 240, 40
    xs = [math.log2(c[0]) for c in cp]
    ys = [math.log2(max(1, v)) for c in cp for v in (c[1] + 1, c[2] + 1)]
    x0, x1, y0, y1 = min(xs), max(xs), 0, max(ys) + 1

    def X(v):
        return P + (W - 2 * P) * (v - x0) / (x1 - x0)

    def Y(v):
        return H - P + (-(H - 2 * P)) * (v - y0) / (y1 - y0)

    def path(idx):
        return " ".join(f"{'M' if i == 0 else 'L'}{X(math.log2(c[0])):.1f},{Y(math.log2(c[idx] + 1)):.1f}"
                        for i, c in enumerate(cp))
    o = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="cells visited on each side against steps, log scales" '
         f'style="width:100%;max-width:{W}px;height:auto;font:11px var(--mono);">']
    for e in range(int(x0), int(x1) + 1, 4):
        o.append(f'<line x1="{X(e):.1f}" x2="{X(e):.1f}" y1="{P/2}" y2="{H-P}" stroke="var(--line)"/>'
                 f'<text x="{X(e):.1f}" y="{H-P+16}" text-anchor="middle" fill="var(--muted)">2^{e}</text>')
    for e in range(0, int(y1) + 1, 4):
        o.append(f'<line x1="{P}" x2="{W-P}" y1="{Y(e):.1f}" y2="{Y(e):.1f}" stroke="var(--line)"/>'
                 f'<text x="{P-6}" y="{Y(e)+4:.1f}" text-anchor="end" fill="var(--muted)">2^{e}</text>')
    # reference slopes 1/2 from the last point
    o.append(f'<path d="{path(1)}" fill="none" stroke="var(--accent)" stroke-width="2"/>')
    o.append(f'<path d="{path(2)}" fill="none" stroke="var(--head)" stroke-width="2"/>')
    o.append(f'<text x="{W-P}" y="{P/2+4}" text-anchor="end" fill="var(--fg2)">'
             f'<tspan fill="var(--accent)">&#9632; left of start</tspan>  '
             f'<tspan fill="var(--head)">&#9632; right of start</tspan>  (steps across, cells up)</text>')
    o.append("</svg>")
    return "".join(o)


def describe(row):
    sl, sr = row["shape_l"], row["shape_r"]
    a = []
    a.append(f"Left of the start, the visited part of the tape {SHAPE_TEXT[sl]}"
             + (f" (fitted exponent {row['alpha_l']})" if row["alpha_l"] is not None and sl not in ("fixed",) else "")
             + ".")
    a.append(f"Right of the start it {SHAPE_TEXT[sr]}"
             + (f" (fitted exponent {row['alpha_r']})" if row["alpha_r"] is not None and sr not in ("fixed",) else "")
             + ".")
    return " ".join(a)


