def write(path, text, mode=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    if mode:
        os.chmod(path, mode)


def generate(row):
    M = row["machine"]
    if M in STUDIED:
        return False
    d = os.path.join(HERE, M)
    sp = os.path.join(d, "status.json")
    if os.path.exists(sp):
        with open(sp) as f:
            if not json.load(f).get("generated", True):
                return False
    m = Machine.parse(M)
    spec = status_spec(row, m)
    write(sp, json.dumps(spec, indent=1, ensure_ascii=False) + "\n")
    write(os.path.join(d, "README.md"), related.readme_with(M, readme(row, m, spec)))
    write(os.path.join(d, "lean", "Machine.lean"),
          machine_lean(M, ns_of(row), f"BB(6) holdout {M} (bbchallenge id {row['id']}); whether it halts from blank "
                                      f"tape is open."))
    write(os.path.join(d, "lean", "Blank.lean"), blank_lean(row, m))
    write(os.path.join(d, "lean", "check.sh"), CHECK_SH, 0o755)
    return True


def main(argv):
    rows = load_triage()
    want = set(argv)
    n = 0
    for row in rows:
        if want and row["machine"] not in want:
            continue
        n += generate(row)
    print(f"{n} folders written")


if __name__ == "__main__":
    main(sys.argv[1:])
