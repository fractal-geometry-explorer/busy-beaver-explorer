"""Generate Rules.lean for 1RB0RD_1LC0RA_1LA0LB_1RE0LC_1LC1RF_0RB---: the outer sweeps.

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
`0^inf` blank tape, L and R any tape.  Words: c = 1101010, a = 10.  Between two arrivals of the head at the left end
of the tape (state C, on the leftmost cell) the tape reads `11010 w (10)^k 1` with w a word over c and a; one round
trip ("sweep pair") puts a new c at the front of w and takes one a off the last block:
`11010 w (10)^(k+2) 1  ->  11010 c w (10)^(k+1) 1`, in 24*#c(w) + 4*#a(w) + 4*k + 41 steps.  The rules below prove
this for every w with at most four blocks of c's (sweep0..sweep3); `py/sweepcheck.py` checks the
general statement against simulation.  E0 is never read in these rules, so they hold for both machines of the pair
1RB0RD_1LC0RA_1LA0LB_1RE0LC_1L{C,D}1RF_0RB---.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RD_1LC0RA_1LA0LB_1RE0LC_1LC1RF_0RB---"
NS = "H84927"

C = "(1101010)"
INIT_END = {
    "1RB0RD_1LC0RA_1LA0LB_1RE0LC_1LC1RF_0RB---":
        "0^inf C> 1 1 0 1 0 1 1 0 1 0 1 0 (10)^27 1 1 0 1 0 1 0 (10)^8 1 1 0 1 0 1 0 (10)^2 1 1 0 1 0 1 0 (10)^43 1 0^inf",
    "1RB0RD_1LC0RA_1LA0LB_1RE0LC_1LD1RF_0RB---":
        "0^inf C> 1 1 0 1 0 (10)^7 1 1 0 1 0 1 0 (10)^2 1 1 0 1 0 1 0 (10)^13 1 0^inf",
}
INIT_DOC = {
    "1RB0RD_1LC0RA_1LA0LB_1RE0LC_1LC1RF_0RB---":
        "From the blank tape to `11010 c a^27 c a^8 c a^2 c (10)^43 1` (step 12262), where the sweep rules take over.",
    "1RB0RD_1LC0RA_1LA0LB_1RE0LC_1LD1RF_0RB---":
        "From the blank tape to `11010 a^7 c a^2 c (10)^13 1` (step 1432), where the sweep rules take over.",
}
RULES = [
    ("init_run", "0^inf A> 0^inf", INIT_END[M], INIT_DOC[M]),
    ("b_c", "L B> 1 1 0 1 0 1 0 R", "L 0 0 1 1 0 0 1 B> R", "Rightward pass: B turns a c into `0011001`."),
    ("b_a", "L B> 1 0 R", "L 0 1 B> R", "Rightward pass: B turns an a into `01`."),
    ("c_a", "L 1 0 C> 1 R", "L C> 1 1 0 R", "Leftward pass: C crosses an a (shifted by one cell) unchanged."),
    ("sweep0", f"0^inf C> 1 1 0 1 0 {C}^n (10)^k+2 1 0^inf", f"0^inf C> 1 1 0 1 0 {C}^n+1 (10)^k+1 1 0^inf",
     "Sweep pair, w = c^n."),
    ("sweep1", f"0^inf C> 1 1 0 1 0 {C}^n (10)^x+1 {C}^m (10)^k+2 1 0^inf",
     f"0^inf C> 1 1 0 1 0 {C}^n+1 (10)^x+1 {C}^m (10)^k+1 1 0^inf", "Sweep pair, w = c^n a^(x+1) c^m."),
    ("sweep2", f"0^inf C> 1 1 0 1 0 {C}^n (10)^x+1 {C}^m (10)^z+1 {C}^p (10)^k+2 1 0^inf",
     f"0^inf C> 1 1 0 1 0 {C}^n+1 (10)^x+1 {C}^m (10)^z+1 {C}^p (10)^k+1 1 0^inf",
     "Sweep pair, w = c^n a^(x+1) c^m a^(z+1) c^p."),
    ("sweep3", f"0^inf C> 1 1 0 1 0 {C}^n (10)^x+1 {C}^m (10)^z+1 {C}^p (10)^u+1 {C}^q (10)^k+2 1 0^inf",
     f"0^inf C> 1 1 0 1 0 {C}^n+1 (10)^x+1 {C}^m (10)^z+1 {C}^p (10)^u+1 {C}^q (10)^k+1 1 0^inf",
     "Sweep pair, w = c^n a^(x+1) c^m a^(z+1) c^p a^(u+1) c^q."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, max_seg=40)[0] for name, a, b, doc in RULES]
    out = rules_file("Machine", NS, ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    # the composition at the end of sweep3 (24 segments) needs more than the default heartbeats
    i = out.index("/-- Sweep pair, w = c^n a^(x+1) c^m a^(z+1) c^p a^(u+1) c^q.")
    out = out[:i] + "set_option maxHeartbeats 4000000 in\n" + out[i:]
    # the run from the blank tape is long (12262 steps for the first machine of the pair)
    i = out.index("/-- From the blank tape")
    out = out[:i] + "set_option maxHeartbeats 0 in\nset_option maxRecDepth 100000 in\n" + out[i:]
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
