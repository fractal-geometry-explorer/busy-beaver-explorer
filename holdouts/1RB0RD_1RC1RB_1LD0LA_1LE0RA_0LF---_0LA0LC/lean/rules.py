"""Generate Rules.lean: shift rules of 1RB0RD_1RC1RB_1LD0LA_1LE0RA_0LF---_0LA0LC, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape, `0^inf` is blank tape.  See README.md for where each rule is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RD_1RC1RB_1LD0LA_1LE0RA_0LF---_0LA0LC"

RULES = [
    ('wall_right', 'L 0 B> (00101011)^n 0 R', 'L 0 (10001111)^n B> 0 R', {},
     'State B runs right across the wall, rewriting each word `00101011` as `10001111` (a zigzag of 36 steps per word).'),
    ('wall_right1', 'L 1 B> (00101011)^n 1 R', 'L 1 (10001111)^n B> 1 R', {},
     'The same between ones.'),
    ('back_left', 'L 0 (10001111)^n F> 0 R', 'L 0 F> 0 (01011001)^n R', {},
     'State F runs left across the rewritten words.'),
    ('d_right', 'L 0 D> (10001111)^n 0 R', 'L 0 (01000000)^n D> 0 R', {},
     'State D runs right across rewritten words, clearing them.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, **kw)[0] for name, a, b, kw, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H104518", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
