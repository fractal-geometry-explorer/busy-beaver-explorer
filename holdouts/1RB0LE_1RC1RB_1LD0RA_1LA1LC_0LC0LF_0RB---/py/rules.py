"""Writes lean/Rules.lean: the shift rules this machine's sweeps use and the shape of a halt, proved by
tools/py/bbtools/symtm.py (`prove`).  Usage: python3 py/rules.py > lean/Rules.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LE_1RC1RB_1LD0RA_1LA1LC_0LC0LF_0RB---"
NS = "H67137"
RULES = [
    ("b_run", "L B> 1^n R", "L 1^n B> R", "B runs right over a run of 1s."),
    ("a_halve", "L 1 0 A> (11)^n R", "L (01)^n 1 0 A> R",
     "Rightward, A turns each pair `11` into `01` (6 steps a pair): a run of 2n ones becomes (01)^n."),
    ("c_halve", "L 1 C> (11)^n R", "L (01)^n 1 C> R", "The same conversion, carried by C."),
    ("c_double", "L (01)^n C> 0 R", "L C> 0 (11)^n R",
     "Leftward, C turns each `01` back into `11` (2 steps a pair)."),
    ("d_double", "L (10)^n D> 1 R", "L D> 1 (11)^n R", "The same leftward conversion, carried by D."),
    ("halt_shape", "L 1 1 1 D> 0 R", "L F> 1 0 0 1 R",
     "The only way to a halt: D on a 0 with three 1s to its left reaches F on a 1 (which halts) in 3 steps."),
]

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d)[0] for n, s, e, d in RULES]
    extra = (f"/-- F reading a 1 halts: with `halt_shape`, `1 1 1 D> 0` halts on the fourth step. -/\n"
             f"theorem halt_after_shape (L R : Tape) : step ⟨L, cons true R, .F⟩ = none := rfl\n")
    print(rules_file("Machine", NS, thms + [extra],
                     f"# {M}: shift rules of the sweeps and the shape of a halt\n\n"
                     "Generated by `py/rules.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `n` and all "
                     "tapes `L`, `R`."))
