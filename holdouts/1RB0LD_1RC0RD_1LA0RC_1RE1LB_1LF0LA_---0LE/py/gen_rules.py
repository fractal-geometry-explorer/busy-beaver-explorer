"""Writes lean/Passes.lean for 1RB0LD_1RC0RD_1LA0RC_1RE1LB_1LF0LA_---0LE: shift rules proved by bbtools.symtm for every
n.  usage: python3 gen_rules.py > ../lean/Passes.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LD_1RC0RD_1LA0RC_1RE1LB_1LF0LA_---0LE"
RULES = [
    ("sweep_right", "L C> (101)^n R", "L (110)^n C> R",
     "The rightward sweep: C zigzags across `1 0 1` words, 7 steps each, rewriting each into `1 1 0`."),
    ("sweep_left_A", "L (110)^n A> 1 R", "L A> 1 (001)^n R",
     "Leftward, A crosses `1 1 0` words, rewriting each into `1 0 0` (read left to right)."),
]
NS = sys.argv[1] if len(sys.argv) > 1 else "H64598"
thms = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
sys.stdout.write(rules_file("Machine", NS, thms, "Shift rules, proved for every n and every surrounding tape "
                            "(`bbtools.symtm`). Generated by `py/gen_rules.py`."))
