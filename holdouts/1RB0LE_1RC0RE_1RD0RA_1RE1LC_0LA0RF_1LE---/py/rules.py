"""Shift rules and halting situations of 1RB0LE_1RC0RE_1RD0RA_1RE1LC_0LA0RF_1LE---, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LE_1RC0RE_1RD0RA_1RE1LC_0LA0RF_1LE---/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LE_1RC0RE_1RD0RA_1RE1LC_0LA0RF_1LE---"
NS = "H48565"
DOC = """# Shift rules of 1RB0LE_1RC0RE_1RD0RA_1RE1LC_0LA0RF_1LE---

Two crossings of the bouncer: going left, E with a 0 ahead turns each `11` into `10` (`left_E`, four steps a pair);
going right, A turns each `0101` into `1110` (`right_A`, six steps a copy).  The halting situations: only F reading
a 1 halts, and `E> 1 1`, `B> 1 1 1`, `D> 0 1 1` and `1 F> 0` lead there.

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('left_E', 'L (11)^n E> 0 R', 'L E> 0 (10)^n R', 'Going left, E (with a 0 ahead) turns each `11` into `10`, four steps a pair.'),
    ('right_A', 'L A> (0101)^n R', 'L (1110)^n A> R', 'Going right, A turns each `0101` into `1110`, six steps a copy.'),
]

HALTS = [
    ('halt_E', 'E> 1 1', 1, '`E> 1 1` halts: E erases the 1 and moves right onto a 1 in state F.'),
    ('halt_F', '1 F> 0', 2, '`1 F> 0` halts: F writes 1 and steps left onto a 1 in state E, and E erases it and steps back onto the new 1 in state F.'),
    ('halt_B', 'B> 1 1 1', 2, '`B> 1 1 1` halts after two steps.'),
    ('halt_D', 'D> 0 1 1', 2, '`D> 0 1 1` halts after two steps.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [prove(M, name, a, b, doc=doc, count_first=True)[0] for name, a, b, doc in RULES]
    thms += [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
