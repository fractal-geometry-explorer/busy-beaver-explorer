"""Generate lean/Rules.lean for 1RB1LD_1RC0LA_1LA0RE_1LB1LA_1RF0RB_---0LB: the shift rules of its sweeps, proved along symbolic runs
(tools/py/bbtools/symtm.py: single steps by `rfl`, a whole repeat crossed by `TM.cross_r` / `TM.cross_l`).

usage (from the repository root): python3 holdouts/1RB1LD_1RC0LA_1LA0RE_1LB1LA_1RF0RB_---0LB/py/rules.py > holdouts/1RB1LD_1RC0LA_1LA0RE_1LB1LA_1RF0RB_---0LB/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape.  Each rule holds for every n and every tape around it; README.md says where each one is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402

symtm.MAX_CARRY = 8  # some sweeps carry a word of up to 6 cells along with the head

M = "1RB1LD_1RC0LA_1LA0RE_1LB1LA_1RF0RB_---0LB"
NS = "H105740"

RULES = [
    ("b_011", "L B> (011)^n R", "L (100)^n B> R",
     "Rightward: B turns each 011 into 100."),
    ("c_111", "L C> (111)^n R", "L (011)^n C> R",
     "Rightward: C turns each 111 into 011."),
    ("a_110", "L (110)^n A> 1 R", "L A> 1 (011)^n R",
     "Leftward: A turns each 110 into 011."),
    ("d_001", "L (001)^n D> 1101 R", "L D> 1101 (111)^n R",
     "Leftward: D, carrying 1101, turns each 001 into 111."),
]


def main():
    ths = [symtm.prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(symtm.rules_file("Machine", NS, ths, f"Sweep rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
