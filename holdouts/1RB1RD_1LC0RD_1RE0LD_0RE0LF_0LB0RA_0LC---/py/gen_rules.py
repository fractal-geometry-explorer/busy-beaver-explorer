"""Write lean/Rules.lean for 1RB1RD_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC--- (2a) or 1RB1RF_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC--- (2b),
proved by `bbtools.symtm.prove`: the shift rules the run uses.

Usage (from the repository root):
  python3 holdouts/1RB1RD_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC---/py/gen_rules.py MACHINE NAMESPACE > holdouts/MACHINE/lean/Rules.lean"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

RULES = [
    ("shift_E", "L E> (110)^n R", "L (010)^n E> R", "E crosses (110)^n to the right, leaving (010)^n."),
    ("shift_D", "L D> (011)^n R", "L (001)^n D> R", "D crosses (011)^n to the right, leaving (001)^n."),
    ("shift_B", "L B> (100)^n R", "L (101)^n B> R", "B crosses (100)^n to the right, leaving (101)^n."),
    ("counter_increment", "L 1 0 0 0 (1010)^n C> 1 1 R", "L 1 0 1 0 1 (0001)^n 0 D> R",
     "Increment of the left binary counter (digits 1010 = one, 1000 = zero, least significant on the right): "
     "C walks left over the n trailing ones, turns the zero into a one, and B walks back rewriting each one as a zero."),
]

def main():
    M, ns = sys.argv[1], sys.argv[2]
    ths = []
    for name, s, e, doc in RULES:
        try:
            t, fin = prove(M, name, s, e, doc=doc)
        except Exception as x:   # 2b: E's crossing of (110) passes A1, where the two machines differ
            print(f"-- {name}: not proved for this machine ({type(x).__name__})", file=sys.stderr)
            continue
        print(f"-- {name}: {s} -> {fin}", file=sys.stderr)
        ths.append(t)
    print(rules_file("Machine", ns, ths, "Shift rules of the 1RB1R?_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC--- family, generated by `py/gen_rules.py` "
                     "of holdouts/1RB1RD_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC--- with `tools/py/bbtools/symtm.py`; do not edit by hand."), end="")

if __name__ == "__main__":
    main()
