"""Write lean/Middle.lean for 1RB1RD_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC--- (2a) or 1RB1RF_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC--- (2b):
the rules of the middle counter (4-cell digits 0001 = zero, 0101 = one, right of the 1101 that ends the left counter),
proved by `bbtools.symtm.prove` for every number c of carried digits and any tape around them.

  reset   L B> (1010)^n R            ->  L (0001)^n B> R                      (4n steps; a cycle starts with n zero digits)
  carry   L 0001 (0101)^c 0001 F> 0000 R  ->  L 0101 0 0 (0100)^c F> 0001 0 1 R   (12c + 42 steps)
  settle  L 0001 (0101)^c 0 0 F> 0001 y z R  ->  L 0101 0 0 (0100)^c 0 1 F> 0 0 y z R   (12c + 32 steps, y z in 01, 00)

`0101 0 0 (0100)^c` is `0101 (0001)^c 0 0` re-bracketed.  So one carry and one settle take
`0001 (0101)^c 0001 F> 0000 0 1 R` to `0101 (0001)^c 0001 F> 0001 R`: the digits left of the head go up by one (the c
trailing ones become zeros, the zero above them a one) and the first tail cell group 0000 becomes 0001.  Neither rule
reads A1, so they hold for both twins.

Usage (from the repository root):
  python3 holdouts/1RB1RD_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC---/py/gen_middle.py MACHINE NAMESPACE > holdouts/MACHINE/lean/Middle.lean"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

RULES = [
    ("middle_reset", "L B> (1010)^n R", "L (0001)^n B> R",
     "Start of a cycle: B crosses (1010)^n to the right, leaving (0001)^n: the middle counter is n zero digits."),
    ("middle_carry", "L 0 0 0 1 (0101)^c 0 0 0 1 F> 0 0 0 0 R", "L 0 1 0 1 0 0 (0100)^c F> 0 0 0 1 0 1 R",
     "Carry of the middle counter: the c trailing one-digits 0101 become zeros, the zero-digit above them a one, "
     "and the head ends two cells further left with 01 pushed into the tail."),
    ("middle_settle_01", "L 0 0 0 1 (0101)^c 0 0 F> 0 0 0 1 0 1 R", "L 0 1 0 1 0 0 (0100)^c 0 1 F> 0 0 0 1 R",
     "Second half-step, tail 0001 01: the digits go up by one again and the 01 comes back into the counter."),
    ("middle_settle_00", "L 0 0 0 1 (0101)^c 0 0 F> 0 0 0 1 0 0 R", "L 0 1 0 1 0 0 (0100)^c 0 1 F> 0 0 0 0 R",
     "Second half-step, tail 0001 00."),
]


def main():
    M, ns = sys.argv[1], sys.argv[2]
    ths = []
    for name, s, e, doc in RULES:
        t, fin = prove(M, name, s, e, doc=doc)
        print(f"-- {name}: {s} -> {fin}", file=sys.stderr)
        ths.append(t)
    print(rules_file("Machine", ns, ths, "Rules of the middle counter of the 1RB1R?_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC--- twins, "
                     "generated by `py/gen_middle.py` of holdouts/1RB1RD_1LC0RD_1RE0LD_0RE0LF_0LB0RA_0LC--- with "
                     "`tools/py/bbtools/symtm.py`; do not edit by hand."), end="")


if __name__ == "__main__":
    main()
