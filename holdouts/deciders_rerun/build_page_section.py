"""Writes the "Rerun on the 257 unfamilied holdouts" section of pages/src/deciders/page.html (the source of
pages/deciders.html) from results.json, between the rerun:start and rerun:end markers; then run
python3 pages/src/deciders/build.py. python3 build_page_section.py [check]"""
import json, os, sys, html
here = os.path.dirname(os.path.abspath(__file__))
page = os.path.join(here, '..', '..', 'pages', 'src', 'deciders', 'page.html')
d = json.load(open(os.path.join(here, 'results.json')))
def ng(r):
    p = r['ngramcps']
    def w(k):
        x = p[k]['halt_reached_up_to']
        return x.split()[0] if x else '-'
    return w('plain'), w('H1'), w('H2'), w('H3'), w('LRU')
rows = []
for r in d['results']:
    rw = r['repwl']; a = ng(r)
    rows.append('<tr><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%d / %d</td></tr>' % (
        html.escape(r['machine']), r['old'],
        'exponential' if r['backward'].startswith('frontier') else '3000',
        ' / '.join(a), html.escape(r['cycler'].replace('none to 2000000000 steps', 'none to 2·10<sup>9</sup>'), quote=False).replace('&lt;', '<').replace('&gt;', '>'),
        rw['halt_reached'], rw['runs']))
sec = '''<!-- rerun:start (generated by holdouts/deciders_rerun/build_page_section.py) -->
<section id="rerun">
  <span class="eyebrow">21 November 2026</span>
  <h2>Rerun on the 257 unfamilied holdouts</h2>
  <div class="col">
    <p>The 257 holdouts that fit none of the families of the 20 November regrouping (<code>holdouts/FAMILIES.md</code>) were run again through the standard deciders, with limits well above the usual ones. <b>None was decided.</b> Nothing new needed a Lean or busycoq certificate.</p>
    <ul>
      <li><b>Cyclers and translated cyclers</b> (<code>tools/c/tcyc.c</code>): 2·10<sup>9</sup> steps from blank tape for each machine, comparing every record configuration with the last 4,000 on the same side. No repeat.</li>
      <li><b>Backward reasoning</b> (<code>tools/c/bkr.c</code>, the rule of busycoq's <code>BackwardsReasoning.v</code>): for 249 machines a backward chain of 3,000 steps from a halting configuration exists, so no depth up to 3,000 works. For the other 8 the set of backward configurations grows exponentially (over 3·10<sup>6</sup> distinct ones by depth 53 for <code>1RB0RE_1LC0RA_0LD1LB_1LA1LF_0LB0RD_0LB---</code>) without dying out.</li>
      <li><b>n-gram CPS</b> (<code>tools/c/ngramcps.c</code>): plain windows up to 30 cells, fixed histories of 1, 2 and 3 up to 20, 15 and 11 cells, LRU up to 11, and asymmetric windows (left 1 to 12, right up to 16). Each width was raised until the decider reached a halting configuration or ran out of budget (8·10<sup>6</sup> configurations or 40 s).</li>
      <li><b>RepWL</b> (<code>tools/c/repwl.cpp</code>): 60 settings per machine, block length 1 to 48 and threshold 2 to 4, with 300,000 configurations (twice Coq-BB5's 150,001). %s of the 15,420 runs reached a halting configuration, and the rest hit the budget.</li>
    </ul>
    <p>Each new decider was tested for soundness against direct simulation on random two- to five-state machines: RepWL decided 132 of 230, translated cyclers 1,091 of 1,500, with no machine it called non-halting halting within 2 to 3·10<sup>6</sup> steps. Per machine: <code>holdouts/deciders_rerun/results.json</code> and <code>README.md</code>.</p>
    <details><summary>All 257 machines</summary>
    <p>Columns: the 13 November family; the backward-reasoning depth already defeated (3000) or "exponential"; the largest n-gram window at which the decider still reached a halt, for plain / history 1 / 2 / 3 / LRU, where "-" means it ran out of budget at the first width; the cycler run; RepWL settings that reached a halt, out of those run.</p>
    <div style="overflow-x:auto"><table class="rerun">
    <thead><tr><th>machine</th><th>family</th><th>backward</th><th>n-gram</th><th>cyclers</th><th>RepWL</th></tr></thead>
    <tbody>
%s
    </tbody></table></div>
    </details>
  </div>
</section>
<!-- rerun:end -->''' % ('{:,}'.format(sum(r['repwl']['halt_reached'] for r in d['results'])), '\n'.join(rows))
s = open(page).read()
a, b = '<!-- rerun:start', '<!-- rerun:end -->'
if a in s:
    new = s[:s.index(a)] + sec + s[s.index(b) + len(b):]
else:
    k = s.index('<section id="sources">')
    new = s[:k] + sec + '\n\n' + s[k:]
if sys.argv[1:] == ['check']:
    sys.exit(0 if new == s else 1)
open(page, 'w').write(new)
