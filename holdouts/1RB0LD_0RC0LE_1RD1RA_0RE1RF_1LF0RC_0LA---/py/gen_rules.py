"""Generate lean/Rules.lean for 1RB0LD_0RC0LE_1RD1RA_0RE1RF_1LF0RC_0LA--- (run from the repository root): shift rules the sweeps use.
Each rule is proved by bbtools.symtm for all values of its variables and every tape L (or R) the run does not
look at."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools import symtm
from bbtools.machine import Machine
M = "1RB0LD_0RC0LE_1RD1RA_0RE1RF_1LF0RC_0LA---"
NS = "H127566"
m = Machine.parse(M)
RULES = [
    ('shiftC', 'Shift rule: C crosses (100)^n to the right, leaving (110)^n.',
     'L C> (100)^n R', 'L (110)^n C> R'),
    ('shiftA', 'Shift rule: A crosses (001)^n to the right, leaving (101)^n.',
     'L A> (001)^n R', 'L (101)^n A> R'),
    ('shiftE', 'Shift rule: E crosses (11010)^n to the right, leaving (01010)^n.',
     'L E> (11010)^n R', 'L (01010)^n E> R'),
]
out = []
for name, doc, a, b in RULES:
    txt, fin = symtm.prove(m, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=30)
    out.append(txt)
sys.stdout.write(symtm.rules_file("Machine", NS, out, f"Rules of {M}; generated by `py/gen_rules.py`; do not edit by hand."))
