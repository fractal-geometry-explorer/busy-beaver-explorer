"""Write lean/Rules.lean: rules of 1RB1LC_1LA1LD_1LD0LC_0LE0RD_1RA1LF_1RC--- proved by bbtools.symtm, for all values of their counts.

Words: p = 10110, q = 10000, S = 1011. The rule is one round of an epoch: from state D at the left end of
`0 q 0 p^a S p^(b+1) S q^(c+1) R`, the head comes back with one more p in each of the two p-blocks and one q fewer.

usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/1RB1LC_1LA1LD_1LD0LC_0LE0RD_1RA1LF_1RC---/py/gen_rules.py
"""
import os
from bbtools import symtm
from bbtools.machine import Machine

M = "1RB1LC_1LA1LD_1LD0LC_0LE0RD_1RA1LF_1RC---"
Q = "1 0 0 0 0"
S = "1 0 1 1"
RULES = [
    ("round", "one round: one q of the block after the second S becomes a p, and the first p-block gains a p",
     f"0^inf D> 0 {Q} 0 (10110)^a {S} (10110)^b+1 {S} (10000)^c+1 R",
     f"0^inf D> 0 {Q} 0 (10110)^a+1 {S} (10110)^b+2 {S} (10000)^c R"),
]


def main():
    m = Machine.parse(M)
    thms = [symtm.prove(m, name, s, e, doc=doc, rotate=True, max_seg=40)[0] for name, doc, s, e in RULES]
    out = symtm.rules_file("Machine", "H42011", thms, "Rules of " + M + ", generated by `py/gen_rules.py` with `bbtools.symtm`.")
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lean", "Rules.lean"), "w") as f:
        f.write(out)


if __name__ == "__main__":
    main()
