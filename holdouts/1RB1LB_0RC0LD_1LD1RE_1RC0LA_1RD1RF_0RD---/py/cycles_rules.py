"""Run 1RB1LB_0RC0LD_1LD1RE_1RC0LA_1RD1RF_0RD--- with the cycle accelerator of tools/py/bbtools/cycles.py (macro blocks of K cells) and write the
cycle rules it proved (each a Lean theorem for all values of its variables) to ../lean/Cycles.lean.

usage: python3 cycles_rules.py [STEPS] > ../lean/Cycles.lean      (prints the jumps on stderr)
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.cycles import Accelerator  # noqa: E402
from bbtools.macro import MacroRun  # noqa: E402

M = "1RB1LB_0RC0LD_1LD1RE_1RC0LA_1RD1RF_0RD---"
K = 3


def main():
    steps = int(float(sys.argv[1])) if len(sys.argv) > 1 else 10 ** 12
    a = Accelerator(MacroRun(M, K)).run(steps)
    for before, n, after, name in a.jumps:
        print(f"{before:.4e} -> {after:.4e}  {n} cycles of {name}", file=sys.stderr)
    r = a.run_
    print(f"{'halted after' if r.halted else 'at'} {r.steps} steps, {len(a.rules)} rules, {len(a.jumps)} jumps", file=sys.stderr)
    print(str(r)[:400], file=sys.stderr)
    sys.stdout.write(a.lean_file("Machine", "H119197", f"Cycle rules of {M} proved by bbtools.cycles (blocks of {K} cells) "
                                 f"on the run to {steps:.0e} steps; generated by `py/cycles_rules.py`, do not edit."))


if __name__ == "__main__":
    main()
