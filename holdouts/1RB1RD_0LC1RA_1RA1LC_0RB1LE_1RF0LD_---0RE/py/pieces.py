"""Generate lean/Pieces.lean: one symbolic run for every case of the phase map of MACHINE (see lean/Phases.lean),
proved along the run by tools/py/bbtools/symtm.py.  Each run starts from a phase and stops at the first configuration
of the given kind ('Q': the bounce frame, state QS on `0 0` with a 1 to its left; 'E': state E at the left end on a
0; 'A': the right-end frame, state AS on blank tape just right of AEND; 'H': the halting configuration); that configuration is the theorem's
right-hand side.

usage (from the repository root):
  python3 holdouts/MACHINE/py/pieces.py > holdouts/MACHINE/lean/Pieces.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import Config, Halted, prove, rules_file, run  # noqa: E402
from bbtools.machine import Machine  # noqa: E402

M = "1RB1RD_0LC1RA_1RA1LC_0RB1LE_1RF0LD_---0RE"
NS = "H70028"
QS = "D"
ES = "E"
AS = "B"
AEND = "0 "  # what stands just left of the head in the right-end frame


def is_q(c):
    r = repr(c)
    return (not c.steps.is_zero() and r.split()[0] == "0^inf" and f"{QS}> 0 0 " in r
            and r.split(f"{QS}>")[0].rstrip().endswith(" 1") and "ABCDEF"[c.state] == QS)


def is_e(c):
    return not c.steps.is_zero() and "ABCDEF"[c.state] == ES and repr(c).startswith(f"0^inf {ES}> 0")


def is_a(c):
    return not c.steps.is_zero() and "ABCDEF"[c.state] == AS and repr(c).endswith(f"{AEND}{AS}> 0^inf")


STOP = {"Q": is_q, "E": is_e, "A": is_a}

PIECES = [
    ("pc_init", "0^inf A> 0^inf", "A", "From blank tape the machine reaches R(0, 2)."),
    ("pc_e", "0^inf E> 0 (10)^x 1^z+2 0^inf", "Q", "E(x, z+2) reaches Q(x, 0, z)."),
    ("pc_eh0", "0^inf E> 0 (10)^x 0^inf", "H", "E(x, 0) runs into the halting transition."),
    ("pc_eh1", "0^inf E> 0 (10)^x 1 0^inf", "H", "E(x, 1) runs into the halting transition."),
    ("pc_round", "0^inf (10)^m+1 1 D> 0 0 (10)^k 1^t+3 0^inf", "Q", "One bounce: Q(m+1, k, t+3) reaches Q(m, k+2, t+1)."),
    ("pc_end", "0^inf 1 D> 0 0 (10)^k 1^t+5 0^inf", "E", "Q(0, k, t+5) reaches E(k+4, t+1)."),
    ("pc_end4", "0^inf 1 D> 0 0 (10)^k 1 1 1 1 0^inf", "A", "Q(0, k, 4)."),
    ("pc_end3", "0^inf 1 D> 0 0 (10)^k 1 1 1 0^inf", "E", "Q(0, k, 3)."),
    ("pc_t2", "0^inf (10)^m 1 D> 0 0 (10)^k 1 1 0^inf", "A", "Q(m, k, 2)."),
    ("pc_t1z", "0^inf 1 D> 0 0 (10)^k 1 0^inf", "E", "Q(0, k, 1) reaches E(1, 2k+4)."),
    ("pc_t1o", "0^inf 1 0 1 D> 0 0 (10)^k 1 0^inf", "E", "Q(1, k, 1) reaches E(3, 2k+2)."),
    ("pc_t1", "0^inf (10)^m+2 1 D> 0 0 (10)^k 1 0^inf", "Q", "Q(m+2, k, 1) reaches Q(m, 1, 2k+4)."),
    ("pc_t0z", "0^inf 1 D> 0 0 (10)^k 0^inf", "E", "Q(0, k, 0) reaches E(1, 2k+2)."),
    ("pc_t0oz", "0^inf 1 0 1 D> 0 0 0^inf", "A", "Q(1, 0, 0) reaches R(0, 6)."),
    ("pc_t0o", "0^inf 1 0 1 D> 0 0 (10)^k+1 0^inf", "E", "Q(1, k+1, 0) reaches E(3, 2k+2)."),
    ("pc_t0", "0^inf (10)^m+2 1 D> 0 0 (10)^k 0^inf", "Q", "Q(m+2, k, 0) reaches Q(m, 1, 2k+2)."),
    ("pc_r00", "0^inf 0 B> 0^inf", "E", "R(0, 0) reaches E(1, 1)."),
    ("pc_r0", "0^inf 1^y+1 0 B> 0^inf", "E", "R(0, y+1) reaches E(1, y+2)."),
    ("pc_r10", "0^inf 1 0 0 B> 0^inf", "E", "R(1, 0) reaches E(1, 5)."),
    ("pc_r11", "0^inf 1 0 1 0 B> 0^inf", "A", "R(1, 1) reaches R(0, 6)."),
    ("pc_r12", "0^inf 1 0 1 1 0 B> 0^inf", "E", "R(1, 2) reaches E(3, 1)."),
    ("pc_r1", "0^inf 1 0 1^y+3 0 B> 0^inf", "E", "R(1, y+3) reaches E(3, y+2)."),
    ("pc_rx0", "0^inf (10)^x+2 0 B> 0^inf", "Q", "R(x+2, 0) reaches Q(x, 1, 1)."),
    ("pc_rx", "0^inf (10)^x+2 1^y+1 0 B> 0^inf", "Q", "R(x+2, y+1) reaches Q(x, 1, y+2)."),
]


def main():
    m = Machine.parse(M)
    ths = []
    for name, start, kind, doc in PIECES:
        c = Config.parse(start)
        if kind == "H":
            try:
                run(m, c, lambda c: False, max_moves=5000, rotate=True)
            except Halted:
                pass
            fin = c
        else:
            fin = run(m, c, STOP[kind], max_moves=5000, rotate=True)
        print(f"-- {name}: {start} -> {fin} [{fin.steps}]", file=sys.stderr)
        ths.append(prove(M, name, start, repr(fin), doc=doc, rotate=True)[0])
    print(rules_file("Machine", NS, ths,
                     f"Pieces of the phase map of {M}, generated by `py/pieces.py`; do not edit."), end="")


if __name__ == "__main__":
    main()
