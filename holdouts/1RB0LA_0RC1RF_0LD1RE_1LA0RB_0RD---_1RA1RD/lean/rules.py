"""Generate Rules.lean for 1RB0LA_0RC1RF_0LD1RE_1LA0RB_0RD---_1RA1RD: the halting context and the shift rules over the words of its tape, proved along the symbolic run of tools/py/bbtools/symtm.py
(single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LA_0RC1RF_0LD1RE_1LA0RB_0RD---_1RA1RD"

RULES = [
    ('halt_ctx', 'L B> 0 1 1 R', 'L 0 1 E> 1 R',
     'B on a 0 with 1 1 after it: C reads the first 1 and E the second (the halting transition).'),
    ('back_A_10_10', 'L (10)^n A> 1 0 R', 'L A> 1 0 (10)^n R',
     'A crosses n copies of `10` to the left in 6n steps, leaving `10` (carrying `1 0`).'),
    ('back_A_01_1', 'L (01)^n A> 1 R', 'L A> 1 (10)^n R',
     'A crosses n copies of `01` to the left in 6n steps, leaving `10` (carrying `1`).'),
    ('back_A_1_1', 'L (1)^n A> 1 R', 'L A> 1 (0)^n R',
     'A crosses n copies of `1` to the left in 1n steps, leaving `0` (carrying `1`).'),
    ('back_A_110_10', 'L (110)^n A> 1 0 R', 'L A> 1 0 (010)^n R',
     'A crosses n copies of `110` to the left in 7n steps, leaving `010` (carrying `1 0`).'),
    ('back_A_011_1', 'L (011)^n A> 1 R', 'L A> 1 (100)^n R',
     'A crosses n copies of `011` to the left in 7n steps, leaving `100` (carrying `1`).'),
    ('run_B_100', 'L B> (100)^n R', 'L (111)^n B> R',
     'B crosses n copies of `100` to the right in 3n steps, leaving `111`.'),
    ('run_B_110_00', 'L 0 0 B> (110)^n R', 'L (101)^n 0 0 B> R',
     'B crosses n copies of `110` to the right in 15n steps, leaving `101` (carrying `0 0`).'),
    ('run_F_001', 'L F> (001)^n R', 'L (111)^n F> R',
     'F crosses n copies of `001` to the right in 3n steps, leaving `111`.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H21606", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
