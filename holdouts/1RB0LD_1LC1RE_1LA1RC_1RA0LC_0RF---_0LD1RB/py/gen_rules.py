"""Writes lean/Passes.lean: the pieces of a sweep of 1RB0LD_1LC1RE_1LA1RC_1RA0LC_0RF---_0LD1RB, proved by
bbtools.symtm for every value of the parameters.  usage: python3 gen_rules.py > ../lean/Passes.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LD_1LC1RE_1LA1RC_1RA0LC_0RF---_0LD1RB"
RULES = [
    ("left_even", "L 0 (11)^k 1 1 C> 0 0 0 R", "L C> 0 0 0 (10)^k 1 0 0 R",
     "Leftward pass over an even block: `1^(2k+2)` becomes the segment `(1 0)^k 1 0 0`, and C moves on to the "
     "0 in front of it with the three 0s it carries."),
    ("left_odd", "L 0 (11)^k 1 C> 0 0 0 R", "L 1 1 B> (10)^k 1 0 0 R",
     "Leftward pass reaching an odd block `1^(2k+1)`: it too becomes `(1 0)^k 1 0 0`, the 0 in front of it and "
     "its first cell become 1 1 (glued to the block on the left) and the head turns right in state B."),
    ("right_group", "L 1 B> (101010)^k R", "L 1 (111101)^k B> R",
     "Rightward pass: every three pairs `1 0 1 0 1 0` become a block `1^5` and a 0 (written here as left words)."),
    ("right_seg0", "L 1 B> 1 0 0 R", "L 1 1 1 1 B> R",
     "Rightward pass at a segment end in phase 0: `1 0 0` becomes `1 1 1`."),
]

thms = [prove(M, name, a, b, rotate=True, doc=doc)[0] for name, a, b, doc in RULES]
sys.stdout.write(rules_file("Machine", "H168919", thms,
                            "The pieces of a sweep, proved for every k and every surrounding tape (`bbtools.symtm`). "
                            "Generated by `py/gen_rules.py`."))
