"""Generate lean/HalvingRules.lean: the two pieces of the halving at the left wall of
1RB0RB_1RC0LE_1LD1LA_---0LC_1RF1LE_1RA0RA, each proved along a symbolic run (tools/py/bbtools/symtm.py).
The induction over the rounds and the halting corollaries are hand-written in lean/Halving.lean.

usage: python3 py/rules.py > lean/HalvingRules.lean      (from this machine's folder)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RB_1RC0LE_1LD1LA_---0LC_1RF1LE_1RA0RA"

RULES = [
    ('half_round', 'L 1^j E> 0 (11)^m+3 0 0 R', 'L 1^j 1 E> 0 (11)^m+2 0 0 1 R',
     'One round of the halving: the block being halved loses two 1s, one joins the growing block on its left and one '
     'the block after the gap `00` (blocks of at least 6).'),
    ('half_four', 'L 1^j E> 0 1 1 1 1 0 0 R', 'L E> 1 1^j 1 0 0 1 0 1 R',
     'The last round, from a block of 4: the left block gets its last two 1s and the separator `0 0 1 0` is rebuilt.'),
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H25221", thms,
                                "Pieces of the halving of 1RB0RB_1RC0LE_1LD1LA_---0LC_1RF1LE_1RA0RA, generated by "
                                "`py/rules.py` (tools/py/bbtools/symtm.py); do not edit by hand. Each theorem holds "
                                "for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
