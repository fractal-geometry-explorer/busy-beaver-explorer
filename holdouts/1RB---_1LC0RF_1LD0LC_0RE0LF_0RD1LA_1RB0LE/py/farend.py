"""Write lean/FarEnd.lean: what lean/Lockstep.lean needs generated.

* The far end of the tape.  The run of this table from state C (1RB0RA_0LC0RF_0LB1RD_1LE---_1RA0LF_1LE0RC, mirrored)
  is the run from state A (this machine) with k = 1 word `10001101` more at the right end.  Two tapes that differ
  only by k such words just right of a cell q (blank beyond q in the first) behave alike as long as the head does not
  move right from cell q.  In the runs it does so only in state B on a 1: `far_B0_run` and `far_B1_run` (the cell left
  of q holding 0 or 1) cross the k words and come back with the same cells as for k = 0, for every k (symbolic runs
  of tools/py/bbtools/symtm.py).
* The table of 1RB0RA_0LC0RF_0LB1RD_1LE---_1RA0LF_1LE0RC, generated by tools/py/bbtools/leangen.py.

usage (from the repo root):
  python3 holdouts/1RB---_1LC0RF_1LD0LC_0RE0LF_0RD1LA_1RB0LE/py/farend.py > holdouts/1RB---_1LC0RF_1LD0LC_0RE0LF_0RD1LA_1RB0LE/lean/FarEnd.lean
  python3 holdouts/1RB---_1LC0RF_1LD0LC_0RE0LF_0RD1LA_1RB0LE/py/farend.py check     # the far-end runs by simulation
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))

M = "1RB---_1LC0RF_1LD0LC_0RE0LF_0RD1LA_1RB0LE"
SISTER = ("M114265", "1RB0RA_0LC0RF_0LB1RD_1LE---_1RA0LF_1LE0RC")
W8 = "10001101"
RUNS = [("far_B%s_run" % a, "X %s B> 1 (%s)^k 0^inf" % (a, W8), "X D> %s 1 0 1 (%s)^k 0^inf" % (a, W8),
         "B on the cell q, a 1 with `(10001101)^k` and blank tape to its right and a %s to its left: the head crosses "
         "the k words and comes back out in D, one cell left of q, with `1 0 1` from q on." % a) for a in "01"]


def table():
    T = {}
    for s, part in enumerate(M.split("_")):
        for r in range(2):
            x = part[3 * r:3 * r + 3]
            T[(s, r)] = None if x[2] == "-" else (int(x[0]), 1 if x[1] == "R" else -1, ord(x[2]) - 65)
    return T


def excursion(T, a, k):
    """B on a 1 at cell 0, `a` at cell -1, `(10001101)^k` from cell 1; run until the head is left of cell 0."""
    cells = {-1: a, 0: 1}
    for i, b in enumerate([int(c) for c in W8] * k):
        cells[1 + i] = b
    pos, st, n = 0, 1, 0
    while pos >= 0:
        t = T[(st, cells.get(pos, 0))]
        assert t is not None
        cells[pos] = t[0]
        pos += t[1]
        st = t[2]
        n += 1
        assert n < 10 ** 5
    E = [cells.get(i, 0) for i in range(-1, max(cells) + 1)]
    while E and E[-1] == 0:
        E.pop()
    return "ABCDEF"[st], E, n


def check():
    T = table()
    ok = True
    for a in (0, 1):
        outs = [excursion(T, a, k) for k in range(5)]
        base = outs[0]
        same = all(o[0] == base[0] and o[1] == base[1] + [int(c) for c in W8] * k and o[2] == base[2] + 44 * k
                   for k, o in enumerate(outs))
        print("B on q, %d to its left: %s  k = 0: %s" % (a, "same for every k = 0..4" if same else "DIFFERS", base))
        ok = ok and same and base[0] == "D" and base[1] == [a, 1, 0, 1]
    print("ALL CHECKS PASS" if ok else "FAILED")
    return ok


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "check":
        sys.exit(0 if check() else 1)
    from bbtools.symtm import prove
    from bbtools.leangen import machine_lean
    out = ["import Machine", "", "/-!", "# The far end of the tape, and the sister table", "",
           "Generated by `py/farend.py`; do not edit by hand.  See `Lockstep.lean`.", "-/", "",
           "namespace H30773", "", "open TM", ""]
    for name, start, end, doc in RUNS:
        out.append(prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=40)[0])
        out.append("")
    ns, text = SISTER
    s = machine_lean(text, ns)
    body = s[s.index("/-- The states"):s.index("abbrev Config")].rstrip() + "\n"
    out += ["namespace %s" % ns, "", body, "end %s" % ns, ""]
    out.append("end H30773")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
