"""Write the Coq (busycoq) data files of the non-halting proof of 1RB0RC_0RC1RC_0LD0RA_1LE0LF_0LA1LC_---1LA.

usage (from the repo root):
  python3 holdouts/1RB0RC_0RC1RC_0LD0RA_1LE0LF_0LA1LC_---1LA/py/coq/gen_coq.py OUTDIR      (about 20 s)
or, as the copy gen_H65826.py with H65826_engine.py and H65826_replay.py next to it:
  python3 gen_H65826.py OUTDIR

The certificate is the one of the Lean replay (py/replay/gen.py, engine.py): 13 + 18 shift rules, 12 cycle rules
each with the number of executor moves of its proof run, the run from blank tape to C(16797709) and the run of one
growth period C(65 + 2x) -> C(321042993 + 2x), x free.  This script only prints them as Coq terms for
lib/SymExecN.v, the Coq port of the executor; every one of them is re-checked there by `vm_compute`.

Writes H65826_Data.v (machine, tables, shift rules checked), H65826_Rules.v (cycle rules checked),
H65826_Arrive.v and H65826_Period.v (the two runs).  H65826.v (the theorem) is written by hand.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

def load(prefix):
    """The replay generator and its engine: ../replay/{gen,engine}.py in the repository, or the copies
    <prefix>_replay.py and <prefix>_engine.py next to this file."""
    rp = os.path.join(HERE, '..', 'replay')
    if os.path.isdir(rp):
        sys.path.insert(0, rp)
        import gen
        import engine
        return gen, engine, False
    import importlib.util
    mods = {}
    for name, fn in (('engine', prefix + '_engine.py'), ('gen', prefix + '_replay.py')):
        spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, fn))
        mods[name] = sys.modules[name] = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mods[name])
    return mods['gen'], mods['engine'], True


G, _engine, COPY = load("H65826")
fmt = _engine.fmt

M = "H65826"
HEAD = "(* Generated by gen_H65826.py (holdouts/.../py/coq/gen_coq.py); do not edit by hand. *)\n\n"


def w(word):
    return "[" + "; ".join("S1" if b else "S0" for b in word) + "]"


def cnt(n):
    return "(mkC %d [%s])" % (n[0], "; ".join(map(str, n[1])))


def toks(ts):
    return "[" + ";\n   ".join("cell %s" % ("S1" if t else "S0") if isinstance(t, int)
                               else "blk %s %s" % (w(t[0]), cnt(t[1])) for t in ts) + "]"


def tmpl(ts):
    out = []
    for t in ts:
        if isinstance(t, int):
            out.append("tcell %s" % ("S1" if t else "S0"))
        elif t[0] == 'f':
            out.append("tfix %s %d" % (w(t[1]), t[2]))
        else:
            out.append("tvar %s %d %d" % (w(t[1]), t[2], t[3]))
    return "[" + ";\n   ".join(out) + "]"


def srules(tab):
    return ["mkS %s %s %d %s %s %d" % ("ABCDEF"[st], w(wd), k, w(u), w(v), c)
            for (st, wd), lst in tab.items() for k, u, v, c in lst]


VM = "Proof. vm_cast_no_check (eq_refl true). Qed.\n"


def main():
    out = sys.argv[1]
    shR, shL, rules0 = G.tables()
    rules, ka, kp = G.static(shR, shL, rules0)
    d = [HEAD, """(** * 1RB0RC_0RC1RC_0LD0RA_1LE0LF_0LA1LC_---1LA (bbchallenge 65826): the machine and the tables of the replay *)

From Coq Require Import Lists.List NArith. Import ListNotations.
From BusyCoq Require Export SymExecN.
Set Default Goal Selector "!".
Local Open Scope N_scope.

Definition tm : TM := fun '(q, s) =>
  match q, s with
  | A, S0 => Some (S1, R, B)  | A, S1 => Some (S0, R, C)
  | B, S0 => Some (S0, R, C)  | B, S1 => Some (S1, R, C)
  | C, S0 => Some (S0, L, D)  | C, S1 => Some (S0, R, A)
  | D, S0 => Some (S1, L, E)  | D, S1 => Some (S0, L, F)
  | E, S0 => Some (S0, L, A)  | E, S1 => Some (S1, L, C)
  | F, S0 => None             | F, S1 => Some (S1, L, A)
  end.

(** The executor for this machine: events are state E at the left end of the tape; blocks of fewer than 3 copies
    are written out; a cycle rule is applied a number of times. *)
Definition thr : N := 3.
Notation TOK := (TblOK tm E).

"""]
    for name, tab, side in (("shR", shR, "right"), ("shL", shL, "left")):
        rs = srules(tab)
        d.append("(** The shift rules to the %s: state, word, copies, carried word, word left behind, steps. *)\n" % side)
        d.append("Definition %s : list SRule :=\n  [%s].\n\n" % (name, ";\n   ".join(rs)))
    d.append("Lemma shR_chk : forallb (chkR tm) shR = true.\n" + VM + "\n")
    d.append("Lemma shL_chk : forallb (chkL tm) shL = true.\n" + VM + "\n")
    d.append("(** The tables without cycle rules: what the cycle rules themselves are proved with. *)\n")
    d.append("Definition T0 : Tbl := mkT shR shL [].\n\n")
    d.append("Lemma T0_ok : TOK T0.\nProof. exact (shifts_ok tm E shR shL shR_chk shL_chk). Qed.\n\n")
    for i, r in enumerate(rules):
        d.append("(** Cycle rule %d (%d events a cycle): [E> %s], the counts with a variable going %s. *)\n"
                 % (i, r.events, fmt(r.sym(0)),
                    ", ".join("%d -> %d" % (t[2], t[3]) for t in r.tmpl if not isinstance(t, int) and t[0] == 'v')))
        d.append("Definition rule%d : CRule := mkR 2\n  %s.\n\n" % (i, tmpl(r.tmpl)))
    n = len(rules)
    d.append("(** The tables of the replay. *)\nDefinition T : Tbl := mkT shR shL [%s].\n\n"
             % "; ".join("rule%d" % i for i in range(n)))
    d.append("(** The right side of C(r) in normal form, as tokens; [n] is the count of the last block. *)\n")
    t = G.C((777, (9,)))
    d.append("Definition cycToks (n : Cnt) : list Tok :=\n  %s.\n" % toks(t).replace("(mkC 777 [9])", "n"))
    open(os.path.join(out, M + "_Data.v"), "w").write("".join(d))

    r_ = [HEAD, """(** * 65826: the %d cycle rules, each proved by a run of the executor without cycle rules *)

From Coq Require Import Lists.List NArith. Import ListNotations.
From BusyCoq Require Export %s_Data.
Set Default Goal Selector "!".
Local Open Scope N_scope.

""" % (n, M)]
    for i, r in enumerate(rules):
        r_.append("Lemma rule%d_chk : chkRule tm E thr stratMin T0 %d rule%d = true.\n" % (i, r.K, i) + VM + "\n")
    r_.append("Lemma T_ok : TOK T.\nProof.\n  apply tbl_ok; [exact T0_ok|].\n")
    for i in range(n):
        r_.append("  apply Forall_cons; [exact (chkRule_ok tm E thr stratMin T0 T0_ok _ _ rule%d_chk)|].\n" % i)
    r_.append("  apply Forall_nil.\nQed.\n")
    open(os.path.join(out, M + "_Rules.v"), "w").write("".join(r_))

    imp = """From Coq Require Import Lists.List NArith. Import ListNotations.
From BusyCoq Require Export %s_Data.
Local Open Scope N_scope.

""" % M
    a = [HEAD, "(** * 65826: the run from blank tape *)\n\n", imp]
    a.append("(** %d moves of the executor from blank tape end at C(%d). *)\n" % (ka, G.REACH_R))
    a.append("Lemma arrive_run :\n  runTo tm E thr stratMin T %d (mkSC [] [] A) (mkSC [] (cycToks (mkC %d [])) E) = true.\n"
             % (ka, G.REACH_R) + VM)
    open(os.path.join(out, M + "_Arrive.v"), "w").write("".join(a))
    p = [HEAD, "(** * 65826: one growth period, the count of the last block with a free variable *)\n\n", imp]
    p.append("(** One machine step and %d more moves of the executor from C(%d + 2 x), x free, end at C(%d + 2 x). *)\n"
             % (kp - 1, G.BASE, G.BASE + G.INC))
    p.append("Lemma period_run :\n  runTo1 tm E thr stratMin T %d (mkSC [] (cycToks (mkC %d [2])) E)\n"
             "    (mkSC [] (cycToks (mkC %d [2])) E) = true.\n" % (kp - 1, G.BASE, G.BASE + G.INC) + VM)
    open(os.path.join(out, M + "_Period.v"), "w").write("".join(p))
    print("arrival %d moves, period %d moves, rules %s" % (ka, kp, [r.K for r in rules]))


if __name__ == "__main__":
    main()
