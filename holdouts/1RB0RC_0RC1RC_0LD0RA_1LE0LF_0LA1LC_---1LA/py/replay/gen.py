"""Find the tables of the replay (shift rules, cycle rules, move counts) with `engine.py` and write the Lean data.

usage (from the repo root):
  python3 holdouts/1RB0RC_0RC1RC_0LD0RA_1LE0LF_0LA1LC_---1LA/py/replay/gen.py [--check]

Writes lean/ExecData.lean (tables, their validity, the 12 cycle rules proved by the executor), lean/Arrive.lean
(blank tape -> C(16797709)) and lean/Period.lean (C(65 + 2x) -> C(65 + 2(x + 160521464))).  With --check nothing
is written; the numbers are compared with the claim.

Two passes.  Discovery: the engine finds shift rules (plain simulation between walls) and cycle rules (a shape seen
three times at equal distance, then a symbolic run) while it runs from blank tape and then through one symbolic
period.  Static: with the tables fixed, every cycle rule is re-proved without cycle rules, and the two runs are
repeated; the static pass is what Lean replays, move for move.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from engine import Engine, Rule, cst, norm, parse, prove_rule, fmt  # noqa: E402

LEAN = os.path.join(HERE, '..', '..', 'lean')
CF = "0 (1011001)^59 1011 00000 1101100110110 (011)^16 001101100110 (011)^%d 0"
REACH_R, REACH_STEPS, REACH_EVENT = 16797709, 1818198163340705, 6086451
BASE, INC, EVENTS, STEPS0, STEPS1 = 65, 321042928, 116320154, 650373336347246654, 8765861712


def C(cnt):
    """The normal form of the right side of C(r), the count of the last block replaced by cnt."""
    t = norm(parse(CF % 777))
    assert sum(1 for x in t if not isinstance(x, int) and x[1][0] == 777) == 1
    return [x if isinstance(x, int) or x[1][0] != 777 else (x[0], cnt) for x in t]


def run_to(e, target, limit=3 * 10 ** 7):
    while not (e.st == 4 and not e.L and e.toks() == target):
        e.move()
        assert e.moves < limit, "no arrival"


def tables():
    e = Engine(discover=True)
    run_to(e, C(cst(REACH_R)))
    assert (e.ev, e.steps) == (REACH_EVENT, cst(REACH_STEPS)), (e.ev, e.steps)
    e2 = Engine(e.shiftR, e.shiftL, e.rules, True)
    e2.st = 4
    e2.R = list(reversed(C((BASE, (2,)))))
    e2.env = [(REACH_R - BASE) // 2]
    run_to(e2, C((BASE + INC, (2,))))
    assert (e2.ev, e2.steps) == (EVENTS, (STEPS0, (STEPS1,))), (e2.ev, e2.steps)
    return e.shiftR, e.shiftL, e.rules


def static(shR, shL, rules0):
    rules = []
    for r in rules0:
        q = Rule(r.tmpl, r.events)
        assert prove_rule(q, shR, shL, False)
        assert all(isinstance(t, int) or t[0] == 'f' or (t[2] - t[3]) % 2 == 0 for t in q.tmpl)
        rules.append(q)
    a = Engine(shR, shL, rules, False)
    run_to(a, C(cst(REACH_R)))
    assert (a.ev, a.steps) == (REACH_EVENT, cst(REACH_STEPS))
    p = Engine(shR, shL, rules, False)
    p.st = 4
    p.R = list(reversed(C((BASE, (2,)))))
    run_to(p, C((BASE + INC, (2,))))
    assert (p.ev, p.steps) == (EVENTS, (STEPS0, (STEPS1,)))
    return rules, a.moves, p.moves


# ---------------------------------------------------------------- Lean text
def lb(w):
    return "[" + ", ".join("true" if b else "false" for b in w) + "]"


def lcnt(n):
    return "⟨%d, [%s]⟩" % (n[0], ", ".join(map(str, n[1])))


def ltoks(toks):
    return "[" + ", ".join(".cell %s" % ("true" if t else "false") if isinstance(t, int)
                           else ".blk %s %s" % (lb(t[0]), lcnt(t[1])) for t in toks) + "]"


def ltmpl(tmpl):
    out = []
    for t in tmpl:
        if isinstance(t, int):
            out.append(".cell %s" % ("true" if t else "false"))
        elif t[0] == 'f':
            out.append(".fix %s %d" % (lb(t[1]), t[2]))
        else:
            out.append(".var %s %d %d" % (lb(t[1]), t[2], t[3]))
    return "[" + ",\n    ".join(out) + "]"


def srules(tab):
    out = []
    for (st, w), lst in tab.items():
        for k, u, v, c in lst:
            out.append("⟨.%s, %s, %d, %s, %s, %d⟩" % ("ABCDEF"[st], lb(w), k, lb(u), lb(v), c))
    return out


HEAD = "/-! Generated by `py/replay/gen.py`; do not edit by hand. -/\n\nnamespace H65826\n\nopen TM\n\n"


def write(shR, shL, rules, ka, kp):
    o = ["import Exec\n\n", HEAD]
    for name, ok, tab in (("shR", "OKR", shR), ("shL", "OKL", shL)):
        rs = srules(tab)
        for i, r in enumerate(rs):
            o.append("def %s%d : SRule := %s\n" % (name, i, r))
            o.append("theorem %s%d_ok : %s%d.%s := fun _ _ => rfl\n" % (name, i, name, i, ok))
        o.append("\n/-- The shift rules to the %s. -/\ndef %sTbl : List SRule := [%s]\n\n"
                 % ("right" if name == "shR" else "left", name, ", ".join("%s%d" % (name, i) for i in range(len(rs)))))
        o.append("theorem %sTbl_ok : ∀ r ∈ %sTbl, r.%s := by\n  intro r hr\n" % (name, name, ok))
        o.append("  simp only [%sTbl, List.mem_cons, List.mem_nil_iff, or_false] at hr\n" % name)
        o.append("  rcases hr with %s\n" % " | ".join(["rfl"] * len(rs)))
        for i in range(len(rs)):
            o.append("  · exact %s%d_ok\n" % (name, i))
        o.append("\n")
    o.append("/-- The tables without cycle rules: what the cycle rules themselves are proved with. -/\n")
    o.append("def T0 : Tbl := ⟨shRTbl, shLTbl, []⟩\n\n")
    o.append("theorem T0_ok : T0.OK := ⟨shRTbl_ok, shLTbl_ok, fun _ h => absurd h List.not_mem_nil⟩\n\n")
    for i, r in enumerate(rules):
        o.append("/-- Cycle rule %d (%d events a cycle): `E> %s`, the counts with a variable going %s. -/\n"
                 % (i, r.events, fmt(r.sym(0)),
                    ", ".join("%d -> %d" % (t[2], t[3]) for t in r.tmpl if not isinstance(t, int) and t[0] == 'v')))
        o.append("def rule%d : List TT :=\n   %s\n\n" % (i, ltmpl(r.tmpl)))
        o.append("theorem rule%d_ok : RuleOK rule%d := ruleOK_of_run T0_ok %d (by native_decide)\n\n" % (i, i, r.K))
    n = len(rules)
    o.append("/-- The tables of the replay. -/\ndef T : Tbl := ⟨shRTbl, shLTbl, [%s]⟩\n\n"
             % ", ".join("rule%d" % i for i in range(n)))
    o.append("theorem T_ok : T.OK := by\n  refine ⟨shRTbl_ok, shLTbl_ok, ?_⟩\n  intro t ht\n")
    o.append("  simp only [T, List.mem_cons, List.mem_nil_iff, or_false] at ht\n")
    o.append("  rcases ht with %s\n" % " | ".join(["rfl"] * n))
    for i in range(n):
        o.append("  · exact ⟨rule%d_ok, by decide⟩\n" % i)
    o.append("\n/-- The right side of C(r) in normal form, as tokens; `n` is the count of the last block. -/\n")
    t = C((777, (9,)))
    o.append("def cycToks (n : Cnt) : List Tok :=\n  %s\n\nend H65826\n" % ltoks(t).replace("⟨777, [9]⟩", "n"))
    open(os.path.join(LEAN, "ExecData.lean"), "w").write("".join(o))
    a = ["import ExecData\n\n", HEAD]
    a.append("/-- %d moves of the executor from blank tape end at C(%d). -/\n" % (ka, REACH_R))
    a.append("theorem arrive_run : run T %d ⟨[], [], .A⟩ = some ⟨[], cycToks ⟨%d, []⟩, .E⟩ := by\n  native_decide\n\n"
             % (ka, REACH_R))
    a.append("end H65826\n")
    open(os.path.join(LEAN, "Arrive.lean"), "w").write("".join(a))
    p = ["import ExecData\n\n", HEAD]
    p.append("/-- %d moves of the executor from C(%d + 2 x), x free, end at C(%d + 2 x). -/\n"
             % (kp, BASE, BASE + INC))
    p.append("theorem period_run :\n    run T %d ⟨[], cycToks ⟨%d, [2]⟩, .E⟩ = some ⟨[], cycToks ⟨%d, [2]⟩, .E⟩ := by\n"
             "  native_decide\n\n" % (kp, BASE, BASE + INC))
    p.append("end H65826\n")
    open(os.path.join(LEAN, "Period.lean"), "w").write("".join(p))


def main():
    shR, shL, rules0 = tables()
    rules, ka, kp = static(shR, shL, rules0)
    print("shift rules: %d right, %d left; cycle rules: %d (proof runs of %s moves)"
          % (sum(map(len, shR.values())), sum(map(len, shL.values())), len(rules), [r.K for r in rules]))
    print("arrival: %d moves; period: %d moves; events and step counts as claimed" % (ka, kp))
    if '--check' not in sys.argv:
        write(shR, shL, rules, ka, kp)
        print("written: lean/ExecData.lean, lean/Arrive.lean, lean/Period.lean")


if __name__ == "__main__":
    main()
