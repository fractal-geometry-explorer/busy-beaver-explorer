"""Generate lean/Rules.lean for 1RB0RC_0RC1RC_0LD0RA_1LE0LF_0LA1LC_---1LA: one-cycle rules of its phases, proved along the symbolic run of
tools/py/bbtools/symtm.py (single steps by `rfl`, shift rules by TM.cross_r/cross_l, re-bracketing by TM.rep_rotate).

usage (from the repo root): python3 holdouts/1RB0RC_0RC1RC_0LD0RA_1LE0LF_0LA1LC_---1LA/py/rules.py > holdouts/1RB0RC_0RC1RC_0LD0RA_1LE0LF_0LA1LC_---1LA/lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RC_0RC1RC_0LD0RA_1LE0LF_0LA1LC_---1LA"
NS = next(l.split()[1] for l in open(os.path.join(HERE, "..", "lean", "Machine.lean")) if l.startswith("namespace "))

RULES = [
    ("a_right",
     "L A> (0011011)^n R",
     "L (1100110)^n A> R",
     "Going right, A crosses the left block (words of seven cells) in 13 steps a word."),
    ("d_left",
     "L (1011001)^n D> 1 R",
     "L D> 1 (0110110)^n R",
     "Going left, D crosses the left block in 23 steps a word."),
    ("a_right3",
     "L A> (011)^n R",
     "L (110)^n A> R",
     "Going right, A crosses the right block (words `011`) in 3 steps a word."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
