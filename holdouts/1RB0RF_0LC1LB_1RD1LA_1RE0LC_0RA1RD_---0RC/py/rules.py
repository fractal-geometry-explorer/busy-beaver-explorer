"""Generate ../lean/Rules.lean: the shift and macro rules of 1RB0RF_0LC1LB_1RD1LA_1RE0LC_0RA1RD_---0RC, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RF_0LC1LB_1RD1LA_1RE0LC_0RA1RD_---0RC"

RULES = [
    ('d_c', 'L D> (011)^n R', 'L (001)^n D> R',
     'D going right turns 011 words into 001 words.'),
    ('d_q1', 'L D> (011010101)^n R', 'L (001111111)^n D> R',
     'Level 1: D going right turns the sparse word 011(01)^3 into the dense word 001 1^6.'),
    ('c_p1', 'L (111111100)^n C> 1 R', 'L C> 1 (011010101)^n R',
     'Level 1: C going left turns the dense word back into the sparse one.'),
    ('e_q1', 'L E> (101101010)^n R', 'L (100111111)^n E> R',
     'Level 1: E going right also makes the word dense.'),
    ('d_q2', 'L D> (011010101010101)^n R', 'L (001111111111111)^n D> R',
     'Level 2: D going right turns the sparse word 011(01)^6 into the dense word 001 1^12.'),
    ('e_q2', 'L E> (101101010101010)^n R', 'L (100111111111111)^n E> R',
     'Level 2: E going right also makes the word dense.'),
    ('d_q3', 'L D> (011010101010101010101)^n R', 'L (001111111111111111111)^n D> R',
     'Level 3: D going right turns the sparse word 011(01)^9 into the dense word 001 1^18.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=20)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H42170", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
