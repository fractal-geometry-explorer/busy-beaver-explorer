"""Generate lean/Events.lean for 1RB0LB_0RC0LD_1LD1RE_0LA0RF_1RB0RD_0RB--- (usage: python3 py/events.py > lean/Events.lean;
`python3 py/events.py --coverage STEPS` matches every event of the run against the rule starts).

Here E0 = 1RB, E1 = 0RD (the reference's E1 and E0 with the read symbol swapped) and F0 = 0RB.  The event (A on
cell 3) is visited only in phase 1, at every second event of the reference: the configurations at the events are
exactly the reference's events 2, 4, 6, ... (checked for 2,097,151 events, 3*10^8 steps).  So one event here is a left
increment and a right increment in one pass: the head carries over the left counter, comes back through the engine
and carries the right counter, then returns.  Each rule = the reference's left rule followed by one of its right
rules (14n steps for the left carry where the reference takes 12n).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "1RB0LB_0RC0LD_1LD1RE_0LA0RF_0RD1RB_0RC---", "py"))
import events as ref  # noqa: E402  (the reference machine's rules and tools)

M = "1RB0LB_0RC0LD_1LD1RE_0LA0RF_1RB0RD_0RB---"
POS = 3
PREFIX = "x_"
LF = "L 0 0 0 1 (0101)^n 0 0 0 1 A> 1"
LT = "L 0 1 0 1 (0001)^n 0 0 0 1 A> 1"
RULES = []
for name, s, e, d in ref.RULES[1:]:
    assert s.startswith(ref.E + " 0 ") and e.startswith(ref.E + " 1 ")
    RULES.append(("left_" + name, LF + s[len(ref.E) + 2:], LT + e[len(ref.E) + 2:],
                  "Left increment (carry over n ones) and then: " + d[0].lower() + d[1:]))

if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--coverage":
        ref.coverage(M, POS, "A", int(sys.argv[2]), RULES, show=int(sys.argv[3]) if len(sys.argv) > 3 else 0)
    else:
        sys.stdout.write(ref.rules_file("Machine", "H28035", ref.theorems(M, RULES, PREFIX),
                                        f"Counter increments of {M}, generated by `py/events.py`; do not edit by hand."))
