import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'tools', 'py'))
from bbtools.symtm import prove, ProofError, rules_file
G = "1RB0LE_0LC0RA_1LE0RD_0RB---_0LF0LD_1LA0LF"
sp = lambda s: ' '.join(s)
ENG = sp("00101001010100")
PRE = sp("1001010100100101010010001001000100100010101010")
MD = {0: "1 0 0 0", 1: "1 0 1 0"}
def rules():
    out = []
    lefts = [("c", "L 0 0 0 (100)^k", "L 1 0 0 (000)^k", "the left counter (3-cell digits 000 = 0, 100 = 1, lowest digit next to the engine) gets 1, carrying over k ones"),
             ("w", "0^inf (100)^k", "0^inf 1 0 0 (000)^k", "the left counter 1...1 (k digits, at the left end of the tape) becomes 10...0 (one digit more)")]
    for ln, ls, le, ld in lefts:
        for m in range(3):
            a, b = m & 1, m >> 1
            c, d = (m + 1) & 1, (m + 1) >> 1
            s = f"{ls} {ENG} A> 0 {PRE} {MD[a]} {MD[b]} R"
            e = f"{le} {ENG} A> 0 {PRE} {MD[c]} {MD[d]} R"
            name = f"ev_{ln}_m{m}"
            t, _ = prove(G, name, s, e, doc=f"One event: {ld}; the 2-bit counter M = {m} becomes {m+1}; nothing right of M is read.",
                         rotate=True, count_first=True, max_seg=40)
            out.append(t)
            print('OK', name, t.split('\n')[2][:40], file=sys.stderr)
    return out
if __name__ == "__main__":
    sys.stdout.write(rules_file("Machine", sys.argv[1], rules(), f"Event rules of {G} (left binary counter and 2-bit counter M), generated by `py/events.py`; do not edit by hand."))
