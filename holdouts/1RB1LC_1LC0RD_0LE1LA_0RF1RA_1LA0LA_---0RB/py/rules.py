"""Generate lean/Rules.lean: rules of 1RB1LC_1LC0RD_0LE1LA_0RF1RA_1LA0LA_---0RB, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 py/rules.py > lean/Rules.lean      (from holdouts/1RB1LC_1LC0RD_0LE1LA_0RF1RA_1LA0LA_---0RB)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LC_1LC0RD_0LE1LA_0RF1RA_1LA0LA_---0RB"

RULES = [
    ('crawl', 'L 1 1 1 0 C> 1^n+2 R', 'L 1 1 1 1 1^n 0 1 A> R',
     'The crawl: a single 0 moves right through a block of 1s, one cell per 5 steps (C, B and A take turns), in 5n+4 steps.'),
    ('a_crawl', 'L 0 1 A> 1^n R', 'L 1^n 0 1 A> R',
     'The same crawl as a shift rule in state A: the pair `0 1` travels right through 1s, 5 steps a cell.')
]


def main():
    thms = []
    for name, start, end, doc in RULES:
        text, _ = prove(M, name, start, end, doc=doc + f" `{start}` to `{end}`.", count_first=True)
        thms.append(text)
    sys.stdout.write(rules_file("Machine", "H134427", thms,
                                "Rules of 1RB1LC_1LC0RD_0LE1LA_0RF1RA_1LA0LA_---0RB, generated by `py/rules.py` (tools/py/bbtools/symtm.py); do not edit "
                                "by hand. Each theorem holds for every value of its variables and every tape L, R."))


if __name__ == "__main__":
    main()
