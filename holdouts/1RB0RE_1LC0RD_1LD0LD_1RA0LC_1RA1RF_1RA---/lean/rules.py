"""Generate Rules.lean: shift rules of 1RB0RE_1LC0RD_1LD0LD_1RA0LC_1RA1RF_1RA---, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape, `0^inf` is blank tape.  See README.md for where each rule is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC0RD_1LD0LD_1RA0LC_1RA1RF_1RA---"

RULES = [
    ('a_right', 'L 0 A> (10)^n 0 R', 'L 0 (01)^n A> 0 R', {},
     'State A runs right across a block of `10`s, shifting it by one cell.'),
    ('a_right1', 'L 1 A> (10)^n 1 R', 'L 1 (01)^n A> 1 R', {},
     'The same between ones.'),
    ('d_left', 'L 1 (10)^n D> 1 R', 'L 1 D> 1 (10)^n R', {},
     'State D runs left across a block of `10`s unchanged.'),
    ('c_left', 'L 0 (01)^n C> 0 R', 'L 0 C> 0 (01)^n R', {},
     'State C runs left across a block of `01`s unchanged.'),
    ('e_right', 'L 0 E> (01)^n 0 R', 'L 0 (10)^n E> 0 R', {},
     'State E runs right across a block, shifting it back.'),
    ('tick_stop', '0^inf D> 0 (10)^a+1 0 0 0 (10)^b 1 R', '0^inf D> 0 (10)^a+2 0 (10)^b+1 1 R', {'rotate': True},
     'One tick of the counter whose first digit is 0 (separator `0 0 0`): the digit becomes 1 (separator `0`), its '
     'first block gains one `10`, and the first block of the tape gains one; 4a + 10 steps.'),
    ('tick_pass1', '0^inf D> 0 (10)^a+1 0 (10)^b+1 1 (10)^c+2 0 0 0 (10)^d 1 R',
     '0^inf D> 0 (10)^a+2 0 0 0 (10)^b+1 1 (10)^c+1 0 (10)^d+1 1 R', {'rotate': True},
     'One tick with a carry over one digit: the first digit goes from 1 to 0 (separator `0` to `0 0 0`, its second '
     'block loses one `10`), the second from 0 to 1; 4a + 8b + 4c + 34 steps.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, **kw)[0] for name, a, b, kw, doc in RULES]
    out = rules_file("Machine", "H131775", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    # the long chains of single steps in the tick rules need more than the default heartbeats
    out = out.replace("namespace H131775", "set_option maxHeartbeats 3000000\n\nnamespace H131775", 1)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
