"""Generate lean/Rules.lean for 1RB0RE_0LC0RF_1LD1LC_1RA0LD_0RD1RE_---0LB: one-cycle rules of its phases, proved along the symbolic run of
tools/py/bbtools/symtm.py (single steps by `rfl`, shift rules by TM.cross_r/cross_l, re-bracketing by TM.rep_rotate).

usage (from the repo root): python3 holdouts/1RB0RE_0LC0RF_1LD1LC_1RA0LD_0RD1RE_---0LB/py/rules.py > holdouts/1RB0RE_0LC0RF_1LD1LC_1RA0LD_0RD1RE_---0LB/lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_0LC0RF_1LD1LC_1RA0LD_0RD1RE_---0LB"
NS = next(l.split()[1] for l in open(os.path.join(HERE, "..", "lean", "Machine.lean")) if l.startswith("namespace "))

RULES = [
    ("grow",
     "0^inf D> 0 0 (1)^5 (00111)^a (100)^a+1 (10111)^b+1 R",
     "0^inf D> 0 0 (1)^5 (00111)^a+1 (100)^a+2 (10111)^b R",
     "Phase A, one visit of the left end: a word `10111` of the right block becomes one `00111` and one `100` on the left (the tape further right, R, is not read)."),
    ("pour",
     "0^inf D> 0 0 (1)^5 (00111)^a (100)^c+4 (111100)^e 0 0^inf",
     "0^inf D> 0 0 (1)^5 (00111)^a+2 (100)^c+2 (111100)^e+1 0 0^inf",
     "Phase B, two visits of the left end: two words `100` go, the left block gains two words `00111` and the right block one `111100`."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
