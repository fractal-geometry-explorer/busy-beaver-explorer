"""Shift rules of 1RB0LA_0RC0LE_0RD1RC_1LD1RE_1LA1RF_---0RB, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LA_0RC0LE_0RD1RC_1LD1RE_1LA1RF_---0RB/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L 1 0 C> (10)^n R` is the head
in state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LA_0RC0LE_0RD1RC_1LD1RE_1LA1RF_---0RB"
NS = "H35717"
DOC = """# Shift rules of 1RB0LA_0RC0LE_0RD1RC_1LD1RE_1LA1RF_---0RB

The two passes over the bulk of the tape, which is made of the words 110 (seen at the right end) or 010 (seen at
the left end): moving right C turns each `010` into `101`, seven steps a word, so that `1 (010)^n` becomes
`(110)^n 1` (`pass_right`); moving left A turns each `011` back into `010` in fifteen steps (`pass_left`).  The only
halt is F reading a 0, reached from `E> 1 0` (`halt_E`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('pass_right',
     'L 1 C> (010)^n R',
     'L 1 (101)^n C> R',
     'C crosses `010` rightwards in seven steps and leaves `101`.'),
    ('pass_left',
     'L (011)^n A> 1 0 R',
     'L A> 1 (010)^n 0 R',
     'A crosses `011` leftwards in fifteen steps and leaves `010`.')
]

# hand-written statements appended to the file (the halting situations), proved by `rfl`
EXTRA = """/-- `E> 1 0` halts: E keeps the 1 and moves right in state F, which reads a 0. -/
theorem halt_E (L R : Tape) : ∃ c, steps 1 ⟨L, cons true (cons false R), .E⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩
"""


def main():
    thms = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
