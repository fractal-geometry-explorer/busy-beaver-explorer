"""Write lean/Rules.lean for 1RB1LD_0RC0LF_1LD1RE_0LA0RB_0RD1RB_0LD---: the three moves of the left binary counter,
for every number n of trailing one-digits and any tape around them, proved by `bbtools.symtm.prove`.

Digits of the left counter are 4 cells, 1010 (one) and 1000 (zero), least significant next to the centre; the head
arrives from the centre in state D on the 0 just right of the counter's final 1.

Usage (from the repository root):
  python3 holdouts/1RB1LD_0RC0LF_1LD1RE_0LA0RB_0RD1RB_0LD---/py/gen_rules.py > holdouts/1RB1LD_0RC0LF_1LD1RE_0LA0RB_0RD1RB_0LD---/lean/Rules.lean"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB1LD_0RC0LF_1LD1RE_0LA0RB_0RD1RB_0LD---"
RULES = [
    ("left_increment", "L 1 0 0 0 (1010)^n 1 D> 0 R", "L 1 0 1 0 1 (0001)^n E> 0 R",
     "Increment: n trailing one-digits 1010 and a zero-digit 1000 before them become 1010 followed by n zero-digits; "
     "A walks left over the ones, E walks back right rewriting each 0101 as 0001."),
    ("left_overflow_even", "0^inf (1010)^n 1 D> 0 R", "0^inf 1 0 1 (0001)^n 0 D> R",
     "Overflow of an all-ones counter with no prefix: the counter becomes the prefix 10 followed by n zero-digits; "
     "the tape grows by two cells on the left."),
    ("left_overflow_odd", "0^inf 1 0 (1010)^n 1 D> 0 R", "0^inf 1 0 1 0 0 (0100)^n 0 C> R",
     "Overflow of an all-ones counter with the prefix 10: the tape grows by two cells on the left and C carries on to "
     "the right (in the run the next visit finds n + 1 one-digits and no prefix, which overflows at once)."),
]

def main():
    ths = []
    for name, s, e, doc in RULES:
        t, fin = prove(M, name, s, e, doc=doc)
        print(f"-- {name}: {s} -> {fin}", file=sys.stderr)
        ths.append(t)
    print(rules_file("Machine", "H173741", ths, "Rules of the left binary counter of " + M + ", generated by "
                     "`py/gen_rules.py` with `tools/py/bbtools/symtm.py`; do not edit by hand."), end="")

if __name__ == "__main__":
    main()
