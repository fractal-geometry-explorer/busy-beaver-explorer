"""Write lean/Carry.lean for 1RB1LD_0RC0LF_1LD1RE_0LA0RB_0RD1RB_0LD---: the machine as a carry system.

Between two moments of the following kind the machine takes one to five steps, so the whole run is a sequence of
these moves (`py/carry_system.py` replays the run with them and compares with the plain machine):

  `>`  the head in state B, about to read the cell after the mark (moving right);
  `<`  the head in state D on the cell before the mark (moving left).

  R1  >011  -> 011>        R4  >00  -> 0<1          L1  10< -> <10
  R2  >0100 -> 011>0       R5  0>1  -> <00          L2  00< -> 1>0
  R3  >0101 -> 0100>       halt: >0111              L3  1<  -> 0>

Each rule is a Lean theorem about the machine's step function, for every tape around the cells shown (R5 and L1 are
stated twice, for the two values of the cell the head lands on).  `carry` is the first consequence: a block of
3-cell digits 010 (one) followed by 00 is a binary counter under a hit from the left.

Usage (from the repository root):
  python3 holdouts/1RB1LD_0RC0LF_1LD1RE_0LA0RB_0RD1RB_0LD---/py/gen_carry.py > holdouts/1RB1LD_0RC0LF_1LD1RE_0LA0RB_0RD1RB_0LD---/lean/Carry.lean"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB1LD_0RC0LF_1LD1RE_0LA0RB_0RD1RB_0LD---"
RULES = [
    ("r1", "L B> 0 1 1 R", "L 0 1 1 B> R", "R1: `>011 -> 011>`. B passes over 011 and leaves it as it is."),
    ("r2", "L B> 0 1 0 0 R", "L 0 1 1 B> 0 R",
     "R2: `>0100 -> 011>0`. A one-digit 010 followed by a 0 becomes 011 and the hit goes on to the next cell: a carry."),
    ("r3", "L B> 0 1 0 1 R", "L 0 1 0 0 B> R", "R3: `>0101 -> 0100>`. The 1 after 010 is erased and B goes on behind it."),
    ("r4", "L B> 0 0 R", "L D> 0 1 R", "R4: `>00 -> 0<1`. B turns round on 00, leaving 01; D stands on the first of the two cells."),
    ("r5_0", "L 0 0 B> 1 R", "L D> 0 0 0 R", "R5: `0>1 -> <00` (the cell D lands on is 0). B on a 1 after a 0 erases it and D goes two cells left."),
    ("r5_1", "L 1 0 B> 1 R", "L D> 1 0 0 R", "R5: `0>1 -> <00` (the cell D lands on is 1)."),
    ("l1_0", "L 0 1 D> 0 R", "L D> 0 1 0 R", "L1: `10< -> <10` (the cell D lands on is 0). D on the 0 of a pair 10 skips the pair."),
    ("l1_1", "L 1 1 D> 0 R", "L D> 1 1 0 R", "L1: `10< -> <10` (the cell D lands on is 1)."),
    ("l2", "L 0 D> 0 R", "L 1 B> 0 R", "L2: `00< -> 1>0`. D on the second cell of 00 turns round, leaving 10."),
    ("l3", "L D> 1 R", "L 0 B> R", "L3: `1< -> 0>`. D on a 1 erases it and turns round."),
    ("carry", "L 1 B> 0 (100)^k 1 0 0 0 R", "L 1 D> 0 0 0 (000)^k 0 1 R",
     "The binary carry on the right: after a 1, the block (010)^(k+1) 00 hit by B becomes (000)^(k+1) 01 and D is back "
     "on its first cell (the block is written 0 (100)^k 1000 here). Read 010 as the digit one and 000 as zero, lowest "
     "digit first: k+1 ones followed by a zero become k+1 zeros followed by a one."),
]

HALT = '''/-- The halting pattern `>0111`: B about to read 0 1 1 1 halts four steps later (B, C, E walk right, B reads the third 1
and steps back, F reads the second 1). Reading the table backwards, this is the only way to reach F on a 1: F is
entered only from B on a 1, and a B that reads a 1 with a 1 on its left was entered from E on a 1 (the other way to
get a 1 on the left, from A on a 0, puts B on a cell that D has just left as 0), E from C on a 1, C from B on a 0. -/
theorem halt_pattern (L R : Tape) :
    ∃ c, steps 4 ⟨L, cons false (cons true (cons true (cons true R))), .B⟩ = some c ∧ step c = none :=
  ⟨⟨cons true (cons false L), cons true (cons false R), .F⟩, rfl, rfl⟩
'''

def main():
    ths = []
    for name, s, e, doc in RULES:
        t, fin = prove(M, name, s, e, doc=doc)
        print(f"-- {name}: {s} -> {fin}", file=sys.stderr)
        ths.append(t)
    ths.append(HALT)
    print(rules_file("Machine", "H173741", ths, "The carry system of " + M + ": the local rules between moments "
                     "with the head in B moving right or in D moving left, the halting pattern, and the binary carry. "
                     "Generated by `py/gen_carry.py` with `tools/py/bbtools/symtm.py`; do not edit by hand."), end="")

if __name__ == "__main__":
    main()
