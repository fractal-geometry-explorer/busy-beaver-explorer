"""Generate Rules.lean: the rounds of a phase of 1RB0RE_1LC0RA_1LA1LD_1LC1LF_0LC0LB_1LE---, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^k` is k copies of `10`, `1^m`
is m ones, R is any tape, `0^inf` is blank tape.  A phase starts at PS(M, T) = `0^inf F> 0 1^M T` (README.md).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC0RA_1LA1LD_1LC1LF_0LC0LB_1LE---"

RULES = [
    ("start", "0^inf F> 0 1^m+5 R", "0^inf D> 0 1 (10)^5 1^m R", {},
     "The start of a phase: five ones of the block become the first five `10` of the wall."),
    ("round", "0^inf D> 0 1 (10)^k 1^m+3 R", "0^inf D> 0 1 1 0 1 0 1 0 (10)^k 1 0 (1)^m R", {"rotate": True},
     "One round trip across the wall: three more ones are eaten and the wall gains four `10` (k + 4 in all), "
     "6k + 39 steps."),
    ("gap_left", "L (10)^n B> 0 0 R", "L B> 0 0 (10)^n R", {},
     "Inside a round: the gap `00` runs left through the wall (states B and E, four steps per `10`)."),
    ("unwall", "L (10)^n C> 1 R", "L C> 1 (11)^n R", {},
     "At the end of a phase: state C runs left across the wall and turns every `10` into `11`."),
    ("end_e0", "0^inf D> 0 1 (10)^k 0^inf", "0^inf F> 0 1 1 (11)^k+2 1 0^inf", {"rotate": True},
     "End of a phase with no tail and no ones left: the wall of k pairs becomes 2k + 7 ones."),
    ("end_e1", "0^inf D> 0 1 (10)^k 1 0^inf", "0^inf F> 0 1 1 (11)^k+3 1 0^inf", {"rotate": True},
     "End of a phase with no tail and one one left: 2k + 9 ones."),
    ("end_e2", "0^inf D> 0 1 (10)^k+2 1 1 0^inf", "0^inf F> 0 1 1 (11)^k+2 1 0 1 1 1 1 1 1 0^inf",
     {"rotate": True},
     "End of a phase with no tail and two ones left: 2(k + 2) + 3 ones, and a block of six ones is pushed as tail."),
    ("end_s0", "0^inf D> 0 1 (10)^k 0 1 1 1 1 1 1 0^inf", "0^inf F> 0 1 1 (11)^k+5 1 0^inf", {"rotate": True},
     "End of a phase with tail [6] and no ones left: the tail is consumed, 2k + 13 ones."),
    ("end_s1", "0^inf D> 0 1 (10)^k 1 0 1 1 1 1 1 1 0^inf", "0^inf F> 0 1 1 (11)^k+11 1 0^inf", {"rotate": True},
     "End of a phase with tail [6] and one one left: three passes over the wall, the tail is consumed, 2k + 25 ones."),
    ("end_s2", "0^inf D> 0 1 (10)^k+1 1 1 0 1 1 1 1 1 1 0^inf",
     "0^inf F> 0 1 1 (11)^k+3 1 0 1 0 1 0 1 1 1 0^inf", {"rotate": True},
     "End of a phase with tail [6] and two ones left: 2(k + 1) + 7 ones and the tail becomes [1, 1, 3]."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, **kw)[0] for name, a, b, kw, doc in RULES]
    out = rules_file("Machine", "H103424", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    # the chain of steps in `end_s1` needs more than the default heartbeats to elaborate
    out = out.replace("namespace H103424", "set_option maxHeartbeats 3000000\n\nnamespace H103424", 1)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
