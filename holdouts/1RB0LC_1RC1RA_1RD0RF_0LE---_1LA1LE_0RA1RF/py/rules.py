"""Shift rules of 1RB0LC_1RC1RA_1RD0RF_0LE---_1LA1LE_0RA1RF, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LC_1RC1RA_1RD0RF_0LE---_1LA1LE_0RA1RF/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L 1 0 C> (10)^n R` is the head
in state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LC_1RC1RA_1RD0RF_0LE---_1LA1LE_0RA1RF"
NS = "H63327"
DOC = """# Shift rules of 1RB0LC_1RC1RA_1RD0RF_0LE---_1LA1LE_0RA1RF

Passes over the regular parts of the tape.  The 24-cell word `q = 010110101101010110101101` (here in the rotation the
head meets) is rewritten by A moving right, 32 steps a copy (`pass_right_q`), and rewritten back by C moving left,
68 steps a copy (`pass_left_q`); A also crosses runs of `011` (`pass_right_c`).  The only halt is D reading a 1, and
D is entered only from C reading a 0, so `C> 0 1` halts (`halt_C`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

# Lean options put before the first theorem (the long words need a deeper recursion limit)
OPTIONS = 'set_option maxRecDepth 100000\n\n'

RULES = [
    ('pass_right_q',
     'L A> (011010110101011010110101)^n R',
     'L (100111001111100111001111)^n A> R',
     'A moving right over the q-region, 32 steps a copy.'),
    ('pass_left_q',
     'L (011111001110011111001110)^n C> 0 0 R',
     'L C> 0 0 (110101011010110101011010)^n R',
     'C moving left over the rewritten q-region, 68 steps a copy, restoring q.'),
    ('pass_right_c',
     'L A> (011)^n R',
     'L (100)^n A> R',
     'A moving right over a run of `011`, 5 steps a copy.')
]

# hand-written statements appended to the file (the halting situations), proved by `rfl`
EXTRA = """/-- `C> 0 1` halts: C writes a 1 and steps right in state D onto a 1, which has no transition. -/
theorem halt_C (L R : Tape) :
    ∃ c, steps 1 ⟨L, cons false (cons true R), .C⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩
"""


def main():
    thms = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    thms[0] = OPTIONS + thms[0]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
