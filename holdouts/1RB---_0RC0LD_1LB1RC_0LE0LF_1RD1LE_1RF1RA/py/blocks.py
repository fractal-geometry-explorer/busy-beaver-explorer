def main():
    m = Machine.parse(M)
    ths = []
    for name, start, end, doc in RULES:
        th, _ = prove(M, "bp_" + name, start, end, doc=doc)
        ths.append(th)
    for name, start, doc in HALTS:
        c = Config.parse(start)
        try:
            run(m, c, lambda c: False, max_moves=1000)
        except Halted:
            pass
        th, _ = prove(M, "bp_" + name, start, repr(c), doc=doc)
        ths.append(th)
    d = os.path.join(HERE, "..", "lean")
    open(os.path.join(d, "BPieces.lean"), "w").write(rules_file(
        "Machine", NS, ths, f"Pieces of the block map of {M}, generated by `py/blocks.py`; do not edit."))
    open(os.path.join(d, "Blocks.lean"), "w").write(BLOCKS.replace("@K@", str(K)).replace("@NS@", NS))
    print("wrote", len(ths), "pieces")


if __name__ == "__main__":
    main()
