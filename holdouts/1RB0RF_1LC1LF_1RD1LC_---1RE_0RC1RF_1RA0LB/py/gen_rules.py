"""Write lean/Rules.lean: the sweeps, the two increment rules of the binary counter and the right-end rule of
1RB0RF_1LC1LF_1RD1LC_---1RE_0RC1RF_1RA0LB, each proved by `bbtools.symtm.prove` (rfl steps and the crossing lemmas
of tools/lean/TM/Basic.lean).  Run from this folder: python3 py/gen_rules.py > lean/Rules.lean

The counter (see README.md): with W(m) the bits of m written most significant first as 1111 (1) / 1010 (0) and
V(n) the bits of n written least significant first as 1011 (1) / 1111 (0), the configuration
    ... W(n-1) 1 1 D> 1 1 1 1 1 V(n) ...
is the counter holding n.  `inc_odd` is the step n -> n+1 when n-1 ends in t+1 ones (n even), `inc_even` when n-1
ends in a 0 (n odd, ending in s+1 ones).
"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB0RF_1LC1LF_1RD1LC_---1RE_0RC1RF_1RA0LB"
RULES = [
    ("sweep_A", "L A> (10)^n R", "L (01)^n A> R", "A crosses `1 0` words to the right, turning each into `0 1`."),
    ("sweep_F", "L F> (01)^n R", "L (10)^n F> R", "F crosses `0 1` words to the right, turning each into `1 0`."),
    ("sweep_E", "L E> (01)^n R", "L (11)^n E> R", "E crosses `0 1` words to the right, filling each with 1s."),
    ("sweep_C", "L 1^n C> 1 R", "L C> 1 (1)^n R", "C crosses a block of 1s to the left, leaving it unchanged."),
    ("sweep_B", "L 0 (11)^n 1 B> 1 R", "L B> 0 0 1 (01)^n R",
     "B (with F) crosses pairs `1 1` to the left, turning each into `0 1`."),
    ("inc_odd", "L 1 0 1 0 (1111)^t+1 1 1 D> 1 1 1 1 1 (1111)^t+1 1 0 1 1 R",
     "L 1 1 1 1 (1010)^t+1 1 1 D> 1 1 1 1 1 1 0 1 1 (1111)^t 1 0 1 1 R",
     "The counter goes from n to n + 1 when n - 1 ends in t + 1 ones: left W(n-1) = ..0 1^(t+1) becomes ..1 0^(t+1), "
     "right V(n) = 0^(t+1) 1.. becomes V(n+1) = 1 0^t 1.."),
    ("inc_even", "L 1 0 1 0 1 1 D> 1 1 1 1 1 (1011)^s+1 1 1 1 1 R",
     "L 1 1 1 1 1 1 D> 1 1 1 1 1 (1111)^s+1 1 0 1 1 R",
     "The counter goes from n to n + 1 when n - 1 ends in a 0: left W(n-1) = ..0 becomes ..1, right V(n) = 1^(s+1) 0.. "
     "becomes V(n+1) = 0^(s+1) 1.."),
    ("right_end", "L 0 1^n 0 1 0 1 0 1 A> 0^inf", "L 0 (1)^n 1 1 1 1 0 1 0 1 A> 0^inf",
     "At the right end of the tape the last block of 1s grows by four in 22 steps."),
]


def main():
    ths = []
    for name, s, e, doc in RULES:
        t, _ = prove(M, name, s, e, doc=doc)
        ths.append(t)
    print(rules_file("Machine", "H39952", ths,
                     "Sweeps and counter rules of 1RB0RF_1LC1LF_1RD1LC_---1RE_0RC1RF_1RA0LB, generated by "
                     "`py/gen_rules.py` with `tools/py/bbtools/symtm.py`; do not edit by hand."), end="")


if __name__ == "__main__":
    main()
