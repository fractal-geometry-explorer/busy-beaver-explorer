"""Generate ../lean/Rules.lean: the rules of the macro step of 1RB0RF_1LC---_1RD0LC_0RE0RD_1LF1LC_1LE1RA, each proved
along a symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(w)^t` the word w
repeated t times, L any tape.  The sample configuration is K(P, m) = `0^inf P (10)^m C> 1 1 1 1 1 0^inf`.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RF_1LC---_1RD0LC_0RE0RD_1LF1LC_1LE1RA"

RULES = [
    ("start", "0^inf A> 0^inf", "0^inf 1 1 0 C> 1 1 1 1 1 0^inf", "From blank tape to the first sample K(1, 1)."),
    ("sweep", "L (10)^m+2 C> 1 (11)^j+1 0^inf", "L (10)^m C> 1 (11)^j+4 0^inf",
     "One round trip: C eats two words `10` at the left end of the block of ones, D runs right turning the ones to 0s, "
     "E and F run back turning them to 1s; the block grows by 6."),
    ("end_e0", "0^inf C> 1 (11)^j+2 0^inf", "0^inf 1 (10)^j+4 C> 1 1 1 1 1 0^inf",
     "No word `10` left, prefix empty: the block of 2j + 5 ones is rewritten as words `10`; K(1, j + 4) next."),
    ("end_e1", "0^inf 1 0 C> 1 (11)^j+2 0^inf", "0^inf (10)^j+7 C> 1 1 1 1 1 0^inf",
     "One word `10` left, prefix empty: K(empty, j + 7) next."),
    ("end_10", "0^inf 1 C> 1 (11)^j+2 0^inf", "0^inf (10)^j+4 C> 1 1 1 1 1 0^inf",
     "No word `10` left, prefix `1`: K(empty, j + 4) next."),
    ("end_11", "0^inf 1 1 0 C> 1 (11)^j+2 0^inf", "0^inf 1 0 0 0 (10)^j+4 C> 1 1 1 1 1 0^inf",
     "One word `10` left, prefix `1`: K(1000, j + 4) next."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H119593", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
