"""Write lean/Rules.lean for a machine of the family 1RB?RF_1RC0RA_1LD1RB_1LE0LD_?L?0LB_0RB--- (the two G12 holdouts
1RB0RF_1RC0RA_1LD1RB_1LE0LD_1LB0LB_0RB--- and 1RB1RF_1RC0RA_1LD1RB_1LE0LD_0RA0LB_0RB---): three shift rules,
each proved by `bbtools.symtm.prove` (rfl steps, the crossing lemmas of tools/lean/TM/Basic.lean and omega).

  rec_erase   the start of a record interval: the last block 1^(2k+1) of the word (after a block of three) is
              erased by D and becomes the single marker 1 at the far end of a gap 0^(2k)
  b_sweep10   B moving right turns each 10 into 01
  b_sweep01   B moving right turns each 01 into 11

None of the three reads A1 or E0 (the two cells in which the machines differ), so the same statements hold for both.

usage (from the repository root):
  python3 holdouts/1RB0RF_1RC0RA_1LD1RB_1LE0LD_1LB0LB_0RB---/py/gen_rules.py MACHINE > holdouts/MACHINE/lean/Rules.lean
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

RULES = [
    ("rec_erase", "L 0 1 1 1 0 1 (11)^k B> 0 0 R", "L 0 1 0 1 0 1 1 C> (00)^k 1 R",
     "After a record `W 0 1 1 1 0 1^(2k+1) B>0 0`: the last block is erased, a marker 1 is left 2k cells out."),
    ("b_sweep10", "L B> (10)^k R", "L (01)^k B> R", "B moving right turns each `10` into `01` (2 steps each)."),
    ("b_sweep01", "L B> (01)^k R", "L (11)^k B> R", "B moving right turns each `01` into `11` (2 steps each)."),
]


def main():
    m = sys.argv[1]
    mach = open(os.path.join(HERE, "../../", m, "lean/Machine.lean")).read()
    ns = re.search(r"^namespace (\w+)", mach, re.M).group(1)
    ths = []
    for name, start, end, doc in RULES:
        t, _ = prove(m, name, start, end, doc=doc, count_first=True, max_seg=40, rotate=True)
        ths.append(t)
    print(rules_file("Machine", ns, ths,
                     f"Shift rules of {m}, generated by `py/gen_rules.py` in the folder of "
                     "1RB0RF_1RC0RA_1LD1RB_1LE0LD_1LB0LB_0RB--- (the shared scripts of the family); do not edit by hand."),
          end="")


if __name__ == "__main__":
    main()
