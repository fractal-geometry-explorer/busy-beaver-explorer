w("""/-- The E-event map: the next tail, the next n and the number of steps; `none` for `Z k` with `k = 0` or
`n < 12k + 12`, the only E-events where the machine leaves the map (and where it can halt). -/
def next : Tail → Nat → Option (Tail × Nat × Nat)
  | .one, n => some (nextOne n)
  | .X t, n => some (nextX t n)
  | .Y t, n => some (nextY t n)
  | .Z t, n => if t = 0 ∨ n < 12 * t + 12 then none else some (nextZ t n)

/-- **The map is sound**: wherever `next` is defined, the machine goes from the E-event `Ev n T` to the one
`next` gives, in exactly the number of steps it gives. -/
theorem next_sound (T : Tail) (n : Nat) (T' : Tail) (n' s : Nat) (h : next T n = some (T', n', s)) :
    steps s (Ev n T) = some (Ev n' T') := by
  cases T with
  | one =>
    have hs := nextOne_sound n
    rw [show nextOne n = (T', n', s) from Option.some.inj h] at hs
    exact hs
  | X t =>
    have hs := nextX_sound t n
    rw [show nextX t n = (T', n', s) from Option.some.inj h] at hs
    exact hs
  | Y t =>
    have hs := nextY_sound t n
    rw [show nextY t n = (T', n', s) from Option.some.inj h] at hs
    exact hs
  | Z t =>
    simp only [next] at h
    by_cases hc : t = 0 ∨ n < 12 * t + 12
    · rw [if_pos hc] at h; cases h
    · rw [if_neg hc] at h
      have hs := nextZ_sound t n (by omega) (by omega)
      rw [show nextZ t n = (T', n', s) from Option.some.inj h] at hs
      exact hs
""")
