def L(s, env=None):
    """a Lin string with variables substituted by Lean expressions, printed for Lean"""
    lin = C.S.parse_lin(s)
    if not env:
        return lin.lean()
    parts = []
    for v, a in sorted(lin.c.items()):
        e = env.get(v, v)
        parts.append(f"{a} * ({e})" if a != 1 else f"({e})")
    if lin.k or not parts:
        parts.append(str(lin.k))
    return " + ".join(parts)


def tail(F, t):
    return {"1": ".one", "X": f".X ({t})", "Y": f".Y ({t})", "Z": f".Z ({t})"}[F]


def args(c, env):
    return " ".join(f"({env.get(v, v)})" for v in c["vars"])


