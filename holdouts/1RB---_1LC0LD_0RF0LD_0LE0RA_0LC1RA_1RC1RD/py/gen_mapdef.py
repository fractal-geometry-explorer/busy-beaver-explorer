blocks, cur = [], None
for ln in lines:
    if re.match(r"(theorem |def |/--|end |inductive )", ln):
        if cur:
            blocks.append(cur)
        cur = [ln] if ln.startswith("theorem ") and "_sound" in ln.split()[1] and ln.split()[1] != "next_sound" else None
    elif cur is not None:
        cur.append(ln)
if cur:
    blocks.append(cur)
for b in blocks:
    t = "\n".join(b).rstrip()
    t = t.replace("_sound", "_pos", 1)
    t = re.sub(r"steps (\(\w+[^()]*\))\.2\.2 .* := by$", r"1 ≤ \1.2.2 := by", t, count=1, flags=re.M)
    t = re.sub(r"exact (\w+)_sound", r"exact \1_pos", t)
    t = re.sub(r"exact (\w+)( |$)", lambda m: f"exact T_{m.group(1)}_pos{m.group(2)}" if m.group(1) in names
               else m.group(0), t, flags=re.M)
    t = re.sub(r"have hs := (\w+)_sound", r"have hs := \1_pos", t)
    w(t + "\n")
