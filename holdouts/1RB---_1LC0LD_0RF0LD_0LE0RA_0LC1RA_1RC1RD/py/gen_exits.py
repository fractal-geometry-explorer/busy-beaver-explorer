"""Writes lean/ExitTab.lean: the fate of every start Z_k, n of the region (n < 12k + 12, and Z_0 with n < 24) with
k < K, other than n = 2 and the halting family n = 12k + 9 (k odd), which ZMap.lean handles for every k.

Each start is followed by direct simulation, E-event by E-event, until the tape is again an E-event with one of the
tails 1, X_j, Y_j, Z_j (the tails of the proved map), or the machine halts.  The table lists (k, n, fate); Lean
re-checks every entry with the list simulator of tools/lean/TM/Fin.lean (`lean/Exits.lean`).

usage: python3 gen_exits.py K [PROCS] [--json]   (writes ../lean/ExitTab.lean and ../lean/exits.json; --json:
       only rewrite ExitTab.lean from exits.json)
"""
import json
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from emap import nxt, parse, word  # noqa: E402


def starts(K):
    for k in range(K):
        for n in range(max(12 * k + 12, 24 if k == 0 else 0)):
            if n == 2 or (k % 2 == 1 and n == 12 * k + 9):
                continue
            yield k, n


def fate(arg):
    k, n = arg
    T, m, steps, passes = word("Z", k), n, 0, 0
    while True:
        r = nxt(T, m, 10**12)
        assert r is not None, (k, n, "timeout")
        passes += 1
        if r[0] == "HALT":
            return dict(k=k, n=n, fate="halt", passes=passes, steps=steps + r[1])
        T, m, s = r
        steps += s
        p = parse(T)
        if p is not None:
            return dict(k=k, n=n, fate="to", T=p[0], t=p[1], n2=m, passes=passes, steps=steps)
        assert passes < 100, (k, n)


def lean_tail(F, t):
    return {"1": ".one", "X": f"(.X {t})", "Y": f"(.Y {t})", "Z": f"(.Z {t})"}[F]


if __name__ == "__main__":
    K = int(sys.argv[1])
    procs = int(sys.argv[2]) if len(sys.argv) > 2 and sys.argv[2].isdigit() else 3
    J = os.path.join(HERE, "..", "lean", "exits.json")
    if "--json" in sys.argv:  # rewrite the Lean file from an earlier run's exits.json
        res = json.load(open(J))
        assert [(r["k"], r["n"]) for r in res] == list(starts(K))
    else:
        with Pool(procs) as P:
            res = list(P.imap(fate, list(starts(K)), chunksize=16))
    json.dump(res, open(os.path.join(HERE, "..", "lean", "exits.json"), "w"), indent=0)
    halts = [r for r in res if r["fate"] == "halt"]
    lines = []
    for r in res:
        f = ".halt" if r["fate"] == "halt" else f"(.to {r['n2']} {lean_tail(r['T'], r['t'])})"
        lines.append(f"  ({r['k']}, {r['n']}, {f})")
    maxp = max(r["passes"] for r in res)
    CH = 400
    nch = (len(lines) + CH - 1) // CH
    chunks = "\n".join(f"def exitTab{i} : List (Nat × Nat × Fate) := [\n" + ",\n".join(lines[i * CH:(i + 1) * CH]) + "\n]\n"
                       for i in range(nch))
    out = f"""import Exits

/-!
# The exits of the region for k < {K}, generated by `py/gen_exits.py {K}`; do not edit by hand

Every start `Ev n (.Z k)` with k < {K} and n < 12k + 12 (and k = 0, n < 24), other than n = 2 and the halting family
n = 12k + 9 with k odd: {len(res)} starts.  {len(halts)} of them halt within {max([r['passes'] for r in halts] or [0])} E-passes; every other one reaches
an E-event with one of the tails 1, X, Y, Z within {maxp} passes.  `exitTab_ok` checks every entry with the
list simulator of `TM/Fin.lean`, by compiled evaluation (about 9 minutes for k < 20).
-/

namespace H70770

def exitK : Nat := {K}

{chunks}
/-- (k, n, fate) for every start of the region with k < {K} (see the module doc). -/
def exitTab : List (Nat × Nat × Fate) := {" ++ ".join(f"exitTab{i}" for i in range(nch))}

theorem exitTab_ok : exitTab.all checkEntry = true := by native_decide

theorem exitTab_cover : coverB exitK exitTab = true := by native_decide

end H70770
"""
    open(os.path.join(HERE, "..", "lean", "ExitTab.lean"), "w").write(out)
    print(len(res), "starts;", len(halts), "halt;", "max passes", maxp,
          "; total simulated steps", sum(r["steps"] for r in res))
