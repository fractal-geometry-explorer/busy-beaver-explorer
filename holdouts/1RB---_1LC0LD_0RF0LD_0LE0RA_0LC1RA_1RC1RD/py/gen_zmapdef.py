"""Writes lean/ZMap.lean from lean/zreg.json (made by gen_zreg.py): every case of ZRegion.lean restated with the
E-events of Map.lean (`zw_<case>`), and the coverage theorems

* `zregion_halt`: Z_k with k odd and n = 12k + 9 halts in its pass;
* `zregion_ev`:   every other Z_k with n < 12k + 12, and Z_0 with any n, reaches a next E-event
                  `EvT n' T = E> 0^6 (10)^n' T` (one of the `zw_` lemmas gives n', T and the step count).

usage: python3 gen_zmapdef.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import chain as C  # noqa: E402

NS = "H70770"
ZJ = json.load(open(os.path.join(HERE, "..", "lean", "zreg.json")))
cases = ZJ["cases"]
BY = {c["name"]: c for c in cases}


def L(s):
    return C.S.parse_lin(s).lean()


def tail_term(tail):
    return C.sterm(C.S.tokens(tail + " 0^inf"))


def cstr(name):
    return int(BY[name]["k"].split("+")[-1])


out = []
w = out.append
w(f"""import Map
import {ZJ["files"][-1]}

/-!
# The region Z_k, n < 12k + 12, of 1RB---_1LC0LD_0RF0LD_0LE0RA_0LC1RA_1RC1RD

Generated by `py/gen_zmapdef.py` from `zreg.json`; do not edit by hand.

`Map.lean` proves the next E-event for every tail except `Z k` with `k = 0` or `n < 12k + 12`.  This file covers
that region.  `zregion_halt`: `Ev n (.Z k)` halts in its pass when k is odd and n = 12k + 9.  `zregion_ev`: every
other start of the region reaches a next E-event `EvT n' T = E> 0^6 (10)^n' T`, where the tail `T` is a word that
is in general not one of `1`, `X`, `Y`, `Z` (the rest of the tail block followed by a short end word, or, for
n = 7 mod 8, the rest multiplied by 9/8).  The lemmas `zw_<case>` give n', T and the number of steps of each
family; each is a theorem of `ZRegion.lean` restated with `Ev`.
-/

namespace {NS}

open TM

/-- An E-event with any tail: `E> 0^6 (10)^n T`. -/
def EvT (n : Nat) (T : Tape) : Config := ⟨blank, rep 6 [false] (rep n [true, false] T), .E⟩

""")

for c in cases:
    vs = c["vars"]
    bs = f" ({' '.join(vs)} : Nat)" if vs else ""
    args = " ".join(f"({v})" for v in vs)
    if c["kind"] == "halt":
        cfg = C.lean_cfg(C.P(c["end"]))
        w(f"""/-- Case `{c['name']}` halts: the run reaches `{c['end']}`, where state A reads 1. -/
theorem zw_{c['name']}{bs} : ∃ t c', steps t (Ev ({L(c['n'])}) (.Z ({L(c['k'])}))) = some c' ∧ step c' = none :=
  ⟨_, _, {c['name']} {args}, rfl⟩
""")
        continue
    w(f"""/-- Case `{c['name']}`: n = {c['n']}, k = {c['k']} goes to n' = {c['n2']}, tail `{c['tail2']}`. -/
theorem zw_{c['name']}{bs} :
    steps ({c['total']}) (Ev ({L(c['n'])}) (.Z ({L(c['k'])}))) = some (EvT ({L(c['n2'])}) ({tail_term(c['tail2'])})) :=
  {c['name']} {args}
""")

w("""/-- Z_k with k odd and n = 12k + 9 halts in its pass. -/
theorem zregion_halt (k n : Nat) (hk : k % 2 = 1) (hn : n = 12 * k + 9) : Halts trans (Ev n (.Z k)) := by
  subst hn
  by_cases h1 : k = 1
  · subst h1; obtain ⟨t, c', h, hs⟩ := zw_zh0; exact ⟨t, c', h, hs⟩
  · obtain ⟨j, rfl⟩ : ∃ j, k = 2 * j + 3 := ⟨(k - 3) / 2, by omega⟩
    have e : 12 * (2 * j + 3) + 9 = 24 * j + 45 := by omega
    rw [e]
    obtain ⟨t, c', h, hs⟩ := zw_zh j
    exact ⟨t, c', h, hs⟩
""")

# ---------------------------------------------------------------- the coverage proof
P = []
p = P.append


def ors(eqs):
    return " ∨ ".join(eqs)


def pats(k):
    return "|".join(["h"] * k) if k > 1 else "h"


def close(name, vs):
    if BY[name]["kind"] == "halt":
        return "exact absurd ⟨by omega, by omega⟩ hh"
    return f"exact ⟨_, _, _, zw_{name} {' '.join(vs)}⟩"


p("""/-- Every start of the region other than the halting family, and Z_0 with any n, reaches a next E-event. -/
theorem zregion_ev (k n : Nat) (h : n < 12 * k + 12 ∨ k = 0) (hh : ¬(k % 2 = 1 ∧ n = 12 * k + 9)) :
    ∃ n' T t, steps t (Ev n (.Z k)) = some (EvT n' T) := by""")
# Z_0 with n >= 24
p("""  by_cases hz : k = 0 ∧ 24 ≤ n
  · obtain ⟨rfl, hn⟩ := hz
    by_cases hp : n % 2 = 0
    · obtain ⟨m, rfl⟩ : ∃ m, n = 2 * m + 24 := ⟨(n - 24) / 2, by omega⟩
      exact ⟨_, _, _, zw_zz0 m⟩
    · obtain ⟨m, rfl⟩ : ∃ m, n = 2 * m + 25 := ⟨(n - 25) / 2, by omega⟩
      exact ⟨_, _, _, zw_zz1 m⟩""")
# n < 24
p("  by_cases hs : n < 24")
p(f"  · rcases (by omega : {ors([f'n = {r}' for r in range(24)])}) with {pats(24)}")
for r in range(24):
    p(f"    · subst h")
    q = 8 if r % 8 == 7 else 1
    ind = "      "
    if q == 8:
        p(f"{ind}rcases (by omega : {ors([f'k % 8 = {i}' for i in range(8)])}) with {pats(8)}")
    for pp in range(q):
        name = f"zs{r}_{pp}" if q > 1 else f"zs{r}"
        Cc = cstr(name)
        ii = ind + ("· " if q == 8 else "")
        i2 = ind + ("  " if q == 8 else "")
        p(f"{ii}by_cases hk : {Cc} ≤ k")
        if q == 1 and Cc == 0:
            p(f"{i2}· {close(name, ['k'])}")
        elif q == 1:
            p(f"{i2}· obtain ⟨e, rfl⟩ : ∃ e, k = {L(f'e+{Cc}')} := ⟨k - {Cc}, by omega⟩")
            p(f"{i2}  {close(name, ['e'])}")
        else:
            p(f"{i2}· obtain ⟨e, rfl⟩ : ∃ e, k = {L(f'8*e+{Cc}')} := ⟨(k - {Cc}) / 8, by omega⟩")
            p(f"{i2}  {close(name, ['e'])}")
        ks = [kk for kk in range(pp, Cc, q)]
        if not ks:
            p(f"{i2}· omega")
            continue
        p(f"{i2}· rcases (by omega : {ors([f'k = {kk}' for kk in ks])}) with {pats(len(ks))}")
        for kk in ks:
            p(f"{i2}  · subst h")
            if (r, kk) == (21, 1):
                p(f"{i2}    exact absurd ⟨by omega, by omega⟩ hh")
            elif r < 12 * kk + 12 or kk == 0:
                p(f"{i2}    {close(f'zt{r}_{kk}', [])}")
            else:
                p(f"{i2}    omega")
# n >= 24
p(f"  · rcases (by omega : {ors([f'(n - 24) % 24 = {r}' for r in range(24)])}) with {pats(24)}")
for r in range(24):
    p(f"    · obtain ⟨j, rfl⟩ : ∃ j, n = {L(f'24*j+{24 + r}')} := ⟨(n - 24) / 24, by omega⟩")
    q = 8 if r % 8 == 7 else 1
    slo = (r + 12) // 12 + 1
    ind = "      "
    if q == 8:
        p(f"{ind}rcases (by omega : {ors([f'(k - 2 * j) % 8 = {i}' for i in range(8)])}) with {pats(8)}")
    for pp in range(q):
        name = f"zr{r}_{pp}" if q > 1 else f"zr{r}"
        Cc = cstr(name)
        ii = ind + ("· " if q == 8 else "")
        i2 = ind + ("  " if q == 8 else "")
        p(f"{ii}by_cases hk : 2 * j + {Cc} ≤ k")
        if q == 1:
            p(f"{i2}· obtain ⟨e, rfl⟩ : ∃ e, k = {L(f'2*j+e+{Cc}')} := ⟨k - 2 * j - {Cc}, by omega⟩")
        else:
            p(f"{i2}· obtain ⟨e, rfl⟩ : ∃ e, k = {L(f'2*j+8*e+{Cc}')} := ⟨(k - 2 * j - {Cc}) / 8, by omega⟩")
        p(f"{i2}  {close(name, ['j', 'e'])}")
        ss = [s for s in range(pp, Cc, q) if s >= slo]
        if not ss:
            p(f"{i2}· omega")
            continue
        p(f"{i2}· rcases (by omega : {ors([f'k = {L(f'2*j+{s}')}' for s in ss])}) with {pats(len(ss))}")
        for s in ss:
            p(f"{i2}  · subst h")
            if (r, s) == (21, 3):
                p(f"{i2}    exact absurd ⟨by omega, by omega⟩ hh")
            else:
                p(f"{i2}    {close(f'zb{r}_{s}', ['j'])}")
w("\n".join(P) + "\n")

w("""/-- The region in one statement: from `Ev n (.Z k)` with n < 12k + 12 (or k = 0) the machine either halts in this
pass, exactly when k is odd and n = 12k + 9, or reaches a next E-event. -/
theorem zregion (k n : Nat) (h : n < 12 * k + 12 ∨ k = 0) :
    (k % 2 = 1 ∧ n = 12 * k + 9 ∧ Halts trans (Ev n (.Z k))) ∨ ∃ n' T t, steps t (Ev n (.Z k)) = some (EvT n' T) := by
  by_cases hh : k % 2 = 1 ∧ n = 12 * k + 9
  · exact .inl ⟨hh.1, hh.2, zregion_halt k n hh.1 hh.2⟩
  · exact .inr (zregion_ev k n h hh)

/-- The start n = 2 of the region never halts: Z_k at n = 2 goes to Z_(k+1) at n = 2 in 102 steps (`zw_zs2`). -/
theorem zregion_two (k : Nat) : ¬ Halts trans (Ev 2 (.Z k)) := by
  have hs : ∀ k, steps 102 (Ev 2 (.Z k)) = some (Ev 2 (.Z (k + 1))) := fun k => zw_zs2 k
  have key : ∀ N k, ∀ M ≤ N, ∃ c, steps M (Ev 2 (.Z k)) = some c := by
    intro N
    induction N with
    | zero => intro k M hM; exact ⟨_, by rw [show M = 0 by omega]; rfl⟩
    | succ N ih =>
      intro k M hM
      by_cases h : M ≤ 102
      · have h2 := hs k
        rw [show 102 = M + (102 - M) by omega] at h2
        exact steps_le trans h2
      · obtain ⟨c, hc⟩ := ih (k + 1) (M - 102) (by omega)
        exact ⟨c, by rw [show M = 102 + (M - 102) by omega]; exact steps_seq trans (hs k) hc⟩
  exact not_halts_of_forall trans (fun M => key M k M (Nat.le_refl M))

end """ + NS + "\n")
open(os.path.join(HERE, "..", "lean", "ZMap.lean"), "w").write("\n".join(out))
print("wrote ZMap.lean")
