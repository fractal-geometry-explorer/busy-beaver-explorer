"""Generate Rules.lean: the round at the right end of 1RB1LC_1LA---_1LD0LA_1RE0LE_0RF1RE_1LB1RD, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(1010)^n` is n copies
of 1010, L is any tape, 0^inf blank tape.  The right end of the tape is  L 1 0 1^P 0 (10)^Q 1^5 E> 0^inf  with Q even.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LC_1LA---_1LD0LA_1RE0LE_0RF1RE_1LB1RD"

RULES = [
    ("round", "L 1 0 1^p+7 0 (1010)^q+1 1^5 E> 0^inf",
     "L 1 0 1^p+5 0 (1010)^q+2 1^5 E> 0^inf",
     "One round at the right end: the head runs left over the (10)^Q block (as 1111 words) to the block of ones, "
     "takes two ones and comes back; (P, Q) -> (P - 2, Q + 2) in 14Q + 36 steps, for every P >= 7, even Q >= 2, L.",
     {"rotate": True}),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, count_first=True, max_seg=60, **kw)[0] for name, a, b, doc, kw in RULES]
    out = rules_file("Machine", "H147121", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
