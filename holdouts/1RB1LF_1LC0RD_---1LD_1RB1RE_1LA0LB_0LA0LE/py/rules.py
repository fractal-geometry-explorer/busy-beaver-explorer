"""Generate lean/Rules.lean: shift rules of 1RB1LF_1LC0RD_---1LD_1RB1RE_1LA0LB_0LA0LE over the words its tape is made of, proved along the symbolic
run (tools/py/bbtools/symtm.py: one copy by `rfl`, all copies by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes left to right, `S>` the head in state S on the next cell, `(10)^n` n copies of `10`, L and R any tape.
The tape is made of runs of `10` (written a) and of ones; these rules are the sweeps over the a-runs.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LF_1LC0RD_---1LD_1RB1RE_1LA0LB_0LA0LE"
NS = "H34042"

RULES = [
    ("cross_B_r_01", "L 0 1 B> (01)^n R", "L (10)^n 0 1 B> R",
     "B crosses `(01)^n` to the right in 8 steps a copy, leaving `(10)^n`, with `01` next to the head."),
    ("cross_D_r_01", "L D> (01)^n R", "L (10)^n D> R",
     "D crosses `(01)^n` to the right in 2 steps a copy, leaving `(10)^n`."),
    ("cross_F_l_01", "L (01)^n F> 0 R", "L F> 0 (10)^n R",
     "F crosses `(01)^n` to the left in 2 steps a copy, leaving `(10)^n`, with `0` next to the head."),
    ("cross_A_l_10", "L (10)^n A> 1 R", "L A> 1 (01)^n R",
     "A crosses `(10)^n` to the left in 2 steps a copy, leaving `(01)^n`, with `1` next to the head."),
    ("cross_B_r_10", "L B> (10)^n R", "L (01)^n B> R",
     "B crosses `(10)^n` to the right in 2 steps a copy, leaving `(01)^n`."),
    ("cross_E_r_10", "L 1 E> (10)^n R", "L (10)^n 1 E> R",
     "E crosses `(10)^n` to the right in 8 steps a copy, leaving `(10)^n`, with `1` next to the head."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
