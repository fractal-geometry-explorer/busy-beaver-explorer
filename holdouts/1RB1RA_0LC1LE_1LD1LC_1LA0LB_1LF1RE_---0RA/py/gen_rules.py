"""Write lean/Rules.lean: the shift rules of Antihydra's sweep, proved from the machine's table by `bbtools.symtm`.

    python3 py/gen_rules.py > lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RA_0LC1LE_1LD1LC_1LA0LB_1LF1RE_---0RA"

RULES = [
    ("inner", "One round of the sweep: the middle block loses 2, the right block gains 3.",
     "L 0 1^a 1 1 1 0 1^b 1 B> 0^inf", "L 0 1^a 1 0 1^b 1 1 1 1 B> 0^inf"),
    ("odd_a", "Middle block 1, first part: C runs to the left end and E comes back over the left block.",
     "0^inf 1^p 1 0 1 0 1^b 1 1 B> 0^inf", "0^inf 1 1 1 1 1^p E> 0 0 1 1 1^b 1 0 0^inf"),
    ("odd_b", "Middle block 1, second part: the new middle block is written.",
     "0^inf 1^p 1 1 1 1 E> 0 0 1 1 1^b 1 0 0^inf", "0^inf 1^p 1 1 1 0 1 1 1 1 1^b 0 1 1 B> 0^inf"),
    ("odd0", "Middle block 1 and no left block.",
     "0^inf 1 0 1^b 1 1 B> 0^inf", "0^inf 1 1 0 1 1 1 1 1^b 0 1 1 B> 0^inf"),
    ("even", "Middle block 2: the left block loses one 1 and the right block becomes the middle block.",
     "0^inf 1^p 1 0 1 1 0 1^b 1 1 B> 0^inf", "0^inf 1^p 0 1 1 1 1 1 1^b 0 1 1 B> 0^inf"),
    ("halt0", "Middle block 2 and no left block: F reaches a 0 at the left end, and F0 halts.",
     "0^inf 1 1 0 1^b 1 1 B> 0^inf", "0^inf F> 0 1 1 0 1 1 1^b 1 0 0^inf"),
]


def main():
    thms = []
    for name, doc, s, e in RULES:
        t, _ = prove(M, name, s, e, doc=doc)
        thms.append(t)
    print(rules_file("Machine", "H9785", thms,
                     "Shift rules of the sweep, generated by `py/gen_rules.py` with `tools/py/bbtools/symtm.py`; "
                     "do not edit by hand."), end="")


if __name__ == "__main__":
    main()
