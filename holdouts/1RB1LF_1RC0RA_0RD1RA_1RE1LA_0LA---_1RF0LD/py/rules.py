"""Generate lean/Rules.lean: shift rules of 1RB1LF_1RC0RA_0RD1RA_1RE1LA_0LA---_1RF0LD over the words its tape is made of, proved along the symbolic
run (tools/py/bbtools/symtm.py: one copy by `rfl`, all copies by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

The words: a = 10 (the blocks) and 110 (in the separators), with their rotations; and the binary decrement
at the left end (`dec_1` .. `dec_3`): the tape there is `A> 0 (10)^x b1 (10)^y1 b2 (10)^y2 ...` with bits b = 0/1.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LF_1RC0RA_0RD1RA_1RE1LA_0LA---_1RF0LD"
NS = "H180268"

RULES = [
    ("cross_A_r_01", "L A> (01)^n R", "L (10)^n A> R",
     "A crosses `(01)^n` to the right in 2 steps a copy, leaving `(10)^n`."),
    ("cross_A_l_01", "L (01)^n A> 1 R", "L A> 1 (01)^n R",
     "A crosses `(01)^n` to the left in 4 steps a copy, leaving `(01)^n`, with `1` next to the head."),
    ("cross_D_l_01", "L (01)^n D> 1 R", "L D> 1 (01)^n R",
     "D crosses `(01)^n` to the left in 4 steps a copy, leaving `(01)^n`, with `1` next to the head."),
    ("cross_F_l_01", "L (01)^n F> 0 1 R", "L F> 0 1 (10)^n R",
     "F crosses `(01)^n` to the left in 4 steps a copy, leaving `(10)^n`, with `01` next to the head."),
    ("cross_A_l_10", "L (10)^n A> 1 R", "L A> 1 (10)^n R",
     "A crosses `(10)^n` to the left in 4 steps a copy, leaving `(10)^n`, with `1` next to the head."),
    ("cross_B_r_10", "L B> (10)^n R", "L (01)^n B> R",
     "B crosses `(10)^n` to the right in 2 steps a copy, leaving `(01)^n`."),
    ("cross_F_l_10", "L (10)^n F> 1 R", "L F> 1 (10)^n R",
     "F crosses `(10)^n` to the left in 4 steps a copy, leaving `(10)^n`, with `1` next to the head."),
    ("cross_A_l_011", "L (011)^n A> 1 1 R", "L A> 1 1 (010)^n R",
     "A crosses `(011)^n` to the left in 15 steps a copy, leaving `(010)^n`, with `11` next to the head."),
    ("dec_1", "0^inf A> 0 (10)^x+1 1 (10)^y+1 R", "0^inf A> 0 (10)^x+3 0 (10)^y R",
     "One visit of the left end with the lowest bit 1: the bit goes to 0 and the block after it loses a copy; the "
     "first block gains 2."),
    ("dec_2", "0^inf A> 0 (10)^x+1 0 (10)^y+1 1 (10)^z+1 R", "0^inf A> 0 (10)^x+3 1 (10)^y+1 0 (10)^z R",
     "The decrement with one borrow: bits 0 1 become 1 0 and the block after the second bit loses a copy."),
    ("dec_3", "0^inf A> 0 (10)^x+1 0 (10)^y+1 0 (10)^w+1 1 (10)^z+1 R",
     "0^inf A> 0 (10)^x+3 1 (10)^y+1 1 (10)^w+1 0 (10)^z R",
     "The decrement with two borrows: bits 0 0 1 become 1 1 0 and the block after the third bit loses a copy."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
