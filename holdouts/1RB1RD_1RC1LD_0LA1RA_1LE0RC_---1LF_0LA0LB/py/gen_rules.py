"""Write lean/Rules.lean for 1RB1RD_1RC1LD_0LA1RA_1LE0RC_---1LF_0LA0LB: the two sweeps over the long left block,
proved by symbolic simulation (tools/py/bbtools/symtm.py) for all lengths and any tapes L, R.

  a = 111110.  Going right in state A, each pair aa becomes v = 101110101101 (32 steps per pair);
  going left in state E, each v becomes 110111110111 (18 steps), which is aa again up to a shift by the carried 1.

usage (from the repository root): PYTHONPATH=tools/py python3 holdouts/<M>/py/gen_rules.py > holdouts/<M>/lean/Rules.lean
"""
import os
import re

from bbtools import symtm

M = '1RB1RD_1RC1LD_0LA1RA_1LE0RC_---1LF_0LA0LB'
RULES = [
    ('sweep_r', 'the rightward sweep over the left block: each pair aa becomes 101110101101',
     'L A> (111110111110)^n R', 'L (101110101101)^n A> R'),
    ('sweep_l', 'the leftward sweep: each 101110101101 becomes 110111110111 (aa, shifted by the carried 1)',
     'L (101110101101)^n E> 1 R', 'L E> 1 (110111110111)^n R'),
]

# The engine between the a-block and the c-block (a = 111110, c = 1^11 0).  Twelve round trips of the head bring the
# engine word X back, with 16 more a's on its left and 6 fewer c's on its right, for every block length and any tape
# R to the right.  Two statements, for an even and an odd number of a's.
A6, S7 = '1 1 1 1 1 0', '1 1 1 1 1 1 1 0'
X = ' '.join([S7, A6, A6, S7, A6, A6, S7, A6, A6, S7, A6, '1 1 1 1'])
for nm, pre in (('even', ''), ('odd', A6 + ' ')):
    RULES.append(('engine_cycle_' + nm,
                  'twelve round trips: the engine word returns, a^N gains 16 a and c^M loses 6 c (' + nm + ' N)',
                  '0^inf F> 0 %s(111110111110)^n+1 %s (111111111110)^m+6 R' % (pre, X),
                  '0^inf F> 0 %s(111110111110)^n+9 %s (111111111110)^m R' % (pre, X)))


def main(ID):
    thms = [symtm.prove(M, n, a, b, doc=d, rotate=True, max_moves=2000000, count_first=True, max_seg=300)[0] for n, d, a, b in RULES]
    print(symtm.rules_file('Machine', 'H' + ID, thms, f'Rules of {M}, generated by py/gen_rules.py (symbolic '
                           'simulation, `tools/py/bbtools/symtm.py`).').replace('open TM\n', 'open TM\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 4000000\n', 1),
          end='')


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    main(re.search(r'namespace H(\d+)', open(os.path.join(here, '..', 'lean', 'Machine.lean')).read()).group(1))
