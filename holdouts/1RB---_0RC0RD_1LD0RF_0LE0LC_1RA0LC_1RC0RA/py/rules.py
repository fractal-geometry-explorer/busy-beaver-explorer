"""The two working modes of 1RB---_0RC0RD_1LD0RF_0LE0LC_1RA0LC_1RC0RA, proved with tools/py/bbtools/symtm.py;
writes lean/Rules.lean.  usage: python3 rules.py [lean/Rules.lean]"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../../tools/py'))
from bbtools.symtm import prove

M = '1RB---_0RC0RD_1LD0RF_0LE0LC_1RA0LC_1RC0RA'
rules = [
    ('mode_a', 'mode A: two 1s of the top block become two more 01 pairs',
     'L 1^x+2 (01)^y 0 F> 0^inf', 'L 1^x (01)^y+2 0 F> 0^inf'),
    ('mode_b', 'mode B: four 1s of the top block become two more 01 pairs and one more pair after the marker 0010',
     'L 1^x+4 (01)^y+1 0010 (01)^z 0 F> 0^inf', 'L 1^x (01)^y+3 0010 (01)^z+1 0 F> 0^inf'),
]
out = {}
for nm, doc, s, e in rules:
    t, f = prove(M, nm, s, e, doc=doc)
    print(nm, 'OK', f.steps)
    out[nm] = t
NS = 'H' + open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '../lean/Machine.lean')).read().split('namespace H')[1].split()[0]
HEAD = f'''import Machine

/-!
# The two working modes of {M}

Generated by `py/rules.py` (`tools/py/bbtools/symtm.py`); do not edit by hand.  Each theorem is one visit of the
head, in state F, to the right end of the tape, to the next one, for all block lengths and any tape `L` to the left.
-/

namespace {NS}

open TM

'''
if len(sys.argv) > 1:
    open(sys.argv[1], 'w').write(HEAD + '\n\n'.join(out[n] for n, *_ in rules) + f'\nend {NS}\n')
