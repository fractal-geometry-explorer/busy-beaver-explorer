"""Writes ../lean/Rules.lean: the two long passes of one excursion over the (11010)^k block, by bbtools.symtm.

At the start of an excursion the right end of the tape is `... 1 1 0 0 0 1 1 0 1 0 (11010)^k` with the head in
state B on the blank cell after it (python3 gen_rules.py)."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB0RA_0LC0RF_0LB1RD_1LE---_1RA0LF_1LE0RC"
RULES = [
    ("pass_left", "The left pass: from the right end across the whole (11010) block (17 steps a word) to the counter.",
     "L 1 1 0 0 0 1 1 0 1 0 (11010)^n+2 B> 0^inf",
     "L 1 1 C> 0 0 0 0 0 1 0 1 0 1 1 0 (10110)^n+1 1 0 1 0^inf"),
    ("pass_right", "The right pass: from the counter back across the block (27 steps a word) to a new cell at the right end.",
     "L A> 1 1 1 0 (11010)^n+1 0^inf",
     "L 0 (10110)^n+1 1 0 1 1 0 1 B> 0^inf"),
]

if __name__ == "__main__":
    thms = []
    for name, doc, a, b in RULES:
        txt, fin = prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)
        thms.append(txt)
        print(name, fin, file=sys.stderr)
    with open(os.path.join(os.path.dirname(__file__), "../lean/Rules.lean"), "w") as f:
        f.write(rules_file("Machine", "H114265", thms, "The two passes of an excursion, generated by py/gen_rules.py"))
