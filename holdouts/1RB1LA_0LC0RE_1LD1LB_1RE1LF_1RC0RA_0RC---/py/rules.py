"""Generate ../lean/Rules.lean: rules of 1RB1LA_0LC0RE_1LD1LB_1RE1LF_1RC0RA_0RC---, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`, repeats re-bracketed
next to the head with `TM.rep_rotate`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.  The bulk of the tape is blocks of the word 101.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LA_0LC0RE_1LD1LB_1RE1LF_1RC0RA_0RC---"

RULES = [
    ('shift_C_001_l', 'L (001)^n C> 0 R', 'L C> 0 (011)^n R',
     'C crosses (001)^n leftwards in 5*n steps.'),
    ('shift_B_010_l', 'L (010)^n B> 0 R', 'L B> 0 (110)^n R',
     'B crosses (010)^n leftwards in 5*n steps.'),
    ('shift_A_011_r', 'L A> (011)^n R', 'L (100)^n A> R',
     'A crosses (011)^n rightwards in 3*n steps.'),
    ('shift_E_011_r', 'L E> (011)^n R', 'L (010)^n E> R',
     'E crosses (011)^n rightwards in 7*n steps.'),
    ('shift_A_1_l', 'L (1)^n A> 1 R', 'L A> 1 (1)^n R',
     'A crosses (1)^n leftwards in n steps.'),
    ('shift_D_100_l', 'L (100)^n D> 1 R', 'L D> 1 (101)^n R',
     'D crosses (100)^n leftwards in 5*n steps.'),
    ('shift_E_101_r', 'L E> (101)^n R', 'L (010)^n E> R',
     'E crosses (101)^n rightwards in 3*n steps.'),
    ('shift_B_110_r', 'L B> (110)^n R', 'L (001)^n B> R',
     'B crosses (110)^n rightwards in 3*n steps.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H159355", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
