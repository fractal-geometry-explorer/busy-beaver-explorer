    ("l_qone", "0^inf 1 0 (10)^y A> 0^inf", "0^inf 1 1 1 1 (11)^y 1 1 1 1 0 A> 0^inf",
     "The tank ends with one 1: `1 0 (10)^y A>` becomes `1^(2y+8) 0 A>`."),
    ("l_qtwo", "0^inf 1 1 0 (10)^y+2 A> 0^inf", "0^inf C> 0 1 0 1 0 1 1 0 (10)^y+2 1 0^inf",
     "The tank ends with two 1s: `1 1 0 (10)^(y+2) A>` becomes `C> 0 (10)^2 1 1 0 (10)^(y+2) 1` (the ternary rounds)."),
    ("l_ls", "0^inf C> 0 (10)^m+2 1 1 0 (10)^k+2 R", "0^inf (11)^m+1 F> 1 0 0 1 0 1 (10)^k+2 R",
     "Start of a ternary round: the pairs at the left end become 1s."),
