"""Event rules of 1RB---_1LC1RF_0LE0RD_0RB0LC_1RD0LD_0RC0RA, proved for all sizes (usage: python3 py/events.py lean > lean/Events.lean;
python3 py/events.py cov > c/rules.txt for the coverage tool c/evcov.c).

Event: the head in state D on cell 110 (cells counted from the start cell).  Tapes are written left to right; the
cell under the head is the first one after `D>`.  HAND are the rules of the counters, written by hand; MINED
(py/mined.txt, written by py/miner.py from the unmatched events of a 3·10^9-step run) are the rarer events, each
proved for the sizes its repeats stand for.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from autoev import cov_line  # noqa: E402
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB---_1LC1RF_0LE0RD_0RB0LC_1RD0LD_0RC0RA"
D0, D1 = "1 0 0 0 1 0 0 0 1 1 0", "(10101000110)^j"     # a middle digit 0 / j middle digits 1 (word D 1000 110)
HAND = [
    ("inc_low", "L 0 1 0 0 (0101)^n D> 0 0 0 1 0 0 0 0 R", "L 0 1 0 1 (0100)^n D> 0 1 0 1 0 0 0 0 R",
     "Two-event epochs, left event: the low counter (digits 0100 = 0, 0101 = 1) gets 1, carry over n ones."),
    ("inc_R", "L D> 0 1 0 1 0 0 0 0 (100)^k 0 0 0 R", "L D> 0 0 0 1 0 0 0 0 (000)^k 1 0 0 R",
     "Two-event epochs, right event: R (digits 100 = 1, 000 = 0, least significant first) gets 1, carry over k ones."),
    ("inc_both", "L 0 0 0 1 (0101)^n D> 0 0 0 1 (001)^k 0 0 0 R", "L 0 1 0 1 (0001)^n D> 0 0 0 1 (000)^k 0 0 1 R",
     "One-event epochs: the low counter (0001 = 0, 0101 = 1) and R (001 = 1) both get 1."),
    ("carry_alt", f"L {D0} {D1} 1 0 0 0 1 1 (0101)^n D> 0 0 0 1 0 0 0 0 R",
     "L 1 0 1 0 1 0 0 0 1 1 0 (10001000110)^j 1 0 0 0 1 1 (0100)^n D> 0 1 0 1 0 0 0 0 R",
     "Two-event epochs: the low counter wraps and the middle counter (digits D 1000 110, D = 1000 or 1010) gets 1."),
    ("carry_both", f"L {D0} {D1} 1 0 0 0 1 1 0 1 (0101)^n D> 0 0 0 1 (001)^k 0 0 0 R",
     "L 1 0 1 0 1 0 0 0 1 1 0 (10001000110)^j 1 0 0 0 1 1 0 1 (0001)^n D> 0 0 0 1 (000)^k 0 0 1 R",
     "One-event epochs: the low counter wraps, the middle counter and R get 1."),
    ("carryH_alt", "L 1 0 0 0 (1010)^i (1000110)^p (10101000110)^j 1 0 0 0 1 1 (0101)^n D> 0 0 0 1 0 0 0 0 R",
     "L 1 0 1 0 (1000)^i (1000110)^p (10001000110)^j 1 0 0 0 1 1 (0100)^n D> 0 1 0 1 0 0 0 0 R",
     "Two-event epochs: the middle counter wraps too; the carry crosses p spacers 1000 110 and adds 1 to the high counter (1000 = 0, 1010 = 1)."),
    ("carryH_both", "L 1 0 0 0 (1010)^i (1000110)^p (10101000110)^j 1 0 0 0 1 1 0 1 (0101)^n D> 0 0 0 1 (001)^k 0 0 0 R",
     "L 1 0 1 0 (1000)^i (1000110)^p (10001000110)^j 1 0 0 0 1 1 0 1 (0001)^n D> 0 0 0 1 (000)^k 0 0 1 R",
     "One-event epochs: the same with R getting 1."),
]


def mined():
    out = []
    for ln in open(os.path.join(HERE, "mined.txt")):
        p = ln.rstrip("\n").split("|")
        out.append((p[0], p[1], p[2], f"Mined rule ({p[4]}): {p[3]} steps."))
    return out


def theorems():
    return [prove(M, "t_" + n, s, e, doc=d, rotate=True, count_first=True, max_seg=40, max_moves=200000)[0]
            for n, s, e, d in HAND + mined()]


if __name__ == "__main__":
    if sys.argv[1:] == ["cov"]:
        for n, s, e, d in HAND + mined():
            print(cov_line(n, s))
    else:
        sys.stdout.write(rules_file("Machine", "H82928", theorems(),
                                    f"Event rules of {M}, generated by `py/events.py`; do not edit by hand."))
