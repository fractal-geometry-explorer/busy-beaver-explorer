"""Writes lean/Rules.lean: the shift rule of the marker of 1RB1RF_1LC1LF_---1LD_1LE0RA_1RE1LB_1RD0LD,
proved by bbtools.symtm from a symbolic trace (shift rules, `rfl`, `omega`).  lean/Phase.lean restates and iterates it.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove

M = "1RB1RF_1LC1LF_---1LD_1LE0RA_1RE1LB_1RD0LD"
NS = "H25899"
RULES = [
    ("marker", "Two sweeps move the marker 3 one digit right: `0^inf D> 00 (110)^a 1110 (110)^(b+1) R` becomes "
     "`0^inf D> 00 (110)^(a+3) 1110 (110)^b R` (as the run writes it: `... 1 (101)^a (110)^(b+1) R`), in 24a+70 steps.",
     "0^inf D> 0 0 (110)^a 1 1 1 0 (110)^b+1 R", "0^inf D> 0 0 (110)^a+3 1 1 1 0 (110)^b R"),
]


def main():
    out = ["import Machine", "", f"/-! Rules of {M}, generated by `py/rules.py`; do not edit by hand. -/", "",
           f"namespace {NS}", "", "open TM", ""]
    for name, doc, start, end in RULES:
        t, f = prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=60)
        out += [t, ""]
    out.append(f"end {NS}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
