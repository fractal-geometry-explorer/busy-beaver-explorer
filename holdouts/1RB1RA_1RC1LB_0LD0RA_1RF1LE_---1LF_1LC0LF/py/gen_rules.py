"""Write lean/Rules.lean: the odd and even rounds of verify_rounds.py for small n, for every length of the block in
front and every tape further left, proved by bbtools.symtm (single steps by `rfl`, runs crossed by shift rules).

usage: python3 py/gen_rules.py > lean/Rules.lean      (from this folder)
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove

M = "1RB1RA_1RC1LB_0LD0RA_1RF1LE_---1LF_1LC0LF"
NS = "H168016"
ODD = [3, 5, 7, 9, 11, 13]
EVEN = [4, 6, 8, 10]


def main():
    out = [f"""import Machine

/-!
# {M}: rounds of the block machine

A block configuration `0^∞ 1^b₁ 0 1^b₂ … 0 1^bₖ C>0 0^∞` has the head in C just right of its last block.  These
theorems are the rounds from it for small last blocks `n`, for every length `a + n` of the block in front and every
tape `L` left of it (generated by `py/gen_rules.py` with `tools/py/bbtools/symtm.py`):

* `odd_n`:  `L 1^(a+n) 0 1^n C>0` reaches `L 1^(a+n) 0 1^(n+2) C>0` in `3·2^((n+3)/2) − 6` steps (`n` odd);
* `even_n`: `L 1^(a+n) 0 1^n C>0` reaches `L 1^(a+n−1) 0 1^(n−1) 0 1^3 C>0` in `6·2^(n/2) − 2n − 2` steps (`n` even).

The end tapes are written as the run leaves them (a block may come out split into `cons` cells and a shorter `rep`).
-/

namespace {NS}

open TM
"""]
    for n in ODD:
        t, _ = prove(M, f"odd_{n}", f"L 1^a+{n} 0 1^{n} C> 0^inf", f"L 1^a+{n} 0 1^{n + 2} C> 0^inf",
                     nsteps=3 * 2 ** ((n + 3) // 2) - 6, count_first=True, max_seg=40,
                     doc=f"The odd round with last block {n}: it grows to {n + 2} in {3 * 2 ** ((n + 3) // 2) - 6} steps.")
        out.append(t)
    for n in EVEN:
        t, _ = prove(M, f"even_{n}", f"L 1^a+{n} 0 1^{n} C> 0^inf", f"L 1^a+{n - 1} 0 1^{n - 1} 0 1^3 C> 0^inf",
                     nsteps=6 * 2 ** (n // 2) - 2 * n - 2, count_first=True, max_seg=40,
                     doc=f"The even round with last block {n}: the block in front loses a 1, the last block splits "
                         f"into {n - 1} and 3, in {6 * 2 ** (n // 2) - 2 * n - 2} steps.")
        out.append(t)
    out.append(f"end {NS}\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
