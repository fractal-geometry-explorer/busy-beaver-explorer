"""Generate lean/Rules.lean for 1RB1RA_1RC---_1RD0LD_1LE1RF_0RA1LD_0RC0LC: one-cycle rules of its phases, proved along the symbolic run of
tools/py/bbtools/symtm.py (single steps by `rfl`, shift rules by TM.cross_r/cross_l, re-bracketing by TM.rep_rotate).

usage (from the repo root): python3 holdouts/1RB1RA_1RC---_1RD0LD_1LE1RF_0RA1LD_0RC0LC/py/rules.py > holdouts/1RB1RA_1RC---_1RD0LD_1LE1RF_0RA1LD_0RC0LC/lean/Rules.lean
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RA_1RC---_1RD0LD_1LE1RF_0RA1LD_0RC0LC"
NS = next(l.split()[1] for l in open(os.path.join(HERE, "..", "lean", "Machine.lean")) if l.startswith("namespace "))

RULES = [
    ("a_right",
     "L A> (1)^n R",
     "L (1)^n A> R",
     "Going right, A runs over a block of ones."),
    ("d_zig",
     "L 1 D> (11)^n R",
     "L (10)^n 1 D> R",
     "D crosses a block of ones going right in a zigzag that erases every second cell (6 steps per pair): this is how a block is taken apart."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=40)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", NS, ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
