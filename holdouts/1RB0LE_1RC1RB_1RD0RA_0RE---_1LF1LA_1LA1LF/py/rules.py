"""Writes lean/Rules.lean: shift rules of this machine's sweeps and the shape of a halt, proved by
tools/py/bbtools/symtm.py (`prove`).  Usage: python3 py/rules.py > lean/Rules.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LE_1RC1RB_1RD0RA_0RE---_1LF1LA_1LA1LF"
NS = "H58953"
RULES = [
    ('b_run', 'L B> 1^n R', 'L 1^n B> R',
     'Rightward, B runs over 1s.'),
    ('f_run', 'L 1^n F> 1 R', 'L F> 1 1^n R',
     'Leftward, F runs over 1s.'),
    ('e_run', 'L (11)^n E> 1 R', 'L E> 1 (01)^n R',
     'Leftward, E (with A between) turns each pair 11 into 01, 2 steps a pair.'),
    ('a_run', 'L A> (0101)^n R', 'L (1110)^n A> R',
     'Rightward, A (with B, C) turns each 0101 into 1110, 4 steps a copy.'),
    ('halt_shape', 'L B> 0 0 1 R', 'L 1 1 D> 1 R',
     'The only way to a halt: B on a double 0 followed by a 1 reaches D on a 1 (which halts) in 2 steps.'),
]
HALT = "D"

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d)[0] for n, s, e, d in RULES]
    extra = (f"/-- {HALT} reading a 1 halts (the end of `halt_shape`). -/\n"
             f"theorem halt_after_shape (L R : Tape) : step ⟨L, cons true R, .{HALT}⟩ = none := rfl\n")
    print(rules_file("Machine", NS, thms + [extra],
                     f"# {M}: shift rules of the sweeps and the shape of a halt\n\n"
                     "Generated by `py/rules.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `n` and all "
                     "tapes `L`, `R`."))
