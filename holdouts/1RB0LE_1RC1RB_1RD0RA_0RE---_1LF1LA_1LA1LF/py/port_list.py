"""Write lean/Absorb.lean, Wall.lean, Crossing.lean, End.lean, Race.lean and Window.lean of this machine from those of
1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF.

This machine has that machine's table with the states renamed A->C, B->D, C->E, D->F, E->A, F->B (it is that table
started in state E), so every proof goes through with the state names changed, as for Pascal.lean and Lucas.lean
(that machine's py/port_pascal.py).  Only the last section of End.lean, the first right turn from blank tape, is
about that machine's own run; it is left out, and lean/Start.lean states this machine's.

usage: python3 py/port_list.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OTHER = "1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF"
SRC = os.path.join(HERE, "..", "..", OTHER, "lean")
DST = os.path.join(HERE, "..", "lean")
REN = {"A": "C", "B": "D", "C": "E", "D": "F", "E": "A", "F": "B"}
NOTE = ("-- Generated by holdouts/1RB0LE_1RC1RB_1RD0RA_0RE---_1LF1LA_1LA1LF/py/port_list.py from the file of the same\n"
        "-- name of 1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF, with its states renamed A->C, B->D, C->E, D->F, E->A,\n"
        "-- F->B (state names in the prose are that machine's); do not edit by hand.\n")
TAIL = "namespace H75625\nopen TM\n\n/-- The first right turn from blank tape"


def port(text):
    text = text.replace("namespace H75625", "namespace H58953").replace("end H75625", "end H58953")
    return re.sub(r"(?<![\w.])\.([A-F])\b", lambda m: "." + REN[m.group(1)], text)


for name in ("Absorb.lean", "Wall.lean", "Crossing.lean", "End.lean", "Race.lean", "Window.lean"):
    with open(os.path.join(SRC, name)) as f:
        src = f.read()
    if name == "End.lean":
        i = src.index(TAIL)
        src = src[:i].rstrip() + "\n"
    out = port(src)
    first, rest = out.split("\n", 1)
    with open(os.path.join(DST, name), "w") as f:
        f.write(first + "\n" + NOTE + rest)
    print("wrote", os.path.join(DST, name))
