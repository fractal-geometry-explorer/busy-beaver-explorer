"""Generate Rules.lean: the half-rounds at the left end of 1RB1LC_1LA0RE_0LD---_1RE0LF_1RF0RD_1LD0LB, proved along the symbolic
run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of 10 (the
word a of ../README.md, seen as 01 while the head is on it), R is any tape, 0^inf blank tape.  At the left end the
tape is  0^inf D> 0 a^x j a^y R  with a junction cell j.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LC_1LA0RE_0LD---_1RE0LF_1RF0RD_1LD0LB"

RULES = [
    ("half_round_0", "0^inf D> 0 (10)^x 0 (10)^y+1 R", "0^inf D> 0 1 0 1 (01)^x 0 1 (10)^y R",
     "With junction 0: two a's more on the left, one fewer on the right, junction 1; R is never read.", {"rotate": True}),
    ("half_round_1", "0^inf D> 0 (10)^x 1 (10)^y+1 R", "0^inf D> 0 1 0 1 (01)^x 0 0 (10)^y R",
     "With junction 1: the same, junction 0.", {"rotate": True}),
]
S = " 0 1 1 0 0"          # the separator s = 01100
MID = [("", "no"), (S + " (10)^d+2", "one"), (S + " (10)^d+2" + S + " (10)^e+2", "two")]
for k, (mid, word) in enumerate(MID):
    sfx = "" if k == 0 else "_%d" % k
    for j0, j1 in (("0", "1"), ("1", "0")):
        RULES.append((
            "mid_round_%s%s" % (j0, sfx),
            "0^inf D> 0 (10)^a+2" + mid + S + " (10)^b %s (10)^c+1 R" % j0,
            "0^inf D> 0 (10)^a+1" + mid + S + " (10)^b+3 %s (10)^c R" % j1,
            "Junction %s in a later block, with %s block(s) of at least two words between: the first block loses a word, "
            "the junction's block gains three, the block after the junction loses one; R is never read." % (j0, word),
            {"rotate": True}))
    RULES.append((
        "tail_round" + sfx,
        "0^inf D> 0 (10)^a+2" + mid + S + " (10)^f+2 (1001100)^n 1 0^inf",
        "0^inf D> 0 (10)^a+1" + mid + S + " (10)^f+2 (1001100)^n+1 1 0^inf",
        "No junction: the first block loses a word and the run of 1001100 at the right end gains one, with %s block(s) "
        "of at least two words between." % word, {"rotate": True}))


def main():
    ths = [prove(M, name, a, b, doc=doc, count_first=True, max_seg=80, **kw)[0] for name, a, b, doc, kw in RULES]
    out = rules_file("Machine", "H166700", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
