"""Generate lean/Edge.lean for 1RB1LC_1LA1RE_0RD0LA_---1LB_1LD0RF_0RE1RB (run from the repository root): the right
sweep through the last block of 1s and what happens at the right end of the tape.

The machine halts only in D on a 0.  On a block of 1s the right sweep cycles E -> F -> B -> E (E1 = 0RF, F1 = 1RB,
B1 = 1RE), so it leaves the block in the state E, F or B by the block's length mod 3 (`sweep`).  On blank tape F
writes 0 and E then writes 1 and steps back onto that 0 in state D: a halt (`edge_halt`).  In E or B the head turns
back (`edge_E`, `edge_B`).  So a right sweep that enters the last block in E halts at the end of the tape if and only
if the block has length 1 mod 3.

Each rule is proved by bbtools.symtm for all values of its variables and every tape L (or R) the run does not
look at."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools import symtm
from bbtools.machine import Machine
M = "1RB1LC_1LA1RE_0RD0LA_---1LB_1LD0RF_0RE1RB"
NS = "H56057"
m = Machine.parse(M)
RULES = [
    ('sweep', 'The right sweep crosses three 1s and is in E again: L E> (111)^n R reaches L (011)^n E> R.',
     'L E> (111)^n R', 'L (011)^n E> R'),
    ('edge_halt', 'A last block of length 3n + 1 entered in E: the head ends in D on a 0, where the machine halts.',
     'L E> (111)^n 1 0^inf', 'L (011)^n 0 D> 0 1 0^inf'),
    ('edge_E', 'A last block of length 3n + 3 entered in E: the head turns back in D on a 1.',
     'L E> (111)^n+1 0^inf', 'L (011)^n 0 1 D> 1 1 0^inf'),
    ('edge_B', 'A last block of length 3n + 2 entered in E: the head turns back in A on a 1.',
     'L E> (111)^n 1 1 0^inf', 'L (011)^n 0 A> 1 1 0^inf'),
]
out = []
for name, doc, a, b in RULES:
    txt, fin = symtm.prove(m, name, a, b, doc=doc, rotate=True, count_first=True, max_seg=30)
    out.append(txt)
sys.stdout.write(symtm.rules_file("Machine", NS, out, f"The right end of the tape for {M}; generated by `py/gen_edge.py`; do not edit by hand."))
