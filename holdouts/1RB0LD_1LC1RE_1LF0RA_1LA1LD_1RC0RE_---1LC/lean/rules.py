"""Generate Rules.lean for 1RB0LD_1LC1RE_1LF0RA_1LA1LD_1RC0RE_---1LC: the halting context and the shift rules over the words of its tape, proved along the symbolic run of tools/py/bbtools/symtm.py
(single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LD_1LC1RE_1LF0RA_1LA1LD_1RC0RE_---1LC"

RULES = [
    ('halt_ctx', 'L 0 C> 0 R', 'L F> 0 1 R',
     'C on a 0 with a 0 on its left hands F that 0 (the halting transition).'),
    ('back_A_10_1', 'L (10)^n A> 1 R', 'L A> 1 (10)^n R',
     'A crosses n copies of `10` to the left in 2n steps, leaving `10` (carrying `1`).'),
    ('run_A_001_0', 'L 0 A> (001)^n R', 'L (111)^n 0 A> R',
     'A crosses n copies of `001` to the right in 9n steps, leaving `111` (carrying `0`).'),
    ('back_C_01_0', 'L (01)^n C> 0 R', 'L C> 0 (11)^n R',
     'C crosses n copies of `01` to the left in 2n steps, leaving `11` (carrying `0`).'),
    ('run_C_100', 'L C> (100)^n R', 'L (111)^n C> R',
     'C crosses n copies of `100` to the right in 9n steps, leaving `111`.'),
    ('back_D_01_0', 'L (01)^n D> 0 R', 'L D> 0 (01)^n R',
     'D crosses n copies of `01` to the left in 2n steps, leaving `01` (carrying `0`).'),
    ('back_D_1_1', 'L (1)^n D> 1 R', 'L D> 1 (1)^n R',
     'D crosses n copies of `1` to the left in 1n steps, leaving `1` (carrying `1`).'),
    ('back_D_110_1', 'L (110)^n D> 1 R', 'L D> 1 (011)^n R',
     'D crosses n copies of `110` to the left in 3n steps, leaving `011` (carrying `1`).'),
    ('back_D_011_0', 'L (011)^n D> 0 R', 'L D> 0 (101)^n R',
     'D crosses n copies of `011` to the left in 3n steps, leaving `101` (carrying `0`).'),
    ('back_D_0001_01', 'L (0001)^n D> 0 1 R', 'L D> 0 1 (1010)^n R',
     'D crosses n copies of `0001` to the left in 12n steps, leaving `1010` (carrying `0 1`).'),
    ('run_E_1', 'L E> (1)^n R', 'L (0)^n E> R',
     'E crosses n copies of `1` to the right in 1n steps, leaving `0`.'),
    ('back_F_10_1', 'L (10)^n F> 1 R', 'L F> 1 (11)^n R',
     'F crosses n copies of `10` to the left in 2n steps, leaving `11` (carrying `1`).'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H125234", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
