import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

M = "1RB0RE_1LC0RA_1RF0RD_---1LE_0LB1LE_1LE1RC"
NS = sys.argv[1] if len(sys.argv) > 1 else None
RULES = [
    ("l_psweep", "L 0 1^x+2 0 (10)^y 1 B> 0^inf", "L 0 (1)^x 0 1 0 1 (01)^y 0 1 B> 0^inf",
     "One sweep of the bouncer, whatever lies left of it: `0 1^(x+2) 0 (10)^y 1 B>` becomes `0 1^x 0 (10)^(y+2) 1 B>`."),
    ("l_pone", "0^inf 1 0 (10)^y+2 1 B> 0^inf", "0^inf C> 0 1 0 1 0 1 (01)^y+2 0^inf",
     "The tank ends with one 1 and blank tape to the left: `C> 0 (10)^(y+4) 1` follows."),
    ("l_pass", "0^inf C> 0 (10)^n+1 1 0^inf", "0^inf C> 0 1 0 1 1 (11)^n+1 1 1 0^inf",
     "`C> 0 (10)^(n+1) 1` becomes `C> 0 (10) 1^(2n+6)`: the doubling rounds start."),
    ("l_dstart", "0^inf C> 0 (10)^m 1^c+4 R", "0^inf (11)^m 1 B> 1 0 1 (1)^c+1 R",
     "Start of a doubling round: the m pairs become 2m+1 ones."),
    ("l_jstep", "0^inf 1^p+2 B> 1 0 (10)^i 1^c+4 R", "0^inf (1)^p B> 1 0 1 0 1 (01)^i 0 1 (1)^c+1 R",
     "One step of a round: two 1s on the left and two on the right make two pairs."),
    ("l_jend", "0^inf 1 B> 1 0 (10)^i 1^c+4 R", "0^inf C> 0 1 0 1 0 1 (01)^i 0 1 (1)^c+1 R",
     "End of a round: `1 B> 1 0 (10)^i 1^(c+4)` becomes `C> 0 (10)^(i+3) 1^(c+2)`."),
    ("l_dhalt", "0^inf C> 0 (10)^m 1 1 0^inf", "0^inf (11)^m 1 1 0 D> 0^inf",
     "A round that starts with exactly two 1s on blank tape reaches D on blank tape, which halts."),
]


def main():
    thms = [prove(M, name, a, b, doc=doc, rotate=True, count_first=True)[0] for name, a, b, doc in RULES]
    return rules_file("Machine", NS, thms, "Leaf rules of " + M +
                      ", proved by `bbtools.symtm.prove` (generated by `py/gen_leaves.py`; do not edit by hand).")


if __name__ == "__main__":
    sys.stdout.write(main())
