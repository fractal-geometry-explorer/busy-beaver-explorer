"""Generate Rules.lean for 1RB1LC_1RC---_1LD1LC_1RE0LC_1RF0RE_1RA0RD: shift rules (one copy of a word crossed by the head in a state, so a whole run of
copies is crossed at once), each proved along a symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`,
shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.machine import Machine  # noqa: E402
from bbtools.symtm import Config, prove, rules_file, run  # noqa: E402

M = "1RB1LC_1RC---_1LD1LC_1RE0LC_1RF0RE_1RA0RD"
NS = "H78071"

# (name, start, doc): the end is the configuration right after the run of copies is crossed
RULES = [
    ('d_left',
     'L (10)^n D> 1 R',
     'D runs left over pairs 10 and leaves them as they are (D1 → 0LC, C0 → 1LD), 2 steps a pair.'),
    ('c_left',
     'L (01)^n C> 0 R',
     'The same in phase C over pairs 01.'),
]

DOC = """Shift rules of the leftward sweep over the period-2 background 10. Generated by py/rules.py (tools/py/bbtools/symtm.py); do not edit by hand."""


def after_cross(start):
    trace = []
    run(Machine.parse(M), Config.parse(start), lambda c: any(t[0] == "cross" for t in trace), trace=trace)
    return next(t[2] for t in trace if t[0] == "cross")


def main():
    ths = []
    for name, start, doc in RULES:
        ths.append(prove(M, name, start, after_cross(start), doc=doc)[0])
    sys.stdout.write(rules_file("Machine", NS, ths, DOC))


if __name__ == "__main__":
    main()
