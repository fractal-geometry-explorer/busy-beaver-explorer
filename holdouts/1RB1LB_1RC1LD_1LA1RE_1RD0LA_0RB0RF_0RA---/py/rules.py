"""Generate ../lean/Rules.lean: rules of 1RB1LB_1RC1LD_1LA1RE_1RD0LA_0RB0RF_0RA---, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`, repeats re-bracketed
next to the head with `TM.rep_rotate`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
`1^n` n ones, L and R any tape.  The tape is mostly the word 110.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LB_1RC1LD_1LA1RE_1RD0LA_0RB0RF_0RA---"

RULES = [
    ('shift_D_0_r', 'L D> (0)^n R', 'L (1)^n D> R',
     'D crosses (0)^n rightwards in n steps.'),
    ('shift_E_001_r', 'L E> (001)^n R', 'L (011)^n E> R',
     'E crosses (001)^n rightwards in 3*n steps.'),
    ('shift_A_01_l', 'L (01)^n A> 1 R', 'L A> 1 (01)^n R',
     'A crosses (01)^n leftwards in 4*n steps.'),
    ('shift_B_010_r', 'L B> (010)^n R', 'L (110)^n B> R',
     'B crosses (010)^n rightwards in 3*n steps.'),
    ('shift_F_011_r', 'L F> (011)^n R', 'L (110)^n F> R',
     'F crosses (011)^n rightwards in 5*n steps.'),
    ('shift_B_10_l', 'L (10)^n B> 1 R', 'L B> 1 (10)^n R',
     'B crosses (10)^n leftwards in 4*n steps.'),
    ('shift_C_100_r', 'L C> (100)^n R', 'L (101)^n C> R',
     'C crosses (100)^n rightwards in 3*n steps.'),
    ('shift_E_101_r', 'L E> (101)^n R', 'L (011)^n E> R',
     'E crosses (101)^n rightwards in 5*n steps.'),
    ('shift_A_111_l', 'L (111)^n A> 1 R', 'L A> 1 (011)^n R',
     'A crosses (111)^n leftwards in 3*n steps.'),
    ('shift_B_111_l', 'L (111)^n B> 1 R', 'L B> 1 (101)^n R',
     'B crosses (111)^n leftwards in 3*n steps.'),
    ('shift_D_111_l', 'L (111)^n D> 1 R', 'L D> 1 (110)^n R',
     'D crosses (111)^n leftwards in 3*n steps.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H126070", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
