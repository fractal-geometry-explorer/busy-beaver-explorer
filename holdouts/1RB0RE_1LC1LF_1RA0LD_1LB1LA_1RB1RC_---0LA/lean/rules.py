"""Generate Rules.lean: shift rules of 1RB0RE_1LC1LF_1RA0LD_1LB1LA_1RB1RC_---0LA, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(10)^n` is n
copies of `10`, `0^inf` is blank tape, L and R are any tape.  What the rules mean is in ../README.md.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_1LC1LF_1RA0LD_1LB1LA_1RB1RC_---0LA"

RULES = [
    ('a_right', 'L 0 A> (110)^n 0 R', 'L 0 (011)^n 1 B> R',
     'Going right, A (with E) shifts a block of `110` words by one cell, three steps per word.'),
    ('d_left', 'L 1 (110)^n D> 1 R', 'L 1 D> 1 (011)^n R',
     'Going left, D (with B, F) crosses a block of `110` words, shifting it by one cell.'),
    ('c_left', 'L 1 (101)^n C> 1 R', 'L 1 C> 1 (110)^n R',
     'Going left, C (with A, D) crosses a block written as `101` words.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True, max_seg=30)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H80070", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
