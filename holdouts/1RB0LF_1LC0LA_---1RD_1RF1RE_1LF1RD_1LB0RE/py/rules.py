"""Shift rules of 1RB0LF_1LC0LA_---1RD_1RF1RE_1LF1RD_1LB0RE, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LF_1LC0LA_---1RD_1RF1RE_1LF1RD_1LB0RE/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L 1 0 C> (10)^n R` is the head
in state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LF_1LC0LA_---1RD_1RF1RE_1LF1RD_1LB0RE"
NS = "H125689"
DOC = """# Shift rules of 1RB0LF_1LC0LA_---1RD_1RF1RE_1LF1RD_1LB0RE

Passes of the machine.  Over the regular left part of the tape, E moving right rewrites each copy of
`1101101101` as `1011110110` (`pass_right`, 12 steps a copy) and A moving left rewrites it back (`pass_left`, 50
steps a copy).  In the irregular right part the head crosses runs of three-cell words: `D> (011)^n` (`cross_D`),
`(101)^n B> 1` (`cross_B`).  The only halt is C reading a 0, and C is entered only from B reading a 0 (writing a 1,
stepping left), so `0 B> 0` halts after two steps (`halt_B`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

# Lean options put before the first theorem (the long words need a deeper recursion limit)
OPTIONS = ''

RULES = [
    ('pass_right',
     'L E> (1101101101)^n R',
     'L (1011110110)^n E> R',
     'E moving right over the left part, 12 steps a copy.'),
    ('pass_left',
     'L (1011110110)^n A> 1 R',
     'L A> 1 (0110110111)^n R',
     'A moving left over the left part, 50 steps a copy; `1 (0110110111)^n` is `(1011011011)^n 1`, a rotation of the word E crosses.'),
    ('cross_D',
     'L D> (011)^n R',
     'L (101)^n D> R',
     'D moving right over `011`, three steps a copy.'),
    ('cross_B',
     'L (101)^n B> 1 R',
     'L B> 1 (100)^n R',
     'B moving left over `101`, three steps a copy.')
]

# hand-written statements appended to the file (the halting situations), proved by `rfl`
EXTRA = """/-- `0 B> 0` halts: B writes a 1 and steps left in state C onto a 0, which has no transition. -/
theorem halt_B (L R : Tape) :
    ∃ c, steps 1 ⟨cons false L, cons false R, .B⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩
"""


def main():
    thms = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    thms[0] = OPTIONS + thms[0]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
