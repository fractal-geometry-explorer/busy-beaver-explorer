"""Writes lean/Rules.lean: what one sweep does to the last blocks of 1s, by the parities of the blocks, each proved
by bbtools.symtm (shift rules, `rfl`, `omega`).  The visit is B at the right end of the tape (B> 0^inf); blocks
are written (11)^a for an even length 2a and (11)^a 1 for an odd length 2a+1; L is any tape.

* odd: the last block z odd: (y, z) -> (y - 1, z + 2);
* even_even: z even, y even: (x, y, z) -> (x - 1, y + 4, z - 2);
* even_odd: z even, y odd >= 3, x even: (w, x, y, z) -> (w - 1, x + 4, y + 2, z - 2);
* halt_case: z even, y = 1, x even: the head reaches F on a 0 (the halting transition F0) in 2b + 4c + 15 steps.
  This configuration does not occur in the run from blank tape (the closed tape language from windows of 6 cells
  allows F0 only with `1` and then blank to the left of the head), but it shows what a halt looks like.

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file, run, Config, Blank, Rep
from bbtools.machine import Machine

M = "1RB1RA_0LC1RF_0LD1LD_1LE1LC_0RB0RA_---1RE"
NS = "H41677"
RULES = [
    ("odd_even_y", "z = 2b+1 odd, y = 2a+2 even: y loses 1, z gains 2.",
     "L 0 (11)^a+1 0 (11)^b 1 B> 0^inf", "L 0 (11)^a 1 0 (11)^b 1 1 1 B> 0^inf"),
    ("odd_odd_y", "z = 2b+1 odd, y = 2a+1 odd: y loses 1, z gains 2.",
     "L 0 (11)^a 1 0 (11)^b 1 B> 0^inf", "L 0 (11)^a 0 (11)^b 1 1 1 B> 0^inf"),
    ("even_even", "z = 2b+4, y = 2a+2, x = 2c+2: x loses 1, y gains 4, z loses 2.",
     "L 0 (11)^c+1 0 (11)^a+1 0 (11)^b+1 1 1 B> 0^inf", "L 0 (11)^c 1 0 (11)^a 1 1 1 1 1 1 0 (11)^b 1 1 B> 0^inf"),
    ("even_odd", "z = 2b+4, y = 2a+3, x = 2c+2, w = 2d+2: w loses 1, x gains 4, y gains 2, z loses 2.",
     "L 0 (11)^d+1 0 (11)^c+1 0 (11)^a+1 1 0 (11)^b+1 1 1 B> 0^inf",
     "L 0 (11)^d 1 0 (11)^c 1 1 1 1 1 1 0 (11)^a 1 1 1 1 1 0 (11)^b 1 1 B> 0^inf"),
    ("halt_case", "z = 2b+2, y = 1, x = 2c+2: F reads a 0 (the halting transition) after 2b + 4c + 15 steps.",
     "L 0 (11)^d+1 0 (11)^c+1 0 1 0 (11)^b+1 B> 0^inf", None),
]


def about_to_halt(c):
    r = c.right[0]
    return c.state == 5 and (r == 0 or isinstance(r, Blank) or (isinstance(r, Rep) and r.word[0] == 0))


def main():
    m = Machine.parse(M)
    thms = []
    for name, doc, start, end in RULES:
        c = Config.parse(start)
        first = [True]

        def visit(cc):
            if first[0]:
                first[0] = False
                return False
            return cc.state == 1 and len(cc.right) == 1 and isinstance(cc.right[0], Blank)
        run(m, c, about_to_halt if end is None else visit, rotate=True)
        end = c
        thms.append(prove(M, name, start, end, doc=doc, rotate=True, count_first=True, max_seg=60)[0])
    print(rules_file("Machine", NS, thms, "One sweep on the last blocks of 1s, by parity. Generated by `py/rules.py`."), end="")


if __name__ == "__main__":
    main()
