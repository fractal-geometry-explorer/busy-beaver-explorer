"""Generate Rules.lean for 1RB0LC_1RC0RA_1LD1LA_1RE1LD_---1RF_0RD1RA: the halting context and the shift rules over the words of its tape, proved along the symbolic run of tools/py/bbtools/symtm.py
(single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LC_1RC0RA_1LD1LA_1RE1LD_---1RF_0RD1RA"

RULES = [
    ('right_end_grow', 'L 1 0 1 0 1 0 1 1 C> 0^inf', 'L 1 1 1 1 1 0 1 0 1 B> 0^inf',
     'At the right end of the tape: the big block absorbs `0 1 0` and the tail moves two cells right, in 21 steps.'),
    ('halt_ctx', 'L F> 0 0 0 R', 'L 0 1 E> 0 R',
     'F on a 0 with 0 0 after it: D writes a 1 on the next 0 and E reads the last 0 (the halting transition).'),
    ('run_A_01', 'L A> (01)^n R', 'L (10)^n A> R',
     'A crosses n copies of `01` to the right in 2n steps, leaving `10`.'),
    ('run_A_001_0', 'L 0 A> (001)^n R', 'L (101)^n 0 A> R',
     'A crosses n copies of `001` to the right in 9n steps, leaving `101` (carrying `0`).'),
    ('run_B_10', 'L B> (10)^n R', 'L (01)^n B> R',
     'B crosses n copies of `10` to the right in 2n steps, leaving `01`.'),
    ('run_D_10_0', 'L 0 D> (10)^n R', 'L (11)^n 0 D> R',
     'D crosses n copies of `10` to the right in 4n steps, leaving `11` (carrying `0`).'),
    ('back_D_1_1', 'L (1)^n D> 1 R', 'L D> 1 (1)^n R',
     'D crosses n copies of `1` to the left in 1n steps, leaving `1` (carrying `1`).'),
    ('run_E_100', 'L E> (100)^n R', 'L (101)^n E> R',
     'E crosses n copies of `100` to the right in 3n steps, leaving `101`.'),
    ('run_F_01', 'L F> (01)^n R', 'L (11)^n F> R',
     'F crosses n copies of `01` to the right in 4n steps, leaving `11`.'),
    ('run_F_001', 'L F> (001)^n R', 'L (011)^n F> R',
     'F crosses n copies of `001` to the right in 3n steps, leaving `011`.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H133770", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
