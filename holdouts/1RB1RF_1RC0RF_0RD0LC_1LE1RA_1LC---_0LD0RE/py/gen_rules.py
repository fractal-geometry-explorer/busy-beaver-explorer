"""Write lean/Rules.lean for 1RB1RF_1RC0RF_0RD0LC_1LE1RA_1LC---_0LD0RE (3a) or 1RB1RF_1RC0RF_0RD0LC_1LE1RA_1LC---_1RB0RE (3b),
proved by `bbtools.symtm.prove`: the F0 rule that makes the two machines agree, and the shift rules the run uses.

Usage (from the repository root):
  python3 holdouts/1RB1RF_1RC0RF_0RD0LC_1LE1RA_1LC---_0LD0RE/py/gen_rules.py MACHINE NAMESPACE > holdouts/MACHINE/lean/Rules.lean"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file

RULES = [
    ("f0_after_1", "L 1 F> 0 R", "L 1 1 B> R",
     "F on a 0 with a 1 on its left: both machines of the family reach B on the next cell with the two cells set to 1 "
     "(3a: F0 = 0LD, D1 = 1RA, A0 = 1RB, three steps; 3b: F0 = 1RB, one step)."),
    ("shift_B", "L B> (1100)^n R", "L (0011)^n B> R", "B crosses (1100)^n to the right, leaving (0011)^n."),
    ("shift_D5", "L D> (11000)^n R", "L (11110)^n D> R", "D crosses (11000)^n to the right, leaving (11110)^n."),
    ("shift_D4", "L D> (1000)^n R", "L (1110)^n D> R", "D crosses (1000)^n to the right, leaving (1110)^n."),
    ("shift_A3", "L A> (110)^n R", "L (101)^n A> R", "A crosses (110)^n to the right, leaving (101)^n."),
    ("shift_A4", "L A> (0001)^n R", "L (1101)^n A> R", "A crosses (0001)^n to the right, leaving (1101)^n."),
]

def main():
    M, ns = sys.argv[1], sys.argv[2]
    ths = []
    for name, s, e, doc in RULES:
        t, fin = prove(M, name, s, e, doc=doc)
        print(f"-- {name}: {s} -> {fin}", file=sys.stderr)
        ths.append(t)
    print(rules_file("Machine", ns, ths, "Rules of the 1RB1RF_1RC0RF_0RD0LC_1LE1RA_1LC---_ family, generated by `py/gen_rules.py` "
                     "of holdouts/1RB1RF_1RC0RF_0RD0LC_1LE1RA_1LC---_0LD0RE with `tools/py/bbtools/symtm.py`; do not edit by hand."), end="")

if __name__ == "__main__":
    main()
