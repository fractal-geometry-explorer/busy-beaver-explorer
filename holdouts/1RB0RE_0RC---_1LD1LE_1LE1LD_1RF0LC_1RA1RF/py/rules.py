"""Generate ../lean/Rules.lean: the shift and macro rules of 1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(10)^n` is n copies of `10`,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF"

RULES = [
    ('d_run', 'L (1111)^n D> 1 R', 'L D> 1 (1111)^n R',
     'Even parity: D runs left over words 1111, leaving them.'),
    ('e_run', 'L (1111)^n E> 1 R', 'L E> 1 (1010)^n R',
     'E runs left over 1111 words, writing 1010.'),
    ('f_run', 'L F> (1111)^n R', 'L (1111)^n F> R',
     'F runs right over 1111 words.'),
    ('d_u0', 'L 0 1 1 1 D> 0 R', 'L C> 0 0 1 0 1 R',
     'Even parity meets u = 1110: it becomes 0101 and the parity turns odd (state C).'),
    ('d_v0', 'L 0 1 1 1 D> 1 R', 'L D> 0 1 1 1 1 R',
     'Even parity meets v = 1111: it stays 1111, parity stays even (D).'),
    ('c_u0', 'L 0 1 1 1 C> 0 R', 'L D> 0 1 1 1 1 R',
     'Odd parity meets u = 1110: it becomes 1111 and the parity turns even (D).'),
    ('c_v0', 'L 0 1 1 1 C> 1 R', 'L C> 0 0 1 0 1 R',
     'Odd parity meets v = 1111: it becomes 0101, parity stays odd (C).'),
    ('d_u1', 'L 1 1 1 1 D> 0 R', 'L C> 1 0 1 0 1 R',
     'As d_u0, the word on the left being 1111.'),
    ('d_v1', 'L 1 1 1 1 D> 1 R', 'L D> 1 1 1 1 1 R',
     'As d_v0, the word on the left being 1111.'),
    ('c_u1', 'L 1 1 1 1 C> 0 R', 'L D> 1 1 1 1 1 R',
     'As c_u0, the word on the left being 1111.'),
    ('c_v1', 'L 1 1 1 1 C> 1 R', 'L C> 1 0 1 0 1 R',
     'As c_v0, the word on the left being 1111.'),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H75625", ths, f"Rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
