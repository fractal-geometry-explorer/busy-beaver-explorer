"""Write lean/Pascal.lean and lean/Lucas.lean of 1RB0LE_1RC1RB_1RD0RA_0RE---_1LF1LA_1LA1LF from this machine's.

That machine has this machine's table with the states renamed A->C, B->D, C->E, D->F, E->A, F->B (it is this table
started in state E), so every proof goes through with the state names changed.  usage: python3 py/port_pascal.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "lean")
OTHER = "1RB0LE_1RC1RB_1RD0RA_0RE---_1LF1LA_1LA1LF"
DST = os.path.join(HERE, "..", "..", OTHER, "lean")
REN = {"A": "C", "B": "D", "C": "E", "D": "F", "E": "A", "F": "B"}
NOTE = ("-- Generated by holdouts/1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF/py/port_pascal.py from that machine's file\n"
        "-- of the same name, with its states renamed A->C, B->D, C->E, D->F, E->A, F->B; do not edit by hand.\n")


def port(text):
    text = text.replace("namespace H75625", "namespace H58953").replace("end H75625", "end H58953")
    text = re.sub(r"(?<![\w.])\.([A-F])\b", lambda m: "." + REN[m.group(1)], text)
    # state names in prose: "in E", "C/D" etc. are left as they are; the header says how to read them
    return text


for name in ("Pascal.lean", "Lucas.lean"):
    with open(os.path.join(SRC, name)) as f:
        src = f.read()
    out = port(src)
    lines = out.split("\n", 1)
    with open(os.path.join(DST, name), "w") as f:
        f.write(lines[0] + "\n" + NOTE + lines[1])
    print("wrote", os.path.join(DST, name))
