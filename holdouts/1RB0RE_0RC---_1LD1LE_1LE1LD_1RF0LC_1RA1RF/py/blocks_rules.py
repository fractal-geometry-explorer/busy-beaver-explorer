"""Generate ../lean/Blocks.lean: the machine read on blocks of 1s separated by 0s (tools/py/bbtools/symtm.py).

usage: python3 blocks_rules.py > ../lean/Blocks.lean

Between two turns of the head the tape is a list of blocks of 1s separated by single 0s.  These rules are every way
the head meets a block or a separator; L and R are any tape, `S>` is the head in state S on the next cell.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0RE_0RC---_1LD1LE_1LE1LD_1RF0LC_1RA1RF"

RULES = [
    ('f_block', 'L F> 1^n R', 'L 1^n F> R',
     'Going right, F crosses a block of 1s.'),
    ('f_single', 'L F> 0 1 0 R', 'L 1 0 1 F> R',
     'F at a separator followed by a block of one cell: the separator is filled, the cell is erased, the next separator is filled, and F goes on. The blocks on both sides each gain a cell.'),
    ('f_turn', 'L F> 0 1 1 R', 'L D> 1 1 0 R',
     'F at a separator followed by a block of two or more cells turns round: the block on the left gains two cells, the block on the right loses two, and the head leaves to the left in D. If the block had exactly two cells, two 0s now stand in a row.'),
    ('f_three_zeros', 'L F> 0 0 0 1 R', 'L 1 1 1 F> 1 R',
     'Three 0s followed by a 1 are filled.'),
    ('f_end', 'L 1 F> 0 0 0 0 R', 'L E> 1 1 0 1 1 R',
     'Four 0s (the right end of the tape): the head writes 1011 and leaves to the left in E.'),
    ('d_block', 'L 1^n D> 1 R', 'L D> 1 1^n R',
     'Going left, D crosses a block of 1s and leaves it as it is.'),
    ('d_sep', 'L 1 D> 0 R', 'L E> 1 1 R',
     'D fills the separator and goes on in E: the next block will be broken up.'),
    ('e_pairs', 'L (11)^n E> 1 R', 'L E> 1 (10)^n R',
     'Going left, E and C alternate over a block: every second cell is erased.'),
    ('e_last', 'L 0 E> 1 R', 'L C> 0 0 R',
     'A block of odd length entered in E: E erases its first cell and C reaches the separator.'),
    ('c_last', 'L 0 C> 1 R', 'L E> 0 1 R',
     'A block of even length entered in E: C keeps its first cell and E reaches the separator, where it turns (`e_turn`).'),
    ('c_sep', 'L 1 C> 0 R', 'L D> 1 1 R',
     'C fills the separator and goes on in D: the next block will be kept.'),
    ('e_turn', 'L E> 0 R', 'L 1 F> R',
     'E on a 0 (after a block of even length, or at the left end of the tape) fills it and turns right in F.'),
]

EXTRA = """/-- `F> 0 0 1` halts: F writes 1, A reads 0 and writes 1, B reads the 1. -/
theorem halt_F (L R : Tape) :
    ∃ c, steps 2 ⟨L, cons false (cons false (cons true R)), .F⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩

/-- A turn at a block of exactly two cells that is followed by `0 1` leaves `0 0 1` on the tape, with the head in D
on the cell F filled (`f_turn` with the two cells after the block written out).  If F later comes back to the first
of the two 0s, the machine halts (`halt_F`). -/
theorem turn_two (L R : Tape) :
    steps 4 ⟨L, cons false (cons true (cons true (cons false (cons true R)))), .F⟩ =
      some ⟨L, cons true (cons true (cons false (cons false (cons true R)))), .D⟩ := rfl
"""


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    text = rules_file("Machine", "H75625", ths, f"Block rules of {M}, generated by `py/blocks_rules.py`; do not edit by hand.")
    i = text.rindex("end H75625")
    sys.stdout.write(text[:i] + EXTRA + "\n" + text[i:])


if __name__ == "__main__":
    main()
