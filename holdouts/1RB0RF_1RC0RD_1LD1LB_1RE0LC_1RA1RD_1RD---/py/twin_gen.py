"""Generate lean/Twin.lean: this machine is the reference machine 1RB0RC_1LC1LA_1RD0LB_1RE1RC_1RA0RF_1RC--- with its
states renamed (and, for the mirror twin, left and right exchanged), started in another state.

usage (from the repository root):  python3 holdouts/MACHINE/py/twin_gen.py > holdouts/MACHINE/lean/Twin.lean
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MACHINE = os.path.basename(os.path.dirname(HERE))
REF = "1RB0RC_1LC1LA_1RD0LB_1RE1RC_1RA0RF_1RC---"
# reference state -> state here; mirror; the reference state that corresponds to this machine's start state A
REN, MIRROR, START = {
    "1RB0RF_1RC0RD_1LD1LB_1RE0LC_1RA1RD_1RD---": (dict(A="B", B="C", C="D", D="E", E="A", F="F"), False, "E"),
    "1RB1RE_1LC0RA_1LD1LB_1LE0LF_1LA0LB_1LB---": (dict(A="E", B="A", C="B", D="C", E="D", F="F"), True, "B"),
}[MACHINE]


def parse(m):
    t = {}
    for s, part in zip("ABCDEF", m.split("_")):
        for r in range(2):
            x = part[3 * r:3 * r + 3]
            t[(s, r)] = None if x[2] == "-" else (int(x[0]), x[1], x[2])
    return t


def check_tables():
    """the claim itself, checked here too: renaming (and mirroring) the reference table gives this machine's table"""
    ref, me = parse(REF), parse(MACHINE)
    for (s, r), tr in ref.items():
        want = None if tr is None else (tr[0], ({"L": "R", "R": "L"}[tr[1]] if MIRROR else tr[1]), REN[tr[2]])
        assert me[(REN[s], r)] == want, (s, r)


def main():
    check_tables()
    ns = re.search(r"^namespace (\S+)", open(os.path.join(HERE, "..", "lean", "Machine.lean")).read(), re.M).group(1)
    ref = parse(REF)
    rows = []
    for s in "ABCDEF":
        for r in range(2):
            tr = ref[(s, r)]
            b = "true" if r else "false"
            rows.append(f"  | .{s}, {b} => " + ("none" if tr is None else f"some ({'true' if tr[0] else 'false'}, .{tr[1]}, .{tr[2]})"))
    ren = "\n".join(f"  | .{a} => .{b}" for a, b in REN.items())
    if MIRROR:
        mapdef = "⟨tail c.r, cons (c.r 0) c.l, ren c.st⟩"
        what = "its mirror image: the two sides of the tape exchanged (the head stays on its cell) and the states renamed"
        simp = "simp [TM.step, rtrans, trans, tw, ren, h, cons_head_tail]"
        init = f"""theorem init_eq : init = tw (TM.blankCfg .{START}) := by
  show (⟨blank, blank, .A⟩ : Config) = ⟨tail blank, cons (blank 0) blank, .A⟩
  have e : cons (blank 0) blank = blank := cons_false_blank
  rw [e]
  rfl"""
        extra = """/-- A stream is its first cell in front of the rest. -/
theorem cons_head_tail (s : Tape) : cons (s 0) (tail s) = s := by
  funext n; cases n <;> rfl

"""
    else:
        mapdef = "⟨c.l, c.r, ren c.st⟩"
        what = "the same configuration with the states renamed"
        simp = "simp [TM.step, rtrans, trans, tw, ren, h]"
        init = f"theorem init_eq : init = tw (TM.blankCfg .{START}) := rfl"
        extra = ""
    sys.stdout.write(f"""import Machine

/-!
# {MACHINE} runs the table of {REF}, from a different start

Generated by `py/twin_gen.py`; do not edit by hand.

`rtrans` is the transition table of the reference machine {REF}, with its own state names.  The map `tw` sends a
configuration of the reference machine to {what}.  It commutes with the step function (`step_tw`), so the two runs
correspond step for step (`steps_tw`), and this machine's run from blank tape is the image of the reference machine's
run from blank tape *started in state {START}* instead of A (`init_eq`).  Hence `halts_iff`: this machine halts from
blank tape if and only if the reference machine, started in state {START} on blank tape, halts, and after the same
number of steps.  This does NOT relate it to the reference machine's own run from blank tape (started in A): that is a
separate halting question, and the two blank-tape runs share no configuration in the first 10^7 steps.
-/

namespace {ns}

open TM

/-- The states of the reference machine. -/
inductive RSt where
  | A | B | C | D | E | F
  deriving DecidableEq, Repr

/-- The transition table of {REF}. -/
def rtrans : RSt → Bool → Option (Bool × Dir × RSt)
{chr(10).join(rows)}

/-- The renaming of the states. -/
def ren : RSt → St
{ren}

{extra}/-- A configuration of the reference machine, seen as a configuration of this machine. -/
def tw (c : Cfg RSt) : Config := {mapdef}

/-- One step of the reference machine is one step of this machine. -/
theorem step_tw (c : Cfg RSt) : TM.step trans (tw c) = (TM.step rtrans c).map tw := by
  obtain ⟨l, r, s⟩ := c
  cases s <;> cases h : r 0 <;> {simp}

/-- The runs correspond step for step. -/
theorem steps_tw (n : Nat) (c : Cfg RSt) : TM.steps trans n (tw c) = (TM.steps rtrans n c).map tw := by
  induction n generalizing c with
  | zero => rfl
  | succ n ih =>
    cases h : TM.step rtrans c with
    | none =>
      have h' : TM.step trans (tw c) = none := by rw [step_tw, h]; rfl
      simp [TM.steps, h, h']
    | some c' =>
      have h' : TM.step trans (tw c) = some (tw c') := by rw [step_tw, h]; rfl
      rw [TM.steps_succ_of_step trans n h', TM.steps_succ_of_step rtrans n h]
      exact ih c'

/-- Blank tape in state A here is blank tape in state {START} there. -/
{init}

/-- This machine halts from blank tape exactly when the reference machine started in state {START} on blank tape does. -/
theorem halts_iff : HaltsFromBlank ↔ TM.Halts rtrans (TM.blankCfg .{START}) := by
  constructor
  · rintro ⟨n, c', h₁, h₂⟩
    rw [init_eq, steps_tw] at h₁
    cases hd : TM.steps rtrans n (TM.blankCfg .{START}) with
    | none => rw [hd] at h₁; cases h₁
    | some d =>
      rw [hd] at h₁
      have e : tw d = c' := by simpa using h₁
      refine ⟨n, d, hd, ?_⟩
      rw [← e] at h₂
      have h₃ : (TM.step rtrans d).map tw = none := by rw [← step_tw]; exact h₂
      cases hs : TM.step rtrans d with
      | none => rfl
      | some x => rw [hs] at h₃; cases h₃
  · rintro ⟨n, d, h₁, h₂⟩
    refine ⟨n, tw d, ?_, ?_⟩
    · show TM.steps trans n init = some (tw d)
      rw [init_eq, steps_tw, h₁]; rfl
    · show TM.step trans (tw d) = none
      rw [step_tw, h₂]; rfl

end {ns}
""")


if __name__ == "__main__":
    main()
