"""Generate Rules.lean: the pieces of a plain pass of 1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD and the halting
zipper, proved along the symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by
`TM.cross_r`/`TM.cross_l`, re-bracketings by `TM.rep_rotate`).

usage (from the repository root):
  python3 holdouts/1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD/lean/rules.py > holdouts/1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD/lean/Rules.lean

Tapes left to right, `S>` the head in state S on the next cell, `(w)^n` n copies of the word w, `0^inf` blank tape,
L and R any tape.  Pass.lean puts the pieces together.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD"

RULES = [
    ("cycle", "L (10)^p+1 (11)^2*k+2 A> 1^s+3 R", "L (10)^p (11)^2*k+4 A> 1^s+1 R",
     "One round of a pass: A eats the last `10` on its left, two 1s on its right, and the block of 1s grows by 4."),
    ("pass_start", "0^inf B> 0 0 (10)^a+2 1^s+3 R", "0^inf 0 1 (01)^a+1 1 1 1 A> 1 1 (1)^s+1 R",
     "The start of a pass: C and E zip over the `10`s, D and B turn the last one into the block `1111`."),
    ("pass_end", "0^inf (11)^m+1 A> 1^s+5 R", "0^inf B> 0 0 1 0 1 (01)^m+1 0 1 (1)^s R",
     "The end of a pass, when no `10` is left: the block of 1s becomes the new run of `10`s."),
    ("zip_halt", "0^inf B> 0 0 (10)^n 0^inf", "0^inf 0 1 0 (10)^n E> 0^inf",
     "From `B>0 0 (10)^n` and blank tape, C and E zip right and E reaches a blank."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, rotate=True)[0] for name, a, b, doc in RULES]
    print(rules_file("Machine", "H149707", ths,
                     "Pieces of a pass of 1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD, generated by `rules.py`; do not edit."), end="")


if __name__ == "__main__":
    main()
