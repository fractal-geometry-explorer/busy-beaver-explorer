"""Generate Pieces.lean: one symbolic run for every case of the phase map of
1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD (see Phases.lean), proved along the run by tools/py/bbtools/symtm.py.
Each run starts from a phase start and stops at the first configuration of the given kind ('A': state A with only
1s on the right, 'B': state B at the left end on `0 0`, 'E': state E on blank tape); that configuration is the
theorem's right-hand side.

usage (from the repository root):
  python3 holdouts/1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD/lean/pieces.py > holdouts/1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD/lean/Pieces.lean
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import Config, prove, rules_file, run  # noqa: E402
from bbtools.machine import Machine  # noqa: E402

M = "1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD"
ONES = re.compile(r"^(1|1\^\S+|\(1\)\^\S+|\(11\)\^\S+)$")


def is_a(c):
    if c.steps.is_zero() or c.state != 0:
        return False
    rt = repr(c).split("A> ")[1].split()
    while len(rt) > 1 and rt[-2] == "0":
        rt.pop(-2)
    return rt[-1] == "0^inf" and len(rt) > 1 and all(ONES.match(t) for t in rt[:-1])


def is_b(c):
    return not c.steps.is_zero() and c.state == 1 and repr(c).startswith("0^inf B> 0 0")


def is_e(c):
    return c.state == 4 and repr(c).endswith("E> 0^inf")


STOP = {"A": is_a, "B": is_b, "E": is_e}

PIECES = [
    ("pc_init", "0^inf A> 0^inf", "B", "From blank tape the machine reaches PS(0, 2)."),
    ("pc_halt1", "0^inf B> 0 0 (10)^n 1 0^inf", "E", "PS(n, 1) reaches E on blank tape."),
    ("pc_halt0", "0^inf B> 0 0 (10)^n 0^inf", "E", "PS(n, 0) reaches E on blank tape."),
    ("pc_start", "0^inf B> 0 0 (10)^a+1 1^c+2 0^inf", "A", "PS(a+1, c+2) reaches Q(a, 2, c+2)."),
    ("pc_ps02", "0^inf B> 0 0 1 1 0^inf", "B", "PS(0, 2) reaches PS(0, 5)."),
    ("pc_ps0", "0^inf B> 0 0 1^c+3 0^inf", "B", "PS(0, c+3) reaches PS(2, c+1)."),
    ("pc_round", "0^inf (10)^a+1 (11)^m+2 A> 1^c+3 0^inf", "A", "One round: Q(a+1, m+2, c+3) reaches Q(a, m+4, c+1)."),
    ("pc_end", "0^inf (11)^m+2 A> 1^c+5 0^inf", "B", "Q(0, m+2, c+5) reaches PS(m+4, c+1)."),
    ("pc_end1", "0^inf (11)^m+2 A> 1 0^inf", "B", "Q(0, m+2, 1) reaches PS(0, 2m+8)."),
    ("pc_end2", "0^inf (11)^m+2 A> 1 1 0^inf", "B", "Q(0, m+2, 2) reaches PS(0, 2m+6)."),
    ("pc_end3", "0^inf (11)^m+2 A> 1 1 1 0^inf", "B", "Q(0, m+2, 3) reaches PS(0, 2m+11)."),
    ("pc_end4", "0^inf (11)^m+2 A> 1 1 1 1 0^inf", "B", "Q(0, m+2, 4) reaches PS(0, 2m+9)."),
    ("pc_one1", "0^inf 1 0 (11)^m+2 A> 1 0^inf", "B", "Q(1, m+2, 1) reaches PS(2, 2m+6)."),
    ("pc_one2", "0^inf 1 0 (11)^m+2 A> 1 1 0^inf", "B", "Q(1, m+2, 2) reaches PS(2, 2m+4)."),
    ("pc_reb1", "0^inf (10)^R+2 (11)^m+2 A> 1 0^inf", "A", "Q(R+2, m+2, 1) reaches Q(R, 2, 2m+8)."),
    ("pc_reb2", "0^inf (10)^R+2 (11)^m+2 A> 1 1 0^inf", "A", "Q(R+2, m+2, 2) reaches Q(R, 2, 2m+6)."),
]


def main():
    m = Machine.parse(M)
    ths = []
    for name, start, kind, doc in PIECES:
        fin = run(m, Config.parse(start), STOP[kind], max_moves=5000, rotate=True)
        ths.append(prove(M, name, start, repr(fin), doc=doc, rotate=True)[0])
    print(rules_file("Machine", "H149707", ths,
                     "Pieces of the phase map of 1RB1RF_1LC1LF_0RE1LD_0LB1LD_---1RC_1RA0RD, generated by `pieces.py`; "
                     "do not edit."), end="")


if __name__ == "__main__":
    main()
