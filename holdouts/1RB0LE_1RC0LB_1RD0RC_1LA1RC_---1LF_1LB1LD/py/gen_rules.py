"""The sweep rules of 1RB0LE_1RC0LB_1RD0RC_1LA1RC_---1LF_1LB1LD as Lean theorems (lean/Rules.lean).

Each rule goes from one moment the head is at the left end in state B reading 1 ("B>1 ...") to the next, for every
value of the counts.  Blocks are (1101)^n separated by single 0 cells; `0 0` is the marker.  The rules at depth 1 and 2 (8 + 4 and
16 + 8 copies per unit) also hold symbolically, but their proofs exceed the kernel's heartbeat limit, so they are
left out.

usage: python3 py/gen_rules.py            (rewrites lean/Rules.lean)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHARED = os.path.join(HERE, "..", "..", "1RB---_1RC0RA_1LD0RB_0LE0LC_1RE1LF_0RD0RB", "py")
sys.path.insert(0, SHARED)
from rulegen import sym, at_end, write_rules  # noqa: E402

M = "1RB0LE_1RC0LB_1RD0RC_1LA1RC_---1LF_1LB1LD"
W = "(1101)"

# (name, start, doc); the end is the next "B>1" moment, found by the symbolic run
STARTS = [
    ("t_one", f"0^inf B> 1 {W}^x+3 0 0 {W}^y+1 0 R",
     "Transfer phase, first half: the block left of the marker loses two copies, the one right of it gains two."),
    ("t_two", f"0^inf B> 1 0 {W}^x+3 0 0 {W}^y+1 0 R",
     "Transfer phase, second half: one more copy appears right of the marker (three in for two out)."),
    ("u0_one", f"0^inf B> 1 {W}^c+1 0 {W}^z+5 0 0 {W}^y+1 0 R",
     "Counting phase, marker in the block next to the counter c: c gains one, four copies move across the marker."),
    ("u0_two", f"0^inf B> 1 0 {W}^c+1 0 {W}^z+3 0 0 {W}^y+1 0 R",
     "Counting phase, depth 0, second half: two more copies move across (six per unit of c)."),
]


def rules():
    out = []
    for name, start, doc in STARTS:
        res, c = sym(M, start, at_end("L", "B", 1))
        assert res == "stop", (name, res, c)
        out.append((name, start, repr(c), doc))
    return out


if __name__ == "__main__":
    rs = rules()
    for name, s, e, _ in rs:
        print(name, ":", s, "->", e)
    n = write_rules(M, "H173433", rs, os.path.join(HERE, "..", "lean", "Rules.lean"),
                    f"Sweep rules of {M}, generated by `py/gen_rules.py`; do not edit by hand.")
    print(n, "theorems")
