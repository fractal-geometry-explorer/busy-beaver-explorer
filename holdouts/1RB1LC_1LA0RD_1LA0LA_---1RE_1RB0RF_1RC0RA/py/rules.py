"""Generate lean/Rules.lean for 1RB1LC_1LA0RD_1LA0LA_---1RE_1RB0RF_1RC0RA: the shift rules of its sweeps, proved along symbolic runs
(tools/py/bbtools/symtm.py: single steps by `rfl`, a whole repeat crossed by `TM.cross_r` / `TM.cross_l`).

usage (from the repository root): python3 holdouts/1RB1LC_1LA0RD_1LA0LA_---1RE_1RB0RF_1RC0RA/py/rules.py > holdouts/1RB1LC_1LA0RD_1LA0LA_---1RE_1RB0RF_1RC0RA/lean/Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` is n copies of the word w,
L and R are any tape.  Each rule holds for every n and every tape around it; README.md says where each one is used.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
import bbtools.symtm as symtm  # noqa: E402

symtm.MAX_CARRY = 8  # some sweeps carry a word of up to 6 cells along with the head

M = "1RB1LC_1LA0RD_1LA0LA_---1RE_1RB0RF_1RC0RA"
NS = "H82139"

RULES = [
    ("a_block", "L (101101)^n A> 1 R", "L A> 1 (110111)^n R",
     "Leftward: A turns each 101101 back into 110111 (a block of five ones)."),
    ("d_block", "L D> (111101)^n R", "L (110110)^n D> R",
     "Rightward: D turns each 111101 (a block of five ones) into 110110."),
    ("e_111", "L E> (111)^n R", "L (101)^n E> R",
     "Rightward: E turns each 111 into 101."),
    ("a_10", "L (10)^n A> 1 R", "L A> 1 (11)^n R",
     "Leftward: A fills each 10 into 11."),
]


def main():
    ths = [symtm.prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(symtm.rules_file("Machine", NS, ths, f"Sweep rules of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
