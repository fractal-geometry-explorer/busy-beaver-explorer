"""Generate Rules.lean for 1RB1LD_1RC0LE_1LA1RE_0LF1LA_1RB0RB_---0LB: the two sweeps across the block of ones at the right end, proved along the symbolic run (tools/py/bbtools/symtm.py:
single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean        (L and R are any tape)
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LD_1RC0LE_1LA1RE_0LF1LA_1RB0RB_---0LB"

RULES = [
    ("hole", "L E> 0 0 (111)^n R", "L (111)^n 1 1 C> R",
     "Going right, a hole 00 moves across the block of ones, three cells every five steps."),
    ("run_left", "L (11)^n D> 1 R", "L D> 1 (11)^n R",
     "Going left, the head runs across the ones in states D and A, one cell a step."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "H6741", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
