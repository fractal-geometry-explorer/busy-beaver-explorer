"""The halting situations of 1RB1LD_1RC0RC_1LD0RE_0LB0LA_0RF1LA_---1RC, proved in Lean from symbolic runs (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB1LD_1RC0RC_1LD0RE_0LB0LA_0RF1LA_---1RC/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L C> (10)^n R` is the head in
state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.  Each halting
situation is (name, pattern, steps, doc): from `pattern` (cells nearest the head; the rest unknown) the machine halts
after `steps` steps.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LD_1RC0RC_1LD0RE_0LB0LA_0RF1LA_---1RC"
NS = "H106785"
DOC = """# Halting situations of 1RB1LD_1RC0RC_1LD0RE_0LB0LA_0RF1LA_---1RC

Only F reading a 0 halts.  F is entered only from E reading a 0 (moving right), E only from C reading a 1 (moving
right), and C from B (on either symbol) or F (on a 1), always moving right.  So a halt is a rightward run onto two
0s: `E> 0 0` halts after one step, `C> 1 0 0` after two, `B> 0 1 0 0` and `B> 1 1 0 0` after three.

Generated by `py/rules.py`; every proof is `rfl`, checked by Lean's kernel."""

RULES = []

HALTS = [
    ('halt_E', 'E> 0 0', 1, '`E> 0 0` halts: E writes 0 and moves right onto the 0 in state F.'),
    ('halt_C', 'C> 1 0 0', 2, '`C> 1 0 0` halts after two steps.'),
    ('halt_B0', 'B> 0 1 0 0', 3, '`B> 0 1 0 0` halts after three steps.'),
    ('halt_B1', 'B> 1 1 0 0', 3, '`B> 1 1 0 0` halts after three steps.'),
]


def _cells(bits, inner):
    t = inner
    for b in bits:
        t = f"cons {'true' if b == '1' else 'false'} ({t})"
    return t


def halt_lemma(name, pattern, n, doc):
    """`∃ c, steps n cfg = some c ∧ step c = none` for the local pattern, by `rfl`."""
    toks = pattern.split()
    i = next(j for j, t in enumerate(toks) if t.endswith(">"))
    left, st, right = toks[:i], toks[i][0], toks[i + 1:]
    lt = _cells(left, "L")  # streams are nearest-first: the cell next to the head is outermost
    rt = _cells(right[::-1], "R")
    return (f"/-- {doc} -/\ntheorem {name} (L R : Tape) : ∃ c, steps {n} ⟨{lt}, {rt}, .{st}⟩ = some c ∧ step c = none :=\n"
            f"  ⟨_, rfl, rfl⟩\n")


def main():
    thms = [halt_lemma(*h) for h in HALTS]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms, DOC))


if __name__ == "__main__":
    main()
