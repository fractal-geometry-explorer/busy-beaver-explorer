"""Writes lean/Rules.lean: shift rules of this machine's sweeps and the shape of a halt, proved by
tools/py/bbtools/symtm.py (`prove`).  Usage: python3 py/rules.py > lean/Rules.lean"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LF_1RC1RB_1RD0RA_1RE0RE_1LF---_0LD1LA"
NS = "H139893"
RULES = [
    ('b_run', 'L B> (11)^n R', 'L (11)^n B> R',
     'Rightward, B crosses ones unchanged, 1 step a cell.', {}),
    ('a_right', 'L A> (0101)^n R', 'L (1110)^n A> R',
     'Rightward, A turns (0101)^n into (1110)^n, 4 steps a block.', {}),
    ('b_right', 'L B> (1010)^n R', 'L (1101)^n B> R',
     'Rightward, B turns (1010)^n into (1101)^n, 4 steps a block.', {}),
    ('a_left', 'L (11)^n A> 1 R', 'L A> 1 (10)^n R',
     'Leftward, A and F turn ones into (10)^n, 2 steps a pair.', {}),
    ('f_left', 'L (11)^n F> 0 R', 'L F> 0 (11)^n R',
     'Leftward, F (on a 0) crosses ones unchanged, 6 steps a pair.', {}),
    ('d_left', 'L (11)^n D> 1 0 R', 'L D> 1 0 (11)^n R',
     'Leftward, D (on 1 0) crosses ones unchanged, 6 steps a pair.', {}),
    ('halt_shape0', 'L C> 0 0 1 R', 'L 1 1 E> 1 R',
     'A way to a halt: C on a 0 with 0 1 to its right reaches E on a 1 (which halts) in 2 steps.', {}),
    ('halt_shape1', 'L C> 0 1 1 R', 'L 1 0 E> 1 R',
     'The other way to a halt: C on a 0 with 1 1 to its right reaches E on a 1 in 2 steps.', {}),
]
HALT = "E"
HSYM = "1"

if __name__ == "__main__":
    thms = [prove(M, n, s, e, doc=d, **kw)[0] for n, s, e, d, kw in RULES]
    extra = (f"/-- {HALT} reading a {HSYM} halts (the end of `halt_shape`). -/\n"
             f"theorem halt_after_shape (L R : Tape) : step ⟨L, cons true R, .{HALT}⟩ = none := rfl\n")
    print(rules_file("Machine", NS, thms + [extra],
                     f"# {M}: shift rules of the sweeps and the shape of a halt\n\n"
                     "Generated by `py/rules.py` with `tools/py/bbtools/symtm.py`; every rule holds for all `n` and all "
                     "tapes `L`, `R`."))
