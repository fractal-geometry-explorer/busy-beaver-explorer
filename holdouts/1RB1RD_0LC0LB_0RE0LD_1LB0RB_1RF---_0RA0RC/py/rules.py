"""Generate lean/Rules.lean: the base-7 odometer of 1RB1RD_0LC0LB_0RE0LD_1LB0RB_1RF---_0RA0RC, proved along the
symbolic run (tools/py/bbtools/symtm.py: single steps by `rfl`, whole blocks by `TM.cross_r` / `TM.cross_l`).

usage: python3 rules.py > ../lean/Rules.lean

Write [k] for (010)^k.  At the left end of the tape the head (state B, blank on its left) reads
[x] M [y] ..., where the marker M is one of seven words, the digit d = 0..6 of the odometer:

    M0 = 0   M1 = 001   M2 = 00110   M3 = 0010001   M4 = 0 [2] 10   M5 = 00101   M6 = 0011

`digit_d` (d = 0..5): one visit of the left end moves the first marker from M_d to M_(d+1), adds a copy to [x]
and changes the block after the marker by -1, -1, -1, -1, +1, 0.
`carry_e` (e = 0..5): from M6 the first marker goes back to M0 (its block gains 1) and the next marker moves from
M_e to M_(e+1), its block changing as in `digit_e`.
The rules hold for every x, y, z and every tape R to the right (the head never reaches R).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RD_0LC0LB_0RE0LD_1LB0RB_1RF---_0RA0RC"
NS = "H63822"
MK = ["0", "001", "00110", "0010001", "0 (010)^2 10", "00101", "0011"]
AFTER = ["3", "3", "3", "3", "5", "4"]      # the block after a marker that moves on: y+4 becomes y+AFTER[d]


def rules():
    out = []
    for d in range(6):
        out.append((f"digit_{d}", f"0^inf B> (010)^x+1 {MK[d]} (010)^y+4 R",
                    f"0^inf B> (010)^x+2 {MK[d + 1]} (010)^y+{AFTER[d]} R",
                    f"Digit {d} to {d + 1}: `B> [x+1] M{d} [y+4]` to `B> [x+2] M{d + 1} [y+{AFTER[d]}]`."))
    for e in range(6):
        out.append((f"carry_{e}", f"0^inf B> (010)^x+1 {MK[6]} (010)^y+4 {MK[e]} (010)^z+4 R",
                    f"0^inf B> (010)^x+2 {MK[0]} (010)^y+5 {MK[e + 1]} (010)^z+{AFTER[e]} R",
                    f"Carry into digit {e}: `B> [x+1] M6 [y+4] M{e} [z+4]` to `B> [x+2] M0 [y+5] M{e + 1} [z+{AFTER[e]}]`."))
    return out


def main():
    ths = [prove(M, name, a, b, doc=doc, max_moves=200000)[0] for name, a, b, doc in rules()]
    sys.stdout.write(rules_file("Machine", NS, ths, f"The odometer of {M}, generated by `py/rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
