"""Generate lean/Events.lean for 1RB0LD_0LC0RE_1LA0RD_0RB0LD_1RC1RF_1RA--- (usage: python3 py/events.py > lean/Events.lean).

The event rules of the first regime ("phase 1" shape), each for every size, proved by `bbtools.symtm.prove` along the
symbolic trace (shift rules by `cross_l`/`cross_r`, re-bracketings by `rep_rotate`).

Event = the head in state A on the cell just right of the engine (absolute cell 65).  Left of the head: H (binary,
4-cell digits 0100 = 0, 0101 = 1, most significant first), the marker 0110, the low counter (binary, 1000 = 0,
1010 = 1).  Right of the head: a phase triple (111 or 110) and the right counter R (base 3, digits 001 = 0, 011 = 1,
010 = 2, least significant first), ended by the cells 0 1 and blank tape.

A 111-event adds 1 to the low counter, a 110-event adds 2 to it and 1 to R; when the low counter overflows, H gets 3.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LD_0LC0RE_1LA0RD_0RB0LD_1RC1RF_1RA---"
D0, D1 = "1 0 0 0", "1 0 1 0"          # low digits 0, 1
H0, H1 = "0 1 0 0", "0 1 0 1"          # H digits 0, 1
MK = "0 1 1 0"

RULES = []
# low +1 (111-event), carry over n ones
RULES.append(("ev111", f"L {D0} (1010)^n A> 1 1 1 R", f"L {D1} (1000)^n A> 1 1 0 R",
              "111-event: the low counter gets 1 (carry over n ones); the phase triple becomes 110."))
# low +2 and R +1 (110-event)
for xn, X in (("0", D0), ("1", D1)):
    RULES.append((f"ev110_{xn}_r0", f"L {D0} (1010)^n {X} A> 1 1 0 (010)^k 0 0 1 R",
                  f"L {D1} (1000)^n {X} A> 1 1 1 (001)^k 0 1 1 R",
                  "110-event: the low counter gets 2, R gets 1 (carry over k digits 2, then a digit 0 becomes 1)."))
    RULES.append((f"ev110_{xn}_r1", f"L {D0} (1010)^n {X} A> 1 1 0 (010)^k 0 1 1 R",
                  f"L {D1} (1000)^n {X} A> 1 1 1 (001)^k 0 1 0 R",
                  "110-event: the low counter gets 2, R gets 1 (carry over k digits 2, then a digit 1 becomes 2)."))
    RULES.append((f"ev110_{xn}_rend", f"L {D0} (1010)^n {X} A> 1 1 0 (010)^k 0 1 0^inf",
                  f"L {D1} (1000)^n {X} A> 1 1 1 (001)^k 0 0 1 0 1 0^inf",
                  "110-event at R = 22...2: R gets one more digit (the right end of the tape moves 3 cells)."))
# low overflow: H gets 3 (four cases of H mod 4; carry over j ones of H/4)
HC = [("r0", f"{H0} {H0}", f"{H1} {H1}", False),
      ("r1", f"{H0} (0101)^j {H0} {H1}", f"{H1} (0100)^j {H0} {H0}", True),
      ("r2", f"{H0} (0101)^j {H1} {H0}", f"{H1} (0100)^j {H0} {H1}", True),
      ("r3", f"{H0} (0101)^j {H1} {H1}", f"{H1} (0100)^j {H1} {H0}", True)]
RC = [("0", "0 0 1 R", "0 1 1 R"), ("1", "0 1 1 R", "0 1 0 R"), ("e", "0 1 0^inf", "0 0 1 0 1 0^inf")]
LOW = [("a", "(1010)^n A> 1 1 1 R", "(1000)^n A> 1 1 0 R", "a 111-event on low = 1...1")]
for xn, X, xd in (("b", D0, "1...10"), ("c", D1, "1...11")):
    for rn, rs, re_ in RC:
        LOW.append((xn + rn, f"(1010)^n {X} A> 1 1 0 (010)^k {rs}", f"(1000)^n {X} A> 1 1 1 (001)^k {re_}",
                    f"a 110-event on low = {xd}"))
for hn, hs, he, _ in HC:
    for ln, ls, le, ld in LOW:
        RULES.append((f"ovf_{hn}_{ln}", f"L {hs} {MK} {ls}", f"L {he} {MK} {le}",
                      f"Low overflow, {ld}: the low counter wraps and H gets 3 (H = {hn[1]} mod 4)."))


def theorems():
    out = []
    for name, s, e, doc in RULES:
        out.append(prove(M, "t_" + name, s, e, doc=doc, rotate=True, count_first=True, max_seg=200)[0])
    return out


if __name__ == "__main__":
    sys.stdout.write(rules_file("Machine", "H122751", theorems(),
                                f"Event rules of {M} (first regime), generated by `py/events.py`; do not edit by hand."))
