"""Shift rules of 1RB0LB_1RC0LD_0LA1RD_1LC1LE_1LF0RE_1LD---, proved in Lean from the symbolic trace (`tools/py/bbtools/symtm.py`).

usage: python3 holdouts/1RB0LB_1RC0LD_0LA1RD_1LC1LE_1LF0RE_1LD---/py/rules.py        writes lean/Rules.lean (checked by lean/check.sh)

Each rule is (name, start, end, doc) in the syntax of `bbtools.symtm.Config.parse`: `L 1 0 C> (10)^n R` is the head
in state C on the first cell after `C>`, `(w)^n` the word w repeated n times, L and R unknown tape.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB0LB_1RC0LD_0LA1RD_1LC1LE_1LF0RE_1LD---"
NS = "H33448"
DOC = """# Shift rules of 1RB0LB_1RC0LD_0LA1RD_1LC1LE_1LF0RE_1LD---

Two fast moves of the machine: E moving right erases a run of 1s (`erase`), D moving left turns each `100` into
`111` (`fill`).  The only halt is F reading a 1; F is entered from E reading a 0, so `1 0 D> 1` halts (D keeps the 1
and steps left, E writes a 1 and steps left onto a 1) (`halt_D`).

Generated by `py/rules.py` from symbolic runs (`tools/py/bbtools/symtm.py`); every proof is `rfl` steps, the
crossing lemmas `TM.cross_r`/`TM.cross_l` and `omega`, checked by Lean's kernel."""

RULES = [
    ('erase',
     'L E> (1)^n R',
     'L (0)^n E> R',
     'E erases a run of 1s moving right, one step a cell.'),
    ('fill',
     'L (100)^n D> 1 R',
     'L D> 1 (111)^n R',
     'D crosses `100` leftwards in three steps and leaves `111`.')
]

# hand-written statements appended to the file (the halting situations), proved by `rfl`
EXTRA = """/-- `1 0 D> 1` halts: D keeps its 1 and steps left in state E, E writes a 1 and steps left in state F onto a 1. -/
theorem halt_D (L R : Tape) :
    ∃ c, steps 2 ⟨cons false (cons true L), cons true R, .D⟩ = some c ∧ step c = none :=
  ⟨_, rfl, rfl⟩
"""


def main():
    thms = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    with open(os.path.join(HERE, "..", "lean", "Rules.lean"), "w") as f:
        f.write(rules_file("Machine", NS, thms + [EXTRA], DOC))


if __name__ == "__main__":
    main()
