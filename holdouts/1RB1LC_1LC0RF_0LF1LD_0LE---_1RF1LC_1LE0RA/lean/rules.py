"""Generate Rules.lean: the round of 1RB1LC_1LC0RF_0LF1LD_0LE---_1RF1LC_1LE0RA, proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(110)^n` is n
copies of 110, R is any tape, 0^inf blank tape.  During a phase the tape is  0^inf F> 0 0 (110)^X 1^Y T.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1LC_1LC0RF_0LF1LD_0LE---_1RF1LC_1LE0RA"

RULES = [
    ("round", "0^inf F> 0 0 (110)^x 1^y+5 R",
     "0^inf F> 0 0 (110)^x+2 1^y+1 R",
     "One round (two visits of the left end): two words 110 more, four ones fewer, in 12x + 26 steps, whatever R is.",
     {"rotate": True}),
]


def main():
    ths = [prove(M, name, a, b, doc=doc, count_first=True, max_seg=60, **kw)[0] for name, a, b, doc, kw in RULES]
    out = rules_file("Machine", "H126128", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand.")
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
