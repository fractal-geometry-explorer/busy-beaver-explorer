"""Event rules of 1RB---_1RC0LE_0LD0RF_1LB0RE_0RC0LE_1RD1RA, proved for all sizes
(python3 py/events.py lean > lean/Events.lean;  python3 py/events.py cov > c/rules.txt).

Event: the head in state D on cell 75 (cells counted from the start cell).  At an event the tape is
    ... [left] D> c1 c2 0 [R] ...
left: binary, 4-cell digits 0001 = 0, 0101 = 1, lowest digit next to the head;  c1 c2: a 2-bit phase
(00, 10, 01, 11 = 0, 1, 2, 3);  R: base 3, 3-cell digits 010 = 0, 110 = 1, 100 = 2, lowest digit first.
Phase 0 -> 1 and 2 -> 3: left + 1.  Phase 1 -> 2: left + 1 and R + 1.  Phase 3 -> 0: nothing else.
So every 4 events add 3 to the left counter and 1 to R.  MINED (py/mined.txt) are the rarer events.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "1RB---_1LC1RF_0LE0RD_0RB0LC_1RD0LD_0RC0RA", "py"))
from autoev import cov_line  # noqa: E402
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB---_1RC0LE_0LD0RF_1LB0RE_0RC0LE_1RD1RA"
HAND = [
    ("ph01", "L 0 0 0 1 (0101)^n D> 0 0 R", "L 0 1 (0100)^n 0 1 D> 1 0 R",
     "Phase 0 to 1: the left counter gets 1 (carry over n ones)."),
    ("ph23", "L 0 0 0 1 (0101)^n D> 0 1 R", "L 0 1 (0100)^n 0 1 D> 1 1 R",
     "Phase 2 to 3: the left counter gets 1 (carry over n ones)."),
    ("ph30", "L D> 1 1 0 R", "L D> 0 0 0 R", "Phase 3 to 0: nothing else changes."),
    ("ph12_r0", "L 0 0 0 1 D> 1 0 0 (100)^k 0 1 0 R", "L 0 1 0 1 D> 0 1 0 (010)^k 1 1 0 R",
     "Phase 1 to 2, low digit 0: the left counter gets 1; R gets 1 (k digits 2 carried, then a 0 becomes 1)."),
    ("ph12_r1", "L 0 0 0 1 D> 1 0 0 (100)^k 1 1 0 R", "L 0 1 0 1 D> 0 1 0 (010)^k 1 0 0 R",
     "Phase 1 to 2, low digit 0: the left counter gets 1; R gets 1 (k digits 2 carried, then a 1 becomes 2)."),
    ("ph12_c_r0", "L 0 0 0 1 0 (1010)^n 1 0 1 D> 1 0 0 (100)^k 0 1 0 R",
     "L 0 1 0 1 0 (0010)^n 0 0 1 D> 0 1 0 (010)^k 1 1 0 R",
     "Phase 1 to 2, carry over n+1 ones of the left counter; R gets 1 (then a 0 becomes 1)."),
    ("ph12_c_r1", "L 0 0 0 1 0 (1010)^n 1 0 1 D> 1 0 0 (100)^k 1 1 0 R",
     "L 0 1 0 1 0 (0010)^n 0 0 1 D> 0 1 0 (010)^k 1 0 0 R",
     "Phase 1 to 2, carry over n+1 ones of the left counter; R gets 1 (then a 1 becomes 2)."),
]


def mined():
    f = os.path.join(HERE, "mined.txt")
    if not os.path.exists(f):
        return []
    out = []
    for ln in open(f):
        p = ln.rstrip("\n").split("|")
        out.append((p[0], p[1], p[2], f"Mined rule ({p[4]}): {p[3]} steps."))
    return out


def theorems():
    return [prove(M, "t_" + n, s, e, doc=d, rotate=True, count_first=True, max_seg=40, max_moves=200000)[0]
            for n, s, e, d in HAND + mined()]


if __name__ == "__main__":
    if sys.argv[1:] == ["cov"]:
        for n, s, e, d in HAND + mined():
            print(cov_line(n, s))
    else:
        sys.stdout.write(rules_file("Machine", "H139516", theorems(),
                                    f"Event rules of {M}, generated by `py/events.py`; do not edit by hand."))
