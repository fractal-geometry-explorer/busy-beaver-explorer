"""The sweep rules of the wall-counter family 1RB0RC_1LC0RD_0LD0LC_1RE0LA_??????_??????, as Lean theorems.

usage: python3 wall_rules.py MACHINE > holdouts/MACHINE/lean/Walls.lean

At the sample point the head is at the left end of the tape in state D on the first 1 of the run of blocks 1000
(`0^inf D> (1000)^(x+1) W (1000)^(y+1) ...`).  One sweep (head right to the first wall, back to the left end) moves
the first wall W one step along its cycle of five shapes

    1001 -> 1001100 -> 100110 -> 10011 -> 10010 -> 1001

and the fourth step (10011 -> 10010) carries: the sweep goes on to the second wall and moves it one step too.
Each theorem is a run of the machine for every x, y (and z) and every tape R to the right, proved by `symtm.prove`
(single steps by `rfl`, runs of 1000 crossed by the library's shift lemmas, the step count by `omega`).  The end
configuration is stated the way the run writes it: `1 (0001)^x 0 0 0` is `(1000)^(x+1)` read with another
bracketing.  Lean is the judge.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "py"))
sys.path.insert(0, os.path.join(HERE, "..", ".."))

from bbtools import symtm  # noqa: E402
from bbtools.machine import Machine, STATES  # noqa: E402

PHASES = ["1001", "1001100", "100110", "10011", "10010"]
NAMES = {"1001": "w0", "1001100": "w1", "100110": "w2", "10011": "w3", "10010": "w4"}
D = STATES.index("D")


def sample(c):
    return (not c.steps.is_zero()) and c.state == D and len(c.left) == 1 and isinstance(c.left[0], symtm.Blank) \
        and c.right and c.right[0] == 1


def one_sweep(m, start):
    """The run from `start` to the next sample point (two returns to the left end: in D on a 0, then on a 1)."""
    c = symtm.Config.parse(start)
    c = symtm.run(m, c, sample, max_moves=20000, rotate=True)
    return c


def rules(text):
    m = Machine.parse(text)
    out = []
    for p in PHASES:
        if p == "10011":
            continue
        start = f"0^inf D> (1000)^x+1 {p} (1000)^y+1 R"
        end = one_sweep(m, start)
        nxt = PHASES[(PHASES.index(p) + 1) % 5]
        doc = f"One sweep with the first wall in shape `{p}`: it becomes `{nxt}` (the counts are in the statement)."
        lean, _ = symtm.prove(m, f"sweep_{NAMES[p]}", start, end, doc=doc, rotate=True, count_first=True, max_seg=200)
        out.append(lean)
    for q in PHASES:
        if q == "10011":
            continue
        start = f"0^inf D> (1000)^x+1 10011 (1000)^y+1 {q} (1000)^z+1 R"
        end = one_sweep(m, start)
        nq = PHASES[(PHASES.index(q) + 1) % 5]
        doc = (f"The carry: one sweep with the first wall in shape `10011` and the second in `{q}`; the first becomes "
               f"`10010` and the second `{nq}`.")
        lean, _ = symtm.prove(m, f"carry_{NAMES[q]}", start, end, doc=doc, rotate=True, count_first=True, max_seg=200)
        out.append(lean)
    return out


def lean_file(text):
    import gen  # holdouts/gen.py: the namespace from the triage row
    row = next(r for r in gen.load_triage() if r["machine"] == text)
    ns = gen.ns_of(row)
    doc = (f"# The sweep rules of {text}\n\nGenerated by `py/wall_rules.py` in the folder of 1RB0RC_1LC0RD_0LD0LC_1RE0LA_0RA0RF_0RD (the family's "
           f"script); do not edit by hand.  The walls `1001`, `1001100`, `100110`, `10011`, `10010` are the five "
           f"shapes of one digit of the base-5 counter (named w0..w4 in the theorem names); see the machine's README.")
    return symtm.rules_file("Machine", ns, rules(text), doc)


if __name__ == "__main__":
    sys.stdout.write(lean_file(sys.argv[1]))
