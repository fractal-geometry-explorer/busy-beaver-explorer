"""Write lean/Rules.lean for one machine of the 1RB1LA_1LC1RD_1LA0LC_1RE0RB_ family: the pass rules, each proved by
`bbtools.symtm.prove` (rfl steps and the crossing lemmas of tools/lean/TM/Basic.lean).

A *pass* starts with the head in state A on a 0 left of a block of 1s and ends at the next such configuration.
The end configuration of each rule is found by running the symbolic simulator from the start until the head is in
state A on a 0 again (or F reads a 1, the halting transition), so the statements below are exactly what Lean checks.

Usage (from the repository root):
  python3 holdouts/<this folder>/py/gen_rules.py MACHINE NAMESPACE > holdouts/MACHINE/lean/Rules.lean"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools import symtm
from bbtools.machine import Machine
from bbtools.symtm import prove, rules_file, Config, Rep

# (name, start, doc); `G` is the base gap (2 for E0 = 1RB, 4 for E0 = 1RF), `P` the gap period (3 or 5)
def rules(G, P):
    z = "0" * (P - 1) + "1"       # one gap of the base size followed by a single 1 that D turns into 1s
    return [
        ("pass_even", f"L 1 A> 0 (11)^k+2 0^g+{G} 1 R",
         "Even top block of length 2k+4: two 1s move to the left part, (01)^k is left behind, the first gap shrinks by one."),
        ("pass_even2", f"L 0 1^a A> 0 1^2 0^g+{G} 1 R",
         "Top block of length 2: the block merges with the 1s on its left and the head returns to the 0 left of them."),
        ("pass_odd", f"L 1 A> 0 (11)^k+2 1 ({z})^j 0^g+{P} 1 R",
         "Odd top block of length 2k+5: D crosses the j small gaps, each becomes 1s, then a gap of length 3j+3 opens."),
        ("pass_odd3", f"L 0 1^b+1 A> 0 1^3 ({z})^j 0^g+{P} 1 R",
         "Top block of length 3: as pass_odd, and the head returns to the 0 left of the merged block."),
        ("pass_even_g1", "L 1 A> 0 (11)^k+2 0 1 1 R",
         "An even top block in front of a gap of length one: the gap is filled and the pass ends normally."),
        ("pass_odd_halt", f"L 1 A> 0 (11)^k+2 1 ({z})^j {'0 1 1' if G == 2 else '0 0 1'} R",
         "Odd top block whose D-run, after the small gaps, meets a gap one cell too short: F reads a 1, the halting transition."),
    ]

def first_stop(m, start, max_moves=2000):
    cfg = Config.parse(start)
    seen = [0]
    def stop(c):
        seen[0] += 1
        if seen[0] == 1:
            return False
        t = c.right[0] if c.right else None
        lit0 = t == 0 or (isinstance(t, Rep) and t.word[0] == 0 and t.n.surely_ge(1))
        lit1 = t == 1 or (isinstance(t, Rep) and t.word[0] == 1 and t.n.surely_ge(1))
        return (c.state == 0 and lit0) or (c.state == 5 and lit1)
    fin = symtm.run(m, cfg, stop, max_moves=max_moves)
    return repr(fin)

def main():
    M, ns = sys.argv[1], sys.argv[2]
    m = Machine.parse(M)
    G, P = (2, 3) if M.split("_")[4].startswith("1RB") else (4, 5)
    ths = []
    extra = []
    if G == 2:   # 1a (F0 = 0RB) and 1b (F0 = 1RC) agree whenever F reads a 0 followed by a 0
        for x in "01":
            extra.append((f"f00_{x}", f"L {x} F> 0 0 R", f"L A> {x} 1 1 R",
                          "F on a 0 followed by a 0: three steps later A reads the cell left of it and two 1s follow; the same for F0 = 0RB and F0 = 1RC."))
    for name, start, end, doc in extra:
        t, fin = prove(M, name, start, end, nsteps=3, doc=doc)
        print(f"-- {name}: {start}  ->  {end}", file=sys.stderr)
        ths.append(t)
    for name, start, doc in rules(G, P):
        try:
            end = first_stop(m, start)
            t, fin = prove(M, name, start, end, doc=doc + f"  (Ends at `{end}`.)")
        except Exception as e:
            print(f"-- {name}: not proved ({type(e).__name__})", file=sys.stderr)
            continue
        print(f"-- {name}: {start}  ->  {end}", file=sys.stderr)
        ths.append(t)
    print(rules_file("Machine", ns, ths,
                     "Pass rules of the 1RB1LA_1LC1RD_1LA0LC_1RE0RB_ family, generated by `py/gen_rules.py` of "
                     "holdouts/1RB1LA_1LC1RD_1LA0LC_1RE0RB_1RB0RF_0RB--- with `tools/py/bbtools/symtm.py`; do not edit by hand."), end="")

if __name__ == "__main__":
    main()
