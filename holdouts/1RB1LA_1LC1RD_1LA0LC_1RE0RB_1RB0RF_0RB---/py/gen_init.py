"""Generate lean/Init.lean for a machine of the 1RB1LA_1LC1RD_1LA0LC_1RE0RB_ family: the blank-tape run reaches a
mode-5 counter configuration C5 (Counter.lean), and the first countdown from there.

usage: python3 gen_init.py MACHINE NS STEPS P E N   (run from anywhere; writes holdouts/MACHINE/lean/Init.lean)
The list configuration after STEPS steps is computed here by the same list semantics as TM.fsteps, and checked by
Lean (`decide`); the bit reading P, E, N is checked by `rfl`."""
import os, sys

def fsteps(M, n):
    rows = M.split('_'); l, r, s = [], [], 0
    for _ in range(n):
        y = r[0] if r else 0
        t = rows[s][3 * y:3 * y + 3]
        assert t[2] != '-', 'halts'
        w, d, s2 = int(t[0]), t[1], ord(t[2]) - 65
        rt = r[1:]
        if d == 'R': l, r = [w] + l, rt
        else: l, r = l[1:], [(l[0] if l else 0), w] + rt
        s = s2
    assert s == 0
    return l, r

def b(xs): return '[' + ', '.join('true' if x else 'false' for x in xs) + ']'

M, NS, STEPS, P, E, N = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6])
l, r = fsteps(M, STEPS)
n0 = max(1, N.bit_length())
nf = (N + 2 * E).bit_length()
B5 = 56 if M.split('_')[4] in ('1RF0LE', '1RF1RC') else 48
src = f'''import Counter

/-! The blank-tape run enters the counter of Counter.lean. Generated by `py/gen_init.py` of
holdouts/1RB1LA_1LC1RD_1LA0LC_1RE0RB_1RB0RF_0RB---; do not edit by hand. -/

namespace {NS}

open TM

theorem bitsN_zero : ∀ k : Nat, bitsN k 0 = List.replicate k false
  | 0 => rfl
  | k + 1 => by rw [bitsN, bitsN_zero k]; rfl

/-- A number below `2^m` written in more bits only gains zero bits at the top. -/
theorem bitsN_pad : ∀ (m x : Nat), x < 2 ^ m → ∀ k, bitsN (m + k) x = bitsN m x ++ List.replicate k false
  | 0, x, h, k => by
    have : x = 0 := by simp at h; omega
    subst this; simp [bitsN_zero, bitsN]
  | m + 1, x, h, k => by
    rw [show m + 1 + k = (m + k) + 1 by omega, bitsN, bitsN,
      bitsN_pad m (x / 2) (by rw [Nat.pow_succ] at h; omega) k]
    rfl

theorem Rbits_append : ∀ (v w : List Bool) (X : Tape), Rbits (v ++ w) X = Rbits v (Rbits w X)
  | [], _, _ => rfl
  | false :: v, w, X => by rw [List.cons_append, Rbits, Rbits, Rbits_append v w X]
  | true :: v, w, X => by rw [List.cons_append, Rbits, Rbits, Rbits_append v w X]

theorem fin_init : fsteps {STEPS} (FCfg.blank .A) =
    some ⟨{b(l)},
      {b(r)}, .A⟩ := by decide

/-- After {STEPS} steps from blank tape the machine is in mode 5 with E = {E} ({P} bits, floor `1^2`) and N = {N}, for
every width of N that holds it. -/
theorem init_counter (k : Nat) : steps {STEPS} init = some (C5 {P} ({n0} + k) {E} {N} (cons true blank) blank) := by
  have h : steps {STEPS} init = some (FCfg.toCfg ⟨{b(l)},
      {b(r)}, .A⟩) := TM.blank_reaches trans fin_init
  rw [h]
  unfold C5
  rw [bitsN_pad {n0} {N} (by decide) k, Rbits_append, Rbits_zero_blank]
  rfl

/-- The first mode-5 countdown, from blank tape: E = {E} runs down to 0 while N goes up to {N + 2 * E}. -/
theorem first_countdown :
    ReachGE init (C5 {P} {nf} 0 {N + 2 * E} (cons true blank) blank) ({STEPS} + {B5} * {E}) := by
  have h0 : ReachGE init (C5 {P} {nf} {E} {N} (cons true blank) blank) {STEPS} :=
    ⟨{STEPS}, Nat.le_refl _, init_counter {nf - n0}⟩
  exact reachGE_trans h0 (run5 {P} {nf} _ _ {E} {E} {N} (Nat.le_refl _) (by decide) (by decide))

end {NS}
'''
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', '..', M, 'lean', 'Init.lean')
open(out, 'w').write(src)
print('wrote', os.path.normpath(out))
