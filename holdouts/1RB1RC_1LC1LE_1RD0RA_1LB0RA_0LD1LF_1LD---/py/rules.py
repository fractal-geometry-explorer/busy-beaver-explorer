"""Writes lean/Rules.lean: one wall-to-wall cycle of the counter dynamics, for every parity of the last two counters
and both kinds of separator, each proved by bbtools.symtm (shift rules, `rfl`, `omega`).

(10)^c is written (1010)^a for c = 2a and (1010)^a 1 0 for c = 2a + 1; L is any tape.  The visit is A at the right
end of the tape (A> 0^inf).

usage: python3 rules.py > ../lean/Rules.lean
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/py"))
from bbtools.symtm import prove, rules_file, run, Config, Blank
from bbtools.machine import Machine

M = "1RB1RC_1LC1LE_1RD0RA_1LB0RA_0LD1LF_1LD---"
NS = "H16609"

RULES = [
    ("sep0_ce_ke", "sep 0, c = 2a+2 even, k = 2b even: c loses 1, k gains 3.",
     "L 0 (1010)^a+1 0 (1010)^b A> 0^inf"),
    ("sep0_co_ke", "sep 0, c = 2a+1 odd, k = 2b even: c loses 1, k gains 3.",
     "L 0 (1010)^a 1 0 0 (1010)^b A> 0^inf"),
    ("sep0_ce_ko", "sep 0, c = 2a+2 even, k = 2b+1 odd: the carry passes c, the counter z left of c loses 1, k gains 3.",
     "L 0 (1010)^z+1 0 (1010)^a+1 0 (1010)^b 1 0 A> 0^inf"),
    ("sep0_ce_ko_zodd", "the same with z = 2z'+1 odd.",
     "L 0 (1010)^z 1 0 0 (1010)^a+1 0 (1010)^b 1 0 A> 0^inf"),
    ("sep1_ce_ke", "sep 1, c even, k even: the separator becomes 0, k gains 2.",
     "L 0 (1010)^a+1 1 (1010)^b A> 0^inf"),
    ("sep1_co_ke", "sep 1, c odd, k even: the separator becomes 0, k gains 2.",
     "L 0 (1010)^a 1 0 1 (1010)^b A> 0^inf"),
    ("sep1_ce_ko", "sep 1, c even, k odd: the separator becomes 0, c loses 1, k gains 3.",
     "L 0 (1010)^a+1 1 (1010)^b 1 0 A> 0^inf"),
    ("sep1_co_ko", "sep 1, c odd, k odd: the separator becomes 0, c loses 1, k gains 3.",
     "L 0 (1010)^a 1 0 1 (1010)^b 1 0 A> 0^inf"),
]


def end_of(start):
    m = Machine.parse(M)
    c = Config.parse(start)
    first = [True]

    def stop(cc):
        if first[0]:
            first[0] = False
            return False
        return cc.state == 0 and len(cc.right) == 1 and isinstance(cc.right[0], Blank)
    run(m, c, stop, rotate=True)
    return c


def main():
    thms = []
    for name, doc, start in RULES:
        fin = end_of(start)
        t, _ = prove(M, name, start, fin, doc=doc, rotate=True, count_first=True, max_seg=60)
        thms.append(t)
    print(rules_file("Machine", NS, thms,
                     "One cycle (A at the right end to A at the right end) of the counter dynamics, every parity case "
                     "of the last two counters. Generated by `py/rules.py`."), end="")


if __name__ == "__main__":
    main()
