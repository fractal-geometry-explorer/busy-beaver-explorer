"""Write a solution of satctl.py as a Lean proof that the machine never halts.

usage: python3 tools/py/satctl_lean.py MACHINE NAMESPACE CERT.json > SatCTL.lean
(CERT.json is the JSON line satctl.py prints; the file imports the machine's Machine.lean.)"""
import sys, json
import os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from satctl import parse
m, ns, cj = sys.argv[1], sys.argv[2], sys.argv[3]
C=json.load(open(cj)); DL, DR = C['DL'], C['DR']
T=parse(m); nL=len(DL); nR=len(DR)
predR={(r,b):[rp for rp in range(nR) if r in DR[rp][b]] for r in range(nR) for b in (0,1)}
predL={l:[(lp,c) for lp in range(nL) for c in (0,1) if l in DL[lp][c]] for l in range(nL)}
seen={(0,0,0)}; todo=[(0,0,0)]
while todo:
    q,l,r=todo.pop()
    for b in (0,1):
        for rp in predR[(r,b)]:
            tr=T[(q,b)]; assert tr is not None, 'halt reachable'
            w,d,q2=tr
            nxt=[(q2,l2,rp) for l2 in DL[l][w]] if d=='R' else [(q2,lp,r3) for (lp,c) in predL[l] for r2 in DR[rp][w] for r3 in DR[r2][c]]
            for x in nxt:
                if x not in seen: seen.add(x); todo.append(x)
S=sorted(seen)
def edges(D):
    out=[]
    for i in range(len(D)):
        for c in (0,1):
            for j in D[i][c]: out.append((j,c,i))
    return sorted(set(out))
def wrap(items, per=8):
    lines=[]
    for k in range(0,len(items),per): lines.append('  '+', '.join(items[k:k+per]))
    return '[\n'+',\n'.join(lines)+']'
def auto(D):
    return '⟨'+wrap([f"({a}, {'true' if x else 'false'}, {b})" for a,x,b in edges(D)])+',\n  [0]⟩'
St='ABCDEF'
print(f"""import Machine

/-!
# A closed tape language for {m} (two automata found by SAT)

Each side of the head is read outward from the head (nearest cell first) by a nondeterministic automaton; state 0
accepts the blank tape.  The automata were found by a SAT search (`tools/py/satctl.py`, the two-automaton closed tape
language search) and the set of {len(S)} abstract configurations is the least set containing the start and closed
under the table.  `TM.CTL.not_halts` turns the three checks below, evaluated by Lean's kernel, into a proof that the
machine never halts from blank tape.  Generated by `tools/py/satctl_lean.py`; do not edit by hand.
-/

namespace {ns}

open TM TM.CTL

/-- The left automaton ({nL} states), nearest cell first. -/
def satL : TM.CTL.Auto := {auto(DL)}

/-- The right automaton ({nR} states), nearest cell first; the head cell is the first cell read. -/
def satR : TM.CTL.Auto := {auto(DR)}

/-- The {len(S)} abstract configurations (state, left automaton state, right automaton state). -/
def satS : List (St × Nat × Nat) := {wrap([f"(.{St[q]}, {l}, {r})" for q,l,r in S])}

theorem sat_closed : TM.CTL.closed trans satL satR satS = true := by decide
theorem sat_starts : TM.CTL.starts satL satR satS .A = true := by decide
theorem sat_noHalt : TM.CTL.noHalt trans satR satS = true := by decide

/-- The machine never halts from blank tape. -/
theorem nonhalt : ¬ HaltsFromBlank := TM.CTL.not_halts trans sat_closed sat_starts sat_noHalt

end {ns}""")
