"""Write the Lean definition of a machine, for the shared library in tools/lean (TM.*).

usage: python3 -m bbtools.leangen MACHINE NAMESPACE > Machine.lean

The file defines the states `St`, the table `trans` (by `match`, so single steps reduce by `rfl` and `decide`) and
short names for the library's functions specialised to this machine.  The table is generated, never typed: the
test `tests/test_tools.py` parses the generated file back and compares it with the machine string.
"""
import sys

from .machine import Machine, STATES


def machine_lean(text, ns, doc=None):
    m = Machine.parse(text)
    names = STATES[:m.n]
    B = {0: "false", 1: "true"}
    rows = []
    for s in range(m.n):
        for y in (0, 1):
            t = m.table[s][y]
            rhs = "none" if t is None else f"some ({B[t[0]]}, .{'R' if t[1] == 1 else 'L'}, .{names[t[2]]})"
            rows.append(f"  | .{names[s]}, {B[y]} => {rhs}")
    halts = ", ".join(m.halting_transitions()) or "none"
    doc = doc or f"The machine {m.text}."
    return f"""import TM

/-!
# {m.text}

{doc}

Generated by `tools/py/bbtools/leangen.py`; do not edit by hand.  Halting transitions: {halts}.
-/

namespace {ns}

open TM

/-- The states. -/
inductive St where
  | {' | '.join(names)}
  deriving DecidableEq, Repr

/-- The transition table of {m.text}: (write, move, next state); `none` halts. -/
def trans : St → Bool → Option (Bool × Dir × St)
{chr(10).join(rows)}

/-- The machine's text form, as the table above was generated from. -/
def text : String := "{m.text}"

abbrev Config := TM.Cfg St
abbrev step := TM.step trans
abbrev steps := TM.steps trans
abbrev fstep := TM.fstep trans
abbrev fsteps := TM.fsteps trans
/-- The configuration of the run from blank tape. -/
abbrev init : Config := TM.blankCfg .A
/-- The machine halts from blank tape. -/
abbrev HaltsFromBlank : Prop := TM.Halts trans init

end {ns}
"""


def parse_lean_table(src):
    """Read the `trans` rows of a generated file back into the standard text form (for the round-trip test)."""
    import re
    rows = re.findall(r"\| \.([A-J]), (false|true) => (none|some \((false|true), \.(L|R), \.([A-J])\))", src)
    table = {}
    for s, y, rhs, w, d, nx in rows:
        table[s, y == "true"] = "---" if rhs == "none" else f"{int(w == 'true')}{d}{nx}"
    states = sorted({s for s, _ in table})
    return "_".join(table[s, False] + table[s, True] for s in states)


if __name__ == "__main__":
    print(machine_lean(sys.argv[1], sys.argv[2]), end="")
