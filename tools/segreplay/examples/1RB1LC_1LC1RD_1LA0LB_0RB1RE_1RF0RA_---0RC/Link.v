(** Joining a generated replay to a proof on the tape, on the example of
    1RB1LC_1LC1RD_1LA0LB_0RB1RE_1RF0RA_---0RC.

    [Visits.op] is the map on natural numbers that the busycoq proof of this machine relates to the tape
    ([Rules.v] there, and [halts_of_orbit]: if [opIter k (2, 9) = Some (a, 3)] the machine halts).  [Map.opz] is
    the map generated by segreplay from specs/1RB1LC_1LC1RD_1LA0LB_0RB1RE_1RF0RA_---0RC.json.  This file proves
    that they are the same map, so that a halt found by a replay of [opz] is an orbit of [op] ending in
    (a, 3): exactly the hypothesis of [halts_of_orbit]. *)
From Coq Require Import ZArith Lia PeanoNat Bool.
From SegReplay Require Import Core.
From M Require Import Map Visits.
Local Open Scope Z_scope.
Ltac Zify.zify_convert_to_euclidean_division_equations_flag ::= constr:(true).

Definition zn (a b : nat) : ZS := zmk 0 (Z.of_nat a) (Z.of_nat b).

Lemma even_mod a : Nat.even a = (Z.of_nat a mod 2 =? 0).
Proof.
  destruct (Nat.even a) eqn:E; symmetry.
  - apply Nat.even_spec in E. destruct E as [k ->]. apply Z.eqb_eq. lia.
  - apply Z.eqb_neq. intro H. assert (O : Nat.odd a = true) by (rewrite <- Nat.negb_even, E; reflexivity).
    apply Nat.odd_spec in O. destruct O as [k ->]. lia.
Qed.

Ltac nsplit := match goal with
  | |- context [(?x =? ?y)%nat] => destruct (Nat.eqb_spec x y)
  | |- context [(?x <=? ?y)%nat] => destruct (Nat.leb_spec x y)
  end.
Ltac zsplit := match goal with
  | |- context [(?x =? ?y)%Z] => destruct (Z.eqb_spec x y)
  | |- context [(?x <=? ?y)%Z] => destruct (Z.leb_spec x y)
  | |- context [(?x <? ?y)%Z] => destruct (Z.ltb_spec x y)
  end; cbn [andb].

(** One visit: the two maps agree, and [op] stops exactly where [opz] halts. *)
Lemma op_opz a b :
  match op (a, b) with
  | Some (a', b') => opz (zn a b) = zn a' b'
  | None => b = 3%nat /\ ztg (opz (zn a b)) = 1
  end.
Proof.
  unfold op, zn, opz, opz_0. rewrite even_mod. change (0 =? 0) with true. cbv iota.
  repeat nsplit; try destruct (Z.of_nat a mod 2 =? 0) eqn:Ev;
    repeat zsplit; try lia; try (split; [lia|reflexivity]); try (f_equal; lia);
    try (rewrite Z.eqb_eq in Ev; lia); try (rewrite Z.eqb_neq in Ev; lia).
Qed.

(** A replay that ends in the halted state gives an orbit of [op] that ends in some (a, 3). *)
Lemma halt_orbit k : forall a b, ztg (zit opz k (zn a b)) = 1 -> exists j a', opIter j (a, b) = Some (a', 3%nat).
Proof.
  induction k as [|k IH]; intros a b H.
  - discriminate H.
  - cbn [zit] in H. pose proof (op_opz a b) as O. destruct (op (a, b)) as [[a1 b1]|] eqn:E.
    + rewrite O in H. destruct (IH a1 b1 H) as (j & a' & J). exists (S j), a'. cbn [opIter]. rewrite E. exact J.
    + destruct O as [-> _]. exists O, a. reflexivity.
Qed.
