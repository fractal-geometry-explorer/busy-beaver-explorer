#!/usr/bin/env python3
"""Turn the `next` frame map of a machine's lean/Phases.lean into a C rule table (rules.h) and a Python reference.

usage: python3 gen.py MACHINE > rules.h       (MACHINE = TNF name, read from holdouts/MACHINE/lean/Phases.lean)
Each rule: constructor, per-argument pattern (literal n, or variable + k meaning arg >= k), result constructor (or
none = halt), and each result argument as const + sum coef * variable. First matching rule wins, as in Lean.
"""
import os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

def split_args(s):
    out, depth, cur = [], 0, ""
    for ch in s.strip():
        if ch == "(":
            depth += 1
            if depth == 1: continue
        if ch == ")":
            depth -= 1
            if depth == 0: out.append(cur.strip()); cur = ""; continue
        if depth == 0 and ch == " ":
            if cur.strip(): out.append(cur.strip())
            cur = ""; continue
        cur += ch
    if cur.strip(): out.append(cur.strip())
    return out

def parse(machine):
    src = open(os.path.join(REPO, "holdouts", machine, "lean", "Phases.lean")).read()
    ctors = re.findall(r"^  \| (\w+) \(([\w ]+) : Nat\)", src.split("inductive Ph where")[1].split("deriving")[0], re.M)
    names = [c for c, _ in ctors]; arity = {c: len(a.split()) for c, a in ctors}
    body = src.split("def next : Ph → Option Ph")[1].split("\n\n")[0]
    rules = []
    for line in body.strip().splitlines():
        m = re.match(r"\s*\| \.(\w+) (.*?) => (none|some \(\.(\w+) (.*)\))$", line)
        assert m, line
        c, pats, res, rc, rargs = m.groups()
        pat = []
        for p in split_args(pats):
            if re.fullmatch(r"\d+", p): pat.append(("lit", int(p), None))
            else:
                mm = re.fullmatch(r"(\w+)(?: \+ (\d+))?", p); assert mm, p
                pat.append(("var", int(mm.group(2) or 0), mm.group(1)))
        assert len(pat) == arity[c]
        out = None
        if res != "none":
            vidx = {v: i for i, (_, _, v) in enumerate(pat) if v}
            out = []
            for e in split_args(rargs):
                const, coef = 0, [0] * arity[c]
                for t in e.split("+"):
                    t = t.strip()
                    if re.fullmatch(r"\d+", t): const += int(t)
                    elif "*" in t:
                        a, v = [x.strip() for x in t.split("*")]; coef[vidx[v]] += int(a)
                    else: coef[vidx[t]] += 1
                out.append((const, coef))
            assert len(out) == arity[rc]
        rules.append((c, pat, rc if out is not None else None, out))
    return names, arity, rules

def ref_step(names, arity, rules, st):
    """unaccelerated reference: st = (ctor, args) -> new st, or None for halt"""
    c, a = st
    for rc, pat, oc, out in rules:
        if rc != c: continue
        if all((x == n) if k == "lit" else (x >= n) for (k, n, _), x in zip(pat, a)):
            if oc is None: return None
            vals = [x - n if k == "var" else 0 for (k, n, _), x in zip(pat, a)]
            return (oc, tuple(const + sum(cf * v for cf, v in zip(coef, vals)) for const, coef in out))
    raise ValueError(f"no rule for {st}")

def emit(machine):
    names, arity, rules = parse(machine)
    A = max(arity.values())
    o = [f"/* generated by gen.py from holdouts/{machine}/lean/Phases.lean */", f"#define NC {len(names)}",
         f"#define NA {A}", f"#define NR {len(rules)}",
         "static const char *CN[NC] = {" + ", ".join(f'"{n}"' for n in names) + "};",
         "static const int AR[NC] = {" + ", ".join(str(arity[n]) for n in names) + "};",
         "/* ctor, lit-mask, pat[NA], out ctor (-1 halt), const[NA], coef[NA][NA] */",
         "static const struct { int c, lit[NA], pat[NA], oc; long cst[NA]; long cf[NA][NA]; } RU[NR] = {"]
    for c, pat, oc, out in rules:
        lit = [1 if k == "lit" else 0 for k, _, _ in pat] + [0] * (A - len(pat))
        pv = [n for _, n, _ in pat] + [0] * (A - len(pat))
        cst = [x[0] for x in out] + [0] * (A - len(out)) if out else [0] * A
        cf = [x[1] + [0] * (A - len(x[1])) for x in out] + [[0] * A] * (A - len(out)) if out else [[0] * A] * A
        L = lambda v: "{" + ",".join(map(str, v)) + "}"
        o.append(f"  {{{names.index(c)}, {L(lit)}, {L(pv)}, {names.index(oc) if oc else -1}, {L(cst)}, {{{','.join(L(r) for r in cf)}}}}},")
    o.append("};")
    return "\n".join(o)

if __name__ == "__main__":
    print(emit(sys.argv[1]))
