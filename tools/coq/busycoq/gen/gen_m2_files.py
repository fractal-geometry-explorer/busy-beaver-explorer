def coqterm(a):
    """A Lean-style argument 'b+6', '2*q+1', 'x+y+6' as a Coq term."""
    t = g.term(a)
    return t


HDR = """From Coq Require Import Lists.List Lia PeanoNat NArith. Import ListNotations.
From BusyCoq Require Import SymForms.
Set Default Goal Selector "!".
Local Open Scope nat_scope.
"""

# ---------------------------------------------------------------- rules file
def rules_file():
    o = ["(** * 1RB0LE_1RC---_1RD1RE_1LA0RF_0RC0LA_0LC0RB (bbchallenge 113677): the machine, its phase forms and rules",
         "",
         "    Each form is a tape template (tokens: single cells and runs [w^n] with [n] linear in the form's",
         "    variables); [fX a b c] is the configuration at those numbers.  Each rule is checked by running the",
         "    symbolic runner of [SymRun] ([rules ... = true], evaluated by [vm_compute]); [rules_sound] turns that",
         "    into a statement about the machine for all values of the variables.  Generated by gen_m2_files.py from",
         "    the forms of py/ends.py and the rules of py/macro.py. *)", "", HDR,
         """Definition tm : TM := fun '(q, s) =>
  match q, s with
  | A, S0 => Some (S1, R, B)  | A, S1 => Some (S0, L, E)
  | B, S0 => Some (S1, R, C)  | B, S1 => None
  | C, S0 => Some (S1, R, D)  | C, S1 => Some (S1, R, E)
  | D, S0 => Some (S1, L, A)  | D, S1 => Some (S0, R, F)
  | E, S0 => Some (S0, R, C)  | E, S1 => Some (S0, L, A)
  | F, S0 => Some (S0, L, C)  | F, S1 => Some (S0, R, B)
  end.

Notation "c -->* c'" := (c -[ tm ]->* c') (at level 40).
Notation "c -->+ c'" := (c -[ tm ]->+ c') (at level 40).

Definition KK := 16.
Definition FUEL := Nat.pow 2 16.

Lemma tr : forall P Q P' Q', P -->* Q -> P = P' -> Q = Q' -> P' -->* Q'.
Proof. intros. subst. assumption. Qed.
Lemma trp : forall P Q P' Q', P -->+ Q -> P = P' -> Q = Q' -> P' -->+ Q'.
Proof. intros. subst. assumption. Qed.

(** ** The forms *)
"""]
    for f in g.FORMS:
        vs = g.fvars(f)
        s = g.FORMS[f](*vs)
        o.append("(** [%s] *)" % s)
        o.append("Definition %s_mc : MC := %s." % (f, g.form_mc(f)))
        o.append("Definition %s (%s : nat) : Q * tape := cden [%s] %s_mc." % (FN[f], " ".join(vs), "; ".join(vs), f))
        ps = " ".join("%s %s'" % (v, v) for v in vs)
        hs = " -> ".join("%s = %s'" % (v, v) for v in vs)
        o.append("Lemma %s_eq : forall %s, %s -> %s %s = %s %s." % (FN[f], ps, hs, FN[f], " ".join(vs), FN[f],
                                                                   " ".join(v + "'" for v in vs)))
        o.append("Proof. intros. subst. reflexivity. Qed.\n")
    o.append("(** ** The rules (start form and arguments, end form and arguments, as in py/macro.py) *)\n")
    for k, (f, a, tf, ta, st) in macro.RULES.items():
        rv = g.rule_vars(a)
        x = "[" + "; ".join(rv) + "]"
        s1, s2 = g.args_lin(a, rv), g.args_lin(ta, rv)
        lhs = "%s %s" % (FN[f], " ".join(coqterm(t) for t in a))
        rhs = "%s %s" % (FN[tf], " ".join(coqterm(t) for t in ta))
        o.append("(** %s steps. *)" % st)
        o.append("Lemma %s : forall %s, %s -->+ %s." % (k, " ".join(rv), lhs, rhs))
        o.append("Proof.")
        o.append("  intros %s." % " ".join(rv))
        o.append("  pose proof (rules_sound tm KK FUEL %s_mc %s %s_mc %s ltac:(vm_compute; reflexivity) %s) as H."
                 % (f, s1, tf, s2, x))
        o.append("  unfold %s, %s. eapply trp; [exact H | f_equal; evs_eq | f_equal; evs_eq]." % (FN[f], FN[tf]))
        o.append("Qed.\n")
    o.append("(** ** Equal forms *)\n")
    EQS = [('rf_odd', 'RF', ['a', '2*q+1', 'm'], 'RF2', ['a', 'q', 'm']),
           ('rf_even', 'RF', ['a', '2*q', 'm'], 'RF2e', ['a', 'q', 'm']),
           ('rg_even', 'RG', ['a', 'x', '2*q', 'm'], 'RG2', ['a', 'x', 'q', 'm']),
           ('rg_odd', 'RG', ['a', 'x', '2*q+1', 'm'], 'RG2o', ['a', 'x', 'q', 'm']),
           ('rg3_even', 'RG3', ['a', 'x', 'y', '2*q', 'm'], 'RG3p', ['a', 'x', 'y', 'q', 'm']),
           ('rg3_odd', 'RG3', ['a', 'x', 'y', '2*q+1', 'm'], 'RG3o', ['a', 'x', 'y', 'q', 'm']),
           ('t3_s1', 'T3', ['a', '0', '0', '0', 'z', 'c'], 'S1', ['a', 'z', 'c'])]
    for k, f, a, tf, ta in EQS:
        rv = g.rule_vars(a)
        x = "[" + "; ".join(rv) + "]"
        lhs = "%s %s" % (FN[f], " ".join(coqterm(t) for t in a))
        rhs = "%s %s" % (FN[tf], " ".join(coqterm(t) for t in ta))
        o.append("Lemma %s : forall %s, %s = %s." % (k, " ".join(rv), lhs, rhs))
        o.append("Proof.")
        o.append("  intros %s." % " ".join(rv))
        o.append("  pose proof (formeq_sound %s_mc %s %s_mc %s ltac:(vm_compute; reflexivity) %s) as H."
                 % (f, g.args_lin(a, rv), tf, g.args_lin(ta, rv), x))
        o.append("  unfold %s, %s. replace [%s] with (evs %s %s) by evs_eq." % (
            FN[f], FN[tf], "; ".join(coqterm(t) for t in a), g.args_lin(a, rv), x))
        o.append("  replace [%s] with (evs %s %s) by evs_eq. exact H." % (
            "; ".join(coqterm(t) for t in ta), g.args_lin(ta, rv), x))
        o.append("Qed.\n")
    o.append(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "m2_derived.v")).read())
    return "\n".join(o)


def nat(v):
    v = int(v)
    return str(v) if v < 5000 else "(N.to_nat %d%%N)" % v


ARGS = {"O": 3, "S1": 3, "T2": 4, "T3": 6, "RF": 3, "EF": 2, "U3": 5, "RG": 4, "RG3": 5}


def table_file():
    rows, esc = macro.replay(1e30)
    assert esc is None
    states = [(f, Pv) for _, f, Pv in rows]
    o = ["(** * 1RB0LE_1RC---_1RD1RE_1LA0RF_0RC0LA_0LC0RB: from blank tape to the last macro state before step 1e30",
         "",
         "    The first 29,301 steps (blank tape to [fO 14 37 11]) by the symbolic runner, then the branch table of",
         "    py/macro.py: %d moves, each a rule or a k-fold iterate with concrete arguments.  Large numbers are" % (len(states) - 1),
         "    written [N.to_nat n%N] and only compared by [lia], never computed in unary. *)", "",
         HDR, "From BusyCoq Require Import %s_Rules.\n" % P,
         'Notation "c -->* c\'" := (c -[ tm ]->* c\') (at level 40).',
         'Notation "c -->+ c\'" := (c -[ tm ]->+ c\') (at level 40).\n',
         "Definition blank_mc : MC := mkMC [] [] A.",
         "Lemma blank_O : c0 -->+ fO 14 37 11.",
         "Proof.",
         "  pose proof (rules_sound tm KK (Nat.pow 2 16) blank_mc [] O_mc [mkLin 14 []; mkLin 37 []; mkLin 11 []]",
         "    ltac:(vm_compute; reflexivity) []) as H.",
         "  exact H.",
         "Qed.\n"]
    for i, (f, Pv) in enumerate(states[:-1]):
        g2, Q = states[i + 1]
        t = table.term(f, list(Pv))
        lhs = "%s %s" % (FN[f], " ".join(nat(p) for p in Pv))
        rhs = "%s %s" % (FN[g2], " ".join(nat(p) for p in Q))
        o.append("Lemma move%d : %s -->* %s." % (i, lhs, rhs))
        if "t3_s1" in t:
            o.append("Proof. rewrite (t3_s1 %s %s %s). apply evstep_refl. Qed." % (nat(Pv[0]), nat(Pv[5]), nat(Pv[4])))
            continue
        m = re.fullmatch(r"(?:⟨_, )?([\w']+) ([\d ]+?)⟩?", t)
        name, args = m.group(1), m.group(2).split()
        app = "(%s %s)" % (name.replace("'", "_"), " ".join(nat(a) for a in args))
        if name.endswith("_iter"):
            o.append("Proof. eapply tr; [exact %s | apply %s_eq; lia | apply %s_eq; lia]. Qed." % (app, FN[f], FN[g2]))
        else:
            o.append("Proof. eapply tr; [apply progress_evstep; exact %s | apply %s_eq; lia | apply %s_eq; lia]. Qed."
                     % (app, FN[f], FN[g2]))
    last = states[-1]
    o.append("\nDefinition last_cfg : Q * tape := %s %s." % (FN[last[0]], " ".join(nat(p) for p in last[1])))
    o.append("Lemma table_run : fO 14 37 11 -->* last_cfg.")
    o.append("Proof.")
    o.append("  unfold last_cfg.")
    for i in range(len(states) - 2):
        o.append("  eapply evstep_trans; [exact move%d |]." % i)
    o.append("  exact move%d." % (len(states) - 2))
    o.append("Qed.\n")
    o.append("Lemma blank_last : c0 -->* last_cfg.")
    o.append("Proof. eapply evstep_trans; [apply progress_evstep; exact blank_O | exact table_run]. Qed.")
    return "\n".join(o), last


def lean_ineqs():
    src = open(os.path.join(M, "lean", "Closed.lean")).read()
    out = {}
    for m in re.finditer(r"def (g\w+) \(([\w ]+) : Nat\) : Prop :=\n((?:  .*\n)+)", src):
        lines = [l.strip().rstrip("∧").strip() for l in m.group(3).splitlines()]
        out[m.group(1)] = (m.group(2).split(), lines)
    return out


def bigc(s):
    """Write constants of 5000 or more as N.to_nat literals."""
    return re.sub(r"\b(\d{4,})\b", lambda mm: nat(mm.group(1)), s)


def closed_file(last):
    I = lean_ineqs()
    o = ["(** * 1RB0LE_1RC---_1RD1RE_1LA0RF_0RC0LA_0LC0RB never halts",
         "",
         "    [Good] (linear inequalities on the counts of the phase forms, from lean/Closed.lean) holds at the end of",
         "    the table, and from every [Good] configuration the machine reaches another one in at least one step",
         "    (one cycle iterate and one exit rule each).  So [progress_nonhalt] applies. *)", "",
         HDR, "From BusyCoq Require Import %s_Rules %s_Table.\n" % (P, P),
         'Notation "c -->* c\'" := (c -[ tm ]->* c\') (at level 40).',
         'Notation "c -->+ c\'" := (c -[ tm ]->+ c\') (at level 40).\n']
    for name, (vs, lines) in I.items():
        body = " /\\\n  ".join(bigc(l.replace("≤", "<=")) for l in lines)
        o.append("Definition %s (%s : nat) : Prop :=\n  %s." % (name, " ".join(vs), body))
    o.append(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "m2_closed.v")).read())
    o.append("Lemma good_last : Good last_cfg.")
    o.append("Proof. unfold last_cfg. apply good_T2. unfold gT2. repeat split; lia. Qed.\n")
    o.append("""Theorem nonhalt : ~ halts tm c0.
Proof.
  apply multistep_nonhalt with (c' := last_cfg); [exact blank_last |].
  apply progress_nonhalt with (P := Good); [| exact good_last].
  intros c Hc. destruct (good_step c Hc) as [c' [H1 H2]]. exists c'. split; assumption.
Qed.

Print Assumptions nonhalt.""")
    return "\n".join(o)


