"""Generate Rules.lean: the sweep rules of 1RB1RF_1LC0LB_1RE0LD_1LB0RF_0RA0RC_1RE---, each proved along a symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean      (tests/test_machine.py checks that the committed file is current)

Tapes are written left to right: `S>` is the head in state S on the next cell, `(w)^n` the word w repeated n times,
L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RF_1LC0LB_1RE0LD_1LB0RF_0RA0RC_1RE---"

RULES = [
    ("e_run", "L E> (10)^n R", "L (01)^n E> R",
     "E runs right over pairs `10`, shifting each one cell to the right (`E1 → 0RC`, `C0 → 1RE`), 2 steps a pair."),
    ("e_mark", "L E> 0 1 0 R", "L 0 1 1 E> R",
     "E at a block boundary `0 10` marks it: the pair after the 0 becomes `11`, and E goes on (`E0`, `A1`, `F0`)."),
    ("b_run", "L 1 (0101)^n B> 0 R", "L 1 B> 0 (0101)^n R",
     "B runs left over pairs, two at a time, shifting each one cell to the right (`B0 → 1LC`, `C1 → 0LD`, "
     "`D0 → 1LB`, `B1 → 0LB`), 4 steps per two pairs; in between, the head is in D."),
]

DOC = """# Sweep rules

Generated by `rules.py` (tools/py/bbtools/symtm.py); do not edit by hand.  The tape is made of pairs `10`; a sweep to
the right in E and a sweep to the left in B and D each shift the pairs they cross by one cell, and E marks each block
boundary it crosses, turning `0 10` into `0 11`.  An E that reaches `0 11` instead halts two steps later
(`Blank.lean`, `halt_shape`), so a mark left in E's way is the only way the machine can stop."""


def main():
    ths = [prove(M, name, s, e, doc=doc)[0] for name, s, e, doc in RULES]
    sys.stdout.write(rules_file("Machine", "BB6e", ths, DOC))


if __name__ == "__main__":
    main()
