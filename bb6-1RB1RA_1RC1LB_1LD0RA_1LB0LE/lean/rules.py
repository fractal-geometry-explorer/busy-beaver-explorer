"""Generate Rules.lean: the pieces of a pass of 1RB1RA_1RC1LB_1LD0RA_1LB0LE_1LF1LD_---0LD, proved along the symbolic
run (tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean      (tests/test_machine.py checks that the committed file is current)

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, `(11)^n` is n copies
of `11`, L and R are any tape.  How the pieces make a pass is in notes/LAB_NOTES.md ("the pass").
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RA_1RC1LB_1LD0RA_1LB0LE_1LF1LD_---0LD"

RULES = [
    ("a_sweep", "L A> 1^n R", "L 1^n A> R", "State A runs right over a block of ones."),
    ("b_sweep", "L 0 1^n B> 1 R", "L B> 0 1 1^n R", "State B runs left over a block of ones to the 0 before it."),
    ("start", "L A> 0 0 0 R", "L 1 D> 1 1 R",
     "A pass starts at the right end: three new ones, and D turns back onto the second."),
    ("de_sweep", "L 0 (11)^n D> 1 R", "L E> 0 (01)^n 0 R",
     "D and E run left, writing 0 and 1 in turn; over an odd stretch of ones E reaches the 0 before it."),
    ("de_sweep_odd", "L 0 1 (11)^n D> 1 R", "L D> 0 1 (01)^n 0 R",
     "The same over an even stretch: D reaches the 0 before it."),
    ("e_cross", "L 1 1 E> 0 R", "L D> 1 0 1 R",
     "E at a 0 with a 1 to its left: the sweep crosses into the block on the left, leaving `00`."),
    ("d_stop", "L 0 1^a+1 D> 0 R", "L 1 0 A> 1^a+1 R",
     "D at a 0: the sweep ends, the 0 before the block on the left moves one cell right, and A starts the zigzag."),
    ("zig", "L 0 1^p+1 A> 0 1 R", "L 1 0 1^p+2 A> R",
     "One round of the zigzag: a `0 1` on the right is absorbed and the 0 on the left moves one cell right."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "BB6d", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
