"""Write the kernel check of the return map below 2^62: lean/R62/Shard*.lean and lean/Return62.lean.

`explore (2^62) 200 60 5 4` in one kernel `decide` needs far more memory than a machine has (the kernel keeps what it
has reduced for the whole declaration), so the class a = 5 + 4u is cut into subclasses (`Plan.lean`: halves by the
parity of u, until each piece costs at most BUDGET symbolic passes), each piece is its own theorem
`Cov (2^62) p q` by `explore` and `decide +kernel`, the pieces are spread over SHARDS files that compile in parallel,
and `Return62.lean` puts them together with `Cov.split`.  How the cut is chosen does not matter for soundness: every
piece is checked by the kernel, and `Cov.split` is a theorem.

usage: LEAN=... LEAN_PATH=... python3 lean/return62.py [BUDGET [SHARDS [E]]]   (run from anywhere; needs out/Plan.olean)

E (default 62) is the exponent of the bound: E = 74 writes lean/R74/ and lean/Return74.lean, the same check below 2^74
(about 5.5 times the work; `check_return74.sh`).
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
F = 200
# per exponent: the name of the bound theorem on passes, and its statement's bound 3 * 2^(E-2) + 1
NAMES = {62: ("no_one_3e18_kernel", "3·2^60 + 1 ≈ 3.46·10¹⁸"), 74: ("no_one_1e22_kernel", "3·2^72 + 1 ≈ 1.42·10²²")}


def get_plan(budget, E):
    src = os.path.join(HERE, "out", "plan_eval.lean")
    with open(src, "w") as f:
        f.write(f"import Plan\nopen BB6d\n#eval IO.println (plan (2^{E}) {budget} {F} {E - 2} 5 4).1.show\n")
    out = subprocess.run([os.environ.get("LEAN", "lean"), src], capture_output=True, text=True, check=True).stdout
    toks = iter(out.split("\n"))

    def parse():
        t = next(toks).split()
        if t[0] == "N":
            return ("N", parse(), parse())
        return ("L", int(t[1]), int(t[2]), int(t[3]), int(t[4]))
    return parse()


def main(argv):
    budget = int(argv[0]) if argv else 12000
    shards = int(argv[1]) if len(argv) > 1 else 8
    E = int(argv[2]) if len(argv) > 2 else 62
    B, R, (no_one, passes) = f"2 ^ {E}", f"R{E}", NAMES[E]
    tree = get_plan(budget, E)
    leaves, nodes = [], []      # leaves: (name, d, p, q, cost); nodes: (name, p, q, left, right), children first

    def walk(t, name):
        if t[0] == "L":
            leaves.append((name, *t[1:]))
            return t[2], t[3]
        p, q2 = walk(t[1], name + "0")
        walk(t[2], name + "1")
        nodes.append((name, p, q2 // 2, name + "0", name + "1"))
        return p, q2 // 2
    walk(tree, "c")

    load = [[0, i, []] for i in range(shards)]
    for leaf in sorted(leaves, key=lambda x: -x[4]):
        s = min(load)
        s[0] += leaf[4]
        s[2].append(leaf)
    os.makedirs(os.path.join(HERE, R), exist_ok=True)
    for old in os.listdir(os.path.join(HERE, R)):
        if old.startswith("Shard") and old.endswith(".lean"):
            os.remove(os.path.join(HERE, R, old))
    for cost, i, ls in sorted(load, key=lambda x: x[1]):
        lines = [f"-- Generated by lean/return62.py (budget {budget}, {shards} shards): shard {i}, {len(ls)} pieces, "
                 f"cost {cost}.", "import Return", "", "namespace BB6d", f"namespace {R}", ""]
        for name, d, p, q, c in sorted(ls):
            lines.append(f"theorem {name} : Cov ({B}) {p} {q} :=")
            lines.append(f"  Cov.of_explore (f := {F}) (d := {d}) (by decide +kernel)")
        lines += ["", f"end {R}", "end BB6d", ""]
        with open(os.path.join(HERE, R, f"Shard{i}.lean"), "w") as f:
            f.write("\n".join(lines))
    lines = [f"-- Generated by lean/return62.py (budget {budget}, {shards} shards): {len(leaves)} pieces, "
             f"{len(nodes)} splits.", "import Return"] + [f"import {R}.Shard{i}" for i in range(shards)] + [
        "", f"/-! The return map below 2^{E} by the kernel alone: the pieces of `{R}/Shard*.lean` put together. -/",
        "", "namespace BB6d", "open TM", f"namespace {R}", ""]
    for name, p, q, l, r in nodes:
        lines.append(f"theorem {name} : Cov ({B}) {p} {q} := Cov.split (by decide) (by decide) {l} {r}")
    lines += ["", f"end {R}", "",
              f"/-- Every `a = 1 mod 4` with `5 ≤ a < 2^{E}` returns: kernel only, no `native_decide`. -/",
              f"theorem returns_2_{E}_kernel : ∀ a, a % 4 = 1 → 5 ≤ a → a < 2 ^ {E} → Returns a :=",
              f"  returns_of_cov {R}.c", "",
              f"/-- **The first {passes} passes** from blank tape never stop at a block of 1, and the "
              "machine\nreaches each of their pass starts: kernel only. -/",
              f"theorem {no_one} (n : Nat) (hn : n ≤ 3 * 2 ^ {E - 2} + 1) :",
              "    ∃ zs t, orbit n = .ok zs ∧ zs.sum = 4 * n ∧ n ≤ t ∧ steps t init = some ⟨enc zs, blank, .A⟩ :=",
              f"  reach_upto _ returns_2_{E}_kernel n (by omega)", "", "end BB6d", ""]
    with open(os.path.join(HERE, f"Return{E}.lean"), "w") as f:
        f.write("\n".join(lines))
    print(f"{len(leaves)} pieces, {len(nodes)} splits, shard costs {[x[0] for x in sorted(load, key=lambda x: x[1])]}")


if __name__ == "__main__":
    main(sys.argv[1:])
