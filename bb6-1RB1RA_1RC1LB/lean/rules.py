"""Generate Rules.lean: rules of 1RB1RA_1RC1LB_1LD0RA_---0LE_1LC0LF_1RE0LB proved along the symbolic run
(tools/py/bbtools/symtm.py: single steps by `rfl`, shift rules by `TM.cross_r`/`TM.cross_l`).

usage: python3 rules.py > Rules.lean      (tests/test_machine.py checks that the committed file is current)

Tapes are written left to right: `S>` is the head in state S on the next cell, `1^n` is n ones, L and R are any tape.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tools", "py"))
from bbtools.symtm import prove, rules_file  # noqa: E402

M = "1RB1RA_1RC1LB_1LD0RA_---0LE_1LC0LF_1RE0LB"

RULES = [
    ("a_sweep", "L A> 1^n R", "L 1^n A> R", "State A runs right over a block of ones."),
    ("b_sweep", "L 0 1^n B> 1 R", "L B> 0 1 1^n R", "State B runs left over a block of ones to the 0 before it."),
]


def main():
    ths = [prove(M, name, a, b, doc=doc)[0] for name, a, b, doc in RULES]
    sys.stdout.write(rules_file("Machine", "BB6b", ths, f"Rules of {M}, generated by `rules.py`; do not edit by hand."))


if __name__ == "__main__":
    main()
