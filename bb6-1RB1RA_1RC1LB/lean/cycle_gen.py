"""Generate the kernel check of the tables, level by level, in pieces: CycleData/, CyclePieces/, CycleLevels/ and
CycleRun.lean (see CycleCert.lean for the method).

usage: python3 cycle_gen.py K [PASSES]   tables for the last 1 … K blocks, then PASSES passes of the last table
                                         (default 0); check_cycles.sh runs this and checks the files

The plan is `py/superrun.py`'s (the plan of lean/CascadeRun.lean).  Everything here mirrors the Lean definitions
(`lev`, `push`, `pushT`, `lvSeg`, `pseg`) exactly, to say what each piece is: the tables, cut into stretches of about
SEG entries, the states between the stretches, and what each stretch gives.  None of it is trusted: every piece is a
theorem checked by `decide +kernel`, and the Lean side chains them (`step_sound`).
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "py"))
import superrun  # noqa: E402

SEG = 3000                # entries per stretch of a table, the size of one piece (about 3 s)
PIECES_PER_FILE = 12
DATA_PER_FILE = 40000     # entries per data file (about 2 s each)
OUT = HERE                # where the files go (generate's out)
HEADER = "-- Generated by cycle_gen.py; do not edit.\n"
NONE, ADD, WAVE = 0, 1, 2


class Halt(Exception):
    pass


# ---- the Lean definitions, mirrored ----

def tsub(a, b):
    return a - b if a > b else 0


def evenT(d):
    return tsub(2 * (d // 2) * (d // 2) + d // 2, 5)


def oddT(d, A):
    return 2 * (d // 2) * (d // 2) + 4 * (d // 2) + 17 + A


def lev(p, e):
    k, v = e
    if k == NONE:
        return p, e, 0
    if k == ADD:
        return p + v, (NONE, 0), 0
    d = p + v
    if d % 2 == 1:
        return (d + 5) // 2, (ADD, (d - 1) // 2), oddT(d, 0)
    return d // 2, (WAVE, d // 2), evenT(d) + d // 2 + 1


def left_end(f, d):
    out = []
    while True:
        if f == 0 or d <= 1:
            return None
        if d % 2 == 1:
            return out + [(d + 5) // 2, (d - 1) // 2]
        out.append(d // 2)
        f, d = f - 1, d // 2


def wave(d, L):
    out = []
    for i, p in enumerate(L):
        if d % 2 == 1:
            return out + [(d + 5) // 2, p + (d - 1) // 2] + L[i + 1:]
        out.append(d // 2)
        d = p + d // 2
    r = left_end(d, d)
    return None if r is None else out + r


def left_time(f, d, A):
    t = 0
    while f > 0:
        if d % 2 == 1:
            return t + oddT(d, A)
        if d == 4:
            return t + 11
        t += evenT(d)
        f, d, A = f - 1, d // 2, A + d // 2 + 1
    return t


def wave_time(d, L, A):
    t = 0
    for p in L:
        if d % 2 == 1:
            return t + oddT(d, A)
        t += evenT(d)
        d, A = p + d // 2, A + d // 2 + 1
    return t + left_time(d, d, A)


def push(e, U):
    k, v = e
    if k == NONE:
        return list(U)
    if k == ADD:
        return [v] if not U else [U[0] + v] + U[1:]
    return left_end(v, v) if not U else wave(U[0] + v, U[1:])


def pushT(e, U):
    k, v = e
    if k != WAVE:
        return 0
    return left_time(v, v, 0) if not U else wave_time(U[0] + v, U[1:], 0)


def lv_seg(S, p, acc):
    """lvSeg: the entries passed on, the accumulator at the end, the block at the end."""
    out, (a1, a2) = [], acc
    for dt, e, c in S:
        p, e2, c2 = lev(p, e)
        if e2[0] == NONE:
            a1, a2 = a1 + dt, a2 + c + c2
        else:
            out.append((a1 + dt, e2, a2 + c + c2))
            a1, a2 = 0, 0
    return out, (a1, a2), p


def pseg(S, U, t):
    for dt, e, c in S:
        U2 = push(e, U)
        if U2 is None:
            raise Halt
        t = t + c + pushT(e, U)
        U = U2
    return U, t


# ---- Lean text ----

def lst(xs):
    return "[" + ", ".join(map(str, xs)) + "]"


def pair(a):
    return f"({a[0]}, {a[1]})"


def table_lit(S):
    return 'tbl% "' + " ".join(f"{dt} {e[0]} {e[1]} {c}" for dt, e, c in S) + '"'


def nest(xs, op="++"):
    """x₀ op (x₁ op (… op xₙ)), right-nested as the chaining lemmas give it."""
    s = xs[-1]
    for x in reversed(xs[:-1]):
        s = f"{x} {op} ({s})" if " " in s else f"{x} {op} {s}"
    return s


def generate(K, passes, out=HERE, verbose=True):
    """Write the files for K levels and PASSES passes into the directory out; return the levels."""
    global OUT
    OUT = out
    plan, _, _ = superrun.lean_plan(K, max(passes, 1))
    plan = plan[:K]
    for d in ("CycleData", "CyclePieces", "CycleLevels"):
        shutil.rmtree(os.path.join(OUT, d), ignore_errors=True)
        os.makedirs(os.path.join(OUT, d))

    T, tl = [(1, (WAVE, 10), 203)], (0, 0)
    groups = [T]                    # the stretches of the current table
    B, U, t = [], [6, 1], 136
    period = 1
    levels = []                     # for CycleRun.lean
    write_data(0, [("O0_0", T)], [["O0_0"]])
    for k in range(1, K + 2):
        last = k == K + 1
        r, L = (passes, 0) if last else plan[k - 1]
        if last and passes == 0:
            break
        prev = k - 1
        pieces = []                 # (name, statement)
        # r passes of the table over U
        pass_steps = []
        for rho in range(r):
            names = []
            for i, S in enumerate(groups):
                U2, t2 = pseg(S, U, t)
                name = f"p{k}_{rho}_{i}"
                pieces.append((name, f"pseg G{prev}_{i} {lst(U)} {t} = some ({lst(U2)}, {t2})"))
                names.append(name)
                U, t = U2, t2
            t += tl[1]
            pass_steps.append((names, U, t))
        if last:
            write_pieces(k, prev, pieces, None)
            levels.append(dict(k=k, prev=prev, r=r, L=0, pass_steps=pass_steps, U=U, t=t, last=True, tl=tl))
            break
        p, U = U[0], U[1:]
        assert U, "the plan needs a level left of the new one"
        # the table for one more level, over L passes of p
        q, acc = p, (0, 0)
        outs, build_steps = [], []
        for j in range(L):
            names, outn, start = [], [], (q, acc)
            for i, S in enumerate(groups):
                o, acc2, q2 = lv_seg(S, q, acc)
                oname = f"O{k}_{j}_{i}"
                name = f"b{k}_{j}_{i}"
                pieces.append((name, f"lvSeg G{prev}_{i} {q} {pair(acc)} = ({oname}, {pair(acc2)}, {q2})"))
                outs.append((oname, o))
                names.append(name)
                outn.append(oname)
                q, acc = q2, acc2
            build_steps.append((names, outn, start, acc, q))
            acc = (acc[0] + tl[0], acc[1] + tl[1])
        assert q == p, f"level {k} does not come back"
        newT = [x for _, o in outs for x in o]
        # regroup the outputs into stretches of at least SEG entries (up to one output more)
        gnames, cur, size = [], [], 0
        for oname, o in outs:
            cur.append(oname)
            size += len(o)
            if size >= SEG:
                gnames.append(cur)
                cur, size = [], 0
        if cur:
            gnames.append(cur)
        groups = []
        lens = {n: o for n, o in outs}
        for g in gnames:
            groups.append([x for n in g for x in lens[n]])
        assert [x for g in groups for x in g] == newT
        write_data(k, outs, gnames)
        write_pieces(k, prev, pieces, build_steps)
        period *= L
        levels.append(dict(k=k, prev=prev, r=r, L=L, p=p, pass_steps=pass_steps, build_steps=build_steps, B=B + [p],
                           U=U, t=t, tl=acc, prev_tl=tl, period=period, gnames=gnames))
        B = B + [p]
        T, tl = newT, acc
        if verbose:
            print(f"level {k}: table {len(T)} entries in {len(groups)} stretches, period {period}, {len(pieces)} pieces,"
                  f" machine step {t}", flush=True)
    write_levels(levels)
    write_run(levels, K, passes)
    return levels


def write_data(k, outs, gnames):
    """CycleData/D{k}_{n}.lean: the outputs of level k's pieces, about DATA_PER_FILE entries to a file;
    CycleData/D{k}.lean: its stretches G and its table T."""
    files, cur, size = [], [], 0
    for oname, o in outs + [(None, None)]:
        if oname is None or (cur and size + len(o) > DATA_PER_FILE):
            n = len(files)
            lines = [HEADER, "import TableLit\n", f"/-! Part {n} of the table of the last {k} blocks, written out. -/\n",
                     "namespace BB6b.Cyc\n", "set_option maxRecDepth 100000\n"]
            lines += [f"noncomputable def {a} : List Entry := {table_lit(b)}\n" for a, b in cur]
            lines.append("end BB6b.Cyc\n")
            with open(os.path.join(OUT, "CycleData", f"D{k}_{n}.lean"), "w") as f:
                f.write("\n".join(lines))
            files.append(f"D{k}_{n}")
            cur, size = [], 0
            if oname is None:
                break
        cur.append((oname, o))
        size += len(o)
    lines = [HEADER, "".join(f"import CycleData.{x}\n" for x in files),
             f"/-! The table of the last {k} blocks: its stretches. -/\n", "namespace BB6b.Cyc\n"]
    for g, names in enumerate(gnames):
        lines.append(f"noncomputable def G{k}_{g} : List Entry := {nest(names)}\n")
    lines.append(f"noncomputable def T{k} : List Entry := {nest([f'G{k}_{g}' for g in range(len(gnames))])}\n")
    lines.append(f"theorem T{k}_eq : T{k} = {nest([f'G{k}_{g}' for g in range(len(gnames))])} := rfl\n")
    lines.append("end BB6b.Cyc\n")
    with open(os.path.join(OUT, "CycleData", f"D{k}.lean"), "w") as f:
        f.write("\n".join(lines))


def write_pieces(k, prev, pieces, build_steps):
    """CyclePieces/P{k}_{n}.lean: the pieces of level k, PIECES_PER_FILE to a file."""
    files = []
    for n in range(0, len(pieces), PIECES_PER_FILE):
        name = f"P{k}_{n // PIECES_PER_FILE}"
        imports = f"import CycleData.D{prev}\n" + (f"import CycleData.D{k}\n" if build_steps is not None else "")
        body = [HEADER, "import CycleCert\n" + imports, "namespace BB6b.Cyc\n"]
        for pname, stmt in pieces[n:n + PIECES_PER_FILE]:
            body.append(f"theorem {pname} : {stmt} := by decide +kernel\n")
        body.append("end BB6b.Cyc\n")
        with open(os.path.join(OUT, "CyclePieces", name + ".lean"), "w") as f:
            f.write("\n".join(body))
        files.append(name)
    with open(os.path.join(OUT, "CyclePieces", f"files{k}.txt"), "w") as f:
        f.write("\n".join(files) + "\n")


def chain_pseg(names):
    s = names[-1]
    for x in reversed(names[:-1]):
        s = f"(pseg_app _ _ _ _ _ _ _ _ {x} {s})"
    return s


def chain_lvseg(names):
    s = names[-1]
    for x in reversed(names[:-1]):
        s = f"(lvSeg_app _ _ _ _ _ _ _ _ _ _ {x} {s})"
    return s


def level_passes(lv, prev, tl):
    """Lean lines for the passes of a level: `pass{k}_{ρ}` and `passes{k}`."""
    k, out = lv["k"], []
    U0, t0 = lv["U0"], lv["t0"]
    U, t = U0, t0
    for rho, (names, U2, t2) in enumerate(lv["pass_steps"]):
        out.append(f"set_option maxRecDepth 100000 in\ntheorem pass{k}_{rho} : pass T{prev} {pair(tl)} {lst(U)} {t} = some ({lst(U2)}, {t2}) := by\n"
                   f"  rw [T{prev}_eq]; exact pass_of_pseg _ _ _ _ _ _ {chain_pseg(names)}\n")
        U, t = U2, t2
    # passes r = pass₀ then passes (r - 1) …
    s = f"(passes_zero T{prev} {pair(tl)} {lst(U)} {t})"
    for rho in reversed(range(len(lv["pass_steps"]))):
        s = f"(passes_succ _ _ _ _ _ _ _ _ pass{k}_{rho} {s})"
    out.append(f"theorem passes{k} : passes {lv['r']} T{prev} {pair(tl)} {lst(U0)} {t0} = some ({lst(U)}, {t}) :=\n"
               f"  {s}\n")
    return out


def write_levels(levels):
    """CycleLevels/L{k}.lean: level k's passes and table, chained from its pieces."""
    U, t = [6, 1], 136
    for lv in levels:
        lv["U0"], lv["t0"] = U, t
        k, prev = lv["k"], lv["prev"]
        tl = lv["prev_tl"] if not lv.get("last") else lv["tl"]
        with open(os.path.join(OUT, "CyclePieces", f"files{k}.txt")) as f:
            files = f.read().split()
        body = [HEADER, "import CycleCert\n" + "".join(f"import CyclePieces.{x}\n" for x in files),
                "namespace BB6b.Cyc\n", "open BB6b\n"]
        body += level_passes(lv, prev, tl)
        if not lv.get("last"):
            steps = []
            for j, (names, outn, start, acc, q) in enumerate(lv["build_steps"]):
                body.append(f"set_option maxRecDepth 100000 in\ntheorem build{k}_{j} : lvSeg T{prev} {start[0]} {pair(start[1])} = ({nest(outn)}, "
                            f"{pair(acc)}, {q}) := by\n  rw [T{prev}_eq]; exact {chain_lvseg(names)}\n")
                steps.append(f"build{k}_{j}")
            s = f"(lvSegs_zero T{prev} {pair(tl)} _ _)"
            for x in reversed(steps):
                s = f"(lvSegs_succ T{prev} {pair(tl)} _ _ _ _ _ _ _ _ _ _ {x} {s} rfl)"
            unfold = ", ".join([f"T{k}"] + [f"G{k}_{g}" for g in range(len(lv["gnames"]))])
            body.append(f"set_option maxRecDepth 100000 in\ntheorem build{k} : build T{prev} {pair(tl)} {lv['p']} {lv['L']} = (T{k}, {pair(lv['tl'])}, "
                        f"{lv['p']}) := by\n  rw [build_segs]\n  have h := {s}\n"
                        f"  simpa only [{unfold}, List.append_assoc, List.append_nil] using h\n")
            U, t = lv["U"], lv["t"]
        body.append("end BB6b.Cyc\n")
        with open(os.path.join(OUT, "CycleLevels", f"L{k}.lean"), "w") as f:
            f.write("\n".join(body))


def write_run(levels, K, passes):
    """CycleRun.lean: the levels chained from the blank tape, the cycles, and the bound."""
    body = [HEADER, "import CycleCert\n" + "".join(f"import CycleLevels.L{lv['k']}\n" for lv in levels),
            f"/-! # The cycles of the last 1 to {K} blocks, checked by the kernel in pieces\n\n"
            f"Generated by `cycle_gen.py {K} {passes}`.  For each `k`, `lvl{{k}}` says that the super orbit from blank "
            "tape reaches a tape whose last `k` blocks are `B` with a table of them (`Rep`), and `cycle{k}` that those "
            "`k` blocks come back after `P` super steps of the bottom (`bs P B = B`), `P` the table's length. -/\n",
            "namespace BB6b.Cyc\n", "open BB6b\n",
            "theorem lvl0 : (∃ j, orbitT j [6, 1] 136 = some ([] ++ [6, 1], 136)) ∧ Rep [] T0 (0, 0) :=\n"
            "  ⟨⟨0, rfl⟩, rep₀⟩\n",
            "theorem len0 : lenT T0 + (0, 0).1 = 1 := by decide +kernel\n",
            "theorem least0 : LeastP [] 1 := least₀\n"]
    B, U, t, tl = [], [6, 1], 136, (0, 0)
    mexpr = "1"
    for lv in levels:
        k, prev = lv["k"], lv["prev"]
        if lv.get("last"):
            body.append(f"theorem orbit_end : ∃ j, orbitT j [6, 1] 136 = some ({lst(B)} ++ {lst(lv['U'])}, {lv['t']}) := by\n"
                        f"  obtain ⟨⟨j, hj⟩, hR⟩ := lvl{prev}\n"
                        f"  obtain ⟨j', hj'⟩ := passes_sound _ _ _ _ _ _ _ _ (by simp) hR passes{k}\n"
                        f"  exact ⟨j + j', by rw [orbitT_add, hj]; exact hj'⟩\n")
            break
        U2, p = lv["U"], lv["p"]
        body.append(
            f"theorem lvl{k} : (∃ j, orbitT j [6, 1] 136 = some ({lst(lv['B'])} ++ {lst(U2)}, {lv['t']})) ∧ "
            f"Rep {lst(lv['B'])} T{k} {pair(lv['tl'])} := by\n"
            f"  obtain ⟨⟨j, hj⟩, hR⟩ := lvl{prev}\n"
            f"  obtain ⟨⟨j', hj'⟩, hR'⟩ := step_sound _ _ _ _ _ {lv['r']} {lv['L']} {p} _ _ _ _ hR (by simp) passes{k} build{k}\n"
            f"  exact ⟨⟨j + j', by rw [orbitT_add, hj]; simpa using hj'⟩, by simpa using hR'⟩\n")
        body.append(
            f"theorem len{k} : lenT T{k} + {pair(lv['tl'])}.1 = {lv['L']} * {lv['period'] // lv['L']} :=\n"
            f"  build_len' build{k} len{prev}\n")
        qs = [st[2][0] for st in lv["build_steps"]]
        facts = ", ".join(f"topv_of_seg hR len{prev} build{k}_{j}" for j in range(lv["L"]))
        facts = facts if lv["L"] == 1 else f"⟨{facts}⟩"
        body.append(
            f"theorem least{k} : LeastP {lst(lv['B'])} ({lv['L']} * {lv['period'] // lv['L']}) := by\n"
            f"  have hR := (lvl{prev}).2\n"
            f"  have h := least_append {lst(B)} {mexpr} {p} {lst(qs[1:])} least{prev} (by simp only [Steps]; exact {facts})"
            f" (by decide)\n  exact h\n")
        body.append(
            f"/-- **The last {k} blocks cycle**: on the orbit from blank tape they are `{lst(lv['B'])}`, and their least "
            f"period is {lv['period']} super steps. -/\n"
            f"theorem cycle{k} : (∃ j U, U ≠ [] ∧ orbit j [6, 1] = some ({lst(lv['B'])} ++ U)) ∧ "
            f"LeastP {lst(lv['B'])} {lv['period']} := by\n"
            f"  obtain ⟨⟨j, hj⟩, _⟩ := lvl{k}\n"
            f"  exact ⟨⟨j, _, by simp, orbitT_orbit _ _ _ _ _ hj⟩, least{k}⟩\n")
        mexpr = f"({lv['L']} * {lv['period'] // lv['L']})"
        B, U, t, tl = lv["B"], U2, lv["t"], lv["tl"]
    last = levels[-1]
    if last.get("last"):
        src, T_end = "orbit_end", last["t"]
    else:
        src, T_end = f"⟨_, (lvl{last['k']}).1⟩", last["t"]
    body.append(f"/-- **No halt in the first {T_end} steps** ({T_end:.1e}), checked by Lean's kernel alone. -/\n"
                f"theorem blank_runs_cycles : ∃ c, steps {T_end} init = some c :=\n"
                f"  runs_of_orbitT _ (by obtain ⟨j, h⟩ := {src}; exact ⟨j, h⟩) (Nat.le_refl _)\n")
    body.append("end BB6b.Cyc\n")
    body.append(f"#print axioms BB6b.Cyc.cycle{K}\n#print axioms BB6b.Cyc.blank_runs_cycles\n")
    with open(os.path.join(OUT, "CycleRun.lean"), "w") as f:
        f.write("\n".join(body))


if __name__ == "__main__":
    generate(int(sys.argv[1]), int(sys.argv[2]) if len(sys.argv) > 2 else 0)
