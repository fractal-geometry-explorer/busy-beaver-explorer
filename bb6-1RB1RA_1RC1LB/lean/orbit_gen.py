"""Generate the chunked check of the super orbit: Orbit/K*.lean, Orbit/N*.lean, OrbitKernel.lean, OrbitNative.lean.

usage: python3 orbit_gen.py        (builds ../c/orbitck.c with gcc; about 35 minutes, almost all of it in orbitck)

The orbit from the tape [1, 6, 5, 0] (step 136) is cut at checkpoints, which `c/orbitck.c` computes.  Each chunk is a
theorem `orbitT n P T = some (P', T')` between two checkpoints, so Lean recomputes every super step and the checkpoints
are not trusted.  The first KERNEL_CHUNKS chunks are decided by the kernel (`decide +kernel`), the rest by compiled
code (`native_decide`).  Each file chains its chunks into one segment, so the files can be checked in parallel
(`check_orbit.sh`); OrbitKernel.lean and OrbitNative.lean chain the segments and state the bounds.
"""
import os
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ORBITCK = os.path.join(HERE, "..", "c", "orbitck.c")

KERNEL_CHUNK = 10 ** 4          # super steps per kernel theorem (about 10 s each; much longer chunks get slow)
KERNEL_CHUNKS = 1000            # 10^7 super steps
KERNEL_PER_FILE = 25
NATIVE_CHUNK = 10 ** 9          # super steps per native_decide theorem (about 2 minutes each with check_orbit.sh)
NATIVE_CHUNKS = 99              # after the kernel's 10^7: up to 10^11 super steps, the first chunk 10^9 - 10^7
NATIVE_PER_FILE = 4

HEADER = "-- Generated by orbit_gen.py; do not edit.\n"


def checkpoints(every, count):
    exe = os.path.join(tempfile.mkdtemp(prefix="orbitck-"), "orbitck")
    subprocess.run(["gcc", "-O2", "-o", exe, ORBITCK], check=True)
    out = subprocess.Popen([exe, str(every), str(count)], stdout=subprocess.PIPE, text=True)
    for line in out.stdout:
        f = line.split()
        assert f[0] != "halt", line
        yield int(f[0]), int(f[1]), [int(x) for x in f[2:]]
    assert out.wait() == 0


def lst(P):
    return "[" + ", ".join(map(str, P)) + "]"


def sci(x):
    """The largest a·10^b (a < 100) at most x, as Lean text and as a name suffix: 14027... -> 14 * 10^15."""
    b = len(str(x)) - 2
    a = x // 10 ** b
    return a * 10 ** b, f"{a // 10}{'_' + str(a % 10) if a % 10 else ''}e{b + 1}"


def segment(name, chunks, tactic, what):
    """One file: the chunk theorems and their chain.  chunks: [(n, (P, T), (P', T'))]."""
    (P0, T0), (P1, T1) = chunks[0][1], chunks[-1][2]
    out = [HEADER, "import WaveTime\n\n",
           f"/-! {what}: {len(chunks)} chunks of the super orbit, from the tape `{lst(P0)}` (nearest first) at step "
           f"{T0:,}\nto `{lst(P1)}` at step {T1:,}. -/\n\n",
           "namespace BB6b.Orbit\n\n"]
    for i, (n, (P, T), (Q, U)) in enumerate(chunks):
        out.append(f"theorem {name}_{i:02} : orbitT {n} {lst(P)} {T} =\n    some ({lst(Q)}, {U}) := by {tactic}\n\n")
    chain = f"⟨_, {name}_00⟩"
    for i in range(1, len(chunks)):
        chain = f"orbitT_trans ({chain}) ⟨_, {name}_{i:02}⟩"
    out.append(f"theorem {name} : ∃ j, orbitT j {lst(P0)} {T0} = some ({lst(P1)}, {T1}) :=\n  {chain}\n\n")
    out.append("end BB6b.Orbit\n")
    return "".join(out), (P1, T1)


def chain_file(imports, segs, end, prev, doc, bound_doc, theorem):
    chain = prev or f"Orbit.{segs[0]}"
    for s in (segs if prev else segs[1:]):
        chain = f"orbitT_trans ({chain}) Orbit.{s}"
    N, suffix = sci(end[1])
    return "".join([HEADER, "".join(f"import {m}\n" for m in imports), "\n", doc, "\n\nnamespace BB6b\n\n",
                    f"theorem {theorem} : ∃ j, orbitT j [6, 1] 136 = some ({lst(end[0])}, {end[1]}) :=\n"
                    f"  {chain}\n\n",
                    bound_doc.format(N=f"{N:,}"), "\n",
                    f"theorem blank_runs_{suffix} : ∃ c, steps {N} init = some c :=\n"
                    f"  runs_of_orbitT _ {theorem} (by decide)\n\n", "end BB6b\n\n",
                    f"#print axioms BB6b.blank_runs_{suffix}\n"]), suffix


def main():
    os.makedirs(os.path.join(HERE, "Orbit"), exist_ok=True)
    start = ([6, 1], 136)
    # kernel: checkpoints every KERNEL_CHUNK super steps
    cks = [start] + [(P, T) for _, T, P in checkpoints(KERNEL_CHUNK, KERNEL_CHUNKS)]
    ksegs = []
    for f in range(KERNEL_CHUNKS // KERNEL_PER_FILE):
        part = [(KERNEL_CHUNK, cks[i], cks[i + 1]) for i in range(f * KERNEL_PER_FILE, (f + 1) * KERNEL_PER_FILE)]
        name = f"k{f:02}"
        src, _ = segment(name, part, "decide +kernel", "Checked by Lean's kernel")
        with open(os.path.join(HERE, "Orbit", f"K{f:02}.lean"), "w") as fh:
            fh.write(src)
        ksegs.append(name)
    kend = cks[-1]
    ksteps = KERNEL_CHUNK * KERNEL_CHUNKS
    src, ksuffix = chain_file(
        [f"Orbit.K{i:02}" for i in range(len(ksegs))], ksegs, kend, None,
        f"/-! # The super orbit, checked by the kernel\n\nThe first {ksteps:,} super steps from the tape "
        f"`[1, 6, 5, 0]`, chained from `Orbit/K*.lean` (generated by `orbit_gen.py`). -/",
        "/-- **No halt in the first {N} steps**, checked by Lean's kernel alone (`check_orbit.sh`). -/",
        "orbit_kernel")
    with open(os.path.join(HERE, "OrbitKernel.lean"), "w") as fh:
        fh.write(src)
    # native: from the kernel's end, checkpoints at multiples of NATIVE_CHUNK (read every 10^7 super steps)
    step = 10 ** 7
    want = {NATIVE_CHUNK * (i + 1) for i in range(NATIVE_CHUNKS)}
    last = max(want)
    nck = [(ksteps, kend)]
    for S, T, P in checkpoints(step, last // step):
        if S in want:
            nck.append((S, (P, T)))
    nsegs = []
    for f in range((NATIVE_CHUNKS + NATIVE_PER_FILE - 1) // NATIVE_PER_FILE):
        part = [(nck[i + 1][0] - nck[i][0], nck[i][1], nck[i + 1][1])
                for i in range(f * NATIVE_PER_FILE, min((f + 1) * NATIVE_PER_FILE, NATIVE_CHUNKS))]
        name = f"n{f:02}"
        src, _ = segment(name, part, "native_decide", "Checked by compiled code (`native_decide`)")
        with open(os.path.join(HERE, "Orbit", f"N{f:02}.lean"), "w") as fh:
            fh.write(src)
        nsegs.append(name)
    nend = nck[-1][1]
    src, nsuffix = chain_file(
        ["OrbitKernel"] + [f"Orbit.N{i:02}" for i in range(len(nsegs))], nsegs, nend, "orbit_kernel",
        f"/-! # The super orbit, checked by compiled code\n\nThe first {last:,} super steps from the tape "
        f"`[1, 6, 5, 0]`: the kernel's {ksteps:,} (`OrbitKernel.lean`), then `Orbit/N*.lean` by `native_decide` "
        f"(generated by `orbit_gen.py`). -/",
        "/-- **No halt in the first {N} steps**, by `native_decide` on top of the kernel's part (`check_orbit.sh`). -/",
        "orbit_native")
    with open(os.path.join(HERE, "OrbitNative.lean"), "w") as fh:
        fh.write(src)
    print("kernel", ksteps, kend[1], ksuffix)
    print("native", last, nend[1], nsuffix)


if __name__ == "__main__":
    main()
